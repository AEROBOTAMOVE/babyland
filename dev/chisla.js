const срещнати = new Map();   // име → Map(стойност → [къде])
for (const t of ТЕМИ) срещнати.set(t.име, new Map());

for (const из of изречения) {
  for (const t of ТЕМИ) {
    if (!t.тема.test(из.контекст)) continue;
    // Числото може да е СПИСЪК от изрази по предпочитание: първият, който хване,
    // печели. Иначе „всяка температура от 38° нагоре" се чете като „всяка", само
    // защото думите стоят по-рано в изречението от числото.
    const списък = Array.isArray(t.число) ? t.число : [t.число];
    let m = null;
    for (const р of списък) { m = из.цифри.match(р); if (m) break; }
    if (!m) continue;
    // нормализираме: „10-15 минути" и „10 – 15 минути" са едно и също
    let ст = m[0].toLowerCase().replace(/\s+/g, ' ').replace(/[–—]/g, '-').replace(/,/g, '.').trim();
    const карта = срещнати.get(t.име);
    if (!карта.has(ст)) карта.set(ст, []);
    if (карта.get(ст).length < 4) карта.get(ст).push({ къде: из.къде, s: из.s.slice(0, 110) });
  }
}

