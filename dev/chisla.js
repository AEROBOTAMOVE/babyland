// 🪤 Редът има значение: „петнадесет" ТРЯБВА да се пробва преди „пет", иначе
//    „петнадесетия" става „5надесетия". Затова списъкът е от голямо към малко.
// 🪤 И границите са ИЗРИЧНИ: \b и \w НЕ работят с кирилица в JS — регулярка с
//    тях не гърми, а мълчаливо не намира нищо. Платено е много пъти в тази база.
const наЦифри = т => {
  let р = т;
  for (const [думи, ц] of ДУМИЧИСЛА)
    р = р.replace(new RegExp('(^|[^а-яА-Я])(' + думи + ')[а-яА-Я]{0,4}(?=[^а-яА-Я]|$)', 'gi'),
      (_, пред) => пред + ц);
  return р;
};


