let спорни = 0, редове = [];
for (const t of ТЕМИ) {
  const карта = срещнати.get(t.име);
  const стойности = [...карта.entries()].sort((a, b) => b[1].length - a[1].length);
  if (!стойности.length) { редове.push({ име: t.име, брой: 0, стойности: [] }); continue; }
  const различни = стойности.length;
  редове.push({ име: t.име, брой: различни, стойности: стойности.map(([с, к]) => ({ стойност: с, места: к.length, примери: к })) });
  if (различни > 1) спорни++;
}

redове_печат: for (const r of редове.sort((a, b) => b.брой - a.брой)) {
  if (!r.брой) { console.log('   ⬜ ' + r.име + '  —  нито едно число'); continue; }
  const знак = r.брой === 1 ? '✅' : (r.брой <= 3 ? '🟠' : '🔴');
  console.log('   ' + знак + ' ' + r.име + '  →  ' + r.брой + ' различни стойности');
  for (const с of r.стойности.slice(0, 6)) {
    console.log('        „' + с.стойност + '"  на ' + с.места + ' места   напр. ' + с.примери[0].къде);
    if (r.брой > 1) console.log('           ' + с.примери[0].s);
  }
  if (r.стойности.length > 6) console.log('        … и още ' + (r.стойности.length - 6));
  console.log('');
}

// ═══ ВЪЗРАСТТА ДО ЧИСЛОТО ═══
// 🔑 УРОКЪТ ОТ 02.09: за мокрите пелени уредът показа четири стойности — 6, 6+,
//    5-6 и „поне 6". Прочетени, те НЕ бяха спор: всяко „6" стои при бебе САМО НА
//    МЛЯКО, а всяко „5-6" — в стая „Захранване", при дете, което вече яде твърдо.
//    Разликата беше ПО ВЪЗРАСТ и лекът НЕ беше едно число, а числото ДА СИ
//    НОСИ ВЪЗРАСТТА. Затова тук се мери друго: не колко са стойностите, а
//    колко от тях са казани БЕЗ да се каже за кое дете важат.
//    Това е мярка, която ПАДА, когато работата е свършена — за разлика от
//    броя стойности, който след верния лек ОСТАВА СЪЩИЯТ.
const ВЪЗРАСТ = /(само на мляко|млякото стига|новородено|първите седмици|първите месеци|твърда храна|вече яде|прикърмван|захранван|кърмено бебе)/i;
const пазенаТ = ТЕМИ.find(t => t.име === 'колко мокри памперса на ден е нормално');
const безВъзраст = [];
for (const из of изречения) {
  if (!пазенаТ.тема.test(из.контекст)) continue;
  if (!из.цифри.match(пазенаТ.число)) continue;
  if (!ВЪЗРАСТ.test(из.s)) безВъзраст.push(из);
}
// ⚠️ САМОПРОВЕРКА В ДВЕТЕ ПОСОКИ: подставена примамка ТРЯБВА да гърми,
//    а здрав случай ТРЯБВА да мълчи. Мярка, която не може да гръмне, е украса.
const _пр = п => пазенаТ.тема.test(п) && !!наЦифри(п).match(пазенаТ.число) && !ВЪЗРАСТ.test(п);
const примамкаБез = _пр('На лекар при под 4 мокри пелени на ден.');
const здравСлучай = _пр('При бебе само на мляко под 6 мокри пелени на ден.');
console.log('   🎂 ВЪЗРАСТТА ДО ЧИСЛОТО (мокри пелени): ' + безВъзраст.length + ' места казват число, без да казват за кое дете важи');
