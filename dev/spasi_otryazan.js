'use strict';
const fs = require('fs');
const path = require('path');
const КОРЕН = path.resolve(__dirname, '..');
process.chdir(КОРЕН);

// ── ПОПРАВКА 1: българската кавичка, затворена с ПРАВА кавичка ──
//   Писачите пишат „най-добро мляко" — отварят с „ (U+201E) и затварят с
//   права ", която ПРЕКЪСВА JSON низа. Файлът гърми на ред 8 и целите 30
//   карти отиват в кофата заради един знак.
//   ПРАВИЛОТО: щом сме вътре в низ и сме видели „, следващата права кавичка
//   е ЗАТВАРЯЩА типографска, не край на низа → става " (U+201C).
//   ⚠️ Не пипа кавичка, пред която НЯМА отворена „ — там правата наистина
//      затваря низа и всяко „оправяне" би слепило два записа.
function затвориКавичките(текст) {
  const ОТВОРЕНА = String.fromCharCode(0x201E); // „
  const ЗАТВОРЕНА = String.fromCharCode(0x201C); // "
  let вън = [], вНиз = false, екраниран = false, чакаЗатваряне = false, поправени = 0;
  for (let i = 0; i < текст.length; i++) {
    const c = текст[i];
    if (екраниран) { вън.push(c); екраниран = false; continue; }
    if (c === String.fromCharCode(92)) { вън.push(c); екраниран = true; continue; }
    if (c === ОТВОРЕНА && вНиз) { чакаЗатваряне = true; вън.push(c); continue; }
    if (c === '"') {
      if (вНиз && чакаЗатваряне) { вън.push(ЗАТВОРЕНА); чакаЗатваряне = false; поправени++; continue; }
      вНиз = !вНиз; чакаЗатваряне = false; вън.push(c); continue;
    }
    вън.push(c);
  }
  return { текст: вън.join(''), поправени: поправени };
}

function спаси(текст) {
  // намира началото на масива
  const старт = текст.indexOf('[');
  if (старт < 0) return null;
  let дълбочина = 0, вКавички = false, екраниран = false;
  let последенЦял = -1;
  for (let i = старт; i < текст.length; i++) {
    const c = текст[i];
    if (екраниран) { екраниран = false; continue; }
    if (c === String.fromCharCode(92)) { екраниран = true; continue; }
    if (c === '"') { вКавички = !вКавички; continue; }
    if (вКавички) continue;
    if (c === '{' || c === '[') дълбочина++;
    else if (c === '}' || c === ']') {
      дълбочина--;
      // дълбочина 1 значи: току-що затворихме обект от първо ниво в масива
      if (дълбочина === 1 && c === '}') последенЦял = i;
      if (дълбочина === 0) return текст.slice(старт, i + 1); // масивът е цял
    }
  }
  if (последенЦял < 0) return null;
  return текст.slice(старт, последенЦял + 1) + ']';
}

let файлове = process.argv.slice(2).filter(x => !x.startsWith('--'));
if (process.argv.includes('--vsichki')) {
  файлове = fs.readdirSync('dev/nahodki')
    .filter(f => /^(karti|statii|klyuchove)_.*\.json$/.test(f))
    .map(f => path.join('dev/nahodki', f))
    .filter(p => { try { JSON.parse(fs.readFileSync(p, 'utf8')); return false; } catch (e) { return true; } });
}
if (!файлове.length) { console.log('  нищо за спасяване'); process.exit(0); }

let спасени = 0, паднали = 0;
for (const п of файлове) {
  const сурово = fs.readFileSync(п, 'utf8');
  try { JSON.parse(сурово); console.log('  ⏭ ' + п + ' е здрав'); continue; } catch (e) {}
  const кав = затвориКавичките(сурово);
  if (кав.поправени) console.log('     ✎ ' + п + ': затворени ' + кав.поправени + ' български кавички');
  const изрязано = спаси(кав.текст);
  if (!изрязано) { console.log('  🔴 ' + п + ' — нищо цяло вътре'); паднали++; continue; }
  let a;
  try { a = JSON.parse(изрязано); } catch (e) { console.log('  🔴 ' + п + ' — и рязането не помогна: ' + e.message.slice(0, 60)); паднали++; continue; }
  if (!Array.isArray(a) || !a.length) { console.log('  🔴 ' + п + ' — празен резултат'); паднали++; continue; }
  // 🩺 самопроверка: всеки спасен запис трябва да носи id, инак не е карта
  const годни = a.filter(x => x && (x.id || x.karta));
  if (годни.length !== a.length) console.log('     (изхвърлени ' + (a.length - годни.length) + ' без id)');
  fs.writeFileSync(п + '.SUROV', сурово);
  fs.writeFileSync(п, JSON.stringify(годни, null, 1));
  console.log('  ✅ ' + п + ' → спасени ' + годни.length + ' записа  (оригиналът е в ' + path.basename(п) + '.SUROV)');
  спасени++;
}
console.log('');
console.log('  спасени файла: ' + спасени + ' · неспасени: ' + паднали);
process.exit(паднали ? 1 : 0);
