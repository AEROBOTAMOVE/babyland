// 🍽️ ЛАКОМИТЕ КЛЮЧОВЕ — къс гол ключ, който яде чужди въпроси
//
// ЗАЩО (26.08.2026, ИЗМЕРЕНО): картата за температура държеше голия ключ
// „пари" — в смисъл „парѝ" (гори). Но голият ключ се търси по НАЧАЛО НА
// ДУМА, значи хваща и „парѝ"-то от „парите". Проверено на живо:
//     „парите за бебето"  →  „Бебето има температура — какво да правя?"
// Майка с въпрос за ПАРИ получаваше картата за ТРЕСКА.
//
// dev/bliznaci.js намери този случай само защото И ДВЕТЕ карти имаха
// „пари". Омоним, който стои само в ЕДНАТА, оставаше невидим. Този уред
// го хваща по друг път: взима всеки къс гол ключ и пита ЧУЖДИТЕ ЗАГЛАВИЯ
// „някоя дума в теб започва ли с този ключ?".
//
// 🪤 ЗАЩО НЕ ВСЯКО СЪВПАДЕНИЕ Е ДЕФЕКТ: „сън" в карта за съня ще съвпадне
//    със заглавие за съня — и това е ВЯРНО. Затова се брои само когато
//    съвпадението е в ДРУГА стая ИЛИ заглавията нямат нито една обща дума;
//    тоест когато темите наистина се разминават.
//
// 🪤 КИРИЛИЦАТА: `\b` и `\w` в JavaScript НЕ работят с кирилица — такъв
//    regex намира НУЛА и мълчи. Границата на дума тук е `(^|[^а-яА-Я])`.
//
// ПУСКАНЕ: node dev/lakomi.js  ·  node dev/lakomi.js --vsichki
// ═══════════════════════════════════════════════════════════
const fs = require('fs');
const vm = require('vm');
const path = require('path');
const КОРЕН = path.resolve(__dirname, '..');

const ctx = { console: { log() {}, warn() {} }, JSON, Math, Date, RegExp, String, Number, Array, Object };
ctx.window = ctx; ctx.globalThis = ctx; ctx.self = ctx;
vm.createContext(ctx);
new vm.Script(fs.readFileSync(path.join(КОРЕН, 'js/kb.js'), 'utf8')).runInContext(ctx);
const записи = ((ctx.BL_KB || ctx.KB) || {}).entries || [];
if (!записи.length) { console.log('🔴 не мога да заредя базата'); process.exit(2); }

// най-късите голи ключове са най-лакомите; над 6 букви случайното
// съвпадение по начало на дума на практика изчезва
const МАКС_ДЪЛЖИНА = 6;
const думиНа = т => String(т || '').toLowerCase()
  .replace(/[^а-яa-z0-9 ]/g, ' ').split(/\s+/).filter(д => д.length > 3);

const находки = [];
for (const з of записи) {
  for (const сур of (з.keys || [])) {
    const к = String(сур).trim().toLowerCase();
    if (!к || к.indexOf(' ') >= 0) continue;          // само ГОЛИ (еднословни)
    if (к.length < 3 || к.length > МАКС_ДЪЛЖИНА) continue;
    // 🪤 кирилска граница на дума — `\b` тук е сляп
    if (!/^[а-яa-z0-9]+$/.test(к)) continue;   // 🪤 без екраниране: ключ със знак се пропуска
    const гранично = new RegExp('(^|[^а-яА-Яa-zA-Z])' + к, 'i');
    for (const друг of записи) {
      if (друг.id === з.id) continue;
      const загл = String(друг.title || '');
      if (!гранично.test(загл.toLowerCase())) continue;
      // ако темите са близки, съвпадението е вярно, не лакомо
      const а = new Set(думиНа(з.title)), б = думиНа(загл);
      const общи = б.filter(д => а.has(д)).length;
      if (общи > 0) continue;
      if (з.room === друг.room) continue;   // в една стая подредбата ги разделя по-надеждно
      находки.push({ ключ: к, откъде: з, накъде: друг });
    }
  }
}

// 🪤 ПЪРВИЯТ МИ ИЗХОД БЕШЕ НЕЧЕТИМ: печатах по един ред на ЖЕРТВА, тоест
//    един лаком ключ с 12 жертви заемаше 36 реда и заглушаваше всичко под
//    себе си. Броят на жертвите обаче е точно МЯРКАТА за това колко е лаком
//    ключът — затова се групира по ВИНОВНИК и се подрежда по брой жертви.
const поВиновник = new Map();
for (const н of находки) {
  const п = н.откъде.id + '|' + н.ключ;
  if (!поВиновник.has(п)) поВиновник.set(п, { ключ: н.ключ, откъде: н.откъде, жертви: [] });
  поВиновник.get(п).жертви.push(н.накъде);
}
const списък = [...поВиновник.values()].sort((а, б) => б.жертви.length - а.жертви.length);

console.log('');
console.log('🍽️ ЛАКОМИТЕ КЛЮЧОВЕ — къс гол ключ, който яде чужди въпроси');
console.log('');
console.log('  ПРЕГЛЕДАНИ : ' + записи.length + ' карти · всеки гол ключ от 3 до ' + МАКС_ДЪЛЖИНА + ' букви');
console.log('  🟠 лакоми ключа : ' + списък.length + '   (върху ' + находки.length + ' чужди заглавия общо)');
console.log('');
const ВСИЧКИ = process.argv.includes('--vsichki');
for (const н of списък.slice(0, ВСИЧКИ ? 9999 : 18)) {
  console.log('     „' + н.ключ + '"  ×' + String(н.жертви.length).padStart(2) + '  в  [' + н.откъде.room + '] ' + н.откъде.id);
  console.log('          „' + н.откъде.title + '"');
  console.log('          отвлича: ' + н.жертви.slice(0, 3).map(ж => '„' + ж.title + '"').join(' · ') +
              (н.жертви.length > 3 ? '  … +' + (н.жертви.length - 3) : ''));
}
if (!ВСИЧКИ && списък.length > 18) console.log('     … и още ' + (списък.length - 18) + '  (--vsichki)');
console.log('');
// ── САМОПРОВЕРКА: уред, който не може да гръмне, е украса ──
(function самопроверка() {
  const прим = [
    { id: 'А', room: 'Стая', title: 'Бебето има температура', keys: ['пари'] },
    { id: 'Б', room: 'Друга', title: 'Колко пари трябват наистина', keys: ['бюджет'] },
    { id: 'В', room: 'Трета', title: 'Съвсем друга тема', keys: ['нещо'] }
  ];
  let хванато = 0;
  for (const з of прим) for (const к of з.keys) {
    if (к.length > 6) continue;
    const г = new RegExp('(^|[^а-яА-Яa-zA-Z])' + к, 'i');
    for (const д of прим) if (д.id !== з.id && з.room !== д.room && г.test(д.title.toLowerCase())) хванато++;
  }
  // и ОБРАТНАТА посока: ключ, който НЕ се среща никъде, не бива да дава находка
  const тихо = !(new RegExp('(^|[^а-яА-Яa-zA-Z])зззз', 'i')).test('Колко пари трябват наистина');
  console.log('  самопроверка: примамката „пари" хваната ' + (хванато === 1 ? '✅' : '🔴 (' + хванато + ')') +
              ' · чужд ключ мълчи ' + (тихо ? '✅' : '🔴'));
})();

// ── ИЗХОДЕН КОД ──
// 🪤 ПЪРВО НАПИСАХ `const ПРАГ = Number(process.env... || 0)` и после `if (ПРАГ && ...)`.
//    Тоест БЕЗ променлива на средата прагът е 0, условието е лъжа и уредът
//    излиза с НУЛА ВИНАГИ. dev/pazachi.js чете точно този код — значи пазачът
//    щеше да свети зелено, без да гледа нищо. Същият дефект вече е плащан тук
//    (тест, който се самоизключваше след regex, изяде 10 проверки без червено).
//
// Прагът е ЗАМРАЗЕНОТО ДНЕШНО ЧИСЛО: не пречи на заварения дълг, но пламва при
// НОВ лаком ключ. Свали ли се дългът — свали и прага, ръчно, тук.
const ПРАГ = Number(process.env.BL_LAKOMI_PRAG || 50);
if (списък.length > ПРАГ) {
  console.log('  🔴 НАХОДКА: лакомите ключове станаха ' + списък.length + ' при замразен праг ' + ПРАГ + '.');
  console.log('     Дай на ключа втора дума или го махни от картата, на която не принадлежи.');
  process.exit(1);
}
if (списък.length < ПРАГ)
  console.log('  🟢 паднаха на ' + списък.length + ' (праг ' + ПРАГ + '). Свали прага в dev/lakomi.js.');
else console.log('  ✅ ' + списък.length + ' — точно замразения праг. Нов лаком ключ не е добавен.');
console.log('');
process.exit(0);