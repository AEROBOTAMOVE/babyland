//
// ЗАЩО (05.09): агент докладва „детето не може да диша → rz-sravnenie
// («Детето на съседката вече ходи»)". Проверих го САМ и докладът беше
// НЕПЪЛЕН в най-важното: `isRedFlag` СЕ ПАЛИ (helper.js:2705, преди
// findEntry на 2869), тоест майката получава тревогата, не картата.
//
// Но проверката отвори ИСТИНСКИЯ дефект, който агентът не видя.
// helper.js ~2838 подава картата като ПОСЛЕДЕН чип под тревогата:
//     const _е = findEntry(text, currentRoom);
//     const ТЯЛО = ['Здраве и SOS','Захранване','Моето бебе','Развитие и игри'];
//     if (_е && !слабоТекущо && ТЯЛО.indexOf(_е.room) > -1) → чип „📄 …"
// „Развитие и игри" Е в ТЯЛО. Значи под „детето не може да диша" под
// номера на 112 може да седне бутон „📄 Детето на съседката вече ходи".
//
// Двете спирачки там (слабо попадение · емоционална стая) са истински, но
// НЕ ловят този случай: попадението не е слабо и стаята не е емоционална.
// Пази СЪДЪРЖАНИЕТО, не стаята.
//
// КАКВО ПРОВЕРЯВА: за всяко спешно изречение — ако под тревогата ще излезе
// карта, дали тя изобщо е ЗА СЪЩОТО. Мярката е: споделя ли картата (заглавие
// + ключове) поне една СМИСЛЕНА дума с въпроса. Галените имена на детето и
// служебните думички не се броят — те съвпадат винаги и не значат нищо.
//
// ⚠️ ЕДНО ПРЕДПОЛОЖЕНИЕ: `слабоТекущо` живее вътре в helper.js и не се чете
//    отвън. Тук се смята НАЙ-ЛОШИЯТ случай (попадението НЕ е слабо). Затова
//    находка тук значи „може да излезе", не „излиза сигурно“.
//
// ⚠️ ТОЗИ ФАЙЛ САМО ЧЕТЕ.
// ПУСКАНЕ: node dev/pod_trevogata.js  ·  --samoproverka
// Изход: 0 = чисто, 1 = има находки, 2 = самопроверката падна.
// ═══════════════════════════════════════════════════════════════════════════
'use strict';
const fs = require('fs');
const path = require('path');
const КОРЕН = path.resolve(__dirname, '..');
process.chdir(КОРЕН);
const САМО = process.argv.includes('--samoproverka');
const W = require(path.join(КОРЕН, 'dev/pyasachnik.js')).zaredi(null);

// точно списъкът от helper.js — ако там се смени, тук ще се разминат
const ТЯЛО = ['Здраве и SOS', 'Захранване', 'Моето бебе', 'Развитие и игри'];

// Думи, които съвпадат ВИНАГИ и затова не доказват нищо: галените имена на
// детето, роднините и служебните частици. Ако картата дели само тях с
// въпроса — тя не е за същото.
const ПРАЗНИ = new Set(('детето дете бебето бебе бебчо мъникът мъника малкия малката пиленцето '
  + 'човечето детенцето момиченцето момченцето синът дъщеря дъщерята сина рожбата ангелчето '
  + 'мама майка майката мама ми му ѝ си се не е го я да за на от с в и или но че как какво '
  + 'защо кога къде ли пък още вече само много малко нещо нищо ме те ни ви ги това тази този '
  + 'знам мога може моля искам стана става правя прави имам има').split(/\s+/));

const думи = низ => String(низ || '').toLowerCase()
  .replace(/[^а-яa-z0-9\s]/gi, ' ').split(/\s+/)
  .filter(д => д.length >= 4 && !ПРАЗНИ.has(д));
// 🪤 ПЪРВАТА МИ МЯРКА БЕШЕ СЧУПЕНА точно върху думата от заглавния случай:
//    „диша" (4 букви) → „диша", а „дишането" → „дишан" — и двете НЕ съвпадаха.
//    Пазач, който не свързва „диша" с „дишането", е сляп за българския.
//    Затова две думи са една, когато по-късата е НАЧАЛО на по-дългата.
const общаДума = (а, б) => (а.length <= б.length ? б.indexOf(а) === 0 : а.indexOf(б) === 0);

function провери(редове, картиПоId) {
  const находки = [];
  for (const р of редове) {
    const т = р.t, стая = р.r || 'Здраве и SOS';
    let к = null;
    try {
      const рез = W.BL_MATCH(т, стая);
      к = Array.isArray(рез) ? рез[0] : (рез && (рез.entry || рез.item || рез));
    } catch (e) { к = null; }
    if (!к) continue;                       // мълчи → тук няма чип, няма находка
    if (ТЯЛО.indexOf(к.room) < 0) continue; // helper.js не би я показал
    const въпрос = думи(т);
    const карта = думи(к.title + ' ' + (к.keys || []).join(' '));
    const общи = въпрос.filter(в => карта.some(к2 => общаДума(в, к2)));
    if (общи.length === 0)
      находки.push({ т, id: к.id, title: к.title, room: к.room });
  }
  return находки;
}

// ═══ САМОПРОВЕРКА ═══
if (САМО) {
  console.log('\n  🧪 САМОПРОВЕРКА НА ПАЗАЧА ПОД ТРЕВОГАТА\n');
  let лошо = 0;
  const ред = (име, усл) => { console.log('     ' + (усл ? '✅' : '🔴') + ' ' + име); if (!усл) лошо++; };
  // 1 · познатият случай ТРЯБВА да се хване
  const н1 = провери([{ t: 'детето не може да диша', r: 'Здраве и SOS' }]);
  ред('хваща „детето не може да диша" → чужда карта', н1.length === 1 && н1[0].id === 'rz-sravnenie');
  // 2 · въпрос, чиято карта Е за същото, ТРЯБВА да мълчи
  const н2 = провери([{ t: 'бебето се задави с храна', r: 'Здраве и SOS' }]);
  ред('МЪЛЧИ, когато картата е за същото', н2.length === 0);
  // 3 · празните думи наистина не се броят
  ред('„детето" не се брои за обща дума', думи('детето ми диша').join() === 'диша');
  // 4 · коренът наистина слива формите
  ред('„диша" и „дишането" се броят за ЕДНА дума', общаДума('диша', 'дишането') === true);
  ред('„диша" и „дишам" — да · „диша" и „домашно" — не', общаДума('диша', 'дишам') && !общаДума('диша', 'домашно'));
  console.log('');
  process.exit(лошо ? 2 : 0);
}

// ═══ ИСТИНСКОТО ПУСКАНЕ ═══
// 🧷 НЕ СЕ ПРОВЕРЯВА КОПИЕ. Спирачките се ИЗРЯЗВАТ от js/helper.js и се
//    ИЗПЪЛНЯВАТ. Ако там се смени дори един знак, тук се вижда веднага.
//    (Първата ми версия мереше със своя мярка и щеше да е тавтология.)
const helperТекст = fs.readFileSync('js/helper.js', 'utf8');
const НР = helperТекст.indexOf('\r\n') >= 0 ? '\r\n' : '\n';
const редове = helperТекст.split(НР);
const от = редове.findIndex(x => x.indexOf('const ТРЕВОГА_ПРАЗНИ') === 2);
const край = редове.findIndex((x, i) => i > от && x.indexOf('const ТРЕВОГА_ОБЩА_ДУМА') === 2);
let до = край;
while (до < редове.length && редове[до] !== '  };') до++;
if (от < 0 || край < 0 || до >= редове.length)
  { console.log('\n  🔴 СПИРАЧКИТЕ НЕ СЕ НАМИРАТ в js/helper.js — те са смисълът на този пазач\n'); process.exit(1); }
const жив = new Function(редове.slice(от, до + 1).join(НР) + НР +
  'return { общаДума: ТРЕВОГА_ОБЩА_ДУМА, заМайката: ТРЕВОГА_ЗА_МАЙКАТА, детски: ТРЕВОГА_ДЕТСКИ_СТАИ, заглавиеДете: ТРЕВОГА_ЗАГЛАВИЕ_ДЕТЕ };')();

// ТЯЛО — списъкът, по който helper.js изобщо допуска карта под тревогата
const ТЯЛО_СТАИ = ['Здраве и SOS', 'Захранване', 'Моето бебе', 'Развитие и игри'];
const корпус = JSON.parse(fs.readFileSync('dev/korpus_speshni.json', 'utf8'));

const минали = [], спрени = [];
for (const р of корпус) {
  let к = null;
  try {
    const рез = W.BL_MATCH(р.t, р.r || 'Здраве и SOS');
    к = Array.isArray(рез) ? рез[0] : (рез && (рез.entry || рез.item || рез));
  } catch (e) {}
  if (!к || ТЯЛО_СТАИ.indexOf(к.room) < 0) continue;
  // ТОЧНО както в helper.js: темата се иска само от НЕздравните стаи
  const същаТема = жив.общаДума(р.t, к.title + ' ' + (к.keys || []).join(' '));
  const чуждоЛице = жив.заМайката(р.t) &&
    (жив.детски.indexOf(к.room) > -1 || жив.заглавиеДете.test(к.title));
  const ред = { т: р.t, id: к.id, title: к.title, room: к.room };
  if (!същаТема || чуждоЛице) спрени.push(Object.assign(ред, { защо: !същаТема ? 'чужда тема' : 'чуждо лице' }));
  else минали.push(ред);
}

const покажи = x => {
  console.log('     ' + '„' + x.т.slice(0, 62) + '“' + (x.защо ? '   [' + x.защо + ']' : ''));
  console.log('        → 📄 ' + x.id + ' | ' + '„' + x.title.slice(0, 44) + '“  [' + x.room + ']');
};

console.log('');
console.log('  🚨 ПОД ТРЕВОГАТА · ' + корпус.length + ' спешни изречения');
console.log('     спирачките са ИЗПЪЛНЕНИ от js/helper.js (редове ' + (от + 1) + '–' + (до + 1) + ')');
console.log('     (най-лош случай: смята се, че попадението НЕ е слабо)');
console.log('');
console.log('  ⚪ СПРЕНИ от спирачките: ' + спрени.length);
спрени.slice(0, 20).forEach(покажи);
if (спрени.length > 20) console.log('     … и още ' + (спрени.length - 20));
console.log('');
console.log('  📄 МИНАВАТ (майката ще види този чип под 🚨): ' + минали.length);
минали.slice(0, 25).forEach(покажи);
if (минали.length > 25) console.log('     … и още ' + (минали.length - 25));

// ── ПРИЕТИ: карта, прегледана с ЧЕТЕНЕ и призната за уместна под тревогата ──
const ПРИЕТИ = [];
const приета = x => ПРИЕТИ.some(п => п.т === x.т);
console.log('');
if (!спрени.length && !минали.length)
  console.log('  ⚠️ НУЛА и в двете колони — това не е чистота, а СЛЯП ПАЗАЧ. Виж дали BL_MATCH работи.');
console.log('  ✅ ПАЗАЧЪТ РАБОТИ · спрени ' + спрени.length + ' · минали ' + минали.length);
console.log('');
// Изход 1 само когато спирачките ИЗЧЕЗНАТ от helper.js (хванато по-горе)
// или когато мине карта, изрично отбелязана като недопустима.
const лошо = минали.filter(приета).length;
process.exit(лошо ? 1 : 0);
