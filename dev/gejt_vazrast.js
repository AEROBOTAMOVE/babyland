// 🎂 ВЪЗРАСТОВИЯТ ГЕЙТ НА КАРТИТЕ — мери ли се, жив ли е  (27.10)
//
// ЗАЩО: присъдата („Код, не думи“ в ЗАДАЧИ.md): „възрастовият гейт в пясъчника
//   е мъртъв“. Пясъчникът нямаше BL_AGE (живее в rooms2.js) — затова никоя мярка
//   не виждаше полетата `от`/`до` на картите (× 0.55 / × 1.15 във findEntry).
//   От 27.10 dev/pyasachnik.js взима BL_AGE дословно от rooms2.js.
//
// КАКВО МЕРИ — три мозъка, един и същ въпросник, бебе на 1 и на 36 месеца:
//   ЖИВ     — helper.js както е, пясъчник с BL_AGE (= живото приложение)
//   ОТВОРЕН — същото, но възрастМесеци() чете bl_baby през lsGet (в паметта,
//             файлът не се пипа) — тоест какво би станало, ако гейтът работи
//   СТАР    — пясъчник без BL_AGE (опции.безВъзраст) — както се мереше досега
//   Въпросникът: по един дълъг собствен ключ от всяка карта С поле от/до,
//   питан в стаята на картата (само картата знае възрастта си — въпросът не).
//   Плюс 609-те и 257-те: колко отговора би сменил отворен гейт (бебе 11 м.).
//
// ПУСКАНЕ: node dev/gejt_vazrast.js [--json изход.json]
// САМОПРОВЕРКА: ОТВОРЕНИЯТ мозък трябва да вижда разлика между 1 и 36 месеца;
//   ако не вижда — уредът е сляп за гейта и спира с изход 2.
//   И BL_AGE трябва да даде ~1 месец за бебе, родено преди 31 дни.
// ПЪТ НАЗАД: само ЧЕТЕ (с --json пише само посочения файл). Изтрий файла.
// ═══════════════════════════════════════════════════════════════════════
const fs = require('fs');
const { zaredi } = require('./pyasachnik.js');
const арг = process.argv.slice(2);
const iJ = арг.indexOf('--json');
const ИЗХОД = iJ > -1 ? арг[iJ + 1] : null;

const ден = д => { const x = new Date(Date.now() - д * 86400000); return x.getFullYear() + '-' + String(x.getMonth() + 1).padStart(2, '0') + '-' + String(x.getDate()).padStart(2, '0'); };
const Р1 = ден(31), Р36 = ден(1096), Р11 = '2025-11-20';   // 11 м. = профилът на dev/prisada_zhivo.js

const ГЕЙТ = "const б = (typeof load === 'function') ? load('bl_baby', {}) : null;";
const отвори = src => {
  if (src.indexOf(ГЕЙТ) < 0) throw new Error('котвата на гейта (възрастМесеци → load) я няма — helper.js е сменен, прегледай уреда');
  return src.replace(ГЕЙТ, "const б = lsGet('bl_baby', {});");
};
const мозък = (birth, вид) => zaredi(вид === 'отворен' ? отвори : null, { памет: { bl_baby: { birth } }, безВъзраст: вид === 'стар' });
const id = (W, т, с) => { const р = W.BL_MATCH(т, с); return р ? р.id : 'ТИШИНА'; };

const М = {};
for (const вид of ['жив', 'отворен', 'стар']) М[вид] = { 1: мозък(Р1, вид), 36: мозък(Р36, вид) };
// самопроверка 1: BL_AGE има ли го и вярно ли брои
const а1 = М.жив[1].BL_AGE ? М.жив[1].BL_AGE(Р1) : null;
if (!а1 || Math.abs(а1.months - 1) > 0.1) { console.log('🔴 СЛЯП: BL_AGE липсва или брои грешно (' + JSON.stringify(а1) + ')'); process.exitCode = 2; return; }
console.log('BL_AGE в пясъчника: ' + typeof М.жив[1].BL_AGE + ' · ' + Р1 + ' → ' + а1.months.toFixed(2) + ' м. · ' + Р36 + ' → ' + М.жив[36].BL_AGE(Р36).months.toFixed(2) + ' м.' +
  ' · стар пясъчник: ' + typeof М.стар[1].BL_AGE);

const KB = М.жив[1].BL_KB || М.жив[1].KB;
const сПоле = KB.entries.filter(e => (e.от != null || e.до != null) && e.room && (e.keys || []).length);
const въпросник = сПоле.map(e => ({ id: e.id, стая: e.room, от: e.от, до: e.до,
  q: (e.keys.filter(k => k.length >= 12).sort((a, b) => b.length - a.length)[0]) || e.keys[0] }));
console.log('карти с поле от/до: ' + сПоле.length + ' от ' + KB.entries.length + ' · въпроси: ' + въпросник.length);

const разлики = {}; const примери = [];
for (const вид of ['жив', 'отворен', 'стар']) {
  let р = 0, свояИ = { 1: 0, 36: 0 };
  for (const x of въпросник) {
    const a = id(М[вид][1], x.q, x.стая), b = id(М[вид][36], x.q, x.стая);
    if (a === x.id) свояИ[1]++; if (b === x.id) свояИ[36]++;
    if (a !== b) { р++; if (вид === 'отворен' && примери.length < 12) примери.push(x.q + '  [' + x.от + '–' + x.до + ' м.]  1м: ' + a + ' · 36м: ' + b); }
  }
  разлики[вид] = { р, свояИ };
}
console.log('\nразличен отговор при 1 срещу 36 месеца (същият въпрос, същата стая):');
console.log('  ЖИВ     (= приложението): ' + разлики.жив.р + '/' + въпросник.length);
console.log('  ОТВОРЕН (гейтът през lsGet): ' + разлики.отворен.р + '/' + въпросник.length + '   своята карта: 1м ' + разлики.отворен.свояИ[1] + ' · 36м ' + разлики.отворен.свояИ[36]);
console.log('  СТАР    (без BL_AGE):      ' + разлики.стар.р + '/' + въпросник.length);
примери.forEach(п => console.log('   · ' + п));

// самопроверка 2: уредът трябва да вижда жив гейт, иначе „0“ при ЖИВ не значи нищо
if (разлики.отворен.р === 0) { console.log('🔴 СЛЯП: и отвореният гейт не мени нищо — уредът не вижда възрастта'); process.exitCode = 2; return; }

// какво би сменил отворен гейт върху общите корпуси (бебе на 11 м., профилът на prisada_zhivo)
const Ж11 = мозък(Р11, 'жив'), О11 = мозък(Р11, 'отворен');
let общо = 0; const смени = [];
for (const ф of ['vaprosi_nezavisimi.json', 'vaprosi_nezavisimi2.json', '_bgmamma_zaglaviya.json', '_bgmamma_zaglaviya2.json']) {
  for (const x of require('./' + ф)) {
    const т = x.v || x.t || x.q; if (!т) continue; общо++;
    const a = id(Ж11, т, x.r || null), b = id(О11, т, x.r || null);
    if (a !== b) смени.push('[' + (x.r || '') + '] ' + т + '  ' + a + ' → ' + b + '  (' + ф + ')');
  }
}
console.log('\nотворен гейт, бебе 11 м. (' + Р11 + '), 609 + 257 въпроса = ' + общо + ': сменен отговор ' + смени.length);
смени.slice(0, 30).forEach(с => console.log('   ↔ ' + с));
console.log('\nПРИСЪДА: ' + (разлики.жив.р === 0
  ? 'гейтът в helper.js е МЪРТЪВ и в приложението (възрастМесеци чете `load`, а глобален `load` няма —' +
    ' всеки файл държи своя в IIFE). Пясъчникът вече подава възраст; „0“ при ЖИВ е истината, не слепота на уреда.'
  : 'гейтът в helper.js е ЖИВ: ' + разлики.жив.р + ' въпроса сменят картата между 1 и 36 месеца.'));
if (ИЗХОД) fs.writeFileSync(ИЗХОД, JSON.stringify({ Р1, Р36, Р11, разлики, примери, смени }, null, 1));
