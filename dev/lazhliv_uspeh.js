const fs = require('fs');
const path = require('path');
process.chdir(path.resolve(__dirname, '..'));
const СПИСЪК = process.argv.includes('--spisak');

// запис, чийто отговор се хвърля: редът ЗАПОЧВА с извикването
const ЗАПИС = /^\s*(?:save|запази|пиши|записва|localStorage\.setItem)\s*\(/;
// правилните шаблони — те НЕ са находка
const ПРАВИЛНО = /(?:if|while|return|const|let|var|\?|&&|\|\||!|=\s*)\s*[^;]*(?:save|запази|пиши|записва|localStorage\.setItem)\s*\(/;

// дума, с която приложението казва на майката „стана"
const УСПЕХ = /✔|✅|💌|🔒|Записано|Запазено|запазено|Прибрано|Готово|Заключено|Запечатан|Готова|Добавено|cheer\s*\(|знак\s*\(|кажи\s*\(|toast\s*\(/;
// 🔴 26.08 — УРЕДЪТ ВИКАШЕ СРЕЩУ ЗДРАВ КОД. В УСПЕХ стоят `кажи(`, `toast(`,
//   `знак(` и `cheer(` — тоест ФУНКЦИИТЕ, с които се говори на майката, без
//   да се гледат ДУМИТЕ вътре. А js/askfield.js:145 записва чернова в `catch`
//   и веднага вика:
//        кажи(„Нещо се запъна и въпросът не тръгна. Думите ти са тук…“)
//   Това е съобщение за ПРОВАЛ, а уредът го броеше за обещание за успех.
//   Съдеше по формата на извикването, не по това, което майката ЧЕТЕ.
//   Затова: съобщение, което САМО ПО СЕБЕ СИ казва, че нещо НЕ е станало, не
//   е обещание — стига да няма и истинска дума за успех до него.
const НЕУСПЕХ = /не (?:тръгна|стана|можах|успях|се запази|се записа|го записах)|запъна|паметта е пълна|пълна\s*[—.,]|провал|⚠️|пробвай пак|грешка/i;
// думите, които наистина обещават — без функциите за показване
const УСПЕХ_ДУМИ = /✔|✅|💌|🔒|Записано|Запазено|запазено|Прибрано|Готово|Заключено|Запечатан|Готова|Добавено/;
// изчистване на поле — то удвоява цената на лъжата
const ЧИСТИ = /\.value\s*=\s*['"`]['"`]|\.textContent\s*=\s*['"`]['"`]|\.innerHTML\s*=\s*['"`]['"`]/;

// 🔴 ПЪРВАТА ВЕРСИЯ ДАДЕ 64 НАХОДКИ И ЧАСТ ОТ ТЯХ БЯХА ЗДРАВ КОД.
// Два вида, и двата открити при преглед един по един:
//   1. СЛЕД записа веднага се ПРЕРИСУВА (`рисувай()`, `draw()`, `replaceWith()`).
//      Прерисуването чете НАНОВО от паметта — падне ли записът, екранът
//      показва старото и мама вижда, че промяната ѝ я няма. Това не е лъжа,
//      а най-много половин истина. (Същото го измери и одитът на стаите:
//      „живият обход доказва, че се самопоправят".)
//   2. Самото ИЗЧИСТВАНЕ на чернова: `save('bl_draft_x', '')`. Тук няма какво
//      да се загуби — това Е операцията.
// Уред, който вика срещу здрав код, е по-лош от липсващ: праща те да
// „поправяш" работещото и заглушава истинските находки в шума.
// 🪤 И ВТОРА ЦЕНА, ПЛАТЕНА ВЕДНАГА: първият израз беше `рисувай\s*\(` — тоест
//   искаше точно „рисувай(". А js/preg20.js вика `рисувайДата()`. Функция с
//   по-дълго име минаваше за „не прерисува" и излизаше като лъжа.
//   Затова навсякъде има продължение след корена на думата.
//
// 🔴🔴 26.08 — И ВТОРАТА МИ ПОПРАВКА БЕШЕ СЧУПЕНА, ПО СЪЩИЯ НАЧИН.
//   Сложих `\w*` и написах в коментара, че вече хваща „рисувайДата". НЕ Я
//   ХВАЩАШЕ: в JavaScript `\w` е САМО ЛАТИНИЦА. Тоест поправката ми беше
//   украса — изразът се държеше точно както преди, и то мълчаливо.
//   Това е ТРЕТИЯТ път днес, в който кирилицата ме лъже в собствен уред.
//   Намери го чужд одит, като ПУСНА израза, вместо да прочете коментара ми.
const ДУМА = '[а-яА-Яa-zA-Z0-9_]*';
const ПРЕРИСУВА = new RegExp(
  ['рисувай', 'нарисувай', 'draw', 'render', 'обнови', 'презареди', 'построй', 'покажи']
    .map(k => k + ДУМА + '\\s*\\(').join('|') + '|replaceWith\\s*\\(');
const ЧИСТИ_ЧЕРНОВА = /save\s*\(\s*(?:[^,]*(?:draft|чернова|ЧЕРНОВА)[^,]*)\s*,\s*['"`]['"`]\s*\)/;

const ПРОЗОРЕЦ = 6;   // колко реда след записа се гледат

function прегледай(име, текст) {
  const L = текст.split(/\r?\n/);
  const находки = [];
  let записи = 0;
  for (let i = 0; i < L.length; i++) {
    const ред = L[i];
    if (/^\s*\/\//.test(ред)) continue;
    if (!ЗАПИС.test(ред)) continue;
    записи++;
    if (ПРАВИЛНО.test(ред)) continue;              // отговорът се ползва → добре
    if (ЧИСТИ_ЧЕРНОВА.test(ред)) continue;         // самото изчистване на чернова
    // 🪤 ПРОЗОРЕЦЪТ СПИРА В СЪЩИЯ БЛОК. Преди четеше шест реда напред слепешката
    //   и преливаше в СЪСЕДНИЯ слушател — js/preg20.js:315 беше обявен заради
    //   `знак()` на съвсем друг бутон. Спираме на ред, който затваря блока.
    const отстъп = (ред.match(/^\s*/) || [''])[0].length;
    const следРедове = [];
    for (let k = i + 1; k < Math.min(L.length, i + 1 + ПРОЗОРЕЦ); k++) {
      const р = L[k];
      if (/^\s*\/\//.test(р)) continue;
      const о = (р.match(/^\s*/) || [''])[0].length;
      if (/^\s*[})\]]/.test(р) && о < отстъп) break;   // блокът свърши
      следРедове.push(р);
    }
    const след = следРедове.join('\n');
    // ако единственият знак за успех е ФУНКЦИЯ за показване, а текстът до нея
    // казва, че нещо не е станало — това не е обещание, а честно признание
    const самоФункция = УСПЕХ.test(след) && !УСПЕХ_ДУМИ.test(след);
    const имаУспех = УСПЕХ.test(след) && !(самоФункция && НЕУСПЕХ.test(след));
    const имаЧисти = ЧИСТИ.test(след);
    if (!имаУспех && !имаЧисти) continue;          // няма обещание → няма лъжа
    // 🔴 26.08 — ПРЕДИ ТУК СТОЕШЕ `continue`, тоест прерисуването СКРИВАШЕ
    //   находката. Обосновката беше „прерисуването чете наново от паметта,
    //   значи екранът се самопоправя". Чужд одит го ОБОРИ с пример:
    //   js/rooms9.js:487 вика `рисувайИст()`, а тя чете масива В ПАМЕТТА, не
    //   от склада — екранът НЕ се самопоправя и мама вижда записан ред, който
    //   го няма. Тоест изключението криеше истински дефекти.
    //   Сега прерисуването само СВАЛЯ ТЕЖЕСТТА, не изтрива находката: кое
    //   точно чете една функция не се вижда статично, а уред няма право да
    //   мълчи за нещо, което не може да докаже.
    const прерисува = ПРЕРИСУВА.test(ред) || ПРЕРИСУВА.test(след);
    находки.push({
      място: име + ':' + (i + 1),
      ред: ред.trim().slice(0, 76),
      тежест: прерисува ? '🔶 обявява успех, но има прерисуване (виж дали чете от склада)'
            : имаЧисти ? '🔴🔴 чисти и полето'
            : '🔴 обявява успех'
    });
  }
  return { находки, записи };
}

const файлове = fs.readdirSync('js').filter(f => f.endsWith('.js') && !/ARCHIVE|PREDI/.test(f)).map(f => 'js/' + f);
let всички = [], записиОбщо = 0, редовеОбщо = 0;
for (const f of файлове) {
  const т = fs.readFileSync(f, 'utf8');
  редовеОбщо += т.split(/\r?\n/).length;
  const р = прегледай(f, т);
  записиОбщо += р.записи;
  всички = всички.concat(р.находки);
}
всички.sort((a, b) => (b.тежест.length - a.тежест.length));

console.log('🤥 ЛЪЖЛИВ УСПЕХ — „✔ Записано" върху нищо\n');
console.log('  ПРЕГЛЕДАНИ ФАЙЛОВЕ : ' + файлове.length);
console.log('  ПРЕГЛЕДАНИ РЕДОВЕ  : ' + редовеОбщо.toLocaleString('bg'));
console.log('  ЗАПИСИ НАМЕРЕНИ    : ' + записиОбщо + '   (от тях с проверен отговор: ' + (записиОбщо - всички.length) + ')');
console.log('  ' + (всички.length ? '🔴' : '✅') + ' ЛЪЖЛИВИ           : ' + всички.length + '\n');
