//                    и при 31 от тях полето на майката СЕ ИЗЧИСТВАШЕ
//     js/women*.js — 76 места
//     js/quickadd, js/pump, js/expr — още няколко
//     js/daily.js  — глобалният слушател за чернови, тоест ЦЯЛОТО приложение
// Всяко от тях беше поправено на ръка. Този файл прави така, че да не могат
// да се върнат — и да се виждат новите, преди да стигнат до майка.
//
// КАКВО Е ДЕФЕКТЪТ, КАЗАНО ТОЧНО:
//   `save(...)` връща да/не (или гърми в празна уловка), отговорът се хвърля,
//   и веднага след това се показва потвърждение. При пълна памет или в
//   частен режим мама вижда „🔒 Заключено", полето ѝ се чисти, и текстът ѝ
//   изчезва ДВА пъти: от паметта и от екрана.
//
// ПРАВИЛОТО, вече приложено в целия проект:
//   записващата функция ВРЪЩА да/не · при „не" се казва честно (общото
//   window.BL_ZAPIS_PADNA, js/rooms.js:41) · полето се чисти САМО след
//   ПОТВЪРДЕН запис.
//   ⚠️ И не през BL_FX.cheer — той МЪЛЧИ при тежък ден и при намалено
//   движение (fx.js:93), тоест точно в деня, когато мама е отбелязала 😩.
//
// КАК СЕ ХВАЩА:
//   Търси се запис, чийто отговор е ХВЪРЛЕН (самостоятелен израз, не в `if`,
//   не в `const x =`, не в `return`), и в следващите няколко реда — дума за
//   успех или изчистване на поле.
//
// 🪤 КАПАНИТЕ, ЗАРАДИ КОИТО ПРАВИЛОТО Е ТАКА:
//   · Запис в „режим огън и забрави" (брояч на посещения, отметка „видяно")
//     НЕ е дефект — там няма какво да се губи. Затова се иска и ДУМА ЗА
//     УСПЕХ наблизо: без нея няма лъжа.
//   · `if (!save(...))` и `const ок = save(...)` са ПРАВИЛНИТЕ шаблони и се
//     пропускат — иначе уредът щеше да вика срещу вече поправеното.
//   · Кирилица: обратна наклонена черта + b НЕ работи в JavaScript. Не се
//     ползва никъде тук.
//   · CRLF: файловете са с CRLF → делим на /\r?\n/.
//   · ARCHIVE/PREDI копия не се броят — те са минало.
//
// ПУСКАНЕ: node dev/lazhliv_uspeh.js [--spisak]
// ПЪТ НАЗАД: файлът само ЧЕТЕ. Изход 1 при находка.
