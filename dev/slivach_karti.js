// ═══ ГЕЙТЪТ ═══
function ГЕЙТ(к, видени) {
  if (!к || typeof к !== 'object') return 'не е обект';
  const липсва = ['id', 'room', 'title', 'core', 'tip', 'keys'].filter(f => !к[f] ||
    (Array.isArray(к[f]) ? !к[f].length : !String(к[f]).trim()));
  if (липсва.length) return 'липсват полета: ' + липсва.join(', ');
  if (!/^[a-z][a-z0-9-]{2,39}$/.test(к.id)) return 'id не е латиница-кебаб: ' + к.id;
  if (КАРТИ.has(к.id)) return 'id ВЕЧЕ съществува в базата';
  if (видени && видени.has(к.id)) return 'id се повтаря в стажа (взет от ' + видени.get(к.id) + ')';
  if (!СТАИ.has(к.room)) return 'непозната стая „' + к.room + '"';

  const текст = [к.title, к.core, к.tip, к.follow || ''].join('\n');
  if (/["']/.test(текст)) return 'ПРАВА КАВИЧКА или апостроф — трябват „ и "';
  if (ДОЗА.test(текст)) return 'ДОЗА на лекарство';
  if (ОБЕЩАНИЯ.test(текст)) return 'обещание („гарантирано" / „100%")';

  if (!Array.isArray(к.keys)) return 'keys не е масив';
  if (к.keys.length < 8) return 'само ' + к.keys.length + ' ключа (под 8)';
  const прави = к.keys.filter(k => /["']/.test(String(k)));
  if (прави.length) return прави.length + ' ключа с права кавичка';
  const главни = к.keys.filter(k => /[А-Я]/.test(String(k)));
  if (главни.length) return главни.length + ' ключа с главна буква (майката пише с малки)';
  // ключ-крадец
  const крадени = к.keys.filter(k => ЖИВИ_КЛЮЧОВЕ.has(String(k).toLowerCase()));
  if (крадени.length) return крадени.length + ' ключа ВЕЧЕ са на друга карта: ' +
    крадени.slice(0, 3).map(k => '„' + k + '"→' + ЖИВИ_КЛЮЧОВЕ.get(String(k).toLowerCase())).join(', ');
  // 🔴 ПРАВИЛО, КОЕТО НАПИСАХ И ОБОРИХ В СЪЩАТА СЕСИЯ — оставено като урок.
  //    Идеята беше вярна: ключ с пълен член („хвърля хранАТА") не вижда
  //    въпроса без него („хвърля храна"). Но изразът /[а-я](та|то|те|ът)/
  //    не различава ЧЛЕНУВАНО ДОПЪЛНЕНИЕ от нормална дума. Той обяви
  //    „детето вижда как ме бие" за счленен ключ — а майка пише точно така;
  //    никой не казва „дете вижда как ме бие". На сухия пробег правилото
  //    отхвърли 10 ДОБРИ карти, включително най-тежките за насилието.
  //    Затова тук то само БРОИ и предупреждава. Мярка, която не различава
  //    двата случая, няма право да отказва.

  for (const ч of (к.chips || [])) {
    if (ч === к.id) return 'чип към самата себе си';
    if (!КАРТИ.has(ч) && !(видени && видени.has(ч))) return 'чип към несъществуваща карта: ' + ч + ' (не гърми — изчезва)';
  }
  for (const п of ['от', 'до']) {
    if (к[п] != null && (typeof к[п] !== 'number' || к[п] < -9 || к[п] > 216)) return п + ' е странно число: ' + к[п];
  }
  if (к.от != null && к.до != null && к.от > к.до) return 'от > до';
  // 🚨 по средата на follow НЕ Е ПОВОД ЗА ОТКАЗ — това е поправимо и се
  //    поправя автоматично по-долу (изречението с 🚨 се вдига най-отпред).
  //    Отказът тук би изхвърлил точно картите, които НАЙ-МНОГО трябват.
  if (String(к.core).split(/\s+/).length > 190) return 'core е роман: ' + String(к.core).split(/\s+/).length + ' думи';
  // 🔗 статия, която не съществува, води майката в нищото — и не гърми
  for (const л of [].concat(к.lib || []).filter(Boolean)) {
    if (!СТАТИИ.has(л)) return 'lib сочи несъществуваща статия: ' + л;
  }
  return null;
}

