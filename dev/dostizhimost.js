#!/usr/bin/env node
/* eslint-disable */
// ═══════════════════════════════════════════════════════════════════════════
// 🎯 ДОСТИЖИМОСТ — коя карта НЕ МОЖЕ да бъде намерена по собствената си тема
// ═══════════════════════════════════════════════════════════════════════════
//
// ЗАЩО (05.09): шест изпита показаха един и същи капан — карта с много
// ключове действа като МАГНИТ и поглъща въпросите на съседките си
// („Колко мляко трябва да яде бебето“ дърпаше седем чужди въпроса за
// кърменето). Обратната страна на същия капан е карта, до която НИКОГА не
// се стига, защото по-силна съседка я бие на всеки въпрос.
//
// МЯРКАТА: за всяка карта се задава нейното СОБСТВЕНО ЗАГЛАВИЕ като въпрос,
// в нейната собствена стая. Ако отговорът е ДРУГА карта — тази е недостижима
// по темата си. Това е най-мекият възможен тест: ако картата не се намира
// дори по заглавието си, майката няма как да я намери.
//
// ⚠️ ТОЗИ ФАЙЛ САМО ЧЕТЕ.
// ПУСКАНЕ: node dev/dostizhimost.js [--vsichki]
// Изход: 0 = под прага, 1 = над прага.
// ═══════════════════════════════════════════════════════════════════════════
'use strict';
const fs = require('fs');
const path = require('path');
const КОРЕН = path.resolve(__dirname, '..');
process.chdir(КОРЕН);
const ВСИЧКИ = process.argv.includes('--vsichki');
const W = require(path.join(КОРЕН, 'dev/pyasachnik.js')).zaredi(null);

const питай = (т, с) => {
  try {
    const р = W.BL_MATCH(т, с);
    const з = Array.isArray(р) ? р[0] : (р && (р.entry || р.item || р));
    return з ? з.id : null;
  } catch (e) { return null; }
};
// заглавието се чисти от украсата, за да прилича на въпрос
const катоВъпрос = т => String(т || '')
  .replace(/[„“"”]/g, ' ')
  .replace(/\s*[—–-]\s*.*$/, '')      // маха обяснението след тире
  .replace(/[?!.]+$/, '')
  .replace(/\s+/g, ' ').trim();

const мълчат = [], чужди = [];
for (const e of W.KB.entries) {
  const въпрос = катоВъпрос(e.title);
  if (въпрос.length < 6) continue;
  const о = питай(въпрос, e.room);
  if (!о) мълчат.push({ id: e.id, t: e.title, q: въпрос, room: e.room });
  else if (о !== e.id) чужди.push({ id: e.id, t: e.title, q: въпрос, взе: о, room: e.room });
}

console.log('');
console.log('  🎯 ДОСТИЖИМОСТ ПО СОБСТВЕНОТО ЗАГЛАВИЕ · ' + W.KB.entries.length + ' карти');
console.log('');
console.log('  ' + (мълчат.length ? '🔴' : '✅') + ' карти, чието заглавие не намира НИЩО: ' + мълчат.length);
for (const x of мълчат.slice(0, ВСИЧКИ ? 999 : 20))
  console.log('     ' + x.id.padEnd(26) + ' „' + x.q.slice(0, 46) + '“');
if (!ВСИЧКИ && мълчат.length > 20) console.log('     … и още ' + (мълчат.length - 20));
console.log('');
console.log('  ' + (чужди.length ? '🟠' : '✅') + ' карти, чието заглавие отива при ДРУГА карта: ' + чужди.length);
for (const x of чужди.slice(0, ВСИЧКИ ? 999 : 25))
  console.log('     ' + x.id.padEnd(24) + ' „' + x.q.slice(0, 34) + '“ → ' + x.взе);
if (!ВСИЧКИ && чужди.length > 25) console.log('     … и още ' + (чужди.length - 25));

const общо = мълчат.length + чужди.length;
console.log('');
console.log('  ── ' + общо + ' от ' + W.KB.entries.length + ' карти (' +
  (общо * 100 / W.KB.entries.length).toFixed(1) + '%) не се намират по темата си ──');
console.log('');
// Прагът е записан, за да се вижда движението, а не да се обявява „чисто“.
const ПРАГ = 40;
console.log('  ' + (общо <= ПРАГ ? '✅ под прага (' + ПРАГ + ')' : '🔴 над прага (' + ПРАГ + ')'));
console.log('');
process.exit(общо <= ПРАГ ? 0 : 1);
