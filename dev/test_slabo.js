function питай(W, q, стая) {
  let m = null;
  try { m = W.BL_MATCH(q, стая); } catch (e) {}
  const ид = (m && (m.id || (m.entry && m.entry.id))) || null;
  let слабо = null;
  try { слабо = W.BL_SLABO ? !!W.BL_SLABO() : null; } catch (e) {}
  return { ид, слабо };
}

