// ═══════════════════════════════════════════════════════════
// 🕳️ ЗАСТОЯЛИТЕ — файл, който се е сменил, а номерът му ?v= не
//
// НАЙ-ТИХИЯТ ДЕФЕКТ В ПРОЕКТА. Поправката се качва, живото я има, всички
// проверки светят зелено — а майката пак вижда старото, защото браузърът ѝ
// има кеширан файл на СЪЩИЯ адрес. Нищо не гърми. Никой не разбира.
//
// ИЗМЕРЕНО 18.08 (флот, фронт „версиите"): към живото 1 от 110 ресурса беше
// застоял — js/lib.js. Съдържанието му се е сменило ПЕТ пъти
// (9d8cda0e → 2dfa4a1e → 7fc1a950 → e30a0967 → 05c1b815), а ?v= стоеше на 51
// от самото начало. Тоест двигателят на библиотеката и вътрешното ѝ LV са
// стигали до майките в СТАРА версия през цялото време.
//
// 🪤 И ПРИЧИНАТА БЕШЕ В УРЕДА, КОЙТО ПАЗИ ОТ ТОВА:
// dev/versii_po_sadarjanie.js питаше „вдигнат ли е вече js/lib.js?" така:
//     редове.some(r => r.indexOf('js/lib.js ') === 2)
// Но редът за LV, който самият той добавя три реда по-горе, изглежда точно
// така: „  js/lib.js LV           55 → 56". Условието беше винаги вярно и
// вдигането се прескачаше НИКОГА да не стане. Пазачът причиняваше дефекта.
// Сега там има явно множество `вдигнати`, а тук — независима проверка.
//
// КАК МЕРИ (без да вярва на ничий доклад):
// за всеки ресурс с ?v= в index.html намира ПОСЛЕДНИЯ комит, в който неговият
// номер се е сменил, и сравнява съдържанието му ТОГАВА със съдържанието СЕГА.
// Различават ли се — файлът е застоял и промените в него не стигат до майката.
//
// ПУСКАНЕ: node dev/zastoyali.js
// ПЪТ НАЗАД: файлът само ЧЕТЕ (git show + четене от диска). Нищо не записва.
// ═══════════════════════════════════════════════════════════
const { execSync } = require('child_process');
const fs = require('fs');
const crypto = require('crypto');
const path = require('path');
process.chdir(path.resolve(__dirname, '..'));

const g = c => { try { return execSync(c, { encoding: 'utf8', stdio: ['ignore', 'pipe', 'ignore'] }); } catch (e) { return ''; } };
const хеш = s => crypto.createHash('md5').update(s).digest('hex').slice(0, 8);

const html = fs.readFileSync('index.html', 'utf8');
const ресурси = [...html.matchAll(/((?:js|css)\/[A-Za-z0-9_.-]+\.(?:js|css))\?v=(\d+)/g)]
  .map(m => ({ файл: m[1], v: m[2] }));
// един файл може да е включен два пъти — броим го веднъж
const уник = [];
const видени = new Set();
for (const р of ресурси) { if (видени.has(р.файл)) continue; видени.add(р.файл); уник.push(р); }

const комити = g('git log --format=%H').split('\n').filter(Boolean);   // най-новият пръв
console.log('🕳️ ЗАСТОЯЛИТЕ\n');
console.log('  ресурси с ?v= в index.html: ' + уник.length + '  (от ' + ресурси.length + ' включвания)');
console.log('  комити в историята: ' + комити.length + '\n');

const застояли = [], безИстория = [];
let проверени = 0;

for (const р of уник) {
  if (!fs.existsSync(р.файл)) { безИстория.push({ ...р, защо: 'няма го на диска' }); continue; }
  const сега = хеш(fs.readFileSync(р.файл, 'utf8').replace(/\r\n/g, '\n'));

  // намираме комита, в който ?v= на този файл за последно е СМЕНЕН
  const ЕСК = р.файл.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
  const re = new RegExp(ЕСК + '\\?v=(\\d+)');
  let комитНаНомера = null, предишен = null;
  for (const c of комити) {
    const h = g('git show ' + c + ':index.html');
    if (!h) break;
    const m = h.match(re);
    if (!m) break;
    if (предишен === null) { предишен = m[1]; комитНаНомера = c; continue; }
    if (m[1] !== предишен) break;          // тук номерът е бил друг → предният комит е моментът
    комитНаНомера = c;
  }
  if (!комитНаНомера) { безИстория.push({ ...р, защо: 'няма история' }); continue; }
  проверени++;

  const тогава = g('git show ' + комитНаНомера + ':' + р.файл);
  if (!тогава) { безИстория.push({ ...р, защо: 'файлът липсва в онзи комит' }); continue; }
  const хТогава = хеш(тогава.replace(/\r\n/g, '\n'));
  if (хТогава !== сега) {
    // колко комита са минали междувременно
    const бр = g('git rev-list --count ' + комитНаНомера + '..HEAD').trim();
    застояли.push({ ...р, тогава: хТогава, сега: сега, откога: комитНаНомера.slice(0, 7), комита: бр });
  }
}

console.log('  ПРОВЕРЕНИ: ' + проверени + '  ·  без история: ' + безИстория.length + '\n');
if (!застояли.length) {
  console.log('  ✅ нито един файл не е застоял — всяка смяна на съдържание си има свой номер');
  process.exit(0);
}
console.log('  🔴 ЗАСТОЯЛИ: ' + застояли.length + '\n');
console.log('  файл                     ?v=   съдържание тогава → сега      от комит   комита оттогава');
застояли.forEach(з => console.log('  ' + з.файл.padEnd(24) + з.v.padEnd(6) +
  з.тогава + ' → ' + з.сега + '        ' + з.откога + '   ' + з.комита));
console.log('\n  Лек: вдигни ?v= на всеки от тях в index.html и вдигни CACHE в sw.js.');
console.log('  Иначе поправките в тези файлове НЕ стигат до майка с кеширано копие.');
process.exit(1);
