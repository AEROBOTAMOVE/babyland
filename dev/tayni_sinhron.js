// ═══════════════════════════════════════════════════════════
// 🗝️ РАЗМИНАХА ЛИ СЕ ТАЙНИТЕ — пазач срещу мълчаливо изтичане
//
// ЗАЩО (25.08.2026): списъкът „кое НЕ влиза в копието за споделяне" стоеше
// преписан дума по дума в js/profile.js:933 и js/rooms2.js:1633. Ако утре
// някой добави ключ само на едното място, копието от другия екран ще носи
// тайната — и НИЩО няма да го покаже. Мама ще прати файла, вярвайки на
// надписа „🔒 Копие без тайните (за споделяне)".
//
// СЛЕД 25.08 източникът е ЕДИН: js/tayni.js. Този пазач следи три неща:
//   1. и двата файла ЧЕТАТ общия списък (а не свой преписан);
//   2. картите зад катинара (js/secrets.js) имат съответните си ключове —
//      иначе карта е скрита от палец, но пътува във файла;
//   3. няма ключ, който сам се обявява за таен по име (secret/tayn/private)
//      и да е оставен незащитен.
//
// 🪤 КАПАНИ:
//   · CRLF → делим на /\r?\n/.
//   · ARCHIVE/PREDI копия не се броят.
//   · Проверката за „чете ли общия списък" гледа за BL_ТАЙНИ В САМИЯ РЕД или
//     в четирите реда над него — резервният израз отдолу е позволен нарочно.
//
// ПУСКАНЕ: node dev/tayni_sinhron.js     (изход 1 при находка)
// ПЪТ НАЗАД: файлът само ЧЕТЕ.
// ═══════════════════════════════════════════════════════════
const fs = require('fs');
const path = require('path');
process.chdir(path.resolve(__dirname, '..'));

function прочети(f) { try { return fs.readFileSync(f, 'utf8'); } catch (e) { return ''; } }

const тайни = прочети('js/tayni.js');
// 🪤 НЕ по целия файл! Първата ми версия вадеше всяко bl_wm_* от js/tayni.js
//   и обяви 15 заключени ключа. А пет от тях са изброени в КОМЕНТАРА за онова,
//   което НАРОЧНО НЕ Е заключено. Тоест пазачът щеше да твърди, че е защитено
//   точно това, което не е — най-лошият възможен вид грешка за пазач.
//   Четем САМО масива `списък:`.
const мСписък = тайни.match(/списък\s*:\s*\[([\s\S]*?)\]/);
const общиУникални = мСписък ? [...new Set(мСписък[1].match(/bl_[a-z0-9_]+/g) || [])].sort() : [];
if (!общиУникални.length) { console.log('🔴 не намирам масива `списък` в js/tayni.js'); process.exit(2); }
// и сверяваме масива с регулярния израз — двата в един файл също могат да се разминат
const мИзраз = тайни.match(/ключове\s*:\s*\/\^\(([^)]+)\)/);
const вИзраза = мИзраз ? мИзраз[1].split('|').map(s => s.trim()).sort() : [];

// къде се решава кое влиза в копието
const ПОТРЕБИТЕЛИ = ['js/profile.js', 'js/rooms2.js'];
const находки = [];
let прегледаниРедове = 0;

for (const f of ПОТРЕБИТЕЛИ) {
  const т = прочети(f);
  const L = т.split(/\r?\n/);
  прегледаниРедове += L.length;
  let намерен = false, ползваОбщия = false;
  L.forEach((ред, i) => {
    if (!/ЗАКЛЮЧЕНИ\s*=/.test(ред)) return;
    намерен = true;
    const около = L.slice(Math.max(0, i - 4), i + 3).join(' ');
    if (/BL_ТАЙНИ/.test(около)) ползваОбщия = true;
  });
  if (!намерен) находки.push(f + ' — НЯМА списък ЗАКЛЮЧЕНИ (преместен? преименуван?)');
  else if (!ползваОбщия) находки.push(f + ' — има СВОЙ преписан списък, не чете js/tayni.js');
}

// картите зад катинара ↔ ключовете
const secr = прочети('js/secrets.js');
const мТайни = secr.match(/const ТАЙНИ = \/\^?([^/]+)\//);
const бройКарти = мТайни ? мТайни[1].split('|').length : 0;

// ключ, който сам се обявява за таен, но не е защитен
const всичкиКлючове = new Set();
for (const f of fs.readdirSync('js').filter(x => x.endsWith('.js') && !/ARCHIVE|PREDI/.test(x))) {
  const т = прочети('js/' + f);
  прегледаниРедове += 0;
  (т.match(/bl_[a-z0-9_]+/g) || []).forEach(k => всичкиКлючове.add(k));
}
const самообявени = [...всичкиКлючове].filter(k => /secret|tayn|private|intim/i.test(k));
const незащитени = самообявени.filter(k => общиУникални.indexOf(k) < 0);

console.log('🗝️ РАЗМИНАХА ЛИ СЕ ТАЙНИТЕ\n');
console.log('  ПРЕГЛЕДАНИ ФАЙЛОВЕ  : ' + (ПОТРЕБИТЕЛИ.length + 1 + fs.readdirSync('js').filter(x => x.endsWith('.js')).length));
console.log('  ПРЕГЛЕДАНИ РЕДОВЕ   : ' + прегледаниРедове.toLocaleString('bg'));
console.log('  ключове в js/tayni.js : ' + общиУникални.length + '   (' + общиУникални.join(', ') + ')');
console.log('  карти зад катинара    : ' + бройКарти + '   (js/secrets.js)');
console.log('  ключове с „тайна" в името : ' + самообявени.length + '\n');

if (незащитени.length) находки.push('ключове, които сами се наричат тайни, но не са в списъка: ' + незащитени.join(', '));
if (вИзраза.join(',') !== общиУникални.join(','))
  находки.push('в js/tayni.js изразът и масивът се разминават — израз: ' + вИзраза.length + ', масив: ' + общиУникални.length);

console.log('  ' + (находки.length ? '🔴' : '✅') + ' НАХОДКИ: ' + находки.length);
находки.forEach(x => console.log('     🔴 ' + x));

// ── САМОПРОВЕРКА в ДВЕТЕ посоки ───────────────────────────
// Пазач, който не може да гръмне, е украса. Тук му се подават два реда с
// известен отговор: единият чете общия списък, другият има свой преписан.
function пробаРед(редове) {
  let намерен = false, общ = false;
  редове.forEach((ред, i) => {
    if (!/ЗАКЛЮЧЕНИ\s*=/.test(ред)) return;
    намерен = true;
    if (/BL_ТАЙНИ/.test(редове.slice(Math.max(0, i - 4), i + 3).join(' '))) общ = true;
  });
  return { намерен, общ };
}
const добър = пробаРед(['const ЗАКЛЮЧЕНИ = (window.BL_ТАЙНИ && window.BL_ТАЙНИ.ключове) ||', '  /^(bl_wm_diary)$/;']);
const лош = пробаРед(['const ЗАКЛЮЧЕНИ = /^(bl_wm_diary|bl_wm_confess)$/;']);
const няма = пробаРед(['const НЕЩО_ДРУГО = 1;']);
const пров = [
  [добър.намерен && добър.общ, 'ХВАЛИ файл, който чете общия списък'],
  [лош.намерен && !лош.общ, 'ХВАЩА файл със свой преписан списък'],
  [!няма.намерен, 'ХВАЩА липсващ списък']
];
console.log('\n  САМОПРОВЕРКА (иначе нулата горе не значи нищо):');
let паднала = false;
пров.forEach(([д, т]) => { if (!д) паднала = true; console.log('     ' + (д ? '✅' : '🔴') + ' ' + т); });
if (паднала) { console.log('\n  🔴 САМОПРОВЕРКАТА ПАДНА.'); process.exit(2); }

if (!находки.length) console.log('\n  Двата екрана съдят по едно и също правило.');
process.exit(находки.length ? 1 : 0);
