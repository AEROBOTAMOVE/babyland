// 🪤 И СОБСТВЕНАТА МИ МЯРКА МЕ ПОДВЕДЕ ДВА ПЪТИ:
//   · първата версия беше НЕСИМЕТРИЧНА — окастряше само въпроса, не и
//     ключовете, и затова подценяваше печалбата
//   · втората върна 0 за всичко и изглеждаше информативна, а беше счупена
//   Проработи чак когато я пуснах срещу въпрос, за който ЗНАМ отговора.
