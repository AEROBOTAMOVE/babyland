//   За останалите 7 морфологията хваща ЕДНОЗНАЧНО: НУЛА.
//   Те мълчат по СЪВСЕМ ДРУГА причина — липсва им карта или ключ изобщо:
//     „зъбите му се разминават" · „памперсът протича" · „играчките са
//     навсякъде" · „пелените свършиха"      — няма такава тема
//     „крачетата му са студени" · „лигите текат постоянно" — картата ИМА,
//        но ключът ѝ е „студени крачета" и „лигави се постоянно"
