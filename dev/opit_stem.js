'use strict';
const fs = require('fs');
const path = require('path');
const КОРЕН = path.resolve(__dirname, '..');
process.chdir(КОРЕН);

const W = require(path.join(КОРЕН, 'dev/pyasachnik.js')).zaredi(null);

// ── ЛЕКО ОКАСТРЯНЕ. Нарочно плитко: маха САМО определителния член и
//    най-честите окончания. Дълбок стемър би слял думи, които не бива
//    („спи" и „спир"), а цената на такова сливане е грешен отговор. ──
const ЧЛЕН = /(ята|ето|ите|ъта|та|то|те|ът|ят|я|а)$/;
const МИН = 5;                               // под 5 букви не се пипа
function окастри(дума) {
  if (дума.length < MIN_LEN()) return дума;
  const к = дума.replace(ЧЛЕН, '');
  return к.length >= 3 ? к : дума;
}
function MIN_LEN() { return МИН; }
const норм = низ => String(низ || '').toLowerCase()
  .split(/\s+/).map(окастри).join(' ');

// ═══ 1 · КОЛКО КЛЮЧА ИЗОБЩО СЕ МЕНЯТ ═══
const всички = [];
for (const e of W.KB.entries) for (const k of (e.keys || [])) всички.push({ k: String(k), id: e.id });
const менени = всички.filter(x => норм(x.k) !== x.k.toLowerCase());

console.log('');
console.log('  🧪 ОПИТ: морфологичен слой — СТРУВА ЛИ СИ');
console.log('');
console.log('  ключове общо        : ' + всички.length);
console.log('  които се променят   : ' + менени.length + '  (' + (менени.length * 100 / всички.length).toFixed(1) + '%)');

// ═══ 2 · СБЛЪСЪЦИ: два РАЗЛИЧНИ ключа на РАЗЛИЧНИ карти, които стават еднакви ═══
const по = new Map();
for (const x of всички) {
  const н = норм(x.k);
  if (!по.has(н)) по.set(н, new Set());
  по.get(н).add(x.id);
}
const сблъсъци = [...по.entries()].filter(([, идове]) => идове.size > 1);
console.log('  НОВИ СБЛЪСЪЦИ       : ' + сблъсъци.length +
  '  (два ключа на РАЗЛИЧНИ карти стават еднакви след окастряне)');
if (сблъсъци.length) {
  console.log('     Това е ЦЕНАТА. Всеки такъв е място, където матчърът вече няма да');
  console.log('     може да различи двете карти. Първите десет:');
  for (const [н, идове] of сблъсъци.slice(0, 10)) {
    const оригинали = всички.filter(x => норм(x.k) === н).map(x => '„' + x.k + '"→' + x.id);
    console.log('     🟠 „' + н + '"  ← ' + [...new Set(оригинали)].slice(0, 3).join(' · '));
  }
}

// ═══ 3 · ПЕЧАЛБАТА: върху ИСТИНСКИ мълчания от изпитите ═══
// Тези въпроси са от свежите изпити и са ИЗМЕРЕНИ като мълчащи или грешни
// в момента на изпита. Тук се пита само едно: щеше ли окастрянето да ги хване.
const ИЗПИТНИ = [
  ['хвърля храната', 'Захранване'], ['спи само на ръцете', 'Моето бебе'],
  ['кърменето боли', 'Захранване'], ['зъбите му се разминават', 'Здраве и SOS'],
  ['коремчето е подуто', 'Здраве и SOS'], ['пелените свършиха', 'Инструменти'],
  ['дрямката е къса', 'Моето бебе'], ['температурата не пада', 'Здраве и SOS'],
  ['млякото ми намаля', 'Захранване'], ['шевовете ме болят', 'Жената в мен'],
  ['движенията намаляха', 'Бременност'], ['контракциите започнаха', 'Бременност'],
  ['памперсът протича', 'Инструменти'], ['гърнето не му харесва', 'Развитие и игри'],
  ['играчките са навсякъде', 'Развитие и игри'], ['вечерята му не се яде', 'Захранване'],
  ['зъбките никнат', 'Здраве и SOS'], ['ноктите растат бързо', 'Моето бебе'],
  ['крачетата му са студени', 'Моето бебе'], ['лигите текат постоянно', 'Развитие и игри']
];
const питай = (т, с) => {
  try { const р = W.BL_MATCH(т, с); const з = Array.isArray(р) ? р[0] : (р && (р.entry || р.item || р)); return з ? з.id : null; }
  catch (e) { return null; }
};
// „щеше ли да хване" се проверява така: питаме с ОКАСТРЕНАТА форма на въпроса
// срещу СЕГАШНАТА база. Ако сега мълчи, а окастреното намира — значи слоят
// щеше да я затвори. (Приблизително: истинският слой би окастрил и ключовете.)
// 🪤 ПЪРВАТА МИ ВЕРСИЯ БЕШЕ НЕСИМЕТРИЧНА и затова подценяваше печалбата:
//    окастряше САМО въпроса и питаше СЕГАШНАТА база с неокастрени ключове.
//    Истинският слой би окастрил ДВЕТЕ страни. Затова тук се проверява
//    точно това: има ли картата ключ, който СЛЕД окастряне се съдържа в
//    окастрения въпрос — тоест дали двустранното окастряне би го хванало.
const двустранноХваща = (въпрос) => {
  const нв = ' ' + норм(въпрос) + ' ';
  const попадения = [];
  for (const e of W.KB.entries) {
    for (const k of (e.keys || [])) {
      const нк = норм(k);
      if (нк.split(/\s+/).length < 2) continue;          // голите думи не решават сами
      if (нв.indexOf(' ' + нк + ' ') >= 0 || нв.indexOf(нк) >= 0) { попадения.push(e.id); break; }
    }
  }
  return [...new Set(попадения)];
};

let сегаМълчат = 0, окастреноНамира = 0, многозначни = 0;
const печалби = [];
for (const [т, с] of ИЗПИТНИ) {
  const сега = питай(т, с);
  if (сега) continue;
  сегаМълчат++;
  const кандидати = двустранноХваща(т);
  if (кандидати.length === 1) { окастреноНамира++; печалби.push([т, кандидати[0]]); }
  else if (кандидати.length > 1) { многозначни++; печалби.push([т, кандидати.slice(0, 3).join(' / ') + '  ⚠️ ' + кандидати.length + ' кандидата']); }
}
console.log('');
console.log('  ── ПЕЧАЛБАТА върху 20 членувани въпроса ──');
console.log('     сега мълчат             : ' + сегаМълчат + ' от ' + ИЗПИТНИ.length);
console.log('     двустранното окастряне ги намира ЕДНОЗНАЧНО: ' + окастреноНамира);
  console.log('     а дава ПОВЕЧЕ ОТ ЕДИН кандидат   : ' + многозначни + '  (тоест не решава, а размива)');
for (const [т, id] of печалби.slice(0, 10)) console.log('     ✅ „' + т.padEnd(28) + '" → ' + id);

// ═══ 4 · ПРИСЪДА ═══
console.log('');
console.log('  ── ПРИСЪДА ──');
const цена = сблъсъци.length;
const полза = окастреноНамира;
if (сегаМълчат === 0) {
  console.log('     ⚪ Върху този набор НЯМА какво да се печели — и 20-те вече намират');
  console.log('        карта. Значи ключовият подход е стигнал дотук БЕЗ морфология,');
  console.log('        и хипотезата не се потвърждава от този набор.');
} else {
  console.log('     полза: ' + полза + ' от ' + сегаМълчат + ' мълчания се затварят');
  console.log('     цена : ' + цена + ' нови сблъсъка между карти');
  console.log('     Съотношението решава. Под 1:1 не си струва — грешният отговор');
  console.log('     е по-скъп от мълчанието.');
}
console.log('');
console.log('  ⚠️ Каквото и да покаже това число, смяна на матчъра НЕ се прави');
console.log('     без пълен пояс: корпусът от 1016 изречения, обиколката от 167');
console.log('     проверки и свеж изпит ПРЕДИ и СЛЕД, на едни и същи въпроси.');
console.log('');
