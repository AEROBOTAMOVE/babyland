// ═══════════════════════════════════════════════════════════
// 🔤 КИРИЛИЦА-ПАЗАЧ — мъртвите решетки
//
// Защо съществува (04.08.2026, обиколката):
//   В JavaScript `\w` е САМО [A-Za-z0-9_]. Кирилицата не е дума за
//   него. А `\b` се дефинира ПРЕЗ `\w`. Оттам две тихи смърти, за
//   които конзолата мълчи:
//     1) `\w` до кирилица → съвпада с ПРАЗЕН низ.
//        „прав\w* ако“ всъщност иска буквално „прав ако“.
//     2) `\b` до кирилица → не се задейства НИКОГА.
//        „\bвече\b“ изглежда като проверка, а е мъртъв код.
//
//   Хванато наживо: „страх ме е да не се задави“ трябваше да мине по
//   тихия път (мама пита предварително), а вдигна сирена с 112.
//   По-лошото: моят собствен тест в Python каза, че всичко е наред —
//   там `\w` е уникоден. Тестът в друг двигател е предположение,
//   не доказателство.
//
// КАК СЕ ПУСКА (в конзолата на приложението):
//   const s=document.createElement('script'); s.src='dev/kirilica.js'; document.body.appendChild(s);
//
// ПЪТ НАЗАД: файлът само ЧЕТЕ. Нищо не пипа. Изтриването му не чупи нищо.
// ═══════════════════════════════════════════════════════════

(async function () {
  const КИР = /[Ѐ-ӿ]/;

  // Кои файлове са ЖИВИ — четат се от index.html, не се гадаят.
  const html = await (await fetch('index.html?k=' + Date.now())).text();
  const файлове = [];
  const реСкрипт = /<script[^>]+src=["']([^"'?]+)/g;
  let m;
  while ((m = реСкрипт.exec(html))) if (m[1].endsWith('.js')) файлове.push(m[1]);

  // Груб изваждач на регулярни литерали. Нарочно груб: търсим само два
  // шаблона, а те не се крият в низове по случайност.
  function решетки(ред) {
    const из = [];
    const re = /\/((?:[^\/\\\n\[]|\\.|\[(?:[^\]\\]|\\.)*\])+)\/[gimsuy]*/g;
    let x;
    while ((x = re.exec(ред))) из.push(x[1]);
    return из;
  }

  const находки = [];

  for (const ф of файлове) {
    let текст;
    try { текст = await (await fetch(ф + '?k=' + Date.now())).text(); }
    catch (e) { console.warn('не се чете:', ф); continue; }

    текст.split('\n').forEach(function (ред, i) {
      if (/^\s*\/\//.test(ред)) return;              // цял ред коментар
      for (const тяло of решетки(ред)) {
        if (!КИР.test(тяло)) continue;               // решетка без кирилица — не ни е работа

        // ⚠️ ВЪТРЕ В КЛАС [...] нещата стоят обратно:
        //    `[^\wа-яё\s]` е ПРАВИЛНИЯТ начин — \w покрива латиницата,
        //    а-яё дописва кирилицата. А `\b` в клас изобщо не е граница,
        //    а знакът backspace. Затова класовете се изрязват ПРЕДИ
        //    проверката. (Първата версия на този пазач вдигна 8 фалшиви
        //    тревоги точно тук — за малко да „поправя“ верен код.)
        const голо = тяло.replace(/\[(?:[^\]\\]|\\.)*\]/g, '§');
        if (!КИР.test(голо)) continue;

        const w = /(?:[Ѐ-ӿ]\\[wW]|\\[wW][*+?{]*\s*[Ѐ-ӿ])/.exec(голо);
        if (w) находки.push({ ф: ф, ред: i + 1, вид: '\\w до кирилица → съвпада с ПРАЗНО', къс: w[0], тяло: тяло });

        const b = /(?:[Ѐ-ӿ]\\b|\\b[Ѐ-ӿ])/.exec(голо);
        if (b) находки.push({ ф: ф, ред: i + 1, вид: '\\b до кирилица → НЕ се задейства никога', къс: b[0], тяло: тяло });
      }
    });
  }

  console.log('%c🔤 КИРИЛИЦА-ПАЗАЧ', 'font-size:15px;font-weight:700');
  console.log('прегледани живи файла: ' + файлове.length);

  if (!находки.length) {
    console.log('%c✅ ЧИСТО — нито един \\w или \\b до кирилица.', 'color:#2e7d32;font-weight:700');
    window.BL_КИРИЛИЦА = { чисто: true, находки: [] };
    return;
  }

  console.log('%c🔴 МЪРТВИ РЕШЕТКИ: ' + находки.length, 'color:#c62828;font-weight:700');
  console.table(находки.map(function (н) {
    return { файл: н.ф + ':' + н.ред, вид: н.вид, къс: н.къс,
             решетка: н.тяло.length > 90 ? н.тяло.slice(0, 90) + '…' : н.тяло };
  }));
  console.log('ЛЕКАРСТВОТО:  \\w → [а-я]   ·   \\b → (?![а-я]) или (^|[^а-я])');
  window.BL_КИРИЛИЦА = { чисто: false, находки: находки };
})();
