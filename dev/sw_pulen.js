// tayni.js, glas.js, dve_kopiya.js — сложих ги в index.html и НЕ ги сложих
// в sw.js. Открих го случайно, докато проверявах друго.
// Цената на пропуска: приложението е ОФЛАЙН-ПЪРВО. Файл, който го няма в
// списъка, не влиза в кеша — и мама без мрежа (в парка, в асансьора, в
// провинцията) губи точно тези четири неща: пазача на картите, тайните,
// гласа и предупреждението за две отворени копия. И нищо не гърми:
// страницата се зарежда, просто ѝ липсват парчета.
//
// Този пазач сверява ТРИ неща:
//   1. всичко, което index.html зарежда, да е в sw.js
//   2. всичко, изброено в sw.js, наистина да съществува на диска
//   3. в sw.js да няма файлове, които index.html вече не иска (мъртъв товар)
//
// 🪤 КАПАНИ:
//   · В index.html имената носят `?v=NN`, в sw.js — не. Сравнява се БЕЗ него.
//   · CRLF: делим на /\r?\n/ там, където е нужно.
//   · Кирилица: обратна наклонена черта + b НЕ работи — не се ползва.
//
// ПУСКАНЕ: node dev/sw_pulen.js       (изход 1 при находка)
// ПЪТ НАЗАД: файлът само ЧЕТЕ.
// ═══════════════════════════════════════════════════════════
const fs = require('fs');
const path = require('path');
process.chdir(path.resolve(__dirname, '..'));

function разбор(html, sw) {
  const вИндекс = [...html.matchAll(/(?:src|href)="((?:js|css)\/[a-z0-9_.-]+\.(?:js|css))(\?v=\d+)?"/g)].map(m => m[1]);
  const уник = [...new Set(вИндекс)];
  const вSW = [...new Set([...sw.matchAll(/'((?:js|css)\/[a-z0-9_.-]+\.(?:js|css))/g)].map(m => m[1]))];
  return { уник, вSW, липсват: уник.filter(f => вSW.indexOf(f) < 0) };
}

const html = fs.readFileSync('index.html', 'utf8');
const sw = fs.readFileSync('sw.js', 'utf8');
const р = разбор(html, sw);
const мъртви = р.вSW.filter(f => !fs.existsSync(f));
const излишни = р.вSW.filter(f => р.уник.indexOf(f) < 0 && fs.existsSync(f));

console.log('📴 ОФЛАЙН СПИСЪКЪТ\n');
console.log('  index.html зарежда : ' + р.уник.length + ' файла');
console.log('  sw.js изброява     : ' + р.вSW.length + ' файла');
console.log('  ' + (р.липсват.length ? '🔴' : '✅') + ' ЗАРЕЖДАТ СЕ, НО ГИ НЯМА ОФЛАЙН : ' + р.липсват.length);
р.липсват.forEach(f => console.log('     🔴 ' + f));
console.log('  ' + (мъртви.length ? '🔴' : '✅') + ' В sw.js, но НЕ СЪЩЕСТВУВАТ     : ' + мъртви.length);
мъртви.forEach(f => console.log('     🔴 ' + f));
console.log('  ' + (излишни.length ? '🔶' : '✅') + ' В sw.js, но не се зареждат     : ' + излишни.length);
излишни.slice(0, 10).forEach(f => console.log('     🔶 ' + f));

// версията на кеша трябва да мърда, иначе новият списък не стига до никого
const мВерсия = sw.match(/CACHE\s*=\s*['"`]([^'"`]+)/);
console.log('\n  версия на кеша (CACHE) : ' + (мВерсия ? мВерсия[1] : '🔴 НЕ Я НАМИРАМ'));

// ── САМОПРОВЕРКА в ДВЕТЕ посоки ──
const пробаHTML = '<script src="js/nov.js?v=3"></script><link href="css/a.css">';
const пробаSW1 = "const A = ['css/a.css'];";                       // липсва js/nov.js
const пробаSW2 = "const A = ['css/a.css', 'js/nov.js'];";          // пълен
const п1 = разбор(пробаHTML, пробаSW1), п2 = разбор(пробаHTML, пробаSW2);
const пров = [
  [п1.липсват.length === 1 && п1.липсват[0] === 'js/nov.js', 'ХВАЩА липсващ файл'],
  [п2.липсват.length === 0, 'МЪЛЧИ, когато списъкът е пълен'],
  [п2.уник.indexOf('js/nov.js') >= 0, 'маха ?v=NN преди сравнението (иначе би викало винаги)'],
  [!!мВерсия, 'намира версията на кеша']
];
console.log('\n  САМОПРОВЕРКА (иначе нулата горе не значи нищо):');
let паднала = false;
пров.forEach(([д, т]) => { if (!д) паднала = true; console.log('     ' + (д ? '✅' : '🔴') + ' ' + т); });
if (паднала) { console.log('\n  🔴 САМОПРОВЕРКАТА ПАДНА.'); process.exit(2); }

if (р.липсват.length) {
  console.log('\n  ЛЕКЪТ: добави ги в списъка в sw.js И вдигни CACHE версията —');
  console.log('  без вдигане новият списък не стига до вече инсталирано приложение.');
}
process.exit((р.липсват.length + мъртви.length) ? 1 : 0);
