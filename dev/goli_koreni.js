// ═══════════════════════════════════════════════════════════════════════
// 🪤 ГОЛИТЕ КОРЕНИ — думата, която живее ВЪТРЕ в друга дума
//
// ЗАЩО СЪЩЕСТВУВА (08.09.2026, платен ТРИ ПЪТИ за един ден):
//     „а ако"  улучва „нА АКО"      → „повръщаното мирише на ако"
//     „сега"   улучва „отСЕГА"      → „…хватката при задавяне отсега" = 112
//     „вече"   улучва „ВЕЧЕр"       → „плаче всяка вечер" отменяше пазач
//   И преди тях: „изчакай" улучва „НЕ изчаквай"; „ужил" улучва „заслУЖИЛа".
//   Всеки път лекът е един и същ и всеки път се прилага на ЕДНО място.
//
//   А в самия js/helper.js СТОИ коментар, писан по-рано:
//       „\b е мъртво до кирилица — то се дефинира ПРЕЗ \w"
//   Тоест урокът е бил научен, записан — и приложен само там, където е болял.
//   Този файл го прилага НАВСЯКЪДЕ, наведнъж, и всеки ден оттук нататък.
//
// УСТРОЙСТВОТО:
//   1. Вади всички образци от js/helper.js — и /литерали/, и низовете,
//      подавани на new RegExp(...).
//   2. Разбива ги на алтернативи по | (само на горно ниво).
//   3. Оставя ГОЛИТЕ: чиста кирилица, без котва, без клас, 3-7 знака.
//   4. РЕЧНИКЪТ НЕ Е ИЗМИСЛЕН: думите идват от js/kb.js — това са думите,
//      които приложението наистина показва и получава. Ако корен се среща
//      вътре в ДРУГА дума оттам, той е капан ЗА ТОЗИ ПРОЕКТ, не на теория.
//   5. Пропуска образец, който вече е ограден с (^|[^а-я]) и (?![а-я]).
//
// ЗАЩО НЕ ПАДА (изход 0 при находки):
//   Не всеки гол корен е дефект — „кръв" вътре в „кръвта" е ЖЕЛАНО.
//   Затова уредът СОРТИРА по опасност и ИЗПИСВА, а не съди. Пада само ако
//   не може да прочете файловете (изход 2) — тоест ако е сляп.
//
// ПУСКАНЕ: node dev/goli_koreni.js [--vsichki] [--nad N]
// ПЪТ НАЗАД: файлът само ЧЕТЕ.
// ═══════════════════════════════════════════════════════════════════════
const fs = require('fs');
const path = require('path');
const ROOT = path.resolve(__dirname, '..');

const ВСИЧКИ = process.argv.includes('--vsichki');
const НАД = (() => { const i = process.argv.indexOf('--nad'); return i > -1 ? Number(process.argv[i + 1]) || 1 : 1; })();

const МОЗЪК = path.join(ROOT, 'js/helper.js');
const БАЗА = path.join(ROOT, 'js/kb.js');
for (const f of [МОЗЪК, БАЗА]) if (!fs.existsSync(f)) { console.log('🔴 липсва ' + f + ' — СЛЯП'); process.exit(2); }
const src = fs.readFileSync(МОЗЪК, 'utf8');
const kb = fs.readFileSync(БАЗА, 'utf8');

// ── 1 · РЕЧНИКЪТ: думите, които приложението наистина ползва ──
const КИР = /[а-яёѝА-ЯЁЍ]{3,}/g;
const думи = new Set();
let m;
while ((m = КИР.exec(kb))) думи.add(m[0].toLowerCase());
while ((m = КИР.exec(src))) думи.add(m[0].toLowerCase());
if (думи.size < 2000) { console.log('🔴 речникът е ' + думи.size + ' думи — това е СЛЯПА сонда'); process.exit(2); }
const списък = Array.from(думи);

// ── 2 · ОБРАЗЦИТЕ ──
const образци = [];
const ЛИТ = /\/((?:[^\/\\\n\[]|\\.|\[(?:[^\]\\\n]|\\.)*\])+)\/[gimsuy]*/g;
while ((m = ЛИТ.exec(src))) if (/[а-яё]/i.test(m[1])) образци.push({ вид: 'литерал', тяло: m[1], ред: src.slice(0, m.index).split('\n').length });
const НИЗ = /"((?:[^"\\\n]|\\.){6,})"/g;
while ((m = НИЗ.exec(src))) if (m[1].indexOf('|') > -1 && /[а-яё]/i.test(m[1])) образци.push({ вид: 'низ', тяло: m[1], ред: src.slice(0, m.index).split('\n').length });
if (образци.length < 50) { console.log('🔴 намерени са само ' + образци.length + ' образеца — СЛЯП'); process.exit(2); }

// ── 3 · АЛТЕРНАТИВИТЕ ──
// Разбива по | само на нулево ниво на скобите — иначе „(а|б)в" се къса грешно.
function алтернативи(p) {
  const вън = [];
  let дълбочина = 0, клас = false, тек = '';
  for (let i = 0; i < p.length; i++) {
    const c = p[i];
    if (c === '\\') { тек += c + (p[i + 1] || ''); i++; continue; }
    if (клас) { тек += c; if (c === ']') клас = false; continue; }
    if (c === '[') { клас = true; тек += c; continue; }
    if (c === '(') { дълбочина++; тек += c; continue; }
    if (c === ')') { дълбочина--; тек += c; continue; }
    if (c === '|' && дълбочина === 0) { вън.push(тек); тек = ''; continue; }
    тек += c;
  }
  вън.push(тек);
  // и вътрешностите на групите, защото там живеят повечето
  //
  // 🪞 ПЪРВАТА ВЕРСИЯ НА ТОЗИ ФАЙЛ ОБЯВИ 314 НАХОДКИ И ПОЧТИ ВСИЧКИТЕ БЯХА
  //    МОИ. Тя четеше „ята|ите|ата|ето" като голи думи — а те са ОКОНЧАНИЯ
  //    в група, залепена за стъбло: „[а-я]*(ята|ите)". Групата, залепена за
  //    буква отляво или отдясно, НЕ Е самостоятелна дума и не може да е гол
  //    корен. Затова тук се гледа знакът ПРЕДИ „(" и СЛЕД ")".
  //    Втори филтър: коренът трябва да е ИСТИНСКА самостоятелна дума в
  //    текста на приложението. „нст" и „ичка" не са.
  const вътре = [];
  const ГР = /\(([^()]*)\)/g;
  let g;
  while ((g = ГР.exec(p))) {
    const преди = g.index > 0 ? p[g.index - 1] : '';
    const след = p[g.index + g[0].length] || '';
    const залепена = /[а-яё\]*+?)]/i.test(преди) || /[а-яё]/i.test(след);
    if (залепена) continue;
    for (const част of g[1].split('|')) вътре.push(част);
  }
  return вън.concat(вътре);
}

// ── ВТОРИ ФИЛТЪР: коренът трябва да е ИСТИНСКА самостоятелна дума ──
//   Тоест да се среща в текста на приложението, ограден с не-букви.
//   Това маха „нст", „ичка", „ване" — фрагменти, не думи.
const самостоятелни = new Set();
{
  const ДУМА_САМА = /(^|[^а-яёѝА-ЯЁЍ])([а-яёѝ]{3,7})(?![а-яёѝА-ЯЁЍ])/gi;
  let d;
  const всичко = kb + '\n' + src;
  while ((d = ДУМА_САМА.exec(всичко))) самостоятелни.add(d[2].toLowerCase());
  if (самостоятелни.size < 1000) { console.log('🔴 самостоятелните думи са ' + самостоятелни.size + ' — СЛЯП'); process.exit(2); }
}

const ЧИСТА_ДУМА = /^[а-яё]{3,7}$/;
const находки = new Map();
for (const о of образци) {
  const ограден = о.тяло.indexOf('(?![а-я])') > -1 && о.тяло.indexOf('[^а-я])') > -1;
  if (ограден) continue;
  for (const а of алтернативи(о.тяло)) {
    const дума = а.trim();
    if (!ЧИСТА_ДУМА.test(дума)) continue;
    if (!самостоятелни.has(дума)) continue;   // фрагмент, не дума
    if (!находки.has(дума)) находки.set(дума, { дума, в: [], образци: [] });
    const н = находки.get(дума);
    if (н.образци.length < 3) н.образци.push('ред ' + о.ред);
  }
}
if (!находки.size) { console.log('✅ нито един гол корен — или сондата е сляпа. Провери.'); process.exit(0); }

// ── 4 · КОЙ КОРЕН ЖИВЕЕ ВЪТРЕ В ДРУГА ДУМА ──
for (const н of находки.values()) {
  for (const д of списък) {
    if (д === н.дума) continue;
    if (д.indexOf(н.дума) > -1) { н.в.push(д); if (н.в.length > 40) break; }
  }
}
const опасни = Array.from(находки.values()).filter(н => н.в.length >= НАД)
  .sort((a, b) => b.в.length - a.в.length);

// ═══════════════════════════════════════════════════════════════════
// 5 · ОТ ПОДОЗРЕНИЕ КЪМ ИЗМЕРВАНЕ
//
// 🪞 ВТОРАТА ВЕРСИЯ НА ТОЗИ ФАЙЛ ПАК ЛЪЖЕШЕ: тя нареждаше 223 „опасни"
//    корена по това В КОЛКО ЧУЖДИ ДУМИ живеят. Но това е ПОДОЗРЕНИЕ, не
//    дефект: „кръв" живее в „кръвта" и това е желано.
//    Списък от подозрения кара човека да чете, вместо да поправя.
//
// Затова оттук нататък уредът НЕ съди по строеж, а ПУСКА:
//    взима думата-капан („отсега", „вечер", „закон"), слага я в СПОКОЙНО
//    изречение и пита приложението какво отговаря. Ако вдигне тревога —
//    това вече не е подозрение, а ИЗМЕРЕН фалшив сигнал, с готов пример.
// ═══════════════════════════════════════════════════════════════════
const { zaredi } = require('./pyasachnik.js');
const W = zaredi(null);
if (typeof W.BL_REDFLAG !== 'function') { console.log('🔴 вратите не се виждат — СЛЯП'); process.exit(2); }
if (W.BL_REDFLAG('бебето не диша') !== true) { console.log('🔴 контролата не гърми — СЛЯП'); process.exit(2); }

function коя(t) {
  try {
    if (typeof W.BL_SHAKEN === 'function' && W.BL_SHAKEN(t)) return 'shaken';
    const m = W.BL_MOTHERFLAG(t); if (m) return m;
    if (W.BL_PREGFLAG(t, null)) return 'preg';
    if (W.BL_REDFLAG(t)) return 'red';
    return null;
  } catch (e) { return null; }
}

// НОСЕЩИТЕ ИЗРЕЧЕНИЯ трябва да са ДОКАЗАНО спокойни, инак мерим тях.
const НОСЕЩИ = [
  д => 'днес говорихме за ' + д + ' и всичко беше спокойно',
  д => 'чудя се за ' + д,
  д => 'прочетох нещо за ' + д + ' в книжката',
];
for (const н of НОСЕЩИ) {
  const контрола = н('шапката');
  if (коя(контрола) !== null) { console.log('🔴 НОСЕЩОТО ИЗРЕЧЕНИЕ САМО ВДИГА ТРЕВОГА: « ' + контрола + ' » → ' + коя(контрола) + ' — СЛЯП'); process.exit(2); }
}

// думите-капани: съдържат гол корен НЕ в началото си
const капани = new Map();
for (const н of находки.values()) {
  for (const д of н.в) {
    if (д.indexOf(н.дума) <= 0) continue;      // в началото — обикновено желано
    if (!капани.has(д)) капани.set(д, new Set());
    капани.get(д).add(н.дума);
  }
}

const хванати = [];
let проби = 0;
for (const [дума, корени] of капани) {
  for (const н of НОСЕЩИ) {
    const изр = н(дума); проби++;
    const г = коя(изр);
    if (г) { хванати.push({ дума, корени: Array.from(корени), изр, г }); break; }
  }
}

console.log('');
console.log('🪤 ГОЛИТЕ КОРЕНИ — ИЗМЕРЕНО, НЕ ПРЕДПОЛОЖЕНО');
console.log('   образци: ' + образци.length + ' · речник: ' + думи.size + ' думи');
console.log('   голи корени: ' + находки.size + ' · думи-капани: ' + капани.size + ' · проби: ' + проби);
console.log('');
console.log('🔴 СПОКОЙНО ИЗРЕЧЕНИЕ, КОЕТО ВДИГА ТРЕВОГА: ' + хванати.length);
const редом = хванати.slice().sort((a, b) => a.дума.localeCompare(b.дума, 'bg'));
for (const х of (ВСИЧКИ ? редом : редом.slice(0, 60))) {
  console.log('   ' + String(х.г).padEnd(10) + ' « ' + х.изр + ' »');
  console.log('              капан: „' + х.корени.join('", „') + '" вътре в „' + х.дума + '"');
}
if (!ВСИЧКИ && редом.length > 60) console.log('   … и още ' + (редом.length - 60) + ' (--vsichki)');
console.log('');
if (!хванати.length) { console.log('✅ нито един гол корен не вдига тревога в спокойно изречение'); process.exit(0); }
console.log('ℹ️ Всяко от горните е ГОТОВ пример за поправка. Присъдата остава човешка:');
console.log('   част от тях може да са уместни („кръвта" при „кръв").');
process.exit(0);
