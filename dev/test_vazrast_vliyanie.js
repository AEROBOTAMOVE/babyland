//    `възрастМесеци()` връща null и полетата са ИНЕРТНИ. Всеки корпус казва
//    „нула регресии" — но той мери приложение, в което възрастта не се знае.
//    Тоест досегашните зелени числа НЕ КАЗВАТ НИЩО за майка, която е въвела
//    рождената дата. А това е повечето майки.
