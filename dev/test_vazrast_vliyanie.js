const fs = require('fs');
const path = require('path');
const ROOT = path.resolve(__dirname, '..');
const { zaredi } = require(path.join(ROOT, 'dev/pyasachnik.js'));

// ── подменяме възрастта: заменяме ТЯЛОТО на функцията с постоянна стойност ──
// 🪤 Котвата се проверява ИЗРИЧНО: ако функцията се преименува утре, уредът
//    трябва да ГРЪМНЕ, а не тихо да мери приложение без възраст.
const КОТВА = 'function възрастМесеци() {';
function сВъзраст(м) {
  return текст => {
    if (текст.indexOf(КОТВА) < 0) throw new Error('НЯМА функция възрастМесеци — уредът мери нещо друго');
    return текст.replace(КОТВА, КОТВА + '\n    return ' + (м === null ? 'null' : м) + ';');
  };
}

const питай = (W, т, с) => {
  try {
    const р = W.BL_MATCH(т, с);
    const з = Array.isArray(р) ? р[0] : (р && (р.entry || р.item || р));
    return з ? з.id : 'ТИШИНА';
  } catch (e) { return 'ГРЕШКА'; }
};

// ── въпросите: взимаме ги от съществуващия корпус, за да не си измислям свои ──
function въпроси() {
  const п = path.join(ROOT, 'dev/tarsene_bez_otgovor.js');
  const т = fs.readFileSync(п, 'utf8');
  const списък = [];
  // редовете са от вида ['въпрос', 'Стая'],
  const Р = /\[\s*'([^']{6,90})'\s*,\s*'([^']{3,30})'\s*\]/g;
  let m;
  while ((m = Р.exec(т))) списък.push([m[1], m[2]]);
  return списък;
}
const ВЪПРОСИ = въпроси();

// спешните — тук отговорът НЕ бива да мърда с възрастта
const СПЕШНИ = [
  ['бебето не диша', 'Здраве и SOS'], ['получи гърч', 'Здраве и SOS'],
  ['устните му посиняха', 'Здраве и SOS'], ['падна и повърна', 'Здраве и SOS'],
  ['температура под 3 месеца', 'Здраве и SOS'], ['кървенето не спира', 'Здраве и SOS'],
  ['глътна лекарство', 'Здраве и SOS'], ['шкафът падна отгоре му', 'Здраве и SOS'],
  ['не мога да го събудя', 'Здраве и SOS'], ['обрив който не избледнява', 'Здраве и SOS'],
  ['кървя силно след раждането', 'Жената в мен'], ['сменям превръзка на час', 'Жената в мен']
];

console.log('');
console.log('🎂 КАКВО ПРАВИ ВЪЗРАСТТА, КОГАТО Я ЗНАЕМ');
console.log('');

// ═══ САМОПРОВЕРКА: наистина ли подмяната работи ═══
// Уред, чиято подмяна мълчаливо не се е приложила, ще обяви „нула промени" за
// всяка възраст — и това ще изглежда точно като чиста база.
let слаби = 0;
try {
  const пробен = zaredi(сВъзраст(24));
  const имаЛи = typeof пробен.BL_MATCH === 'function';
  console.log('   ' + (имаЛи ? '✅' : '🔴') + ' подмяната се зарежда и двигателят работи');
  if (!имаЛи) слаби++;
} catch (e) { console.log('   🔴 подмяната гърми: ' + e.message); слаби++; }
try {
  zaredi(т => { if (т.indexOf('НЯМА ТАКАВА ФУНКЦИЯ') < 0) throw new Error('котвата липсва — както трябва'); return т; });
  console.log('   🔴 липсваща котва НЕ гръмна — уредът може да мери грешно нещо'); слаби++;
} catch (e) { console.log('   ✅ липсваща котва ГЪРМИ (уредът не мери мълчаливо друго)'); }

// и най-важното: при РАЗЛИЧНИ възрасти двигателят наистина ли дава различно?
const пробаА = zaredi(сВъзраст(1)), пробаБ = zaredi(сВъзраст(36));
let различни = 0;
// 🪤 Първо мерех само първите 60 въпроса и след една поправка тази проверка
//    обяви ЖИВО поле за инертно — двете разлики в извадката бяха точно
//    случаите, които поправката затвори. Извадка, по-малка от ефекта, лъже.
for (const [т, с] of ВЪПРОСИ) if (питай(пробаА, т, с) !== питай(пробаБ, т, с)) различни++;
console.log('   ' + (различни > 0 ? '✅' : '🔴') + ' възрастта ВЛИЯЕ: ' + различни + ' различни отговора между 1 и 36 месеца (от ' + ВЪПРОСИ.length + ')');
if (различни === 0) { слаби++; console.log('      🔴 нула разлика значи, че полето е инертно — мярката отдолу няма смисъл'); }
if (слаби) { console.log(''); console.log('   🔴 УРЕДЪТ Е СЧУПЕН — не му вярвай'); process.exit(1); }
console.log('');

// ═══ МЕРЕНЕ ═══
const W0 = zaredi(сВъзраст(null));
const основа = ВЪПРОСИ.map(([т, с]) => питай(W0, т, с));
const основаСпешни = СПЕШНИ.map(([т, с]) => питай(W0, т, с));
const мълчаливиВОсновата = основа.filter(x => x === 'ТИШИНА').length;

console.log('   основа (възрастта НЕ се знае): ' + ВЪПРОСИ.length + ' въпроса · ' + мълчаливиВОсновата + ' тишини');
console.log('');
console.log('   възраст    смени отговор   НОВА ТИШИНА   спешни мръднали');
console.log('   ' + '─'.repeat(58));

let общоЧервено = 0;
const подробно = [];
for (const м of [1, 6, 18, 36]) {
  const W = zaredi(сВъзраст(м));
  let смени = 0, новаТишина = 0;
  const тишини = [];
  ВЪПРОСИ.forEach(([т, с], i) => {
    const г = питай(W, т, с);
    if (г !== основа[i]) смени++;
    if (г === 'ТИШИНА' && основа[i] !== 'ТИШИНА') { новаТишина++; тишини.push(т); }
  });
  let спешниМръднали = 0;
  const мърднали = [];
  СПЕШНИ.forEach(([т, с], i) => {
    const г = питай(W, т, с);
    if (г !== основаСпешни[i]) { спешниМръднали++; мърднали.push(т + ': ' + основаСпешни[i] + ' → ' + г); }
  });
  const червено = новаТишина > 0 || спешниМръднали > 0;
  if (червено) общоЧервено++;
  console.log('   ' + (червено ? '🔴' : '✅') + ' ' + String(м + ' мес.').padEnd(9) +
    String(смени).padStart(9) + String(новаТишина).padStart(14) + String(спешниМръднали).padStart(17));
  подробно.push({ месеци: м, смени, новаТишина, тишини: тишини.slice(0, 8), спешниМръднали, мърднали });
}
console.log('');

for (const p of подробно) {
  if (!p.новаТишина && !p.спешниМръднали) continue;
  console.log('   ── ' + p.месеци + ' месеца ──');
  for (const т of p.тишини) console.log('      🔇 занемя: „' + т + '"');
  for (const м of p.мърднали) console.log('      🚨 спешен смени отговора: ' + м);
  console.log('');
}

fs.writeFileSync(path.join(__dirname, 'test_vazrast_vliyanie.json'), JSON.stringify(подробно, null, 1));
console.log('   💾 dev/test_vazrast_vliyanie.json');
console.log('');
if (общоЧервено) {
  console.log('   🔴 ' + общоЧервено + ' от 4 възрасти губят отговор или местят спешно.');
  console.log('      Възрастовото поле НЕ бива да отнема отговор — само да подрежда.');
} else {
  console.log('   ✅ нито една възраст не отнема отговор и не мести спешно.');
  console.log('      Полето подрежда, без да скрива — точно каквото е замислено.');
}
console.log('');
process.exit(общоЧервено ? 1 : 0);
