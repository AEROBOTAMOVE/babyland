// Този уред подменя възрастта на четири стойности и мери какво се мести:
//    1 месец (новородено) · 6 месеца · 18 месеца · 36 месеца
//
// Правилото на двигателя: несъответствие × 0.55 (потъва), съвпадение × 1.15.
// Тоест никоя карта не бива да ИЗЧЕЗВА — но може да падне под друга. Уредът
// брои точно това и вика ЧЕРВЕНО, ако:
//    · въпрос, който е намирал отговор, започне да мълчи
//    · СПЕШЕН въпрос смени отговора си
