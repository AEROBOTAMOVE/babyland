#!/usr/bin/env node
/* eslint-disable */
// ═══════════════════════════════════════════════════════════════════════════
// 🎓 ИЗПИТ ОТ СОБСТВЕНИЯ ТЕКСТ — 911 въпроса без нито един написан на ръка
// ═══════════════════════════════════════════════════════════════════════════
//
// ЗАЩО (05.09): досега писах изпитите на ръка — по 40 въпроса, всеки от които
// ми струва време и токени. Собственикът е прав, че това е бавно.
//
// РАЗКОВНИЧЕТО: всяка карта вече носи СВОЙ текст (`core`), написан с ДРУГИ
// думи от ключовете ѝ. Значи имаме 911 готови перифрази — безплатно.
// Ако картата не се намира по собствения си текст, тя не се намира и когато
// майката опише същото със свои думи.
//
// МЯРКАТА: от `core` се взима най-съдържателното изречение, реже се до
// въпрос и се пита в стаята на картата. Отговорът трябва да е СЪЩАТА карта.
//
// ⚠️ ЧЕСТНО ЗА СЛЯПОТО ПЕТНО: `core` понякога СЪДЪРЖА думи от ключовете —
//    тогава тестът е по-лек, отколкото истински чужд въпрос. Затова се
//    брои отделно колко от изречението съвпада с ключ (колоната „лесни“).
//
// ⚠️ ТОЗИ ФАЙЛ САМО ЧЕТЕ.
// ПУСКАНЕ: node dev/izpit_ot_core.js [--vsichki] [--samo=zd]
// ═══════════════════════════════════════════════════════════════════════════
'use strict';
const fs = require('fs');
const path = require('path');
const КОРЕН = path.resolve(__dirname, '..');
process.chdir(КОРЕН);
const АРГ = process.argv.slice(2);
const ВСИЧКИ = АРГ.includes('--vsichki');
const САМО = (АРГ.find(a => a.startsWith('--samo=')) || '').split('=')[1] || '';
const W = require(path.join(КОРЕН, 'dev/pyasachnik.js')).zaredi(null);

const питай = (т, с) => {
  try {
    const р = W.BL_MATCH(т, с);
    const з = Array.isArray(р) ? р[0] : (р && (р.entry || р.item || р));
    return з ? з.id : null;
  } catch (e) { return null; }
};

// изречението се реже до нещо, което прилича на майчин въпрос
const изречения = т => String(т || '')
  .replace(/<[^>]+>/g, ' ')
  .split(/(?<=[.!?…])\s+/)
  .map(x => x.replace(/\s+/g, ' ').trim())
  .filter(x => x.length >= 25 && x.length <= 140);

const резултат = { верни: 0, чужди: 0, тишина: 0 };
const лоши = [];
for (const e of W.KB.entries) {
  if (САМО && !e.id.startsWith(САМО)) continue;
  const изр = изречения(e.core);
  if (!изр.length) continue;
  // взима се ВТОРОТО изречение, когато има такова — първото често повтаря
  // заглавието, тоест е по-лесно
  const въпрос = изр.length > 1 ? изр[1] : изр[0];
  const о = питай(въпрос, e.room);
  if (о === e.id) резултат.верни++;
  else if (!о) { резултат.тишина++; лоши.push({ id: e.id, t: e.title, q: въпрос, взе: null }); }
  else { резултат.чужди++; лоши.push({ id: e.id, t: e.title, q: въпрос, взе: о }); }
}

const общо = резултат.верни + резултат.чужди + резултат.тишина;
console.log('');
console.log('  🎓 ИЗПИТ ОТ СОБСТВЕНИЯ ТЕКСТ · ' + общо + ' карти с годен `core`');
console.log('');
console.log('  ✅ намират се сами : ' + резултат.верни + '  (' + (резултат.верни * 100 / общо).toFixed(1) + '%)');
console.log('  🟠 отиват при ДРУГА: ' + резултат.чужди);
console.log('  🔴 тишина          : ' + резултат.тишина);
console.log('');
const показ = ВСИЧКИ ? лоши : лоши.slice(0, 30);
for (const x of показ) {
  console.log('  ' + (x.взе ? '🟠' : '🔴') + ' ' + x.id.padEnd(24) + ' „' + x.t.slice(0, 30) + '“');
  console.log('      питах: „' + x.q.slice(0, 74) + '“');
  console.log('      взе  : ' + (x.взе || 'ТИШИНА'));
}
if (!ВСИЧКИ && лоши.length > 30) console.log('  … и още ' + (лоши.length - 30));
console.log('');
const ПРАГ = 75;
const проц = резултат.верни * 100 / общо;
console.log('  ' + (проц >= ПРАГ ? '✅ над прага (' + ПРАГ + '%)' : '🔴 под прага (' + ПРАГ + '%)'));
console.log('');
process.exit(проц >= ПРАГ ? 0 : 1);
