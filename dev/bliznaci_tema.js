// от 11 агента ги съди ЕДНА ПО ЕДНА. Четири излязоха истински дубли и са слети
// (zah-parvo→zh-parvo · lb-koliki→mb-colic · zah-koga→zh-koga-start ·
// in-prava-rabota→nia-prava-rabota). Осемте, които остават, са прегледани и
// имат РАЗЛИЧНИ РОЛИ — записани тук, за да не се преоткриват:
//   zh-koga-start / zh-parvo   — КОГА да започна срещу С КАКВО да започна
//   nia-work / nia-prava-rabota — чувството при връщането срещу закона
//   br-dvizhenie / nia-dvijenie — движение ПО ВРЕМЕ на бременността срещу СЛЕД
//   rz-inat-2g / rz-hiperaktiven — какво правя в бурята срещу има ли диагноза
//   zh-milk-qty / zh-koga-start — колко мляко СЛЕД захранването срещу кога
//   rz-hvarlia / zh-hvarlia    — хвърля при ИГРА срещу хвърля ХРАНАТА
//   nia-koya / dn-tatko-priznaci — общата им дума е само коренът „позна-"
//   mb-cry / lb-opasen-plach   — нормалният плач срещу тревожният
