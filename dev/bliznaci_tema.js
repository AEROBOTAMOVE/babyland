// 🔴 КАК СЕ НАМЕРИ ДУПКАТА (01.09):
//    Гледах Лабораторията и видях две карти:
//        lb-zashto7  „Защо опитът е 7 вечери"
//        em-why7     „Защо седем вечери"
//    ЕДНА И СЪЩА ТЕМА, написана два пъти, в ЕДНА И СЪЩА стая.
//    А `dev/bliznaci.js` казваше 0 истински близнаци — и беше „прав" по
//    собственото си правило: то търси СПОДЕЛЕНИ КЛЮЧОВЕ, а тези две карти
//    делят НУЛА ключа. Едната пише цифрата „7", другата думата „седем".
//
//    Тоест пазачът е сляп за точно най-лошия случай: тема, писана два пъти
//    от различни хора с различни думи. Колкото по-различно са написани, толкова
//    по-невидими са — а точно тогава е най-вероятно да са дубъл.
//
// ТАЗИ ЛЕЩА гледа ЗАГЛАВИЕТО и ТЯЛОТО, не ключовете. Сравнява ги след
// сводене: цифрите стават думи, окончанията се режат, служебните думи падат.
// ═══════════════════════════════════════════════════════════
const fs = require('fs');
const vm = require('vm');
const К = __dirname + '/../';

const ЦИФРИ = { '1': 'едно', '2': 'две', '3': 'три', '4': 'четири', '5': 'пет', '6': 'шест', '7': 'седем', '8': 'осем', '9': 'девет', '10': 'десет', '12': 'дванайсет', '24': 'двайсет и четири', '40': 'четирийсет' };
const СЛУЖЕБНИ = new Set(['и', 'а', 'но', 'или', 'да', 'не', 'се', 'си', 'е', 'са', 'ще', 'че', 'за', 'на', 'в', 'с', 'от', 'по', 'до', 'при', 'като', 'ли', 'то', 'ти', 'аз', 'ми', 'му', 'ѝ', 'им', 'ги', 'го', 'я', 'ме', 'те', 'кое', 'кой', 'коя', 'как', 'кога', 'какво', 'къде', 'защо', 'колко', 'един', 'една', 'едно', 'този', 'тази', 'това', 'моето', 'моя', 'моите']);

// сводене: цифра→дума · малки букви · режем окончанието (последните 2 знака при дълги думи)
// 🪤 01.09, ВТОРА ПОПРАВКА: рязането по ДВЕ букви от края беше сляпо за
//    членуването и за глаголните окончания. Живо намерено: четири карти за
//    началото на захранването стояха като две неразпознати двойки —
//    „С какво се започва" срещу „С какво да започнем?" даваше „започ" срещу
//    „започн", тоест два различни корена за една дума. Сведение по ПРЕФИКС
//    от пет букви: точно там седи членът на български.
//    ⚠️ Същата поправка беше направена в dev/statii_bliznaci.js — двете лещи
//    трябва да се сведят ЕДНАКВО, иначе едната лови това, което другата не.
const корен = w => w.length > 5 ? w.slice(0, 5) : w;
const сведи = t => {
  let s = String(t || '').toLowerCase();
  for (const [ц, д] of Object.entries(ЦИФРИ)) s = s.replace(new RegExp('(^|[^0-9])' + ц + '([^0-9]|$)', 'g'), '$1' + д + '$2');
  return (s.match(/[а-яё]+/g) || []).filter(w => w.length > 2 && !СЛУЖЕБНИ.has(w)).map(корен);
};
// 🪤 ВТОРА ПОПРАВКА НА ЛЕЩАТА: първият вариант даде 34 двойки, но половината
//    бяха шум — „Документите след раждането" и „Сексът след раждането" делят
//    само „след раждането", фраза, която стои в 30 заглавия. Затова думите се
//    ТЕГЛЯТ по рядкост: дума, срещана навсякъде, почти не тежи.
let ТЕЖЕСТ = new Map();
const тежи = w => ТЕЖЕСТ.get(w) || 1;
const жакар = (a, b) => {
  const A = new Set(a), B = new Set(b);
  if (!A.size || !B.size) return 0;
  let общи = 0, обед = 0;
  for (const x of A) { обед += тежи(x); if (B.has(x)) общи += тежи(x); }
  for (const x of B) if (!A.has(x)) обед += тежи(x);
  return обед ? общи / обед : 0;
};

// ── САМОПРОВЕРКА В ДВЕТЕ ПОСОКИ — иначе лещата е украса ──
const пробаА = жакар(сведи('Защо опитът е 7 вечери'), сведи('Защо седем вечери'));
const пробаБ = жакар(сведи('Коликите вечер'), сведи('Документите след раждането'));
if (пробаА < 0.4) { console.log('🔴 ЛЕЩАТА Е СЛЯПА: не вижда „7 вечери" = „седем вечери" (' + пробаА.toFixed(2) + ')'); process.exit(1); }
if (пробаБ > 0.1) { console.log('🔴 ЛЕЩАТА ЛЪЖЕ НАГОРЕ: свързва колики с документи (' + пробаБ.toFixed(2) + ')'); process.exit(1); }
console.log('  ✅ самопроверка: „7 вечери"≈„седем вечери" ' + пробаА.toFixed(2) + '  ·  колики≉документи ' + пробаБ.toFixed(2));

const ctx = { console: { log() {}, warn() {} }, JSON, Math, Date, RegExp, String, Number, Array, Object };
ctx.window = ctx; ctx.self = ctx; vm.createContext(ctx);
new vm.Script(fs.readFileSync(К + 'js/kb.js', 'utf8')).runInContext(ctx);
const З = ctx.KB.entries;

// IDF: колко заглавия съдържат думата. Дума в 1-2 заглавия тежи 1;
// дума в 30 заглавия тежи почти нищо.
{
  const бр = new Map();
  for (const z of З) for (const w of new Set(сведи(z.title))) бр.set(w, (бр.get(w) || 0) + 1);
  for (const [w, n] of бр) ТЕЖЕСТ.set(w, Math.log(З.length / n) / Math.log(З.length));
}
const гол = h => String(h || '').replace(/<[^>]+>/g, ' ');
const подготвени = З.map(z => ({
  z, загл: сведи(z.title), тяло: сведи(гол(z.core) + ' ' + гол(z.tip)),
  ключове: new Set((z.keys || []).map(k => String(k).toLowerCase()))
}));

const находки = [];
for (let i = 0; i < подготвени.length; i++) {
  for (let j = i + 1; j < подготвени.length; j++) {
    const a = подготвени[i], b = подготвени[j];
    const сЗагл = жакар(a.загл, b.загл);
    if (сЗагл < 0.5) continue;
    // колко ключа делят БУКВАЛНО — ако делят много, старият пазач вече ги вижда
    let общиКл = 0;
    for (const k of a.ключове) if (b.ключове.has(k)) общиКл++;
    находки.push({ a: a.z, b: b.z, сЗагл, сТяло: жакар(a.тяло, b.тяло), общиКл, ЕднаСтая: a.z.room === b.z.room });
  }
}
находки.sort((x, y) => (y.сЗагл + y.сТяло) - (x.сЗагл + x.сТяло));
const невидими = находки.filter(f => f.общиКл === 0);

console.log('');
console.log('👯 БЛИЗНАЦИ ПО ТЕМА — лещата, която гледа ЗАГЛАВИЕТО, не ключовете');
console.log('');
console.log('  ПРЕГЛЕДАНИ  : ' + З.length + ' карти  (' + (З.length * (З.length - 1) / 2).toLocaleString('bg') + ' двойки)');
console.log('  🔴 ТЕМАТИЧНИ БЛИЗНАЦИ : ' + находки.length + '   (заглавия над 50% еднакви)');
console.log('  🔴 от тях НЕВИДИМИ за стария пазач (0 общи ключа): ' + невидими.length);
console.log('');
for (const f of находки.slice(0, 30)) {
  console.log('  ' + (f.ЕднаСтая ? '🔴 ЕДНА СТАЯ' : '🟠 през стаи') + '  заглавия ' + (f.сЗагл * 100).toFixed(0) + '% · тела ' + (f.сТяло * 100).toFixed(0) + '% · общи ключове ' + f.общиКл);
  console.log('       [' + f.a.room + '] ' + f.a.id.padEnd(22) + ' „' + f.a.title + '"');
  console.log('       [' + f.b.room + '] ' + f.b.id.padEnd(22) + ' „' + f.b.title + '"');
}
fs.writeFileSync(__dirname + '/bliznaci_tema.json', JSON.stringify(находки.map(f => ({ a: f.a.id, at: f.a.title, ar: f.a.room, b: f.b.id, bt: f.b.title, br: f.b.room, zagl: +f.сЗагл.toFixed(2), tialo: +f.сТяло.toFixed(2), obshti: f.общиКл })), null, 1));
console.log('');
console.log('  💾 dev/bliznaci_tema.json');

