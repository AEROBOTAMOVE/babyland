// dev/innerhtml_mama.js — КЪДЕ СОБСТВЕНИЯТ ТЕКСТ НА МАЙКАТА ВЛИЗА В innerHTML.
// Пускане: node dev/innerhtml_mama.js
//
// Въпросът не е „има ли innerHTML" (има го навсякъде — 700+ места).
// Въпросът е: може ли МАЙКАТА да счупи собствения си екран с това, което пише.
// Затова уредът не брои innerHTML, а проследява ВЛОЖКИТЕ (${…} и ' + x + ') и
// пита за всяка: минава ли през екраниране, и идва ли отнякъде, където мама пише.
//
// ⚠️ ПРАВИЛО 1: примамка първо. Долу има фалшив файл с 6 вида вложки —
//    3 опасни, 3 безопасни. Ако уредът не разграничи точно тях, не струва.

const fs = require('fs'), path = require('path');
const КОРЕН = path.resolve(__dirname, '..');

// ── Кои имена значат „мама е писала това" ─────────────────────────────────
// 🔴 ПОПРАВКА след падане на собствената примамка (уредът хвана 1 от 3):
//    писах /\bиме\b/ — а \b и \w В JS НЕ ПОЗНАВАТ КИРИЛИЦА. За низа „име"
//    \b на позиция 0 иска отляво не-дума, отдясно дума: „и" не е \w → няма
//    съвпадение. Всяка кирилска дума в списъка мълчеше. Границата се пише
//    ИЗРИЧНО. Точно капанът от правило 2.
const ДУМА = '[A-Za-zА-Яа-я0-9_$]';
const гр = д => new RegExp('(^|[^' + ДУМА.slice(1, -1) + '])' + д + '([^' + ДУМА.slice(1, -1) + ']|$)', 'i');
const МАМИНИ = [
  гр('име'), гр('името'), гр('ime'), гр('name'), гр('names'),
  гр('бележк[аите]*'), гр('бележник'), гр('notes?'), гр('note'),
  гр('текст[а]?'), гр('text'), гр('val'), гр('value'),
  /\.value\b/, гр('input'), гр('textarea'), гр('вход'),
  гр('мама'), гр('mama'), гр('бебе'), гр('bebe'), гр('baby'),
  /\bload\s*\(/, /localStorage/, гр('съхранено'), гр('запис'),
  гр('отговор[а]?'), гр('въпрос[а]?'), гр('мисъл'), гр('мисли'),
  гр('желание'), гр('мечта'), гр('мечти'), гр('дневник'),
  гр('t'), гр('txt'), гр('s'),
];

// Обвивки, които правят вложката безопасна
const БЕЗОПАСНИ = /^(?:esc|escape|escHtml|ескр|безопасно|encodeURIComponent|Number|parseInt|parseFloat|String\(\s*Number)\s*\(/;

// ── Разбор: намери всяко присвояване .innerHTML = <израз> ─────────────────
// Изразът е до края на statement-а; вземаме балансирано по кавички/скоби.
function вложки(израз) {
  const сп = [];
  // template literal ${...}
  let i = 0;
  while ((i = израз.indexOf('${', i)) !== -1) {
    let дълб = 1, j = i + 2;
    while (j < израз.length && дълб > 0) {
      if (израз[j] === '{') дълб++;
      else if (израз[j] === '}') дълб--;
      if (дълб === 0) break;
      j++;
    }
    сп.push({ вид: '${}', код: израз.slice(i + 2, j) });
    i = j + 1;
  }
  // конкатенация ' + ИЗРАЗ + '  /  " + ИЗРАЗ + "
  const рег = /['"]\s*\+\s*([^+]+?)\s*\+\s*['"]/g;
  let m;
  while ((m = рег.exec(израз))) сп.push({ вид: "+", код: m[1] });
  return сп;
}

function изразСлед(текст, поз) {
  // от '=' до ';' на нулево ниво извън низове/шаблони
  let i = поз, дълб = 0, кав = null, шаб = 0;
  const край = Math.min(текст.length, поз + 6000);
  for (; i < край; i++) {
    const c = текст[i], пред = текст[i - 1];
    if (кав) { if (c === кав && пред !== '\\') кав = null; continue; }
    if (шаб) {
      if (c === '`' && пред !== '\\') { шаб--; continue; }
      if (c === '$' && текст[i + 1] === '{') { дълб++; i++; continue; }
      if (c === '}' && дълб > 0) { дълб--; continue; }
      continue;
    }
    if (c === '"' || c === "'") { кав = c; continue; }
    if (c === '`') { шаб++; continue; }
    if ('([{'.includes(c)) { дълб++; continue; }
    if (')]}'.includes(c)) { дълб--; continue; }
    if (c === ';' && дълб <= 0) break;
    if (c === '\n' && дълб <= 0) {
      // край на ред без ; — гледаме дали следващият започва нов оператор
      const ост = текст.slice(i + 1, i + 60).trim();
      if (!/^[.+?:)\]}]/.test(ост) && !/[+({[,?:]\s*$/.test(текст.slice(Math.max(0, i - 40), i))) break;
    }
  }
  return текст.slice(поз, i);
}

function сканирайФайл(име, текст) {
  const резултат = [];
  const редНа = п => текст.slice(0, п).split(/\r?\n/).length;

  // 1) .innerHTML = …   и   .innerHTML += …
  const рег = /\.innerHTML\s*\+?=\s*/g;
  let m;
  while ((m = рег.exec(текст))) {
    const п = m.index + m[0].length;
    const израз = изразСлед(текст, п);
    резултат.push({ файл: име, ред: редНа(m.index), форма: '.innerHTML=', израз, вложки: вложки(израз) });
  }
  // 2) помощникът el(tag, cls, HTML) — трети довод отива в innerHTML
  const рег2 = /\bel\s*\(\s*(['"][^'"]*['"])\s*,\s*([^,()]*(?:\([^()]*\))?[^,]*)\s*,\s*/g;
  while ((m = рег2.exec(текст))) {
    const п = m.index + m[0].length;
    const израз = изразСлед(текст, п).replace(/\)\s*$/, '');
    const в = вложки(израз);
    if (в.length) резултат.push({ файл: име, ред: редНа(m.index), форма: 'el(,,HTML)', израз, вложки: в });
  }
  // 3) insertAdjacentHTML
  const рег3 = /insertAdjacentHTML\s*\(\s*['"][^'"]+['"]\s*,\s*/g;
  while ((m = рег3.exec(текст))) {
    const п = m.index + m[0].length;
    const израз = изразСлед(текст, п);
    резултат.push({ файл: име, ред: редНа(m.index), форма: 'insertAdjacentHTML', израз, вложки: вложки(израз) });
  }
  return резултат;
}

function прецени(в) {
  const к = в.код.trim();
  if (БЕЗОПАСНИ.test(к)) return { риск: 'екранирано', защо: 'обвито в ' + к.slice(0, к.indexOf('(')) };
  if (/^\d+(\.\d+)?$/.test(к)) return { риск: 'чисто', защо: 'число' };
  // сложен израз: гледаме дали ГОРНОТО ниво е esc(...)
  if (/^esc\s*\(/.test(к)) return { риск: 'екранирано', защо: 'esc' };
  const мами = МАМИНИ.filter(р => р.test(к));
  if (мами.length) return { риск: 'МАМИН', защо: 'съвпада с ' + мами.slice(0, 2).map(String).join(' ') };
  return { риск: 'чуждо?', защо: '' };
}

// ── 0. ПРИМАМКА ───────────────────────────────────────────────────────────
const ПРИМАМКА = `
  const a = document.createElement('div');
  a.innerHTML = \`<p>Здравей, \${име}!</p>\`;                       // ОПАСНО (мамино, голо)
  a.innerHTML = \`<p>Здравей, \${esc(име)}!</p>\`;                  // безопасно
  a.innerHTML = '<b>' + бележка + '</b>';                           // ОПАСНО (мамино, голо)
  a.innerHTML = '<b>' + esc(бележка) + '</b>';                      // безопасно
  a.innerHTML = \`<span>\${бройка}</span>\`;                        // чуждо (не мамино)
  a.insertAdjacentHTML('beforeend', \`<i>\${load('bl_notes','')}</i>\`); // ОПАСНО
`;
const пр = сканирайФайл('(ПРИМАМКА)', ПРИМАМКА);
let прОпасни = 0, прБезопасни = 0;
пр.forEach(р => р.вложки.forEach(в => {
  const о = прецени(в);
  if (о.риск === 'МАМИН') прОпасни++;
  if (о.риск === 'екранирано') прБезопасни++;
}));
console.log('═══ 0. ПРОВЕРКА НА УРЕДА (примамка) ═══');
console.log(`  намерени места: ${пр.length} (очаквани 6)`);
console.log(`  вдигнати като МАМИН/голи: ${прОпасни} (очаквани 3)`);
console.log(`  разпознати като екранирани: ${прБезопасни} (очаквани 2)`);
if (пр.length < 6 || прОпасни < 3 || прБезопасни < 2) {
  console.log('  ❌ УРЕДЪТ Е СЛЯП — не прави разликата.');
  process.exitCode = 2;
} else console.log('  ✅ уредът разграничава голо-мамино от екранирано\n');

// ── 1. Истинското сканиране ───────────────────────────────────────────────
const файлове = fs.readdirSync(path.join(КОРЕН, 'js'))
  .filter(f => /\.js$/.test(f) && !/PREDI|\.BAK|ARCHIVE/.test(f)).map(f => 'js/' + f);
файлове.push('index.html');

const всички = [];
for (const f of файлове) всички.push(...сканирайФайл(f, fs.readFileSync(path.join(КОРЕН, f), 'utf8')));

let бройМеста = всички.length, бройВложки = 0;
const мамини = [], чужди = [], екран = [];
for (const р of всички) for (const в of р.вложки) {
  бройВложки++;
  const о = прецени(в);
  const ред = { файл: р.файл, ред: р.ред, форма: р.форма, код: в.код.replace(/\s+/g, ' ').slice(0, 130), защо: о.защо };
  if (о.риск === 'МАМИН') мамини.push(ред);
  else if (о.риск === 'екранирано' || о.риск === 'чисто') екран.push(ред);
  else чужди.push(ред);
}

console.log('═══ 1. РАЗМЕРЪТ НА ЗАДАЧАТА ═══');
console.log(`  места, които пишат HTML : ${бройМеста}`);
console.log(`  вложки в тях            : ${бройВложки}`);
console.log(`  ├ екранирани/числа      : ${екран.length}`);
console.log(`  ├ ГОЛИ и приличат мамини: ${мамини.length}`);
console.log(`  └ голи, друг произход   : ${чужди.length}`);

console.log('\n═══ 2. ГОЛИ ВЛОЖКИ, КОИТО ПРИЛИЧАТ НА МАМИН ТЕКСТ ═══');
const поФайл = {};
мамини.forEach(r => (поФайл[r.файл] = поФайл[r.файл] || []).push(r));
Object.entries(поФайл).sort((a, b) => b[1].length - a[1].length).forEach(([f, сп]) => {
  console.log(`\n  ▸ ${f} — ${сп.length}`);
  сп.forEach(r => console.log(`      :${String(r.ред).padStart(5)}  ${r.код}`));
});

fs.writeFileSync(path.join(__dirname, 'innerhtml_mama.json'),
  JSON.stringify({ бройМеста, бройВложки, мамини, чужди }, null, 1), 'utf8');
console.log('\n→ dev/innerhtml_mama.json');
