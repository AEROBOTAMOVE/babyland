const fs = require('fs');
const path = require('path');
process.chdir(path.resolve(__dirname, '..'));

const S = 'C:/Users/User/AppData/Local/Temp/claude/C--Users-User-Downloads-----/' +
          'a78d0ad3-272e-4eb0-929e-dba161c5ab2a/scratchpad';
const СПИСЪК = process.argv.includes('--spisak');

let zaredi;
try { zaredi = require(S + '/pyasachnik.js').zaredi; }
catch (e) { console.log('🔴 няма пясъчник: ' + e.message); process.exit(1); }

let корпус;
try { корпус = JSON.parse(fs.readFileSync(S + '/rez350.json', 'utf8')); }
catch (e) { console.log('🔴 няма корпус: ' + e.message); process.exit(1); }

if (!Array.isArray(корпус) || корпус.length < 100) {
  console.log('🔴 корпусът е ' + (корпус && корпус.length) + ' записа — очаквам 350');
  process.exit(1);
}

const W = zaredi(null);

function флагове(т, стая) {
  const из = [];
  try { if (W.BL_REDFLAG(т)) из.push('ЧЕРВЕН'); } catch (e) {}
  try { const m = W.BL_MOTHERFLAG && W.BL_MOTHERFLAG(т); if (m) из.push('МАЙКА:' + m); } catch (e) {}
  // 🪤 19.08: тук се викаше BL_PREGFLAG(т) БЕЗ стая. А pregLevel(text, room)
  //   иска room === 'Бременност' ИЛИ записана дата на цикъл — иначе връща
  //   false за ВСИЧКО. Тоест мярката НЕ ВИЖДАШЕ нито един бременностен флаг
  //   и подценяваше. Стаята идва от самия корпус (полето r).
  try { if (W.BL_PREGFLAG && W.BL_PREGFLAG(т, стая)) из.push('БРЕМЕННОСТ'); } catch (e) {}
  return из;
}

let n = 0, спешни = 0, невинни = 0, карти = 0;
let пропуснати = 0, фалшиви = 0, безОтговор = 0;
const пр = [], фа = [], бо = [];

for (const x of корпус) {
  const т = x.t, о = String(x.e || '').toUpperCase(), стая = x.r || 'Здраве и SOS';
  if (!т || !о) continue;
  n++;
  const ф = флагове(т, стая);
  const имаФлаг = ф.length > 0;

  if (о === 'SPESHNO') {
    спешни++;
    if (!имаФлаг) { пропуснати++; пр.push(т); }
  } else {
    невинни++;
    if (имаФлаг) { фалшиви++; фа.push(т + '   ← ' + ф.join(' + ')); }
  }
  if (о === 'KARTA') {
    карти++;
    let r = null; try { r = W.BL_MATCH(т, стая); } catch (e) {}
    if (!имаФлаг && !r) { безОтговор++; бо.push(т); }
  }
}

console.log('📏 КОРПУСЪТ ОТ 350\n');
console.log('  ПРЕГЛЕДАНИ: ' + n + ' изречения  (спешни ' + спешни +
            ' · невинни ' + невинни + ' · очакващи карта ' + карти + ')\n');
const пц = x => (x * 100).toFixed(0) + '%';
console.log('  🔴 ПРОПУСНАТИ СПЕШНИ : ' + пропуснати + ' от ' + спешни + '  (' + пц(пропуснати / (спешни || 1)) + ')');
console.log('  🟠 ФАЛШИВИ ТРЕВОГИ   : ' + фалшиви + ' от ' + невинни + '  (' + пц(фалшиви / (невинни || 1)) + ')');
console.log('  🟡 БЕЗ ОТГОВОР       : ' + безОтговор + ' от ' + карти + '  (' + пц(безОтговор / (карти || 1)) + ')');

if (СПИСЪК) {
  console.log('\n── ПРОПУСНАТИ СПЕШНИ ──');
  пр.forEach(x => console.log('   🔴 ' + x));
  console.log('\n── ФАЛШИВИ ТРЕВОГИ ──');
  фа.slice(0, 60).forEach(x => console.log('   🟠 ' + x));
  console.log('\n── БЕЗ ОТГОВОР ──');
  бо.slice(0, 40).forEach(x => console.log('   🟡 ' + x));
} else {
  console.log('\n  (пусни с --spisak за поименния списък)');
}
console.log('\n  ЦЕЛТА: пропуснати 0 · фалшиви под 5% · без отговор под 10%');
