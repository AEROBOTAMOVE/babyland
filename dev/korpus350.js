function флагове(т, стая) {
  const из = [];
  try { if (W.BL_REDFLAG(т)) из.push('ЧЕРВЕН'); } catch (e) {}
  try { const m = W.BL_MOTHERFLAG && W.BL_MOTHERFLAG(т); if (m) из.push('МАЙКА:' + m); } catch (e) {}
  // 🪤 19.08: тук се викаше BL_PREGFLAG(т) БЕЗ стая. А pregLevel(text, room)
  //   иска room === 'Бременност' ИЛИ записана дата на цикъл — иначе връща
  //   false за ВСИЧКО. Тоест мярката НЕ ВИЖДАШЕ нито един бременностен флаг
  //   и подценяваше. Стаята идва от самия корпус (полето r).
  try { if (W.BL_PREGFLAG && W.BL_PREGFLAG(т, стая)) из.push('БРЕМЕННОСТ'); } catch (e) {}
  return из;
}

// ── ЕДНО обхождане, изнесено във функция, за да може същата сметка да мери и
//    подставените примамки. Мярка, чиято логика съществува на едно място,
//    може да бъде изпитана; преписана два пъти — не.
function мери(записи) {
  let n = 0, спешни = 0, невинни = 0, карти = 0;
  let пропуснати = 0, фалшиви = 0, безОтговор = 0;
  const пр = [], фа = [], бо = [];

  for (const x of записи) {
    const т = x.t, о = String(x.e || '').toUpperCase(), стая = x.r || 'Здраве и SOS';
    if (!т || !о) continue;
    n++;
    const ф = флагове(т, стая);
    const имаФлаг = ф.length > 0;

    if (о === 'SPESHNO') {
      спешни++;
      if (!имаФлаг) { пропуснати++; пр.push(т); }
    } else if (о === 'NEVINNO') {
      // 🔴 26.08: тук стоеше голо else, тоест ВСЕКИ не-спешен запис влизаше в
      //    сметката за фалшиви тревоги — включително въпросите, които очакват
      //    карта. А сред тях има истински спешни („глътна монета", „опари се с
      //    чай"): приложението вдигаше ВЕРЕН флаг, а пазачът го броеше за
      //    фалшива тревога. Числото сочеше в грешната посока.
      //    Сега фалшивите се мерят САМО срещу нарочно написаните невинни
      //    изречения — онези, за които някой е ГАРАНТИРАЛ, че не са спешни.
      невинни++;
      if (имаФлаг) { фалшиви++; фа.push(т + '   ← ' + ф.join(' + ')); }
    }
    if (о === 'KARTA' || о === 'VUPROS') {   // и двата вида очакват ОТГОВОР — флаг ИЛИ карта
      карти++;
      let r = null; try { r = W.BL_MATCH(т, стая); } catch (e) {}
      if (!имаФлаг && !r) { безОтговор++; бо.push(т); }
    }
  }
  return { n, спешни, невинни, карти, пропуснати, фалшиви, безОтговор, пр, фа, бо };
}

