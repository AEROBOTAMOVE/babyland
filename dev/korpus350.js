// Дотогава меркахме двигателя срещу СОБСТВЕНИТЕ МУ ключове и заглавия. Това е
// несправедливо лесно: майка не пише ключа, тя пише как ѝ дойде. Затова е
// направен корпус от 350 изречения в пет регистъра, писани ОТВЪН:
//   A СПЕШНИ (70)        трябва да вдигнат тревога
//   Б НЕВИННИ (70)       съдържат опасни думи в друг смисъл — трябва да мълчат
//   В ОБИКНОВЕНИ (70)    всекидневни въпроси — трябва да получат карта
//   Г ГРЕШКИ (70)        сгрешено + правилно в двойки (латиница, разменени букви…)
//   Д ГРАНИЧНИ (70)      там, където и човек се колебае
//
// Всяко изречение носи `e` — какво ТРЯБВА да получи:
//   SPESHNO · KARTA · USPOKOENIE · MALCHANIE
//
// 🪤 ЗАЩО ТОЗИ ФАЙЛ, А НЕ „помня числата": първата ми мярка срещу този корпус
// върна 0 от 0, защото гадаех имената на полетата (`text`, `expect`). Те са
// `t` и `e`. Мярка, която не намира данните си, показва нули и изглежда като
// успех. Затова тук долу има ИЗРИЧНА проверка, че корпусът е прочетен.
