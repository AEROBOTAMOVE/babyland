// ═══════════════════════════════════════════════════════════════════════════
// 👋 ПАЗАЧ НА СБОГУВАНЕТО — „лека“ не е „ЛЕКАрката“
// ═══════════════════════════════════════════════════════════════════════════
//
// ЗАЩО (05.09): правилото за сбогуване в js/smalltalk.js беше низ БЕЗ
// граници: /лека нощ|лека|чао|отивам|.../ . Затова
//     „ЛЕКАрката каза друго“        → „Чао, миличка! 💜 Гушни бебето от мен.“
//     „ЛЕКАрствата не помагат“      → същото
//     „бебето има ЛЕКА жълтеница“   → същото
//     „отивам на преглед утре“      → същото
// ИЗМЕРЕНО преди поправката: 16 от 21 проби откраднати.
//
// Сбогуването е ЦЯЛОТО съобщение, не дума вътре в него.
//
// 🧷 ТОЗИ ПАЗАЧ НЕ ПРОВЕРЯВА КОПИЕ. Той изрязва самото правило от
//    js/smalltalk.js и го ИЗПЪЛНЯВА. Смени ли се там — вижда се тук.
//
// ⚠️ ТОЗИ ФАЙЛ САМО ЧЕТЕ.
// ПУСКАНЕ: node dev/sbogom.js
// Изход: 0 = чисто, 1 = крадене или прекалено стягане, 2 = правилото го няма.
// ═══════════════════════════════════════════════════════════════════════════
'use strict';
const fs = require('fs');
const path = require('path');
process.chdir(path.resolve(__dirname, '..'));

const текст = fs.readFileSync('js/smalltalk.js', 'utf8');
const НР = текст.indexOf('\r\n') >= 0 ? '\r\n' : '\n';
const редове = текст.split(НР);
const от = редове.findIndex(x => x.indexOf('{ when: (q) => {') > -1 &&
  редове.slice(x ? 0 : 0).length > 0 && x.indexOf('изрично') < 0);
// намираме блока по неговия пръв ред и го затваряме на реда с `}, say:`
let край = -1;
for (let i = от; i < редове.length && i < от + 40; i++)
  if (редове[i].indexOf('}, say:') > -1) { край = i; break; }
if (от < 0 || край < 0) {
  console.log('');
  console.log('  🔴 ПРАВИЛОТО ЗА СБОГУВАНЕ НЕ СЕ НАМИРА в js/smalltalk.js.');
  console.log('     Това е смисълът на пазача — без него той не мери нищо.');
  console.log('');
  process.exit(2);
}
const тяло = редове.slice(от, край + 1).join(НР)
  .replace('{ when: (q) => {', 'function сбогом(q) {')
  .replace(/\}, say:.*$/, '}');
const сбогом = new Function(тяло + НР + 'return сбогом;')();

// ── ПРОБИ: истинско сбогуване · и въпроси, които НЕ бива да падат в него ──
const ДА = ['лека нощ', 'лека', 'чао', 'чао чао', 'до скоро', 'до утре',
  'приятен ден', 'хайде чао', 'ок чао', 'лека нощ и на теб', 'лека и на теб мила',
  'благодаря лека нощ', 'трябва да вървя', 'отивам да спя', 'тръгвам си'];
const НЕ = ['лекарката каза друго', 'лекарят ми каза да спра',
  'какви лекарства може да пие', 'детето взе лекарството на баба',
  'отивам на преглед утре', 'отивам при педиатъра', 'отивам да го къпя',
  'трябва ли да отивам в спешното', 'лекарствата не помагат', 'болката е лека',
  'температурата е лека', 'лека форма на вирус', 'имам лека кръв в акото',
  'бебето има лека жълтеница', 'до утре имам час при гинеколога',
  'затварям очи и заспивам', 'лекувам гърлото с чай', 'кой лекар лекува това'];

const пропуснати = ДА.filter(т => !сбогом(т));
const откраднати = НЕ.filter(т => сбогом(т));
console.log('');
console.log('  👋 ПАЗАЧ НА СБОГУВАНЕТО · правилото е ИЗПЪЛНЕНО от js/smalltalk.js (ред ' + (от + 1) + ')');
console.log('');
console.log('  ' + (откраднати.length ? '🔴' : '✅') + ' откраднати въпроси: ' + откраднати.length + ' от ' + НЕ.length);
for (const т of откраднати) console.log('       „' + т + '“');
console.log('  ' + (пропуснати.length ? '🔴' : '✅') + ' пропуснати сбогувания: ' + пропуснати.length + ' от ' + ДА.length);
for (const т of пропуснати) console.log('       „' + т + '“');
console.log('');
// Пазач, който хваща само едната посока, лъже: стягането е също дефект.
console.log('  ' + (откраднати.length || пропуснати.length ? '🔴 ЗА ГЛЕДАНЕ' : '✅ ЧИСТО и в двете посоки'));
console.log('');
process.exit(откраднати.length || пропуснати.length ? 1 : 0);
