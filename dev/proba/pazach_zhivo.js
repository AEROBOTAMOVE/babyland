// 🚪 ПАЗАЧ (22.11.2026): проба, която подменя /api (напр. /api/me = 200), върви САМО на местен адрес.
// На живия сайт това е минаване през вратата — само с изричното „да“ на собственика, и то с думите му:
//   --sobstvenikat-kaza-da "22.11: да, пусни я на живо"      (празен флаг или само „1“ не стига; думите се печатат)
// „Да“ от друг чат не е „да“ от собственика.  ПОЛЗВАНЕ: require('./pazach_zhivo.js')(АДРЕС);
module.exports = function пазач(адрес) {
  let дом = ''; try { дом = new URL(адрес).hostname; } catch (e) {}
  if (дом === 'localhost' || дом === '127.0.0.1' || дом === '[::1]' || /\.localhost$/.test(дом)) return;
  const i = process.argv.indexOf('--sobstvenikat-kaza-da');
  const думи = i > -1 ? String(process.argv[i + 1] || '').trim() : '';
  if (думи.length >= 8 && !думи.startsWith('--')) { console.log('🚪 НЕМЕСТЕН адрес ' + (дом || адрес) + ' с подмяна на /api · думите на собственика: ' + думи); return; }
  console.log('🔴 ПАЗАЧ: тази проба подменя /api, а „' + (дом || адрес) + '“ не е местен адрес. Дай --url https://localhost:<порт> (местен сървър на същия комит).');
  console.log('   На живо — само ако собственикът изрично е казал „да“: --sobstvenikat-kaza-da "<думите му>"');
  process.exit(5);
};
