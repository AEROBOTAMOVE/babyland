// ── съчиняване на майчиния въпрос от заглавието
const СЛУЖЕБНИ = new Set(['при', 'след', 'преди', 'през', 'към', 'между', 'без', 'над', 'под',
  'кога', 'какво', 'как', 'защо', 'кое', 'кои', 'кой', 'или', 'това', 'тези', 'която', 'които',
  'срещу', 'според', 'дали', 'още', 'най', 'все', 'вече', 'само', 'също', 'едно', 'една']);
const думи = t => String(t || '').toLowerCase()
  .replace(/[0-9]+[-–][0-9]+/g, ' ').replace(/[^а-яa-z\s]/g, ' ')
  .split(/\s+/).filter(w => w.length >= 4 && !СЛУЖЕБНИ.has(w));

function намери(q, ид, room) {
  let r;
  try { r = L.search(q, room || '', 10) || []; } catch (e) { return -1; }
  const списък = Array.isArray(r) ? r : (r.items || r.резултати || []);
  for (let i = 0; i < списък.length; i++) {
    const x = списък[i];
    const id = x && (x.id || (x.it && x.it.id) || (x[1] && x[1].id));
    if (id === ид) return i + 1;
  }
  return 0;
}

// ═══════════════ 🛡️ САМОПРОВЕРКА (01.09.2026, ВЪЛНА 1.3) ═══════════════
//
// Този уред вече е падал в собствения си капан: index оставаше null и
// излизаше „100% не се намира" — което изглежда като страшна находка, а е
// счупен пясъчник. Коментарът за това го има от началото, но НИЩО не го
// проверяваше. Сега се проверява — в двете посоки:
//   · статия, потърсена с ЦЯЛОТО си заглавие, трябва да излезе (иначе е
//     счупен уредът, не библиотеката);
//   · безсмислица НЕ трябва да я намира;
//   · несъществуващ id НЕ трябва да се намира никога — иначе сметката лъже.
// И долна граница на БРОЯ, защото „65% на първо място" от 3 статии е нула.
(function самопроверкаНаТърсачката() {
  const ДОЛНИ_СТАТИИ = 700;
  const редове = [];
  let червено = 0;

  if (items.length < ДОЛНИ_СТАТИИ) { червено++; редове.push(['🔴', 'индексът е ' + items.length + ' статии — под ' + ДОЛНИ_СТАТИИ]); }
  else редове.push(['✅', 'индексът е ' + items.length + ' статии ≥ ' + ДОЛНИ_СТАТИИ]);

  // взимаме три статии от РАЗЛИЧНИ места в индекса — една може да е особена
  const пробни = [items[0], items[Math.floor(items.length / 2)], items[items.length - 1]].filter(Boolean);
  let намерени = 0;
  for (const it of пробни) {
    const p = намери(String(it.t || ''), it.id, it.r);
    if (p >= 1) намерени++;
  }
  if (намерени === пробни.length)
    редове.push(['✅', 'примамка: и трите пробни статии се намират по ЦЯЛОТО си заглавие']);
  else { червено++; редове.push(['🔴', 'примамка: само ' + намерени + ' от ' + пробни.length +
                                 ' се намират по цялото си заглавие — счупен е УРЕДЪТ, не библиотеката']); }

  const п0 = пробни[0] ? намери('зюмбюл трактор престилка', пробни[0].id, пробни[0].r) : -1;
  if (п0 === 0) редове.push(['✅', 'примамка (обратната посока): безсмислицата не намира статията']);
  else { червено++; редове.push(['🔴', 'примамка: безсмислицата „намери" статията на място ' + п0 + ' — сметката лъже']); }

  const п1 = пробни[0] ? намери(String(пробни[0].t || ''), 'НЯМА-ТАКЪВ-ИД', пробни[0].r) : -1;
  if (п1 === 0) редове.push(['✅', 'примамка: несъществуващ id не се намира никога']);
  else { червено++; редове.push(['🔴', 'примамка: несъществуващ id излезе на място ' + п1]); }

  console.log('  САМОПРОВЕРКА (иначе процентите долу не значат нищо):');
  редове.forEach(([з, т]) => console.log('     ' + з + ' ' + т));
  console.log('');
  if (червено) { console.log('🔴 САМОПРОВЕРКАТА ПАДА — процентите долу НЕ СЕ БРОЯТ.'); process.exit(1); }
})();

let n = 0;
const общо = { първи: 0, тройка: 0, десетка: 0, нула: 0 };
const еднаДума = { първи: 0, тройка: 0, десетка: 0, нула: 0 };
const провалени = [];

// ⏱️ пълният обход е 789 × 2 търсения × 793 записа — изтича. Взима се
// РАВНОМЕРНА извадка през целия индекс (не първите N, за да не мери само
// една стая). Стъпката е в изхода, за да се знае колко е гледано.
const СТЪПКА = Math.max(1, Math.ceil(items.length / 160));
for (let бр = 0; бр < items.length; бр += СТЪПКА) {
  const it = items[бр];
  const д = думи(it.t);
  if (д.length < 2) continue;
  n++;
  // въпросът: две-три смислови думи, НЕ по реда на заглавието
  const три = [д[д.length - 1], д[0], д[1]].filter(Boolean).slice(0, 3).join(' ');
  const p = намери(три, it.id, it.r);
  if (p === 1) общо.първи++;
  if (p >= 1 && p <= 3) общо.тройка++;
  if (p >= 1) общо.десетка++; else общо.нула++;
  // и само първата дума
  const p1 = намери(д[0], it.id, it.r);
  if (p1 === 1) еднаДума.първи++;
  if (p1 >= 1 && p1 <= 3) еднаДума.тройка++;
  if (p1 >= 1) еднаДума.десетка++; else еднаДума.нула++;
  if (p === 0) провалени.push({ ид: it.id, t: it.t, q: три, r: it.r });
}

const п = (x) => (100 * x / n).toFixed(0) + '%';
console.log('🔍 ТЪРСАЧКАТА НА БИБЛИОТЕКАТА\n');
console.log('  статии в индекса : ' + items.length);
console.log('  ПРОВЕРЕНИ        : ' + n + '   (останалите имат под 2 смислови думи в заглавието)\n');
console.log('  ── въпрос от 3 разбъркани смислови думи ──');
console.log('     на 1-во място : ' + общо.първи + '  (' + п(общо.първи) + ')');
console.log('     в първите 3   : ' + общо.тройка + '  (' + п(общо.тройка) + ')');
console.log('     в първите 10  : ' + общо.десетка + '  (' + п(общо.десетка) + ')');
console.log('     🔴 НЕ СЕ НАМИРА: ' + общо.нула + '  (' + п(общо.нула) + ')\n');
console.log('  ── въпрос от ЕДНА дума (както пише припряна майка) ──');
console.log('     на 1-во място : ' + еднаДума.първи + '  (' + п(еднаДума.първи) + ')');
console.log('     в първите 3   : ' + еднаДума.тройка + '  (' + п(еднаДума.тройка) + ')');
console.log('     в първите 10  : ' + еднаДума.десетка + '  (' + п(еднаДума.десетка) + ')');
console.log('     🔴 НЕ СЕ НАМИРА: ' + еднаДума.нула + '  (' + п(еднаДума.нула) + ')');

if (провалени.length) {
  console.log('\n  🔴 СТАТИИ, КОИТО НЕ СЕ НАМИРАТ ПО СОБСТВЕНИТЕ СИ ДУМИ: ' + провалени.length);
  провалени.slice(0, СПИСЪК ? 999 : 20).forEach(x =>
    console.log('   „' + x.q + '"  →  не намира  ' + x.ид + '  („' + String(x.t).slice(0, 52) + '")'));
  if (!СПИСЪК && провалени.length > 20) console.log('   … още ' + (провалени.length - 20) + ' — с --spisak');
}

// ── ПАЗАЧ СРЕЩУ САМИЯ МЕН ──
// 100% провал е почти винаги счупена подложка, не счупена библиотека. Точно
// това вече се е случвало тук (index === null). Числото тогава не е находка.
{
  const ДОЛНА_ПРОВЕРЕНИ = 100;
  if (n < ДОЛНА_ПРОВЕРЕНИ) {
    console.log('');
    console.log('🔴 ПАЗАЧ: само ' + n + ' проверени статии — под ' + ДОЛНА_ПРОВЕРЕНИ + '. Това не е „чисто", а слепота.');
    process.exitCode = 1;
  } else if (общо.нула === n) {
    console.log('');
    console.log('🔴 ПАЗАЧ: ВСИЧКИТЕ ' + n + ' статии излизат ненамираеми. Почти сигурно е счупен');
    console.log('   пясъчникът (index === null), не библиотеката. Числата горе НЕ са находка.');
    process.exitCode = 1;
  }
}
