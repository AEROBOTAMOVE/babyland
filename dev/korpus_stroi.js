vm.createContext(ctx);
new vm.Script(fs.readFileSync(path.join(КОРЕН, 'js/kb.js'), 'utf8')).runInContext(ctx);
const KB = ctx.KB;

const корпус = [];
const добави = (t, e, r) => { if (t && String(t).trim().length > 4) корпус.push({ t: String(t).trim(), e, r }); };

// ── 1. СПЕШНИ: фразата, вградена в изречение, каквото майка наистина пише ──
// Взима се РАЗПРЪСНАТА извадка от всяко семейство, за да не тежи едно.
const ОБВИВКИ = [
  ф => ф,
  ф => ф + ' какво да правя',
  ф => 'помощ ' + ф,
  ф => ф + ' много ме е страх',
  ф => 'моля те кажи ми нещо ' + ф,
  ф => ф + ' от снощи е'
];
const СЕМ = [
  ['redFlags', 'Здраве и SOS'], ['pregFlags', 'Бременност'], ['dvFlags', 'Жената в мен'],
  ['motherFlags', 'Дневник на мама'], ['heavyFlags', 'Дневник на мама'],
  ['mamaBodyFlags', 'Жената в мен'], ['lossFlags', 'Дневник на мама']
];
// 🪤 ПЪРВИЯТ МИ СТРОЕЖ ПРАВЕШЕ ФАЛШИВ КОРПУС: списъците съдържат и КОРЕНИ
//    („обезводн", „гърч", „конвулси"), а не само изречения. От тях излизаше
//    „обезводн какво да правя" — низ, който никоя майка не пише. Корпус от
//    такива изречения мери речника, не приложението.
//    Правилото: за корпуса стават само фрази с ПОВЕЧЕ ОТ ЕДНА ДУМА — те са
//    парчета от истински изречения.
// 🪤 И ВТОРИЯТ МИ ФИЛТЪР БЕШЕ СЛАБ: „втвърди се и" мина, защото има интервал
//    и осем знака — но свършва на СЪЮЗ, тоест е половин изречение. Такъв низ
//    пак мери речника, не приложението. Затова: поне три думи И да не свършва
//    на служебна дума.
const ОПАШКА = /(^|\s)(и|или|на|от|с|със|за|да|че|но|в|във|по|до|при|към|под|над|без)$/;
const истинскаФраза = ф =>
  typeof ф === 'string' &&
  ф.trim().split(/\s+/).length >= 3 &&
  ф.length >= 12 &&
  !ОПАШКА.test(ф.trim());
let брОбвивка = 0;
for (const [сем, стая] of СЕМ) {
  const сп = (KB[сем] || []).filter(истинскаФраза);
  if (!сп.length) continue;
  // равномерна извадка: стъпка, която дава ~18 от всяко семейство
  const стъпка = Math.max(1, Math.floor(сп.length / 18));
  for (let i = 0; i < сп.length; i += стъпка) {
    добави(ОБВИВКИ[брОбвивка++ % ОБВИВКИ.length](сп[i]), 'SPESHNO', стая);
  }
}

// ── 2. КАРТА: обикновени въпроси, които трябва да получат ОТГОВОР, не флаг ──
// Взимат се от заглавията-въпроси на самите карти — те са по определение
// въпросите, на които приложението знае отговора.
// 🪤 Заглавията-въпроси са само 58 — твърде малко. Истинските въпроси на
//    майката живеят в dev/tarsene_bez_otgovor.js (209 броя, всеки със стая) и
//    са писани точно като нейния език, не като заглавие на карта. Четат се
//    оттам, за да има ЕДИН списък в проекта вместо два, които се разминават.
(function отСондата() {
  const п = path.join(__dirname, 'tarsene_bez_otgovor.js');
  if (!fs.existsSync(п)) { console.log('  ⚠️ няма dev/tarsene_bez_otgovor.js — въпросите ще са малко'); return; }
  const текст = fs.readFileSync(п, 'utf8');
  const АП = String.fromCharCode(39);
  // редове от вида:   ['въпрос', 'Стая'],
  let брой = 0;
  for (const ред of текст.split(/\r?\n/)) {
    const т = ред.trim();
    if (т.indexOf('[' + АП) !== 0) continue;
    const части = т.split(АП);
    if (части.length < 5) continue;
    const въпрос = части[1], стая = части[3];
    if (въпрос && стая && стая.length > 2) { добави(въпрос, 'KARTA', стая); брой++; }
  }
  if (!брой) console.log('  ⚠️ нито един въпрос не се извади от сондата — форматът ѝ се е сменил');
})();

const въпроси = (KB.entries || []).filter(z => /\?$/.test(String(z.title || '')));
const стъпкаВ = Math.max(1, Math.floor(въпроси.length / 40));
for (let i = 0; i < въпроси.length; i += стъпкаВ) {
  добави(String(въпроси[i].title).replace(/\?$/, ''), 'KARTA', въпроси[i].room);
}

