// 🔴 КАК СЕ НАМЕРИ ДУПКАТА (01.09): построих `dev/bliznaci_tema.js`, за да
//    ловя тема, написана два пъти. Той гледа КАРТИТЕ. След това отряд написа
//    статия „Прощъпулникът: питката, предметите и как се прави" в
//    lib/sezoni-1.json, докато същата статия вече стоеше в lib/mama-1.json —
//    и никой уред не се обади. `dev/siraci.js` брои статии БЕЗ карта;
//    `dev/bez_brauzar.js` брои счупени препратки. Нито един не пита дали
//    ДВЕ статии казват едно и също.
//
//    Това е по-скъпо от дубъл в картите: статията е дълга, майката ще прочете
//    едната и после ще срещне другата, и ще реши, че приложението се повтаря.
//    А при разминаване между двете — че си противоречи.
//
// Лещата е същата като при картите: заглавието се свежда (цифри→думи,
// окончания отрязани, служебни думи махнати), думите се теглят по РЯДКОСТ,
// за да не тежи „с бебе" колкото „прощъпулник". Гледа се и ТЯЛОТО.
//
// ПУСКАНЕ: node dev/statii_bliznaci.js  [BL_STATII_PRAG=n]
// ПЪТ НАЗАД: файлът само ЧЕТЕ.
// ═══════════════════════════════════════════════════════════
const fs = require('fs');
const К = __dirname + '/../';

const ЦИФРИ = { '1': 'едно', '2': 'две', '3': 'три', '4': 'четири', '5': 'пет', '6': 'шест', '7': 'седем', '8': 'осем', '9': 'девет', '10': 'десет', '12': 'дванайсет', '24': 'двайсет и четири', '40': 'четирийсет' };
const СЛУЖЕБНИ = new Set(['и', 'а', 'но', 'или', 'да', 'не', 'се', 'си', 'е', 'са', 'ще', 'че', 'за', 'на', 'в', 'с', 'от', 'по', 'до', 'при', 'като', 'ли', 'то', 'ти', 'аз', 'ми', 'му', 'им', 'ги', 'го', 'я', 'ме', 'те', 'кое', 'кой', 'коя', 'как', 'кога', 'какво', 'къде', 'защо', 'колко', 'един', 'една', 'едно', 'този', 'тази', 'това', 'кои', 'къв', 'каква']);
// 🪤 01.09: първата версия режеше по ДВЕ букви от края и пропусна точно
//    дубъла, заради който е написана: „прощъпулник" ставаше „прощъпулни",
//    а „прощъпулникът" ставаше „прощъпулник" — два различни корена за една
//    и съща дума. Сведение по ПРЕФИКС е по-грубо, но не се дразни от
//    членуването, което е основната разлика между две заглавия за едно нещо.
// 🪤 И ШЕСТ БУКВИ НЕ СТИГНАХА: оправиха „прощъпулник", но счупиха „пълна"
//    срещу „пълната" („пълна" остава, „пълнат" се получава) и двойката за
//    самотата изчезна. ПЕТ покрива и двете — членът на български седи точно
//    там. Мярка, поправена веднъж, се проверява срещу СТАРИТЕ си находки.
const корен = w => w.length > 5 ? w.slice(0, 5) : w;
const сведи = t => {
  let s = String(t || '').toLowerCase();
  for (const [ц, д] of Object.entries(ЦИФРИ)) s = s.replace(new RegExp('(^|[^0-9])' + ц + '([^0-9]|$)', 'g'), '$1' + д + '$2');
  return (s.match(/[а-яё]+/g) || []).filter(w => w.length > 2 && !СЛУЖЕБНИ.has(w)).map(корен);
};
let ТЕЖЕСТ = new Map();
const тежи = w => ТЕЖЕСТ.get(w) || 1;
const жакар = (a, b) => {
  const A = new Set(a), B = new Set(b);
  if (!A.size || !B.size) return 0;
  let общи = 0, обед = 0;
  for (const x of A) { обед += тежи(x); if (B.has(x)) общи += тежи(x); }
  for (const x of B) if (!A.has(x)) обед += тежи(x);
  return обед ? общи / обед : 0;
};

// ── САМОПРОВЕРКА В ДВЕТЕ ПОСОКИ (преди тежестите — там всичко тежи 1) ──
const А = жакар(сведи('Прощъпулник: питката, предметите и как се прави'), сведи('Прощъпулникът: питката, предметите и как се прави'));
const Б = жакар(сведи('Коликите вечер'), сведи('Документите след раждането'));
if (А < 0.75) { console.log('🔴 ЛЕЩАТА Е СЛЯПА за очевиден дубъл (' + А.toFixed(2) + ')'); process.exit(1); }
if (Б > 0.1) { console.log('🔴 ЛЕЩАТА ЛЪЖЕ НАГОРЕ (' + Б.toFixed(2) + ')'); process.exit(1); }
console.log('  ✅ самопроверка: очевиден дубъл ' + А.toFixed(2) + ' · несвързани ' + Б.toFixed(2));

// ── данните ──
const idx = JSON.parse(fs.readFileSync(К + 'lib/index.json', 'utf8'));
const мета = (idx.items || []).filter(a => a && a.id);
const тела = new Map();
for (const f of fs.readdirSync(К + 'lib').filter(f => /^[a-z0-9-]+\.json$/.test(f) && f !== 'index.json')) {
  const o = JSON.parse(fs.readFileSync(К + 'lib/' + f, 'utf8'));
  for (const [id, md] of Object.entries(o)) if (typeof md === 'string') тела.set(id, { md, файл: f });
}
{
  const бр = new Map();
  for (const a of мета) for (const w of new Set(сведи(a.t))) бр.set(w, (бр.get(w) || 0) + 1);
  for (const [w, n] of бр) ТЕЖЕСТ.set(w, Math.log(мета.length / n) / Math.log(мета.length));
}

const подг = мета.map(a => ({
  a, загл: сведи(a.t),
  тяло: сведи(String((тела.get(a.id) || {}).md || '').slice(0, 4000)),
  файл: (тела.get(a.id) || {}).файл || '—'
}));

const находки = [];
for (let i = 0; i < подг.length; i++) {
  for (let j = i + 1; j < подг.length; j++) {
    const сЗ = жакар(подг[i].загл, подг[j].загл);
    const сТ = жакар(подг[i].тяло, подг[j].тяло);
    // дубъл е ИЛИ много близко заглавие, ИЛИ близко заглавие + близко тяло
    if (сЗ >= 0.7 || (сЗ >= 0.45 && сТ >= 0.35)) находки.push({ a: подг[i], b: подг[j], сЗ, сТ });
  }
}
находки.sort((x, y) => (y.сЗ + y.сТ) - (x.сЗ + x.сТ));

console.log('');
console.log('📚 БЛИЗНАЦИ МЕЖДУ СТАТИИ');
console.log('');
console.log('  ПРЕГЛЕДАНИ : ' + подг.length + ' статии  (' + (подг.length * (подг.length - 1) / 2).toLocaleString('bg') + ' двойки)');
console.log('  🔴 ДУБЛИРАНИ ТЕМИ : ' + находки.length);
console.log('');
for (const f of находки.slice(0, 25)) {
  const еднаСтая = f.a.a.r === f.b.a.r;
  console.log('  ' + (еднаСтая ? '🔴 ЕДНА СТАЯ' : '🟠 през стаи') + '  заглавия ' + (f.сЗ * 100).toFixed(0) + '% · тела ' + (f.сТ * 100).toFixed(0) + '%');
  console.log('       [' + f.a.a.r + ' · ' + f.a.файл + '] ' + f.a.a.id);
  console.log('          „' + f.a.a.t + '"');
  console.log('       [' + f.b.a.r + ' · ' + f.b.файл + '] ' + f.b.a.id);
  console.log('          „' + f.b.a.t + '"');
}
fs.writeFileSync(__dirname + '/statii_bliznaci.json', JSON.stringify(находки.map(f => ({
  a: f.a.a.id, at: f.a.a.t, af: f.a.файл, ar: f.a.a.r,
  b: f.b.a.id, bt: f.b.a.t, bf: f.b.файл, br: f.b.a.r,
  zagl: +f.сЗ.toFixed(2), tialo: +f.сТ.toFixed(2)
})), null, 1));
console.log('');
console.log('  💾 dev/statii_bliznaci.json');

const ПРАГ = Number(process.env.BL_STATII_PRAG || 0);
if (находки.length > ПРАГ) {
  console.log('');
  console.log('  🔴 НАД ПРАГА (' + ПРАГ + ') — една и съща статия е написана два пъти');
  console.log('     Лекът: остави ЕДНАТА, пренеси в нея това, което само другата казва,');
  console.log('     пренасочи картите към оцелялата и махни дублата от lib/ и index.json.');
  console.log('     ⚠️ Статия без карта е находка за dev/siraci.js — пренасочи ПРЕДИ да триеш.');
  process.exit(1);
}
console.log('  ✅ под прага ' + ПРАГ);
