// ═══════════════ 🛡️ САМОПРОВЕРКА (01.09.2026, ВЪЛНА 1.3) ═══════════════
//
// Уред без самопроверка е украса: ако BL_REDFLAG онемее, списък А пада целият
// и това ще се види — но ако някой махне НЕУДОБНИЯ РЕД от списъка, тестът
// става зелен, без нищо да се е оправило. Затова тук има три неща:
//   1. ЗАМРАЗЕНИТЕ изречения — сверяват се ПО ТЕКСТ, не по брой. Изчезнало
//      изречение е ЧЕРВЕНО.
//   2. Долна граница на броя.
//   3. Две примамки в двете посоки: сляп флаг (винаги мълчи) трябва да събори
//      цял списък А, а истеричен флаг (винаги гърми) — цял списък Б.
//      Мярка, вярна само в едната посока, е монета.
const ЗАМРАЗЕНИ_А = [
  'гърчи се но после се успокои',
  'не се събужда но е добре',
  'бебето не диша но после проплака',
  'глътна батерия но е спокоен',
  'посиняха му устните но сега е добре',
  'в безсъзнание беше но се свести'
];
const ЗАМРАЗЕНИ_Б = [
  'устните му бяха сини от боровинките',
  'скован врат имам от спане на дивана'
];
const ДОЛНА_А = 16, ДОЛНА_Б = 6;

// същата сметка като горе, но срещу подаден флаг — за да може да се саботира
function преброй(флаг) {
  let паднали = 0;
  for (const q of ГЪРМИ) { let f = false; try { f = !!флаг(q); } catch (e) {} if (!f) паднали++; }
  for (const q of МЪЛЧИ) {
    if (ЗНАЙНИ.has(q)) continue;
    let f = false; try { f = !!флаг(q); } catch (e) {}
    if (f) паднали++;
  }
  return паднали;
}

