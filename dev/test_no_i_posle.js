// В isRedFlag има пазач УСПОКОЕНИЕ, който омекотява тревогата, когато майката
// сама е дала успокоителен белег („устните му бяха сини ОТ БОРОВИНКИТЕ").
// В израза му стои `(но|а)s+…` — БЕЗ обратна наклонена черта. Изглежда като
// изпусната черта и МОЛИ да бъде „поправена": така написан, изразът търси
// буквата „s" след „но" и на кирилица не съвпада никога.
//
// ПОПРАВИХ Я. И ето какво стана:
//     „ГЪРЧИ СЕ но после се успокои"   🚨 → 🔇
//     „НЕ СЕ СЪБУЖДА но е добре"       🚨 → 🔇
// Гърч, който е спрял, си остава гърч. Дете, което не се събужда, си остава
// спешен случай — каквото и да добави майката след „но".
// Причината: 'гърч' и 'не се събужда' СА в списъка ОМЕКОТИМИ (сложени са там
// заради ДРУГИ белези, например „гърч от смях"), а оживелият клон ги омекотява
// с всеки „но…".
//
// 🪤 КОРПУСЪТ ОТ 350 НЕ ХВАНА ТОВА. Тези две формулировки просто ги няма в него
// и той остана на „0 пропуснати" през цялото време. Мярка, която не съдържа
// случая, не е доказателство за него. Затова случаите живеят ТУК.
//
// Тестът пази В ДВЕТЕ ПОСОКИ:
//   А. спешното гърми ДОРИ с успокоителна добавка след „но"
//   Б. истински успокоените (майка за себе си, храна, оцветяване) мълчат
// Ако някой ден А почне да пада — някой е „поправил" чертата. Върни я.
//
