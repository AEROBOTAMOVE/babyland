//   2. виновник() да НЕ върне KB.redFlags както го е заварил — той ги
//      разглобява един по един и ги сглобява обратно. Счупи ли се
//      сглобяването, всяко следващо число в този файл е боклук.
//   3. Обратната посока: безобидно изречение да не намира виновник.
function самопроверкаНаДвигателя() {
  const ДОЛНИ = { redFlags: 300, pregFlags: 150, dvFlags: 150, motherFlags: 150 };
  const редове = [];
  let червено = 0;

  for (const име of Object.keys(ДОЛНИ)) {
    const н = (KB[име] || []).length;
    if (н < ДОЛНИ[име]) { червено++; редове.push(['🔴', име + ' е ' + н + ' — под долната граница ' + ДОЛНИ[име]]); }
    else редове.push(['✅', име + ' ' + н + ' ≥ ' + ДОЛНИ[име]]);
  }

  const предиRed = (KB.redFlags || []).length;
  const предиPreg = (KB.pregFlags || []).length;
  let в1 = '';
  try { в1 = виновник('бебето не диша'); } catch (e) { в1 = 'ГРЪМ: ' + e.message; }
  const следRed = (KB.redFlags || []).length;
  const следPreg = (KB.pregFlags || []).length;

  if (предиRed === следRed && предиPreg === следPreg)
    редове.push(['✅', 'виновник() връща списъците както ги е заварил (' + следRed + ' / ' + следPreg + ')']);
  else { червено++; редове.push(['🔴', 'виновник() РАЗГЛОБИ базата: redFlags ' + предиRed + '→' + следRed +
                                 ' · pregFlags ' + предиPreg + '→' + следPreg + ' — всяко число оттук нататък е боклук']); }

  if (/ЧЕРВЕН/.test(в1)) редове.push(['✅', 'примамка: истинско спешно намира виновник']);
  else { червено++; редове.push(['🔴', 'примамка: „бебето не диша" не намери виновник — уредът е сляп (' + в1 + ')']); }

  let в2 = '';
  try { в2 = виновник('съседката подари на бабата шарена престилка за имен ден'); } catch (e) { в2 = 'ГРЪМ: ' + e.message; }
  if (!в2) редове.push(['✅', 'примамка (обратната посока): безобидното изречение няма виновник']);
  else { червено++; редове.push(['🔴', 'примамка: безобидното изречение вдига „' + в2 + '"']); }

  console.log('  САМОПРОВЕРКА (иначе списъците долу не значат нищо):');
  редове.forEach(([з, т]) => console.log('     ' + з + ' ' + т));
  console.log('');
  if (червено) { console.log('🔴 САМОПРОВЕРКАТА ПАДА — този уред не вижда. Числата му не важат.'); process.exit(1); }
}

const СПИСЪЦИ = ['dvFlags', 'lossFlags', 'motherFlags', 'mamaBodyFlags', 'heavyFlags'];

function виновник(т) {
  const из = [];
  if (W.BL_REDFLAG(т)) {
    const все = KB.redFlags.slice(), в = [];
    for (const f of все) { KB.redFlags = [f]; try { if (W.BL_REDFLAG(т)) в.push(f); } catch (e) {} }
    KB.redFlags = все;
    из.push('ЧЕРВЕН[' + (в.join(' | ') || 'ПРАВИЛО, не флаг от списъка') + ']');
  }
  const м = W.BL_MOTHERFLAG(т);
  if (м) {
    const снимка = {}; СПИСЪЦИ.forEach(n => { снимка[n] = KB[n] ? KB[n].slice() : null; });
    const в = [];
    for (const n of СПИСЪЦИ) {
      if (!KB[n]) continue;
      for (const f of снимка[n]) {
        СПИСЪЦИ.forEach(x => { if (KB[x]) KB[x] = []; });
        KB[n] = [f];
        try { if (W.BL_MOTHERFLAG(т) === м) в.push(n + '«' + f + '»'); } catch (e) {}
      }
    }
    СПИСЪЦИ.forEach(n => { if (снимка[n]) KB[n] = снимка[n]; });
    // >20 съвпадения значи, че гърми ПРАВИЛОТО за подлога, не отделен флаг
    из.push('МАЙКА:' + м + '[' + (в.length > 20 ? 'ПРАВИЛОТО за подлога (партньор + насилие)'
            : (в.join(' | ') || 'ПРАВИЛО, не флаг от списъка')) + ']');
  }
  if (W.BL_PREGFLAG && W.BL_PREGFLAG(т, стаяЗаФлаг(т))) {
    const все = KB.pregFlags.slice(), в = [];
    for (const f of все) { KB.pregFlags = [f]; try { if (W.BL_PREGFLAG(т, стаяЗаФлаг(т))) в.push(f); } catch (e) {} }
    KB.pregFlags = все;
    из.push('БРЕМЕННОСТ[' + в.join(' | ') + ']');
  }
  return из.join('   ');
}

