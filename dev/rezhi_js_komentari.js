'use strict';

// Токенизатор: връща масив от парчета {вид, текст}. Видове: код, низ, шаблон,
// регулярен, ред-коментар, блок-коментар. Не е пълен парсер на JS — достатъчен е,
// защото проверката накрая хваща всяко разминаване в низовете.
function токени(src) {
  const т = [];
  let i = 0, нач = 0;
  const n = src.length;
  let последноЗначимо = '';           // за да различим / (делене) от /регулярен/
  const пусни = (вид, до) => { т.push({ вид, текст: src.slice(нач, до) }); нач = до; };
  const кодДо = до => { if (до > нач) пусни('код', до); };
  while (i < n) {
    const c = src[i], d = src[i + 1];
    if (c === '/' && d === '/') {
      кодДо(i); let j = i + 2; while (j < n && src[j] !== '\n') j++; пусни('ред-коментар', j); i = j; continue;
    }
    if (c === '/' && d === '*') {
      кодДо(i); let j = src.indexOf('*/', i + 2); j = j < 0 ? n : j + 2; пусни('блок-коментар', j); i = j; continue;
    }
    if (c === '"' || c === "'") {
      кодДо(i); let j = i + 1;
      while (j < n && src[j] !== c) { if (src[j] === '\\') j++; if (src[j] === '\n') break; j++; }
      пусни('низ', Math.min(j + 1, n)); i = Math.min(j + 1, n); последноЗначимо = 'а'; continue;
    }
    if (c === '`') {
      кодДо(i); let j = i + 1, дълбочина = 0;
      while (j < n) {
        const x = src[j];
        if (x === '\\') { j += 2; continue; }
        if (дълбочина === 0 && x === '`') break;
        if (x === '$' && src[j + 1] === '{') { дълбочина++; j += 2; continue; }
        if (дълбочина > 0 && x === '}') { дълбочина--; j++; continue; }
        if (дълбочина > 0 && x === '`') {                  // вложен шаблон в ${ }
          let k = j + 1; while (k < n && src[k] !== '`') { if (src[k] === '\\') k++; k++; } j = k + 1; continue;
        }
        j++;
      }
      пусни('шаблон', Math.min(j + 1, n)); i = Math.min(j + 1, n); последноЗначимо = 'а'; continue;
    }
    if (c === '/') {
      // регулярен израз, ако преди него няма стойност (идентификатор, число, затваряща скоба)
      const пред = последноЗначимо;
      if (!/[\w$)\]]/.test(пред)) {
        кодДо(i); let j = i + 1, вКлас = false;
        while (j < n) {
          const x = src[j];
          if (x === '\\') { j += 2; continue; }
          if (x === '\n') break;
          if (x === '[') вКлас = true; else if (x === ']') вКлас = false;
          else if (x === '/' && !вКлас) break;
          j++;
        }
        j++; while (j < n && /[a-z]/i.test(src[j])) j++;
        пусни('регулярен', j); i = j; последноЗначимо = 'а'; continue;
      }
    }
    if (!/\s/.test(c)) последноЗначимо = c;
    i++;
  }
  кодДо(n);
  return т;
}

// Реже само коментар, който е САМ на реда (преди него на реда има само празно).
function режи(src) {
  const т = токени(src);
  let изход = '';
  for (let k = 0; k < т.length; k++) {
    const ч = т[k];
    if (ч.вид === 'ред-коментар' || ч.вид === 'блок-коментар') {
      const редДосега = изход.slice(изход.lastIndexOf('\n') + 1);
      if (/^[ \t]*$/.test(редДосега)) {
        // махаме и отстъпа преди него; новия ред след ред-коментара ще изяде кодът
        изход = изход.slice(0, изход.length - редДосега.length);
        if (ч.вид === 'ред-коментар' && т[k + 1] && т[k + 1].вид === 'код' && т[k + 1].текст.startsWith('\n')) {
          т[k + 1] = { вид: 'код', текст: т[k + 1].текст.slice(1) };
        }
        continue;
      }
    }
    изход += ч.текст;
  }
  return изход;
}

// Всички низове, шаблони и регулярни — те са текстът, който не бива да се мени.
function отпечатък(src) {
  return токени(src).filter(ч => ч.вид === 'низ' || ч.вид === 'шаблон' || ч.вид === 'регулярен').map(ч => ч.текст).join('\u0000');
}

// Главното: реже, после се проверява сам. Разминаване → оригиналът.
function безопасноРежи(src, име) {
  let нов;
  try { нов = режи(src); } catch (e) { return { текст: src, пести: 0, защо: 'токенизаторът гръмна: ' + e.message }; }
  if (отпечатък(нов) !== отпечатък(src)) return { текст: src, пести: 0, защо: 'низовете се различават — оставям оригинала' };
  try { new Function(нов); } catch (e) { return { текст: src, пести: 0, защо: 'синтаксисът се счупи: ' + e.message }; }
  return { текст: нов, пести: src.length - нов.length, защо: '' };
}

module.exports = { безопасноРежи, режи, отпечатък, токени };

