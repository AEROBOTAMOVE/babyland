// Трите находки на dev/standarti.js в новите карти.
// ⚠️ ПОПРАВЯ СЕ ТЕКСТЪТ, НЕ ПАЗАЧЪТ. Замразените стандарти са платени с
//    опит; разхлабването им, за да мине нов текст, е обратното на пазач.
//
// 1. g3b-slaga-v-ustata… — картата ПРЕДУПРЕЖДАВА за пръст, олово и дребни
//    неща, но списъкът с думи-освобождаващи търси „задавян", а текстът
//    казва „задавят". Добавя се „опасни" — и по-ясно е за майката.
// 2+3. g3-umorata-v-parvite-meseci — „вършат повече от три кафета" в стая
//    „Бременност" пали А10 и Б10 (кофеинът се мери с ЕДНО кафе на ден).
//    Сравнението с брой кафета отпада изцяло.
const fs = require('fs');
const П = 'js/kb.js';
let s = fs.readFileSync(П, 'utf8');

const ЗАМЕНИ = [
  ['а дребните неща се задавят.',
   'а дребните неща са опасни — риск от задавяне.'],
  ['двайсет минути легнала следобед вършат повече от три кафета.',
   'двайсет минути легнала следобед вършат повече от всяко кафе.'],
];
let сменени = 0;
for (const [стар, нов] of ЗАМЕНИ) {
  const бр = s.split(стар).length - 1;
  if (бр !== 1) { console.log('🔴 котвата се среща ' + бр + ' пъти: „' + стар.slice(0, 50) + '"'); process.exit(2); }
  s = s.replace(стар, нов); сменени++;
}
if (!сменени) { console.log('🔴 нищо'); process.exit(2); }
fs.writeFileSync(П + '.PREDI_STANDARTI3', fs.readFileSync(П, 'utf8'));
fs.writeFileSync(П, s);
console.log('✅ сменени ' + сменени + ' · копие: ' + П + '.PREDI_STANDARTI3');
