const fs = require('fs');
const vm = require('vm');
const path = require('path');
const КОРЕН = path.resolve(__dirname, '..');

function зареди(текст) {
  const ctx = { console: { log() {} }, JSON, Math, Date, RegExp, String, Number, Array, Object };
  ctx.window = ctx; ctx.globalThis = ctx; ctx.self = ctx;
  vm.createContext(ctx);
  new vm.Script(текст).runInContext(ctx);
  return (ctx.BL_KB || ctx.KB);
}

// 🔑 намира НАЧАЛОТО на записа — и с 'единични', и с "двойни" кавички
function намериЗапис(src, id) {
  const варианти = ["id: '" + id + "'", 'id: "' + id + '"'];
  for (const в of варианти) {
    const н = src.indexOf(в);
    if (н >= 0) {
      // и втори такъв не бива да има — иначе не знам кой е
      if (src.indexOf(в, н + 1) >= 0) return { грешка: 'id „' + id + '" се среща ПОВЕЧЕ ОТ ВЕДНЪЖ' };
      return { н, дължина: в.length };
    }
  }
  return { грешка: 'id „' + id + '" НЕ Е НАМЕРЕН нито с единични, нито с двойни кавички' };
}

function редътСКлючове(src, id) {
  const з = намериЗапис(src, id);
  if (з.грешка) return з;
  const кн = src.indexOf('keys: [', з.н);
  if (кн < 0) return { грешка: id + ': няма `keys: [` след записа' };
  const кк = src.indexOf(']', кн);
  if (кк < 0) return { грешка: id + ': няма затваряща скоба на keys' };
  // ⚠ ПАЗАЧ: между id-то и keys НЕ бива да има друго id — иначе сме прескочили
  const между = src.slice(з.н + з.дължина, кн);
  if (/id:\s*['"]/.test(между)) return { грешка: id + ': между id и keys има ДРУГО id — прескочил съм записа' };
  return { от: кн, до: кк + 1 };
}

function хирург(опции) {
  const добави = опции.добави || {};
  const махни = опции.махни || {};
  const пиши = !!опции.пиши;
  const тих = !!опции.тих;
  const бр = (...a) => { if (!тих) console.log(...a); };

  const път = path.join(КОРЕН, 'js/kb.js');
  let src = fs.readFileSync(път, 'utf8');
  const преди = зареди(src);
  const снимкаПреди = {};
  преди.entries.forEach(z => снимкаПреди[z.id] = (z.keys || []).join('|'));

  const чий = new Map();
  преди.entries.forEach(z => (z.keys || []).forEach(k => чий.set(k, z.id)));
  const поId = new Map(преди.entries.map(z => [z.id, z]));

  const целеви = new Set(Object.keys(добави).concat(Object.keys(махни)));
  let дДобавени = 0, дМахнати = 0, откази = 0;
  const грешки = [];

  // 🪤 ДВА ПРОХОДА, НЕ ЕДИН. Първата версия махаше и добавяше в един цикъл и
  //   ключ, махнат от карта А, продължаваше да се брои за „зает от А" — затова
  //   не можеше да бъде даден на карта Б в същия ход. А точно това е най-честата
  //   операция: ключът се ПРЕМЕСТВА от крадеца при истинския собственик.
  //   Затова първо се маха ВСИЧКО, картата на собствениците се пречиства, и
  //   чак после се добавя.
  const новиКлючове = {};
  for (const id of целеви) {
    const z = поId.get(id);
    if (!z) { грешки.push('🔴 няма запис ' + id); continue; }
    новиКлючове[id] = (z.keys || []).slice();
  }
  for (const id of Object.keys(махни)) {
    if (!новиКлючове[id]) continue;
    for (const k of махни[id]) {
      if (!новиКлючове[id].includes(k)) { бр('  🔶 „' + k + '" вече го няма на ' + id); continue; }
      новиКлючове[id] = новиКлючове[id].filter(x => x !== k);
      чий.delete(k);          // ← освободен: сега може да бъде даден на друг
      дМахнати++;
    }
  }

  for (const id of целеви) {
    const z = поId.get(id);
    if (!z) continue;
    let ключове = новиКлючове[id];
    const преди2 = (z.keys || []).length;

    for (const k of (добави[id] || [])) {
      if (String(k).indexOf("'") >= 0) { грешки.push('🔴 апостроф в „' + k + '"'); continue; }
      if (ключове.includes(k)) continue;
      const чужд = чий.get(k);
      if (чужд && чужд !== id) { бр('  🔶 „' + k + '" вече е на ' + чужд + ' — пропускам'); откази++; continue; }
      ключове.push(k); чий.set(k, id); дДобавени++;
    }
    if (ключове.length < 3) { грешки.push('🔴 ' + id + ' би останал с ' + ключове.length + ' ключа'); continue; }

    const р = редътСКлючове(src, id);
    if (р.грешка) { грешки.push('🔴 ' + р.грешка); continue; }
    src = src.slice(0, р.от) + 'keys: [' + ключове.map(k => "'" + k + "'").join(', ') + ']' + src.slice(р.до);
    бр('  ✏️  ' + id.padEnd(24) + преди2 + ' → ' + ключове.length + ' ключа');
  }

  if (грешки.length) {
    бр('\n  ⛔ ГРЕШКИ — НИЩО НЕ Е ЗАПИСАНО:');
    грешки.forEach(x => бр('     ' + x));
    return { ок: false, грешки };
  }

  // ═══ СВЕРКА: пипнато ли е точно каквото исках, и НИЩО ДРУГО ═══
  let след;
  try { след = зареди(src); }
  catch (e) { бр('🔴 kb.js не се зарежда след промяната: ' + e.message); return { ок: false, грешки: [e.message] }; }
  if (след.entries.length !== преди.entries.length) {
    бр('🔴 записите станаха ' + след.entries.length + ' вместо ' + преди.entries.length);
    return { ок: false, грешки: ['брой записи'] };
  }
  const мръднали = [];
  след.entries.forEach(z => {
    const сега = (z.keys || []).join('|');
    if (снимкаПреди[z.id] !== сега) мръднали.push(z.id);
  });
  const неискани = мръднали.filter(id => !целеви.has(id));
  бр('\n  СВЕРКА: мръднали карти ' + мръднали.length + ' · целеви ' + целеви.size);
  if (неискани.length) {
    bрГрешка();
    function bрГрешка() {
      бр('  🔴🔴 МРЪДНАЛИ СА КАРТИ, КОИТО НЕ СЪМ ПИПАЛ: ' + неискани.join(', '));
      бр('     Точно това остана невидимо миналия път. НИЩО НЕ Е ЗАПИСАНО.');
    }
    return { ок: false, грешки: ['мръднали чужди карти: ' + неискани.join(', ')] };
  }
  бр('  ✅ нито една чужда карта не е мръднала');

  if (!пиши) { бр('\n  (пробен ход — подай пиши:true, за да запише)'); return { ок: true, пробен: true, дДобавени, дМахнати, откази }; }
  fs.copyFileSync(път, път + '.PREDI_HIRURG');
  fs.writeFileSync(път, src);
  бр('\n  💾 ЗАПИСАНО · добавени ' + дДобавени + ' · махнати ' + дМахнати + ' · откази ' + откази);
  bр2();
  function bр2() { бр('     ПЪТ НАЗАД: js/kb.js.PREDI_HIRURG'); }
  return { ок: true, дДобавени, дМахнати, откази };
}

