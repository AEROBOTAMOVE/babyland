//   1. намира записа и с ЕДИНИЧНИ, и с ДВОЙНИ кавички
//   2. ОТКАЗВА ШУМНО, ако не го намери — вместо да пише напосоки
//   3. след писането сверява ЦЯЛАТА база: пипнатите карти да са точно
