// ═══════════════════════════════════════════════════════════
// 🧪 ВСИЧКО — един пускач за шестте теста, едно число накрая
//
// Защо (11.08): шестте теста бяха писани от шест агента и всеки кръсти
// метода си различно — провери / пусни / провери(async). Пускането им
// на ръка иска да помниш кой как се вика. Тест, който е неудобен за
// пускане, не се пуска. А непускан тест е нула.
//
// КАК СЕ ПУСКА (в конзолата на приложението):
//   var s=document.createElement('script'); s.src='dev/vsichko.js'; document.body.appendChild(s);
//   await BL_ВСИЧКО.пусни()
//
// Връща ЕДНО число: колко теста са паднали. Нула значи чисто.
// Всеки друг резултат носи и точния списък, не само бройката.
//
// ПЪТ НАЗАД: файлът само ЧЕТЕ и вика другите тестове. Изтриването му
// не чупи нищо. НЕ е закачен в index.html.
// ═══════════════════════════════════════════════════════════
(function () {
  'use strict';

  // Всеки тест се описва с: файл, глобално име, как се вика и как се чете.
  // Ако утре се добави нов тест — един ред тук и толкова.
  var ТЕСТОВЕ = [
    { име: 'флагове',    файл: 'dev/test_flagove.js',    глоб: ['BL_ФЛАГОВЕ', 'BL_FLAGS'] },
    { име: 'отговори',   файл: 'dev/test_otgovori.js',   глоб: ['BL_ОТГОВОРИ', 'BL_ANSWERS'] },
    { име: 'библиотека', файл: 'dev/test_biblioteka.js', глоб: ['BL_БИБЛИОТЕКА', 'BL_LIBTEST'] },
    // 🪤 Тези две имена ги бях написал по памет и бяха ГРЕШНИ:
    // паметта се казва BL_MEMORY (не BL_MEMTEST), езикът BL_EZIK (не BL_LANG).
    // Сгрешено име тук не гърми — тестът просто „не се експортира“ и
    // тихо не се пуска. Сверени с реалните редове в самите файлове.
    { име: 'памет',      файл: 'dev/test_pamet.js',      глоб: ['BL_ПАМЕТ', 'BL_MEMORY'] },
    { име: 'телефон',    файл: 'dev/test_telefon.js',    глоб: ['BL_ТЕЛЕФОН', 'BL_PHONE'] },
    { име: 'език',       файл: 'dev/test_ezik.js',       глоб: ['BL_ЕЗИК', 'BL_EZIK'] },
    { име: 'заглавия',   файл: 'dev/zaglavia.js',        глоб: ['BL_ЗАГЛАВИЯ', 'BL_TITLES'] }
  ];

  function изчакай(ms) { return new Promise(function (r) { setTimeout(r, ms); }); }

  function вземи(имена) {
    for (var i = 0; i < имена.length; i++) if (window[имена[i]]) return window[имена[i]];
    return null;
  }

  // 🪤 Зареждаше се със <script src>. На жив сървър това 404-ваше мълчаливо
  // (относителният път се решаваше спрямо адреса на СТРАНИЦАТА, не спрямо
  // корена), а onload все пак се брои за успех — тестът „се зареждаше“ и
  // после го нямаше. fetch дава HTTP кода и грешката се вижда.
  function зареди(файл) {
    return fetch(файл + '?k=' + Date.now())
      .then(function (r) {
        if (!r.ok) throw new Error('HTTP ' + r.status);
        return r.text();
      })
      .then(function (код) { (0, eval)(код); return true; })
      .catch(function (e) { console.warn('🔴 ' + файл + ' — ' + e.message); return false; });
  }

  // Шестте API-та се казват различно. Опитваме познатите имена по ред.
  function извикай(API) {
    var имена = ['провери', 'пусни', 'run', 'check'];
    for (var i = 0; i < имена.length; i++) {
      if (typeof API[имена[i]] === 'function') return API[имена[i]].call(API);
    }
    throw new Error('няма метод за пускане (търсих: ' + имена.join('/') + ')');
  }

  // И докладите се различават. Свеждаме ги до три числа.
  function чети(r) {
    if (!r || typeof r !== 'object') return { пуснати: '?', минали: '?', паднали: '?' };
    var пуснати = r.ПУСНАТИ_ТЕСТА != null ? r.ПУСНАТИ_ТЕСТА
                : r.ПУСНАТИ != null ? r.ПУСНАТИ
                : r.ПРЕГЛЕДАНИ_ЗАПИСА != null ? r.ПРЕГЛЕДАНИ_ЗАПИСА
                : r.общо != null ? r.общо : '?';
    var паднали = r.ПАДНАЛИ != null ? r.ПАДНАЛИ
                : r.ПАДНАЛИ_ЧЕРВЕНИ != null ? r.ПАДНАЛИ_ЧЕРВЕНИ
                : r.ЧЕРВЕНИ_общо != null ? r.ЧЕРВЕНИ_общо : '?';
    var минали = r.МИНАЛИ != null ? r.МИНАЛИ
               : (пуснати !== '?' && паднали !== '?') ? пуснати - паднали : '?';
    // списъкът с паднали се казва различно навсякъде
    var списък = r.ПАДНАЛИТЕ || r.ЧЕРВЕНИ || r.паднали || r.НАХОДКИ || [];
    return { пуснати: пуснати, минали: минали, паднали: паднали, списък: списък,
             самопроверка: r.САМОПРОВЕРКА || r.самопроверка || null, суров: r };
  }

  async function пусни(опции) {
    опции = опции || {};
    var редове = [], общо = 0, паднали = 0, липсващи = [];

    for (var i = 0; i < ТЕСТОВЕ.length; i++) {
      var т = ТЕСТОВЕ[i];
      var API = вземи(т.глоб);
      if (!API) {
        var ок = await зареди(т.файл);
        await изчакай(700);
        API = вземи(т.глоб);
        if (!API) {
          липсващи.push(т.име + (ок ? ' (зареди се, но не се експортира)' : ' (файлът липсва)'));
          редове.push({ тест: т.име, статус: '⚠ няма' });
          continue;
        }
      }
      var r;
      try {
        r = извикай(API);
        if (r && typeof r.then === 'function') r = await r;
      } catch (e) {
        редове.push({ тест: т.име, статус: '🔴 гръмна: ' + String(e.message).slice(0, 70) });
        паднали++;
        continue;
      }
      var ч = чети(r);
      if (typeof ч.пуснати === 'number') общо += ч.пуснати;
      if (typeof ч.паднали === 'number') паднали += ч.паднали;
      редове.push({
        тест: т.име, пуснати: ч.пуснати, минали: ч.минали, паднали: ч.паднали,
        самопроверка: ч.самопроверка,
        статус: ч.паднали === 0 ? '✅' : '🔴',
        подробно: опции.подробно ? ч.списък : (ч.списък || []).slice(0, 4)
      });
      window['__' + т.име] = ч.суров;   // за ровене след това
      await изчакай(250);
    }

    var присъда = паднали === 0 && !липсващи.length ? '✅ ЧИСТО' : '🔴 ИМА ПАДНАЛИ';

    console.log('%c🧪 ВСИЧКО', 'font-weight:bold;font-size:15px');
    console.table(редове.map(function (r) {
      return { тест: r.тест, пуснати: r.пуснати, паднали: r.паднали, статус: r.статус };
    }));
    console.log(присъда + ' · общо пуснати: ' + общо + ' · паднали: ' + паднали);
    if (липсващи.length) console.log('⚠ незаредени:', липсващи);

    return {
      ПРИСЪДА: присъда,
      ОБЩО_ПУСНАТИ: общо,
      ПАДНАЛИ: паднали,
      незаредени: липсващи,
      по_тест: редове
    };
  }

  window.BL_ВСИЧКО = { пусни: пусни, тестове: ТЕСТОВЕ };
  window.BL_ALL = window.BL_ВСИЧКО;
  console.log('🧪 зареден. Пусни:  await BL_ВСИЧКО.пусни()');
})();
