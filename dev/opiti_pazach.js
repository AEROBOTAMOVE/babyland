// ═══════════════════════════════════════════════════════════
// 🛡️ ПАЗАЧ: СОБСТВЕНИТЕ НИ ОПИТИ СРЕЩУ СОБСТВЕНИТЕ НИ ФИЛТРИ
//
// Лабораторията има три пазача (isMedical, isSubstance, isBedRisk), които
// спират МАЙКАТА, ако напише опасен собствен опит. Никой не питаше същите
// пазачи за НАШИТЕ готови опити.
//
// 🔴 ПЪРВОТО ПУСКАНЕ (01.09) намери жив дефект — не в опита, а в ПАЗАЧА:
//    „Прибиране с песничка" беше отхвърлено заради „приБИРАне". Оттам:
//    „чувствам се виновна" → вино · „отваряне на прозореца" → отвар.
//    Три корена стояха като свободен подниз и ловяха невинното.
//
// Пазачът мери в ДВЕТЕ посоки: нашите опити да минават, а четирите известни
// опасни („мед в биберона", „по корем заспива по-бързо", „билков чай преди
// лягане", „играчка в креватчето") да си остават спрени.
// ═══════════════════════════════════════════════════════════
const fs = require('fs');
const П = __dirname + '/../js/lab.js';
// ── СВЕРКА ──
const vm = require('vm');
try { new vm.Script(fs.readFileSync(П, 'utf8')); } catch (e) { console.log('🔴 lab.js НЕ СЕ ПАРСВА: ' + e.message); process.exit(1); }
console.log('  ✅ lab.js парсва се');

// изваждаме READY и филтрите от живия файл, за да мерим ИСТИНСКИТЕ, не свои копия
const текст = fs.readFileSync(П, 'utf8');
const мR = текст.match(/const READY = \[[\s\S]*?\n  \];/);
if (!мR) { console.log('🔴 не намирам READY'); process.exit(1); }
const дайRe = име => {
  const m = текст.match(new RegExp('const ' + име + ' = (/.*/[a-z]*);'));
  if (!m) { console.log('🔴 не намирам ' + име); process.exit(1); }
  return eval(m[1]);
};
const MED = дайRe('MED'), ВЕЩЕСТВО = дайRe('ВЕЩЕСТВО'), ПОЗА_ЛЕГЛО = дайRe('ПОЗА_ЛЕГЛО'),
  САМО_ЗА_ЛЕГЛО = дайRe('САМО_ЗА_ЛЕГЛО'), ПРЕДМЕТ = дайRe('ПРЕДМЕТ'), МЯСТО = дайRe('МЯСТО_ЗА_СЪН');
const READY = eval('(' + мR[0].replace('const READY = ', '').replace(/;$/, '') + ')');

console.log('  📋 готови опити: ' + READY.length);
const поВъзраст = {};
for (const o of READY) { const k = o.от || 0; поВъзраст[k] = (поВъзраст[k] || 0) + 1; }
console.log('  по най-ранна възраст: ' + Object.entries(поВъзраст).sort((a, b) => a[0] - b[0]).map(([k, v]) => (k === '0' ? 'без праг' : 'от ' + k + ' м.') + ' ' + v).join(' · '));

// ── ГЛАВНАТА ПРОВЕРКА: собствените ни пазачи одобряват ли собствените ни опити ──
console.log('');
console.log('  🛡️ ПИТАМЕ СОБСТВЕНИТЕ СИ ФИЛТРИ ЗА СОБСТВЕНИТЕ СИ ОПИТИ:');
let блокирани = 0;
for (const o of READY) {
  const t = o.q + ' ' + o.a + ' ' + o.b;
  const мед = MED.test(t), вещ = ВЕЩЕСТВО.test(t);
  const легло = ПОЗА_ЛЕГЛО.test(t) || САМО_ЗА_ЛЕГЛО.test(t) || (ПРЕДМЕТ.test(t) && МЯСТО.test(t));
  if (мед || вещ || легло) {
    блокирани++;
    console.log('     🔴 ' + o.id.padEnd(14) + ' „' + o.q.slice(0, 52) + '"  ← ' + [мед && 'медицински', вещ && 'вещество', легло && 'легло/поза'].filter(Boolean).join(', '));
  }
}
console.log('     ' + (блокирани ? '🔴 ' + блокирани + ' от нашите опити НЕ БИХА МИНАЛИ през собствения ни пазач' : '✅ нито един готов опит не се спъва в собствените ни филтри'));

// ── и обратната посока: пазачът още ли лови опасното? ──
const опасни = ['Мед в биберона за по-дълъг сън', 'по корем заспива по-бързо', 'билков чай преди лягане', 'играчка в креватчето'];
let пуснати = 0;
for (const t of опасни) {
  const спрян = MED.test(t) || ВЕЩЕСТВО.test(t) || ПОЗА_ЛЕГЛО.test(t) || САМО_ЗА_ЛЕГЛО.test(t) || (ПРЕДМЕТ.test(t) && МЯСТО.test(t));
  if (!спрян) { пуснати++; console.log('     🔴 пазачът ПУСКА опасното: „' + t + '"'); }
}
console.log('     ' + (пуснати ? '🔴 пазачът пуска ' + пуснати : '✅ пазачът още лови и четирите известни опасни опита'));

// ═══════════════ 🛡️ САМОПРОВЕРКА (01.09.2026, ВЪЛНА 1.3) ═══════════════
//
// „Нито един готов опит не се спъва" е вярно и когато опитите са НУЛА.
// А „пазачът лови и четирите опасни" е вярно и когато пазачът лови ВСИЧКО.
// Затова: долна граница на броя опити + две подставени примамки.
const ДОЛНА_ОПИТИ = 30;
const спъва = t => MED.test(t) || ВЕЩЕСТВО.test(t) || ПОЗА_ЛЕГЛО.test(t) ||
                   САМО_ЗА_ЛЕГЛО.test(t) || (ПРЕДМЕТ.test(t) && МЯСТО.test(t));
console.log('');
console.log('  САМОПРОВЕРКА (иначе зеленото горе не значи нищо):');
let самоЧервено = 0;

if (READY.length < ДОЛНА_ОПИТИ) {
  самоЧервено++;
  console.log('     🔴 само ' + READY.length + ' готови опита — под долната граница ' + ДОЛНА_ОПИТИ +
              '. „Нито един не се спъва" при празен списък е нула, не успех.');
} else console.log('     ✅ готовите опити са ' + READY.length + ' ≥ ' + ДОЛНА_ОПИТИ);

{
  const примамка = 'Капка мед в биберона преди сън';
  if (спъва(примамка)) console.log('     ✅ примамка: подставен ОПАСЕН опит се спъва в пазача');
  else { самоЧервено++; console.log('     🔴 примамка: подставеният опасен опит МИНАВА — пазачът е ослепял'); }
}
{
  const примамка = 'Разходка в парка следобед';
  if (!спъва(примамка)) console.log('     ✅ примамка (обратната посока): подставен НЕВИНЕН опит минава');
  else { самоЧервено++; console.log('     🔴 примамка: пазачът спира и невинното — той спира всичко'); }
}
if (самоЧервено) {
  console.log('');
  console.log('🔴 САМОПРОВЕРКАТА ПАДА — числата горе НЕ СЕ БРОЯТ.');
}
process.exit((блокирани || пуснати || самоЧервено) ? 1 : 0);

