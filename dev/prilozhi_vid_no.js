const К_ОТРИЦ_НОВ = "(дави|задавя|задави|повръща|гърчи|припада|посинява|кърви|кърви|кървеше|пада|падна)(?![а-я])";
const К_ГОТВЕНЕ = '    if (ГОТВЕНЕ_ИЗГОРЯ.test(q)) return false;';

const ГЛАВА = [
  '  // ═══════════════════════════════════════════════════════════',
  '  // 🧬 ОСТА ВИД (свършен ↔ несвършен) — 09.09, ИЗМЕРЕНО',
  '  //',
  '  //   pre() реже ЕДНА буква и прощава окончания. Но българският вид мени',
  '  //   СТЪБЛОТО, не окончанието:',
  '  //       „глътна батерия"  🚨      „лапа батерия"        🔇',
  '  //       „стисна ме за врата" 🚨   „стиска ми гърлото"   🔇',
  '  //       „падна отгоре му" 🚨      „пада отгоре му"      🔇',
  '  //   Тоест: майка, която описва СЛУЧВАЩО СЕ СЕГА, получаваше тишина, а',
  '  //   майка, която разказва СВЪРШЕНО, получаваше тревога. Обратното на',
  '  //   нужното.',
  '  //',
  '  //   видКорен реже наставката за несвършен вид (-ва/-в/-н) и стига до',
  '  //   корена; видРавни пита дали другата дума започва от СЪЩИЯ корен и',
  '  //   продължава с гласна от вида (за да не лепне „падна" за „падам" и',
  '  //   „падение" за „пад"). _ЯЕ и _МЕТ гладят я↔е и пълногласието (гълт↔глът).',
  '  //',
  '  //   ИЗМЕРЕНО срещу 2874 правила и 1690 корпусни изречения:',
  '  //   0 заглушени · 0 сменени врати. Проговарят 12 от 12 смъртоносни',
  '  //   тишини, вкл. „лапа батерия", „гълта прах за пране", „пада в басейна",',
  '  //   „стиска ми гърлото", „натиска ме до стената", „посягах на бебето".',
  '  //',
  '  // ⚠️ ПЪРВИЯТ МИ ОПИТ ЗАМЕНИ „падна" с „пада" в ВЪРХУ_ЧОВЕК — а „пада"',
  '  //   НЕ Е префикс на „падна". Тоест смених свършеното СРЕЩУ несвършеното',
  '  //   и заглуших „шкафът ПАДНА отгоре му". Долу се ДОБАВЯ: пад(на|а).',
  '  // ПЪТ НАЗАД: махни „|| видРавни(…)" от пасва и хваща — останалото е',
  '  //   само разширени списъци и се маха дума по дума.',
  '  // ═══════════════════════════════════════════════════════════',
  '  const _ЯЕ = w => String(w).replace(/я/g, "е");',
  '  const _МЕТ = w => String(w).replace(/([бвгджзйклмнпрстфхцчшщ])ъ([лр])/g, "$1$2ъ");',
  '  const _ВИДОСТ = /^[вкщжчшст]?[ае]/;',
  '  const _ВИДПАМЕТ = new Map();',
  '  function видКорен(f) {',
  '    if (_ВИДПАМЕТ.has(f)) return _ВИДПАМЕТ.get(f);',
  '    const m = /^(.{3,})(ва|в|н)(ат|ям|ам|аш|яш|ах|ях|их|ох|ем|еш|ете|хме|хте|ха|ла|ло|ли|ят|а|е|и|о|у|м|ш|т|х|л)?$/.exec(_МЕТ(_ЯЕ(f)));',
  '    const r = (m && m[1].length >= 3) ? m[1] : null;',
  '    _ВИДПАМЕТ.set(f, r); return r;',
  '  }',
  '  function видРавни(x, f) {',
  '    const k = видКорен(f);',
  '    if (k === null) return false;',
  '    const nx = _МЕТ(_ЯЕ(x));',
  '    return nx.startsWith(k) && _ВИДОСТ.test(nx.slice(k.length));',
  '  }',
  К_PHRASE,
].join('\n');

const КОМ_НО = [
  '    // 🔴🔴 09.09 (ИЗМЕРЕНО) — ГОЛОТО „но" ИЗКЛЮЧВАШЕ ЦЕЛИЯ ПАЗАЧ.',
  '    //    Долният израз казва: „ако майката е добавила НО, не ѝ вярвай, че',
  '    //    всичко е наред". Но „но" нямаше граници и се улучваше вътре в',
  '    //    „стабилНО", „спокойНО", „нормалНО" и — най-често от всичко в',
  '    //    българския — в „мНОго". Тоест:',
  '    //        „не се дави, МНОГО е добре"        → 🚨 112',
  '    //        „не се гърчи, спи спокойНО"        → 🚨 112',
  '    //        „не посинява, много е розово"      → 🚨 112',
  '    //    Майка, която ИЗРИЧНО казва, че детето е добре, получаваше 112.',
  '    //    ИЗМЕРЕНО с границите: 2874 правила и 1690 изречения — 0 заглушени,',
  '    //    0 нови тревоги, 0 сменени врати. Истинското „но" продължава да',
  '    //    работи: „не се дави НО днес се задави два пъти" → 🚨.',
  '    //    (същият клас като \\b срещу кирилица — виж коментара при isRedFlag)',
].join('\n');

let s = fs.readFileSync(П, 'utf8');
const котви = [['①но', К_НО], ['phraseHit', К_PHRASE], ['пасва', К_ПАСВА], ['хваща', К_ХВАЩА],
  ['ГЛЪТНАТО', К_ГЛЪТ], ['ВЪРХУ_ЧОВЕК', К_ВЪРХУ_СТАР], ['отрицание', К_ОТРИЦ], ['готвене', К_ГОТВЕНЕ]];
let липсва = 0;
for (const [име, к] of котви) { const n = s.split(к).length - 1; console.log((n === 1 ? '  ✅ ' : '  🔴 ') + име + ' — срещания: ' + n); if (n !== 1) липсва++; }
if (липсва) { console.log('\n🔴 ' + липсва + ' котви не са точно по една — НЕ ПИША.'); process.exit(2); }
if (s.indexOf('видРавни') >= 0) { console.log('\n⚠️ видРавни вече е вътре — вече е приложено. Спирам.'); process.exit(0); }

const нов = s
  .replace(К_PHRASE, ГЛАВА)
  .replace(К_ПАСВА, К_ПАСВА + ' видРавни(x, w) ||')
  .replace(К_ХВАЩА, К_ХВАЩА.replace('изядена(x, f) ||', 'изядена(x, f) || видРавни(x, f) ||'))
