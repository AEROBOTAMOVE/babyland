const fs = require('fs');
const ПИШИ = process.argv.indexOf('--pishi') >= 0;
const П = 'js/helper.js';

const К_НО = "&& !/(но|обаче|а после|а сега|днес се|пак се)/.test(q)) return false;";
const К_НО_НОВ = "&& !/((^|[^а-я])(но|обаче|ама)(?![а-я]))|а после|а сега|днес се|пак се|само че/.test(q)) return false;";

const К_PHRASE = '  function phraseHit(q, phrase) {';
const К_ПАСВА = 'x.startsWith(pre(w)) || имперфект(x, w) || изядена(x, w) ||';
const К_ХВАЩА = '    const хваща = (x, f) => x.startsWith(pre(f)) || изядена(x, f) ||';
const К_ГЛЪТ = 'сдъвка|изяде|изяла|изяло|яде от|близна|смука от|пи от)';
