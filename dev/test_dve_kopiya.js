// 🧪 ДВЕ КОПИЯ — изпитание на js/dve_kopiya.js
//
// Пазач, който не е бил изпитан, е добро намерение. Тук се проверява и
// ДВЕТЕ посоки, защото само едната не доказва нищо:
//   ВДИГА ЛИ тревога при истински запис от другото копие
//   МЪЛЧИ ЛИ при дреболия (тема), при еднаква стойност, при чужд ключ
//   ЧАКА ЛИ, докато майката пише — и идва ли, щом тя спре
//
// 🪤 Node няма браузър. Тук се строи МЪНИЧЪК свят: колкото елементи и
//   събития са нужни, за да живее файлът. Ако утре той почне да ползва
//   нещо, което този свят няма, тестът ще ГРЪМНЕ — и това е добре: по-добре
//   червено, отколкото зелено върху непокрит код.
//
// ПУСКАНЕ: node dev/test_dve_kopiya.js
// ПЪТ НАЗАД: файлът само ЧЕТЕ проекта.
// ═══════════════════════════════════════════════════════════
const fs = require('fs');
const vm = require('vm');
const path = require('path');
process.chdir(path.resolve(__dirname, '..'));

function свят() {
  const слушатели = {};
  const мк = таг => {
    const е = {
      tagName: таг, style: { cssText: '' }, children: [], value: '', textContent: '',
      isContentEditable: false, isConnected: false,
      setAttribute() {}, focus() {}, blur() {},
      appendChild(x) { this.children.push(x); x.isConnected = true; return x; },
      remove() { this.isConnected = false; },
      addEventListener() {},
      querySelectorAll() { return []; },
      set innerHTML(v) { this._html = v; }, get innerHTML() { return this._html || ''; }
    };
    return е;
  };
  const body = мк('BODY');
  const ctx = {
    console: { log() {}, warn() {} }, JSON, Math, Date, String, Number, Array, Object, RegExp,
    setTimeout: (f) => { f(); return 0; },     // без забавяне — светът е синхронен
    Event: function (тип) { this.type = тип; }
  };
  ctx.document = {
    body,
    activeElement: body,
    createElement: мк,
    addEventListener(тип, f) { (слушатели[тип] = слушатели[тип] || []).push(f); },
    querySelectorAll() { return []; },
    hidden: false
  };
  ctx.window = ctx; ctx.globalThis = ctx; ctx.self = ctx;
  ctx.addEventListener = function (тип, f) { (слушатели[тип] = слушатели[тип] || []).push(f); };
  ctx.dispatchEvent = function (е) { (слушатели[е.type] || []).forEach(f => f(е)); };
  ctx.location = { reload() {} };
  vm.createContext(ctx);
  new vm.Script(fs.readFileSync('js/dve_kopiya.js', 'utf8')).runInContext(ctx);
  ctx.__лентиБрой = () => body.children.length;
  ctx.__слушатели = слушатели;
  return ctx;
}

let паднали = 0, общо = 0;
function проверка(текст, условие) {
  общо++;
  if (!условие) паднали++;
  console.log('     ' + (условие ? '✅' : '🔴') + ' ' + текст);
}

console.log('🧪 ДВЕ КОПИЯ НА ЕДНО МЯСТО\n');

// ── 1. истински запис от другото копие → тревога
let w = свят();
w.BL_ДВЕ_КОПИЯ.пробвай('bl_fears', '[]', '[{"t":"нещо"}]');
console.log('  ── когато другото копие запише нещо на майката ──');
проверка('вдига тревога', w.BL_ДВЕ_КОПИЯ.казано() === true);
проверка('лентата е сложена в страницата', w.__лентиБрой() === 1);
проверка('запомня КОЙ ключ е сменен', w.BL_ДВЕ_КОПИЯ.сменени().indexOf('bl_fears') >= 0);
w.BL_ДВЕ_КОПИЯ.пробвай('bl_diary', '[]', '[1]');
проверка('втори запис НЕ прави втора лента', w.__лентиБрой() === 1);

// ── 2. дреболиите мълчат
console.log('\n  ── когато другото копие смени нещо дребно ──');
for (const [ключ, старо, ново, какво] of [
  ['bl_theme', 'light', 'dark', 'смяна на тема'],
  ['bl_room_visited', '[]', '["x"]', 'брояч на посетени стаи'],
  ['bl_fears', '[1]', '[1]', 'СЪЩАТА стойност'],
  ['чужд_ключ', 'a', 'b', 'ключ, който не е на приложението'],
  ['bl_sounds', '0', '1', 'звуците']
]) {
  const т = свят();
  т.BL_ДВЕ_КОПИЯ.пробвай(ключ, старо, ново);
  проверка('мълчи при ' + какво, т.BL_ДВЕ_КОПИЯ.казано() === false && т.__лентиБрой() === 0);
}

// ── 3. изчистване на ВСИЧКО от другото копие → винаги тревога
console.log('\n  ── когато другото копие изчисти ВСИЧКО ──');
const т3 = свят();
т3.BL_ДВЕ_КОПИЯ.пробвай(null, null, null);
проверка('вдига тревога и при пълно изчистване', т3.BL_ДВЕ_КОПИЯ.казано() === true);

// ── 4. не прекъсва майка, която пише
console.log('\n  ── докато майката ПИШЕ ──');
const т4 = свят();
const поле = т4.document.createElement('TEXTAREA');
поле.value = 'недописано изречение за бебето';
т4.document.activeElement = поле;
т4.BL_ДВЕ_КОПИЯ.пробвай('bl_diary', '[]', '[{"t":"нещо"}]');
проверка('НЕ показва лента върху недописан текст', т4.__лентиБрой() === 0);
проверка('но си отбелязва, че чака', т4.BL_ДВЕ_КОПИЯ.чака() === true);
// мама спира да пише и докосва екрана
т4.document.activeElement = т4.document.body;
(т4.__слушатели['pointerdown'] || []).forEach(f => f({ type: 'pointerdown' }));
проверка('щом спре да пише → лентата идва', т4.__лентиБрой() === 1);

// ── 5. празно поле не е „пише"
console.log('\n  ── когато полето е празно (курсорът стои, но няма текст) ──');
const т5 = свят();
const празно = т5.document.createElement('INPUT');
празно.value = '';
т5.document.activeElement = празно;
т5.BL_ДВЕ_КОПИЯ.пробвай('bl_diary', '[]', '[1]');
проверка('казва веднага — няма какво да прекъсне', т5.__лентиБрой() === 1);

// ── 6. самопроверка: може ли този тест изобщо да гръмне
console.log('\n  ── САМОПРОВЕРКА ──');
const т6 = свят();
проверка('нов свят започва БЕЗ лента (иначе всичко горе е фалшиво зелено)',
  т6.__лентиБрой() === 0 && т6.BL_ДВЕ_КОПИЯ.казано() === false);
проверка('файлът наистина е закачил слушател за „storage"',
  (т6.__слушатели['storage'] || []).length > 0);

console.log('\n  ПРОВЕРКИ: ' + общо + ' · ' + (паднали ? '🔴 ПАДНАЛИ: ' + паднали : '✅ всички минаха'));
process.exit(паднали ? 1 : 0);
