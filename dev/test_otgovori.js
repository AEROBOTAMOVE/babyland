  function пусни(опции) {
    опции = опции || {};
    var снимкаПреди = снимка();

    console.log('%c🎯 ТЕСТ ЗА ОТГОВОРИТЕ', 'font-size:15px;font-weight:700');

    var записи = базата();
    if (typeof window.BL_MATCH !== 'function' || !записи || !записи.length) {
      var празно = {
        ПУСНАТИ_ТЕСТА: 0,
        ГРЕШКА: typeof window.BL_MATCH !== 'function'
          ? 'няма window.BL_MATCH — helper.js не е зареден или не е стигнал до края'
          : 'базата е празна'
      };
      console.log('%c🔴 НЕ ПУСНАХ НИТО ЕДИН ТЕСТ — ' + празно.ГРЕШКА, 'color:#c62828;font-weight:700');
      console.log('Това НЕ е „0 провала“. Тест без пуснати тестове е счупен тест.');
      window.BL_ОТГОВОРИ.последен = празно;
      return празно;
    }

    var т = сглоби();
    var паднали = т.filter(function (x) { return !x.мина; });
    var минали = т.length - паднали.length;

    // ── покритие: кои стаи и колко различни записа са били достигнати ──
    var стаи = {}, достигнати = {};
    т.forEach(function (x) {
      стаи[x.стая] = стаи[x.стая] || { пуснати: 0, паднали: 0 };
      стаи[x.стая].пуснати++;
      if (!x.мина) стаи[x.стая].паднали++;
      if (x.запис) достигнати[x.запис.id] = true;
    });
    var бройСтаи = Object.keys(стаи).length;
    var бройЗаписи = Object.keys(достигнати).length;

    var сп = самопроверка();
    var спПаднали = сп.filter(function (x) { return !x.мина; });

    var промени = сверка(снимкаПреди);

    var доклад = {
      ПУСНАТИ_ТЕСТА: т.length,
      МИНАЛИ: минали,
      ПАДНАЛИ: паднали.length,
      по_вид: ['има-отговор', 'кражба', 'кражба-нова', 'стандарт', 'контрола'].map(function (в) {
        var г = т.filter(function (x) { return x.вид === в; });
        var м = г.filter(function (x) { return x.мина; }).length;
        return в + ': ' + м + '/' + г.length;
      }).join('  ·  '),
      ПОКРИТИЕ: 'стаи ' + бройСтаи + '/9  ·  различни записа достигнати ' + бройЗаписи +
        ' от ' + записи.length + '  ·  въпроси „има-отговор“ ' + т.filter(function (x) { return x.вид === 'има-отговор'; }).length,
      по_стаи: стаи,
      ПРОВАЛИ: паднали.map(function (x) {
        return { вид: x.вид, име: x.име, въпрос: x.въпрос, стая: x.стая, ОЧАКВАНО: x.ОЧАКВАНО, ПОЛУЧЕНО: x.ПОЛУЧЕНО };
      }),
      САМОПРОВЕРКА: сп,
      САМОПРОВЕРКА_ПАДНАЛИ: спПаднали.length,
      LOCALSTORAGE: промени.четимо
        ? (промени.промени.length ? { пипнати: промени.промени } : 'непокътнат — нито един ключ не е добавен, променен или изтрит')
        : 'недостъпен (не може да се прочете)',
      ВСИЧКИ: опции.всички ? т.map(function (x) {
        return { вид: x.вид, име: x.име, ОЧАКВАНО: x.ОЧАКВАНО, ПОЛУЧЕНО: x.ПОЛУЧЕНО, мина: x.мина };
      }) : '(подай {всички:true}, за да видиш и миналите)'
    };

    // ── изход в конзолата ──
    console.log('пуснати теста: ' + т.length + '  ·  минали: ' + минали + '  ·  паднали: ' + паднали.length);
    console.log('покритие → ' + доклад.ПОКРИТИЕ);
    console.log('по вид → ' + доклад.по_вид);

    if (паднали.length) {
      console.log('%c🔴 ПАДНАЛИ: ' + паднали.length, 'color:#c62828;font-weight:700');
      console.table(доклад.ПРОВАЛИ);
    } else {
      console.log('%c✅ 0 провала от ' + т.length + ' пуснати теста.', 'color:#2e7d32;font-weight:700');
    }

    if (спПаднали.length) {
      console.log('%c🔴 САМОПРОВЕРКАТА ПАДНА (' + спПаднали.length + ') — на този доклад НЕ може да се вярва:',
        'color:#c62828;font-weight:700');
    } else {
      console.log('%c🧪 самопроверка: ' + сп.length + '/' + сп.length +
        ' — тестът доказано пада на нарочно счупено и връща всичко обратно.', 'color:#2e7d32');
    }
    console.table(сп);

    if (опции.всички) console.table(доклад.ВСИЧКИ);

    console.log('localStorage → ' + (typeof доклад.LOCALSTORAGE === 'string'
      ? доклад.LOCALSTORAGE : 'ПИПНАТ, върнат — виж доклада'));

    window.BL_ОТГОВОРИ.последен = доклад;
    return доклад;
  }

  window.BL_ОТГОВОРИ = { пусни: пусни, последен: null };
  window.BL_ANSWERS = window.BL_ОТГОВОРИ;   // за писане без кирилица в конзолата
