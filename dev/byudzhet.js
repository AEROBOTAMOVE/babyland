#!/usr/bin/env node
/* eslint-disable */
// ═══════════════════════════════════════════════════════════════════════════
// 📦 БЮДЖЕТЪТ — колко тежи приложението за майката, и кога да се разтревожим
// ═══════════════════════════════════════════════════════════════════════════
//
// ЗАЩО (07.09.2026): наръчникът за immersive web (§65) казва, че бюджетът е
// ДИЗАЙН ОГРАНИЧЕНИЕ, не отчет — определя се ПРЕДИ да се избере ефект.
// Днес приложението нямаше никакъв: измерих 100 скрипта и 8.96 MB сурово.
//
// 🪤 И ЕДНО ЧЕСТНО ЧИСЛО, КОЕТО ОБОРИ СОБСТВЕНАТА МИ ТРЕВОГА:
//    първо казах „10.3 MB на първо отваряне". После проверих какво реално
//    пътува: GitHub Pages компресира и kb.js минава като 1.0 MB вместо 4.8.
//    Истинското първо отваряне е ~2.8 MB. Тоест мери се СЛЕД gzip, инак
//    бюджетът плаши с числа, които никой не тегли.
//
// КАКВО МЕРИ (само това, което index.html наистина зарежда):
//   · JS и CSS, сурово и след gzip
//   · шрифтовете (woff2 вече са компресирани)
//   · броя заявки — 100 отделни файла имат своя цена, но и своя полза:
//     сменен файл се тегли сам, а не в пакет. Затова тук е предупреждение,
//     не забрана.
//
// 🔴 07.09, ПОПРАВКА НА САМИЯ ИНСТРУМЕНТ: първо сложих таван 140 KB за CSS,
//    изведен от ПАРТИАЛНО измерване (регулярният ми израз беше пропуснал част
//    от файловете). Истинската база е 156 KB. Таван ПОД собствената база не
//    мери нищо — той просто гърми всеки ден и научава човека да го игнорира.
//    Това е същият дефект, който поправях цял ден в другите пазачи, само че
//    мой. Таванът е вдигнат на 190 (база + запас) и причината е ТУК, записана,
//    а не мълчаливо коригирана.
//
// ПРАГОВЕТЕ не са закон от небето. Изведени са от измереното днес плюс
// запас за растеж, за да ХВАЩАТ РЕГРЕСИЯ, не да гълчат за нормалното.
//
// ⚠️ ТОЗИ ФАЙЛ САМО ЧЕТЕ.
// ПУСКАНЕ: node dev/byudzhet.js          (изход 1 при надвишен таван)
//          node dev/byudzhet.js --zapis  (записва снимка в qa/)
// ═══════════════════════════════════════════════════════════════════════════
'use strict';
const fs = require('fs');
const path = require('path');
const zlib = require('zlib');
const КОРЕН = path.resolve(__dirname, '..');
process.chdir(КОРЕН);
const ЗАПИС = process.argv.includes('--zapis');

// ── праговете ──
const ТАВАН = {
  gzip_общо_MB: 3.2,      // измерено 2.79 + запас; над това мамата чака осезаемо
  // 🔴 09.09 — ТАВАНЪТ СЕ ВДИГА СЪЗНАТЕЛНО, С ПРИЧИНА (както пише §65 долу).
  //   Беше 2.4 (измерено 2.11). Днешното пълнене го мина: +58 карти,
  //   +2321 ключа, +11 статии → 2.42. Тоест 20 KB над тавана.
  //   ЗАЩО СЕ ВДИГА, А НЕ СЕ РЕЖЕ: това е офлайн приложение, раздавано по
  //   връзка — теглото се плаща ВЕДНЪЖ, после майката го ползва без мрежа.
  //   2.98 MB общо са секунди на 4G, а всяка от 58-те карти е въпрос, на
  //   който досега се отговаряше с тишина или с чужда карта.
  //   ⚠️ ЧЕСТНОТО ЧИСЛО: kb.js сам е 1296 KB gz — 53% от целия JS.
  //
  // 🔴🔴 09.09, ПО-КЪСНО СЪЩИЯ ДЕН — „РАЗЦЕПИ kb.js" Е ОБОРЕНО С МЯРКА.
  //   Тук пишеше „следващото прекрачване не се вдига — разцепва се".
  //   Това беше ДОГАДКА. Измерено (dev/ot_kakvo_e_kb.js · dev/brotli_ili_
  //   razcepvane.js · dev/cenata_na_obnovlenieto.js), по трите възможни оси:
  //
  //   1) ПО КЛЮЧОВЕ (както предполагах). Ключовете са само 22.7% от gzip,
  //      не обемът. Обемът е ТЕКСТЪТ: core 30.1% + tip 17.7% + follow 13.7%.
  //         kb.js без ключове 988 КБ + отделен файл с тях 319 КБ = 1306 КБ
  //         срещу 1296 КБ сега → +10 КБ. РАЗЦЕПВАНЕТО ГО ПРАВИ ПО-ГОЛЯМО.
  //      Причината: gzip печели от повторенията МЕЖДУ ключове и текст;
  //      разделиш ли ги, всеки губи речника на другия.
  //
  //   2) ПО СТАЯ (9 файла). Девет парчета = 1212 КБ. При ДНЕШНОТО обновяване
  //      осем от девет стаи са пипнати → 1185 КБ срещу 1296 КБ = −110 КБ.
  //      Под прага, срещу 9 нови заявки И капана на закования списък в
  //      sw.js (нов файл извън списъка = МЪЛЧАЛИВА грешка офлайн).
  //
  //   3) КОМПРЕСИЯТА — ето къде е печалбата, и тя е в СЕРВИРАНЕТО, не в кода:
  //         kb.js  gzip 1296 КБ  →  brotli 886 КБ   (−410 КБ, −32%)
  //         всички  gzip 1626 КБ →  brotli 1149 КБ  (−476 КБ)
  //      Причината е ПРОЗОРЕЦЪТ: gzip има закован 32 КБ и не вижда
  //      повторенията през 5.5 МБ файл. brotli с 2^22 ги вижда.
  //      ИЗМЕРЕНО ЖИВО на 09.09: GitHub Pages връща `content-encoding: gzip`
  //      и content-length 1 458 643 за kb.js. Netlify сервира brotli сам —
  //      тоест самото преместване, което вече е подготвено, носи −476 КБ.
  //      ⚠️ Че Netlify наистина праща brotli, е ПРЕДПОЛОЖЕНО, докато не се
  //         качи и не се измери със същата сонда:
  //           fetch(url, {cache:'reload'}).then(r=>r.headers.get('content-encoding'))
  //
  //   ЗАТОВА: не разцепвай. Ако таванът пак опре — първо мери, после решавай.
  gzip_js_MB: 2.6,        // беше 2.4; вдигнат 09.09 с причината горе
  gzip_css_KB: 190,       // база 156 + запас за растеж
  заявки: 130,            // измерени 114; предупреждение, не забрана
  един_файл_gzip_KB: 1400 // kb.js е 1133; над 1.4 MB трябва разцепване
};

const html = fs.readFileSync('index.html', 'utf8');
const пътища = [...html.matchAll(/(?:src|href)=["']([^"']+\.(?:js|css))(?:\?[^"']*)?["']/g)]
  .map(m => m[1].replace(/^\.\//, ''));
const уникални = [...new Set(пътища)];

let суровоJS = 0, gzJS = 0, суровоCSS = 0, gzCSS = 0, brВсичко = 0;
const файлове = [];
// 🧵 09.09: мери се И brotli. Не за да се сравнява с таван, а защото
//   разликата между двете Е решението „кой хост" — а тя не е дребна:
//   измерено, целият JS+CSS пада с около 30% само от компресията.
const бро = b => zlib.brotliCompressSync(b, { params: {
  [zlib.constants.BROTLI_PARAM_QUALITY]: 11,
  [zlib.constants.BROTLI_PARAM_LGWIN]: 22,
  [zlib.constants.BROTLI_PARAM_SIZE_HINT]: b.length } }).length;
for (const п of уникални) {
  let b;
  try { b = fs.readFileSync(п); } catch (e) { continue; }
  const g = zlib.gzipSync(b, { level: 9 }).length;
  брВсичкоДобави(b);
  файлове.push([п, b.length, g]);
  if (/\.css$/.test(п)) { суровоCSS += b.length; gzCSS += g; }
  else { суровоJS += b.length; gzJS += g; }
}
function брВсичкоДобави(b) { try { brВсичко += бро(b); } catch (e) {} }
let шрифт = 0, бройШрифт = 0;
try { for (const f of fs.readdirSync('fonts')) { шрифт += fs.statSync(path.join('fonts', f)).size; бройШрифт++; } } catch (e) {}

// 🩺 самопроверка: празен резултат значи счупен четец, не лек проект
if (файлове.length < 20) {
  console.error('');
  console.error('  🔴 СЛЯП УРЕД: прочетени само ' + файлове.length + ' файла от index.html.');
  console.error('     Приложението има над 100. Числата долу нямаше да значат нищо.');
  console.error('');
  process.exit(2);
}

const gzОбщо = gzJS + gzCSS + шрифт;
const MB = n => (n / 1048576).toFixed(2);
const KB = n => Math.round(n / 1024);

const редове = [];
const съди = (име, стойност, таван, форм, мек) => {
  const над = стойност > таван;
  редове.push([име, форм(стойност), форм(таван), над ? (мек ? '⚠️' : '🔴') : '✅', над && !мек]);
};

console.log('');
console.log('  📦 БЮДЖЕТ НА ПЪРВОТО ОТВАРЯНЕ');
console.log('     (сурово е това, което браузърът ПАРСВА; gzip е това, което ТЕГЛИ)');
console.log('');
console.log('     JS  : ' + MB(суровоJS) + ' MB сурово  →  ' + MB(gzJS) + ' MB по мрежата');
console.log('     CSS : ' + MB(суровоCSS) + ' MB сурово  →  ' + KB(gzCSS) + ' KB по мрежата');
console.log('     шрифтове: ' + KB(шрифт) + ' KB (' + бройШрифт + ' woff2, вече компресирани)');
console.log('     ─────────────────────────────────────────────');
console.log('     ОБЩО ПО МРЕЖАТА: ' + MB(gzОбщо) + ' MB   ·   заявки: ' + уникални.length);
console.log('');
// 🧵 КОЙ ХОСТ — това е по-голямото решение от всяко разцепване
if (brВсичко) {
  const спестени = (gzJS + gzCSS) - brВсичко;
  console.log('     🧵 СЪЩИТЕ ФАЙЛОВЕ С BROTLI: ' + MB(brВсичко) + ' MB'
    + '   (−' + Math.round(спестени / 1024) + ' KB, −' + (100 * спестени / (gzJS + gzCSS)).toFixed(0) + '%)');
  console.log('        Измерено живо 09.09: GitHub Pages праща gzip. Netlify праща');
  console.log('        brotli сам. Тоест ХОСТЪТ решава повече от кода тук.');
  console.log('        Проверка след качване, в конзолата на живия сайт:');
  console.log('          fetch(location.href+"js/kb.js",{cache:"reload"})');
  console.log('            .then(r=>r.headers.get("content-encoding"))');
  console.log('');
}

съди('общо по мрежата', gzОбщо / 1048576, ТАВАН.gzip_общо_MB, x => x.toFixed(2) + ' MB');
съди('от тях JS', gzJS / 1048576, ТАВАН.gzip_js_MB, x => x.toFixed(2) + ' MB');
съди('от тях CSS', gzCSS / 1024, ТАВАН.gzip_css_KB, x => Math.round(x) + ' KB');
съди('брой заявки', уникални.length, ТАВАН.заявки, x => String(x), true);
const найГолям = файлове.slice().sort((a, b) => b[2] - a[2])[0];
съди('най-голям файл', найГолям[2] / 1024, ТАВАН.един_файл_gzip_KB, x => Math.round(x) + ' KB');

console.log('  ── СРЕЩУ ТАВАНА ──');
let паднали = 0;
for (const [име, стойност, таван, знак, лошо] of редове) {
  console.log('     ' + знак + ' ' + име.padEnd(18) + String(стойност).padStart(10) + '   таван ' + таван);
  if (лошо) паднали++;
}
console.log('');
console.log('  ── НАЙ-ЕДРИТЕ ПО МРЕЖАТА ──');
for (const [п, b, g] of файлове.sort((a, b2) => b2[2] - a[2] || b2[2] - a[2]).slice(0, 6)) {
  console.log('     ' + String(KB(g)).padStart(5) + ' KB gz  (' + String(KB(b)).padStart(5) + ' KB сурово)  ' + п);
}

if (ЗАПИС) {
  const дир = 'qa';
  try { fs.mkdirSync(дир, { recursive: true }); } catch (e) {}
  const снимка = {
    кога: new Date().toISOString(),
    gzip_общо_байта: gzОбщо, gzip_js: gzJS, gzip_css: gzCSS, шрифтове: шрифт,
    сурово_js: суровоJS, сурово_css: суровоCSS,
    заявки: уникални.length,
    най_едри: файлове.sort((a, b) => b[2] - a[2]).slice(0, 10).map(([п, b, g]) => ({ файл: п, сурово: b, gzip: g })),
    таван: ТАВАН
  };
  fs.writeFileSync(path.join(дир, 'byudzhet.json'), JSON.stringify(снимка, null, 1));
  console.log('');
  console.log('  📄 снимка записана в qa/byudzhet.json');
}
console.log('');
if (паднали) {
  console.log('  🔴 ' + паднали + ' таван(а) надвишен(и).');
  console.log('     Наръчникът (§65): бюджетът е ДИЗАЙН ОГРАНИЧЕНИЕ. Или се маха тежест,');
  console.log('     или таванът се вдига СЪЗНАТЕЛНО и с записана причина — не мълчаливо.');
  console.log('');
  process.exit(1);
}
console.log('  ✅ в бюджета');
console.log('');
