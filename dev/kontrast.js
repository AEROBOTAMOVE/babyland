// 👁️ КОНТРАСТЪТ — по КОРЕН, не по списък
//
// Защо пак: една поправка обяви „22 → 0, в двете теми". Ревизията я обори:
// „Кръгът е затворен по СПИСЪК, не по КОРЕН — селекторите са намерени ЧРЕЗ
// теста, а тестът не гледа онбординга, затова .onb-lbl-soft оцеля."
// После одитът на таба „Вход" намери 115 от 203 текста под прага в светла тема.
// Тоест две мерки казват несъвместими неща. Тази брои ВСИЧКО и казва КОЛКО.
//
// 🪤 ЧЕТИРИТЕ НАЧИНА, ПО КОИТО ТАКЪВ МЕРАЧ ЛЪЖЕ (всеки платен в този проект):
// 1. ГРАДИЕНТЪТ не е в backgroundColor. Елемент с linear-gradient има
//    backgroundColor: transparent → наивният мерач намира бял фон отдолу и
//    вика „контраст 1.1". Даде 4 фалшиви тревоги. Тук такива се отчитат
//    ОТДЕЛНО като „не мога да отсъдя", а не като дефект.
// 2. ВХОДНАТА АНИМАЦИЯ държи слоя на opacity 0 в скрит таб → всичките 203
//    излизат „под прага". Затова тук анимациите се ЗАМРАЗЯВАТ преди мерене.
// 3. OPACITY СЕ НАТРУПВА по веригата родители. Текст с .7 в кутия с .8 е
//    реално .56. Мерене само на собствената opacity подценява.
// 4. ТЪМНАТА ТЕМА е с ОБРАТНА посока. Формулата на WCAG е симетрична
//    (по-светлото отгоре), затова важи и за двете — но прагът за „голям текст"
//    (3:1) е друг и се смята по размера, не по темата.
//
// ПУСКАНЕ в конзолата:  await BL_KONTRAST()          // текущият екран
//                       await BL_KONTRAST({всички:1}) // обхожда екраните
// ПЪТ НАЗАД: файлът само чете; замразяващият стил се маха накрая.
// ═══════════════════════════════════════════════════════════
(function () {
  'use strict';

  var ПРАГ = 4.5, ПРАГ_ГОЛЯМ = 3.0;

  function разбор(c) {
    var m = String(c).match(/[\d.]+/g);
    if (!m) return null;
    return { r: +m[0], g: +m[1], b: +m[2], a: m.length > 3 ? +m[3] : 1 };
  }
  function смеси(отгоре, отдолу) {
    var a = отгоре.a;
    return { r: отгоре.r * a + отдолу.r * (1 - a),
             g: отгоре.g * a + отдолу.g * (1 - a),
             b: отгоре.b * a + отдолу.b * (1 - a), a: 1 };
  }
  function лум(c) {
    var f = function (v) { v /= 255; return v <= 0.03928 ? v / 12.92 : Math.pow((v + 0.055) / 1.055, 2.4); };
    return 0.2126 * f(c.r) + 0.7152 * f(c.g) + 0.0722 * f(c.b);
  }
  function отношение(a, b) {
    var x = лум(a), y = лум(b);
    return (Math.max(x, y) + 0.05) / (Math.min(x, y) + 0.05);
  }

  // ⏱️ 18.08: първата версия викаше getComputedStyle за ВСЕКИ прародител на
  // ВСЕКИ елемент — при стая с ~2000 възела това е десетки хиляди викания и
  // мерачът просто забиваше (30 сек без отговор, три пъти подред).
  // Тук всеки елемент се пита ВЕДНЪЖ, а веригите нагоре се помнят.
  var кешСтил, кешНепроз, кешФон;
  function стил(e) {
    var v = кешСтил.get(e);
    if (!v) { v = getComputedStyle(e); кешСтил.set(e, v); }
    return v;
  }

  // 🪤 3: opacity се натрупва по цялата верига нагоре
  function общаНепрозрачност(e) {
    var в = кешНепроз.get(e);
    if (в !== undefined) return в;
    var своя = parseFloat(стил(e).opacity);
    if (isNaN(своя)) своя = 1;
    var р = (!e.parentElement || e === document.documentElement)
      ? своя : своя * общаНепрозрачност(e.parentElement);
    кешНепроз.set(e, р);
    return р;
  }

  // 🪤 1: ако по пътя нагоре има картинка/градиент — НЕ съдим
  function фонПод(e) {
    var в = кешФон.get(e);
    if (в !== undefined) return в;
    var cs = стил(e), р;
    if (cs.backgroundImage && cs.backgroundImage !== 'none') р = { градиент: true };
    else {
      var b = разбор(cs.backgroundColor);
      if (b && b.a > 0.99) р = { цвят: b };
      else if (b && b.a > 0) р = { полупрозрачен: true, цвят: b };
      else р = e.parentElement ? фонПод(e.parentElement) : { цвят: { r: 255, g: 255, b: 255, a: 1 } };
    }
    кешФон.set(e, р);
    return р;
  }

  // ⏱️ 18.08, ВТОРАТА спирачка: тук стоеше getBoundingClientRect за ВСЕКИ
  // елемент. Той принуждава браузъра да преизчисли подредбата — хиляда пъти
  // подред, при това веднага след четене на стилове, тоест най-лошият възможен
  // ред. В СКРИТ панел рендерерът е дроселиран и мерачът виси над 30 секунди
  // (три пъти подред, докато не го проследих).
  // checkVisibility() отговаря на същия въпрос БЕЗ да пипа подредбата.
  // Резервният път ползва offsetParent — също без принудително преизчисляване.
  function видим(e) {
    var cs = стил(e);
    if (cs.display === 'none' || cs.visibility === 'hidden') return false;
    if (e.checkVisibility) return e.checkVisibility({ checkOpacity: false, checkVisibilityCSS: true });
    return e.offsetParent !== null || cs.position === 'fixed';
  }

  function същинскиТекст(e) {
    var t = '';
    for (var i = 0; i < e.childNodes.length; i++)
      if (e.childNodes[i].nodeType === 3) t += e.childNodes[i].nodeValue;
    return t.replace(/\s+/g, ' ').trim();
  }

  // 🪤 5 (хванат на живо 18.08): ЕМОДЖИТО не се боядисва от `color`.
  // Мерачът обяви „🎤" и „💃" за контраст 1.45:1, защото правилото им дава
  // color:black върху тъмен фон — но емоджито се рисува със собствените си
  // цветове и черното не го докосва. Две фалшиви тревоги в тъмна тема.
  // Ако бях повярвал, щях да „поправям" здрави правила.
  // Тук пада всичко, в което няма НИТО ЕДНА буква или цифра.
  var БУКВА = /[a-zA-Zа-яА-Я0-9]/;
  function самоЗнаци(t) { return !БУКВА.test(t); }

  function мериЕкран(име) {
    // кешовете са ЗА ЕДНО МЕРЕНЕ — иначе втората тема чете стойностите на първата
    кешСтил = new WeakMap(); кешНепроз = new WeakMap(); кешФон = new WeakMap();
    var всички = document.querySelectorAll('body *');
    var прегледани = 0, съдени = 0, паднали = [], неотсъдени = 0;
    var скрити = 0, емоджита = 0, прозрачни = 0;
    for (var i = 0; i < всички.length; i++) {
      var e = всички[i];
      var текст = същинскиТекст(e);
      if (!текст || текст.length < 2) continue;
      if (самоЗнаци(текст)) { емоджита++; continue; }  // 🪤 5
      прегледани++;
      if (!видим(e)) { скрити++; continue; }
      var cs = стил(e);
      var цвят = разбор(cs.color);
      if (!цвят) continue;
      var неп = общаНепрозрачност(e);
      if (неп < 0.02) { прозрачни++; continue; }      // невидим — не е дефект
      var ф = фонПод(e);
      if (ф.градиент || ф.полупрозрачен) { неотсъдени++; continue; }
      съдени++;
      // цветът се слива с фона, като се вземе И натрупаната непрозрачност
      var ефективен = смеси({ r: цвят.r, g: цвят.g, b: цвят.b, a: цвят.a * неп }, ф.цвят);
      var к = отношение(ефективен, ф.цвят);
      var размер = parseFloat(cs.fontSize) || 16;
      var дебел = (parseInt(cs.fontWeight, 10) || 400) >= 700;
      var голям = размер >= 24 || (размер >= 18.66 && дебел);
      var праг = голям ? ПРАГ_ГОЛЯМ : ПРАГ;
      if (к < праг) {
        паднали.push({
          екран: име,
          клас: (e.className && typeof e.className === 'string' ? e.className : e.tagName).slice(0, 46),
          таг: e.tagName.toLowerCase(),
          текст: текст.slice(0, 38),
          контраст: +к.toFixed(2), праг: праг,
          размер: Math.round(размер), непрозрачност: +неп.toFixed(2),
          цвят: cs.color, фон: 'rgb(' + Math.round(ф.цвят.r) + ',' + Math.round(ф.цвят.g) + ',' + Math.round(ф.цвят.b) + ')'
        });
      }
    }
    return { екран: име, прегледани: прегледани, съдени: съдени, неотсъдени: неотсъдени,
             скрити: скрити, емоджита: емоджита, прозрачни: прозрачни, паднали: паднали };
  }

  window.BL_KONTRAST = function (опции) {
    опции = опции || {};
    // 🪤 2: замразяваме анимациите — иначе входната държи слоя на opacity 0
    var s = document.createElement('style');
    s.textContent = '*,*::before,*::after{animation:none!important;transition:none!important}';
    document.head.appendChild(s);

    var р = мериЕкран(опции.име || 'текущият екран');
    document.head.removeChild(s);

    // групираме по КЛАС — коренът, не отделният елемент
    var по_клас = {};
    р.паднали.forEach(function (п) {
      var к = п.клас.split(' ')[0] || п.таг;
      if (!по_клас[к]) по_клас[к] = { брой: 0, най_лош: 9, пример: '', цвят: п.цвят, фон: п.фон, непроз: п.непрозрачност };
      по_клас[к].брой++;
      if (п.контраст < по_клас[к].най_лош) { по_клас[к].най_лош = п.контраст; по_клас[к].пример = п.текст; }
    });
    var корени = Object.keys(по_клас).map(function (к) {
      return { клас: к, брой: по_клас[к].брой, най_лош: по_клас[к].най_лош,
               непрозрачност: по_клас[к].непроз, цвят: по_клас[к].цвят, фон: по_клас[к].фон,
               пример: по_клас[к].пример };
    }).sort(function (a, b) { return b.брой - a.брой || a.най_лош - b.най_лош; });

    return {
      екран: р.екран,
      тема: document.documentElement.getAttribute('data-theme') || 'light',
      ПРЕГЛЕДАНИ: р.прегледани,
      съдени: р.съдени,
      не_мога_да_отсъдя: р.неотсъдени + ' (градиент или полупрозрачен фон — НЕ са дефекти)',
      ПАДНАЛИ: р.паднали.length,
      корени: корени.slice(0, 18),
      най_тежките: р.паднали.sort(function (a, b) { return a.контраст - b.контраст; }).slice(0, 10)
    };
  };
})();
