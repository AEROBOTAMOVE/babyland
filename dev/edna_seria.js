// ═══════════════════════════════════════════════════════════
// 🔥 ЕДНА СЕРИЯ — пазач срещу разминаване
//
// КАКВО: сравнява блока [БЛОК-СЕРИЯ-НАЧАЛО…КРАЙ] в js/daily.js и
//        js/profile.js дума по дума и проверява, че никой от двата файла
//        не смята серия сам за себе си.
// ЗАЩО:  до 19.08 всеки от двата екрана броеше поотделно. За една и съща
//        майка „Днес“ казваше 0, а „Профил“ — 30. Блокът е нарочно
//        дублиран (двата файла се зареждат в различен ред и всеки трябва
//        да може да работи сам); дублиран текст се разминава мълчаливо —
//        затова този пазач.
// ПУСКАНЕ: node dev/edna_seria.js       (изход 0 = чисто, 1 = разминаване)
// ПЪТ НАЗАД: изтрий файла — нищо не зависи от него.
// ═══════════════════════════════════════════════════════════
'use strict';
const fs = require('fs'), path = require('path');
const КОРЕН = path.join(__dirname, '..');
const ФАЙЛОВЕ = ['js/daily.js', 'js/profile.js'];
const НАЧАЛО = '[БЛОК-СЕРИЯ-НАЧАЛО]', КРАЙ = '[БЛОК-СЕРИЯ-КРАЙ]';

let провала = 0, прегледани = 0;
const блокове = {};

for (const f of ФАЙЛОВЕ) {
  let src;
  try { src = fs.readFileSync(path.join(КОРЕН, f), 'utf8'); }
  catch (e) { console.log('✗ ' + f + ': не се чете — ' + e.message); провала++; continue; }
  прегледани++;
  const a = src.indexOf(НАЧАЛО), b = src.indexOf(КРАЙ);
  if (a < 0 || b < 0) { console.log('✗ ' + f + ': няма [БЛОК-СЕРИЯ]'); провала++; continue; }
  if (b < a) { console.log('✗ ' + f + ': КРАЙ стои преди НАЧАЛО'); провала++; continue; }
  // нормализираме САМО края на реда — CRLF срещу LF не е разминаване по смисъл
  блокове[f] = src.slice(a, b).split('\r\n').join('\n');
}

const имена = Object.keys(блокове);
if (имена.length === ФАЙЛОВЕ.length) {
  const п = имена[0], в = имена[1];
  if (блокове[п] === блокове[в]) {
    console.log('✓ блокът е ДУМА ПО ДУМА еднакъв в ' + п + ' и ' + в +
                ' (' + блокове[п].split('\n').length + ' реда)');
  } else {
    провала++;
    console.log('✗ БЛОКОВЕТЕ СЕ РАЗМИНАВАТ — двата екрана пак може да дадат различни числа:');
    const A = блокове[п].split('\n'), Б = блокове[в].split('\n');
    for (let i = 0; i < Math.max(A.length, Б.length); i++) {
      if (A[i] !== Б[i]) {
        console.log('   ред ' + (i + 1) + ':');
        console.log('     ' + п + ': ' + JSON.stringify(A[i]));
        console.log('     ' + в + ': ' + JSON.stringify(Б[i]));
      }
    }
  }
} else if (прегледани === ФАЙЛОВЕ.length) {
  console.log('✗ не можах да сравня — липсва блок в поне един файл');
}

// никой да не си смята серия отделно
const ЗАБРАНЕНИ = [
  [/while\s*\(\s*days\s*\[/, 'собствен обход по bl_walk_days вместо BL_SERIA'],
  [/while\s*\(\s*активенДен\s*\(/, 'собствен обход в profile.js вместо BL_SERIA']
];
for (const f of ФАЙЛОВЕ) {
  let src;
  try { src = fs.readFileSync(path.join(КОРЕН, f), 'utf8'); } catch (e) { continue; }
  // махаме редовите коментари, за да не гърми пазачът от собствените си обяснения
  const тяло = src.split('\n').map(r => {
    const i = r.indexOf('//');
    return i < 0 ? r : r.slice(0, i);
  }).join('\n');
  for (const двойка of ЗАБРАНЕНИ) {
    if (двойка[0].test(тяло)) { console.log('✗ ' + f + ': ' + двойка[1]); провала++; }
  }
}

console.log('прегледани файла: ' + прегледани + ' · находки: ' + провала);
process.exit(провала ? 1 : 0);
