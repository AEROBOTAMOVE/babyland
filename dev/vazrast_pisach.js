// ═══════════════════════════════════════════════════════════
// ✍️ ПИСАЧ НА ВЪЗРАСТ — слага `от`/`до` по id, с котва и брояч
//
// ЗАЩО СВОЙ ИНСТРУМЕНТ: dev/klyuch_hirurg.js е за КЛЮЧОВЕ. Възрастта е
//   друго поле и се пише на друго място — веднага след `id: "X",`.
//
// 🪤 ЕДИНСТВЕНАТА ОПАСНОСТ Е ДВОЙНА КОТВА: ако `id: "X",` се среща два
//   пъти, вмъкването пише на грешно място. Затова котвата се БРОИ и при
//   брой различен от 1 картата се ПРОПУСКА, а не се познава.
//
// 🪤 ВТОРАТА ОПАСНОСТ Е ЧУЖД ЗАПИС: главната сесия и други агенти пишат в
//   същия файл. Затова файлът се чете НЕПОСРЕДСТВЕНО преди писането, а
//   карта, която ВЕЧЕ има възраст, не се пипа.
//
// ПУСКАНЕ: node dev/vazrast_pisach.js <партида.json>
//   партидата е масив от {"id":"...", "от":N|null, "до":N|null}
//
// ПЪТ НАЗАД: cp js/kb.js.PREDI_VAZRAST js/kb.js
//   (плюс: всяко пускане прави js/kb.js.PISACH_BAK преди да пипне)
// ═══════════════════════════════════════════════════════════
const fs = require('fs');
const path = require('path');
const ROOT = path.resolve(__dirname, '..');
const KB = path.join(ROOT, 'js/kb.js');

const партида = JSON.parse(fs.readFileSync(process.argv[2], 'utf8'));
let текст = fs.readFileSync(KB, 'utf8');
fs.writeFileSync(KB + '.PISACH_BAK', текст);

const екр = s => s.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
let писани = 0, пропуснати = 0;
const бележки = [];

for (const з of партида) {
  if (з.от == null && з.до == null) { бележки.push('⚪ ' + з.id + ' — няма какво да се пише'); пропуснати++; continue; }
  // котвата: `id: "X",` или `id: 'X',`
  const Р = new RegExp('(\\bid:\\s*["\']' + екр(з.id) + '["\']\\s*,)', 'g');
  const бр = (текст.match(Р) || []).length;
  if (бр !== 1) { бележки.push('🔴 ' + з.id + ' — котвата е ' + бр + ' пъти, ПРОПУСКАМ'); пропуснати++; continue; }
  // вече ли има възраст? гледаме реда на котвата и следващия
  const и = текст.search(Р);
  const прозорец = текст.slice(и, и + 400);
  if (/\bот:\s*-?\d/.test(прозорец) || /\bдо:\s*-?\d/.test(прозорец)) {
    бележки.push('⚠️ ' + з.id + ' — ВЕЧЕ има възраст (чужд запис?), ПРОПУСКАМ'); пропуснати++; continue;
  }
  const части = [];
  if (з.от != null) части.push('от: ' + з.от);
  if (з.до != null) части.push('до: ' + з.до);
  текст = текст.replace(Р, '$1 ' + части.join(', ') + ',');
  писани++;
}

fs.writeFileSync(KB, текст);
for (const б of бележки) console.log('   ' + б);
console.log('   ✍️ записани: ' + писани + ' · пропуснати: ' + пропуснати);

// ── веднага проверяваме, че файлът още се парсва ──
try {
  new (require('vm').Script)(fs.readFileSync(KB, 'utf8'));
  console.log('   ✅ js/kb.js се парсва');
} catch (e) {
  console.log('   🔴 js/kb.js НЕ СЕ ПАРСВА: ' + e.message);
  fs.copyFileSync(KB + '.PISACH_BAK', KB);
  console.log('   ↩️ върнато от js/kb.js.PISACH_BAK');
  process.exit(1);
}
