// 🍯 ИЗПИТ НА ПРАВИЛО А2 (медът и границата 1 година) В ДВЕТЕ ПОСОКИ
//
// ЗАЩО (26.08.2026): dev/standarti.js пази замразените стандарти, но кой
// пази ПАЗАЧА? Правило А2 три пъти днес викна срещу ВЕРЕН текст, защото
// речникът му не познаваше как е написана границата:
//     „мед НЕ СЕ ДАВА преди 1 година"  ·  „не преди НАВЪРШЕНА 1 година"
// Отрядът, който писа статиите, преформулира собствения си верен текст три
// пъти, за да го накара да млъкне. Това е най-тихата цена на лъжливата
// тревога: не грешен текст, а ХОРА, които заобикалят пазача.
//
// 🪤 И ОБРАТНОТО Е ОПАСНО: речник, разширен, докато спре да вика, спира да
//    вика И срещу истинския риск. Затова тук се пита ЕДНОВРЕМЕННО:
//      · верният текст минава ли безшумно
//      · опасният текст („сложи мед в кашата") още ли гърми
//    Падне ли ЕДНА от двете посоки, числото на пазача не важи.
//
// Изразът се сглобява от САМИЯ dev/standarti.js — не е преписан тук. Ако
// някой промени речника, този изпит го изпитва веднага, без да се пипа.
//
// ПУСКАНЕ: node dev/test_med_granica.js
// ПЪТ НАЗАД: файлът само ЧЕТЕ.
// ═══════════════════════════════════════════════════════════
const fs = require('fs');
// пътят се смята спрямо самия файл, не спрямо откъде е пуснат
const path = require('path');
const П = path.resolve(__dirname, 'standarti.js');
const src = fs.readFileSync(П, 'utf8');

// изваждаме самия речник от файла, без да пускаме целия пазач
const н = src.indexOf('const А2_ГРАНИЦА = рег(');
const к = src.indexOf(');', н);
let тяло = src.slice(src.indexOf('(', н) + 1, к);
// махаме коментарите и събираме низовете
const части = [];
tomber();
function tomber() {
  const re = /'([^']*)'/g;
  let m;
  for (const ред of тяло.split(/\r?\n/)) {
    if (ред.trim().indexOf('//') === 0) continue;
    re.lastIndex = 0;
    while ((m = re.exec(ред))) части.push(m[1]);
  }
}
const израз = new RegExp(части.join(''), 'i');

const ТРЯБВА_ДА_МИНАВА = [   // верен текст → пазачът НЕ бива да вика
  'мед не се дава преди 1 година',
  'мед не преди навършена 1 година',
  'мед само след едната година',
  'медът до годинката е забранен',
  'мед в кашата - никога преди навършена година',
  'мед под 1 година носи риск от ботулизъм',
  'мед може от 1 година нататък'
];
const ТРЯБВА_ДА_ГЪРМИ = [    // опасен текст → пазачът ТРЯБВА да вика
  'сложи малко мед в кашата за вкус',
  'мед в чая помага на бебето при кашлица',
  'намажи биберона с мед',
  'мед от 6 месеца е чудесен подсладител'
];

let паднали = 0;
console.log('');
console.log('  ── ВЕРЕН ТЕКСТ: пазачът трябва да МЪЛЧИ ──');
for (const т of ТРЯБВА_ДА_МИНАВА) {
  const ок = израз.test(т);
  if (!ок) паднали++;
  console.log('    ' + (ок ? '✅ мълчи ' : '🔴 ВИКА  ') + '„' + т + '"');
}
console.log('');
console.log('  ── ОПАСЕН ТЕКСТ: пазачът трябва да ВИКА ──');
for (const т of ТРЯБВА_ДА_ГЪРМИ) {
  const ок = !израз.test(т);
  if (!ок) паднали++;
  console.log('    ' + (ок ? '✅ вика  ' : '🔴 МЪЛЧИ ') + '„' + т + '"');
}
console.log('');
console.log(паднали ? '  🔴 ПАДНАЛИ: ' + паднали : '  ✅ и двете посоки държат');
console.log('  (речникът е сглобен от ' + части.length + ' парчета в самия файл)');

process.exit(паднали ? 1 : 0);
