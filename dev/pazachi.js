// ═══════════════════════════════════════════════════════════
// 🛡️ ВСИЧКИТЕ ПАЗАЧИ — една команда, една таблица, едно число
//
// ЗАЩО (26.08.2026): в dev/ има 99 уреда, от които 61 излизат с код при
// находка. За да знаеш здраво ли е приложението, трябва да помниш 61
// команди. Уред, който е неудобен за пускане, не се пуска. Непускан пазач е
// нула — и точно това вече се е случвало тук: `dev/standarti.py` е на Python,
// а Python на тази машина е СЧУПЕН, значи медицинските стандарти се пазеха
// от нищо, без никой да забележи.
//
// dev/vsichko.js прави подобно, но за ШЕСТ БРАУЗЪРНИ теста. Този е за
// пазачите, които вървят в Node — тоест за всичко, което може да се пусне
// без да се отваря приложението.
//
// КАКВО ПРАВИ:
//   Пуска всеки пазач в отделен процес, чете КОДА НА ИЗХОДА и подрежда:
//     0  → ✅ чисто
//     1  → 🔴 НАХОДКА
//     2  → 🟠 самопроверката на пазача е паднала (числото му не важи)
//     друг → 🔴 гръмнал
//   Пазач, който иска браузър, се разпознава по грешката и се брои отделно —
//   не като провал, а като „не е за тук".
//
// 🪤 КАПАНИТЕ:
//   · БАВНИТЕ. Някои пазачи вървят по минута и половина (корпусът от 350,
//     пълната памет). Тук има срок; надхвърли ли го, това се ЗАПИСВА като
//     ⏱, а не се премълчава. „Не се дочака" не е „чисто".
//   · Пазач без изходен код НЕ СЕ БРОИ за зелен — той просто печата. Такива
//     се изброяват отделно, за да не изглежда покритието по-голямо.
//   · Кирилица в изхода на дъщерния процес: чете се като utf8 изрично,
//     иначе на Windows излиза каша.
//
// ПУСКАНЕ:
//   node dev/pazachi.js            — бързите (срок 30 сек всеки)
//   node dev/pazachi.js --vsichko  — и бавните (срок 5 минути)
//   node dev/pazachi.js --spisak   — показва и уредите без изходен код
// ПЪТ НАЗАД: файлът само ЧЕТЕ и вика другите. Изтриването му не чупи нищо.
// ═══════════════════════════════════════════════════════════
const fs = require('fs');
const path = require('path');
const { spawnSync } = require('child_process');
process.chdir(path.resolve(__dirname, '..'));

const ВСИЧКО = process.argv.includes('--vsichko');
const СПИСЪК = process.argv.includes('--spisak');
const СРОК = ВСИЧКО ? 300000 : 12000;   // 12 сек стигат за статичните; бавните са в БАВНИ

// Пазачи, които ЗНАЯ че са бавни. Пускат се само с --vsichko, за да може
// бързият пробег да се вика след всяка промяна, без да чакаш.
const БАВНИ = new Set(['dati.js', 'dupka.js', 'glasat.js', 'metachka.js', 'naslednici.js',
                       'sliv_banya.js', 'tarsachkata.js', 'metachka2.js',
                       'test_no_i_posle.js', 'test_slabo.js', 'parvata_minuta.js', 'parvata_vrata.js',
                       'interaktivno_stai.js', 'interaktivno_stai2.js', 'interaktivno_jenata.js',
                       'interaktivno_igri.js', 'broyachi_dnevnik.js', 'broyachi.js', 'chuzhda_staya.js',
                       'proveri_naliv.js', 'dubli_lib.js', 'kriv_zapis.js', 'standarti.js',
                       'korpus350.js', 'pylna_pamet.js', 'mrytvi.js', 'klyuch_doma.js',
                       'zastoyali.js', 'prepokrivane.js', 'audit_bot.js']);
// Не са пазачи: пускачи, хирурзи, прилагачи — те ПРОМЕНЯТ или само печатат.
// 🪤 Някои уреди искат АРГУМЕНТ и без него гърмят (metachka2) — те не са
//    пазачи, а инструменти. Стоят в БАВНИ, за да не вдигат фалшива тревога.
const НЕ_СА_ПАЗАЧИ = /^(pazachi|vsichko|dvigatel|klyuch_hirurg|prilozhi_|popravi_|slej_|kavichki_bg|versii_po_sadarjanie|statichttp|raf_podporka|redni_popravka)/;

const файлове = fs.readdirSync('dev')
  .filter(f => f.endsWith('.js') && !НЕ_СА_ПАЗАЧИ.test(f))
  .sort();

const NODE = process.execPath;
const редове = [];
let зелени = 0, находки = 0, самопроверки = 0, гръмнали = 0, срокове = 0, браузърни = 0, безКод = 0;

for (const f of файлове) {
  const съдържание = fs.readFileSync('dev/' + f, 'utf8');
  const имаКод = /process\.exit\s*\(/.test(съдържание);
  if (!имаКод) { безКод++; if (СПИСЪК) редове.push(['⚪', f, 'само печата — няма изходен код']); continue; }
  if (БАВНИ.has(f) && !ВСИЧКО) { редове.push(['⏭', f, 'бавен — с --vsichko']); continue; }

  const р = spawnSync(NODE, ['dev/' + f], { timeout: СРОК, encoding: 'utf8', maxBuffer: 64 * 1024 * 1024 });
  const изход = (р.stdout || '') + (р.stderr || '');

  if (р.error && р.error.code === 'ETIMEDOUT') { срокове++; редове.push(['⏱', f, 'не се дочака за ' + (СРОК / 1000) + ' сек']); continue; }
  if (/window is not defined|document is not defined|navigator is not defined/.test(изход)) {
    браузърни++; редове.push(['🌐', f, 'иска браузър — не е за тук']); continue;
  }
  // едно число от изхода, за да не е само цвят
  const бележка = (изход.split(/\r?\n/).find(l => /ПРЕГЛЕДАН|ПРОВЕРКИ|НАХОДКИ|прегледани/.test(l)) || '').trim().slice(0, 62);

  // 🪤 NODE ИЗЛИЗА С 1 И ПРИ ГРЪМНАЛА ПРОГРАМА, не само при находка.
  //   Първият пробег обяви `metachka2` за „находка" — а той просто иска
  //   аргумент и гърми с ERR_INVALID_ARG_TYPE. Пускач, който брои гърмежите
  //   за находки, вдига фалшива тревога; пускач, който ги брои за зелени,
  //   е още по-лош. Разпознаваме ги по следата от изключение.
  const гръмнало = /^\s+at .+\n/m.test(изход) && /Error|Exception|throw/.test(изход);
  if (гръмнало) {
    гръмнали++;
    const първа = (изход.split(/\r?\n/).find(l => /Error|Exception/.test(l)) || '').trim().slice(0, 58);
    редове.push(['🔴', f, 'ГРЪМНА: ' + първа]);
    continue;
  }
  if (р.status === 0) { зелени++; редове.push(['✅', f, бележка]); }
  else if (р.status === 1) { находки++; редове.push(['🔴', f, бележка || 'находка']); }
  else if (р.status === 2) { самопроверки++; редове.push(['🟠', f, 'САМОПРОВЕРКАТА ПАДНА — числото му не важи']); }
  else { гръмнали++; редове.push(['🔴', f, 'гръмна (код ' + р.status + '): ' + (изход.split(/\r?\n/).find(l => /Error/.test(l)) || '').slice(0, 50)]); }
}

console.log('🛡️ ВСИЧКИТЕ ПАЗАЧИ' + (ВСИЧКО ? '  (и бавните)' : '  (бързите; --vsichko за всички)') + '\n');
for (const [з, име, бел] of редове) console.log('  ' + з + ' ' + име.replace(/\.js$/, '').padEnd(26) + ' ' + бел);

const пуснати = зелени + находки + самопроверки + гръмнали;
console.log('\n  ПУСНАТИ ПАЗАЧИ : ' + пуснати + ' от ' + файлове.length + ' файла в dev/');
console.log('  ✅ чисти               : ' + зелени);
console.log('  ' + (находки ? '🔴' : '✅') + ' с НАХОДКА           : ' + находки);
console.log('  ' + (самопроверки ? '🟠' : '✅') + ' с паднала самопроверка: ' + самопроверки);
console.log('  ' + (гръмнали ? '🔴' : '✅') + ' гръмнали             : ' + гръмнали);
if (срокове) console.log('  ⏱ не се дочакаха      : ' + срокове + '   ← това НЕ е „чисто"');
console.log('  🌐 браузърни (пропуснати): ' + браузърни);
console.log('  ⚪ без изходен код       : ' + безКод + (СПИСЪК ? '' : '   (--spisak ги показва)'));

// ── САМОПРОВЕРКА: може ли този пускач изобщо да види червено ──
// Пускач, който брои само зелени, е по-опасен от липсващ: дава спокойствие.
const пробаПът = 'dev/__proba_pazach__.js';
fs.writeFileSync(пробаПът, 'console.log("ПРЕГЛЕДАНИ: 1");\nprocess.exit(1);\n');
const пр = spawnSync(NODE, [пробаПът], { timeout: 10000, encoding: 'utf8' });
fs.unlinkSync(пробаПът);
const видяЧервено = пр.status === 1;
console.log('\n  САМОПРОВЕРКА: ' + (видяЧервено ? '✅' : '🔴') +
            ' пускачът вижда изход 1 като находка' + (видяЧервено ? '' : ' — ЧИСЛАТА ГОРЕ НЕ ВАЖАТ'));
if (!видяЧервено) process.exit(2);

if (срокове) console.log('\n  ⚠️ „Не се дочака" НЕ значи „чисто". Пусни ги поотделно или с --vsichko.');
process.exit((находки + самопроверки + гръмнали) ? 1 : 0);
