const КИР = 'а-яА-ЯёЁ';
const КИР_ПРЕДИ = `(?<![${КИР}])`;   // Node ≥ 8.3 поддържа lookbehind — проверено на v24
const КИР_СЛЕД  = `(?![${КИР}])`;
const БУКВА_ИЛИ_ЦИФРА_СЛЕД = `(?![${КИР}a-zA-Z0-9])`;

function рег(изр, флагове) { return new RegExp(изр, флагове === undefined ? 'i' : флагове); }

