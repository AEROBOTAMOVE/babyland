function самопроверка() {
  console.log('═'.repeat(74));
  console.log('🧪 САМОПРОВЕРКА В ДВЕТЕ ПОСОКИ — ' + ИЗПИТИ.length + ' правила × 2 посоки');
  console.log('═'.repeat(74));
  let паднали = 0, минали = 0;
  const покрити = new Set();
  for (const [код, лош, добър, стая] of ИЗПИТИ) {
    покрити.add(код);
    const пр = ПРАВИЛА.find(p => p.код === код);
    if (!пр) { console.log('   ✘ ' + код + ' — няма такова правило'); паднали++; continue; }
    // Стаята има значение: правилата за детския триаж НАРОЧНО мълчат в
    // майчините стаи. Изпитът трябва да подава стаята, в която правилото живее.
    const мери = (текст) => {
      находки.length = 0;
      пр.fn({ вид: 'изпит', източник: 'изпит', ид: код, заглавие: 'изпит',
              стая: стая || 'Здраве и SOS', текст: норм(текст) });
      return находки.length;
    };
    const гърми = мери(лош);
    const мълчи = мери(добър);
    const ок1 = гърми > 0, ок2 = мълчи === 0;
    if (ок1 && ок2) { минали++; console.log('   ✔ ' + код.padEnd(4) + ' гърми на нарушение (' + гърми + '), мълчи на верен текст'); }
    else {
      паднали++;
      console.log('   ✘ ' + код.padEnd(4) + (ок1 ? '' : ' НЕ ГЪРМИ на известно нарушение') + (ок2 ? '' : ' ФАЛШИВА ТРЕВОГА на верен текст (' + мълчи + ')'));
      if (!ок1) console.log('        нарушение: ' + лош);
      if (!ок2) console.log('        верен:     ' + добър);
    }
  }
  находки.length = 0;
  // 🪤 „тест, който се самоизключва": сравняваме ИМЕНАТА, не броя.
  const непокрити = ПРАВИЛА.filter(p => !покрити.has(p.код)).map(p => p.код);
  console.log('\n   правила: ' + ПРАВИЛА.length + ' · с изпит: ' + покрити.size +
              ' · без изпит: ' + (непокрити.length ? непокрити.join(', ') : 'няма'));
  if (непокрити.length) паднали += непокрити.length;
  console.log('\n   МИНАЛИ: ' + минали + '   ПАДНАЛИ: ' + паднали);
  return паднали === 0;
}

