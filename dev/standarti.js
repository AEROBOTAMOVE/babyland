// ЗАРЕЖДАНЕ НА КОРПУСА
// ═══════════════════════════════════════════════════════════════════════════
// 🔧 ПОПРАВЕН ДЕФЕКТ спрямо python-версията:
//    python прави glob('lib/*.json') и пропуска само 'index.json'. Значи
//    ЗАСМУКВА и lib/index.ARCHIVE.json — а там стойността на ключа "built"
//    е низ, тоест в тела{} влиза фалшива „статия" с id „built" и текст
//    „2026-07-14". Броят статии в заглавието на доклада ставаше с 1 по-голям
//    от истината. Тук index* и *.ARCHIVE* се изключват изрично.
function зареди() {
  const единици = [];
  // 🪤 ПЛАТЕН КАПАН (26.08, в тази сесия): първо написах JSON.parse(норм(файл)).
  //    норм() сменя „ " с права кавичка — а права кавичка ВЪТРЕ в JSON низ
  //    чупи файла. Резултат: SyntaxError на lib/preg-1.json, ред 57, и уредът
  //    не тръгваше изобщо. норм() важи за ТЕКСТА НА СТАТИЯТА, не за носача.
  const idx = JSON.parse(fs.readFileSync('lib/index.json', 'utf8'));
  const мета = {};
  for (const it of idx.items) мета[it.id] = it;

  const дублирани = [];
  const видяни = {};
  let файлове = 0;
  for (const f of fs.readdirSync('lib').sort()) {
    if (!/\.json$/.test(f)) continue;
    if (/^index/i.test(f) || /ARCHIVE/i.test(f)) continue;
    файлове++;
    const d = JSON.parse(fs.readFileSync(path.join('lib', f), 'utf8'));
    for (const k of Object.keys(d)) {
      if (typeof d[k] !== 'string') continue;
      // 🔧 python държи тела{} като речник по id → статия от втори файл със
      //    същото id ТИХО изяжда първата и не се проверява никога. Тук всяка
      //    статия е отделна единица и дублажът се ДОКЛАДВА.
      if (видяни[k]) дублирани.push([k, видяни[k], f]);
      видяни[k] = f;
      const м = мета[k] || {};
      единици.push({
        вид: 'статия', източник: 'lib/' + f, ид: k,
        заглавие: м.t || '?', стая: м.r || '?',
        текст: норм(d[k]),
      });
    }
  }

  // ── картите на помощничките ──
  // 🔧 python чете js/kb.js като ЕДИН низ и пуска само дозовото правило върху
  //    него. Значи 531-те карти не минават през нито едно от другите девет
  //    правила, а находката няма име на карта („-"). Тук kb.js се ИЗПЪЛНЯВА в
  //    пясъчник и всяка карта е отделна единица с id и заглавие.
  const ктх = { window: {}, console: { log() {}, warn() {}, error() {} } };
  ктх.self = ктх.window; ктх.globalThis = ктх;
  vm.createContext(ктх);
  vm.runInContext(fs.readFileSync('js/kb.js', 'utf8'), ктх, { filename: 'js/kb.js' });
  const KB = ктх.window.KB;
  if (!KB || !Array.isArray(KB.entries)) throw new Error('js/kb.js не даде window.KB.entries');

  for (const e of KB.entries) {
    единици.push({
      вид: 'карта', източник: 'js/kb.js', ид: e.id,
      заглавие: e.title || '?', стая: e.room || '?',
      текст: норм([e.title, e.core, e.tip, e.follow].filter(x => typeof x === 'string').join('\n')),
    });
  }
  // флаговите списъци и готовите отговори — там също не бива да има доза
  let флагКлючове = 0;
  for (const k of Object.keys(KB)) {
    if (k === 'entries') continue;
    флагКлючове++;
    const v = KB[k];
    const текст = Array.isArray(v) ? v.join('\n')
      : (v && typeof v === 'object') ? Object.values(v).map(x => Array.isArray(x) ? x.join('\n') : String(x)).join('\n')
      : String(v);
    единици.push({ вид: 'флагове', източник: 'js/kb.js', ид: 'KB.' + k, заглавие: 'KB.' + k, стая: '-', текст: норм(текст) });
  }

  return { единици, дублирани, файлове, флагКлючове, индекс: idx };
}

