// ── Б2. ВИСОКА ТЕМПЕРАТУРА НА ВСЯКА ВЪЗРАСТ ↔ 40° ─────────────────────────
// ОТКЪДЕ: kb.js го казва „над 40°" на 5 места (zd-temp-tri-dni, zd-temp2 ×2,
// zd-temperatura, zd-nastinka ×2). Всяко друго число в същата конструкция
// („над 39°C" без възрастова уговорка) е второ правило за същото нещо.
// 🔧 НАРОЧНО СТЕСНЕНО (26.08, след първото пускане): първата версия гърмеше
//    33 пъти, от които 31 бяха ВЕРНИ текстове — „температура над 38°C" при
//    майката (цистит, шевове, замряла, сауна) и при новороденото, където 38 Е
//    правилният праг. Пазач с 94% фалшива тревога учи да го изключат.
//    Затова тук се мери САМО стойността 39: 38 е законният праг за под 3
//    месеца, 40 е замразеният праг за всяка възраст, а 39 е единственото
//    число, което казва СЪЩОТО правило с ДРУГА цифра.
const Б2_НАД = рег('(над|повече от|мине)\\s*(39)(?:[.,]\\d)?\\s*(?:°|градус)', 'gi');
function Б2(ед) {
  броякНа('Б2');
  if (МАЙЧИНИ_СТАИ.has(ед.стая)) return;
  for (const сурово of изречения(ед.текст)) {
    const изр = сцифри(сурово);
    if (МАЙЧИНИ_ДУМИ.test(изр)) continue;
    всички(Б2_НАД, изр, m => {
      // ако изречението огражда конкретна възраст, не е „на всяка възраст"
      if (рег('\\d\\s*-\\s*\\d\\s*месец|под \\d+ месец|до \\d+ месец').test(изр)) return;
      сигнал('Б2 „на всяка възраст" прагът не е 40°', ед, сурово, 'намерено над 39°');
    });
  }
}

// ── Б3. КОЛКО ДНИ ТЕМПЕРАТУРА ↔ ТРЕТИ ДЕН ─────────────────────────────────
// ОТКЪДЕ: „трети ден с температура" е формулировката в kb.js (4 места).
// Едно и също правило, казано като „48 часа", звучи като друго правило.
const Б3_ЧАСОВЕ = рег('(\\d+)\\s*час(а|ове)?' + КИР_СЛЕД, 'gi');
function Б3(ед) {
  броякНа('Б3');
  for (const сурово of изречения(ед.текст)) {
    const изр = сцифри(сурово);
    if (!Б_ТЕМПЕРАТУРА.test(изр)) continue;
    if (!рег('не пуска|не спада|държи|продължава|върви|трае|остава').test(изр)) continue;
    всички(Б3_ЧАСОВЕ, изр, m => {
      const ч = +m[1];
      if (ч < 24) return;                       // „на всеки 4 часа" не е срок
      if (ч === 72) return;                     // 72 ч = трети ден, същото правило
      сигнал('Б3 срокът на температурата е казан в часове, различни от 72 (= трети ден)', ед, сурово, 'намерено ' + ч + ' часа');
    });
    const дни = числаОт(изр, рег('(\\d+)\\s*(ден|дена|дни)' + КИР_СЛЕД, 'gi')).map(m => +m[1]);
    for (const д of дни) {
      if (д === 3) continue;
      if (д > 3) continue;                      // „5 дни хрема" е друга тема
      сигнал('Б3 срокът на температурата не е 3 дни / трети ден', ед, сурово, 'намерено ' + д + ' дни');
    }
  }
}

// ── Б4. МЕД ↔ 12 МЕСЕЦА / 1 ГОДИНА ────────────────────────────────────────
// ОТКЪДЕ: 15 места в корпуса, всичките казват 12 месеца / 1 година / годинката.
// Общ вид: „N месеца" и „N години", но САМО ако числото е ДО моята котва.
const МЕСЕЦИ = рег('(\\d+)-?[а-я]{0,3}\\s*(?:месец|месеца|мес' + КИР_СЛЕД + ')', 'gi');
const ГОДИНИ = рег('(\\d+)-?[а-я]{0,3}\\s*годин', 'gi');
function граница(ед, сурово, тема, замрМесеци, име) {
  const изр = сцифри(сурово);
  if (МИТ.test(изр)) return;
  for (const м of числаНаТемата(изр, тема, МЕСЕЦИ, 1)) {
    if (м === замрМесеци) continue;
    сигнал(име + ': границата не е ' + замрМесеци + ' месеца', ед, сурово, 'намерено ' + м + ' месеца');
  }
  for (const г of числаНаТемата(изр, тема, ГОДИНИ, 1)) {
    if (г * 12 === замрМесеци) continue;
    сигнал(име + ': границата не е ' + (замрМесеци / 12) + ' година', ед, сурово, 'намерено ' + г + ' години');
  }
}

