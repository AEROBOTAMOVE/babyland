// 🧪 ГЪРМИ ЛИ НАИСТИНА — изпитание на js/pazach_karti.js
//
// Пазач, който не е бил изпитан със СЧУПЕНА карта, е само добро намерение.
// Тук веригата се строи точно както я строят 214-те места в проекта, в
// средата ѝ се слага брънка, която гърми, и се брои КОЛКО КАРТИ ОЦЕЛЯВАТ.
//
// В ДВЕТЕ ПОСОКИ, защото едната половина не доказва нищо:
//   БЕЗ пазача → трябва да оцелеят САМО картите ПРЕДИ счупената.
//                (ако тук излязат всички, значи опитът не възпроизвежда бъга)
//   С пазача   → трябва да оцелеят ВСИЧКИ ОСВЕН счупената.
//                (ако тук липсват повече, пазачът яде здрави карти)
//
// ПУСКАНЕ: node dev/test_pazach_karti.js
// ПЪТ НАЗАД: файлът само ЧЕТЕ проекта.
// ═══════════════════════════════════════════════════════════
const fs = require('fs');
const vm = require('vm');
const path = require('path');
process.chdir(path.resolve(__dirname, '..'));

// мъничък свят: колкото трябва, за да живее ROOM_FEATURES
function свят() {
  const ctx = {
    console: { warn() {}, log() {}, error() {} },
    JSON, Math, Date, RegExp, String, Number, Array, Object, Proxy, Error
  };
  ctx.window = ctx; ctx.globalThis = ctx; ctx.self = ctx;
  vm.createContext(ctx);
  return ctx;
}

// строи веригата: 5 карти, третата гърми
function опит(ctx, сПазач) {
  const сложени = [];
  ctx.ROOM_FEATURES = { 'Дневник на мама': root => { сложени.push('карта1'); } };

  if (сПазач) new vm.Script(fs.readFileSync('js/pazach_karti.js', 'utf8')).runInContext(ctx);

  const закачи = (номер, гърми) => {
    const база = ctx.ROOM_FEATURES['Дневник на мама'];
    ctx.ROOM_FEATURES['Дневник на мама'] = root => {
      база(root);
      if (гърми) throw new Error('крив запис bl_custom_lists = [null]');
      сложени.push('карта' + номер);
    };
  };
  закачи(2, false);
  закачи(3, true);      // ← счупената, точно по средата
  закачи(4, false);
  закачи(5, false);

  let гръмна = null;
  try { ctx.ROOM_FEATURES['Дневник на мама']({}); }
  catch (e) { гръмна = e.message; }
  return { сложени, гръмна, грешки: (ctx.BL_КАРТИ_ГРЕШКИ || []).length };
}

const без = опит(свят(), false);
const с = опит(свят(), true);

console.log('🧪 ЕДНА СЧУПЕНА КАРТА ОТНАСЯ ЛИ ОСТАНАЛИТЕ\n');
console.log('  веригата: 5 карти, ТРЕТАТА гърми (както при bl_custom_lists = [null])\n');
console.log('  БЕЗ пазача : оцеляват ' + без.сложени.length + ' — ' + (без.сложени.join(', ') || 'нито една'));
console.log('               гръмна навън: ' + (без.гръмна ? '🔴 ДА (' + без.гръмна.slice(0, 40) + '…)' : 'не'));
console.log('  С пазача   : оцеляват ' + с.сложени.length + ' — ' + (с.сложени.join(', ') || 'нито една'));
console.log('               гръмна навън: ' + (с.гръмна ? '🔴 ДА' : '✅ не') + ' · записани грешки: ' + с.грешки);

const проверки = [
  [без.сложени.length === 2, 'БЕЗ пазача се губят картите СЛЕД счупената (иначе опитът не възпроизвежда бъга)'],
  [!!без.гръмна, 'БЕЗ пазача грешката излиза навън и убива строенето на стаята'],
  [с.сложени.length === 4, 'С пазача оцеляват ВСИЧКИ ОСВЕН счупената (нито повече, нито по-малко)'],
  [!с.гръмна, 'С пазача нищо не излиза навън'],
  [с.грешки === 1, 'С пазача грешката е ЗАПИСАНА, не изядена мълчаливо'],
  [с.сложени.indexOf('карта4') >= 0 && с.сложени.indexOf('карта5') >= 0, 'картите СЛЕД счупената се строят'],
  [с.сложени.indexOf('карта3') < 0, 'счупената НЕ се брои за построена']
];

console.log('\n  ПРОВЕРКИ:');
let паднали = 0;
проверки.forEach(([д, т]) => { if (!д) паднали++; console.log('     ' + (д ? '✅' : '🔴') + ' ' + т); });

console.log('\n  ' + (паднали ? '🔴 ПАДНАЛИ: ' + паднали : '✅ ВСИЧКИ ' + проверки.length + ' МИНАХА'));
process.exit(паднали ? 1 : 0);
