// ⏱️ ИМА ЛИ ДВИГАТЕЛЯТ ПАМЕТ — заключен отговор: НЯМА
//
// ЗАЩО СЪЩЕСТВУВА (26.08.2026): отряд, който мереше 300 независими въпроса,
// докладва, че „шевовете ме болят като седна" дава КАРТА на чист двигател и
// ТИШИНА, ако преди него са минали други въпроси. Изводът му беше, че всяка
// сонда трябва да зарежда ЧИСТ двигател за всеки въпрос — което му струва
// 211 секунди вместо секунди.
//
// 🔴 ПРОВЕРИХ И ТВЪРДЕНИЕТО НЕ СЕ ПОТВЪРДИ. Двигателят е БЕЗ СЪСТОЯНИЕ:
//    · същият въпрос десет пъти подред → същият отговор
//    · след 60 чужди въпроса → същият отговор
//    · след 8 истински въпроса от други стаи → същият отговор
//    · и в двата реда на подреждане → същият отговор
//
// ИСТИНСКАТА ПРИЧИНА за разликата, която той е видял: js/kb.js СЕ Е МЕНЯЛ
// ПОД САМОТО ИЗМЕРВАНЕ. Точно в онези минути аз добавях ключове „шевове" към
// nia-shevove-dolu. Тоест двете му измервания са били върху ДВА РАЗЛИЧНИ ФАЙЛА.
//
// ПОУКАТА, която този файл пази: когато мярка се промени между два ръна,
// първото обяснение не е „системата има състояние", а „входът се е сменил".
// Дрейфът на файла изглежда точно като памет.
//
// И ако някой ден НАИСТИНА се въведе състояние в BL_MATCH (кеш, „скоро
// показано", лична история), този файл ще гръмне и ще го обяви на глас.
//
// ПУСКАНЕ: node dev/test_dvigatel_pamet.js     (изход 1 при провал)
// ПЪТ НАЗАД: файлът само ЧЕТЕ.
// ═══════════════════════════════════════════════════════════
const { zaredi } = require('./pyasachnik.js');

const W = zaredi(null);
const дай = (т, с) => {
  try {
    const р = W.BL_MATCH(т, с);
    const з = Array.isArray(р) ? р[0] : (р && (р.entry || р.item || р));
    return з ? з.id : 'нищо';
  } catch (e) { return 'грешка:' + e.message; }
};

// Въпросите са нарочно РАЗНОРОДНИ — ако някъде има кеш по стая или по тема,
// разнородността го изважда наяве.
const КОНТРОЛНИ = [
  ['бебето има температура', 'Здраве и SOS'],
  ['кога проговаря', 'Развитие и игри'],
  ['колко мляко трябва да яде', 'Захранване'],
  ['не мога да спя от тревога', 'Дневник на мама'],
  ['кога се връща цикълът', 'Жената в мен']
];
const ШУМ = [];
for (let i = 0; i < 60; i++) ШУМ.push(['съвсем друг въпрос номер ' + i, 'Моето бебе']);

let паднали = 0;
const провал = (какво) => { паднали++; console.log('    🔴 ' + какво); };

console.log('');
console.log('⏱️ ИМА ЛИ ДВИГАТЕЛЯТ ПАМЕТ');
console.log('');

// 1. повторение
console.log('  ── същият въпрос десет пъти ──');
for (const [т, с] of КОНТРОЛНИ) {
  const отг = [];
  for (let i = 0; i < 10; i++) отг.push(дай(т, с));
  const различни = new Set(отг);
  if (различни.size === 1) console.log('    ✅ „' + т.slice(0, 34) + '" → ' + отг[0]);
  else провал('„' + т + '" дава РАЗЛИЧНИ отговори: ' + [...различни].join(' / '));
}

// 2. шум между двете питания
console.log('');
console.log('  ── 60 чужди въпроса между двете питания ──');
for (const [т, с] of КОНТРОЛНИ) {
  const преди = дай(т, с);
  for (const [ш, шс] of ШУМ) дай(ш, шс);
  const след = дай(т, с);
  if (преди === след) console.log('    ✅ „' + т.slice(0, 34) + '" → ' + преди);
  else провал('„' + т + '" беше ' + преди + ', стана ' + след);
}

// 3. обратен ред
console.log('');
console.log('  ── обратният ред на задаване ──');
const W2 = zaredi(null);
const дай2 = (т, с) => {
  try {
    const р = W2.BL_MATCH(т, с);
    const з = Array.isArray(р) ? р[0] : (р && (р.entry || р.item || р));
    return з ? з.id : 'нищо';
  } catch (e) { return 'грешка'; }
};
const напред = КОНТРОЛНИ.map(([т, с]) => дай2(т, с));
const W3 = zaredi(null);
const дай3 = (т, с) => {
  try {
    const р = W3.BL_MATCH(т, с);
    const з = Array.isArray(р) ? р[0] : (р && (р.entry || р.item || р));
    return з ? з.id : 'нищо';
  } catch (e) { return 'грешка'; }
};
const назад = КОНТРОЛНИ.slice().reverse().map(([т, с]) => дай3(т, с)).reverse();
for (let i = 0; i < КОНТРОЛНИ.length; i++) {
  if (напред[i] === назад[i]) console.log('    ✅ „' + КОНТРОЛНИ[i][0].slice(0, 34) + '" → ' + напред[i]);
  else провал('„' + КОНТРОЛНИ[i][0] + '" напред ' + напред[i] + ', назад ' + назад[i]);
}

// ── САМОПРОВЕРКА: изпитът трябва да УМЕЕ да види разлика ──
// Ако мерките му са слепи, „стабилно" не значи нищо.
const а = дай('бебето има температура', 'Здраве и SOS');
const б = дай('кога проговаря', 'Развитие и игри');
const виждаРазлика = а !== б;
console.log('');
console.log('  самопроверка: изпитът различава два различни въпроса ' + (виждаРазлика ? '✅' : '🔴'));
if (!виждаРазлика) паднали++;

console.log('');
console.log('  ПРЕГЛЕДАНИ: ' + (КОНТРОЛНИ.length * 10 + КОНТРОЛНИ.length * 2 + КОНТРОЛНИ.length * 2) +
            ' питания  ·  ' + (паднали ? '🔴 ПАДНАЛИ: ' + паднали : '✅ двигателят е БЕЗ СЪСТОЯНИЕ'));
console.log('');
process.exit(паднали ? 1 : 0);
