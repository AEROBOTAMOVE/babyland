// ═══════════════════════════════════════════════════════════════════════════
// 🛡️ УСТОЙЧИВОСТ — справя ли се мозъкът с ВСЯКАКЪВ текст
// ═══════════════════════════════════════════════════════════════════════════
//
// ЗАЩО (05.09): майка пише с една ръка, в тъмното, на телефон. Пише с грешки,
// без препинателни знаци, с ГЛАВНИ БУКВИ, с двойни интервали, понякога на
// латиница. Ако картата се намира само при идеално изписване, тя не се намира.
//
// МЯРКАТА: взима се ПЪРВИЯТ ключ на всяка карта (тоест изречение, за което
// ЗНАЕМ верния отговор), развалят се по осем начина, и се брои колко от
// развалените форми още стигат до същата карта.
//
// Осемте развали, всяка от истински наблюдение:
//   1 ГЛАВНИ БУКВИ            2 без препинателни знаци
//   3 двойни интервали        4 разменени две съседни букви (типична печатна)
//   5 изпусната буква         6 удвоена буква
//   7 „и“ → „й“ (най-честата българска печатна грешка)
//   8 латиница (шльокавица)
//
// ⚠️ ТОЗИ ФАЙЛ САМО ЧЕТЕ.
// ПУСКАНЕ: node dev/ustoychivost.js [--vsichki]
// ═══════════════════════════════════════════════════════════════════════════
'use strict';
const fs = require('fs');
const path = require('path');
const КОРЕН = path.resolve(__dirname, '..');
process.chdir(КОРЕН);
const ВСИЧКИ = process.argv.includes('--vsichki');
const W = require(path.join(КОРЕН, 'dev/pyasachnik.js')).zaredi(null);

const питай = (т, с) => {
  try {
    const р = W.BL_MATCH(т, с);
    const з = Array.isArray(р) ? р[0] : (р && (р.entry || р.item || р));
    return з ? з.id : null;
  } catch (e) { return null; }
};

const КИР = 'абвгдежзийклмнопрстуфхцчшщъьюя';
const ЛАТ = { 'а':'a','б':'b','в':'v','г':'g','д':'d','е':'e','ж':'j','з':'z','и':'i',
  'й':'i','к':'k','л':'l','м':'m','н':'n','о':'o','п':'p','р':'r','с':'s','т':'t',
  'у':'u','ф':'f','х':'h','ц':'c','ч':'ch','ш':'sh','щ':'sht','ъ':'a','ь':'','ю':'yu','я':'ya' };

const развали = {
  'ГЛАВНИ': т => т.toUpperCase(),
  'без знаци': т => т.replace(/[.,?!;:]/g, ''),
  'двойни интервали': т => т.replace(/ /g, '  '),
  'разменени букви': т => {
    const д = т.split(' ');
    const i = д.findIndex(x => x.length > 4);
    if (i < 0) return т;
    const w = д[i]; const j = Math.floor(w.length / 2);
    д[i] = w.slice(0, j) + w[j + 1] + w[j] + w.slice(j + 2);
    return д.join(' ');
  },
  'изпусната буква': т => {
    const д = т.split(' ');
    const i = д.findIndex(x => x.length > 4);
    if (i < 0) return т;
    const w = д[i]; const j = Math.floor(w.length / 2);
    д[i] = w.slice(0, j) + w.slice(j + 1);
    return д.join(' ');
  },
  'удвоена буква': т => {
    const д = т.split(' ');
    const i = д.findIndex(x => x.length > 4);
    if (i < 0) return т;
    const w = д[i]; const j = Math.floor(w.length / 2);
    д[i] = w.slice(0, j) + w[j] + w.slice(j);
    return д.join(' ');
  },
  'и → й': т => т.replace(/и/g, 'й'),
  'латиница': т => т.split('').map(c => {
    const м = ЛАТ[c.toLowerCase()];
    return м === undefined ? c : м;
  }).join(''),
};

const имена = Object.keys(развали);
const резултат = new Map(имена.map(и => [и, { ок: 0, зле: 0, примери: [] }]));
let база = 0;
for (const e of W.KB.entries) {
  const ключ = (e.keys || []).find(k => String(k).split(/\s+/).length >= 2 && String(k).length > 9);
  if (!ключ) continue;
  // мери се САМО върху ключ, който в нормален вид намира СВОЯТА карта
  if (питай(String(ключ), e.room) !== e.id) continue;
  база++;
  for (const име of имена) {
    const развален = развали[име](String(ключ));
    const о = питай(развален, e.room);
    const r = резултат.get(име);
    if (о === e.id) r.ок++;
    else { r.зле++; if (r.примери.length < 4) r.примери.push('„' + развален.slice(0, 40) + '“ → ' + (о || 'ТИШИНА')); }
  }
}

console.log('');
console.log('  🛡️ УСТОЙЧИВОСТ НА МОЗЪКА · ' + база + ' изречения с известен верен отговор');
console.log('');
let най = 100;
for (const име of имена) {
  const r = резултат.get(име);
  const п = база ? (r.ок * 100 / база) : 0;
  // 🪤 „и“ → „й“ сменя ВСЯКО „и“ в изречението — тоест 3-4 грешки наведнъж.
  //    Никоя прошка за ЕДНА грешка не може да я покрие, и никоя майка не
  //    пише така. Оставя се ВИДИМА, но не влиза в прага — иначе прагът
  //    мери невъзможното и пазачът става вечно червен, тоест невидим.
  if (име !== 'и → й' && п < най) най = п;
  console.log('  ' + (п >= 90 ? '✅' : п >= 70 ? '🟠' : '🔴') + ' ' + име.padEnd(20) +
    String(r.ок).padStart(4) + '/' + база + '  (' + п.toFixed(1) + '%)');
  if (п < 90 || ВСИЧКИ) for (const x of r.примери) console.log('        ' + x);
}
console.log('');
console.log('  ── най-слабата развала: ' + най.toFixed(1) + '% ──');
console.log('');
// Прагът е записан, за да се вижда движението.
const ПРАГ = 70;
console.log('  ' + (най >= ПРАГ ? '✅ над прага (' + ПРАГ + '%)' : '🔴 под прага (' + ПРАГ + '%)'));
console.log('');
process.exit(най >= ПРАГ ? 0 : 1);
