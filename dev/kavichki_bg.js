// ═══════════════════════════════════════════════════════════
// „ БЪЛГАРСКИТЕ КАВИЧКИ — една книга, написана по два начина
//
// ИЗМЕРЕНО (dev/pravopis.js): в библиотеката стоят
//     2933 български „ …"     и     812 прави "
// Тоест едни и същи неща са цитирани по два различни начина в един и същи
// текст. Не е дребно: правият знак е машинописен, а не български, и се
// набива на око точно в изречение, което иска да звучи като написано от
// човек („болката не се "търпи"" срещу „болката не се „търпи"").
//
// ПРАВИЛОТО: първата от двойката става „ (U+201E, долу), втората — "
// (U+201C, горе). Точно както се пише на български.
//
// 🪤 ТРИТЕ ПАЗАЧА, без които това е опасна операция:
//   1. НЕЧЕТЕН БРОЙ кавички в текст = не мога да ги сдвоя, без да гадая.
//      Такъв текст СЕ ПРОПУСКА и се докладва поименно. Гадаенето би
//      обърнало посоката на всички следващи в текста.
//   2. Файлът се ЧЕТЕ като JSON, пипат се само СТОЙНОСТИТЕ, и се записва
//      пак през JSON.stringify. Така екранирането е работа на JSON-а, не
//      моя — а точно ръчното екраниране е чупило този проект.
//   3. След писането: файлът трябва пак да се парсва, броят на записите да
//      е СЪЩИЯТ, а дължината на всеки текст да е НЕПРОМЕНЕНА (двата знака
//      са по един символ). Разминаване = не пиша.
//
// ⛔ НЕ ПИПА js/kb.js: там низовете са в апострофи и правият знак вътре е
//    напълно законен за JavaScript. Ще се гледа отделно и внимателно.
//
// ПУСКАНЕ: node dev/kavichki_bg.js [--pisi]
// ПЪТ НАЗАД: .PREDI_KAVICHKI_BG копие на всеки пипнат файл.
// ═══════════════════════════════════════════════════════════
const fs = require('fs');
const path = require('path');
process.chdir(path.resolve(__dirname, '..'));

const ПИШИ = process.argv.includes('--pisi');
const ДОЛУ = '„';   // „
const ГОРЕ = '“';   // "

function сдвои(т) {
  const брой = (т.match(/"/g) || []).length;
  if (!брой) return { т, сменени: 0, нечетен: false };
  if (брой % 2) return { т, сменени: 0, нечетен: true };
  let отворена = false;
  const нов = т.replace(/"/g, () => { отворена = !отворена; return отворена ? ДОЛУ : ГОРЕ; });
  return { т: нов, сменени: брой, нечетен: false };
}

// ⛔ АРХИВИТЕ НЕ СЕ ПИПАТ. index.ARCHIVE.json носи 278 от намерените кавички,
//    но той е стар запис — смяната там е чиста загуба и мътни дифове.
// ⛔ И В index.json СЕ ПИПАТ САМО ВИДИМИТЕ ПОЛЕТА: `t` (заглавие) и `s`
//    (резюме). Полето `k` са ДУМИТЕ ЗА ТЪРСЕНЕ — смяна там мени какво намира
//    търсачката, а това не е правопис, а поведение.
const САМО_ВИДИМИ = { 'index.json': new Set(['t', 's']) };
const файлове = fs.readdirSync('lib')
  .filter(f => f.endsWith('.json') && f.indexOf('.ARCHIVE.') < 0 && f.indexOf('.BAK') < 0);
console.log('„ БЪЛГАРСКИТЕ КАВИЧКИ\n');

let прегледаниФ = 0, прегледаниТ = 0, сменени = 0, нечетни = 0, пипнати = 0;
const списъкНечетни = [];

for (const ф of файлове) {
  const път = 'lib/' + ф;
  let сурово;
  try { сурово = fs.readFileSync(път, 'utf8'); } catch (e) { continue; }
  let обект;
  try { обект = JSON.parse(сурово); } catch (e) { console.log('  ⚪ ' + ф + ' — не е валиден JSON, пропускам'); continue; }
  прегледаниФ++;

  let вФайла = 0;
  const дължиниПреди = {};

  function мини(o, път2) {
    if (typeof o === 'string') { прегледаниТ++; return o; }
    if (Array.isArray(o)) return o.map((x, i) => мини(x, път2 + '[' + i + ']'));
    if (o && typeof o === 'object') {
      const из = {};
      for (const k of Object.keys(o)) {
        const v = o[k];
        if (typeof v === 'string') {
          прегледаниТ++;
          // само видимите полета, ако файлът е в списъка (виж горе)
          const позволени = САМО_ВИДИМИ[ф];
          if (позволени && !позволени.has(k)) { из[k] = v; continue; }
          дължиниПреди[път2 + '/' + k] = v.length;
          const р = сдвои(v);
          if (р.нечетен) { нечетни++; списъкНечетни.push(ф + ' → ' + k + ' (' + (v.match(/"/g) || []).length + ' кавички)'); из[k] = v; continue; }
          вФайла += р.сменени; из[k] = р.т;
        } else из[k] = мини(v, път2 + '/' + k);
      }
      return из;
    }
    return o;
  }

  const нов = мини(обект, ф);
  if (!вФайла) continue;
  пипнати++; сменени += вФайла;
  console.log('  ✏️  ' + ф.padEnd(18) + ' ' + вФайла + ' кавички');

  if (ПИШИ) {
    // отстъпът да остане какъвто е бил (иначе дифът става целият файл)
    const отстъп = /^\{\n( +)"/.test(сурово) ? (сурово.match(/^\{\n( +)"/) || [])[1].length : 1;
    const текст = JSON.stringify(нов, null, отстъп);
    // 🪤 ПАЗАЧ 3: парсва ли се, същият ли е броят, същите ли са дължините
    let проба;
    try { проба = JSON.parse(текст); } catch (e) { console.log('  🔴 ' + ф + ' — след смяната не се парсва → НЕ ПИША'); continue; }
    if (Object.keys(проба).length !== Object.keys(обект).length) { console.log('  🔴 ' + ф + ' — броят записи се смени → НЕ ПИША'); continue; }
    let лошаДължина = 0;
    for (const k of Object.keys(проба)) {
      if (typeof проба[k] === 'string' && typeof обект[k] === 'string' && проба[k].length !== обект[k].length) лошаДължина++;
    }
    if (лошаДължина) { console.log('  🔴 ' + ф + ' — ' + лошаДължина + ' текста смениха ДЪЛЖИНАТА си → НЕ ПИША'); continue; }
    fs.copyFileSync(път, път + '.PREDI_KAVICHKI_BG');
    fs.writeFileSync(път, текст);
  }
}

console.log('\n  ПРЕГЛЕДАНИ: ' + прегледаниФ + ' файла · ' + прегледаниТ + ' текста');
console.log('  ✏️  ЗА СМЯНА  : ' + сменени + ' кавички в ' + пипнати + ' файла');
console.log('  ' + (нечетни ? '🔶' : '✅') + ' НЕЧЕТНИ (пропуснати, за ръка): ' + нечетни);
if (нечетни) списъкНечетни.slice(0, 15).forEach(x => console.log('       ' + x));

// ── самопроверка
const п1 = сдвои('той каза "нещо" и после "друго"');
const п2 = сдвои('един "нечетен знак');
const п3 = сдвои('чист български текст без кавички');
console.log('\n  САМОПРОВЕРКА:');
console.log('     ' + (п1.т === 'той каза ' + ДОЛУ + 'нещо' + ГОРЕ + ' и после ' + ДОЛУ + 'друго' + ГОРЕ ? '✅' : '🔴') + ' сдвоява две двойки правилно');
console.log('     ' + (п2.нечетен && п2.сменени === 0 ? '✅' : '🔴') + ' НЕ пипа текст с нечетен брой (обратната посока)');
console.log('     ' + (п3.сменени === 0 ? '✅' : '🔴') + ' НЕ пипа текст без кавички');
console.log('     ' + (п1.т.length === 'той каза "нещо" и после "друго"'.length ? '✅' : '🔴') + ' дължината не се мени');

if (!ПИШИ) console.log('\n  (пробен ход — пусни с --pisi, за да запише)');
else console.log('\n  💾 ЗАПИСАНО. ПЪТ НАЗАД: файловете с .PREDI_KAVICHKI_BG');
