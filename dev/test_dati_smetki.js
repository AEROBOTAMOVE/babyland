// ═══════════════════════════════════════════════════════════
// 📅 СМЕТКИТЕ С ДАТИ — ръчно пресметнати примери
//
// ЗАЩО: това е приложение за бременност и бебе. Тук сгрешена дата не е
// досадна, а опасна: ваксина на грешен ден, термин с две седмици разлика,
// „бебето е на 5 месеца" при 4. И най-лошото — сгрешената дата изглежда
// напълно правдоподобна, нищо не гърми, никой не разбира.
//
// Проектът има ДВА документирани капана точно тук и двата вече са платени:
//   · `setMonth(+n)` ПРЕЛИВА: 31 август + 6 месеца → „31 февруари" → 3 март.
//     Затова BL_DATE.addMonths клампва до последния ден (js/data.js:339).
//   · `new Date('2026-08-25')` е UTC полунощ, `new Date(2026,7,25)` е МЕСТНА.
//     Изваждането им дава ±1 ден. В София лятото разликата е 3 часа.
//
// Досега тези две неща се пазеха само от коментари. Тук се пазят от числа.
// ВСЯКО очаквано число долу е пресметнато НА РЪКА и е записано КАК.
//
// 🪤 ЗАЩО ТЕСТЪТ НЕ ПОЛЗВА `new Date()` ЗА „ДНЕС":
//   Тест, който зависи от деня, в който се пуска, утре казва друго. Тук
//   „днес" е ЗАКОВАНО. Ако някой ден трябва да се смени, това е решение,
//   не случайност.
//
// ПУСКАНЕ: node dev/test_dati_smetki.js
// ПЪТ НАЗАД: файлът само ЧЕТЕ проекта.
// ═══════════════════════════════════════════════════════════
const fs = require('fs');
const vm = require('vm');
const path = require('path');
process.chdir(path.resolve(__dirname, '..'));

// зареждаме истинския BL_DATE от проекта, не негово копие
const ctx = { console: { log() {}, warn() {} }, JSON, Math, Date, RegExp, String, Number, Array, Object };
ctx.window = ctx; ctx.globalThis = ctx; ctx.self = ctx;
vm.createContext(ctx);
try { new vm.Script(fs.readFileSync('js/data.js', 'utf8')).runInContext(ctx); }
catch (e) { console.log('🔴 js/data.js не се зареди: ' + e.message); process.exit(2); }
const BL_DATE = ctx.BL_DATE;
if (!BL_DATE || !BL_DATE.addMonths) { console.log('🔴 няма BL_DATE.addMonths'); process.exit(2); }

// местна дата — БЕЗ низ, за да няма UTC изместване
const д = (г, м, ден) => new Date(г, м - 1, ден);
const низ = x => x.getFullYear() + '-' + String(x.getMonth() + 1).padStart(2, '0') + '-' + String(x.getDate()).padStart(2, '0');

let паднали = 0, общо = 0;
function равно(какво, получено, очаквано, обяснение) {
  общо++;
  const ок = String(получено) === String(очаквано);
  if (!ок) паднали++;
  console.log('     ' + (ок ? '✅' : '🔴') + ' ' + какво);
  console.log('        получено: ' + получено + (ок ? '' : '   ОЧАКВАНО: ' + очаквано));
  if (обяснение) console.log('        ' + обяснение);
}

console.log('📅 СМЕТКИТЕ С ДАТИ — ръчно пресметнати примери\n');

// ── 1. ПРЕЛИВАНЕТО НА МЕСЕЦА (капанът с ваксините) ──
console.log('  ── 1. Месец с по-малко дни (заради него бебе отива на ваксина в грешен ден) ──');
равно('31 август 2026 + 6 месеца',
  низ(BL_DATE.addMonths(д(2026, 8, 31), 6)), '2027-02-28',
  'февруари 2027 има 28 дни (2027 не е високосна) → клампва се до 28, не прелива в март');
равно('31 август 2027 + 6 месеца (ВИСОКОСНА)',
  низ(BL_DATE.addMonths(д(2027, 8, 31), 6)), '2028-02-29',
  '2028 се дели на 4 и не е кръгла → 29 дни');
равно('31 януари + 1 месец',
  низ(BL_DATE.addMonths(д(2026, 1, 31), 1)), '2026-02-28', 'най-честият случай изобщо');
равно('31 март − 1 месец (назад)',
  низ(BL_DATE.addMonths(д(2026, 3, 31), -1)), '2026-02-28', 'клампването важи и назад');
равно('15 декември + 2 месеца (през Нова година)',
  низ(BL_DATE.addMonths(д(2026, 12, 15), 2)), '2027-02-15', 'годината се сменя правилно');
равно('29 февруари 2028 + 12 месеца',
  низ(BL_DATE.addMonths(д(2028, 2, 29), 12)), '2029-02-28',
  '2029 не е високосна → 29 февруари не съществува, взима се 28');
равно('30 април + 0 месеца',
  низ(BL_DATE.addMonths(д(2026, 4, 30), 0)), '2026-04-30', 'нула не бива да мърда нищо');

// ── 2. ТЕРМИНЪТ (280 дни по Негеле) ──
console.log('\n  ── 2. Терминът: първи ден на цикъла + 280 дни ──');
const ПМ = д(2026, 1, 1);
const термин = new Date(ПМ.getTime() + 280 * 86400000);
равно('ПМ 1 януари 2026 → термин',
  низ(термин), '2026-10-08',
  'на ръка: ян 30 + фев 28 + мар 31 + апр 30 + май 31 + юни 30 + юли 31 + авг 31 + сеп 30 = 272, + 8 дни октомври = 280');

// ── 3. СЕДМИЦАТА (същата формула на 4 места в проекта) ──
console.log('\n  ── 3. Седмицата на бременността ──');
// формулата, която ползват preg20.js, preg.js и rooms2.js (2 пъти)
const седмица = (пм, днес) => Math.floor((днес - пм) / 604800000);
const ДНЕС = д(2026, 8, 25);
равно('ПМ 1 януари 2026, днес 25 август 2026',
  седмица(ПМ, ДНЕС), 33,
  'на ръка: ян 30 + фев 28 + мар 31 + апр 30 + май 31 + юни 30 + юли 31 = 211, + 25 = 236 дни; 236 / 7 = 33.7 → 33 ПЪЛНИ седмици');
равно('в самия ден на ПМ',
  седмица(ДНЕС, ДНЕС), 0, 'нулева седмица, не първа — броим ПЪЛНИ седмици');
равно('6 дни след ПМ', седмица(д(2026, 8, 19), ДНЕС), 0, 'още не е минала цяла седмица');
равно('7 дни след ПМ', седмица(д(2026, 8, 18), ДНЕС), 1, 'точно на седмия ден става 1');

// ── 4. КАПАНЪТ С ЧАСОВИЯ ПОЯС ──
console.log('\n  ── 4. Часовият пояс: низ срещу местна дата ──');
const отНиз = new Date('2026-08-25');          // UTC полунощ
const отЧисла = д(2026, 8, 25);                 // местна полунощ
const разликаЧаса = Math.round((отЧисла - отНиз) / 3600000);
console.log('     ℹ️  new Date("2026-08-25") и new Date(2026,7,25) се различават с ' +
            разликаЧаса + ' часа на тази машина');
console.log('        Затова ВСЯКА сметка за „днес" в проекта трябва да ползва');
console.log('        местни числа. Ако разликата беше пренебрегната при изваждане,');
console.log('        резултатът може да падне с ЦЯЛ ДЕН при пресмятане на серии.');
// 🪤 Това е БЕЛЕЖКА, не проверка: разликата зависи от часовия пояс на
//   машината и в Гринуич би била 0. Тест, който съди по нея, би бил зелен
//   в Лондон и червен в София — тоест би мерил къде е пуснат, не какво
//   прави кодът. Затова числото се ПОКАЗВА, но не се съди.
//   Истинската проверка за този капан живее в dev/dati.js (сравнява как
//   самият проект строи датите), не тук.

// ── 5. САМОПРОВЕРКА: може ли този файл изобщо да гръмне ──
console.log('\n  ── 5. САМОПРОВЕРКА (иначе зелените горе не значат нищо) ──');
const прелива = (дата, n) => { const x = new Date(дата); x.setMonth(x.getMonth() + n); return низ(x); };
const наивно = прелива(д(2026, 8, 31), 6);
console.log('     ' + (наивно !== '2027-02-28' ? '✅' : '🔴') +
            ' НАИВНАТА сметка (setMonth без клампване) дава ' + наивно + ' — тоест грешката Е възможна');
console.log('        Ако и тя даваше 2027-02-28, тестът горе нямаше да доказва нищо.');
if (наивно === '2027-02-28') паднали++;
общо++;

console.log('\n  ПРОВЕРКИ: ' + общо + ' · ' + (паднали ? '🔴 ПАДНАЛИ: ' + паднали : '✅ всички минаха'));
process.exit(паднали ? 1 : 0);
