// ═══════════════════════════════════════════════════════════
// 👆 ПОД ПРЪСТА — колко голямо е всяко натискаемо нещо
//
// ЗАЩО: приложението се гледа на ТЕЛЕФОН, много често с ЕДНА РЪКА, защото
// другата държи бебе. Нещо под ~44×44 пиксела се уцелва трудно дори с две
// ръце; с една, нощем, при плачещо дете — то е капан. И най-скъпо е точно
// там, където мама бърза: спешните бутони.
//
// 44 не е мое мнение — това е прагът, който Apple и Google дават в своите
// правила за докосване (Apple: 44pt, Google: 48dp). Тук се брои в CSS
// пиксели, което на телефон е близко до едното и другото.
//
// ТОЗИ ФАЙЛ РАБОТИ САМО В БРАУЗЪР:
//     const r = await fetch('/dev/dopir.js'); (0,eval)(await r.text());
//     await BL_DOPIR.самопроверка()
//     await BL_DOPIR.обходи()
//
// КАКВО СЕ МЕРИ ЗА ВСЯКО НЕЩО:
//   · височина и ширина на кутията му НА ЕКРАНА (не в css файла — там
//     стойността може да е презаписана от друго правило)
//   · РАЗСТОЯНИЕТО до най-близкия друг натискаем съсед: два малки бутона,
//     залепени един до друг, са по-опасни от един малък сам
//   · дали е СПЕШЕН (112, отрова, кръв) — там прагът е по-строг
//
// 🪤 КАПАНИТЕ, ЗАРАДИ КОИТО ТОВА НЕ Е ПРОСТО querySelectorAll:
//   · Кутията на елемента НЕ Е зоната за натискане. `padding` увеличава,
//     `transform: scale()` също, а прозрачно поле около иконка се брои.
//     Затова се чете getBoundingClientRect на САМИЯ елемент — това е
//     каквото пръстът среща.
//   · Скрито нещо (offsetParent null, нулева кутия) НЕ Е дефект — просто не
//     се вижда. Брои се отделно, не се обявява.
//   · `position: fixed` има offsetParent === null ВИНАГИ, дори когато се
//     вижда на цял екран. Този капан е платен два пъти в проекта
//     (js/izvan_ekrana.js, js/plavno.js) — тук се проверява по кутия.
//   · Вложени натискаеми: бутон вътре в бутон се брои веднъж.
// ═══════════════════════════════════════════════════════════
(function () {
  'use strict';

  const ПРАГ = 44;           // пиксела — долната граница за пръст
  const ПРАГ_СПЕШНО = 48;    // където мама бърза, искаме повече
  const БЛИЗО = 8;           // под толкова пиксела разстояние = залепени
  const СПЕШНО = /112|150|линейк|отров|кръв|задав|спешн|SOS|гърч|припад|токсик/i;
  const СПИ = ms => new Promise(r => setTimeout(r, ms));

  const СЕЛЕКТОР = 'button, [role="button"], a[href], input, select, textarea, ' +
                   'label.jr-check, .jr-chip, .chip, .ro-chip, [data-act], [onclick]';

  const надпис = e => (e.getAttribute('aria-label') || e.value || e.placeholder ||
                       (e.textContent || '').trim() || e.className || e.tagName).slice(0, 44);

  function натискаемите(корен) {
    const всички = [...(корен || document).querySelectorAll(СЕЛЕКТОР)];
    return всички.filter(e => {
      const r = e.getBoundingClientRect();
      if (r.width === 0 || r.height === 0) return false;           // скрито
      if (getComputedStyle(e).visibility === 'hidden') return false;
      // вложено натискаемо — родителят стига
      const родител = e.parentElement && e.parentElement.closest(СЕЛЕКТОР);
      if (родител && всички.indexOf(родител) >= 0) return false;
      return true;
    });
  }

  // 🔴🔴 БЕЗ ТОВА ЦЕЛИЯТ УРЕД ЛЪЖЕ. ИЗМЕРЕНО 25.08:
  //   Първият пробег обяви 704 от 1537 неща за „под прага", включително
  //   бутона „🫁 Напъване или задавяне" (38 пиксела). При проверка на едно от
  //   тях се оказа, че CSS вече му дава `min-height: 44px` — тоест мярката
  //   казваше невъзможното.
  //   ПРИЧИНАТА: мери се ПО ВРЕМЕ НА АНИМАЦИЯТА ЗА ВЛИЗАНЕ. Предшествениците
  //   носеха `transform: matrix3d(...)` (картата още се завърта) и
  //   `scale(0.96)` (панелът още влиза). getBoundingClientRect връща
  //   РАЗМЕРА СЛЕД ТРАНСФОРМАЦИЯ — тоест смалената, летяща кутия.
  //   И най-лошото: в СКРИТ раздел анимациите изобщо не текат, значи
  //   никога не се уталожват сами и грешката е ПОСТОЯННА, не случайна.
  //   ЛЕКЪТ: анимациите се ДОКАРВАТ до края преди мерене. Тогава кутията е
  //   тази, която пръстът наистина среща.
  //   ⚠️ Пипа страницата — затова само в уред, никога в самото приложение.
  function уталожиАнимациите() {
    let докарани = 0;
    try {
      for (const a of document.getAnimations()) {
        // безкрайните нямат край — тях ги оставяме, те не мърдат геометрия
        try { if (a.effect && a.effect.getTiming().iterations === Infinity) continue; } catch (e) {}
        try { a.finish(); докарани++; } catch (e) {}
      }
    } catch (e) {}
    return докарани;
  }

  // 🔴🔴 И ВТОРАТА ЛЪЖА НА СЪЩИЯ УРЕД, също измерена:
  //   След уталожването пак излизаха 911 „малки" — включително бутона
  //   „🤫 Задавяне" с 42 пиксела. Проверих ЕДИН от тях направо:
  //       getBoundingClientRect().height = 42
  //       offsetHeight                   = 44      ← истината
  //       min-height (css)               = 44px
  //   Тоест CSS-ът Е ПРАВ и се спазва. Разликата идва от мащаб върху
  //   контейнер някъде нагоре (панелът влиза с scale) — а rect връща
  //   размера СЛЕД трансформация, тоест КАРТИНКАТА, не кутията.
  //   Пръстът среща картинката, но 4% разлика не е дефект; преправяне на
  //   911 елемента заради 2 пиксела би било пипане на здраво.
  //   Затова мерим ПОДРЕДБАТА (offsetWidth/offsetHeight) — тя не се влияе от
  //   трансформации. За SVG и подобни, където те са 0, падаме на rect.
  const кутия = e => {
    const w = e.offsetWidth, h = e.offsetHeight;
    if (w > 0 && h > 0) return { width: w, height: h, откъде: 'подредба' };
    const r = e.getBoundingClientRect();
    return { width: r.width, height: r.height, откъде: 'картинка (няма подредба)' };
  };

  function прегледай(корен, име) {
    уталожиАнимациите();
    const ел = натискаемите(корен);
    const кутии = ел.map(e => ({ e, r: кутия(e), рект: e.getBoundingClientRect() }));
    const малки = [], залепени = [];
    for (const { e, r, рект } of кутии) {
      const н = надпис(e);
      const спешен = СПЕШНО.test(н);
      const праг = спешен ? ПРАГ_СПЕШНО : ПРАГ;
      const най = Math.min(r.width, r.height);
      if (най < праг) {
        малки.push({ име, надпис: н, размер: Math.round(r.width) + '×' + Math.round(r.height),
                     праг, спешен, недостиг: Math.round(праг - най) });
      }
      // залепен ли е за друг натискаем
      let найБлизък = Infinity;
      for (const друг of кутии) {
        if (друг.e === e) continue;
        const d = разстояние(рект, друг.рект);
        if (d < найБлизък) найБлизък = d;
      }
      if (найБлизък < БЛИЗО && най < ПРАГ)
        залепени.push({ име, надпис: н, разстояние: Math.round(найБлизък) });
    }
    return { прегледани: ел.length, малки, залепени };
  }

  function разстояние(a, b) {
    const dx = Math.max(0, Math.max(a.left - b.right, b.left - a.right));
    const dy = Math.max(0, Math.max(a.top - b.bottom, b.top - a.bottom));
    return Math.sqrt(dx * dx + dy * dy);
  }

  async function обходи(опции) {
    опции = опции || {};
    const СТАИ = опции.стая ? [опции.стая] : ['Бременност', 'Моето бебе', 'Захранване',
      'Здраве и SOS', 'Развитие и игри', 'Инструменти', 'Дневник на мама',
      'Жената в мен', 'Лабораторията'];
    window._ldDirect = 1;
    const общо = { прегледани: 0, малки: 0, спешни_малки: 0, залепени: 0 };
    const списък = [], поЕкрани = {};

    const екран = (име, корен) => {
      const р = прегледай(корен, име);
      общо.прегледани += р.прегледани;
      общо.малки += р.малки.length;
      общо.спешни_малки += р.малки.filter(x => x.спешен).length;
      общо.залепени += р.залепени.length;
      поЕкрани[име] = { прегледани: р.прегледани, малки: р.малки.length };
      списък.push(...р.малки);
    };

    try { MamaHelper.close && MamaHelper.close(); } catch (e) {}
    await СПИ(0);
    екран('НАЧАЛНА', document);

    for (const с of СТАИ) {
      try { MamaHelper.close && MamaHelper.close(); } catch (e) {}
      await СПИ(0);
      try { MamaHelper.open(с); } catch (e) { поЕкрани[с] = { НЕ_СЕ_ОТВОРИ: e.message }; continue; }
      // чакаме съдържание, не време (скрит раздел дроселира таймерите)
      for (let i = 0; i < 30; i++) {
        const п = document.getElementById('roRoom');
        if (п && натискаемите(п).length > 0) break;
        await СПИ(0);
      }
      const п = document.getElementById('roRoom');
      екран(с, п || document.body);
    }
    try { MamaHelper.close && MamaHelper.close(); } catch (e) {}

    списък.sort((a, b) => (b.спешен - a.спешен) || (b.недостиг - a.недостиг));
    return { ОБЩО: общо, по_екрани: поЕкрани, най_малките: списък.slice(0, 30),
             праг: ПРАГ + 'px (спешните: ' + ПРАГ_СПЕШНО + 'px)' };
  }

  // ── самопроверка: различава ли голямо от малко, и вижда ли залепените
  async function самопроверка() {
    const кутия = document.createElement('div');
    кутия.style.cssText = 'position:fixed;left:0;top:0;width:300px;height:200px';
    const мк = д => { const b = document.createElement('button'); b.textContent = д;
      b.style.cssText = 'display:block;width:60px;height:60px'; return b; };
    const голям = мк('голям');
    const малък = мк('малък'); малък.style.cssText = 'display:block;width:20px;height:20px';
    const спешен = мк('112'); спешен.style.cssText = 'display:block;width:46px;height:46px';
    кутия.append(голям, малък, спешен);
    document.body.appendChild(кутия);
    // ── и капанът, който за малко не ме прати да поправям здрав код:
    //    бутон 60×60, но СВИТ от анимация на родителя си. Уред без
    //    уталожване го обявява за малък.
    const летящ = document.createElement('div');
    летящ.style.cssText = 'position:fixed;left:0;top:300px;width:300px;height:200px';
    const голямВЛет = мк('в полет'); голямВЛет.style.cssText = 'display:block;width:60px;height:60px';
    летящ.appendChild(голямВЛет);
    document.body.appendChild(летящ);
    const анимация = летящ.animate([{ transform: 'scale(0.5)' }, { transform: 'scale(1)' }],
                                   { duration: 100000, fill: 'both' });
    const рЛет = прегледай(летящ, 'полет');

    const р = прегледай(кутия, 'проба');
    const имена = р.малки.map(x => x.надпис);
    кутия.remove();
    try { анимация.cancel(); } catch (e) {}
    летящ.remove();
    return {
      '✅ прегледа и трите': р.прегледани === 3,
      '✅ ГОЛЯМ (60×60) не е находка': имена.indexOf('голям') < 0,
      '✅ МАЛЪК (20×20) е находка': имена.indexOf('малък') >= 0,
      '✅ СПЕШЕН 46×46 е находка (за него прагът е 48)': имена.indexOf('112') >= 0,
      '✅ и НЕ обявява скритото': прегледай(document.createElement('div'), 'празно').прегледани === 0,
      '✅ НЕ обявява голям бутон, СВИТ от анимация (иначе целият уред лъже)':
          рЛет.малки.length === 0
    };
  }

  window.BL_DOPIR = { обходи, самопроверка, прегледай, натискаемите };
  console.log('👆 под пръста → await BL_DOPIR.самопроверка() после await BL_DOPIR.обходи()');
})();
