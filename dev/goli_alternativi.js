// 🚨 ГОЛИТЕ АЛТЕРНАТИВИ — пазач за класа, който намери „но" вътре в „мНОго".
//
// В js/helper.js има стотици регулярни изрази от вида /(а|б|в)/. Когато
// алтернативата е КЪСА българска дума без граница, тя се улучва ВЪТРЕ в
// друга дума. Според мястото си това или вдига фалшива тревога, или —
// по-коварното — ИЗКЛЮЧВА пазач и пак вдига тревога.
//
// ⚖️ Този пазач НЕ ПОДОЗИРА, а МЕРИ: за всяка къса гола алтернатива търси
//    в истински списък от български думи (ключовете на kb.js + корпусите)
//    думи, които я СЪДЪРЖАТ, без да са тя. Няма такива → мълчи.
//
// Многосъставните („а сега", „днес се") са безопасни голи — интервалът им
// е граница. Затова се гледат само едносъставните.
const fs = require('fs');

const ФАЙЛ = process.argv[2] || 'js/helper.js';
const ПРАГ = 4;      // дума с толкова или по-малко букви е „къса"
const МАКС_ПРИМЕРИ = 4;

// Служебните думи на българския: съюзи, предлози, частици, кратки
// местоимения. Те НЯМАТ форми, тоест никога не са корен на друга дума —
// значи всяко улучване вътре в дума е СЛУЧАЙНО и е дефект.
const СЛУЖЕБНИ = new Set([
  'но', 'а', 'и', 'или', 'ала', 'ама', 'та', 'че', 'да', 'не', 'ни', 'нито',
  'в', 'във', 'с', 'със', 'от', 'до', 'за', 'по', 'на', 'о', 'при', 'над',
  'под', 'през', 'към', 'из', 'без', 'край', 'сред', 'у',
  'се', 'си', 'ми', 'ти', 'му', 'ѝ', 'ни', 'ви', 'им', 'го', 'я', 'ги',
  'ме', 'те', 'ти', 'аз', 'ний', 'той', 'тя', 'то', 'те', 'тия', 'тоя',
  'ще', 'ли', 'дори', 'пък', 'ето', 'ей', 'нали', 'май', 'чак', 'все',
  'е', 'са', 'бе', 'би', 'сме', 'сте', 'бях', 'беше', 'бил',
]);

// ── речникът: истинските думи, които майката пише ────────────────────────
const думи = new Set();
function ядж(s) { String(s).toLowerCase().split(/[^а-яё]+/).forEach(w => { if (w.length > 2) думи.add(w); }); }
try {
  const kb = fs.readFileSync('js/kb.js', 'utf8');
  (kb.match(/'[^']{3,60}'|"[^"]{3,60}"/g) || []).forEach(x => { if (/[а-я]/.test(x)) ядж(x); });
} catch (e) { console.log('⚠️ kb.js не се чете'); }
for (const и of ['korpus350', 'korpus_nevinni', 'korpus_nevinni2', 'korpus_speshni', 'korpus_hipoteza']) {
  try { require('./' + и + '.json').forEach(q => ядж(q.t || '')); } catch (e) {}
}

// ── алтернациите ─────────────────────────────────────────────────────────
const редове = fs.readFileSync(ФАЙЛ, 'utf8').split('\n');
const намерени = [];
редове.forEach((ред, i) => {
  const гол = ред.trim();
  if (гол.slice(0, 2) === '//' || гол.slice(0, 1) === '*') return;      // коментарите не са код
  if (ред.indexOf('/') < 0) return;                                     // няма регуляр на реда

  // ⚖️ ЗАЩО САМО ОТРИЦАТЕЛНИТЕ ПРОВЕРКИ
  //   Общата сонда върна 379 находки и почти всички бяха окончания или
  //   изрази с граница малко по-нататък — тоест шум. Пазач, който вика
  //   вълк 379 пъти, не се чете и после мълчи, когато има вълк.
  //   Опасният случай е ТЕСЕН и е точно този, който намери „но":
  //   къса гола дума в ОТРИЦАТЕЛНА проверка (!/…/ или „→ return false").
  //   Там улучването не вдига тревога — ИЗКЛЮЧВА пазача, и никой пазач
  //   за ключове не го вижда.
  if (ред.indexOf('!/') < 0 && !/return false/.test(ред)) return;

  // всяка скоба с поне една чертичка вътре, съдържаща кирилица
  const групи = ред.match(/\([^()]*\|[^()]*\)/g) || [];
  for (const г of групи) {
    const вътре = г.slice(1, -1);
    if (!/[а-я]/.test(вътре)) continue;
    if (/\?[:!=<]/.test(г)) continue;                                   // (?: (?! (?= — не са алтернации от думи

    const идx = ред.indexOf(г);
    const преди = ред.slice(Math.max(0, идx - 24), идx);
    const след = ред.slice(идx + г.length, идx + г.length + 12);

    // 🧹 ОКОНЧАНИЯТА НЕ СА ДЕФЕКТ. „лиц(е|ето|енце)" е шаблон за ЕДНА дума —
    //    групата е залепена за корен и не може да се улучи другаде. Дефектът
    //    е само когато групата стои САМА, тоест е цяла дума.
    if (/[а-яa-z0-9\]*+?]$/i.test(преди) && !/\\s\*?$|\)$/.test(преди)) continue;
    // Границата е (^|[^а-я]) / (?![а-я]) / \b / \s — но и ЖИВИЯТ ИНТЕРВАЛ:
    // „корем[а-я]* (е|си е) добре" е защитено от самите шпации.
    const сГраницаПреди = /(\^\|\[\^а-я\]\)|\\b|\[\^а-я\]|\\s[*+?]?| )\s*$/.test(преди);
    const сГраницаСлед = /^(\(\?!\[а-я\]\)|\\b|\[\^а-я\]|\\s|\$| )/.test(след);
    if (сГраницаПреди && сГраницаСлед) continue;                        // напълно защитена

    for (const алт of вътре.split('|')) {
      const a = алт.trim();
      if (!/^[а-я]+$/.test(a)) continue;                                // само чисти едносъставни думи
      if (a.length > ПРАГ) continue;
      // ⚖️ САМО СЛУЖЕБНИ ДУМИ.
      //   „блед" вътре в „пребледня" е НАРОЧНО — корен, който лови формите.
      //   „но" вътре в „много" е СЛУЧАЙНО — съюз няма форми. Машина не може
      //   да отсъди кое е кое, затова списъкът е ръчен и къс: съюзи,
      //   предлози, частици и местоимения. Само те никога не са корен.
      if (!СЛУЖЕБНИ.has(a)) continue;
      // МЕРЯ: има ли истинска дума, която я съдържа, без да е тя?
      const хващa = [];
      for (const w of думи) { if (w !== a && w.indexOf(a) >= 0) { хващa.push(w); if (хващa.length >= 40) break; } }
      if (!хващa.length) continue;
      намерени.push({ ред: i + 1, алт: a, група: г.slice(0, 70), примери: хващa.slice(0, МАКС_ПРИМЕРИ), брой: хващa.length, край: сГраницаСлед, начало: сГраницаПреди });
    }
  }
});

// ── подредба: най-много улучени думи най-отгоре ──────────────────────────
намерени.sort((a, b) => b.брой - a.брой);
console.log('');
console.log('🚨 ГОЛИТЕ АЛТЕРНАТИВИ в ' + ФАЙЛ);
console.log('   речник от истински думи: ' + думи.size);
if (!намерени.length) { console.log('\n   ✅ ЧИСТО — нито една къса гола алтернатива не се улучва вътре в дума.'); process.exit(0); }
console.log('   ⚠️ намерени: ' + намерени.length + '\n');
const пок = намерени.slice(0, 40);
for (const н of пок) {
  const защита = (н.начало ? '' : ' без-начало') + (н.край ? '' : ' без-край');
  console.log('   ред ' + String(н.ред).padEnd(6) + '„' + н.алт + '"'.padEnd(3) + ' улучва ' + String(н.брой).padStart(3) + '+ думи:' + защита);
  console.log('        ' + н.примери.join(' · '));
  console.log('        в: ' + н.група);
}
if (намерени.length > пок.length) console.log('   … и още ' + (намерени.length - пок.length));
console.log('');
console.log('   ЛЕК: обгради групата с (^|[^а-я])…(?![а-я]) ИЛИ извади късата дума');
console.log('        в отделен клон със собствени граници.');
console.log('   ⚠️ Не всяка находка е дефект — важи мястото. Голямата беше „но"');
console.log('      в ОТРИЦАТЕЛЕН пазач: там улучването ИЗКЛЮЧВА защитата.');
process.exit(намерени.length ? 1 : 0);
