// 🩹 rAF ПОДПОРКА — защо тестовете забиваха ЦЕЛИЯ ДЕН
//
// Browser панелът заби над петнайсет пъти на 12.08. Всеки път изглеждаше
// като случайност: „табът не отговаря", „изглежда заклещен". Не беше.
//
// ИЗМЕРЕНО от агента по паметта:
//   скрит панел → setTimeout гръмва за 0 ms
//                 микрозадачите за 0 ms
//                 requestAnimationFrame НЕ СЕ ОБАЖДА И СЛЕД 9.9 СЕК
//
// Браузърът не рисува кадри за невидим таб, значи rAF няма кога да се
// пусне. Всеки тест, който чака анимация през rAF, виси ЗАВИНАГИ.
// Първият пробег на теста за паметта стоя ЧЕТИРИ МИНУТИ на една група и
// нямаше да мръдне. Тестът за телефона висеше три пъти по същата причина
// и никога не даде число.
//
// И втора причина, също измерена: СТАРИ ТАБОВЕ от същия произход блокират
// целия рендерер. Четири таба даваха таймаут; щом два се затворят,
// останалите оживяват веднага.
//
// Това е ПОДПОРКА НА СРЕДАТА, не промяна в приложението: сменя rAF само в
// прозореца на теста и изчезва при презареждане. Приложението не я вижда.
//
// ПУСКАНЕ — преди зареждане на тест:
//   var s=document.createElement('script'); s.src='dev/raf_podporka.js'; document.body.appendChild(s);
//   // или:  await (await fetch('dev/raf_podporka.js')).text().then(eval)
//
// ПЪТ НАЗАД: BL_RAF.върни() слага оригиналния rAF обратно.
//            Презареждането също го връща — нищо не остава.
// ═══════════════════════════════════════════════════════════
(function () {
  'use strict';

  if (window.BL_RAF && window.BL_RAF.сложена) {
    console.log('🩹 подпорката вече е сложена');
    return;
  }

  var истинскиRAF = window.requestAnimationFrame;
  var истинскиCancel = window.cancelAnimationFrame;

  // 16 ms ≈ един кадър при 60 в секунда. Не бърза изкуствено — само
  // гарантира, че обратното извикване ИДВА.
  window.requestAnimationFrame = function (cb) {
    return setTimeout(function () { cb(performance.now()); }, 16);
  };
  window.cancelAnimationFrame = function (id) { clearTimeout(id); };

  window.BL_RAF = {
    сложена: true,
    скрит: document.hidden,
    върни: function () {
      window.requestAnimationFrame = истинскиRAF;
      window.cancelAnimationFrame = истинскиCancel;
      window.BL_RAF.сложена = false;
      return 'истинският rAF е върнат';
    },
    // доказва, че подпорката е нужна ИЛИ че не е — не гадае
    провери: function () {
      return new Promise(function (готово) {
        var почна = performance.now(), дойде = false;
        истинскиRAF(function () { дойде = true; });
        setTimeout(function () {
          готово({
            табът_е_скрит: document.hidden,
            истинският_rAF_се_обади_за_1_сек: дойде,
            присъда: дойде ? '✅ rAF работи — подпорката не е нужна'
                           : '🔴 rAF НЕ СЕ ПУСКА — без подпорка всеки тест виси',
            милисекунди: Math.round(performance.now() - почна)
          });
        }, 1000);
      });
    }
  };

  console.log('🩹 rAF подпорка сложена (таб ' + (document.hidden ? 'СКРИТ' : 'видим') +
              '). Провери с: await BL_RAF.провери()   ·   Върни с: BL_RAF.върни()');
})();
