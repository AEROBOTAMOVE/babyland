// ═══════════════════════════════════════════════════════════
// 📚 ПРЕПОКРИВАНЕТО В БИБЛИОТЕКАТА — колко статии казват едно и също
//
// ЗАЩО (25.08.2026): добавих статия „Попарване с гореща течност" и после
// видях в списъка, че тя е СЕДМАТА на тази тема. Проверих: 31 статии за
// ЯСЛА, 11 за СКРИНИНГ, 6 за ИЗГАРЯНЕ — и всичко това ОТПРЕДИ днес.
// Тоест библиотеката расте, но част от растежа е повторение.
//
// 849 статии звучи богато. 849 статии, от които 31 за едно и също, звучи
// различно — майката отваря темата и вижда единайсет заглавия, които не
// може да различи.
//
// КАК СЕ МЕРИ БЕЗ ДА СЕ ЧЕТЕ ВСИЧКО:
//   За всяка двойка статии в ЕДНА стая се смята припокриването на СМИСЛОВИТЕ
//   думи в заглавието и резюмето (коефициент на Жакар). Служебните думи не
//   се броят. Двойка над прага е кандидат за сливане, не присъда.
//
// 🪤 ЗАЩО НЕ ПО ТЯЛОТО: две статии по една тема почти винаги делят голяма
//   част от думите в тялото (симптоми, съвети) и прагът става безсмислен.
//   Заглавието и резюмето казват ЗА КАКВО Е статията — там повторението личи.
//
// 🪤 И ЗАЩО НЕ Е ПРИСЪДА: „Ясла: адаптация" и „Ясла: документи" делят думата
//   „ясла", но са РАЗЛИЧНИ теми. Затова уредът дава СПИСЪК ЗА ГЛЕДАНЕ, не
//   команда за триене. Числото му е сравнително: пусни го пак след чистене.
//
// 🔴 СЛЯПОТО МУ ПЕТНО, КАЗАНО ОТКРИТО (собствената му самопроверка го показва):
//   „Изгаряния и попарвания 0-3: горещи течности, фурна, слънце" срещу
//   „Изгаряния, попарвания, отравяния и домашна безопасност" дава едва 0.22 —
//   ПОД всеки разумен праг. Тоест ДВЕ СТАТИИ ЗА ЕДНО И СЪЩО, написани с
//   различни думи, минават невидими.
//   Затова ГЛАВНИЯТ изход на този файл НЕ е броят двойки, а ВТОРАТА таблица:
//   коя дума се среща в най-много заглавия. Тя намери 29 статии с „ясла" и
//   46 с „раждане" — и точно тя ме прати да гледам с очи.
//   Двойките са допълнение; нула двойки НЕ значи „няма повторение".
//
// ПУСКАНЕ: node dev/prepokrivane.js [--prag=0.5] [--spisak]
// ПЪТ НАЗАД: файлът само ЧЕТЕ.
// ═══════════════════════════════════════════════════════════
const fs = require('fs');
const path = require('path');
process.chdir(path.resolve(__dirname, '..'));

const СПИСЪК = process.argv.includes('--spisak');
const ПРАГ = parseFloat((process.argv.find(a => a.indexOf('--prag=') === 0) || '').split('=')[1]) || 0.45;

const СЛУЖЕБНИ = new Set(['при', 'след', 'преди', 'през', 'към', 'между', 'без', 'над', 'под',
  'кога', 'какво', 'как', 'защо', 'кое', 'кои', 'кой', 'коя', 'или', 'това', 'тези', 'която',
  'които', 'срещу', 'според', 'дали', 'още', 'най', 'все', 'вече', 'само', 'също', 'едно',
  'една', 'един', 'има', 'няма', 'ако', 'дори', 'нещо', 'става', 'прави', 'значи', 'бебе',
  'бебето', 'дете', 'детето', 'мама', 'майка', 'майката', 'себе', 'него', 'нея', 'тях']);

const думи = t => new Set(String(t || '').toLowerCase()
  .replace(/[0-9]+[-–—][0-9]+/g, ' ').replace(/[^а-яa-z\s]/g, ' ')
  .split(/\s+/).filter(w => w.length >= 4 && !СЛУЖЕБНИ.has(w)));

function жакар(a, b) {
  if (!a.size || !b.size) return 0;
  let общи = 0;
  for (const w of a) if (b.has(w)) общи++;
  return общи / (a.size + b.size - общи);
}

const idx = JSON.parse(fs.readFileSync('lib/index.json', 'utf8'));
const статии = (idx.items || []).map(x => ({
  id: x.id, t: x.t || '', r: x.r || '(без стая)',
  думи: думи((x.t || '') + ' ' + (x.s || ''))
}));

console.log('📚 ПРЕПОКРИВАНЕТО В БИБЛИОТЕКАТА\n');
console.log('  статии : ' + статии.length);
console.log('  праг   : ' + ПРАГ + '   (дял общи смислови думи в заглавие+резюме)\n');

// по стаи, за да не сравняваме всичко с всичко
const поСтаи = {};
статии.forEach(s => { (поСтаи[s.r] = поСтаи[s.r] || []).push(s); });

let двойки = 0, сравнени = 0;
const намерени = [];
for (const [стая, списък] of Object.entries(поСтаи)) {
  for (let i = 0; i < списък.length; i++) {
    for (let j = i + 1; j < списък.length; j++) {
      сравнени++;
      const к = жакар(списък[i].думи, списък[j].думи);
      if (к >= ПРАГ) { двойки++; намерени.push({ стая, к, a: списък[i], b: списък[j] }); }
    }
  }
}
намерени.sort((x, y) => y.к - x.к);

console.log('  СРАВНЕНИ ДВОЙКИ : ' + сравнени.toLocaleString('bg') + '   (само в рамките на една стая)');
console.log('  ' + (двойки ? '🔶' : '✅') + ' НАД ПРАГА       : ' + двойки + '\n');

const показ = СПИСЪК ? намерени : намерени.slice(0, 18);
for (const н of показ) {
  console.log('  ' + н.к.toFixed(2) + '  [' + н.стая + ']');
  console.log('        ' + н.a.t.slice(0, 66));
  console.log('        ' + н.b.t.slice(0, 66));
}
if (!СПИСЪК && намерени.length > 18) console.log('  … още ' + (намерени.length - 18) + ' — с --spisak');

// ── и по ТЕМИ: коя дума се повтаря в най-много заглавия
const броене = {};
статии.forEach(s => { for (const w of думи(s.t)) броене[w] = (броене[w] || 0) + 1; });
const челни = Object.entries(броене).filter(([, n]) => n >= 8).sort((a, b) => b[1] - a[1]).slice(0, 14);
console.log('\n  ── ДУМИ В НАЙ-МНОГО ЗАГЛАВИЯ (кандидати за пренаситена тема) ──');
челни.forEach(([w, n]) => console.log('     ' + String(n).padStart(3) + '  ' + w));

// ── САМОПРОВЕРКА: уред, който никога не гърми, не мери нищо
// Първата мярка върна 0 и на праг 0.45, и на 0.32. Това е или добра новина,
// или сляп уред — и разликата се доказва само с примамка.
const п1 = жакар(думи('Попарване с гореща течност — първите двайсет минути'),
                 думи('Попарване с гореща течност: първите двайсет минути'));
const п2 = жакар(думи('Изгаряния и попарвания 0-3: горещи течности, фурна, слънце'),
                 думи('Изгаряния, попарвания, отравяния и домашна безопасност'));
const п3 = жакар(думи('Ясла: адаптация, боледуване, храна и сън'),
                 думи('Общинска ясла: кандидатстване, прием, документи'));
const п4 = жакар(думи('Кърлеж: вади се веднага с пинцета'),
                 думи('Колко мляко трябва да яде бебето'));
console.log('\n  САМОПРОВЕРКА (иначе нулата горе не значи нищо):');
console.log('     ' + (п1 >= 0.8 ? '✅' : '🔴') + ' ПОЧТИ ЕДНАКВИ заглавия → ' + п1.toFixed(2) + '  (очаквам над 0.80)');
console.log('     ' + (п2 >= 0.3 ? '✅' : '🔶') + ' същата тема, различни думи → ' + п2.toFixed(2));
console.log('     ' + (п3 < 0.45 ? '✅' : '🔴') + ' обща дума, РАЗЛИЧНА тема → ' + п3.toFixed(2) + '  (не бива да е находка)');
console.log('     ' + (п4 < 0.1 ? '✅' : '🔴') + ' съвсем различни → ' + п4.toFixed(2));
console.log('     ' + (сравнени > 10000 ? '✅' : '🔴') + ' сравнени двойки: ' + сравнени.toLocaleString('bg'));

console.log('\n  Числото е СРАВНИТЕЛНО и е СПИСЪК ЗА ГЛЕДАНЕ, не команда за триене:');
console.log('  „Ясла: адаптация" и „Ясла: документи" делят дума, но са различни теми.');
console.log('  ⚖️ Нула над прага значи: заглавията и резюметата СА различни. Това НЕ');
console.log('  доказва, че телата не се повтарят — тялото се мери с друг уред.');
