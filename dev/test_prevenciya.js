const { zaredi } = require('./pyasachnik.js');
const W = zaredi(null);
// ВЪПРОСИ ЗА ПРЕВЕНЦИЯ И РАЗПОЗНАВАНЕ — трябва да дадат КАРТА, не сирена
const ПИТА = [
 'как изглеждат петехиите','как да позная дали е обезводнено',
 'как да предотвратя обезводняване','опасно ли е ако глътне батерия питам предварително',
 'как да крия капсулите за пране','как да разбера че се дави',
 'какво да гледам при удар в главата','как изглежда гърч при бебе',
 'от какво може да посинее бебе','как да позная менингит',
 'какви са признаците на задавяне','кога температурата е опасна',
 'как да предпазя от изгаряне в кухнята','какво трябва да знам за безопасния сън',
 'как се разпознава фебрилен гърч','искам да съм подготвена ако се задави'];
// а ТЕЗИ трябва да си останат спешни
const СПЕШНИ = ['бебето се дави','глътна батерия','гърчи се','посиня','не диша',
 'петехии по корема','обезводнено е и не пишка','удари главата и повърна'];
let сирена = 0, карти = 0;
console.log('❓ ВЪПРОС ЗА ПРЕВЕНЦИЯ — трябва КАРТА, не сирена:');
for (const т of ПИТА) {
  const ф = !!W.BL_REDFLAG(т);
  if (ф) сирена++; else карти++;
  let r = null; try { r = W.BL_MATCH(т, 'Здраве и SOS'); } catch (e) {}
  console.log('  ' + (ф ? '🔴 СИРЕНА' : '✅ ' + (r ? r.id : 'няма карта')).padEnd(24) + т);
}
console.log('\n🚨 ИСТИНСКИ СПЕШНИ — трябва да останат сирена:');
let паднали = 0;
for (const т of СПЕШНИ) { const ф = !!W.BL_REDFLAG(т); if (!ф) паднали++;
  console.log('  ' + (ф ? '✅' : '🔴 МЪЛЧИ') + '  ' + т); }
console.log('\n  сирена при въпрос за превенция: ' + сирена + ' от ' + ПИТА.length);
console.log('  пропуснати истински спешни:     ' + паднали + ' от ' + СПЕШНИ.length);
