'use strict';
const path = require('path');
const { zaredi } = require(path.join(__dirname, 'pyasachnik.js'));
const САМО = process.argv.includes('--samoproverka');

const СТАИ = ['Бременност', 'Моето бебе', 'Захранване', 'Здраве и SOS', 'Дневник на мама',
  'Развитие и игри', 'Инструменти', 'Жената в мен', 'Лабораторията'];

// корпусът: етикетираните изречения + битови думи, които минават през пазачите
const изречения = [];
for (const и of ['korpus350', 'korpus_nevinni', 'korpus_nevinni2', 'korpus_speshni', 'korpus_hipoteza']) {
  try { for (const q of require(path.join(__dirname, и + '.json'))) if (q && q.t) изречения.push(q.t); } catch (e) {}
}
// 🪤 точно тези минават през НЕ_Е_ЧОВЕК / ДРУГА_ТЕМА / ПРЕДМЕТ — там беше дупката
for (const д of ['кантарът показва че съм качила 3 кила', 'с прането не мога да се справя', 'печката пуши',
  'колата не пали', 'часовникът спря', 'телевизорът падна', 'листата падат', 'хлябът мухляса',
  'gurchi se', 'не дише', 'коремчето ми е подуто', '', '   ', '???', '😀', 'а'.repeat(400)]) изречения.push(д);

const ПРОФИЛИ = [
  ['майка с бебе', { bl_baby: { birth: '2025-11-20', name: 'Алекс' } }],
  ['бременна', { bl_lmp: '2026-04-01' }],
  ['празен', {}],
];

function мери(подмяна) {
  const гърмежи = [];
  let повиквания = 0;
  for (const [име, памет] of ПРОФИЛИ) {
    const W = zaredi(подмяна || null, { памет });
    const врати = [
      ['BL_REDFLAG', т => W.BL_REDFLAG(т)],
      ['BL_MOTHERFLAG', т => W.BL_MOTHERFLAG(т)],
      ['BL_PREGFLAG', т => W.BL_PREGFLAG ? W.BL_PREGFLAG(т, 'Бременност') : null],
    ];
    for (const с of СТАИ) врати.push(['BL_MATCH/' + с, т => W.BL_MATCH(т, с)]);
    // 🪤 30.09 МЕРЕНО: всички врати върху целия корпус = 46 000 търсения на карта и
    //   над ДВА часа. Уред, който чакаш два часа, никой не пуска. Затова: трите врати
    //   за тревога (бързи — и там беше истинската грешка) минават ВСИЧКО; търсенето
    //   на карта минава всяко ШЕСТО изречение плюс всичките битови думи накрая.
    //   Извадката е детерминирана — едно и също всеки път, за да е сравнимо.
    const ИЗВАДКА = т => { const и = изречения.indexOf(т); return и % 6 === 0 || и >= изречения.length - 16; };
    for (const т of изречения) for (const [врата, ф] of врати) {
      if (врата.startsWith('BL_MATCH/') && !ИЗВАДКА(т)) continue;
      повиквания++;
      try { ф(т); } catch (e) {
        if (гърмежи.length < 400) гърмежи.push(име + ' · ' + врата + ' · ' + e.constructor.name + ': ' + String(e.message).slice(0, 70) + '  ← „' + String(т).slice(0, 50) + '“');
      }
    }
  }
  return { гърмежи, повиквания };
}

console.log('\n💥 НИКОГА НЕ ГЪРМИ\n');
console.log('  изречения: ' + изречения.length + ' · профили: ' + ПРОФИЛИ.length + ' · врати: 3 + ' + СТАИ.length + ' стаи');

if (САМО) {
  // подменяме pregLevel с такава, която гърми винаги — уредът ТРЯБВА да я хване
  const счупи = src => src.replace('function pregLevel(text, room) {', 'function pregLevel(text, room) { throw new Error("саботаж");');
  const р = мери(счупи);
  const хваща = р.гърмежи.some(г => /саботаж/.test(г));
  console.log('  САМОПРОВЕРКА: подменена врата, която гърми → ' + (хваща ? '✅ уредът я хваща (' + р.гърмежи.length + ' гърмежа)' : '🔴 уредът е СЛЯП'));
  process.exit(хваща ? 0 : 1);
}

const р = мери(null);
console.log('  повиквания: ' + р.повиквания);
if (р.гърмежи.length) {
  // групираме по вид, за да се вижда причината, а не 300 реда
  const групи = {};
  for (const г of р.гърмежи) { const к = г.split('  ← ')[0]; групи[к] = (групи[к] || 0) + 1; }
  console.log('\n  🔴 ГЪРМИ ' + р.гърмежи.length + ' ПЪТИ:');
  Object.entries(групи).sort((a, b) => b[1] - a[1]).slice(0, 15).forEach(([к, n]) => console.log('     ' + n + '×  ' + к));
  console.log('\n  примери:');
  р.гърмежи.slice(0, 5).forEach(г => console.log('     ' + г));
  process.exit(1);
}
console.log('\n  ✅ НУЛА ГРЕШКИ — всяка врата отговаря на всяко изречение, при всеки профил');
