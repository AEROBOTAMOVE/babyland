// там, където редът беше написан „const q = normalize(text);“. В pregLevel е
// написан иначе → ReferenceError. Мерено: „кантарът показва че съм качила
// 3 кила“, „с прането не мога да се справя“, „печката пуши“ — при бременна
// гърмяха и чатът оставаше на трите точки. ЦЯЛ ДЕН.
//
// Никой от пазачите не го хвана, защото всички тестват с профил на МАЙКА
// С БЕБЕ, а pregLevel работи само при бременна. Хвана го агент, който чете
// кода с очи. Това не бива да зависи от късмет.
