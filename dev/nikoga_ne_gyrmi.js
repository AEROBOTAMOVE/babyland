// КАКВО ПРАВИ: пуска ВСЯКА публична врата (тревоги, майчина, бременна и
// картите във всичките 9 стаи) върху целия етикетиран корпус С ТРИ ПРОФИЛА —
// майка с бебе, бременна, празен (първо отваряне) — и брои изключенията.
// Очакваното е НУЛА. Едно изключение е майка, на която приложението не отговаря.
//
// САМОПРОВЕРКА (--samoproverka): подменя една врата с такава, която гърми,
// и изисква уредът да го хване. Уред, който не може да гръмне, не мери.
//
// ПУСКАНЕ: node dev/nikoga_ne_gyrmi.js  ·  --samoproverka
// ПЪТ НАЗАД: файлът само ЧЕТЕ. Нула следи по диска.
