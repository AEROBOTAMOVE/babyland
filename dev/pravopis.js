// ✍️ ПРАВОПИСЪТ — шест вида грешка, които окото не вижда
//
// Няма български речник на машината, а „изтегли речник" не е отговор, когато
// текстът е 1900 KB. Затова тук се ловят само неща, които се доказват САМИ,
// без да се знае дали думата съществува:
//
// 1. 🔤 ЛАТИНСКА БУКВА В КИРИЛСКА ДУМА — най-коварната. „кръвнa" с латинско
//    „a" изглежда еднакво, но е ДРУГА дума: търсачката не я намира, ключът
//    не съвпада, а майката гледа буквите и не разбира защо не работи.
//    Опасните двойници: а/a е/e о/o с/c р/p х/x у/y к/k м/m т/t в/B н/H
// 2. 🔁 УДВОЕНА ДУМА — „на на", „се се", „от от". Класика при пренаписване.
// 3. ␣ ЛИПСВАЩ ИНТЕРВАЛ след точка/запетая („дума.Друга") и ДВОЕН интервал.
// 4. „ ПРАВ ЗНАК ЗА КАВИЧКА в български текст (трябва „ … ").
// 5. ⁉️ ДВЕ ПУНКТУАЦИИ ПОДРЕД („,,", „..", „!!" извън многоточие).
// 6. 🔡 ГОЛЯМА БУКВА В СРЕДАТА НА ДУМА („кръвНа") — следа от лепене.
//
// 🪤 ЗАЩО НЕ ЛОВЯ „непозната дума": без речник всяка проверка по честота
//    обявява редките ВЕРНИ думи („преходът", „хориоамнионит") за грешки и
//    удавя истинските находки. Мярка с 90% шум не е мярка.
//
// 🪤 И ЕДНО, КОЕТО МЕ Е ЛОВИЛО В ТОЗИ ПРОЕКТ: `\b` и `\w` НЕ работят с
//    кирилица в JavaScript — регулярен израз с тях намира НУЛА и мълчи.
//    Тук границите са изрични класове [а-яА-Я], никъде \b.
//
// ПУСКАНЕ: node dev/pravopis.js [--spisak] [--samo=latinica|dubli|interval|kavichki|punkt|glavna]
// ПЪТ НАЗАД: файлът само ЧЕТЕ.
// ═══════════════════════════════════════════════════════════
const fs = require('fs');
const vm = require('vm');
const path = require('path');
process.chdir(path.resolve(__dirname, '..'));

const СПИСЪК = process.argv.includes('--spisak');
const САМО = (process.argv.find(a => a.indexOf('--samo=') === 0) || '').split('=')[1] || '';

// ── латинските букви, които изглеждат като кирилски
const ДВОЙНИЦИ = 'aAeEoOcCpPxXyIHTBKMHTЕ';
const ЛАТ = /[a-zA-Z]/;
const КИР = /[а-яА-Я]/;

// ── източниците: библиотеката + базата на помощничките
function съберèТекстове() {
  const из = [];
  const idx = JSON.parse(fs.readFileSync('lib/index.json', 'utf8'));
  for (const it of (idx.items || [])) {
    из.push({ где: 'индекс/' + it.id, поле: 'заглавие', т: it.t || '' });
    из.push({ где: 'индекс/' + it.id, поле: 'резюме', т: it.s || '' });
  }
  const тела = fs.readdirSync('lib').filter(f => f.endsWith('.json') && f !== 'index.json');
  for (const ф of тела) {
    let d; try { d = JSON.parse(fs.readFileSync('lib/' + ф, 'utf8')); } catch (e) { continue; }
    for (const k of Object.keys(d)) {
      if (typeof d[k] === 'string') из.push({ где: ф + '/' + k, поле: 'тяло', т: d[k] });
    }
  }
  const ctx = { console: { log() {} }, JSON, Math, Date, RegExp, String, Number, Array, Object };
  ctx.window = ctx; ctx.globalThis = ctx; ctx.self = ctx;
  vm.createContext(ctx);
  new vm.Script(fs.readFileSync('js/kb.js', 'utf8')).runInContext(ctx);
  const KB = ctx.BL_KB || ctx.KB;
  for (const e of (KB.entries || [])) {
    for (const п of ['title', 'core', 'tip', 'follow']) {
      if (e[п]) из.push({ где: 'kb/' + e.id, поле: п, т: String(e[п]) });
    }
    for (const k of (e.keys || [])) из.push({ где: 'kb/' + e.id, поле: 'ключ', т: String(k) });
  }
  return из;
}

const текстове = съберèТекстове();
const находки = { latinica: [], dubli: [], interval: [], kavichki: [], punkt: [], glavna: [] };

for (const { где, поле, т } of текстове) {
  // ── 1. латиница в кирилска дума
  // дума = поредица от букви (кирилски ИЛИ латински) без разделител
  const думи = т.split(/[^а-яА-Яa-zA-Z]+/);
  for (const д of думи) {
    if (д.length < 2) continue;
    if (!КИР.test(д) || !ЛАТ.test(д)) continue;      // само СМЕСЕНИТЕ
    // изключваме нарочните смеси: „PWA-то", „SOS", мерни единици
    if (/^[A-Z]{2,}/.test(д)) continue;
    находки.latinica.push({ где, поле, дума: д,
      букви: д.split('').filter(c => ЛАТ.test(c)).join('') });
  }
  // ── 2. удвоена дума
  // 🪤 ПЪРВАТА ВЕРСИЯ ДАДЕ 12 НАХОДКИ И ПОЧТИ ВСИЧКИТЕ БЯХА ШУМ:
  //   · „Болката\n\nБолката" — заглавие, следвано от абзац, който почва със
  //     същата дума. Съвсем нормално в текст с подзаглавия.
  //   · „си си", „кой кой", „кое кое", „що що" — ПРАВИЛЕН български:
  //     „ако си си взела", „кой кой е", „разбираш кое кое е".
  //   Мярка, в която истинските находки се давят в позволеното, не е мярка.
  //   Затова: само на ЕДИН ред (без нов ред между двете) и без позволените.
  const ПОЗВОЛЕНИ = new Set(['си', 'кой', 'коя', 'кое', 'кои', 'що', 'ха', 'но']);
  const м2 = т.match(/(^|[\s(])([а-яА-Я]{2,})[ \t]+\2([\s.,;:!?)]|$)/g);
  if (м2) for (const x of м2) {
    const дума = (x.trim().split(/[ \t]+/)[0] || '').toLowerCase();
    if (ПОЗВОЛЕНИ.has(дума)) continue;
    находки.dubli.push({ где, поле, къс: x.trim().slice(0, 40) });
  }
  // ── 3. интервали
  const м3a = т.match(/[а-яА-Я]{2,}[.,;:!?][А-Я][а-я]/g);
  if (м3a) for (const x of м3a) находки.interval.push({ где, поле, вид: 'липсва интервал', къс: x });
  const м3b = т.match(/[а-яА-Я]  +[а-яА-Я]/g);
  if (м3b) for (const x of м3b) находки.interval.push({ где, поле, вид: 'двоен интервал', къс: x.replace(/ /g, '␣') });
  // ── 4. прав знак за кавичка
  const прави = (т.match(/"/g) || []).length;
  if (прави) находки.kavichki.push({ где, поле, брой: прави });
  // ── 5. двойна пунктуация (без многоточие „…" и без „..." )
  const м5 = т.match(/[,;:]{2,}|!{2,}|\?{2,}|(?<!\.)\.{2}(?!\.)/g);
  if (м5) for (const x of м5) находки.punkt.push({ где, поле, къс: x });
  // ── 6. главна буква в средата на дума
  const м6 = т.match(/[а-я]{2,}[А-Я][а-я]{2,}/g);
  if (м6) for (const x of м6) находки.glavna.push({ где, поле, дума: x });
}

// ── самопроверка: може ли изобщо да гръмне
function самопроверка() {
  const примамки = [
    ['latinica', 'кръвнa група', 'латинско a в кирилска дума'],
    ['dubli', 'дай му на на бебето', 'удвоено „на"'],
    ['interval', 'едно.Друго нещо', 'липсва интервал'],
    ['kavichki', 'той каза "нещо" там', 'прав знак за кавичка'],
    ['punkt', 'ето така,, после', 'двойна запетая'],
    ['glavna', 'кръвНата група', 'главна в средата']
  ];
  const из = [];
  for (const [вид, текст, опис] of примамки) {
    let хванат = false;
    const думи = текст.split(/[^а-яА-Яa-zA-Z]+/);
    if (вид === 'latinica') хванат = думи.some(д => д.length >= 2 && КИР.test(д) && ЛАТ.test(д) && !/^[A-Z]{2,}/.test(д));
    if (вид === 'dubli') хванат = /(^|[\s(])([а-яА-Я]{2,})\s+\2([\s.,;:!?)]|$)/.test(текст);
    if (вид === 'interval') хванат = /[а-яА-Я]{2,}[.,;:!?][А-Я][а-я]/.test(текст);
    if (вид === 'kavichki') хванат = текст.indexOf('"') >= 0;
    if (вид === 'punkt') хванат = /[,;:]{2,}|!{2,}|\?{2,}/.test(текст);
    if (вид === 'glavna') хванат = /[а-я]{2,}[А-Я][а-я]{2,}/.test(текст);
    из.push({ вид, опис, хванат });
  }
  // и обратната посока: чист български текст не бива да вдига НИЩО
  const чист = 'Първите нощи са мъгла. Ще ти кажат да спиш, докато бебето спи — и ще ти се стори невъзможно.';
  const чистДуми = чист.split(/[^а-яА-Яa-zA-Z]+/);
  const фалшиви =
    (чистДуми.some(д => д.length >= 2 && КИР.test(д) && ЛАТ.test(д)) ? 1 : 0) +
    (/(^|[\s(])([а-яА-Я]{2,})\s+\2([\s.,;:!?)]|$)/.test(чист) ? 1 : 0) +
    (/[а-яА-Я]{2,}[.,;:!?][А-Я][а-я]/.test(чист) ? 1 : 0) +
    (чист.indexOf('"') >= 0 ? 1 : 0) +
    (/[,;:]{2,}|!{2,}|\?{2,}/.test(чист) ? 1 : 0) +
    (/[а-я]{2,}[А-Я][а-я]{2,}/.test(чист) ? 1 : 0);
  return { примамки: из, фалшивиНаЧист: фалшиви };
}

