  function сурово(k) { try { return localStorage.getItem(k); } catch (e) { return null; } }
  function чети(k, п) { try { var v = JSON.parse(localStorage.getItem(k)); return v == null ? п : v; } catch (e) { return п; } }
  function изчакай(мс) { return new Promise(function (r) { setTimeout(r, мс); }); }
  // ⏳ Чакане по СЪБИТИЕ, не по будилник.
  //   Измерено (11.08, скрит таб): Chrome дави таймерите на страница в
  //   заден план до един път в минутата. Чакане „питай на всеки 40 ms"
  //   тогава струва цяла минута ВЪВ ВСЯКА точка — целият тест ставаше 12
  //   минути и изглеждаше забил. MutationObserver се обажда веднага щом
  //   надписът се смени, защото не е будилник; будилникът остава само като
  //   таван, за да не чакаме вечно, ако нищо не се случи.
  function дочакайПромяна(възел, макс) {
    return new Promise(function (res) {
      if (!възел) return res(false);
      var начало = възел.textContent, свършено = false;
      var ob = null, чс = null;
      function край(смени) {
        if (свършено) return; свършено = true;
        if (ob) ob.disconnect(); if (чс) clearTimeout(чс);
        res(смени);
      }
      try {
        ob = new MutationObserver(function () { if (възел.textContent !== начало) край(true); });
        ob.observe(възел, { childList: true, characterData: true, subtree: true });
      } catch (e) { ob = null; }
      чс = setTimeout(function () { край(възел.textContent !== начало); }, макс || 4000);
      if (възел.textContent !== начало) край(true);
    });
  }
  // кратък, ЧЕТИМ вид на стойност за колоната ПОЛУЧЕНО
  function кратко(x, n) {
    var s;
    try { s = (typeof x === 'string') ? x : JSON.stringify(x); } catch (e) { s = String(x); }
    if (s === undefined) s = String(x);
    n = n || 80;
    return s.length > n ? s.slice(0, n) + '…' : s;
  }

  // ── сцената: истинската стая, нарисувана извън погледа ─────
  // Контейнерът СЕ ЗАКАЧА в документа (offscreen), не виси в нищото:
  // част от картите мерят ширина при рисуване, а откачен елемент дава 0
  // и мълчаливо прескача половината си работа. „0 находки" от невиждана
  // стая не е чисто — то е 0 прегледани.
  var сцени = [];
  function сцена() {
    var d = document.createElement('div');
    d.setAttribute('data-bl-test', 'памет');
    d.style.cssText = 'position:fixed;left:-99999px;top:0;width:420px;height:800px;overflow:hidden;pointer-events:none';
    document.body.appendChild(d);
    сцени.push(d);
    return d;
  }
  function изчистиСцените() {
    сцени.forEach(function (d) { try { d.remove(); } catch (e) {} });
    сцени.length = 0;
    try { document.querySelectorAll('.prof-overlay').forEach(function (o) { o.remove(); }); } catch (e) {}
  }

  var броено = { стаи: 0, карти: 0, кликове: 0, бутони: 0 };

  function рисувай(стая) {
    var d = сцена();
    var г = null;
    try {
      if (!window.ROOM_FEATURES || !window.ROOM_FEATURES[стая]) г = 'няма такава стая в ROOM_FEATURES';
      else window.ROOM_FEATURES[стая](d);
    } catch (e) { г = String(e && e.message || e); }
    броено.стаи++;
    броено.карти += d.querySelectorAll('.jr-card').length;
    броено.бутони += d.querySelectorAll('button').length;
    return { корен: d, грешка: г };
  }
  // 🔴 НЕНАМЕРЕНОТО СЕ ЗАПИСВА. Ако утре някой преименува карта или бутон,
  //    търсенето връща null, кликът не става — и половината тестове
  //    позеленяват върху нищо, защото „нищо не се е променило в паметта" е
  //    точно това, което очакват някои редове. Затова всяко неуспешно
  //    търсене се брои и накрая става ЧЕРВЕН ред (З1), а не тишина.
  var ненамерени = [];
  function карта(корен, заглавие) {
    var всички = [].slice.call(корен.querySelectorAll('.jr-card'));
    for (var i = 0; i < всички.length; i++) {
      var h = всички[i].querySelector('.jr-title');
      if (h && h.textContent.indexOf(заглавие) >= 0) return всички[i];
    }
    ненамерени.push('карта „' + заглавие + '"');
    return null;
  }
  function бутон(к, текст) {
    if (!к) { ненамерени.push('бутон „' + текст + '" (картата липсва)'); return null; }
    var б = [].slice.call(к.querySelectorAll('button'));
    for (var i = 0; i < б.length; i++) if (б[i].textContent.indexOf(текст) >= 0) return б[i];
    ненамерени.push('бутон „' + текст + '"');
    return null;
  }
  function поЕтикет(к, етикет) {
    if (!к) { ненамерени.push('бутон с етикет „' + етикет + '" (картата липсва)'); return null; }
    var б = [].slice.call(к.querySelectorAll('button'));
    for (var i = 0; i < б.length; i++) if ((б[i].getAttribute('aria-label') || '') === етикет) return б[i];
    ненамерени.push('бутон с етикет „' + етикет + '"');
    return null;
  }
  function клик(б) { if (!б) return false; б.click(); броено.кликове++; return true; }

  // ── дневникът на тестовете ─────────────────────────────────
  // Всеки ред носи ИМЕ, ОЧАКВАНО и ПОЛУЧЕНО. „мина/падна" само по себе си
  // не казва нищо на човека, който чете доклада в 3 сутринта.
  function Дневник() { this.редове = []; }
  Дневник.prototype.Т = function (група, име, очаквано, получено, добре, тагове) {
    var т = тагове || {};
    this.редове.push({
      група: група, име: име,
      ОЧАКВАНО: кратко(очаквано, 110),
      ПОЛУЧЕНО: кратко(получено, 110),
      мина: !!добре,
      ключ: т.ключ || '',
      вид: т.вид || 'жив',            // 'жив' = мама може да го срещне днес
      бележка: т.бележка || ''
    });
  };
  Дневник.prototype.равни = function (група, име, очаквано, получено, тагове) {
    this.Т(група, име, очаквано, получено, кратко(очаквано, 110) === кратко(получено, 110), тагове);
  };

  // ═══════════════════════════════════════════════════════════
  //  ПРЕДУСЛОВИЯ — казани на глас, не скрити
  //  Калкулаторът на растежа отказва без пол (кривите на СЗО са различни),
  //  а „Първите пъти" не се рисува без рождена дата. Затова тестът слага
