    клик(минус); клик(минус); клик(минус);
    Д.равни(Г, 'пелени: броячът не пада под нулата', 0, (чети('bl_diapers', {})[ДНЕС] || {}).wet, { ключ: 'bl_diapers' });
    клик(плюс); клик(плюс); клик(плюс);   // оставяме нещо в паметта за копието

    // A8 · мерки (растеж)
    var кр = карта(б.корен, 'Калкулатор на растежа');
    var полета = кр ? кр.querySelectorAll('input') : [];
    if (полета.length >= 2) { полета[0].value = '7.4'; полета[1].value = '6'; }
    клик(бутон(кр, 'Изчисли'));
    var g = чети('bl_growth', []);
