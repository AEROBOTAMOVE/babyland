//      всяко време с:  BL_ПАМЕТ.етап   (и историята: BL_ПАМЕТ.етапи)
//      В СКРИТ таб (друг прозорец отгоре) браузърът дави таймерите до един
//      път в минутата — измерено. Затова чакането е по СЪБИТИЕ, не по
