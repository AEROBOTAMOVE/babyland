// ── живата база ──
function зареди(текст) {
  const ctx = { console: { log() {}, warn() {} }, JSON, Math, Date, RegExp, String, Number, Array, Object };
  ctx.window = ctx; ctx.self = ctx; vm.createContext(ctx);
  new vm.Script(текст || fs.readFileSync(KB, 'utf8')).runInContext(ctx);
  return ctx.KB.entries;
}
const карти = зареди();
const поId = new Map(карти.map(z => [z.id, z]));
const гол = h => String(h || '').replace(/<[^>]+>/g, ' ').replace(/\s+/g, ' ').trim();
const цял = z => гол(z.core) + ' ' + гол(z.tip) + ' ' + гол(z.follow);

// ── нормализация за сравнение на цитата: кавички, тирета, интервали ──
// Отрядът често преписва цитата с прави кавички или с друго тире. Това НЕ е
// гадаене — това е препис. Затова се сравнява по нормализиран вид, но САМО след
// като се докаже, че нормализацията не прави всичко да съвпада с всичко.
const норм = т => String(т)
  .replace(/[„“”«»"']/g, '')
  .replace(/[–—−]/g, '-')
  .replace(/\s+/g, ' ')
  .trim()
  .toLowerCase();

function провери(п) {
  const беди = [];
  const z = поId.get(п.id);
  if (!z) return ['картата не съществува'];
  if (z.ot !== undefined || z.do !== undefined || z.от !== undefined || z.до !== undefined)
    беди.push('картата ВЕЧЕ има възрастово поле');

  // ⭐ ФАЛСИФИКАТОРЪТ
  const цитат = String(п.citat || '');
  if (цитат.length < 15) беди.push('цитатът е твърде къс, за да доказва нещо (' + цитат.length + ' знака)');
  else if (норм(цял(z)).indexOf(норм(цитат)) < 0) беди.push('ЦИТАТЪТ ГО НЯМА В КАРТАТА — присъдата е гадаене, не четене');

  // граници
  const ot = п.ot, do_ = п.do;
  if (ot == null && do_ == null) беди.push('нито една граница');
  if (ot != null && (ot < -9 || ot > 240)) беди.push('ot извън −9..240: ' + ot);
  if (do_ != null && (do_ < -9 || do_ > 240)) беди.push('do извън −9..240: ' + do_);
  if (ot != null && do_ != null) {
    if (do_ < ot) беди.push('do < ot (' + ot + ' > ' + do_ + ')');
    else if (do_ - ot < 1 && ot > 0) беди.push('обхватът е под един месец — твърде тесен, картата ще потъне почти навсякъде');
  }
  return беди;
}

// ═══ САМОПРОВЕРКА ═══
function самопроверка() {
  // 🪤 ПОПРАВЕНО ПРИ ВТОРОТО ПУСКАНЕ: примамката ползваше `карти[0]`, а тя вече
  //    беше получила възрастово поле от ПЪРВОТО прилагане. Тогава „истински
  //    цитат МИНАВА" падаше — не защото правилото е счупено, а защото
  //    примамката е застояла. Мярка, чиято примамка не се обновява заедно с
  //    данните, обявява ЖИВ уред за счупен. Затова се търси карта БЕЗ поле.
  const z = карти.find(x => x.от === undefined && x.до === undefined && x.ot === undefined && x.do === undefined && цял(x).length > 120) || карти[0];
  const истински = цял(z).split(/(?<=[.!?])\s+/).find(s => s.length > 40) || цял(z).slice(0, 60);
  const случаи = [
    ['истински цитат МИНАВА', { id: z.id, citat: истински, ot: 0, do: 12 }, null],
    ['измислен цитат ПАДА', { id: z.id, citat: 'Това изречение никога не е било в тази карта и не може да бъде.', ot: 0, do: 12 }, 'ЦИТАТЪТ ГО НЯМА'],
    ['несъществуваща карта ПАДА', { id: 'няма-такава-карта-xyz', citat: истински, ot: 0, do: 12 }, 'не съществува'],
    ['обърнати граници ПАДАТ', { id: z.id, citat: истински, ot: 24, do: 3 }, 'do < ot'],
    ['без граница ПАДА', { id: z.id, citat: истински }, 'нито една граница'],
    ['къс цитат ПАДА', { id: z.id, citat: 'да', ot: 0, do: 12 }, 'твърде къс'],
    ['цитат с ДРУГИ кавички МИНАВА', { id: z.id, citat: истински.replace(/[„“]/g, '"'), ot: 0, do: 12 }, null]
  ];
  let паднали = 0; const редове = [];
  for (const [име, п, чакам] of случаи) {
    const беди = провери(п);
    const ок = чакам ? беди.some(b => b.indexOf(чакам) >= 0) : беди.length === 0;
    if (!ок) паднали++;
    редове.push([ок, име, беди.join(' | ').slice(0, 62) || '(чисто)']);
  }
  // ⚠️ и обратната посока за нормализацията: тя не бива да прави всичко еднакво
  const чуждо = цял(карти[Math.min(50, карти.length - 1)]).slice(0, 80);
  const нелепо = норм(цял(карти[0])).indexOf(норм(чуждо)) >= 0;
  редове.push([!нелепо, 'нормализацията НЕ прави всичко еднакво', нелепо ? '🔴 чужд текст съвпада!' : '(чисто)']);
  if (нелепо) паднали++;
  return { паднали, редове };
}

