// ═══════════════════════════════════════════════════════════
// 🏷️ ЗАГЛАВИЯ — записът си има заглавие-въпрос, но не си го знае
//
// Защо съществува (11.08):
//   Тестът за отговорите падаше 15 от 116. Отворих ги една по една и
//   всичките петнайсет бяха един и същ дефект:
//
//       Записът СЪЩЕСТВУВА. Отговорът е написан. Заглавието му е ТОЧНО
//       въпроса на майката. Но заглавието не е сред ключовете му, затова
//       матчърът не го намира.
//
//   Най-ясният случай: карта със заглавие „Хвърля всичко на пода“.
//   Майка пише „хвърля всичко на пода“. Приложението отговаря НЯМА.
//   Същото за „Нямам и минута за себе си“ и за „Кога мога пак да се движа“.
//
//   Поправих ги и после потърсих близнака в цялата база: 47 записа със
//   заглавие-въпрос, чиито думи не се срещат в ключовете им. Поправени 38.
//
//   Този пазач стои тук, за да не се върне. Всяка нова карта, писана с
//   хубаво заглавие и забравени ключове, ще светне още при следващото
//   пускане, не след като майката е останала без отговор.
//
// КАК СЕ ПУСКА (в конзолата на приложението):
//   var s=document.createElement('script'); s.src='dev/zaglavia.js'; document.body.appendChild(s);
//   BL_ЗАГЛАВИЯ.провери()
//
// ПЪТ НАЗАД: файлът само ЧЕТЕ KB. Не пипа нищо. Изтриването му не чупи
// нищо. НЕ е закачен в index.html.
// ═══════════════════════════════════════════════════════════
(function () {
  'use strict';

  // Служебни думички. Липсата им в ключовете не значи нищо.
  var СТОП = ('и или на в за да не се ми му си ги го ли от с по то е са как кога какво '
            + 'защо къде колко ако но че при след преди ти те аз ни им я '
            // и въпросителните местоимения — „Кое може втора употреба" се
            // оплакваше от „кое", а „кое" не е тема, а начало на изречение
            + 'кое кой коя кои някои някой нещо всичко').split(' ');

  // Само заглавия, които звучат като ВЪПРОС или като оплакване на майка.
  // Заглавие „Витамин Д“ не е въпрос — там ключовете носят цялата тежест.
  //
  // 🪤 БЕЗ \b — ТОВА Е КАПАН, В КОЙТО ПАДНАХ ТОЧНО ТУК.
  // Първата версия беше /\b(как|кога|…)\b/i и намери НУЛА въпроса от 383
  // заглавия. В JavaScript \b се дефинира през \w, а \w е само [A-Za-z0-9_].
  // Кирилицата не е \w, затова граница пред „К“ няма и изразът не хваща
  // никога. Мълчи — не гърми. Самопроверката долу го хвана; без нея щях
  // да кача пазач, който винаги казва „чисто“.
  // Затова: изричен клас за буква отляво и отдясно, не \b.
  var БУКВА = 'а-яёА-ЯЁa-zA-Z';
  var ВЪПРОС = new RegExp(
    '(^|[^' + БУКВА + '])(как|кога|какво|защо|къде|колко|мога|може|трябва|нормално|ли|искам|нямам)'
    + '([^' + БУКВА + ']|$)', 'i');

  function корен(w) { return w.slice(0, Math.max(4, w.length - 1)); }

  function провери(опции) {
    опции = опции || {};
    var KB = window.KB || {};
    var записи = KB.entries || KB.items || [];
    if (!записи.length) {
      return { ПРИСЪДА: '⚠ KB не е зареден — нищо не е проверено', ПРЕГЛЕДАНИ: 0 };
    }

    var прегледани = 0, с_въпрос = 0, находки = [];

    for (var i = 0; i < записи.length; i++) {
      var з = записи[i];
      прегледани++;
      var загл = String(з.title || '');
      if (!ВЪПРОС.test(загл)) continue;
      с_въпрос++;

      // 🎯 САМО ВЪПРОСЪТ, НЕ ПОДЗАГЛАВИЕТО.
      // Първото пускане даде 6 находки, но 4 бяха шум: заглавието
      // „Колко облечено за сън (по-малко е по-добре)" се оплакваше от
      // „малко" и „добре" — думи от пояснението в скоби, с които никоя
      // майка не търси. Същото за „— и в двете посоки е нормално" и
      // „(и защо някои прескачат)".
      // Затова режем при тире и при отваряща скоба: питаме само за
      // главното изречение, което Е въпросът на майката.
      var въпросът = загл.split(/\s[—–-]\s|\(/)[0];

      var ключове = (з.keys || []).join(' ').toLowerCase();
      var думи = (въпросът.toLowerCase().match(/[а-яё]{3,}/g) || [])
                   .filter(function (w) { return СТОП.indexOf(w) < 0; });
      if (!думи.length) continue;

      var липсват = думи.filter(function (w) { return ключове.indexOf(корен(w)) < 0; });

      // Една липсваща дума е шум (синоним, друг словоред). Две и повече
      // значи, че заглавието и ключовете говорят за различни неща.
      if (липсват.length >= 2) {
        находки.push({
          id: з.id, стая: з.room, заглавие: загл,
          липсват_в_ключовете: липсват.slice(0, 5),
          ключове_сега: (з.keys || []).length
        });
      }
    }

    var присъда = находки.length === 0 ? '✅ ЧИСТО' : '🔴 ' + находки.length + ' записа не се знаят по заглавие';

    // ── САМОПРОВЕРКА ── пазач, който не може да гръмне, е декорация.
    // Слагаме нарочно записа-примамка и гледаме дали го хваща.
    //
    // 🪤 12.08: този блок НЕ беше зад `if (!опции.вътрешно)`. Значи вътрешното
    // викане пак стигаше дотук, слагаше нова примамка и се викаше пак —
    // безкрайно. Не се въртеше вечно САМО защото стекът прелива, RangeError-ът
    // се хваща от `catch (e) {}` и всяко ниво тихо продължава.
    // Тоест „минаваше" през препълване на стека: десетки хиляди обиколки на
    // 383 записа за нищо. Под натоварване пазачът минаваше две минути и
    // изглеждаше заклещен.
    // Проверката е ЕДНА, най-отвън.
    var хвана = null, върнато = null;
    if (!опции.вътрешно) {
      var примамка = { id: '__примамка__', room: 'тест',
                       title: 'Колко пелени отиват на ден',
                       keys: ['нещо съвсем друго'] };
      записи.push(примамка);
      var пак = null;
      try { пак = провери({ вътрешно: true }); } catch (e) {}
      записи.pop();  // ← пътят назад, веднага
      хвана = !!(пак && (пак.НАХОДКИ || []).some(function (n) { return n.id === '__примамка__'; }));
      върнато = записи.indexOf(примамка) < 0;
    }

    if (!опции.вътрешно) {
      console.log('%c🏷️ ЗАГЛАВИЯ', 'font-weight:bold;font-size:15px');
      console.log('прегледани записа: ' + прегледани + ' · от тях заглавие-въпрос: ' + с_въпрос);
      console.log(присъда);
      if (находки.length) console.table(находки.slice(0, 40));
      console.log('самопроверка: примамката ' + (хвана ? 'беше хваната ✅' : 'НЕ беше хваната 🔴')
                  + ' · базата ' + (върнато ? 'върната ✅' : 'ОСТАНА МРЪСНА 🔴'));
    }

    return {
      ПРИСЪДА: присъда,
      ПРЕГЛЕДАНИ: прегледани,
      ОТ_ТЯХ_ВЪПРОСИ: с_въпрос,
      ПАДНАЛИ: находки.length,
      НАХОДКИ: находки,
      САМОПРОВЕРКА: опции.вътрешно ? null : {
        примамка_хваната: !!хвана,
        базата_върната: върнато,
        мина: !!хвана && върнато
      }
    };
  }

  window.BL_ЗАГЛАВИЯ = { провери: провери };
  window.BL_TITLES = window.BL_ЗАГЛАВИЯ;
  console.log('🏷️ зареден. Пусни:  BL_ЗАГЛАВИЯ.провери()');
})();
