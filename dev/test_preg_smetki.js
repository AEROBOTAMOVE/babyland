// ═══════════════════════════════════════════════════════════
// 🤰 ЕДНА СМЕТКА ЗА СЕДМИЦАТА — изпитание на BL_PREG (js/data.js)
//
// Тук се доказва ТОЧНО това, което новата сметка трябва да поправи, и се
// показва, че СТАРАТА наистина греши — иначе зелените не значат нищо.
//
// ИЗМЕРЕНОТО, което роди BL_PREG (5760 мига = всеки час от 240 дни):
//   старият израз се разминава с календара в 1.6% от миговете, винаги
//   между 00:00 и 02:00, и то на всеки седми ден;
//   в самия ден на последната менструация, между 00:00 и 02:00, дава −1.
//
// ПУСКАНЕ: node dev/test_preg_smetki.js
// ПЪТ НАЗАД: файлът само ЧЕТЕ проекта.
// ═══════════════════════════════════════════════════════════
const fs = require('fs');
const vm = require('vm');
const path = require('path');
process.chdir(path.resolve(__dirname, '..'));

const ctx = { console: { log() {} }, JSON, Math, Date, RegExp, String, Number, Array, Object };
ctx.window = ctx; ctx.globalThis = ctx; ctx.self = ctx;
vm.createContext(ctx);
new vm.Script(fs.readFileSync('js/data.js', 'utf8')).runInContext(ctx);
const P = ctx.BL_PREG;
if (!P || !P.седмица) { console.log('🔴 няма BL_PREG'); process.exit(2); }

// точно старият израз, преписан от 13-те места
const старо = (пм, сега) => Math.floor((сега - new Date(пм)) / 604800000);

let паднали = 0, общо = 0;
const пров = (текст, условие) => { общо++; if (!условие) паднали++; console.log('     ' + (условие ? '✅' : '🔴') + ' ' + текст); };

console.log('🤰 ЕДНА СМЕТКА ЗА СЕДМИЦАТА\n');
const ПМ = '2026-01-01';

// ── 1. основното: съвпада с ръчно пресметнатото ──
console.log('  ── ръчно пресметнати примери ──');
пров('ПМ 1 ян, днес 25 авг → 33 пълни седмици (236 дни / 7)',
  P.седмица(ПМ, new Date(2026, 7, 25, 14, 0)) === 33);
пров('в самия ден на ПМ, по обяд → 0', P.седмица(ПМ, new Date(2026, 0, 1, 12, 0)) === 0);
пров('6 дни след ПМ → 0', P.седмица(ПМ, new Date(2026, 0, 7, 12, 0)) === 0);
пров('7 дни след ПМ → 1', P.седмица(ПМ, new Date(2026, 0, 8, 12, 0)) === 1);
пров('терминът е 8 октомври 2026', (() => { const т = P.термин(ПМ);
  return т.getFullYear() === 2026 && т.getMonth() === 9 && т.getDate() === 8; })());

// ── 2. ЧАСЪТ НА ДЕНЯ НЕ БИВА ДА ВЛИЯЕ ──
console.log('\n  ── един и същ ден, различен час → едно и също число ──');
for (const ден of [[2026, 0, 1], [2026, 0, 8], [2026, 2, 12], [2026, 7, 25]]) {
  const часове = [];
  for (let ч = 0; ч < 24; ч++) часове.push(P.седмица(ПМ, new Date(ден[0], ден[1], ден[2], ч, 30)));
  const еднакви = часове.every(x => x === часове[0]);
  пров(ден[2] + '.' + (ден[1] + 1) + ' — и в 24-те часа дава ' + часове[0], еднакви);
}

// ── 3. СТАРАТА сметка НАИСТИНА греши (иначе горното не доказва нищо) ──
console.log('\n  ── доказваме, че старият израз греши ──');
const вНощта = new Date(2026, 0, 1, 1, 0);
пров('старата дава −1 в 01:00 на деня на ПМ (тоест отрицателна седмица)',
  старо(ПМ, вНощта) === -1);
пров('новата дава 0 в същия миг', P.седмица(ПМ, вНощта) === 0);

let разлики = 0, мига = 0;
for (let д = 0; д < 240; д++) for (let ч = 0; ч < 24; ч++) {
  const сега = new Date(2026, 0, 1 + д, ч, 30); мига++;
  if (старо(ПМ, сега) !== P.седмица(ПМ, сега)) разлики++;
}
console.log('        измерено сега: ' + мига + ' мига · разминават се ' + разлики +
            ' (' + (100 * разлики / мига).toFixed(1) + '%)');
пров('разминаването е РЕАЛНО (иначе смяната е излишна)', разлики > 0);
пров('и не е поголовно (новата не обръща всичко наопаки)', разлики < мига * 0.1);

// ── 4. „остават N дни" — една сметка вместо ceil срещу round ──
console.log('\n  ── дните до термина ──');
пров('в деня на термина остават 0', P.доТермина(ПМ, new Date(2026, 9, 8, 22, 0)) === 0);
пров('ден преди термина остава 1', P.доТермина(ПМ, new Date(2026, 9, 7, 0, 30)) === 1);
пров('часът пак не влияе', (() => {
  const с = []; for (let ч = 0; ч < 24; ч++) с.push(P.доТермина(ПМ, new Date(2026, 8, 30, ч, 15)));
  return с.every(x => x === с[0]); })());

// ── 5. счупени входове не бива да гърмят ──
console.log('\n  ── счупени входове ──');
пров('празно → null', P.седмица('') === null && P.доТермина('') === null);
пров('глупост → null', P.седмица('не-е-дата') === null);
пров('обект Date също работи', P.седмица(new Date(2026, 0, 1), new Date(2026, 0, 8, 12)) === 1);

console.log('\n  ПРОВЕРКИ: ' + общо + ' · ' + (паднали ? '🔴 ПАДНАЛИ: ' + паднали : '✅ всички минаха'));
process.exit(паднали ? 1 : 0);
