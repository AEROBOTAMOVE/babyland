// КАК: ползва богатия кукленски DOM на пясъчника (сверен срещу живия
//   браузър: 5 от 5 съвпаднаха) и прекарва целия корпус на „гласът на
//   майката" през ИСТИНСКИЯ ред на вратите.
//
// КАКВО ЛОВИ (само неща, които се четат от текста, без гадаене):
//   1. спешен въпрос без нито едно ДЕЙСТВИЕ (112 / лекар / веднага)
//   2. текст за СЛЕД РАЖДАНЕ, даден в стая „Бременност"
//   3. текст за БРЕМЕННОСТ, даден в детска стая
//   4. празен или подозрително къс отговор
