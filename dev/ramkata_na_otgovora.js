'use strict';
const path = require('path');
const fs = require('fs');
const КОРЕН = path.resolve(__dirname, '..');
const { zaredi } = require('./pyasachnik.js');
const ВСИЧКИ = process.argv.includes('--vsichki');

// ── вземаме корпуса от „гласът на майката", за да не се дублира ──
const изв = fs.readFileSync(path.join(КОРЕН, 'dev/glasat_na_mama.js'), 'utf8');
const нач = изв.indexOf('const В = [');
const кр = изв.indexOf('];', нач);
if (нач < 0 || кр < 0) { console.log('🔴 корпусът в glasat_na_mama.js не се намира — СЛЯП'); process.exit(2); }
let В;
try { В = eval(изв.slice(нач + 'const В = '.length, кр + 1)); } catch (e) { console.log('🔴 корпусът не се чете: ' + e.message.slice(0, 90)); process.exit(2); }
if (!Array.isArray(В) || В.length < 100) { console.log('🔴 корпусът дава ' + (В || []).length + ' въпроса — СЛЯП'); process.exit(2); }

const списък = ВСИЧКИ ? В : В.slice(0, 40);
console.log('');
console.log('🖼️ РАМКАТА НА ОТГОВОРА');
console.log('');
console.log('   въпроси: ' + списък.length + ' от ' + В.length + (ВСИЧКИ ? '' : '   (--vsichki за целия)'));
console.log('');

const СЛЕД_РАЖДАНЕ = /след раждане|следродил|лохи|откакто роди|родих/i;
// 🪤 ПЪРВАТА МИ ВЕРСИЯ ТУК ИЗВИКА ВЪЛК 6 ПЪТИ ОТ 40 — и всичките шест
//   бяха МОИ грешки, не дефекти. Бях сложил „акушер-гинеколог" за белег на
//   бременност. А за РОДИЛА жена акушер-гинекологът е точно верният лекар:
//   „обади се днес на акушер-гинеколога си" е правилният съвет при
//   подут крак след раждане (тромбоза).
//   Пазач, който вика вълк 15% от времето, не се чете. Затова тук стоят
//   САМО белези, които НЕ МОГАТ да значат нищо друго.
const ЗА_БРЕМЕННА = /при бременност|бъдеща майк|в коя седмица си|докато чакаш бебето|в корема ти/i;
const ДЕЙСТВИЕ = /112|лекар|спешн|веднага|сега|незабавно|бърза помощ|педиатър/i;

let i = 0;
const находки = [];
let прочетени = 0;

function следващ() {
  if (i >= списък.length) return край();
  const [въпрос, стая, вид] = списък[i++];
  let W;
  try { W = zaredi(null, { домБогат: true }); } catch (e) { находки.push({ въпрос, б: 'пясъчникът не се зареди: ' + e.message.slice(0, 60) }); return следващ(); }
  try { W.MamaHelper.open(стая); W.MamaHelper.ask(въпрос); }
  catch (e) { находки.push({ въпрос, стая, б: 'ГРЪМНА: ' + e.message.slice(0, 70) }); return следващ(); }
  setTimeout(() => {
    const c = W.document._поId['roChat'];
    const мехури = c ? c.children.slice(1).map(r => (r.всичкиятТекст || '').replace(/\s+/g, ' ')) : [];
    const текст = мехури.join(' ').trim();
    прочетени++;
    const б = [];
    if (!текст) б.push('ПРАЗЕН ОТГОВОР');
    else if (текст.length < 60) б.push('подозрително къс (' + текст.length + ' знака)');
    // 🕯️ ЗАГУБАТА Е ИЗКЛЮЧЕНИЕ, И ТО НАРОЧНО.
    //   „загубих бебето" вдига вратата loss, чийто отговор е „Тук съм. Ела,
    //   седни за минутка… Няма да те питам нищо." Няма 112 — и НЕ ТРЯБВА да
    //   има. На жена, чието дете е починало, „обади се на 112" е жестокост.
    //   Първата ми версия го броеше за дефект. Не е.
    const ЗАГУБА = /загубих|почина|няма го вече|не оцеля|помятам|помятане/i;
    if (вид === 'флаг' && текст && !ДЕЙСТВИЕ.test(текст) && !ЗАГУБА.test(въпрос)) б.push('спешен въпрос БЕЗ действие (няма 112/лекар/веднага)');
    if (стая === 'Бременност' && СЛЕД_РАЖДАНЕ.test(текст)) б.push('текст за СЛЕД РАЖДАНЕ в стая Бременност');
    if (/бебе|дете/.test(стая.toLowerCase()) === false && стая !== 'Бременност' && ЗА_БРЕМЕННА.test(текст) && !/бремен/i.test(въпрос)) {
      б.push('текст за БРЕМЕННА извън стая Бременност');
    }
    if (б.length) {
      находки.push({ въпрос, стая, б: б.join(' · '), извадка: текст.slice(0, 130) });
      console.log('   🔴 [' + стая + '] ' + въпрос);
      console.log('       ' + б.join(String.fromCharCode(10) + '       '));
      console.log('       « ' + текст.slice(0, 130) + ' »');
    }
    следващ();
  }, 2200);
}

function край() {
  console.log('');
  // 🪞 самопроверка: непрочетени отговори значи, че уредът не е стигнал дотам
  if (прочетени < списък.length) {
    console.log('   🔴 прочетени само ' + прочетени + ' от ' + списък.length + ' — СЛЯП');
    process.exit(2);
  }
  if (находки.length) {
    console.log('   🔴 НАХОДКИ: ' + находки.length + ' от ' + списък.length);
    process.exit(1);
  }
  console.log('   ✅ всичките ' + списък.length + ' отговора говорят на правилната жена');
  process.exit(0);
}

следващ();
