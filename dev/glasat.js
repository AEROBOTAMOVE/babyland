// ═══════════════════════════════════════════════════════════
// 🫀 ГЛАСЪТ — редовете, които правят приложението различно от брошура
//
// ЗАЩО СЪЩЕСТВУВА: на 19.08 проход по „изглаждане на тона" махна 8 реда от
// вида „ако вътрешният глас казва, че нещо не е наред — това е достатъчна
// причина да се обадиш". Мярката за КОНКРЕТИКА (числа, институции, спешни
// думи) ги пропусна — те нямат нито едно число. И точно те са разликата
// между помощник и медицинска листовка.
//
// Изглаждането е добро, докато маха ПЪЛНЕЖ. Стане ли да маха ВАЛИДАЦИЯ,
// приложението изстива, а числата остават зелени.
//
// КАКВО БРОИ (четири семейства):
//   1. ДОВЕРИЕ В УСЕТА    — вътрешният глас, майчинският инстинкт
//   2. РАЗРЕШЕНИЕ          — нормално е, не си лоша майка, не е твоя вина
//   3. БЕЗ ИЗИСКВАНЕ       — не си длъжна, имаш право да спреш, нормален избор
//   4. ПРИЗНАВАНЕ НА ТЕЖКО — трудно е, изтощително е, знам че е страшно
//
// ПУСКАНЕ: node dev/glasat.js [<комит-за-сравнение>]
// ПЪТ НАЗАД: файлът само ЧЕТЕ.
// ═══════════════════════════════════════════════════════════
const fs = require('fs');
const path = require('path');
const { execSync } = require('child_process');
process.chdir(path.resolve(__dirname, '..'));
const БАЗА = process.argv[2] || 'HEAD';
const g = c => { try { return execSync(c, { encoding: 'utf8', maxBuffer: 1e9 }); } catch (e) { return ''; } };

const СЕМЕЙСТВА = [
  { име: 'доверие в усета', re: /(вътрешния[т]? глас|вътрешно усещане|майчински[ят]? инстинкт|нещо не е наред|вярвай на усета|вярвай на себе си|ти познаваш детето|твоето усещане|усещаш ли)/gi },
  { име: 'разрешение', re: /(нормално е|не си лоша майка|не е твоя вина|не си виновна|случва се на всички|няма перфектн|достатъчно добра)/gi },
  { име: 'без изискване', re: /(не си длъжна|имаш право да|нормален избор|не е пропуск|ти решаваш|може и да не)/gi },
  { име: 'признаване на тежко', re: /(трудно е|изтощително е|знам, че е страшно|знам колко|тежко е|няма лесен начин|боли и това е)/gi }
];

function брой(тела) {
  const из = {};
  for (const с of СЕМЕЙСТВА) из[с.име] = 0;
  for (const k in тела) {
    const t = String(тела[k]);
    for (const с of СЕМЕЙСТВА) { с.re.lastIndex = 0; из[с.име] += (t.match(с.re) || []).length; }
  }
  return из;
}

const сега = {}, преди = {};
for (const f of fs.readdirSync('lib')) {
  if (!f.endsWith('.json') || /BAK|ARCHIVE|index/.test(f)) continue;
  try { const d = JSON.parse(fs.readFileSync('lib/' + f, 'utf8')); for (const k in d) сега[k] = d[k]; } catch (e) {}
  try { const d = JSON.parse(g('git show ' + БАЗА + ':lib/' + f)); for (const k in d) преди[k] = d[k]; } catch (e) {}
}
const kbСега = fs.readFileSync('js/kb.js', 'utf8');
const kbПреди = g('git show ' + БАЗА + ':js/kb.js');
сега['__kb'] = kbСега; if (kbПреди) преди['__kb'] = kbПреди;

// ═══════════════ 🛡️ САМОПРОВЕРКА (01.09.2026, ВЪЛНА 1.3) ═══════════════
//
// НАЙ-ТИХИЯТ НАЧИН ТОЗИ УРЕД ДА ЛЪЖЕ: „преди" се вади с `git show`, а g()
// гълта всяка грешка и връща празен низ. Няма ли git, сменен ли е комитът,
// преименувана ли е папката — `преди` става ПРАЗНО, всяко „преди" е нула,
// нищо не може да е паднало и уредът пише „✅ гласът е запазен". Зелено при
// нула сравнени. Затова:
//   1. долна граница на БРОЯ статии в ДВЕТЕ снимки (не само в сегашната);
//   2. три примамки през СЪЩАТА функция брой() — намира ли известните фрази,
//      мълчи ли на текст без тях, и вижда ли нарочно направена ЗАГУБА.
(function самопроверкаНаГласа() {
  const ДОЛНА_СТАТИИ = 500, ДОЛНО_ОБЩО = 100;
  const редове = [];
  let червено = 0;

  const нСега = Object.keys(сега).length - 1, нПреди = Object.keys(преди).length - 1;
  if (нСега < ДОЛНА_СТАТИИ) { червено++; редове.push(['🔴', 'сегашните статии са ' + нСега + ' — под ' + ДОЛНА_СТАТИИ]); }
  else редове.push(['✅', 'сегашни статии ' + нСега + ' ≥ ' + ДОЛНА_СТАТИИ]);
  if (нПреди < ДОЛНА_СТАТИИ) {
    червено++;
    редове.push(['🔴', 'СНИМКАТА „ПРЕДИ" Е ' + нПреди + ' статии — git не е дал нищо. ' +
                 'Тогава „нищо не е паднало" е вярно по конструкция, не по измерване.']);
  } else редове.push(['✅', 'снимка „преди" ' + нПреди + ' ≥ ' + ДОЛНА_СТАТИИ]);

  // примамка 1: текст с по една фраза от всяко семейство
  const примамка = {
    едно: 'вътрешният глас ти казва нещо',
    две: 'нормално е да се чувстваш така',
    три: 'не си длъжна да го правиш',
    четири: 'трудно е и това е истина'
  };
  const б1 = брой(примамка);
  const намерени = Object.keys(б1).filter(k => б1[k] > 0).length;
  if (намерени === СЕМЕЙСТВА.length) редове.push(['✅', 'примамка: подставеният топъл текст пали и четирите семейства']);
  else { червено++; редове.push(['🔴', 'примамка: подставеният топъл текст пали само ' + намерени + ' от ' + СЕМЕЙСТВА.length + ' семейства']); }

  // примамка 2 (обратната посока): текст без нито една фраза
  const б2 = брой({ едно: 'зелен трактор пее на покрива в четвъртък', две: 'три лехи и една престилка' });
  const шум = Object.keys(б2).reduce((с, k) => с + б2[k], 0);
  if (шум === 0) редове.push(['✅', 'примамка (обратната посока): безразличният текст не пали нищо']);
  else { червено++; редове.push(['🔴', 'примамка: безразличният текст пали ' + шум + ' попадения — мярката брои шум']); }

  // примамка 3: нарочна ЗАГУБА — точно това, което уредът съществува да лови
  const преди3 = брой(примамка);
  const сега3 = брой({ едно: 'вътрешният глас ти казва нещо' });
  const спад = Object.keys(преди3).reduce((с, k) => с + Math.max(0, преди3[k] - сега3[k]), 0);
  if (спад >= 3) редове.push(['✅', 'примамка: нарочно махнатите редове излизат като спад (−' + спад + ')']);
  else { червено++; редове.push(['🔴', 'примамка: нарочна загуба даде спад ' + спад + ' — уредът НЕ вижда махнат глас']); }

  console.log('  САМОПРОВЕРКА (иначе „гласът е запазен" не значи нищо):');
  редове.forEach(([з, т]) => console.log('     ' + з + ' ' + т));
  console.log('');
  if (червено) { console.log('🔴 САМОПРОВЕРКАТА ПАДА — таблицата долу НЕ СЕ БРОИ.'); process.exit(1); }
})();

const a = брой(преди), b = брой(сега);
console.log('🫀 ГЛАСЪТ — срещу ' + БАЗА + '\n');
console.log('  статии: ' + (Object.keys(преди).length - 1) + ' → ' + (Object.keys(сега).length - 1) + '\n');
let паднали = 0, общоA = 0, общоB = 0;
console.log('  семейство                 преди   сега');
for (const с of СЕМЕЙСТВА) {
  const д = b[с.име] - a[с.име];
  общоA += a[с.име]; общоB += b[с.име];
  if (д < 0) паднали += -д;
  console.log('  ' + с.име.padEnd(24) + String(a[с.име]).padStart(5) + String(b[с.име]).padStart(8) +
    (д < 0 ? '   🔴 ' + д : д > 0 ? '   ✅ +' + д : '   ='));
}
console.log('  ' + '─'.repeat(46));
console.log('  ОБЩО' + String(общоA).padStart(24) + String(общоB).padStart(8) +
  (общоB < общоA ? '   🔴 −' + (общоA - общоB) : '   ✅'));

if (паднали) {
  console.log('\n  КОИ СТАТИИ СА ИЗГУБИЛИ ГЛАС:');
  const списък = [];
  for (const k in сега) {
    if (k === '__kb' || !(k in преди) || преди[k] === сега[k]) continue;
    let ap = 0, bp = 0;
    for (const с of СЕМЕЙСТВА) {
      с.re.lastIndex = 0; ap += (String(преди[k]).match(с.re) || []).length;
      с.re.lastIndex = 0; bp += (String(сега[k]).match(с.re) || []).length;
    }
    if (bp < ap) списък.push({ k, ap, bp });
  }
  списък.sort((x, y) => (y.ap - y.bp) - (x.ap - x.bp));
  списък.slice(0, 15).forEach(x => console.log('   🔴 ' + x.k.padEnd(22) + x.ap + ' → ' + x.bp));
  console.log('\n  Лек: върни махнатите редове. Изглаждането маха ПЪЛНЕЖ, не ВАЛИДАЦИЯ.');
  process.exit(1);
}
console.log('\n  ✅ гласът е запазен');
