// 👯 БЛИЗНАЦИ — две карти, които се борят за един и същ въпрос
//
// ЗАЩО (26.08.2026, ИЗМЕРЕНО): dev/klyuch_doma.js показа 17 въпроса,
// които отиват при ЧУЖДА карта. Погледнах ги един по един и почти
// всички имаха еднакъв вид: „никнат зъби" се пада между lb-nikat-zabi
// и zd-teeth; „колко мляко" между zh-milk-qty и mb-kolko-mliako; „не
// пълзи" между lb2-syada-palzi и rz-palzene. Тоест дефектът НЕ е в
// подредбата — той е в това, че ДВЕ КАРТИ казват, че отговарят на
// един и същи въпрос. Подредбата после хвърля ези-тура.
//
// ЗАЩО Е ВАЖНО ЗА МАЙКАТА: тя вижда едната карта и никога не научава,
// че другата съществува. Съдържанието е написано и е невидимо.
//
// 🪤 ВНИМАНИЕ — НЕ ВСЕКИ БЛИЗНАК Е ДЕФЕКТ. Две карти за никнещи зъби в
//    РАЗЛИЧНИ стаи може да са нарочни: една при „Моето бебе" (какво да
//    очаквам) и една при „Здраве и SOS" (боли го, какво правя сега).
//    Затова уредът РАЗДЕЛЯ близнаците в една стая от тези през стаи и
//    НЕ обявява вторите за грешка.
//
// ПУСКАНЕ: node dev/bliznaci.js            (само общо)
//          node dev/bliznaci.js --vsichki  (всички двойки)
// ═══════════════════════════════════════════════════════════
const fs = require('fs');
const vm = require('vm');
const path = require('path');
const КОРЕН = path.resolve(__dirname, '..');

function зареди() {
  const ctx = { console: { log() {}, warn() {} }, JSON, Math, Date, RegExp, String, Number, Array, Object };
  ctx.window = ctx; ctx.globalThis = ctx; ctx.self = ctx;
  vm.createContext(ctx);
  new vm.Script(fs.readFileSync(path.join(КОРЕН, 'js/kb.js'), 'utf8')).runInContext(ctx);
  return ctx.BL_KB || ctx.KB;   // 🪤 картите са в KB.entries, не в самия KB
}

const база = зареди();
const записи = Array.isArray(база) ? база : ((база && база.entries) || []);
if (!записи.length) { console.log('🔴 не мога да заредя базата'); process.exit(1); }

// ── кой ключ при кои карти живее ──
const поКлюч = new Map();
let бройКлючове = 0;
for (const з of записи) {
  for (const к of (з.keys || [])) {
    const н = String(к).trim().toLowerCase();
    if (!н) continue;
    бройКлючове++;
    if (!поКлюч.has(н)) поКлюч.set(н, []);
    const списък = поКлюч.get(н);
    if (!списък.some(x => x.id === з.id)) списък.push({ id: з.id, room: з.room, title: з.title });
  }
}

// ── двойки карти, които делят поне един ключ ──
const двойки = new Map();
for (const [к, карти] of поКлюч) {
  if (карти.length < 2) continue;
  for (let i = 0; i < карти.length; i++) for (let j = i + 1; j < карти.length; j++) {
    const ключДвойка = [карти[i].id, карти[j].id].sort().join(' ⇄ ');
    if (!двойки.has(ключДвойка)) двойки.set(ключДвойка, { а: карти[i], б: карти[j], общи: [] });
    двойки.get(ключДвойка).общи.push(к);
  }
}

const всички = [...двойки.values()].sort((x, y) => y.общи.length - x.общи.length);

// 🪤 ПЪРВАТА ВЕРСИЯ НА ТОЗИ УРЕД СЛИВАШЕ ДВА РАЗЛИЧНИ ДЕФЕКТА в едно число.
//    Погледнах 26-те двойки с око и се оказаха ДВА вида:
//      · „Коликите" ⇄ „Колики ли са това?" — ЕДНА И СЪЩА тема, написана два
//        пъти. Тук поправката е сливане или ясно разделяне на ролите.
//      · „Кръвната захар в бременността" ⇄ „Секс при бременност" — нямат нищо
//        общо, но ДЕЛЯТ ключа „ще навреди ли на бебето". Тук поправката е точно
//        обратната: ключът е ЛАКОМ и се маха от картата, на която не принадлежи.
//    Едно число за двете кара да се търси грешната поправка.
const думи = т => new Set(String(т || '').toLowerCase()
  .replace(/[^а-яa-z0-9 ]/g, ' ').split(/s+/).filter(д => д.length > 3));
const близостЗаглавия = (а, б) => {
  const х = думи(а), у = думи(б);
  if (!х.size || !у.size) return 0;
  let общи = 0; for (const д of х) if (у.has(д)) общи++;
  return общи / Math.min(х.size, у.size);
};
for (const д of всички) {
  д.близост = близостЗаглавия(д.а.title, д.б.title);
  д.вид = (д.общи.length >= 2 || д.близост >= 0.34) ? 'близнак' : 'лаком';
}

const еднаСтая = всички.filter(д => д.а.room === д.б.room);
const презСтаи = всички.filter(д => д.а.room !== д.б.room);
const близнаци = всички.filter(д => д.вид === 'близнак');
const лакоми  = всички.filter(д => д.вид === 'лаком');

console.log('');
console.log('👯 БЛИЗНАЦИ — карти, които се борят за един въпрос');
console.log('');
console.log('  ПРЕГЛЕДАНИ  : ' + записи.length + ' карти · ' + бройКлючове + ' ключа');
console.log('  двойки общо : ' + всички.length + '   (в една стая ' + еднаСтая.length + ' · през стаи ' + презСтаи.length + ')');
console.log('');
console.log('  🔴 ИСТИНСКИ БЛИЗНАЦИ : ' + близнаци.length + '   една тема, написана два пъти');
console.log('       поправка: слей ги или им дай ЯСНО различни роли');
console.log('  🟠 ЛАКОМИ КЛЮЧОВЕ    : ' + лакоми.length + '   различни теми, откраднат общ ключ');
console.log('       поправка: махни ключа от картата, на която НЕ принадлежи');
console.log('');

const ВСИЧКИ = process.argv.includes('--vsichki');
const покажи = (заглавие, списък) => {
  if (!списък.length) return;
  console.log('  ── ' + заглавие + ' (' + списък.length + ') ──');
  for (const д of списък.slice(0, ВСИЧКИ ? 9999 : 14)) {
    const еднаЛи = д.а.room === д.б.room ? '🔴 една стая' : '🟡 през стаи';
    console.log('     ' + String(д.общи.length).padStart(3) + ' общи · ' + еднаЛи +
                ' · заглавия ' + Math.round(д.близост * 100) + '% еднакви');
      console.log('         [' + д.а.room + '] ' + д.а.id + '  „' + (д.а.title || '') + '"');
      console.log('         [' + д.б.room + '] ' + д.б.id + '  „' + (д.б.title || '') + '"');
    console.log('         общи: ' + д.общи.slice(0, 6).map(x => '„' + x + '"').join(' '));
  }
  if (!ВСИЧКИ && списък.length > 14) console.log('     … и още ' + (списък.length - 14) + '  (node dev/bliznaci.js --vsichki)');
  console.log('');
};
покажи('ИСТИНСКИ БЛИЗНАЦИ', близнаци);
покажи('ЛАКОМИ КЛЮЧОВЕ', лакоми);

// ── САМОПРОВЕРКА: уредът трябва да УМЕЕ да гръмне ──
// Без нея „0 близнака" не значи нищо — може просто да не гледа никъде.
(function самопроверка() {
  const примамка = [
    { id: 'ПРИМАМКА-А', room: 'Стая', title: 'А', keys: ['еднакъв ключ', 'свой а'] },
    { id: 'ПРИМАМКА-Б', room: 'Стая', title: 'Б', keys: ['еднакъв ключ', 'свой б'] },
    { id: 'ПРИМАМКА-В', room: 'Друга', title: 'В', keys: ['еднакъв ключ'] }
  ];
  const м = new Map();
  for (const з of примамка) for (const к of з.keys) {
    if (!м.has(к)) м.set(к, []); м.get(к).push(з);
  }
  const хванати = [...м.values()].filter(x => x.length > 1);
  const вЕдна = хванати.length && хванати[0].filter(x => x.room === 'Стая').length === 2;
  console.log('  самопроверка: примамката хваната ' + (хванати.length ? '✅' : '🔴') +
              ' · разделя стаите ' + (вЕдна ? '✅' : '🔴'));
})();

// ── ИЗХОДЕН КОД ──
// 🔴 ПЪРВАТА ВЕРСИЯ НА ТОЗИ РЕД БЕШЕ `process.exit(еднаСтая.length ? 0 : 0)` —
//    тоест НУЛА при всяко положение. Уред, който не може да гръмне, не е
//    пазач, а украса; в този проект вече е плащано за такъв (тест, който
//    се самоизключваше след regex, изяде 10 проверки без нито едно червено).
//    dev/pazachi.js сам открива всеки нов файл в dev/ и чете кода на изхода
//    му — значи този ред решава дали близнаците изобщо се пазят.
//
// ЗАЩО ПРАГ, А НЕ НУЛА: днес има истински дълг (близнаци, писани преди
//    уредът да съществува). Праг на НУЛА би светил червено вечно и щеше да
//    бъде заглушен — а заглушен пазач е по-лош от липсващ. Затова прагът е
//    ЗАМРАЗЕНОТО ДНЕШНО ЧИСЛО: не пречи на заварения дълг, но пламва в мига,
//    в който някой добави НОВ близнак. Дългът се вижда в изхода всеки път.
//    Свали ли се дългът — прагът се сваля СЪЩО, ръчно, тук.
const ПРАГ = { близнаци: Number(process.env.BL_BLIZNACI_PRAG || 0) };

const надхвърля = близнаци.length > ПРАГ.близнаци;
if (надхвърля) {
  console.log('  🔴 НАХОДКА: истинските близнаци станаха ' + близнаци.length +
              ' при замразен праг ' + ПРАГ.близнаци + '.');
  console.log('     Или слей новата двойка, или ѝ дай ясно различни ключове.');
} else if (близнаци.length < ПРАГ.близнаци) {
  console.log('  🟢 близнаците паднаха на ' + близнаци.length + ' (праг ' + ПРАГ.близнаци +
              '). Свали прага в dev/bliznaci.js, за да не се върне дългът тихо.');
} else {
  console.log('  ✅ близнаците са ' + близнаци.length + ' — точно замразения праг. Нов не е добавен.');
}
console.log('');
process.exit(надхвърля ? 1 : 0);
