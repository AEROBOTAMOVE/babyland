#!/usr/bin/env node
/* eslint-disable */
// ═══════════════════════════════════════════════════════════════════════════
// 🔎 „А КАК ГО ПИШЕ ТЯ?“ — храповик срещу следващото „не дише“
// ═══════════════════════════════════════════════════════════════════════════
//
// ЗАЩО (30.09.2026): „не ДИША“ гърмеше, „не ДИШЕ“ МЪЛЧЕШЕ. И петте форми.
// „Дише“ не е грешка — това е обикновената разговорна форма. Дишането е
// най-важният флаг тук. Намерих го СЛУЧАЙНО, докато меря друго.
// Случайността не е стратегия. Оттам този уред.
//
// КАКВО ПРАВИ: взема ВСЕКИ червен флаг и го пренаписва така, както истинска
// българка го пише в чата, после мери кои варианти МЪЛЧАТ.
//
// ПРЕОБРАЗУВАНИЯТА — малко на брой и всяко оправдано:
//   1 · пълен член „-ът“ → „-а“   („гардеробът“ → „гардероба“)
//   2 · глагол „-а“ → „-е“        („диша“ → „дише“)
//   3 · „щ“ → „шт“                 („още“ → „оште“)
//   4 · изпусната „й“              („гной“ → „гнои“)
//   5 · „ѝ“ → „и“                  (никой не пише ударението)
//
// ⚠️ УРЕДЪТ НЕ Е ПРИСЪДА. Преобразуване 2 дава ~160 „находки“, но прегледани
//    на ръка повечето са безсмислици („печката“ → „печкате“). ЧОВЕК преглежда
//    списъка и решава кои форми влизат като флагове. Затова прагът за това
//    преобразуване е широк — то е за четене, не за спиране.
//
// ⚠️ ЗАЩО НЕ СЕ СГЪВАТ БУКВИТЕ в normalize(): евтино е, но „бой“ и „бои“
//    стават една дума, а „бои“ е боя за стена. Плаща се с фалшиви тревоги.
//    Влизат ТОЧНО измерените форми, не правило.
//
// САМОПРОВЕРКА: пуска и 80 непокътнати флага. Ако те не гърмят, уредът е сляп
// и числата долу не значат нищо — излиза с грешка.
//
// ХРАПОВИК: числата се сверяват с dev/kak_go_pishe_izmereno.json. Повече
// мълчащи от записаното = изход 1. Записване на нова мярка: --zapishi.
//
// ПУСКАНЕ: node dev/kak_go_pishe_tya.js  ·  node dev/kak_go_pishe_tya.js --zapishi
// ПЪТ НАЗАД: файлът само ЧЕТЕ проекта (освен --zapishi, който пипа своя json).
// ═══════════════════════════════════════════════════════════════════════════
'use strict';
const fs = require('fs');
const path = require('path');
const ROOT = path.join(__dirname, '..');
const ЗАПИШИ = process.argv.includes('--zapishi');
const МЯРКА = path.join(__dirname, 'kak_go_pishe_izmereno.json');

const { zaredi } = require(path.join(__dirname, 'pyasachnik.js'));
const W = zaredi(null, { памет: { bl_baby: { birth: '2025-11-20' } } });
const KB = W.BL_KB || W.KB;
const флагове = (KB.redFlags || []).map(String);

const ПРЕОБРАЗУВАНИЯ = [
  ['пълен член -ът→-а', ф => ф.replace(/([а-я]{3,})ът(?![а-я])/g, '$1а')],
  ['глагол -а→-е', ф => ф.replace(/(^|\s)([а-я]{3,})а(?=\s|$)/g, (m, p, w) => p + w + 'е')],
  ['щ→шт', ф => ф.replace(/щ/g, 'шт')],
  ['без й', ф => ф.replace(/й/g, 'и')],
  ['ѝ→и', ф => ф.replace(/ѝ/g, 'и')],
];

const гърми = т => { try { return !!W.BL_REDFLAG(т); } catch (e) { return false; } };

console.log('\n🔎 А КАК ГО ПИШЕ ТЯ\n');

// ── самопроверка ПЪРВО: мярка, която не може да гръмне, не мери ──
let контрола = 0;
for (const ф of флагове.slice(0, 80)) if (гърми(ф)) контрола++;
console.log('  САМОПРОВЕРКА · 80 непокътнати флага: гърмят ' + контрола + ' от 80');
if (контрола < 72) {
  console.log('  🔴 УРЕДЪТ Е СЛЯП — не вярвай на нищо по-долу.');
  process.exit(1);
}
console.log('  ✅ уредът вижда\n');

const сега = {};
const пълно = {};
for (const [име, преобр] of ПРЕОБРАЗУВАНИЯ) {
  const мълчат = [];
  let пипнати = 0;
  for (const ф of флагове) {
    const в = преобр(ф);
    if (в === ф) continue;
    пипнати++;
    if (!гърми(в)) мълчат.push(ф + '   →   ' + в);
  }
  сега[име] = мълчат.length;
  пълно[име] = мълчат;
  const дял = пипнати ? Math.round(мълчат.length * 100 / пипнати) : 0;
  console.log('  ■ ' + име + ': пипнати ' + пипнати + ' · МЪЛЧАТ ' + мълчат.length + '  (' + дял + '%)');
  мълчат.slice(0, 5).forEach(x => console.log('       🔇 ' + x));
  if (мълчат.length > 5) console.log('       … и още ' + (мълчат.length - 5));
}

fs.writeFileSync(path.join(__dirname, 'nahodki', 'kak_go_pishe_tya.json'), JSON.stringify(пълно, null, 1));

if (ЗАПИШИ) {
  fs.writeFileSync(МЯРКА, JSON.stringify(сега, null, 1));
  console.log('\n  📝 мярката е записана: ' + JSON.stringify(сега));
  process.exit(0);
}

let известно = null;
try { известно = JSON.parse(fs.readFileSync(МЯРКА, 'utf8')); } catch (e) {}
if (!известно) {
  console.log('\n  ⚠️ няма записана мярка — пусни с --zapishi, за да стане храповик.');
  process.exit(0);
}

const по_лошо = [];
for (const име of Object.keys(сега)) {
  const беше = известно[име];
  if (typeof беше === 'number' && сега[име] > беше) по_лошо.push(име + ': ' + беше + ' → ' + сега[име]);
}
console.log('');
if (по_лошо.length) {
  console.log('  🔴 СТАНА ПО-ЛОШО:');
  по_лошо.forEach(x => console.log('     · ' + x));
  console.log('\n  Някой е добавил флаг, който мълчи в обикновеното писане,');
  console.log('  или е махнал форма. Виж dev/nahodki/kak_go_pishe_tya.json.');
  process.exit(1);
}
console.log('  ✅ НЯМА НОВИ МЪЛЧАЩИ ФОРМИ');
