// ═══════════════════════════════════════════════════════════
// 📚 СИРАЦИТЕ — статия, до която не води НИТО ЕДНА карта
//
// ЗАЩО (26.08.2026, ИЗМЕРЕНО): библиотеката има 898 статии. Само 386 от тях
// са посочени от поне една карта. Останалите 512 (57%) се разлистват — те са
// в lib/index.json и се виждат, ако мама тръгне да ги ТЪРСИ — но НЕ изскачат,
// когато тя зададе въпроса, на който отговарят.
//
// А майка с болно бебе в 3 през нощта не разлиства. Тя пита. Затова най-лошо
// е точно там, където най-много боли: „Здраве и SOS" — 167 сирака от 220.
//
// dev/bez_brauzar.js мери ОБРАТНАТА посока: карта, която сочи към несъщест-
// вуваща статия (счупена препратка). Тя е винаги 0 и оттам изглежда, че
// библиотеката е свързана. Не е — просто никой не беше броил в тази посока.
//
// 🪤 „СИРАК" ТУК НЕ ЗНАЧИ „НЕВИДИМА". Всичките 898 са в индекса и се
//    разлистват по стаи. Уредът нарочно го пише при всяко пускане, за да не
//    се чете числото по-страшно, отколкото е.
//
// ПУСКАНЕ: node dev/siraci.js  ·  node dev/siraci.js --vsichki
// ПЪТ НАЗАД: файлът само ЧЕТЕ. Изтрий го и нищо не се променя.
// ═══════════════════════════════════════════════════════════
const fs = require('fs');
const vm = require('vm');
const path = require('path');
const КОРЕН = path.resolve(__dirname, '..');

function статии() {
  const idx = JSON.parse(fs.readFileSync(path.join(КОРЕН, 'lib/index.json'), 'utf8'));
  return (idx.items || []).filter(x => x && x.id);
}
function карти() {
  const ctx = { console: { log() {}, warn() {} }, JSON, Math, Date, RegExp, String, Number, Array, Object };
  ctx.window = ctx; ctx.globalThis = ctx; ctx.self = ctx;
  vm.createContext(ctx);
  new vm.Script(fs.readFileSync(path.join(КОРЕН, 'js/kb.js'), 'utf8')).runInContext(ctx);
  return ((ctx.BL_KB || ctx.KB) || {}).entries || [];
}

const сп = статии();
const записи = карти();
if (!сп.length || !записи.length) {
  console.log('🔴 не мога да заредя ' + (!сп.length ? 'библиотеката' : 'картите') + ' — числото долу би било лъжа');
  process.exit(2);
}

// една низова снимка на всички карти: препратките към статии се пишат по
// различни начини (поле lib, вътре в текста, в chips), затова се търси по id
const текстКарти = JSON.stringify(записи);
const сирак = а => текстКарти.indexOf(а.id) < 0;

const сираци = сп.filter(сирак);
const поСтая = {};
for (const а of сп) {
  const r = а.r || '—';
  поСтая[r] = поСтая[r] || { общо: 0, без: 0 };
  поСтая[r].общо++;
  if (сирак(а)) поСтая[r].без++;
}

console.log('');
console.log('📚 СИРАЦИТЕ — статия без нито една карта към нея');
console.log('');
console.log('  ПРЕГЛЕДАНИ : ' + сп.length + ' статии · ' + записи.length + ' карти');
console.log('  ✅ с врата от карта : ' + (сп.length - сираци.length) + '  (' + Math.round((сп.length - сираци.length) / сп.length * 100) + '%)');
console.log('  🟠 СИРАЦИ           : ' + сираци.length + '  (' + Math.round(сираци.length / сп.length * 100) + '%)');
console.log('     разлистват се в библиотеката, но НЕ изскачат при въпрос');
console.log('');
console.log('  ── по стаи (най-зле отгоре) ──');
Object.entries(поСтая).sort((x, y) => y[1].без - x[1].без).forEach(([r, v]) =>
  console.log('     ' + String(v.без).padStart(3) + ' от ' + String(v.общо).padStart(3) +
              '  (' + String(Math.round(v.без / v.общо * 100)).padStart(3) + '%)  ' + r));
console.log('');

const ВСИЧКИ = process.argv.indexOf('--vsichki') >= 0;
if (ВСИЧКИ) {
  console.log('  ── всички сираци ──');
  for (const а of сираци) console.log('     [' + (а.r || '—') + '] ' + а.id + '  ' + String(а.t || '').slice(0, 70));
  console.log('');
} else if (сираци.length) {
  console.log('  ── първите десет (за всички: --vsichki) ──');
  for (const а of сираци.slice(0, 10)) console.log('     [' + (а.r || '—') + '] ' + а.id + '  ' + String(а.t || '').slice(0, 66));
  console.log('');
}

// ── САМОПРОВЕРКА в ДВЕТЕ посоки ──
// Уред, който не може да гръмне, е украса. И уред, който брои всичко за
// сирак, е също толкова безполезен — затова се проверява и че НЕ вика.
(function самопроверка() {
  // 🪤 ПЪРВАТА ВЕРСИЯ ТУК ГРЪМНА заради ОМОГЛИФ: кръстих помощната функция с
  //    КИРИЛСКО „е" и я виках с ЛАТИНСКО „e". За окото са един знак, за Node
  //    са две различни имена. Затова тук няма едносимволни имена изобщо.
  const примКарти = [{ id: 'к1', lib: 'lib-ИМА' }, { id: 'к2', core: 'виж lib-СЪЩО' }];
  const снимка = JSON.stringify(примКарти);
  const сирак2 = ид => снимка.indexOf(ид) < 0;
  const хваща = сирак2('lib-НЯМА') === true;
  const мълчиПоле = сирак2('lib-ИМА') === false;
  const мълчиТекст = сирак2('lib-СЪЩО') === false;
  console.log('  самопроверка: хваща сирак ' + (хваща ? '✅' : '🔴') +
              ' · вижда препратка в поле ' + (мълчиПоле ? '✅' : '🔴') +
              ' · вижда препратка в текста ' + (мълчиТекст ? '✅' : '🔴'));
  if (!(хваща && мълчиПоле && мълчиТекст)) { console.log('  🔴 САМОПРОВЕРКАТА ПАДНА — числото горе не важи.'); process.exit(2); }
})();

// Прагът е ЗАМРАЗЕНОТО ДНЕШНО ЧИСЛО. Не пречи на заварения дълг, но пламва,
// ако някой добави статия, без да ѝ отвори врата. Падне ли дългът — свали
// прага тук, ръчно, иначе се връща тихо.
const ПРАГ = Number(process.env.BL_SIRACI_PRAG || 490);
if (сираци.length > ПРАГ) {
  console.log('  🔴 НАХОДКА: сираците станаха ' + сираци.length + ' при замразен праг ' + ПРАГ + '.');
  console.log('     Нова статия без карта към нея е написана напразно — мама няма как да я срещне.');
  console.log('');
  process.exit(1);
}
console.log(сираци.length < ПРАГ
  ? '  🟢 паднаха на ' + сираци.length + ' (праг ' + ПРАГ + '). Свали прага в dev/siraci.js.'
  : '  ✅ ' + сираци.length + ' — точно замразения праг. Нов сирак не е добавен.');
console.log('');
process.exit(0);
