function пуснисСаботаж(замяна) {
  const кодС = замяна(денНулаКод + String.fromCharCode(10) + КОД);
  let гаснат = 0, остават = 0;
  for (const [, хран] of СЛУЧАИ) {
    const LS = Object.assign({}, хран);
    const сандък = {
      localStorage: {
        getItem: k => (k in LS ? LS[k] : null),
        setItem: (k, v) => { LS[k] = String(v); },
        removeItem: k => { delete LS[k]; }
      },
      document: { dispatchEvent() {} },
      CustomEvent: function () {},
      window: {},
      load: (k, d) => { try { const v = JSON.parse(LS[k]); return v == null ? d : v; } catch (e) { return d; } },
      Date, isNaN, JSON, String, Number, console
    };
    sandboxRun(сандък, кодС + String.fromCharCode(10) + 'гасиБременносттаПриРаждане();');
    if (сандък.__ГРЕШКА__) return null;
    if (LS.bl_lmp) остават++; else гаснат++;
  }
  return { гаснат, остават };
}

