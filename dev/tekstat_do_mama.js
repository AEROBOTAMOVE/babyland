function следващ() {
  if (i >= сцени.length) return край();
  const с = сцени[i++];
  const W = zaredi(null, { домБогат: true });   // чист свят за всяка сцена
  try {
    W.MamaHelper.open(с.стая);
    W.MamaHelper.ask(с.т);
  } catch (e) {
    паднали.push(с.име + ' — ГРЪМНА: ' + e.message.slice(0, 90));
    return следващ();
  }
  setTimeout(() => {
    const c = W.document._поId['roChat'];
    const мехури = c ? c.children.slice(1).map(r => (r.всичкиятТекст || '').replace(/\s+/g, ' ')) : [];
    const текст = мехури.join(' ');
    пуснати++;
    if (!текст.trim()) { паднали.push(с.име + ' — ПРАЗЕН ОТГОВОР'); return следващ(); }
    let бележки = [];
    for (const и of (с.иска || [])) if (!и.test(текст)) бележки.push('липсва ' + и);
    for (const з of (с.забранява || [])) if (з.test(текст)) бележки.push('СЪДЪРЖА забраненото ' + з);
    if (бележки.length) {
      паднали.push(с.име + ' — ' + бележки.join(' · '));
      console.log('   🔴 ' + с.име);
      console.log('      ' + бележки.join(String.fromCharCode(10) + '      '));
      console.log('      защо е важно: ' + с.защо);
      console.log('      текстът: ' + текст.slice(0, 190));
    } else {
      console.log('   ✅ ' + с.име);
    }
    следващ();
  }, 2300);
}

function край() {
  console.log('');
  // 🪞 САМОПРОВЕРКА: нула пуснати значи, че уредът не е стигнал до отговор —
  //    а тогава „чисто" е лъжа. Точно тази форма на сляп пазач вече ме лъга.
  if (пуснати < сцени.length) {
    console.log('   🔴 стигнати само ' + пуснати + ' от ' + сцени.length + ' сцени — уредът е СЛЯП');
    process.exit(2);
  }
  if (паднали.length) {
    console.log('   🔴 ПАДНАЛИ: ' + паднали.length + ' от ' + сцени.length);
    process.exit(1);
  }
  console.log('   ✅ всичките ' + сцени.length + ' сцени: текстът е за ПРАВИЛНАТА жена');
  process.exit(0);
}

