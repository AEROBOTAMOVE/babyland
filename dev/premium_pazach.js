function прегледай(файлове, индекс, сw, наДиска) {
  const находки = [];
  const активи = new Set((сw.match(/'([^'\n]+)'/g) || []).map(x => x.slice(1, -1)));
  const рисунки = new Map();   // път → къде се споменава
  for (const [ф, т] of Object.entries(файлове)) {
    const css = ф.endsWith('.css');
    // 3 · относителните url капани
    if (css) {
      const лош = т.match(/url\(\s*['"]?img\//);
      if (лош) находки.push(ф + ': url(img/…) в CSS — разрешава се спрямо css/ → 404 (трябва ../img/)');
      // 4 · скобите
      let о = 0; for (const ч of т.replace(/\/\*[\s\S]*?\*\//g, '').replace(/"(?:\\.|[^"\\])*"|'(?:\\.|[^'\\])*'/g, '""')) { if (ч === '{') о++; else if (ч === '}') о--; }
      if (о !== 0) находки.push(ф + ': скобите не са балансирани (' + (о > 0 ? '+' : '') + о + ') — всичко след счупеното място изпада тихо');
    } else {
      // коментарите не са код (първото пускане: 2 от 3 находки бяха бележки „🪤 беше getElementById…“);
      // `//` след `:` е адрес (https://), не коментар
      const код = т.replace(/\/\*[\s\S]*?\*\//g, '').replace(/(^|[^:\\'"])\/\/[^\n]*/g, '$1');
      if (/url\(\s*['"]?\.\.\/img\//.test(код)) находки.push(ф + ': url(../img/…) в JS — стилът на елемента се разрешава спрямо страницата → 404 (трябва img/)');
      // 5 · несъществуващият id — освен ако файлът сам не му го дава (pl-dobavi.js:399)
      if (/getElementById\(\s*['"]plus-btn['"]\s*\)/.test(код) && !/\.id\s*=\s*['"]plus-btn['"]/.test(код)) находки.push(ф + ": getElementById('plus-btn') — такъв id няма; бутонът е .plus-btn в #blPlus (polish.js:314)");
      // 6 · синтаксис
      try { new vm.Script(т, { filename: ф }); } catch (e) { находки.push(ф + ': синтаксис — ' + e.message); }
    }
    // 6 · tel: връзки
    for (const м of т.matchAll(/href=\\?["']tel:([^"'\\]*)/g)) if (!/^\+?\d{2,15}$/.test(м[1])) находки.push(ф + ': tel:' + м[1] + ' — не е номер');
    // 1–2 · рисунките
    for (const м of т.matchAll(/img\/(?:art|scene)\/[\w.-]+\.webp/g)) { if (!рисунки.has(м[0])) рисунки.set(м[0], ф); }
  }
  for (const [р, ф] of рисунки) {
    if (!наДиска(р)) находки.push(ф + ': ' + р + ' — НЯМА го на диска (празна рисунка)');
    else if (!активи.has(р)) находки.push(ф + ': ' + р + ' — не е в офлайн кеша (sw.js ASSETS) — офлайн ще е празно');
  }
  // вкарани ли са
  const чакащи = [];
  for (const ф of Object.keys(файлове)) if (/(^|\/)pl-[\w-]+\.(css|js)$/.test(ф) && !индекс.includes(ф + '?v=') && !индекс.includes(ф + '"')) чакащи.push(ф);
  return { находки, рисунки: рисунки.size, чакащи };
}

function четиФайлове() {
  const с = {};
  for (const д of ['css', 'js']) for (const ф of fs.readdirSync(д)) {
    if ((/^premium/.test(ф) || /^pl-/.test(ф)) && /\.(css|js)$/.test(ф) && !/\.(bak|BAK|PREDI)/.test(ф)) с[д + '/' + ф] = fs.readFileSync(path.join(д, ф), 'utf8');
  }
  return с;
}

