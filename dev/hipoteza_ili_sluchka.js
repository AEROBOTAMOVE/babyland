//   Корпусът е от БЛИЗНАЦИ. Всяка двойка е един и същ израз два пъти:
//       „страх ме е да не се задави с гроздето"   ← въпрос, NEVINNO
//       „задави се с грозде преди малко"          ← случка, SPESHNO
//   Пазач, който просто заглушава всичко хипотезно, ще мине половината.
//   Пазач, който вика 112 на всичко, ще мине другата половина.
