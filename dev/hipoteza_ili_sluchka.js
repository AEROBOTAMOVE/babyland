//
// ТРИТЕ ЧИСЛА, КОИТО ВРЪЩА:
//   🔴 ЗАГЛУШЕНА СПЕШНОСТ — SPESHNO близнак без НИКАКЪВ отговор. Пада уредът.
//   🟠 ФАЛШИВА ТРЕВОГА    — NEVINNO близнак с червено. Пада уредът.
//   ⬜ ТИШИНА ПРИ ВЪПРОС  — NEVINNO близнак без карта. НЕ пада: това е
//      липсващо съдържание, не дефект на вратите. Брои се и се изписва.
