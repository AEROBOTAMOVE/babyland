const fs = require('fs');
const path = require('path');
const { zaredi } = require('./pyasachnik.js');

const ВСИЧКИ = process.argv.includes('--vsichki');
const КОРПУС = path.join(__dirname, 'korpus_hipoteza.json');
if (!fs.existsSync(КОРПУС)) { console.log('🔴 korpus_hipoteza.json липсва — СЛЯП'); process.exit(2); }
const записи = JSON.parse(fs.readFileSync(КОРПУС, 'utf8'));

// ── 0 · САМИЯТ КОРПУС Е ИЗПРАВЕН ЛИ ──
// Близнак без двойник мери една страна и си мисли, че мери разликата.
const двойки = {};
for (const з of записи) (двойки[з.dv] = двойки[з.dv] || []).push(з);
const счупени = Object.entries(двойки).filter(([, в]) =>
  в.length !== 2 || !в.some(x => x.e === 'NEVINNO') || !в.some(x => x.e === 'SPESHNO'));
if (счупени.length) {
  console.log('🔴 СЛЯП ПАЗАЧ: ' + счупени.length + ' счупени двойки');
  for (const [к, в] of счупени.slice(0, 10)) console.log('   ' + к + ' → ' + в.map(x => x.e).join('+'));
  process.exit(2);
}

const W = zaredi(null);
// ── 1 · ДОКАЗВАМ, ЧЕ СОНДАТА ЛОВИ, ПРЕДИ ДА СЪДЯ ──
if (typeof W.BL_REDFLAG !== 'function' || typeof W.BL_MOTHERFLAG !== 'function') {
  console.log('🔴 вратите не се виждат — СЛЯП'); process.exit(2);
}
if (W.BL_REDFLAG('бебето не диша') !== true) { console.log('🔴 контролата не гърми — СЛЯП'); process.exit(2); }
if (W.BL_REDFLAG('днес беше слънчево и се разходихме') === true) { console.log('🔴 контролата гърми на всичко — СЛЯП'); process.exit(2); }

// същият ред като в respond(): motherLevel → pregLevel → isRedFlag → findEntry
function коя(текст, стая) {
  const m = W.BL_MOTHERFLAG(текст);
  if (m) return m;
  if (W.BL_PREGFLAG(текст, стая || null)) return 'preg';
  if (W.BL_REDFLAG(текст)) return 'red';
  const k = W.BL_MATCH(текст, стая || null);
  return k ? 'karta:' + k.id : 'nishto';
}
const тревога = г => г === 'red' || г === 'preg' || г === 'heavy' || г === 'mother' ||
                      г === 'dv' || г === 'loss' || г === 'mamabody';

console.log('');
console.log('🎭 ХИПОТЕЗА ИЛИ СЛУЧКА');
console.log('   двойки близнаци: ' + Object.keys(двойки).length + ' · изречения: ' + записи.length);
console.log('');

const заглушени = [], фалшиви = [], тихиВъпроси = [], неразличени = [];
for (const [ключ, в] of Object.entries(двойки)) {
  const н = в.find(x => x.e === 'NEVINNO'), с = в.find(x => x.e === 'SPESHNO');
  const гн = коя(н.t, н.r), гс = коя(с.t, с.r);
  if (!тревога(гс)) заглушени.push({ ключ, т: с.t, г: гс });
  if (гн === 'red') фалшиви.push({ ключ, т: н.t, г: гн });
  if (гн === 'nishto') тихиВъпроси.push({ ключ, т: н.t });
  if (гн === гс) неразличени.push({ ключ, н: н.t, с: с.t, г: гн });
  if (ВСИЧКИ) {
    console.log('   ' + ключ + '  ❓ ' + String(гн).padEnd(24) + ' « ' + н.t + ' »');
    console.log('        ' + '  ‼️ ' + String(гс).padEnd(24) + ' « ' + с.t + ' »');
  }
}

console.log('');
console.log('🔴 ЗАГЛУШЕНА СПЕШНОСТ: ' + заглушени.length);
for (const з of заглушени) console.log('     ' + з.ключ + ' → ' + з.г + '  « ' + з.т + ' »');
console.log('🟠 ФАЛШИВА ТРЕВОГА:    ' + фалшиви.length);
for (const ф of фалшиви) console.log('     ' + ф.ключ + ' → red  « ' + ф.т + ' »');
console.log('⚪ НЕРАЗЛИЧЕНИ ДВОЙКИ: ' + неразличени.length + '   (двата близнака дават ЕДНО И СЪЩО)');
for (const н of неразличени) console.log('     ' + н.ключ + ' → ' + н.г + '  ❓« ' + н.н + ' »  ‼️« ' + н.с + ' »');
console.log('⬜ ТИШИНА ПРИ ВЪПРОС:  ' + тихиВъпроси.length + '   (липсва СЪДЪРЖАНИЕ, не е дефект на вратите)');
for (const т of тихиВъпроси) console.log('     ' + т.ключ + '  « ' + т.т + ' »');
console.log('');

const пада = заглушени.length + фалшиви.length + неразличени.length;
if (пада) { console.log('🔴 ПАДА: ' + пада + ' (заглушени ' + заглушени.length + ' · фалшиви ' + фалшиви.length + ' · неразличени ' + неразличени.length + ')'); process.exit(1); }
console.log('✅ ВСЯКА ДВОЙКА СЕ РАЗЛИЧАВА · ' + тихиВъпроси.length + ' въпроса чакат съдържание');
process.exit(0);
