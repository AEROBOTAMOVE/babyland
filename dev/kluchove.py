def прочети(п):
    return io.open(п, encoding='utf-8').read()


def запиши(п, s):
    # ПАЗАЧ 1: без сурогати (миналия път изтри целия файл)
    for ch in s:
        if 0xD800 <= ord(ch) <= 0xDFFF:
            raise SystemExit('🔴 СУРОГАТ в текста — НЕ пиша.')
    # ПАЗАЧ 2: кодирай ПРЕДИ да пипнеш файла
    b = s.encode('utf-8')
    # ПАЗАЧ 3: файлът не бива да се смалява
    стар = os.path.getsize(п)
    if len(b) < стар * 0.98:
        raise SystemExit('🔴 Файлът се смалява %d → %d — НЕ пиша.' % (стар, len(b)))
    io.open(п, 'wb').write(b)


def блок_keys(текст, ид):
    """намира keys: [...] на записа с този id (кавичките са ту ', ту ")"""
    m = re.search(r'id:\s*[\'"]' + re.escape(ид) + r'[\'"]', текст)
    if not m:
        return None
    k = текст.find('keys:', m.end())
    if k < 0 or k - m.end() > 400:
        return None
    ляво = текст.find('[', k)
    дясно = текст.find(']', ляво)
    if ляво < 0 or дясно < 0:
        return None
    return (ляво + 1, дясно, текст[ляво + 1:дясно])


def цитат(s):
    return '"' + s + '"' if "'" in s else "'" + s + "'"


def main():
    t = прочети(ФАЙЛ)
    if not os.path.exists(РЕЗЕРВА):
        shutil.copyfile(ФАЙЛ, РЕЗЕРВА)
        print('🧯 път назад: ' + os.path.basename(РЕЗЕРВА))

    махнати, добавени, пропуснати = 0, 0, []

    # обработваме от края към началото, за да не местим отместванията
    задачи = []
    for ид in set(list(МАХНИ.keys()) + list(ДОБАВИ.keys())):
        b = блок_keys(t, ид)
        if not b:
            пропуснати.append(ид + ' (няма такъв запис)')
            continue
        задачи.append((b[0], b[1], b[2], ид))
    задачи.sort(reverse=True)

    for ляво, дясно, вътре, ид in задачи:
        ключове = [k.strip() for k in re.findall(r'''['"]([^'"]*)['"]''', вътре)]
        нови = list(ключове)

        for k in МАХНИ.get(ид, []):
            if k in нови:
                нови.remove(k)
                махнати += 1
            else:
                пропуснати.append(ид + ' ✂ „' + k + '“ (вече го няма)')

        for k in ДОБАВИ.get(ид, []):
            if k not in нови:
                нови.append(k)
                добавени += 1

        if нови == ключове:
            continue
        t = t[:ляво] + ', '.join(цитат(k) for k in нови) + t[дясно:]

    запиши(ФАЙЛ, t)
    print('✂  махнати крадци : %d' % махнати)
    print('➕ добавени думи  : %d' % добавени)
    if пропуснати:
        print('⚠  за проверка:')
        for p in пропуснати:
            print('   · ' + p)


if __name__ == '__main__':
    main()
