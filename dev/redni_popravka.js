// ═══════════════════════════════════════════════════════════
// 🔢 РЕДНИТЕ ЧИСЛИТЕЛНИ — поправка по правило, не на око
//
// js/redna.js държи правилото от 05.08, но на много места наставката е
// лепната на ръка. Жената в 28-а седмица чете „28-та седмица", а базата
// на помощничките пише „28-ма" — едно и също число, два правописа в едно
// приложение, и то на екрана, където се решава дали да се звъни.
// Особено важни са 37-ма и 38-ма: те стоят в спешния текст за контракции.
//
// 🪤 ДВА КАПАНА, в които паднах, докато го мерех:
//
// 1. `\b` НЕ ВАЖИ ЗА КИРИЛИЦА. Първият ми израз беше
//    /(\d+)-?(ва|ра|ма|та)\b/ и намери НУЛА от 182. В JavaScript \b се
//    дефинира през \w = [A-Za-z0-9_]; след „а" граница няма.
//    Трети път днес същият капан. Лек: (?![а-яa-z0-9]).
//
// 2. РОДЪТ РЕШАВА. Второто ми мерене хвана 41 „грешни", но част от тях
//    са ВЕРНИ: „28-ми отговор", „1-ви ден" са мъжки род и така е редно.
//    Две таблици, не една:
//      женски (седмица, минута): 1→-ва 2→-ра 7,8→-ма 11-19→-та ост.→-та
//      мъжки  (ден, триместър):  1→-ви 2→-ри 7,8→-ми 11-19→-ти ост.→-ти
//    Родът се чете от думата СЛЕД числото.
//
// ПУСКАНЕ: node dev/redni_popravka.js          — само показва
//          node dev/redni_popravka.js --pishi  — записва
// ПЪТ НАЗАД: прави .PREDI_REDNI копие на всеки пипнат файл.
// ═══════════════════════════════════════════════════════════
const fs = require('fs');
const path = require('path');
process.chdir(path.resolve(__dirname, '..'));

const Ж = n => { const е = n % 10, д = n % 100;
  if (д >= 11 && д <= 19) return '-та';
  return е === 1 ? '-ва' : е === 2 ? '-ра' : (е === 7 || е === 8) ? '-ма' : '-та'; };
const М = n => { const е = n % 10, д = n % 100;
  if (д >= 11 && д <= 19) return '-ти';
  return е === 1 ? '-ви' : е === 2 ? '-ри' : (е === 7 || е === 8) ? '-ми' : '-ти'; };

const ЖЕНСКИ = /^(седмица|седмици|седмицата|минута|минути|минутата|година|години|нощ|сутрин|вечер|доза|проба|ваксина|глътка)/i;
const МЪЖКИ  = /^(ден|дни|денят|месец|месеца|триместър|път|пъти|отговор|рожден|зъб|прием)/i;

const ЖЕНСКА_НАСТАВКА = /^(ва|ра|ма|та)$/;
const РЕ = /(\d{1,3})[-‑](ва|ра|ма|та|ви|ри|ми|ти)(?![а-яa-z0-9])/g;

const файлове = [];
for (const f of fs.readdirSync('js'))
  if (f.endsWith('.js') && !/ARCHIVE|PREDI|BAK|NOV_|_izmervane/.test(f)) файлове.push('js/' + f);
for (const f of fs.readdirSync('lib'))
  if (f.endsWith('.json') && !/BAK|ARCHIVE/.test(f)) файлове.push('lib/' + f);

const пиши = process.argv.indexOf('--pishi') >= 0;
let общо = 0, поправени = 0, неясни = 0;
const списък = [];

for (const f of файлове) {
  const t = fs.readFileSync(f, 'utf8');
  let нов = t, местни = 0;
  const замени = [];
  // редовете, които са КОМЕНТАР — там наставката често е ЦИТАТ на самия
  // дефект („четеше 28-та седмица“). Смениш ли я, изтриваш документацията
  // на стара поправка и следващият пак ще падне в същия капан.
  const редовеНачала = [];
  { let поз = 0; for (const р of t.split('\n')) { редовеНачала.push(поз); поз += р.length + 1; } }
  const редът = i => { let л = 0, д = редовеНачала.length - 1;
    while (л < д) { const с = (л + д + 1) >> 1; if (редовеНачала[с] <= i) л = с; else д = с - 1; } return л; };
  const редове = t.split('\n');
  const вКоментар = i => {
    const r = редове[редът(i)] || '';
    const к = r.indexOf('//');
    if (к >= 0 && i - редовеНачала[редът(i)] > к) return true;
    return /^\s*(\*|\/\*)/.test(r);
  };

  for (const m of t.matchAll(РЕ)) {
    const n = +m[1]; if (n < 1 || n > 99) continue;
    общо++;
    if (вКоментар(m.index)) continue;
    const след = t.slice(m.index + m[0].length).replace(/^[\s"'“”«»,;:.\-–—]+/, '').slice(0, 14);
    let род = null;
    if (ЖЕНСКИ.test(след)) род = 'ж';
    else if (МЪЖКИ.test(след)) род = 'м';
    else род = ЖЕНСКА_НАСТАВКА.test(m[2]) ? 'ж' : 'м';   // ако не личи — вярваме на самата наставка
    const вярно = n + (род === 'ж' ? Ж(n) : М(n));
    if (m[0] === вярно) continue;
    // не гадаем: сменяме САМО ако родът е ясен ИЛИ наставката вече е от същия ред
    if (!ЖЕНСКИ.test(след) && !МЪЖКИ.test(след)) {
      const същиРед = род === 'ж' ? ЖЕНСКА_НАСТАВКА.test(m[2]) : !ЖЕНСКА_НАСТАВКА.test(m[2]);
      if (!същиРед) { неясни++; continue; }
    }
    замени.push({ старо: m[0], ново: вярно, около: (след || '?').slice(0, 12) });
  }
  if (!замени.length) continue;
  for (const з of замени) {
    const преди = нов;
    // точкова смяна: същият израз, но само този конкретен низ
    нов = нов.split(з.старо + ' ').join(з.ново + ' ')
             .split(з.старо + '“').join(з.ново + '“')
             .split(з.старо + '"').join(з.ново + '"')
             .split(з.старо + ',').join(з.ново + ',')
             .split(з.старо + '.').join(з.ново + '.')
             .split(з.старо + '<').join(з.ново + '<');
    if (нов !== преди) { местни++; поправени++; списък.push(f + '  ' + з.старо + ' → ' + з.ново + '   (' + з.около + ')'); }
  }
  if (пиши && нов !== t) {
    fs.copyFileSync(f, f + '.PREDI_REDNI');
    fs.writeFileSync(f, нов, 'utf8');
  }
}

console.log('🔢 РЕДНИТЕ ЧИСЛИТЕЛНИ\n');
console.log('  прегледани: ' + общо + ' · поправени: ' + поправени + ' · оставени неясни: ' + неясни);
console.log('\n' + [...new Set(списък)].join('\n'));
console.log('\n' + (пиши ? '✍️ ЗАПИСАНО (има .PREDI_REDNI копия)' : '👀 само показах — пусни с --pishi'));
