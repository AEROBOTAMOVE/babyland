// ═══════════════════════════════════════════════════════════
// ⏸️ ПАУЗАТА СЛЕД ЗАГУБА — кои напомняния гаснат и кои ОСТАВАТ
//
// Жена, загубила бебе, натиска пауза. Тогава бременностните ѝ напомняния
// трябва да изчезнат — но САМО те. Зъболекарят, личният лекар и рожденият
// ден на кака си остават нейни. Един израз в js/helper.js (`БРЕМЕННО`)
// решава кое от двете е. Тук той се вади ОТ ЖИВИЯ ФАЙЛ и се съди срещу
// истински заглавия — а не срещу свое копие, което може да е остаряло.
//
// ═══ 🛡️ САМОПРОВЕРКА (01.09.2026, ВЪЛНА 1.3) ═══
// До днес този файл беше УКРАСА: печаташе „🔴" и излизаше с код 0. Тоест
// можеха да паднат и десетте бременни заглавия, а всяка проверка, която го
// вика, щеше да го брои за минал. Сега:
//   1. пада с изход 1;
//   2. долна граница на БРОЯ заглавия — свие ли се списъкът, е червено;
//   3. две примамки в ДВЕТЕ посоки: израз, който не хваща НИЩО, трябва да
//      събори първия списък; израз, който хваща ВСИЧКО — втория. Мярка,
//      вярна само в едната посока, е монета.
//
// ПУСКАНЕ: node dev/test_pauza.js
// ПЪТ НАЗАД: файлът само ЧЕТЕ. Нищо не записва.
// ═══════════════════════════════════════════════════════════
const fs = require('fs');
const path = require('path');
process.chdir(path.resolve(__dirname, '..'));

const h = fs.readFileSync(path.join(__dirname, '..', 'js/helper.js'), 'utf8');
// самата регулярка, извадена от кода — проверяваме я срещу истински заглавия
const m = h.match(/const БРЕМЕННО = (\/[^\n]+\/i);/);
if (!m) { console.log('🔴 не намерих БРЕМЕННО'); process.exit(1); }
const re = eval(m[1]);

const БРЕМЕННИ = ['Ехография 20 седмица', 'Термин', 'Женска консултация', 'Биохимичен скрининг',
  'Фетална морфология', 'Акушерка — преглед', 'Токограма', 'НСТ', 'Ехография 12 с.', 'Раждане — курс'];
const ДРУГИ = ['Педиатър — профилактика', 'Ваксина 4 месеца', 'Зъболекар', 'Личен лекар',
  'Ясла — документи', 'Стоматолог за мен', 'Очен преглед', 'Рожден ден на кака'];
const ДОЛНА_БРЕМЕННИ = 10, ДОЛНА_ДРУГИ = 8;

// една сметка, срещу подаден израз — за да може да се саботира
function съди(израз) {
  let гаснат = 0, остават = 0;
  const паднали = [];
  for (const t of БРЕМЕННИ) { if (израз.test(t)) гаснат++; else паднали.push('НЕ гасне: ' + t); }
  for (const t of ДРУГИ) { if (!израз.test(t)) остават++; else паднали.push('гасне НАПРАЗНО: ' + t); }
  return { гаснат, остават, паднали };
}

console.log('⏸️  ПАУЗАТА СЛЕД ЗАГУБА\n');
const И = съди(re);
console.log('  БРЕМЕННИ (трябва да гаснат при пауза):');
БРЕМЕННИ.forEach(t => console.log('    ' + (re.test(t) ? '✅' : '🔴') + ' ' + t));
console.log('  ДРУГИ (трябва да ОСТАНАТ):');
ДРУГИ.forEach(t => console.log('    ' + (!re.test(t) ? '✅' : '🔴 гасне напразно') + ' ' + t));
console.log('\n  гаснат ' + И.гаснат + '/' + БРЕМЕННИ.length + '  ·  остават ' + И.остават + '/' + ДРУГИ.length);

let червено = И.паднали.length;
if (червено) { console.log('\n  ── ПАДНАЛИ ──'); И.паднали.forEach(x => console.log('     🔴 ' + x)); }

console.log('\n  САМОПРОВЕРКА (иначе числата горе не значат нищо):');
let самоЧервено = 0;

if (БРЕМЕННИ.length < ДОЛНА_БРЕМЕННИ || ДРУГИ.length < ДОЛНА_ДРУГИ) {
  самоЧервено++;
  console.log('     🔴 СПИСЪЦИТЕ СА СЕ СВИЛИ: бременни ' + БРЕМЕННИ.length + ' (долна ' +
              ДОЛНА_БРЕМЕННИ + ') · други ' + ДРУГИ.length + ' (долна ' + ДОЛНА_ДРУГИ + ')');
} else {
  console.log('     ✅ броят е над долната граница (бременни ' + БРЕМЕННИ.length +
              ' · други ' + ДРУГИ.length + ')');
}

{
  // примамка 1: израз, който не хваща НИЩО → всичките бременни трябва да паднат
  const нищо = /^(?!)$/;
  const р = съди(нищо);
  if (р.гаснат === 0 && р.паднали.length >= БРЕМЕННИ.length)
    console.log('     ✅ примамка: празен израз събаря целия списък БРЕМЕННИ (' + р.паднали.length + ' паднали)');
  else { самоЧервено++; console.log('     🔴 примамка: празен израз даде гаснат=' + р.гаснат + ', паднали=' + р.паднали.length); }
}
{
  // примамка 2: израз, който хваща ВСИЧКО → всичките други трябва да паднат
  const всичко = /.?/;
  const р = съди(всичко);
  if (р.остават === 0 && р.паднали.length >= ДРУГИ.length)
    console.log('     ✅ примамка: всеяден израз събаря целия списък ДРУГИ (' + р.паднали.length + ' паднали)');
  else { самоЧервено++; console.log('     🔴 примамка: всеяден израз даде остават=' + р.остават + ', паднали=' + р.паднали.length); }
}
{
  // и обратната посока: истинският израз НЕ бива да прилича на никоя от двете примамки
  if (И.гаснат > 0 && И.остават > 0)
    console.log('     ✅ живият израз е между двете крайности (' + И.гаснат + ' гаснат · ' + И.остават + ' остават)');
  else { самоЧервено++; console.log('     🔴 живият израз се държи като примамка — не разделя нищо'); }
}

if (самоЧервено) console.log('\n🔴 САМОПРОВЕРКАТА ПАДА — числата горе НЕ СЕ БРОЯТ.');
else if (червено) console.log('\n🔴 ' + червено + ' заглавия отиват в грешната посока.');
else console.log('\n✅ ЧИСТО — ' + (БРЕМЕННИ.length + ДРУГИ.length) + ' заглавия, 3 примамки');
process.exitCode = (червено || самоЧервено) ? 1 : 0;
