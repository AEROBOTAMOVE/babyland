// 🗣️ ОБРЪЩЕНИЕТО КЪМ МАЙКАТА — трети опит на уреда.
//
// 🪤 ДВА ПЪТИ ГРЕШЕН УРЕД ЗА ЕДНО И СЪЩО НЕЩО:
//   1) /\bти\b/ — \b не работи с кирилица → 898 от 898 „не говорят на майката".
//   2) само МЕСТОИМЕНИЯ (ти/теб/твоя) → 559 „учебници". Но българският ИЗПУСКА
//      местоимението: „какво ГЛЕДАШ, преди да звъннеш", „прекарай длан по
//      корема" — това е чисто второ лице БЕЗ нито едно „ти". Статията за
//      скарлатината беше обявена за учебник, а е една от добрите.
//   Второто лице в българския живее в ОКОНЧАНИЕТО (-ш) и в ПОВЕЛИТЕЛНОТО.
const fs = require('fs');
const К = __dirname + '/../';
const Г = '[^а-яА-ЯёЁa-zA-Z]';

// ── не всяка дума на -ш е глагол ──
const НЕ_ГЛАГОЛ = new Set(['душ', 'кеш', 'марш', 'туш', 'кош', 'маш', 'фалш', 'кръш', 'плюш', 'гуляш', 'финиш', 'фиш', 'кръш']);
const второЛице = t => {
  const думи = t.toLowerCase().match(/[а-яё]+/g) || [];
  let гл = 0;
  for (const d of думи) if (d.length >= 4 && d.endsWith('ш') && !НЕ_ГЛАГОЛ.has(d)) гл++;
  let мест = 0;
  for (const w of ['ти', 'теб', 'твоя', 'твоето', 'твоята', 'твоите', 'твой'])
    мест += (t.match(new RegExp('(^|' + Г + ')' + w + '(' + Г + '|$)', 'gi')) || []).length;
  const пов = (t.match(/(^|[^а-яА-Я])(дай|виж|сложи|направи|провери|кажи|опитай|започни|извади|измери|обади|потърси|запиши|подготви|подръж|остави|вземи|намали|спри|избери|изчакай|прекарай|питай|звънни|легни|дишай|запомни|недей|гледай|снимай|проветри|пускай|обличай|слагай|дръж|мери|брой|чакай|тръгвай|тръгвайте|прибирай|прибирайте|пази|помни|избягвай|използвай|сипвай|храни|къпи|носи|сядай|ставай|излизай|говори|пей|четѐ|четете|почвай|карай|тествай|пробвай|сравни|отбележи|отметни|разкажи|поискай|настоявай|откажи|приеми|раздели|сменѝ|смени|измий|подсуши|завий|отвий|повдигни|наведи|подпри)([^а-яА-Я]|$)/gi) || []).length;
  return { гл, мест, пов, общо: гл + мест + пов };
};
// ── САМОПРОВЕРКА в ДВЕТЕ посоки ──
const A = второЛице('Какво гледаш, преди да звъннеш. Прекарай длан по корема.');
 const C = второЛице('Не гледай часовника, а детето. Прибирайте се при първите мокри ръкавици. Снимай го.');
const B = второЛице('Скарлатината е бактериална инфекция с обрив по гънките на тялото.');
if (!(A.общо >= 3)) { console.log('🔴 уредът НЕ ВИЖДА второ лице: ' + JSON.stringify(A)); process.exit(1); }
if (B.общо !== 0) { console.log('🔴 уредът ЛЪЖЕ НАГОРЕ: ' + JSON.stringify(B)); process.exit(1); }
if (!(C.общо >= 3)) { console.log('🔴 уредът не вижда повелителните: ' + JSON.stringify(C)); process.exit(1); }
 console.log('  ✅ самопроверка в двете посоки: вижда „гледаш/прекарай" (' + A.общо + '), не вижда учебникарско изречение (' + B.общо + ')');

const idx = JSON.parse(fs.readFileSync(К + 'lib/index.json', 'utf8'));
const мета = new Map((idx.items || []).map(a => [a.id, a]));
const тела = new Map();
for (const f of fs.readdirSync(К + 'lib').filter(f => /^[a-z0-9-]+\.json$/.test(f) && f !== 'index.json')) {
  const o = JSON.parse(fs.readFileSync(К + 'lib/' + f, 'utf8'));
  for (const [id, md] of Object.entries(o)) if (typeof md === 'string') тела.set(id, { md, файл: f });
}
const реду = [];
for (const [id, м] of мета) {
  const т = тела.get(id); if (!т) continue;
  const в = второЛице(т.md);
  const на1000 = в.общо / (т.md.length / 1000);
  реду.push({ id, t: м.t, r: м.r, файл: т.файл, n: т.md.length, ...в, гъстота: +на1000.toFixed(1) });
}
реду.sort((a, b) => a.гъстота - b.гъстота);
const N = реду.length;
const мед = реду[Math.floor(N / 2)].гъстота;
console.log('');
console.log('🗣️ ОБРЪЩЕНИЯ КЪМ МАЙКАТА на 1000 знака   —   ' + N + ' статии');
console.log('   средна гъстота: ' + мед + '   ·   най-ниска ' + реду[0].гъстота + '   ·   най-висока ' + реду[N - 1].гъстота);
console.log('');
const студ = реду.filter(x => x.гъстота < 2);
const леден = реду.filter(x => x.общо === 0);
console.log('  🔴 НИТО ЕДНО обръщение в цялата статия : ' + леден.length + '  (' + (леден.length / N * 100).toFixed(1) + '%)');
console.log('  🟠 под 2 обръщения на 1000 знака       : ' + студ.length + '  (' + (студ.length / N * 100).toFixed(1) + '%)');
console.log('');
const поФайл = {};
for (const x of студ) поФайл[x.файл] = (поФайл[x.файл] || 0) + 1;
const общоФайл = {};
for (const x of реду) общоФайл[x.файл] = (общоФайл[x.файл] || 0) + 1;
console.log('  ── КЪДЕ СА СТУДЕНИТЕ (файл: студени / всички) ──');
for (const [f, n] of Object.entries(поФайл).sort((a, b) => b[1] - a[1]))
  console.log('     ' + String(n).padStart(3) + ' / ' + String(общоФайл[f]).padEnd(4) + '  ' + f + '   ' + (n / общоФайл[f] > .5 ? '← почти целият файл' : ''));
console.log('');
console.log('  ── НАЙ-СТУДЕНИТЕ 20 ──');
for (const x of реду.slice(0, 20)) console.log('     ' + String(x.гъстота).padStart(4) + '  [' + x.r + '] ' + String(x.t).slice(0, 62));
fs.writeFileSync(__dirname + '/studeni.json', JSON.stringify(студ, null, 1));
console.log('');
console.log('  💾 dev/studeni.json  (' + студ.length + ' статии)');

// ═══ ПРАГ ═══
// 🪤 Отрядът, който стопли 69-те статии, намери следното: докато работеше,
//    библиотеката порасна от 907 на 919 статии и ДВЕ от новите се родиха
//    студени. Тоест писането ражда студени по-бързо, отколкото кампания ги
//    хваща. Затова уредът става ПАЗАЧ, а не еднократно мерене.
// 🪤 И ВТОРО, негово: писането на studeni.json беше ОТНОСИТЕЛНО спрямо
//    текущата папка — уред, пуснат от друга папка, презаписа собствения си
//    списък от 69 с новия от 2. Сега пътят е спрямо dev/.
const ПРАГ = Number(process.env.BL_STUDENI_PRAG || 0);
if (студ.length > ПРАГ) {
  console.log('');
  console.log('  🔴 НАД ПРАГА (' + ПРАГ + ') — има статия, която говори на майката като учебник');
  console.log('     лекът НЕ е да се напръска с „ти\": второто лице в българския живее в');
  console.log('     ОКОНЧАНИЕТО („какво гледаш\") и в повелителното („прекарай длан\").');
  process.exit(1);
}
console.log('  ✅ под прага ' + ПРАГ);
