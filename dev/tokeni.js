// 🎨 ПАЗАЧ НА ТОКЕНИТЕ — всяка var() има дефиниция, нула самопрепратки
// ═══════════════════════════════════════════════════════════════════════════
//
// ЗАЩО (07.09.2026, платено два пъти в един час):
//   dev/motion_tokeni.js замени 98 литерални криви с var(). Два пъти замени
//   и СAMИТЕ ДЕФИНИЦИИ, създавайки цикъл:
//       --bl-ease-spring: var(--bl-ease-spring);
//   Първия път в css/tier.css, втория в css/anim.css. Вторият работеше само
//   по СЛУЧАЙНОСТ — tier.css се зарежда след anim.css и печели в каскадата.
//   Смени ли се редът на файловете, движението изчезва наведнъж в 135 правила.
//
// ⚠️ И ЕДИН УРОК ЗА САМИЯ ПАЗАЧ: първата му версия четеше КОМЕНТАРИТЕ като
//    код и обяви за цикъл едно изречение, което ОПИСВАШЕ стария дефект.
//    Уред, който не различава код от бележка, вдига фалшива тревога върху
//    собствената си документация. Затова коментарите се махат ПРЕДИ четене.
//
// КАКВО ПРОВЕРЯВА:
//   1. всяка ползвана var(--bl-…) има дефиниция          → инак правилото пада
//   2. никоя дефиниция не сочи към себе си                → цикъл = невалидно
//   3. дефиниция в ДВА файла се показва                   → каскадата решава, но
//      мълчаливото разминаване е капан
//   4. празен резултат = СЛЯП УРЕД, не „чисто"
//
// ⚠️ ТОЗИ ФАЙЛ САМО ЧЕТЕ.
// ПУСКАНЕ: node dev/tokeni.js
// ═══════════════════════════════════════════════════════════════════════════
'use strict';
const fs = require('fs');
const path = require('path');
const КОРЕН = path.resolve(__dirname, '..');
process.chdir(КОРЕН);

// коментарите не са код
const безКоментари = s => s.replace(/\/\*[\s\S]*?\*\//g, ' ');

const деф = new Map();      // име → [[файл, стойност]]
const упот = new Map();     // име → брой
const цикли = [];

const файлове = fs.readdirSync('css').filter(f => /\.css$/.test(f));
for (const ф of файлове) {
  const сурово = fs.readFileSync(path.join('css', ф), 'utf8');
  const s = безКоментари(сурово);
  for (const m of s.matchAll(/(--bl-[a-z0-9-]+)\s*:\s*([^;{}]+);/g)) {
    const име = m[1], стойност = m[2].trim();
    деф.set(име, (деф.get(име) || []).concat([[ф, стойност]]));
    if (стойност.indexOf('var(' + име + ')') > -1) цикли.push(ф + ' → ' + име);
  }
  for (const m of s.matchAll(/var\((--bl-[a-z0-9-]+)\)/g)) {
    упот.set(m[1], (упот.get(m[1]) || 0) + 1);
  }
}

console.log('');
console.log('  🎨 ПАЗАЧ НА ТОКЕНИТЕ · ' + файлове.length + ' файла');

// 🩺 самопроверка: нула намерени токена значи счупен четец, не чист проект
if (!деф.size || !упот.size) {
  console.error('');
  console.error('  🔴 СЛЯП УРЕД: намерени ' + деф.size + ' дефиниции и ' + упот.size + ' употреби.');
  console.error('     Проектът има токени — значи четецът е счупен, не CSS-ът.');
  console.error('');
  process.exit(2);
}

console.log('');
console.log('  ── ДЕФИНИЦИИ ──');
const двойни = [];
for (const [име, места] of деф) {
  const редове = места.map(([ф, v]) => ф + ' = ' + v.slice(0, 34)).join('   |   ');
  console.log('     ' + име.padEnd(18) + редове);
  // повторна дефиниция е нормална САМО когато е нарочно пренастройване
  // (например утихване при reduce) — тоест когато е в друг блок на СЪЩИЯ файл
  const файлове2 = new Set(места.map(x => x[0]));
  if (файлове2.size > 1) двойни.push(име + ' (' + [...файлове2].join(' + ') + ')');
}

console.log('');
console.log('  ── ПОЛЗВАНИ ──');
let липсва = 0;
for (const [име, n] of [...упот].sort((a, b) => b[1] - a[1])) {
  const ок = деф.has(име);
  if (!ок) липсва++;
  console.log('     ' + (ок ? '✅' : '🔴 БЕЗ ДЕФИНИЦИЯ') + ' ' + String(n).padStart(4) + '×  ' + име);
}

console.log('');
console.log('  общо употреби : ' + [...упот.values()].reduce((a, b) => a + b, 0));
console.log('  самопрепратки : ' + (цикли.length ? '🔴 ' + цикли.join(', ') : '✅ нула'));
console.log('  без дефиниция : ' + (липсва ? '🔴 ' + липсва : '✅ нула'));
if (двойни.length) {
  console.log('  ⚪ в два файла : ' + двойни.join(', '));
  console.log('     (каскадата решава — по-късният файл печели. Не е дефект,');
  console.log('      но заслужава да се знае, за да не се разминат мълчаливо.)');
}
console.log('');
process.exit((цикли.length || липсва) ? 1 : 0);
