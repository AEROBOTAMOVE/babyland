#!/usr/bin/env node
/* eslint-disable */
// ═══════════════════════════════════════════════════════════════════════════
// 🪶 ПАЗАЧ НА ОПАШКИТЕ — шаблонни изречения на грешна тема
// ═══════════════════════════════════════════════════════════════════════════
//
// ЗАЩО (05.09): статията „Диастаза — раздалечените коремни мускули след
// раждане" — за корема на МАЙКАТА — завършваше с:
//     „Ти познаваш ДЕТЕТО си по начин, по който никой друг не го познава."
// Шаблонна опашка, залепена по инерция. Жена, която чете за собственото си
// тяло, получава на края изречение за детето — и то точно там, където
// текстът трябва да е за нея.
//
// Такъв дефект е невидим за всеки друг уред: статията е дълга, има 🚨,
// парсва се, минава пазача на числата. Само ЧЕТЕНЕ на края го хваща.
//
// КАКВО ПРОВЕРЯВА:
//   А. Статия за ТЯЛОТО НА МАЙКАТА, чийто край говори за ДЕТЕТО
//   Б. Статия за ДЕТЕТО, чийто край говори за тялото на майката
//   В. Шаблонна фраза, повторена ВЪТРЕ в една и съща статия
//   Г. Две статии, които започват с едно и също изречение
//
// ⚠️ ТОЗИ ФАЙЛ САМО ЧЕТЕ.
// ПУСКАНЕ: node dev/opashki.js  ·  --samoproverka
// Изход: 0 = чисто, 1 = има находки, 2 = самопроверката падна.
// ═══════════════════════════════════════════════════════════════════════════
'use strict';
const fs = require('fs');
const path = require('path');
const КОРЕН = path.resolve(__dirname, '..');
process.chdir(КОРЕН);
const САМО = process.argv.includes('--samoproverka');

const ix = JSON.parse(fs.readFileSync('lib/index.json', 'utf8'));
const тела = {};
for (const f of fs.readdirSync('lib').filter(x => /^[a-z0-9-]+\.json$/.test(x) && !x.startsWith('index')))
  Object.assign(тела, JSON.parse(fs.readFileSync('lib/' + f, 'utf8')));

// Темата на статията се чете от ЗАГЛАВИЕТО ѝ — то е най-надеждният сигнал.
const ЗА_МАЙКАТА = /диастаза|шев|шевове|цикъл|косопад|зъбите ми|тялото ми|тялото след|следродил|изпускане на урина|тазово дъно|мастит|гърдите ми|коремът ми след|либидо|контрацепц|менструац/i;
const ЗА_ДЕТЕТО = /бебе|дете|новородено|детск|бебешк|захранван|никнене|пелен|прохожд/i;
// Опашки, които говорят за ДЕТЕТО
const ОПАШКА_ДЕТЕ = /познаваш (детето|бебето) си|детето ти го знае|твоето бебе те знае|никой не познава детето|ти познаваш (него|нея) най-добре/i;
// Опашки, които говорят за ТЯЛОТО НА МАЙКАТА
const ОПАШКА_МАЙКА = /тялото ти (си )?знае|познаваш тялото си|твоето тяло (те )?носи/i;
const КРАЙ = 320;

const ФРАЗИ = [
  'довери се на усещането си', 'ти познаваш детето си', 'всяко бебе е различно',
  'не си сама', 'достатъчно добра майка', 'помни, че', 'важно е да',
  'всяка майка е различна', 'няма правилен начин',
];

function провери(корпус) {
  const находки = { А: [], Б: [], В: [], Г: [] };
  const начала = new Map();
  for (const i of корпус) {
    const t = тела[i.id] || i._тяло;
    if (!t) continue;
    const край = t.slice(-КРАЙ).replace(/\s+/g, ' ');

    // А · за майката, край за детето
    if (ЗА_МАЙКАТА.test(i.t) && !ЗА_ДЕТЕТО.test(i.t) && ОПАШКА_ДЕТЕ.test(край))
      находки.А.push({ id: i.id, t: i.t, край: край.slice(-130) });
    // Б · за детето, край за тялото на майката
    if (ЗА_ДЕТЕТО.test(i.t) && !ЗА_МАЙКАТА.test(i.t) && ОПАШКА_МАЙКА.test(край))
      находки.Б.push({ id: i.id, t: i.t, край: край.slice(-130) });

    // В · шаблонна фраза, повторена ВЪТРЕ в статията
    const низ = t.toLowerCase();
    for (const ф of ФРАЗИ) {
      let n = 0, поз = 0;
      while ((поз = низ.indexOf(ф, поз)) >= 0) { n++; поз += ф.length; }
      if (n > 1) находки.В.push({ id: i.id, ф, n });
    }

    // Г · еднакво начало
    const първо = t.replace(/^##[^\n]*\n+/, '').split(/[.!?]/)[0].trim().slice(0, 60).toLowerCase();
    if (първо.length >= 20) {
      if (!начала.has(първо)) начала.set(първо, []);
      начала.get(първо).push(i.id);
    }
  }
  for (const [н, л] of начала) if (л.length > 1) находки.Г.push({ начало: н, идове: л });
  return находки;
}

// ═══ САМОПРОВЕРКА: пазач, който не може да гръмне, е тишина ═══
if (САМО) {
  const примамки = [
    { id: 'проба-А', t: 'Диастаза след раждане', _тяло: 'Текст за корема на майката. Ти познаваш детето си по начин, по който никой друг не го познава.' },
    { id: 'проба-Б', t: 'Никнене на зъби при бебето', _тяло: 'Текст за бебето. Тялото ти знае какво прави.' },
    { id: 'проба-В', t: 'Нещо', _тяло: 'Не си сама в това. Много текст помежду. И пак: не си сама.' },
    { id: 'проба-Г1', t: 'Едно', _тяло: 'Това е съвсем еднакво първо изречение за проба. После друго.' },
    { id: 'проба-Г2', t: 'Друго', _тяло: 'Това е съвсем еднакво първо изречение за проба. После трето.' },
  ];
  const ч = { id: 'чиста', t: 'Шевовете долу', _тяло: 'Текст за шевовете. Ти познаваш това тяло по-добре от всеки друг.' };
  const н = провери(примамки);
  const нч = провери([ч]);
  let лошо = 0;
  const ред = (име, усл) => { console.log('     ' + (усл ? '✅' : '🔴') + ' ' + име); if (!усл) лошо++; };
  console.log('\n  🧪 САМОПРОВЕРКА НА ПАЗАЧА НА ОПАШКИТЕ\n');
  ред('хваща А: за майката, край за детето', н.А.length === 1);
  ред('хваща Б: за детето, край за майката', н.Б.length === 1);
  ред('хваща В: фраза, повторена вътре', н.В.length === 1);
  ред('хваща Г: две еднакви начала', н.Г.length === 1);
  ред('МЪЛЧИ върху чиста статия', нч.А.length === 0 && нч.Б.length === 0 && нч.В.length === 0);
  console.log('');
  process.exit(лошо ? 2 : 0);
}

// ═══ ИСТИНСКОТО ПУСКАНЕ ═══
const н = провери(ix.items);
console.log('');
console.log('  🪶 ПАЗАЧ НА ОПАШКИТЕ · прегледани ' + ix.items.length + ' статии');
console.log('');
const печат = (ключ, име) => {
  const л = н[ключ];
  console.log('  ' + (л.length ? '🔴' : '✅') + ' ' + име + ': ' + л.length);
  for (const x of л.slice(0, 8)) {
    if (ключ === 'Г') console.log('       ' + x.идове.join(' · ') + '  → „' + x.начало + '…"');
    else if (ключ === 'В') console.log('       ' + x.id + '  „' + x.ф + '" × ' + x.n);
    else { console.log('       ' + x.id + ' | ' + x.t.slice(0, 54)); console.log('          …' + x.край); }
  }
  if (л.length > 8) console.log('       … и още ' + (л.length - 8));
};
печат('А', 'статия за МАЙКАТА с опашка за ДЕТЕТО');
печат('Б', 'статия за ДЕТЕТО с опашка за тялото на майката');
печат('В', 'шаблонна фраза, повторена ВЪТРЕ в една статия');
печат('Г', 'две статии с еднакво първо изречение');
// ═══ ПРИЕТИ НАХОДКИ ═══
// Находка, прегледана с ЧЕТЕНЕ и призната за вярна, се записва тук с причина.
// Не се маха от проверката — печата се като приета, за да остане видима.
// Пазач, чието число е зелено чрез сваляне на летвата, не мери нищо.
const ПРИЕТИ = [
  { id: 'lib-90099b16', вид: 'В', ф: 'не си сама',
    защо: 'статия за безплодието и репродуктивната подкрепа. Двете места са в РАЗЛИЧЕН контекст — веднъж за самия път, веднъж за чуждата история — и точно това изречение е носещото ѝ послание. Повторението е нарочно.' },
];
const приета = x => ПРИЕТИ.some(п => п.id === x.id && (!п.ф || п.ф === x.ф));
const истински = ['А', 'Б', 'В', 'Г'].reduce((с, к) => с + н[к].filter(x => !приета(x)).length, 0);
const приетиБрой = ['А', 'Б', 'В', 'Г'].reduce((с, к) => с + н[к].filter(приета).length, 0);

if (приетиБрой) {
  console.log('  ── ПРИЕТИ (прегледани с четене и признати за верни) ──');
  for (const п of ПРИЕТИ) console.log('     ⚪ ' + п.id + ' · ' + (п.ф ? '„' + п.ф + '" · ' : '') + п.защо);
  console.log('');
}
console.log('  ' + (истински ? '🔴 ЗА ГЛЕДАНЕ: ' + истински : '✅ ЧИСТО') +
  (приетиБрой ? '   (плюс ' + приетиБрой + ' приети)' : ''));
console.log('');
process.exit(истински ? 1 : 0);
