// точният ред от helper.js respond()
function врата(т, стая) {
  try { const м = W.BL_MOTHERFLAG(т); if (м) return ['💜' + м, null]; } catch (e) {}
  try { if (W.BL_PREGFLAG(т, стая)) return ['🤰', null]; } catch (e) {}
  try { if (W.BL_REDFLAG(т)) return ['🚨', null]; } catch (e) {}
  for (const с of [стая].concat(СТАИ.filter(x => x !== стая))) {
    try {
      const р = W.BL_MATCH(т, с);
      const з = Array.isArray(р) ? р[0] : (р && (р.entry || р.item || р));
      if (з) return ['', з];
    } catch (e) {}
  }
  return ['', null];
}

