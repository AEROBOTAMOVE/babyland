def запиши(п, s):
    for ch in s:
        if 0xD800 <= ord(ch) <= 0xDFFF:
            raise SystemExit('🔴 СУРОГАТ — НЕ пиша.')
    b = s.encode('utf-8')
    стар = os.path.getsize(п)
    if len(b) < стар:
        raise SystemExit('🔴 Файлът се смалява %d → %d — НЕ пиша.' % (стар, len(b)))
    io.open(п, 'wb').write(b)


def блок_keys(текст, ид):
    m = re.search(r'id:\s*[\'"]' + re.escape(ид) + r'[\'"]', текст)
    if not m:
        return None
    k = текст.find('keys:', m.end())
    if k < 0 or k - m.end() > 400:
        return None
    ляво = текст.find('[', k)
    дясно = текст.find(']', ляво)
    return (ляво + 1, дясно, текст[ляво + 1:дясно]) if ляво > 0 and дясно > 0 else None


def цитат(s):
    return '"' + s + '"' if "'" in s else "'" + s + "'"


