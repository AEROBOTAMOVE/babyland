// 🪤 кирилицата: режем по КЛАС ОТ ЗНАЦИ, не по \b
function думи(текст) {
  return String(текст || '').toLowerCase()
    .replace(/\r?\n/g, ' ')
    .split(/[^а-яa-z0-9]+/)
    .filter(w => w.length >= 4 && !СЛУЖЕБНИ.has(w) && !/^[0-9]+$/.test(w));
}

// брой на всяка дума в един текст
function брои(текст) {
  const м = new Map();
  for (const w of думи(текст)) м.set(w, (м.get(w) || 0) + 1);
  return м;
}

// вериги от по 6 поредни думи
function вериги(текст, n = 6) {
  const w = думи(текст);
  const s = new Set();
  for (let i = 0; i + n <= w.length; i++) s.add(w.slice(i, i + n).join(' '));
  return s;
}

function косинус(a, b) {   // върху нормирани tf-idf вектори (Map дума→тежест)
  if (!a.size || !b.size) return 0;
  const [м, г] = a.size <= b.size ? [a, b] : [b, a];
  let с = 0;
  for (const [w, x] of м) { const y = г.get(w); if (y) с += x * y; }
  return с;
}
function съдържание(a, b) {   // дял на по-МАЛКОТО множество, което е вътре в другото
  if (!a.size || !b.size) return 0;
  const [м, г] = a.size <= b.size ? [a, b] : [b, a];
  let общи = 0;
  for (const w of м) if (г.has(w)) общи++;
  return общи / м.size;
}

