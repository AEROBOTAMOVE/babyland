//   ОПИТ 3 — истинските шаблони на живо: подавам мамина стойност и РАЗБИРАМ
//            получения HTML — броя дали от нейния текст е излязъл ЕЛЕМЕНТ.

const fs = require('fs'), path = require('path'), vm = require('vm');
const КОРЕН = path.resolve(__dirname, '..');
const файлове = fs.readdirSync(path.join(КОРЕН, 'js'))
  .filter(f => /\.js$/.test(f) && !/PREDI|\.BAK|ARCHIVE/.test(f)).map(f => 'js/' + f);

// ── Батерия: какво реално може да напише майка (или да ѝ дойде с внесено копие)
const ВРАЖДЕБНИ = [
  { име: 'начало на таг',      т: '<b>Мими</b>' },
  { име: 'скрипт',             т: '<img src=x onerror=alert(1)>' },
  { име: 'права кавичка',      т: 'Мими" onmouseover="alert(1)' },
  { име: 'апостроф',           т: "Мими' onfocus='alert(1)" },
  { име: 'затваряне на таг',   т: '</p><script>x</script><p>' },
  { име: 'амперсанд',          т: 'Мими &amp; Ани' },
  { име: 'нов ред',            т: 'ред1\nред2' },
  { име: 'обратна кавичка',    т: 'Мими`+alert(1)+`' },
  { име: 'долар-скоба',        т: 'Мими${alert(1)}' },
];

// ── МАЛЪК, НО ЧЕСТЕН РАЗБОР НА HTML ────────────────────────────────────────
// Не се преструва на браузър. Прави едно: намира къде започва ЕЛЕМЕНТ и къде
// започва АТРИБУТ, за да мога да питам „това дойде ли от текста на майката".
function тагове(html) {
  const изх = []; const р = /<\/?([a-zA-Z][a-zA-Z0-9-]*)((?:[^>"']|"[^"]*"|'[^']*')*)>/g; let m;
  while ((m = р.exec(html))) изх.push({ поз: m.index, таг: m[1], атрибути: m[2], цял: m[0] });
  return изх;
}
function атрибути(низ) {
  const изх = []; const р = /([a-zA-Z_:][-a-zA-Z0-9_:.]*)\s*(?:=\s*("[^"]*"|'[^']*'|[^\s"'>]+))?/g; let m;
  while ((m = р.exec(низ))) if (m[1]) изх.push({ име: m[1], стойност: m[2] });
  return изх;
}

