// 🔴 ПОПРАВКА (уредът гръмна на собствения си опит): режех определението с
//    /[^;]*?/ — а `'&amp;'` СЪДЪРЖА точка и запетая. Изразът се отрязваше
//    насред низа и излизаше `.replace(/&/g, '&amp)`. Точка и запетая вътре в
//    низ не е край на оператор. Затова краят се търси със СКАНИРАНЕ, което
//    знае къде е вътре в кавички.
function крайНаИзраз(т, поз) {
  let i = поз, д = 0, кав = null;
  const лимит = Math.min(т.length, поз + 1200);
  for (; i < лимит; i++) {
    const c = т[i], p = т[i - 1];
    if (кав) { if (c === кав && p !== '\\') кав = null; continue; }
    if (c === '"' || c === "'" || c === '`') { кав = c; continue; }
    if (c === '/' && т[i + 1] !== '/' && т[i + 1] !== '*' && /[=(,|&]\s*$/.test(т.slice(Math.max(0, i - 6), i))) {
      // начало на регулярка — прескачаме до незащитената затваряща /
      let j = i + 1, вКлас = false;
      for (; j < лимит; j++) {
        if (т[j] === '\\') { j++; continue; }
        if (т[j] === '[') вКлас = true;
        else if (т[j] === ']') вКлас = false;
        else if (т[j] === '/' && !вКлас) break;
      }
      i = j; continue;
    }
    if ('([{'.includes(c)) { д++; continue; }
    if (')]}'.includes(c)) { д--; continue; }
    if (c === ';' && д <= 0) break;
  }
  return i;
}

const escИзходни = new Map();   // изходен текст -> [файлове]
for (const f of файлове) {
  const т = fs.readFileSync(path.join(КОРЕН, f), 'utf8');
  const р = /const\s+(esc\w*)\s*=\s*/g; let m;
  while ((m = р.exec(т))) {
    const н = m.index, к = крайНаИзраз(т, m.index + m[0].length);
    const код = т.slice(н, к);
    if (!/replace/.test(код)) continue;
    const ключ = код.replace(/\s+/g, ' ');
    if (!escИзходни.has(ключ)) escИзходни.set(ключ, []);
    escИзходни.get(ключ).push(f + ':' + т.slice(0, н).split(/\r?\n/).length);
  }
}
console.log(`  различни определения на esc: ${escИзходни.size} (в ${[...escИзходни.values()].reduce((s, a) => s + a.length, 0)} места)\n`);

let общоСлаби = 0;
for (const [код, места] of escИзходни) {
  const ctx = vm.createContext({ String, RegExp });
  let fn; try { fn = vm.runInContext('(' + код.replace(/^const\s+esc\w*\s*=\s*/, '').replace(/;$/, '') + ')', ctx); }
  catch (e) { console.log('  ⚠ не мога да изпълня:', код.slice(0, 70)); continue; }
  const слаби = [];
  for (const в of ВРАЖДЕБНИ) {
    const изх = String(fn(в.т));
    // 1) излязъл ли е ЕЛЕМЕНТ от нейния текст
    if (тагове(изх).length && !/^ред1<br>ред2$/.test(изх)) слаби.push(в.име + ' → таг');
    // 2) останала ли е гола кавичка (чупи атрибут)
    else if (/"/.test(изх)) слаби.push(в.име + ' → останала "');
    else if (/'/.test(изх) && !/&#39;/.test(изх)) слаби.push(в.име + " → останал '");
  }
  const кратко = код.slice(0, 58).replace(/\s+/g, ' ');
  if (слаби.length) { общоСлаби++; console.log(`  ❌ ${места.length} места · ${кратко}…\n       СЛАБО ПРИ: ${слаби.join(' · ')}\n       напр. ${места.slice(0, 3).join(', ')}`); }
  else console.log(`  ✅ ${String(места.length).padStart(3)} места · държи всичките ${ВРАЖДЕБНИ.length} · ${кратко}…`);
}

// ═══ ОПИТ 2: мамино поле ВЪТРЕ В АТРИБУТ ═════════════════════════════════
console.log('\n═══ ОПИТ 2: мамина стойност вътре в атрибут ═══');
const МАМИНИ = /\.(name|note|txt|text|q|first|what|then|now)\b|load\s*\(\s*['"]bl_/;
const вАтрибут = [];
for (const f of файлове) {
  const т = fs.readFileSync(path.join(КОРЕН, f), 'utf8');
  // атрибут="…${X}…"  /  атрибут='…${X}…'  /  атрибут=${X}  (без кавички!)
  const р = /([a-zA-Z-]+)\s*=\s*(")([^"]*\$\{[^}]*\}[^"]*)"|([a-zA-Z-]+)\s*=\s*(')([^']*\$\{[^}]*\}[^']*)'|([a-zA-Z-]+)\s*=\s*(\$\{[^}]*\})/g;
  let m;
  while ((m = р.exec(т))) {
    const атр = m[1] || m[4] || m[7];
    const съдър = m[3] || m[6] || m[8];
    const безКавички = !!m[7];
    if (!МАМИНИ.test(съдър)) continue;
    вАтрибут.push({ файл: f, ред: т.slice(0, m.index).split(/\r?\n/).length, атр, безКавички,
      esc: /esc\s*\(/.test(съдър), къс: (атр + '=' + (m[2] || m[5] || '') + съдър).replace(/\s+/g, ' ').slice(0, 120) });
  }
}
if (!вАтрибут.length) console.log('  (нула)');
вАтрибут.forEach(x => console.log(`  ${x.esc && !x.безКавички ? '✔' : '⚠'} ${x.файл}:${x.ред}  ${x.безКавички ? '[БЕЗ КАВИЧКИ] ' : ''}${x.esc ? '' : '[БЕЗ esc] '}${x.къс}`));

// примамка за опит 2
const прим = `x.innerHTML = \`<div title="\${b.name}" data-y=\${b.note}></div>\`;`;
{
  const р = /([a-zA-Z-]+)\s*=\s*(")([^"]*\$\{[^}]*\}[^"]*)"|([a-zA-Z-]+)\s*=\s*(\$\{[^}]*\})/g;
  const н = [...прим.matchAll(р)].length;
  console.log(`  [примамка] очаквани 2 попадения, намерени ${н} → ${н === 2 ? '✅ уредът вижда' : '❌ СЛЯП'}`);
}

// ═══ ОПИТ 3: истински шаблони на живо ═══════════════════════════════════
console.log('\n═══ ОПИТ 3: враждебно име през ИСТИНСКИ шаблони ═══');
// вземаме реалната esc от js/rooms.js (най-често срещаната форма) и я пускаме
const кодRooms = fs.readFileSync(path.join(КОРЕН, 'js/rooms.js'), 'utf8');
const мEsc = кодRooms.match(/const\s+esc\s*=\s*([^;]*?replace\([^;]*?);/);
const escЖив = vm.runInContext('(' + мEsc[1] + ')', vm.createContext({ String, RegExp }));

const ШАБЛОНИ = [
  { къде: 'js/rooms2.js:333 (име на бебе в заглавие)', f: n => `<h4>${escЖив(n) || 'Бебето'}</h4>` },
  { къде: 'js/profile.js:751 (име на мама)',           f: n => `<strong>${escЖив(n || 'Мама')}</strong>` },
  { къде: 'ГОЛО (за сравнение — какво щеше да стане)',  f: n => `<h4>${n}</h4>` },
];
for (const ш of ШАБЛОНИ) {
  let счупени = 0; const примери = [];
  for (const в of ВРАЖДЕБНИ) {
    const html = ш.f(в.т);
    // от НЕЙНИЯ текст ли е излязъл таг: гледаме тагове, които не са наши
    const наши = тагове(ш.f('X')).map(t => t.цял).join('|');
    const нови = тагове(html).filter(t => !наши.includes(t.цял));
    if (нови.length) { счупени++; примери.push(в.име + ' → <' + нови[0].таг + '>'); }
  }
  console.log(`  ${счупени ? '❌' : '✅'} ${ш.къде.padEnd(46)} счупени ${счупени}/${ВРАЖДЕБНИ.length}` + (примери.length ? '  ' + примери.slice(0, 3).join(' · ') : ''));
}
console.log('\n  (последният ред е примамката: доказва, че разборът ВИЖДА счупване)');
