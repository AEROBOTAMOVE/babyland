// ═══════════════════════════════════════════════════════════
// 📋 ГЛАСЪТ 2 — коя статия звучи като здравна брошура, а не като приятелка
//
// ЗАЩО СЪЩЕСТВУВА (21.08): dev/glasat.js брои ТОПЛОТО (доверие в усета,
// разрешение, признаване на тежко) и пази да не бъде изтрито. Но топлото
// може да е НУЛА и в двете посоки — статия без нито един такъв ред просто
// не се вижда от него. Този уред гледа обратното: СТУДЕНОТО. Не „липсва ли
// топлина", а „има ли брошура".
//
// КАКВО БРОИ (пет признака, всеки поотделно, за да се вижда кой тежи):
//   1. ШАБЛОНЪТ      — „## С прости думи", „## Кое е важно да знаеш",
//                      „## Практически насоки", „## Ситуации, които сигурно
//                      познаваш". Това са заглавията на внесените брошури.
//                      Най-силният признак: 3 от 4 заедно е почти сигурно.
//   2. ПРЕДПИСАНИЯ   — „препоръчва се", „следва да", „необходимо е",
//                      „задължително е", „не се допуска", „при необходимост"
//   3. КАНЦЕЛАРИЯ    — „осъществява", „посредством", „с оглед на", „спрямо",
//                      „съгласно", „в рамките на", „относно", „при наличие на"
//   4. ДЪЛГИ ИЗРЕЧЕНИЯ — над 25 думи. Дълго изречение = загубена майка в 3 ч.
//   5. БЕЗ ТИ        — плътност на второто лице (ти, те, си, твоя, -еш/-иш/
//                      -аш/-яш). Нула „ти" на 1000 знака = говори се ЗА нея,
//                      не НА нея.
//
// 🪤 ЗАЩО НЕ Е ЕДНО ЧИСЛО: ако смеся петте в един резултат, статия с много
//    „ти" ще си купи опрощение за десет „препоръчва се". Затова показвам и
//    петте отделно, а подредбата е по СБОР ОТ ТОЧКИ, не по процент.
//
// 🪤 ВТОРО ЛИЦЕ В БЪЛГАРСКИ: `\w` НЕ хваща кирилица в JS (записано в паметта
//    на проекта). Затова навсякъде тук е [а-яА-Я], не \w.
//
// 🪤 ГРАНИЦИТЕ СА ИЗМЕРЕНИ, НЕ ИЗМИСЛЕНИ: прагът „над 25 думи" е зададен в
//    задачата; останалите прагове НЕ режат — те само подреждат. Уредът не
//    казва „тази е лоша", а „тази е най-студената от прегледаните N".
//
// ПУСКАНЕ:  node dev/glasat2.js            — челото на класацията
//           node dev/glasat2.js --vsichki  — всички 791
//           node dev/glasat2.js --id lib-x — една статия, с примерите
// ПЪТ НАЗАД: файлът само ЧЕТЕ. Нищо не записва.
// ═══════════════════════════════════════════════════════════
const fs = require('fs');
const path = require('path');
process.chdir(path.resolve(__dirname, '..'));

const ШАБЛОН = [
  /^##\s*С прости думи/m,
  /^##\s*Кое е важно да знаеш/m,
  /^##\s*Практически насоки/m,
  /^##\s*Ситуации, които сигурно познаваш/m
];

const ПРЕДПИСАНИЯ = /(препоръчва се|се препоръчва|препоръчително е|следва да|необходимо е|е необходимо|задължително е|не се допуска|при необходимост|по преценка на|се изисква|надлежно|уместно е|целесъобразно)/gi;

const КАНЦЕЛАРИЯ = /(осъществява|осъществяване|посредством|с оглед на|спрямо|съгласно|в рамките на|относно|при наличие на|в случай на|поради което|извършва се|провежда се|се прилага|се назначава|обезпечав|реализира се|с цел да се|представлява)/gi;

// второ лице: местоимения + окончания -еш/-иш/-аш/-яш
const ВТОРОЛИЦЕ = /(\bти\b|\bте\b|\bси\b|\bтвоя\b|\bтвоят\b|\bтвоето\b|\bтвоите\b|\bтвоя[тм]?\b|\bсебе си\b|[а-я]{2,}(?:еш|иш|аш|яш)\b)/gi;

function изречения(t) {
  return String(t)
    .replace(/^#{1,6}\s.*$/gm, ' ')      // заглавията не са изречения
    .replace(/^\s*[-•*]\s+/gm, ' ')      // точките в списък също не са
    .split(/(?<=[.!?…])\s+|\n{2,}/)
    .map(s => s.replace(/[*_`]/g, '').trim())
    .filter(s => s.length > 3);
}

function мери(t) {
  const текст = String(t);
  const знаци = текст.length || 1;
  const шаблон = ШАБЛОН.filter(r => r.test(текст)).length;
  const предп = (текст.match(ПРЕДПИСАНИЯ) || []);
  const канц = (текст.match(КАНЦЕЛАРИЯ) || []);
  const изр = изречения(текст);
  const дълги = изр.filter(s => s.split(/\s+/).length > 25);
  const второ = (текст.match(ВТОРОЛИЦЕ) || []).length;
  const наХиляда = x => +(x * 1000 / знаци).toFixed(2);

  // ── ТОЧКИ: всеки признак дава своя дял, никой не може сам да реши ──
  let точки = 0;
  точки += шаблон * 8;                                  // 0..32 — най-тежкото
  точки += Math.min(наХиляда(предп.length) * 6, 18);
  точки += Math.min(наХиляда(канц.length) * 4, 14);
  точки += Math.min(дълги.length / Math.max(изр.length, 1) * 40, 16);
  точки += второ === 0 ? 20 : Math.max(0, 20 - наХиляда(второ) * 2.2);

  return {
    знаци, шаблон,
    предписания: предп.length, предпНа1000: наХиляда(предп.length),
    канцелария: канц.length, канцНа1000: наХиляда(канц.length),
    изречения: изр.length, дълги: дълги.length,
    делДълги: +(дълги.length / Math.max(изр.length, 1) * 100).toFixed(1),
    второлице: второ, второНа1000: наХиляда(второ),
    точки: +точки.toFixed(1),
    примери: { предп: [...new Set(предп)].slice(0, 6), канц: [...new Set(канц)].slice(0, 6), дълго: дълги.slice(0, 2) }
  };
}

// ── зареждане ──
const idx = JSON.parse(fs.readFileSync('lib/index.json', 'utf8'));
const карта = new Map(idx.items.map(i => [i.id, i]));
const файлове = fs.readdirSync('lib').filter(f => /^[a-z]+-\d+\.json$/.test(f));
const тела = {};
for (const f of файлове) {
  const d = JSON.parse(fs.readFileSync('lib/' + f, 'utf8'));
  for (const k of Object.keys(d)) тела[k] = d[k];
}

const редове = [];
let прегледани = 0, безТяло = 0;
for (const it of idx.items) {
  const t = тела[it.id];
  if (t === undefined) { безТяло++; continue; }
  прегледани++;
  редове.push({ it, m: мери(t) });
}
редове.sort((a, b) => b.m.точки - a.m.точки);

const едно = process.argv.indexOf('--id');
if (едно > -1) {
  const id = process.argv[едно + 1];
  const r = редове.find(x => x.it.id === id);
  if (!r) { console.log('няма такава статия:', id); process.exit(1); }
  console.log('📋 ' + id + ' «' + r.it.t + '» [' + r.it.f + ']');
  console.log(JSON.stringify(r.m, null, 1));
  process.exit(0);
}

const всички = process.argv.includes('--vsichki');
const колко = всички ? редове.length : 30;

console.log('📋 ГЛАСЪТ 2 — брошура срещу приятелка\n');
console.log('  ПРЕГЛЕДАНИ СТАТИИ: ' + прегледани + ' от ' + idx.items.length + ' в index.json');
if (безТяло) console.log('  ⚠ БЕЗ ТЯЛО (непрегледани): ' + безТяло);
console.log('  файлове с тела: ' + файлове.length + '\n');

const сШаблон = редове.filter(r => r.m.шаблон >= 3).length;
const безТи = редове.filter(r => r.m.второлице === 0).length;
const многоПредп = редове.filter(r => r.m.предписания >= 3).length;
console.log('  ── общата картина ──');
console.log('  с брошурния шаблон (3-4 от 4-те заглавия): ' + сШаблон);
console.log('  с НУЛА второ лице (нито едно „ти"):        ' + безТи);
console.log('  с 3 и повече предписателни фрази:          ' + многоПредп);
const т = редове.map(r => r.m.точки).sort((a, b) => a - b);
console.log('  точки: медиана ' + т[Math.floor(т.length / 2)] + ' · 90-и персентил ' + т[Math.floor(т.length * 0.9)] + ' · връх ' + т[т.length - 1] + '\n');

console.log('  ── най-студените ' + колко + ' ──');
console.log('  точки шбл предп канц дълги/изр  ти/1000  файл           заглавие');
for (const r of редове.slice(0, колко)) {
  const m = r.m;
  console.log(
    '  ' + String(m.точки).padStart(5) +
    String(m.шаблон).padStart(4) +
    String(m.предписания).padStart(6) +
    String(m.канцелария).padStart(5) +
    (m.дълги + '/' + m.изречения).padStart(11) +
    String(m.второНа1000).padStart(9) + '  ' +
    r.it.f.padEnd(15) + r.it.t.slice(0, 60)
  );
}
console.log('\n  (шбл = колко от 4-те брошурни заглавия има; ти/1000 = плътност на второто лице)');
