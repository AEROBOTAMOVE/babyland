#!/usr/bin/env node
/* eslint-disable */
// ═══════════════════════════════════════════════════════════════════════════
// 🔗 КАРТА ↔ СТАТИЯ — на място ли е вързаната статия
// ═══════════════════════════════════════════════════════════════════════════
//
// ЗАЩО (05.09): 850 карти носят `lib`. Част от връзките са слагани на ръка,
// част от агенти, част от мен. Днес сам вързах zd-sinuzit за статия за
// КОКЛЮШ, защото търсенето ми съвпадна на думата „кашлица“ — хванах го само
// защото прочетох заглавието. Никой уред не пази от това.
//
// МЯРКАТА: картата и статията трябва да делят поне една СМИСЛЕНА дума.
// Служебните и галените („бебето“, „детето“, „кога“, „какво“) не се броят —
// те съвпадат винаги и не доказват нищо. Сравнява се по НАЧАЛО на думата,
// за да мине склонението („синузит“ ↔ „синузитът“).
//
// ⚠️ СЛЯПОТО ПЕТНО, КАЗАНО НАГЛАС: две статии на СЪСЕДНИ теми ще споделят
//    дума и ще минат. Уредът лови ГРУБОТО разминаване, не финото.
//
// ⚠️ ТОЗИ ФАЙЛ САМО ЧЕТЕ.
// ПУСКАНЕ: node dev/karta_statiya.js [--vsichki]
// ═══════════════════════════════════════════════════════════════════════════
'use strict';
const fs = require('fs');
const path = require('path');
const КОРЕН = path.resolve(__dirname, '..');
process.chdir(КОРЕН);
const ВСИЧКИ = process.argv.includes('--vsichki');
const W = require(path.join(КОРЕН, 'dev/pyasachnik.js')).zaredi(null);
const ix = JSON.parse(fs.readFileSync('lib/index.json', 'utf8'));
const поId = new Map(ix.items.map(i => [i.id, i]));
const тела = {};
for (const f of fs.readdirSync('lib').filter(x => /^[a-z0-9-]+\.json$/.test(x) && !x.startsWith('index')))
  Object.assign(тела, JSON.parse(fs.readFileSync('lib/' + f, 'utf8')));

const ПРАЗНИ = new Set(('бебето бебе бебета детето дете деца новородено новороденото майка майката мама '
  + 'кога какво как защо кой коя кое колко дали може мога има имам искам знам трябва прави правя '
  + 'това този тази тези което когато след преди сега вече още само много малко нещо нищо '
  + 'първи първите първата година години месец месеца месеци ден дни нощ нощем').split(/\s+/));
const думи = низ => String(низ || '').toLowerCase()
  .replace(/[^а-яa-z0-9\s]/gi, ' ').split(/\s+/)
  .filter(д => д.length >= 4 && !ПРАЗНИ.has(д));
const общаДума = (а, б) => а.some(x => б.some(y => (x.length <= y.length ? y.indexOf(x) === 0 : x.indexOf(y) === 0)));

const разминати = [], липсващи = [];
let проверени = 0;
for (const e of W.KB.entries) {
  for (const id of [].concat(e.lib || [])) {
    const ст = поId.get(id);
    if (!ст) { липсващи.push({ карта: e.id, lib: id }); continue; }
    проверени++;
    // картата дава заглавие + ключове, статията — заглавие + резюме + ключови думи
    const а = думи(e.title + ' ' + (e.keys || []).slice(0, 25).join(' '));
    const б = думи(ст.t + ' ' + (ст.s || '') + ' ' + (ст.k || ''));
    if (!общаДума(а, б)) {
      // втори шанс: срещу ТЯЛОТО на статията (по-широко)
      const в = думи(String(тела[id] || '').slice(0, 1200));
      if (!общаДума(а, в)) разминати.push({ карта: e.id, зк: e.title, lib: id, зс: ст.t });
    }
  }
}

console.log('');
console.log('  🔗 КАРТА ↔ СТАТИЯ · ' + проверени + ' връзки от ' + W.KB.entries.length + ' карти');
console.log('');
console.log('  ' + (липсващи.length ? '🔴' : '✅') + ' връзки към НЕСЪЩЕСТВУВАЩА статия: ' + липсващи.length);
for (const x of липсващи.slice(0, 10)) console.log('       ' + x.карта + ' → ' + x.lib);
console.log('  ' + (разминати.length ? '🟠' : '✅') + ' връзки БЕЗ нито една обща дума: ' + разминати.length);
for (const x of разминати.slice(0, ВСИЧКИ ? 999 : 20)) {
  console.log('       ' + x.карта.padEnd(24) + ' „' + x.зк.slice(0, 34) + '“');
  console.log('          → ' + x.lib.padEnd(20) + ' „' + x.зс.slice(0, 46) + '“');
}
if (!ВСИЧКИ && разминати.length > 20) console.log('       … и още ' + (разминати.length - 20));
console.log('');
const ПРАГ = 25;
const лошо = липсващи.length || разминати.length > ПРАГ;
console.log('  ' + (лошо ? '🔴 ЗА ГЛЕДАНЕ' : '✅ ЧИСТО (праг ' + ПРАГ + ' за разминатите)'));
console.log('');
process.exit(лошо ? 1 : 0);
