#!/usr/bin/env node
/* eslint-disable */
// ═══════════════════════════════════════════════════════════════════════════
// 🔑 НАМИРА ЛИ КЛЮЧЪТ СОБСТВЕНАТА СИ КАРТА
// ═══════════════════════════════════════════════════════════════════════════
//
// ЗАЩО (05.09): всяка карта носи ключове — думите, с които майката трябва да
// я намери. Но ключ, който НЕ води до своята карта, е обещание, което базата
// си дава сама и не изпълнява. Такъв дефект е невидим за всеки друг уред:
// картата съществува, ключът съществува, отговор ИМА — просто е чужд.
//
// ═══ КАКВО ПОКАЗА ПЪРВОТО ПУСКАНЕ (12 912 ключа) ═══
//   99.8% намират своята карта. НЕ намират 20:
//     · 3 са ТИШИНА — голи думи („бебето", „започна", „започне")
//     · 17 отиват при чужда карта
//   Тоест базата е здрава, а подозрението ми беше по-голямо от дефекта.
//
// ═══ И ЕДНО ПОДОЗРЕНИЕ, КОЕТО ИЗМЕРВАНЕТО ОБОРИ ═══
//   Голата едносрична дума („сън", „плач", „рита") не може да спечели сама —
//   прагът иска два. Но тя добавя 0.34 към картата си при ВСЯКО попадение
//   (score = best + 0.34 × others). Точно този механизъм накара картата
//   „Кога ще усетя бебето да мърда?" да печели СПРЕЛИТЕ движения.
//   Затова проверих системно: 731 голи ключа, и НУЛА от тях стоят на повече
//   от една карта. 15 проби с чужди въпроси, съдържащи гола дума → 13 верни.
//   ПРИСЪДА: голите ключове НЕ вредят системно. Случаят с движенията беше
//   специфичен — три карти се биеха за една тема.
//   ⚠️ Не махай голи ключове „за всеки случай". Мери първо.
//
// ПУСКАНЕ (от папката babyland):
//   node dev/klyuch_sam_sebe_si.js            — БЪРЗО: само голите и късите
//   node dev/klyuch_sam_sebe_si.js --vsichki  — всичките (~10 минути)
//   node dev/klyuch_sam_sebe_si.js --probi    — 15-те проби с чужди въпроси
//
// ⚠️ ТОЗИ ФАЙЛ САМО ЧЕТЕ. Изход: 0 = чисто, 1 = има находки.
// ═══════════════════════════════════════════════════════════════════════════
'use strict';
const path = require('path');
const КОРЕН = path.resolve(__dirname, '..');
process.chdir(КОРЕН);

const АРГ = process.argv.slice(2);
const ВСИЧКИ = АРГ.includes('--vsichki');
const ПРОБИ = АРГ.includes('--probi');

const W = require(path.join(КОРЕН, 'dev/pyasachnik.js')).zaredi(null);
const питай = (т, с) => {
  try {
    const р = W.BL_MATCH(т, с);
    const з = Array.isArray(р) ? р[0] : (р && (р.entry || р.item || р));
    return з ? з.id : 'ТИШИНА';
  } catch (e) { return 'ГРЕШКА'; }
};

console.log('');
console.log('  🔑 НАМИРА ЛИ КЛЮЧЪТ СОБСТВЕНАТА СИ КАРТА');
console.log('');

// ═══ ПРОБИТЕ: чужд въпрос, който СЪДЪРЖА гола дума ═══
if (ПРОБИ) {
  // Всеки от тези въпроси е за СЪВСЕМ ДРУГО, но носи гола дума от чужда карта.
  // Ако голите ключове вредяха системно, тук щеше да е клане.
  const проби = [
    ['иска само баня с мен вечер', 'Моето бебе', 'mb-bath'],
    ['плач при пишкане', 'Здраве и SOS', 'ns-urinna-infekciya'],
    ['сън на детето в яслата', 'Развитие и игри', 'in-gradina'],
    ['рита ме в ребрата нощем', 'Бременност', null],
    ['очи сълзят на бебето', 'Моето бебе', 'mb-oci'],
    ['ухо тече от бебето', 'Здраве и SOS', 'zd-ear'],
    ['мед за кашлица на 2 години', 'Захранване', 'lb-med-sol'],
    ['гади ми се от миризми в къщи', 'Бременност', 'br-toshnota'],
    ['слух проверка на 2 години', 'Здраве и SOS', null],
    ['вяло дете след ваксина', 'Здраве и SOS', 'zd-sled-vaksina'],
    ['сок за дете на 3 години', 'Захранване', 'zh-voda'],
    ['аки твърдо и боли', 'Здраве и SOS', 'zd-zapek'],
    ['срок за подаване на документи', 'Инструменти', 'in-dokumenti'],
    ['38 градуса навън жега', 'Здраве и SOS', null]
  ];
  let паднали = 0;
  for (const [т, с, чакам] of проби) {
    const г = питай(т, с);
    const ок = чакам === null ? true : г === чакам;
    if (!ок) паднали++;
    console.log('     ' + (чакам === null ? '⚪' : (ок ? '✅' : '🔴')) + ' „' + т.padEnd(30) + '" → ' + г +
      (чакам && !ок ? '   (чакам ' + чакам + ')' : ''));
  }
  console.log('');
  console.log('     ' + (паднали ? '🔴 ' + паднали + ' паднали' : '✅ всички с очакване минават') +
    '   (⚪ = няма установено очакване)');
  console.log('');
  process.exit(паднали ? 1 : 0);
}

// ═══ ОСНОВНОТО МЕРЕНЕ ═══
const карти = W.KB.entries;
const общоКлючове = карти.reduce((a, e) => a + (e.keys || []).length, 0);

let проверени = 0, намират = 0;
const тишини = [], чужди = [];
for (const e of карти) {
  for (const k of (e.keys || [])) {
    const низ = String(k).trim();
    // БЪРЗИЯТ режим гледа само ГОЛИТЕ (една дума) и двусловните под 14 знака —
    // там е рискът и там мереното става за секунди, не за десет минути.
    // 🪤 Първата ми версия пропускаше само многословни НАД 22 знака, тоест
    //    почти нищо: „бързият" режим мереше 11 000 ключа и падна по време.
    if (!ВСИЧКИ) {
      const думи = низ.split(/\s+/).length;
      if (думи > 2 || (думи === 2 && низ.length > 14)) continue;
    }
    проверени++;
    const г = питай(низ, e.room);
    if (г === e.id) { намират++; continue; }
    (г === 'ТИШИНА' ? тишини : чужди).push({ к: низ, своя: e.id, отива: г, стая: e.room });
  }
}

console.log('  ключове в базата : ' + общоКлючове);
console.log('  ПРОВЕРЕНИ        : ' + проверени + (ВСИЧКИ ? '  (всички)' : '  (голите и късите; за всички: --vsichki)'));
console.log('  намират своята   : ' + намират + '  (' + (намират * 100 / Math.max(1, проверени)).toFixed(1) + '%)');
console.log('  НЕ намират       : ' + (тишини.length + чужди.length));
console.log('');

if (тишини.length) {
  console.log('  ── ТИШИНА: ключът не води НИКЪДЕ (' + тишини.length + ') ──');
  console.log('     Такъв ключ не може да спечели (прагът иска две думи), но');
  console.log('     добавя 0.34 към картата си при ВСЯКО попадение. Мери, преди да махаш.');
  for (const т of тишини.slice(0, 20)) console.log('     🔇 „' + т.к.padEnd(26) + '"  своя: ' + т.своя);
  if (тишини.length > 20) console.log('     … и още ' + (тишини.length - 20));
  console.log('');
}
if (чужди.length) {
  console.log('  ── ОТИВА ПРИ ЧУЖДА КАРТА (' + чужди.length + ') ──');
  for (const ч of чужди.slice(0, 25)) console.log('     🔴 „' + ч.к.slice(0, 30).padEnd(30) + '"  своя: ' + ч.своя.padEnd(24) + ' отива: ' + ч.отива);
  if (чужди.length > 25) console.log('     … и още ' + (чужди.length - 25));
  console.log('');
}

// ═══ ГОЛИТЕ ДУМИ — брой и сблъсъци ═══
const голи = [];
for (const e of карти) for (const k of (e.keys || [])) if (!/\s/.test(String(k).trim())) голи.push({ к: String(k).trim(), карта: e.id });
const по = {};
for (const г of голи) (по[г.к] = по[г.к] || []).push(г.карта);
const сблъсъци = Object.entries(по).filter(([, л]) => new Set(л).size > 1);
console.log('  ── голите едносрични ключове ──');
console.log('     брой: ' + голи.length + ' · на ПОВЕЧЕ ОТ ЕДНА карта: ' + сблъсъци.length +
  (сблъсъци.length ? '' : '  ✅'));
for (const [k, л] of сблъсъци.slice(0, 10)) console.log('     🟠 „' + k + '" е на: ' + [...new Set(л)].join(', '));
console.log('');
process.exit((тишини.length + чужди.length + сблъсъци.length) ? 1 : 0);
