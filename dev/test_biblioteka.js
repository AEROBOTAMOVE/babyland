  // ── 3.3 🚨 редовете — пали ли се червената кутия ──
  function провериСирени(статии, тела) {
    var р = { прегледани_тела: 0, прегледани_реда: 0, редове_със_сирена: 0,
              ЗАЛЕПЕНИ: [], жълто_вътре_в_изречение: [] };
    статии.forEach(function (с) {
      var тяло = тела[с.id];
      if (typeof тяло !== 'string') return;
      р.прегледани_тела++;
      тяло.split('\n').forEach(function (сур) {
        р.прегледани_реда++;
        var l = сур.trim();
        var i = l.indexOf(СИРЕНА);
        if (i < 0) return;
        р.редове_със_сирена++;
        if (i === 0) return;                              // както трябва
        if (/^(#{1,6}\s|-\s|>\s|\*\s)/.test(l)) return;   // заглавие, точка, цитат
        var ляво = l.slice(0, i).replace(/\s+$/, '');
        var край = ляво.charAt(ляво.length - 1);
        if (ляво && '.!?…:»”“"\''.indexOf(край) >= 0)
          р.ЗАЛЕПЕНИ.push({ id: с.id, заглавие: (с.t || '').slice(0, 40), ред: l.slice(0, 120) });
        else
          р.жълто_вътре_в_изречение.push({ id: с.id, заглавие: (с.t || '').slice(0, 40), ред: l.slice(0, 120) });
      });
    });
    return р;
  }

  // ── 3.4 препратките „виж «заглавие»" ──
  // Съвпадението е меко нарочно: препратката „Сол и захар" сочи статия
  // „Сол и захар: защо не преди година", а „Растежните вълни" — „Апетитът
  // скача и спада — растежните вълни". Строгото равенство би обявило и
  // двете за счупени, а мама ги намира без проблем. Затова: точно, или
  // заглавието СЪДЪРЖА препратката като цяла фраза.
  // ⚠️ Главната буква и прозорецът наоколо са мерени, не гадани: kb.js пише и
  //    „Виж „5-те минути“ … в тази стая", и „виж „5-те минути“ … в таб „Стаята"".
  //    Без флага `i` първото изречение изобщо не се четеше, а с прозорец от 20
  //    знака надясно думите „в таб" оставаха отвън и препратката към КАРТА се
  //    обявяваше за висяща статия. Затова: без разлика в главните и 90 знака
  //    надясно.
  var ПРЕПРАТКА = /виж\s+[„"']([^„“"']{4,80})[“"']/gi;
  function провериПрепратки(текстове, заглавия) {
    var долни = заглавия.map(function (т) { return (т || '').toLowerCase(); });
    var р = { прегледани_текста: 0, намерени: 0, ВИСЯЩИ: [], ок: [], към_карта_в_стая: [] };
    текстове.forEach(function (т) {
      р.прегледани_текста++;
      var м, re = new RegExp(ПРЕПРАТКА.source, 'gi');
      while ((м = re.exec(т.текст)) !== null) {
        р.намерени++;
        var реф = м[1].trim(), низ = реф.toLowerCase();
        var къде = -1;
        for (var i = 0; i < долни.length; i++) { if (долни[i].indexOf(низ) >= 0) { къде = i; break; } }
        var около = т.текст.slice(Math.max(0, м.index - 60), м.index + м[0].length + 90);
        if (къде >= 0) р.ок.push({ източник: т.id, препратка: реф, сочи: заглавия[къде].slice(0, 55) });
        else if (/в таб|в тази стая|в Инструменти|в стая/i.test(около))
          р.към_карта_в_стая.push({ източник: т.id, препратка: реф, около: около.slice(-70) });
        else
          р.ВИСЯЩИ.push({ източник: т.id, препратка: реф, около: около.slice(-70) });
      }
    });
    return р;
  }

