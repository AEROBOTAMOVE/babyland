  // ═══════════════════════════════════════════════════════════
  function ред(група, име, очаквано, получено, мина, бележка) {
    return { група: група, име: име, ОЧАКВАНО: очаквано, ПОЛУЧЕНО: получено,
             мина: !!мина, бележка: бележка || '' };
  }
  function списък(масив, поле, макс) {
    if (!масив || !масив.length) return '(нищо)';
    return масив.slice(0, макс || 3).map(function (x) {
      return поле ? String(x[поле]).slice(0, 55) : String(x).slice(0, 55);
    }).join(' · ') + (масив.length > (макс || 3) ? ' … +' + (масив.length - (макс || 3)) : '');
  }

  // ── един ред от таблицата ТЪРСЕНИЯ ──
  function изпълниТърсене(т, search) {
    var резултат, заглавия = [], грешка = null;
    try {
      резултат = search(т.q, т.стая || null, т.n || 3) || [];
      заглавия = резултат.map(function (x) { return (x && x.t) || '(без заглавие)'; });
    } catch (e) {
      грешка = 'ГРЕШКА: ' + (e && e.message ? e.message : e);
      резултат = [];
    }
    var показ = грешка || (заглавия.length ? заглавия.join(' · ') : '(нищо)');
    var име = т.и + '   [„' + т.q + '"]';

    if (грешка) return ред(т.г, име, 'без изключение', показ, false);
    if (т.празно)
      return ред(т.г, име, 'НИТО ЕДНА статия (мълчание)',
        резултат.length + ' статии: ' + показ, резултат.length === 0);
    if (т.забрана) {
      var виновни = заглавия.filter(function (з) { return т.забрана.test(з); });
      return ред(т.г, име, 'нито едно заглавие с ' + т.дума,
        (виновни.length ? '🔴 ' + виновни.join(' · ') + '   (от: ' + показ + ')' : показ),
        виновни.length === 0);
    }
    if (т.искане)
      return ред(т.г, име, 'поне едно заглавие с ' + т.дума, показ,
        заглавия.some(function (з) { return т.искане.test(з); }));
    if (т.първа)
      return ред(т.г, име, 'ПЪРВАТА статия да е ' + т.дума,
        (заглавия[0] || '(нищо)') + '   (следващи: ' + заглавия.slice(1).join(' · ') + ')',
        !!заглавия.length && т.първа.test(заглавия[0]));
    if (т.стаяТрябва) {
      var стаи = резултат.map(function (x) { return x.r; });
      return ред(т.г, име, 'поне една статия от стая „' + т.стаяТрябва + '"',
        стаи.join(' · ') || '(нищо)', стаи.indexOf(т.стаяТрябва) >= 0);
    }
    if (т.макс)
      return ред(т.г, име, 'най-много ' + т.макс + ' статии',
        резултат.length + ' статии: ' + показ, резултат.length <= т.макс);
    if (т.безДубли) {
      var видени = {}, дубли = [];
      резултат.forEach(function (x) { if (видени[x.id]) дубли.push(x.id); видени[x.id] = 1; });
      return ред(т.г, име, '0 повторени id', дубли.length ? дубли.join(', ') : '0 (' + показ + ')',
        дубли.length === 0);
    }
    if (т.цели) {
      var осакатени = резултат.filter(function (x) { return !x || !x.id || !x.t; });
      return ред(т.г, име, 'всяка статия с id и заглавие',
        осакатени.length ? осакатени.length + ' осакатени' : резултат.length + ' цели: ' + показ,
        осакатени.length === 0);
    }
    return ред(т.г, име, '(няма условие)', показ, false, 'редът е без условие — поправи таблицата');
  }

