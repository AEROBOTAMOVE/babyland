  function снимка() {
    var s = {};
    try { for (var i = 0; i < localStorage.length; i++) { var k = localStorage.key(i); s[k] = localStorage.getItem(k); } }
    catch (e) { return null; }
    return s;
  }
  function разлика(а, б) {
    if (!а || !б) return ['(не мога да прочета localStorage)'];
    var изход = [], k;
    for (k in а) if (!(k in б)) изход.push('изчезнал: ' + k);
    for (k in б) if (!(k in а)) изход.push('нов: ' + k);
    for (k in а) if (k in б && а[k] !== б[k]) изход.push('променен: ' + k);
    return изход;
  }

  function празенДоклад(защо) {
    var д = { ПУСНАТИ_ТЕСТА: 0, ГРЕШКА: защо +
      ' — това НЕ е „0 провала", а 0 ПУСНАТИ теста.' };
    console.log('%c📚 ТЕСТ ЗА БИБЛИОТЕКАТА', 'font-size:15px;font-weight:700');
    console.log('%c🔴 ' + д.ГРЕШКА, 'color:#c62828;font-weight:700');
    window.BL_БИБЛИОТЕКА.последен = д;
    return д;
  }

  function провери() {
    console.log('%c📚 ТЕСТ ЗА БИБЛИОТЕКАТА', 'font-size:15px;font-weight:700');
    if (!window.BL_LIB || typeof window.BL_LIB.search !== 'function' ||
        typeof window.BL_LIB.поId !== 'function')
      return Promise.resolve(празенДоклад('липсва window.BL_LIB (js/lib.js не е зареден)'));

    var предиLS = снимка();
    console.log('дозареждам индекса и телата на статиите…');

    return Promise.resolve(window.BL_LIB.init()).then(function (индекс) {
      if (!индекс || !индекс.length)
        return празенДоклад('BL_LIB.init() върна празен индекс (lib/index.json не се зареди)');

      var пакети = {};
      индекс.forEach(function (с) { if (с.f) пакети[с.f] = 1; });
      var имена = Object.keys(пакети);

      return Promise.all(имена.map(function (f) {
        return Promise.resolve(window.BL_LIB.fetchBundle(f)).then(function (b) {
          return { f: f, тела: b || {} };
        }).catch(function (e) { return { f: f, тела: {}, грешка: String(e) }; });
      })).then(function (пакетите) {
        return довърши(индекс, пакетите, предиLS);
      });
    });
  }

  function довърши(индекс, пакетите, предиLS) {
    var редове = [];
    var тела = {}, поПакет = {};
    пакетите.forEach(function (п) {
      поПакет[п.f] = п.тела;
      for (var k in п.тела) тела[k] = п.тела[k];
    });

    // ── ГРУПА 1–5: търсенето ──
    ТЪРСЕНИЯ.forEach(function (т) { редове.push(изпълниТърсене(т, window.BL_LIB.search)); });

    // ── ГРУПА F: поId ──
    var ids = {};
    индекс.forEach(function (с) { ids[с.id] = с; });
    var първа = индекс[0];
    var поId1 = window.BL_LIB.поId(първа.id);
    редове.push(ред('F · поId', 'поId(истински id) връща записа   [' + първа.id + ']',
      'обект с id ' + първа.id, поId1 ? ('обект с id ' + поId1.id) : String(поId1),
      !!поId1 && поId1.id === първа.id));
    редове.push(ред('F · поId', 'поId(несъществуващ id) → null', 'null',
      String(window.BL_LIB.поId('lib-няма-такава-статия-12345')),
      window.BL_LIB.поId('lib-няма-такава-статия-12345') === null));
    редове.push(ред('F · поId', 'поId("") → null', 'null', String(window.BL_LIB.поId('')),
      window.BL_LIB.поId('') === null));
    var ненамерени = [], непълни = [];
    индекс.forEach(function (с) {
      var о = window.BL_LIB.поId(с.id);
      if (!о) { ненамерени.push(с.id); return; }
      if (!о.t || !о.r || !о.f) непълни.push(с.id);
    });
    редове.push(ред('F · поId', 'всеки id от индекса се намира през поId',
      '0 ненамерени от ' + индекс.length, ненамерени.length + ' ненамерени: ' + списък(ненамерени),
      ненамерени.length === 0));
    редове.push(ред('F · поId', 'всеки запис има заглавие, стая и пакет',
      '0 непълни от ' + индекс.length, непълни.length + ' непълни: ' + списък(непълни),
      непълни.length === 0));

    // ── ГРУПА G: `lib:` полетата в KB ──
    var записи = (window.KB && (window.KB.entries || window.KB.items)) || null;
    if (!записи) {
      редове.push(ред('G · lib: в KB', 'базата на знанието е налична', 'KB.entries',
        'няма window.KB — не мога да проверя нито едно lib: поле', false));
    } else {
      var л = провериLib(записи, ids);
      редове.push(ред('G · lib: в KB', 'има какво да се проверява (иначе зеленото е празно)',
        'поне 1 запис с lib:', л.с_lib + ' полета lib: в ' + л.прегледани_записа + ' записа', л.с_lib > 0));
      редове.push(ред('G · lib: в KB', 'НИТО ЕДНО lib: не виси',
        '0 висящи от ' + л.с_lib, л.ВИСЯЩИ.length + ' висящи: ' + списък(л.ВИСЯЩИ, 'сочи_към'),
        л.ВИСЯЩИ.length === 0));
      редове.push(ред('G · lib: в KB', 'всяко lib: се намира и през BL_LIB.поId',
        '0 разминавания', (function () {
          var лоши = [];
          записи.forEach(function (з) { if (з && з.lib && !window.BL_LIB.поId(з.lib)) лоши.push(з.lib); });
          return лоши.length + ' разминавания: ' + списък(лоши);
        })(), (function () {
          var ок = true;
          записи.forEach(function (з) { if (з && з.lib && !window.BL_LIB.поId(з.lib)) ок = false; });
          return ок;
        })()));
      редове.push(ред('G · lib: в KB', 'ЖЪЛТО: статията е в стаята на записа',
        '0 в чужда стая (не е грешка, но е за поглед)',
        л.друга_стая.length + ' в чужда стая: ' + списък(л.друга_стая, 'запис'),
        л.друга_стая.length === 0, 'жълто — статия от друга стая е позволена'));
    }

    // ── ГРУПА H: заглавие и резюме — по СТАЯ ──
    var полета = провериПолета(индекс, тела);
    var стаи = {};
    индекс.forEach(function (с) { (стаи[с.r || '(без стая)'] = стаи[с.r || '(без стая)'] || []).push(с); });
    Object.keys(стаи).sort().forEach(function (име) {
      var п = провериПолета(стаи[име], тела);
      редове.push(ред('H · заглавия', 'стая „' + име + '": всяка статия има ЗАГЛАВИЕ',
        '0 без заглавие от ' + стаи[име].length,
        п.без_заглавие.length + ' без заглавие: ' + списък(п.без_заглавие, 'id'),
        п.без_заглавие.length === 0));
      редове.push(ред('H · резюмета', 'стая „' + име + '": всяка статия има РЕЗЮМЕ',
        '0 без резюме от ' + стаи[име].length,
        п.без_резюме.length + ' без резюме: ' + списък(п.без_резюме, 'id'),
        п.без_резюме.length === 0));
    });

    // ── ГРУПА I: телата — по ПАКЕТ ──
    Object.keys(поПакет).sort().forEach(function (f) {
      var мои = индекс.filter(function (с) { return с.f === f; });
      var празни = мои.filter(function (с) { return !(тела[с.id] || '').trim(); });
      редове.push(ред('I · тела', 'пакет ' + f + ': всяко тяло е непразно СЛЕД дозареждане',
        '0 празни от ' + мои.length,
        празни.length + ' празни: ' + списък(празни, 'id'), празни.length === 0));
    });
    редове.push(ред('I · тела', 'нито едно тяло не е по-късо от 120 знака',
      '0 къси от ' + индекс.length,
      полета.късо_тяло.length + ' къси: ' + списък(полета.късо_тяло, 'id'),
      полета.късо_тяло.length === 0));
    var осиротели = [];
    for (var k in тела) if (!ids[k]) осиротели.push(k);
    редове.push(ред('I · тела', 'ЖЪЛТО: тяло без запис в индекса',
      '0 осиротели тела', осиротели.length + ': ' + списък(осиротели),
      осиротели.length === 0, 'жълто — мъртъв товар, не дупка за мама'));

    // ── ГРУПА J: резюме на строителски език ──
    редове.push(ред('J · езикът', 'НИТО ЕДНО резюме не почва с бележка към редактора',
      '0 такива от ' + индекс.length + ' резюмета',
      полета.редакторско_резюме.length + ': ' + списък(полета.редакторско_резюме, 'резюме', 2),
      полета.редакторско_резюме.length === 0));
    РЕДАКТОРСКИ.forEach(function (ш) {
      var мои = полета.редакторско_резюме.filter(function (x) { return x.шаблон === ш.име; });
      редове.push(ред('J · езикът', 'шаблон ' + ш.име, '0 резюмета',
        мои.length + ': ' + списък(мои, 'id'), мои.length === 0));
    });
    редове.push(ред('J · езикът', 'ЖЪЛТО: резюме-парче от списък (малка буква или „;" накрая)',
      '0 парчета', полета.фрагмент_резюме.length + ': ' + списък(полета.фрагмент_резюме, 'резюме', 2),
      полета.фрагмент_резюме.length === 0, 'жълто — чете се странно, но не е дупка'));

    // ── ГРУПА K: препратките „виж …" ──
    var текстове = индекс.map(function (с) { return { id: с.id, текст: тела[с.id] || '' }; });
    var заглавия = индекс.map(function (с) { return с.t || ''; });
    if (window.BL_ARTICLES_DATA)
      window.BL_ARTICLES_DATA.forEach(function (а) { if (а && а.title) заглавия.push(а.title); });
    if (записи) записи.forEach(function (з) { if (з && з.title) заглавия.push(з.title); });
    var пр = провериПрепратки(текстове, заглавия);
    редове.push(ред('K · препратки', 'има какво да се проверява (иначе зеленото е празно)',
      'поне 1 препратка „виж …"', пр.намерени + ' препратки в ' + пр.прегледани_текста + ' тела',
      пр.намерени > 0));
    редове.push(ред('K · препратки', 'всяка „виж «заглавие»" в СТАТИЯ сочи съществуващо заглавие',
      '0 висящи от ' + пр.намерени, пр.ВИСЯЩИ.length + ': ' + списък(пр.ВИСЯЩИ, 'препратка'),
      пр.ВИСЯЩИ.length === 0));
    // същото, но в текстовете на помощничките (kb.js) — те се четат от мама също
    var прKB = { намерени: 0, ВИСЯЩИ: [], към_карта_в_стая: [], ок: [] };
    if (записи) {
      var кбТекстове = [];
      записи.forEach(function (з) {
        if (!з) return;
        var т = [з.core, з.tip, з.follow].filter(Boolean).join('\n');
        if (т) кбТекстове.push({ id: з.id || '(без id)', текст: т });
      });
      прKB = провериПрепратки(кбТекстове, заглавия);
      редове.push(ред('K · препратки', 'всяка „виж «заглавие»" в KB сочи статия',
        '0 висящи от ' + прKB.намерени,
        прKB.ВИСЯЩИ.length + ': ' + списък(прKB.ВИСЯЩИ, 'препратка') +
        '   (към карта в стая, не статия: ' + прKB.към_карта_в_стая.length + ')',
        прKB.ВИСЯЩИ.length === 0));
    }

    // ── ГРУПА L: 🚨 редовете ──
    var сир = провериСирени(индекс, тела);
    редове.push(ред('L · сирени', 'има какво да се проверява (иначе зеленото е празно)',
      'поне 1 ред със 🚨', сир.редове_със_сирена + ' реда със 🚨 в ' + сир.прегледани_тела +
      ' тела / ' + сир.прегледани_реда + ' реда', сир.редове_със_сирена > 0));
    редове.push(ред('L · сирени', 'НИТО ЕДИН 🚨 не е залепен за края на изречение',
      '0 залепени от ' + сир.редове_със_сирена + ' реда със 🚨',
      сир.ЗАЛЕПЕНИ.length + ': ' + списък(сир.ЗАЛЕПЕНИ, 'ред', 2),
      сир.ЗАЛЕПЕНИ.length === 0));
    редове.push(ред('L · сирени', 'ЖЪЛТО: 🚨 навътре в изречение (украса, не кутия)',
      '0 такива', сир.жълто_вътре_в_изречение.length + ': ' +
      списък(сир.жълто_вътре_в_изречение, 'ред', 2),
      сир.жълто_вътре_в_изречение.length === 0, 'жълто — не пали кутията, но и не лъже'));

    // ── самопроверка ──
    var сам = самопроверка();
    var самОк = сам.every(function (с) { return с.ЛОВИ_ЛИ === 'ДА'; });

    // ── localStorage ──
    var следLS = снимка();
    var промени = разлика(предиLS, следLS);

    var паднали = редове.filter(function (р) { return !р.мина; });
    var жълти = паднали.filter(function (р) { return /^жълто/.test(р.бележка); });
    var червени = паднали.filter(function (р) { return !/^жълто/.test(р.бележка); });
    var поГрупи = {};
    червени.forEach(function (р) { поГрупи[р.група] = (поГрупи[р.група] || 0) + 1; });

    var доклад = {
      ПУСНАТИ_ТЕСТА: редове.length,
      МИНАЛИ: редове.length - паднали.length,
      ПАДНАЛИ_ЧЕРВЕНИ: червени.length,
      паднали_жълти: жълти.length,
      САМОПРОВЕРКА: самОк ? 'ОК — тестът пада на нарочно счупено (' + сам.length + ' сцени)' : 'СЧУПЕНА',
      ПОКРИТИЕ: {
        статии_в_индекса: индекс.length,
        дозаредени_пакета: Object.keys(поПакет).length,
        дозаредени_тела: Object.keys(тела).length,
        прегледани_реда_в_телата: сир.прегледани_реда,
        редове_със_сирена: сир.редове_със_сирена,
        прегледани_lib_полета: записи ? провериLib(записи, ids).с_lib : 0,
        прегледани_записа_в_KB: записи ? записи.length : 0,
        прегледани_препратки: пр.намерени + (прKB.намерени || 0),
        търсения_с_реални_въпроси: ТЪРСЕНИЯ.length
      },
      паднали_по_групи: поГрупи,
      ЧЕРВЕНИ: червени,
      ЖЪЛТИ: жълти,
      самопроверка_редове: сам,
      localStorage: {
        ключове_преди: предиLS ? Object.keys(предиLS).length : '(недостъпен)',
        ключове_след: следLS ? Object.keys(следLS).length : '(недостъпен)',
        ПРОМЕНИ: промени.length ? промени : 'НЯМА — нищо на мама не е пипано'
      },
      подробно: {
        висящи_lib: записи ? провериLib(записи, ids).ВИСЯЩИ : [],
        редакторски_резюмета: полета.редакторско_резюме,
        резюмета_парчета: полета.фрагмент_резюме,
        залепени_сирени: сир.ЗАЛЕПЕНИ,
        сирени_вътре_в_изречение: сир.жълто_вътре_в_изречение,
        висящи_препратки_в_статии: пр.ВИСЯЩИ,
        висящи_препратки_в_KB: прKB.ВИСЯЩИ,
        препратки_към_карта: (пр.към_карта_в_стая || []).concat(прKB.към_карта_в_стая || []),
        осиротели_тела: осиротели,
        къси_тела: полета.късо_тяло
      },
      всички_редове: редове
    };

    // ── изход в конзолата ──
    console.log('пуснати теста: ' + доклад.ПУСНАТИ_ТЕСТА +
      '  ·  минали: ' + доклад.МИНАЛИ +
      '  ·  ЧЕРВЕНИ: ' + доклад.ПАДНАЛИ_ЧЕРВЕНИ +
      '  ·  жълти: ' + доклад.паднали_жълти);
    console.log('покритие: ' + индекс.length + ' статии · ' + Object.keys(тела).length +
      ' дозаредени тела от ' + Object.keys(поПакет).length + ' пакета · ' +
      сир.прегледани_реда + ' прегледани реда · ' + доклад.ПОКРИТИЕ.прегледани_lib_полета +
      ' lib: полета · ' + доклад.ПОКРИТИЕ.прегледани_препратки + ' препратки');
    console.log('localStorage: ' + (промени.length ? '🔴 ПРОМЕНИ: ' + промени.join(', ')
      : 'непокътнат (' + (предиLS ? Object.keys(предиLS).length : '?') + ' ключа, 0 промени)'));

    if (!самОк) console.log('%c🔴 САМОПРОВЕРКАТА Е СЧУПЕНА — не вярвай на нищо отгоре',
      'color:#c62828;font-weight:700');
    else console.log('%c✔ самопроверка: тестът пада на нарочно счупено (' + сам.length +
      ' сцени, в двете посоки)', 'color:#2e7d32');
    console.table(сам);

    if (червени.length) {
      console.log('%c🔴 ЧЕРВЕНИ: ' + червени.length, 'color:#c62828;font-weight:700');
      console.table(червени.map(function (р) {
        return { група: р.група, тест: р.име, ОЧАКВАНО: р.ОЧАКВАНО, ПОЛУЧЕНО: р.ПОЛУЧЕНО };
      }));
    } else {
      console.log('%c✅ 0 червени от ' + редове.length + ' пуснати теста.',
        'color:#2e7d32;font-weight:700');
    }
    if (жълти.length) {
      console.log('%c⚠ жълти (за поглед, не присъда): ' + жълти.length, 'color:#ef6c00');
      console.table(жълти.map(function (р) {
        return { тест: р.име, ПОЛУЧЕНО: р.ПОЛУЧЕНО, защо_жълто: р.бележка };
      }));
    }

    window.BL_БИБЛИОТЕКА.последен = доклад;
    return доклад;
  }

  window.BL_БИБЛИОТЕКА = { провери: провери, последен: null,
                           търсения: ТЪРСЕНИЯ,
                           // отделните проверчици — за ръчно ровене
                           проверчици: { полета: провериПолета, lib: провериLib,
                                         сирени: провериСирени, препратки: провериПрепратки } };
  window.BL_LIBTEST = window.BL_БИБЛИОТЕКА;   // за писане без кирилица в конзолата
  console.log('📚 тестът за библиотеката е зареден → await BL_БИБЛИОТЕКА.провери()  (или BL_LIBTEST.провери())');
