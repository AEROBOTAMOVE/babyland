// ⚠️ ЧЕСТНОТО ПРЕДУПРЕЖДЕНИЕ, ПРЕДИ ВСЯКО ЧИСЛО:
//    „Процент от какво?" е по-важният въпрос. НЯМА външен списък „всичко, от
//    което една майка има нужда". Затова всеки процент тук е срещу знаменател,
//    който САМИ сме си направили — и такъв процент лесно става самопохвала.
//
//    Затова тук се мери с ЧЕТИРИ НЕЗАВИСИМИ знаменателя, и трите от тях НЕ са
//    писани, за да ласкаят:
//      1. СТРУКТУРА — колко от собствените ни карти са завършени (статия, чип,
//         възраст, тон). Тук 100% е постижимо и значи „нищо не е недовършено".
//      2. КОРПУС от 1016 изречения — писан е ОТ НАС, значи вижда каквото сме
//         строили. Висок процент тук значи по-малко, отколкото изглежда.
//      3. НЕЗАВИСИМ ИЗПИТ от 100 въпроса, писан БЕЗ да се гледа базата.
//         Този е най-честният и затова е най-нисък.
//      4. РАЗПРЕДЕЛЕНИЕ по възрасти и стаи — не е процент „готовност", а
//         показва къде е тънко.
//
//    🔑 Ако четирите се разминават, вярвай на НАЙ-НИСКИЯ.
//
// ПУСКАНЕ: node dev/dokade_sme.js
// ПЪТ НАЗАД: файлът само ЧЕТЕ.
// ═══════════════════════════════════════════════════════════
