const питай = (т, с) => {
  try { const р = W.BL_MATCH(т, с); const з = Array.isArray(р) ? р[0] : (р && (р.entry || р.item || р)); return з ? з.id : null; }
  catch (e) { return null; }
};
// 🪤 ПЪРВОТО ПУСКАНЕ ДАДЕ 86.4% спешни, а dev/korpus350.js казва 0 пропуснати
//    от 265. Едно от двете лъжеше. Отворих корпуса: той проверява И ТРЕТИ флаг —
//    `BL_PREGFLAG(текст, СТАЯ)` — а той връща false за всичко, ако стаята не е
//    подадена. Моята мярка го нямаше изобщо и подценяваше с 36 изречения.
//    Мярка, на която ѝ липсва един от трите входа, дава честно изглеждащо
//    число за непълен въпрос. Стаята идва от самия корпус (полето r).
const флаг = (т, стая) => {
  try { if (W.BL_REDFLAG(т)) return true; } catch (e) {}
  try { if (W.BL_MOTHERFLAG && W.BL_MOTHERFLAG(т)) return true; } catch (e) {}
  try { if (W.BL_PREGFLAG && W.BL_PREGFLAG(т, стая)) return true; } catch (e) {}
  return false;
};
const отговаря = (т, с) => !!питай(т, с) || флаг(т, с);   // ← както е в приложението: флагът също е отговор

const пр = (a, b) => b ? Math.round(a * 1000 / b) / 10 : 0;
const лента = п => {
  const n = Math.round(п / 5);
  return '█'.repeat(n) + '░'.repeat(20 - n);
};

