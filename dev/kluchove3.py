def запиши(п, s):
    for ch in s:
        if 0xD800 <= ord(ch) <= 0xDFFF:
            raise SystemExit('🔴 СУРОГАТ — НЕ пиша.')
    b = s.encode('utf-8')
    if len(b) < os.path.getsize(п):
        raise SystemExit('🔴 файлът се смалява — НЕ пиша.')
    io.open(п, 'wb').write(b)


def блок_keys(t, ид):
    m = re.search(r'id:\s*[\'"]' + re.escape(ид) + r'[\'"]', t)
    if not m:
        return None
    k = t.find('keys:', m.end())
    if k < 0 or k - m.end() > 400:
        return None
    л = t.find('[', k)
    д = t.find(']', л)
    return (л + 1, д, t[л + 1:д]) if л > 0 and д > 0 else None


def цитат(s):
    return '"' + s + '"' if "'" in s else "'" + s + "'"


