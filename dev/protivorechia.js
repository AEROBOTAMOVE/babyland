function нормализирай(s) {
  return String(s).toLowerCase().replace(/ё/g, 'е').replace(/\s+/g, ' ');
}

// 🪤 2: диапазонът се чете като диапазон
function еДиапазон(текст, поз) {
  const около = текст.slice(Math.max(0, поз - 30), поз + 30);
  return /между\s*\d|\d\s*(?:-|–|до)\s*\d/.test(около);
}

const източници = записи().concat(статии());
const намерени = new Map();   // тема|единица  →  [{стойност, ид, вид, откъс}]
let прегледаниИзточници = 0, прегледаниЧисла = 0;

for (const и of източници) {
  прегледаниИзточници++;
  const t = нормализирай(и.текст + ' ' + и.заглавие);
  if (!t.trim()) continue;
  for (const { ед, re } of ЕДИНИЦИ) {
    re.lastIndex = 0;
    let m;
    while ((m = re.exec(t))) {
      прегледаниЧисла++;
      const поз = m.index;
      const прозорец = t.slice(Math.max(0, поз - 90), поз + 90);
      // 🪤 3: темата се съставя от единицата + гнездото, не само от числото
      const гнездо = ГНЕЗДА.find(г => (!г.само || г.само.indexOf(ед) > -1) && г.корени.some(к => прозорец.indexOf(к) > -1));
      if (!гнездо) continue;
      const стойност = m[1].replace(',', '.').replace(/\s+/g, ' ');
      const ключ = гнездо.тема + ' | ' + ед;
      if (!намерени.has(ключ)) намерени.set(ключ, []);
      намерени.get(ключ).push({
        стойност: стойност,
        диапазон: еДиапазон(t, поз),
        ид: и.ид, вид: и.вид, заглавие: и.заглавие.slice(0, 44),
        откъс: t.slice(Math.max(0, поз - 46), поз + 46).trim()
      });
    }
  }
}

// ── групите с повече от една различна стойност
const подозрителни = [];
for (const [ключ, списък] of намерени) {
  const по_стойност = new Map();
  списък.forEach(x => {
    if (x.диапазон) return;                 // 🪤 2
    if (!по_стойност.has(x.стойност)) по_стойност.set(x.стойност, []);
    по_стойност.get(x.стойност).push(x);
  });
  if (по_стойност.size < 2) continue;
  подозрителни.push({ ключ, стойности: [...по_стойност.entries()].sort((a, b) => b[1].length - a[1].length) });
}

// най-опасните теми първо
