подозрителни.sort((a, b) => {
  const ta = ТЕЖЕСТ[a.ключ.split(' | ')[0]] ?? 50, tb = ТЕЖЕСТ[b.ключ.split(' | ')[0]] ?? 50;
  return ta - tb || b.стойности.length - a.стойности.length;
});

