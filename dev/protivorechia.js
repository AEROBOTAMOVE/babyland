// ── източниците: записите на помощничките + телата на статиите
function записи() {
  const t = fs.readFileSync('js/kb.js', 'utf8');
  const из = [];
  const re = /\{\s*id:\s*['"]([^'"]+)['"][\s\S]*?(?=\n    \{\s*id:|\n  \])/g;
  let m;
  while ((m = re.exec(t))) {
    const тяло = m[0];
    const загл = (тяло.match(/title:\s*['"]([^'"]{0,120})/) || [, ''])[1];
    const текст = (тяло.match(/core:\s*['"]([\s\S]*?)['"],\s*\n/) || [, ''])[1] + ' ' +
                  (тяло.match(/tip:\s*['"]([\s\S]*?)['"],\s*\n/) || [, ''])[1] + ' ' +
                  (тяло.match(/follow:\s*['"]([\s\S]*?)['"],\s*\n/) || [, ''])[1];
    из.push({ вид: 'запис', ид: m[1], заглавие: загл, текст: текст });
  }
  return из;
}
function статии() {
  const из = [];
  let индекс = {};
  try {
    const j = JSON.parse(fs.readFileSync('lib/index.json', 'utf8'));
    (j.items || []).forEach(x => индекс[x.id] = x.t || '');
  } catch (e) {}
  for (const f of fs.readdirSync('lib')) {
    if (!f.endsWith('.json') || /BAK|ARCHIVE|index/.test(f)) continue;
    let d; try { d = JSON.parse(fs.readFileSync('lib/' + f, 'utf8')); } catch (e) { continue; }
    for (const k in d) {
      const т = typeof d[k] === 'string' ? d[k] : JSON.stringify(d[k]);
      из.push({ вид: 'статия', ид: k, заглавие: индекс[k] || '', текст: т.replace(/<[^>]*>/g, ' ') });
    }
  }
  return из;
}

