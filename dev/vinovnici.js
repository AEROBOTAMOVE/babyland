function кой(текст) {
  const r = { червен: !!(W.BL_REDFLAG && W.BL_REDFLAG(текст)),
              майка: null, бременност: false };
  try { r.майка = W.BL_MOTHERFLAG ? W.BL_MOTHERFLAG(текст) : null; } catch (e) {}
  try { r.бременност = W.BL_PREGFLAG ? !!W.BL_PREGFLAG(текст) : false; } catch (e) {}
  return r;
}

// коя дума от списъка redFlags е виновна — пробваме всеки флаг поотделно
const KB = W.KB;
const RF = (KB && KB.redFlags) || [];
const norm = s => String(s || '').toLowerCase().replace(/[^\wа-яё\s]/gi, ' ').replace(/\s+/g, ' ').trim();
function виновник(текст) {
  const q = norm(текст), qw = q.split(' ');
  const пре = w => w.slice(0, Math.max(4, w.length - 1));
  const виновни = [];
  for (const f of RF) {
    const nf = norm(f), fw = nf.split(' ').filter(Boolean);
    let хит = false;
    if (fw.length < 2) хит = qw.some(x => x.startsWith(nf));
    else if (q.includes(nf)) хит = true;
    else хит = fw.every(w => qw.some(x => x.startsWith(пре(w))));
    if (хит) виновни.push(f);
  }
  return виновни;
}

