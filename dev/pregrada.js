const { zaredi } = require('./pyasachnik.js');

// закачаме се за вътрешностите — преградата няма изнесен вход навън
const КОТВА = 'window.BL_SLABO = () => слабоТекущо;';
const W = zaredi(src => {
  if (src.indexOf(КОТВА) < 0) throw new Error('котвата в helper.js липсва — поясът не може да мери');
  return src.replace(КОТВА, КОТВА +
    '\n  window.__PREGRADA = { looksMedical, MED_FREE, findEntry, вдига: преградатаСеВдига,' +
    ' слабо: () => слабоТекущо };');
});
const M = W.__PREGRADA;
if (!M || typeof M.вдига !== 'function') throw new Error('преградатаСеВдига липсва — уредът щеше да брои нули');

const преграда = (т, стая) => M.MED_FREE.has(стая) && M.looksMedical(т) && !M.вдига(т, стая);
const карта = (т, стая) => {
  try { const e = M.findEntry(т, стая); return e ? e.id + ' [' + e.room + ']' + (M.слабо() ? ' СЛАБО' : '') : '—'; }
  catch (e) { return 'ГРЕШКА'; }
};

