console.log('\n🚧 ПОЯСЪТ НА МЕДИЦИНСКАТА ПРЕГРАДА\n');
let паднали = 0, проверени = 0;
for (const стая of ['Жената в мен', 'Лабораторията']) {
  console.log('══════ ' + стая + ' ══════');
  const блокове = [
    ['ТЯЛОТО НА МАЙКАТА — минава', МИНАВАТ, false],
    ['ДОЗА · ДИАГНОЗА · ДЕТЕТО — преграда', ОСТАВАТ, true],
    ['НЕВИННИТЕ ВЪПРОСИ НА СТАЯТА — минава', НЕВИННИ, false]
  ];
  for (const [име, списък, искано] of блокове) {
    console.log('  · ' + име);
    for (const q of списък) {
      const п = преграда(q, стая); проверени++;
      const ок = (п === искано);
      if (!ок) паднали++;
      if (!ок) console.log('     ❌ ' + q.padEnd(38) + ' | ' + (п ? 'ПРЕГРАДА' : 'минава') + ' | ' + карта(q, стая));
    }
    console.log('     ' + (списък.length) + ' проверени');
  }
}
