const fs = require('fs');
const path = require('path');
const { zaredi } = require('./pyasachnik.js');

const СТАИ_С_ЛИЦЕ = new Set(['Моето бебе', 'Здраве и SOS', 'Захранване', 'Развитие и игри',
  'Дневник на мама', 'Жената в мен', 'Бременност', 'Инструменти', 'Лабораторията']);

function направи(опции) {
  const ЧАКА = !!(опции && опции.чака);
  const ПАМЕТ = ЧАКА ? { bl_lmp: '2026-04-01' } : { bl_baby: { birth: '2025-11-20', name: 'Мими' } };
  const W = zaredi(null, { памет: ПАМЕТ });
  const РОДИЛА = !ЧАКА, ЧАКА_СЕГА = ЧАКА;
  if (W.BL_REDFLAG('бебето не диша') !== true) throw new Error('СЛЯПА СОНДА');
  if (W.BL_REDFLAG('днес беше слънчево') === true) throw new Error('СЛЯПА СОНДА 2');

  const изв = fs.readFileSync(path.join(__dirname, '..', 'js/helper.js'), 'utf8');
  const бл = /const БЕЗ_ПОДАВАНЕ = \[([\s\S]*?)\];/.exec(изв);
  if (!бл) throw new Error('не намирам БЕЗ_ПОДАВАНЕ в helper.js — СЛЯПА МЯРКА');
  const БЕЗ_ПОДАВАНЕ = (бл[1].match(/'[a-z0-9-]+'/g) || []).map(x => x.slice(1, -1));
  if (БЕЗ_ПОДАВАНЕ.length < 13) throw new Error('прочетени само ' + БЕЗ_ПОДАВАНЕ.length + ' id');

  function присъда(t, стая) {
    if (typeof W.BL_SHAKEN === 'function' && W.BL_SHAKEN(t)) return { вид: 'тревога', как: 'shaken' };
    const m = W.BL_MOTHERFLAG(t); if (m) return { вид: 'тревога', как: m };
    if (W.BL_PREGFLAG(t, стая || null)) return { вид: 'тревога', как: 'preg' };
    if (W.BL_REDFLAG(t)) return { вид: 'тревога', как: 'red' };
    const k = W.BL_MATCH(t, стая || null);
    let слабо = W.BL_SLABO ? !!W.BL_SLABO() : false;         // питай ВЕДНАГА след BL_MATCH
    const фраза = W.BL_FRAZA ? !!W.BL_FRAZA() : false;       // 🚪 16.09: и това веднага
    const скор = W.BL_SKOR ? +W.BL_SKOR() : 0;               // и това
    if (!k) return { вид: 'тишина' };
    // гейтът от helper.js:4340 — родила жена не се бута към стая „Бременност"
    if (k.room === 'Бременност' && стая !== 'Бременност' && РОДИЛА && !ЧАКА_СЕГА && !(k.до > 0)) слабо = true;
    if (k.room === стая) return { вид: 'вярна', как: k.id, стая: k.room };
    if (!слабо && СТАИ_С_ЛИЦЕ.has(k.room) && БЕЗ_ПОДАВАНЕ.indexOf(k.id) < 0
        && !(фраза && скор >= 5 && !(стая === 'Бременност' && ['Моето бебе', 'Захранване', 'Развитие и игри', 'Здраве и SOS'].indexOf(k.room) > -1))
        && !(k.room === 'Бременност' && k.до > 0 && РОДИЛА && !ЧАКА_СЕГА))
      return { вид: 'врата', как: k.id, стая: k.room };
    return { вид: слабо ? 'пита' : 'вярна', как: k.id, стая: k.room };
  }
  return { W, присъда, БЕЗ_ПОДАВАНЕ, ЧАКА };
}

module.exports = { направи, СТАИ_С_ЛИЦЕ };
