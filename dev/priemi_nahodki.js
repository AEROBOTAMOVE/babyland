// ── от „js/kb.js карта dn-skrol поле follow" вадим файла ──
const файлът = м => {
  const s = String(м || '');
  // 🪤 РЕДЪТ В РЕДУВАНЕТО. Първо написах (?:js|json|css) и „lib/baby-1.json" даваше
  //    „lib/baby-1.js" — изразът хваща js, защото json ЗАПОЧВА с js, и спира там.
  //    Резултат: девет истински находки бяха обявени за „файлът не съществува".
  //    По-дългото окончание ВИНАГИ стои първо, и накрая се слага граница.
  const m = s.match(/((?:js|lib|css)\/[A-Za-z0-9_.-]+\.(?:json|css|js))(?![A-Za-z0-9])/);
  return m ? m[1] : null;
};

// ═══ ОСЕМТЕ ПРОВЕРКИ ═══
const числаВ = т => (String(т).match(/\d+(?:[.,]\d+)?/g) || []);
const СПЕШНИ = ['🚨', '112', '150', '116', 'веднага', 'спешн', 'лекар', 'педиатър', 'болниц', 'линейк', 'не чакай', 'същия ден'];
const ВЪЗРАСТИ = /(\d+\s*(?:месец|месеца|месеч|годин|седмиц|ден|дни|дена))|(под\s*\d+)|(над\s*\d+)|новородено|кърмаче/gi;

function провери(н, текст, предупреждения) {
  const беди = [];
  предупреждения = предупреждения || [];
  const старо = String(н.staro || н.старо_дословно || '');
  const ново = String(н.novo || н.ново_дословно || '');
  if (!старо || !ново) return ['празно старо или ново'];

  // 1 · съществува ли точно веднъж
  const бр = текст.split(старо).length - 1;
  if (бр === 0) беди.push('старият низ НЕ СЪЩЕСТВУВА във файла');
  else if (бр > 1) беди.push('старият низ се среща ' + бр + ' пъти — не е уникален');

  // 2 · изгубено число
  const сЧ = числаВ(старо), нЧ = числаВ(ново);
  const липсващи = сЧ.filter(x => nБрой(сЧ, x) > nБрой(нЧ, x));
  if (липсващи.length) беди.push('ИЗЧЕЗНАЛО число: ' + [...new Set(липсващи)].join(', '));

  // 3 · изгубена спешност
  for (const д of СПЕШНИ) {
    const с = (старо.toLowerCase().split(д.toLowerCase()).length - 1);
    const нн = (ново.toLowerCase().split(д.toLowerCase()).length - 1);
    if (с > нн) { беди.push('ИЗЧЕЗНАЛА спешност: „' + д + '" (' + с + ' → ' + нн + ')'); break; }
  }

  // 4 · изгубена възраст
  const сВ = (старо.match(ВЪЗРАСТИ) || []).map(x => x.toLowerCase().replace(/\s+/g, ' '));
  const нВ = (ново.match(ВЪЗРАСТИ) || []).map(x => x.toLowerCase().replace(/\s+/g, ' '));
  const изчезнали = сВ.filter(x => nБрой(сВ, x) > nБрой(нВ, x));
  if (изчезнали.length) беди.push('ИЗЧЕЗНАЛА възраст: ' + [...new Set(изчезнали)].join(', '));

  // 5 · права кавичка или апостроф (те затварят низа в kb.js)
  // 🪤 ПОПРАВЕНО: тази проверка отхвърли ВСИЧКИТЕ 97 находки на отряда за
  //    вратите — а те пипат РЕДОВЕ КОД от вида `lib: ['lib-a1b2c3']`, където
  //    апострофът Е синтаксисът, не текст. Мярка, която реже кода за това, че
  //    е код, не пази нищо.
  //    Разграничението: проверява се само ако новото е ПРОЗА — тоест носи
  //    български думи ИЗВЪН кавичките. Ред, който е чист код (ключ: стойност,
  //    списък от идентификатори), се съди по проверка 7 — парсва ли се.
  const извънКавички = ново.replace(/'[^']*'/g, '').replace(/"[^"]*"/g, '');
  const еПроза = /[а-яА-Я]{3}/.test(извънКавички);
  if (еПроза && /["']/.test(ново))
    беди.push('ПРАВА кавичка или АПОСТРОФ в новия текст — затваря JS низа');

  // 6 · раздуване
  // 🪤 ПОПРАВЕНО СЛЕД ПЪРВОТО ПУСКАНЕ. Прагът беше 45% и отхвърли 12 от 36
  //    поправки за знака 🚨 — а тяхната ЦЕЛ е да ДОПИШАТ действие след знака
  //    („тръгвай при педиатъра днес"). Добавено изречение по определение
  //    удължава. Мярка, която реже точно поправката, за която е повикана, е
  //    строга не където трябва.
  //    Разграничението: ЗАГУБАТА е опасна (проверки 2-4 и си остават откази),
  //    ДОБАВКАТА е самата работа. Затова раздуването реже само при явно
  //    преписване — над 200% И над 200 знака — а между двете е предупреждение.
  const ръст = ново.length / Math.max(1, старо.length);
  if (ръст > 3 && ново.length - старо.length > 200)
    беди.push('ПРЕПИСАН, не поправен: ' + Math.round((ръст - 1) * 100) + '% (' + старо.length + ' → ' + ново.length + ')');
  else if (ръст > 1.45 && ново.length - старо.length > 60)
    предупреждения.push('пораснал с ' + Math.round((ръст - 1) * 100) + '% (' + старо.length + ' → ' + ново.length + ')');

  return беди;
}
function nБрой(масив, x) { return масив.filter(y => y === x).length; }

// ═══ САМОПРОВЕРКА — примамка за всяка от шестте мерими проверки ═══
function самопроверка() {
  const текст = 'Това е примерен текст с 38 градуса и 🚨 при бебе под 3 месеца, веднага при лекар.';
  const случаи = [
    ['несъществуващ стар низ', { staro: 'няма ме никъде тук', novo: 'нещо' }, 'НЕ СЪЩЕСТВУВА'],
    ['изчезнало число', { staro: 'с 38 градуса', novo: 'с висока температура' }, 'ИЗЧЕЗНАЛО число'],
    ['изчезнала спешност', { staro: '🚨 при бебе', novo: 'при бебе' }, 'ИЗЧЕЗНАЛА спешност'],
    ['изчезнала възраст', { staro: 'под 3 месеца', novo: 'при малко бебе' }, 'ИЗЧЕЗНАЛА възраст'],
    ['права кавичка', { staro: 'веднага при лекар', novo: 'веднага при "лекар"' }, 'ПРАВА кавичка'],
    // 🪤 Примамката ми беше сгрешена, не правилото: сложих БЪЛГАРСКИ думи извън
    //    кавичките и редът правилно се обяви за проза. Истинският ред от kb.js
    //    изглежда точно така — само ключове на латиница, кирилицата е ВЪТРЕ.
    ['РЕД КОД с апостроф МИНАВА (апострофът е синтаксис)', { staro: 'примерен текст', novo: ['id: ', 'x', ', room: ', 'Дневник на мама', ', lib: [', 'lib-a1b2c3', '],'].join(String.fromCharCode(39)) }, null],
    // 🪤 Тази примамка беше написана за СТАРОТО поведение (отказ при 45%) и
    //    падна, когато прагът стана предупреждение. Мярка, чиято примамка не е
    //    пренаписана заедно с правилото, обявява ЖИВА порта за счупена.
    //    Сега проверява каквото трябва: умереният ръст МИНАВА, но НЕ мълчи.
    ['умерен ръст минава, но вдига ПРЕДУПРЕЖДЕНИЕ', { staro: 'веднага при лекар', novo: 'веднага при лекар и още доста думи отгоре, които го правят чувствително по-дълъг' }, null, 'пораснал'],
    ['чиста замяна МИНАВА', { staro: 'примерен текст', novo: 'примерен текстец' }, null],
    ['ДОБАВЕНО действие минава (не е загуба)', { staro: 'веднага при лекар', novo: 'веднага при лекар — тръгвай при педиатъра още днес, а нощем към спешния кабинет' }, null],
    ['ПРЕПИСАН се хваща', { staro: 'веднага при лекар', novo: 'веднага при лекар '+'и още цял абзац, който няма нищо общо със стария текст и просто го замества с нещо съвсем друго, дълго и чуждо, '.repeat(3) }, 'ПРЕПИСАН']
  ];
  let паднали = 0;
  const редове = [];
  for (const [име, н, чакам, чакамПред] of случаи) {
    const пред = [];
    const беди = провери(н, текст, пред);
    let хванато = чакам ? беди.some(b => b.indexOf(чакам) >= 0) : беди.length === 0;
    if (чакамПред) хванато = хванато && пред.some(p => p.indexOf(чакамПред) >= 0);
    if (!хванато) паднали++;
    редове.push([хванато, име, беди.join(' | ').slice(0, 70) || '(чисто)']);
  }
  return { паднали, редове };
}

const сп = самопроверка();
