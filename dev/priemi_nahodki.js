// 📥 ПРИЕМАНЕ НА НАХОДКИ — механичната порта пред всяка чужда поправка
//
// ЗАЩО (02.09): работен поток върна 148 предложени замени от пет отряда, но
// адверсарните скептици бяха отрязани от лимит. Тоест сто четиридесет и осем
// поправки, за които НИКОЙ не е проверил дори че старият текст съществува.
//
// 🔑 Прилагането им наведнъж е точно грешката, която тази база е плащала
//    най-често: `String.replace` НЕ ГЪРМИ, когато не намери нищо. Сто
//    четиридесет и осем „успешни" замени, от които половината не са станали,
//    изглеждат абсолютно същото като сто четиридесет и осем сработили.
//
// Този уред е ПОРТА. Той не преценява дали поправката е УМНА — за това има
// скептици. Той мери само това, което машина може да измери сигурно, и
// отхвърля всичко, което не мине. Осем проверки, всяка с примамка:
//
//   1. старият низ съществува в живия файл ТОЧНО ВЕДНЪЖ
//   2. новият текст не ГУБИ число, което е било в стария
//   3. новият не губи 🚨, 112, „веднага", „лекар" — думите на спешността
//   4. новият не губи възраст („3 месеца", „под година")
//   5. няма ПРАВА кавичка или АПОСТРОФ (те затварят низа в kb.js)
//   6. новият не е по-дълъг с над 45% (раздуване без факт)
//   7. файлът се парсва/е валиден JSON СЛЕД замяната
//   8. броят карти/статии не се променя
//
// ПУСКАНЕ:
//   node dev/priemi_nahodki.js <файл.json>            ← само мери, НЕ пише
//   node dev/priemi_nahodki.js <файл.json> --pishi    ← прилага минахите
//   node dev/priemi_nahodki.js <файл.json> --samo bezopasnost
//
// ПЪТ НАЗАД: при --pishi всеки пипнат файл получава <име>.PREDI_PRIEM.
// ═══════════════════════════════════════════════════════════
