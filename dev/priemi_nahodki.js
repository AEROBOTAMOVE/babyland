console.log('');
console.log('   САМОПРОВЕРКА (иначе присъдите отдолу не значат нищо):');
for (const [ок, име, бел] of сп.редове)
  console.log('      ' + (ок ? '✅' : '🔴') + ' ' + име.padEnd(24) + ' ' + бел);
if (сп.паднали) { console.log(''); console.log('   🔴 ПОРТАТА Е СЧУПЕНА — не ѝ вярвай'); process.exit(1); }
console.log('');

// ═══ СЪДЕНЕ ═══
const поФайлове = new Map();
for (const н of НАХОДКИ) {
  const ф = файлът(н.myasto || н.място);
  if (!ф) { (поФайлове.get('(без файл)') || поФайлове.set('(без файл)', []).get('(без файл)')).push({ н, беди: ['не мога да разчета кой е файлът от „' + String(н.myasto || н.място).slice(0, 50) + '"'] }); continue; }
  if (!поФайлове.has(ф)) поФайлове.set(ф, []);
  поФайлове.get(ф).push({ н });
}

let минали = 0, паднали = 0;
const записи = [];
for (const [ф, списък] of поФайлове) {
  if (ф === '(без файл)') { for (const x of списък) { паднали++; записи.push({ ф, ...x, ок: false }); } continue; }
  const П = path.join(ROOT, ф);
  if (!fs.existsSync(П)) { for (const x of списък) { паднали++; x.беди = ['файлът не съществува']; записи.push({ ф, ...x, ок: false }); } continue; }
  const текст = fs.readFileSync(П, 'utf8');
  for (const x of списък) {
    const пред = [];
    const беди = x.беди || провери(x.н, текст, пред);
    x.пред = пред;
    const ок = беди.length === 0;
    if (ок) минали++; else паднали++;
    записи.push({ ф, н: x.н, беди, пред: x.пред || [], ок });
  }
}

// ── извеждане ──
const поТежест = {};
for (const з of записи) {
  const т = String(з.н.tejest || з.н.тежест || '—');
  поТежест[т] = поТежест[т] || { мина: 0, падна: 0 };
  поТежест[т][з.ок ? 'мина' : 'падна']++;
}
console.log('   НАХОДКИ: ' + записи.length + (САМО ? '   (само тежест „' + САМО + '") ' : ''));
console.log('   ✅ минават портата : ' + минали);
console.log('   🔴 отхвърлени      : ' + паднали);
console.log('');
console.log('   по тежест: ' + Object.entries(поТежест).map(([т, о]) => т + ' ' + о.мина + '✅/' + о.падна + '🔴').join('  ·  '));
console.log('');
if (паднали) {
  console.log('   ── ОТХВЪРЛЕНИТЕ и защо ──');
  const причини = {};
  for (const з of записи.filter(x => !x.ок)) {
    const п = з.беди[0].replace(/: .*/, '').replace(/\d+ пъти/, 'N пъти');
    причини[п] = (причини[п] || 0) + 1;
  }
  for (const [п, б] of Object.entries(причини).sort((a, b) => b[1] - a[1]))
    console.log('      ' + String(б).padStart(4) + ' × ' + п);
  console.log('');
  for (const з of записи.filter(x => !x.ок).slice(0, 12))
    console.log('      🔴 ' + String(з.н.myasto || з.н.място).slice(0, 46).padEnd(48) + з.беди.join(' | ').slice(0, 76));
  if (паднали > 12) console.log('      … и още ' + (паднали - 12));
  console.log('');
}

fs.writeFileSync(path.join(__dirname, 'priemi_nahodki.json'),
  JSON.stringify(записи.map(з => ({ файл: з.ф, място: з.н.myasto || з.н.място, ок: з.ок, беди: з.беди, tejest: з.н.tejest })), null, 1));

if (!ПИШИ) {
  console.log('   ⏸️  СУХО ПУСКАНЕ — нищо не е записано. За прилагане: --pishi');
  console.log('   💾 dev/priemi_nahodki.json');
  console.log('');
  process.exit(0);
}

// ═══ ПРИЛАГАНЕ ═══
console.log('   ── ПРИЛАГАМ ' + минали + ' находки ──');
let приложени = 0, счупени = 0;
for (const [ф, _] of поФайлове) {
  if (ф === '(без файл)') continue;
  const мои = записи.filter(з => з.ф === ф && з.ок);
  if (!мои.length) continue;
  const П = path.join(ROOT, ф);
  let текст = fs.readFileSync(П, 'utf8');
  let вФайла = 0;
  for (const з of мои) {
    const старо = String(з.н.staro || з.н.старо_дословно);
    const ново = String(з.н.novo || з.н.ново_дословно);
    // ПАК проверяваме — предишна замяна в СЪЩИЯ файл може да е изяла котвата
    const бр = текст.split(старо).length - 1;
    if (бр !== 1) { счупени++; console.log('      🔴 ' + String(з.н.myasto).slice(0, 40) + ' — котвата стана ' + бр + ' след предишна замяна'); continue; }
    текст = текст.split(старо).join(ново);
    вФайла++;
  }
  if (!вФайла) continue;
  // 7 · парсва ли се
  let добре = true;
  if (ф.endsWith('.json')) { try { JSON.parse(текст); } catch (e) { добре = false; console.log('      🔴 ' + ф + ' нямаше да е валиден JSON: ' + e.message.slice(0, 70)); } }
  else if (ф.endsWith('.js')) { try { new vm.Script(текст); } catch (e) { добре = false; console.log('      🔴 ' + ф + ' нямаше да се парсва: ' + e.message.slice(0, 70)); } }
  if (!добре) { счупени += вФайла; continue; }
  fs.copyFileSync(П, П + '.PREDI_PRIEM');
  fs.writeFileSync(П, текст);
  приложени += вФайла;
  console.log('      ✅ ' + ф.padEnd(22) + вФайла + ' замени');
}

