// ═══════════════════════════════════════════════════════════
// 🧹 ШУМЪТ В GIT — кои .json файлове са ИЗХОД на уред и заливат diff-а
//
// ЗАЩО (02.09): днес открих, че 169 карти са получили възрастово поле от чужд
// отряд и са влезли в МОЕ качване, без да ги видя. Причината не е невнимание —
// причината е, че `git show --stat` за онова качване изглеждаше така:
//
//     dev/korpus350.json  | 282 ++++++------
//     js/kb.js            | 352 ++++++------     ← истинската промяна
//     dev/chisla.json     | 114 ++++------
//
// Тоест 169 нови полета в живата база стояха между два генерирани файла, които
// се пренаписват при ВСЯКО пускане на уред. Такъв diff не се чете — той се
// прескача. А непрочетеният diff е точно толкова добър, колкото непускан тест.
//
// 🔑 ПРАВИЛОТО: файл, който УРЕД ПИШЕ и НИКОЙ не чете, няма работа в git.
//    Той не е изходен код и не е решение на човек — той е снимка на последното
//    пускане. Историята му е шум, който крие сигнала.
//
// ⚠️ НО НЕ ВСИЧКИ .json в dev/ са изход. Част от тях са ВХОД — корпусите с
//    въпроси, решенията кой сирак къде отива. Те са писани от ЧОВЕК и без тях
//    уредите не работят. Затова тук не се гадае по име, а се проверява:
//       ПИШЕ ли го уред · ЧЕТЕ ли го уред
//    и от git излизат само тези, които се пишат и НЕ се четат.
//
// ПУСКАНЕ: node dev/shum_v_git.js          ← само показва
//          node dev/shum_v_git.js --pishi  ← добавя ги в .gitignore и ги маха
//                                            от индекса (файловете ОСТАВАТ на диска)
// ПЪТ НАЗАД: `git rm --cached` не трие файл от диска. Връщане: махни реда от
//            .gitignore и `git add dev/<име>.json`.
// ═══════════════════════════════════════════════════════════
const fs = require('fs');
const cp = require('child_process');
const path = require('path');
const ROOT = path.resolve(__dirname, '..');

const ПИШИ = process.argv.includes('--pishi');

const вГит = cp.execSync('git ls-files dev/', { encoding: 'utf8', cwd: ROOT })
  .split('\n').map(s => s.trim()).filter(f => f.endsWith('.json'));

// 🪤 ПЪРВОТО ПУСКАНЕ ПАДНА НА СОБСТВЕНАТА СИ ОПАШКА: този файл също е в dev/ и
//    съдържа имената на примамките си до думите writeFileSync/readFileSync.
//    Мярка, която чете САМА СЕБЕ СИ, вижда своите примери като истински
//    употреби — и обяви живата си самопроверка за счупена.
const САМИЯТ = path.basename(__filename);
const уреди = fs.readdirSync(path.join(ROOT, 'dev'))
  .filter(f => f.endsWith('.js') && !/PREDI|BAK|ARCHIVE/.test(f) && f !== САМИЯТ);
const целият = уреди.map(f => fs.readFileSync(path.join(ROOT, 'dev', f), 'utf8')).join('\n');

// търсим по ИМЕТО като обикновен подниз в подходящ контекст — без регулярки,
// защото името съдържа точка и лесно се получава израз, който хваща всичко.
// 🪤 И се гледа В ДВЕТЕ ПОСОКИ: `readFileSync(п)` слага думата ПРЕДИ името, но
//    `const п = х + 'име.json'; fs.readFileSync(п)` я слага СЛЕД него.
const близоДо = (текст, име, думи) => {
  let i = -1;
  while ((i = текст.indexOf(име, i + 1)) >= 0) {
    const прозорец = текст.slice(Math.max(0, i - 110), i + име.length + 60);
    if (думи.some(д => прозорец.indexOf(д) >= 0)) return true;
  }
  return false;
};

// 🪤 ВТОРА ПОПРАВКА. Първо търсех думата „readFileSync" близо до името и
//    `korpus_speshni.json` мина за изход — а той е ВХОД: в korpus_stroi.js стои
//    в списък, а самото четене е няколко реда по-надолу, извън всеки прозорец.
//    Мярка, която търси четенето до името, ще сбърка при всеки уред, който
//    първо изброява файловете и после ги отваря. А цената на тази грешка е
//    изтрит от git корпус — тоест изтрито решение на човек.
//
//    ПО-СИГУРНОТО ПРАВИЛО, без прозорци: файлът е ЧИСТ ИЗХОД само ако ВСЯКО
//    негово споменаване е вътре в извикване на writeFileSync. Едно-единствено
//    споменаване извън писане го прави вход и той остава в git.
//    Тази посока греши в БЕЗОПАСНАТА страна: в най-лошия случай оставяме шум.
//    🪤 ТРЕТА ПОПРАВКА: и това правило падна. `plan_sverka.json` се среща ДВА
//    пъти — веднъж в writeFileSync и веднъж в `console.log('💾 dev/…')`.
//    Всеки уред тук печата името на файла, който е записал. Правило, което
//    брои печата за употреба, обявява ВСЕКИ изход за вход.
//
//    КРАЙНОТО ПРАВИЛО, по РЕД, не по прозорец:
//      · ред с writeFileSync/appendFileSync   → ПИСАНЕ
//      · ред, който започва с //              → коментар, неутрален
//      · ред с console.log                    → печат, неутрален
//      · всеки друг ред                       → ПОЛЗВАНЕ (брои се за четене)
//    Последното е нарочно консервативно: списък от имена, който уред обхожда
//    и отваря по-надолу (както korpus_stroi прави с корпусите), е ползване,
//    макар четенето да е на друг ред. Грешката отива в безопасната страна —
//    в най-лошия случай оставяме шум в git, вместо да махнем нужен файл.
const вПисане = (текст, име) => {
  const редове = текст.split(/\r?\n/);
  let писане = 0, ползване = 0, неутрални = 0;
  for (const ред of редове) {
    if (ред.indexOf(име) < 0) continue;
    const гол = ред.trim();
    if (/writeFileSync|appendFileSync/.test(ред)) { писане++; continue; }
    if (гол.startsWith('//') || гол.startsWith('*')) { неутрални++; continue; }
    if (ред.indexOf('console.log') >= 0) { неутрални++; continue; }
    ползване++;
  }
  return { общо: писане + ползване + неутрални, вписани: писане, писане, ползване, неутрални };
};

const изход = [], вход = [];
for (const ф of вГит) {
  const име = ф.replace(/^dev\//, '');
  const р = вПисане(целият, име);
  const чистИзход = р.писане > 0 && р.ползване === 0;
  (чистИзход ? изход : вход).push({ ф, име, писане: р.писане, ползване: р.ползване });
}

// ═══ САМОПРОВЕРКА ═══
// Мярка, която обяви всичко за изход, би изтрила корпусите от git. Затова се
// проверява в двете посоки с два известни файла.
const проби = [
  // 🪤 ТРЕТА ПОПРАВКА, И ТЯ ОБОРВА ПОСТАНОВКАТА МИ. За примамка бях избрал
  //    korpus350.json като „очевиден изход". Мярката отказа — и беше ПРАВА:
  //    той се ЧЕТЕ от три уреда (korpus350.js, dvigatel.js, prilozhi_frazi.js).
  //    Не е снимка от пускане, а самият корпус, строен веднъж от korpus_stroi.
  //    Ако бях приложил първата си догадка, щях да махна корпуса от историята.
  ['известен ИЗХОД (plan_sverka) се разпознава като изход', (() => { const r = вПисане(целият, 'plan_sverka.json'); return r.писане > 0 && r.ползване === 0; })()],
  ['известен ВХОД (korpus_speshni) НЕ се брои за изход', (() => { const r = вПисане(целият, 'korpus_speshni.json'); return !(r.писане > 0 && r.ползване === 0); })()],
  ['измислено име не е нито едното', (() => { const r = вПисане(целият, 'няма-такъв-файл-xyz.json'); return r.общо === 0; })()],
  ['входният index.json НЕ се брои за изход', (() => { const r = вПисане(целият, 'lib/index.json'); return !(r.писане > 0 && r.ползване === 0); })()]
];
console.log('');
console.log('🧹 ШУМЪТ В GIT — генерирани файлове, които крият истинските промени');
console.log('');
let слаби = 0;
for (const [име, ок] of проби) { if (!ок) слаби++; console.log('   ' + (ок ? '✅' : '🔴') + ' самопроверка: ' + име); }
if (слаби) { console.log(''); console.log('   🔴 МЯРКАТА Е СЧУПЕНА — не ѝ вярвай'); process.exit(1); }
console.log('');

// колко реда шум носят
let шумниРедове = 0;
for (const x of изход) {
  const п = path.join(ROOT, x.ф);
  if (fs.existsSync(п)) шумниРедове += fs.readFileSync(п, 'utf8').split('\n').length;
}

console.log('   📤 ЧИСТ ИЗХОД на уред — може да излезе от git: ' + изход.length);
for (const x of изход) console.log('      ' + x.име);
console.log('');
console.log('   📥 ВХОД или четен от уред — ОСТАВА в git: ' + вход.length);
for (const x of вход) console.log('      ' + x.име.padEnd(30) + 'писане:' + x.писане + '  ползване:' + x.ползване);
console.log('');
console.log('   шум, който изчезва от всеки diff: ~' + шумниРедове + ' реда');
console.log('');

if (!ПИШИ) {
  console.log('   ⏸️  СУХО ПУСКАНЕ. За прилагане: node dev/shum_v_git.js --pishi');
  console.log('');
  process.exit(0);
}

if (!изход.length) { console.log('   нищо за махане.'); process.exit(0); }

const ГИ = path.join(ROOT, '.gitignore');
let ги = fs.readFileSync(ГИ, 'utf8');
const НР = ги.indexOf('\r\n') >= 0 ? '\r\n' : '\n';
const блок = [
  '',
  '# ── 02.09: снимки от последното пускане на уред, НЕ изходен код ──',
  '# Тези файлове се пренаписват при всяко пускане и заливаха всеки diff с',
  '# хиляди редове. Заради това 169 нови възрастови полета в js/kb.js минаха',
  '# незабелязано в едно качване. Файл, който уред ПИШЕ и никой не ЧЕТЕ, няма',
  '# работа в историята. Остават на диска — махат се само от индекса.',
  '# Проверено машинно с dev/shum_v_git.js, не по име.'
].concat(изход.map(x => x.ф)).join(НР);
if (ги.indexOf('dev/shum_v_git.js') < 0 && ги.indexOf(изход[0].ф) < 0) {
  fs.writeFileSync(ГИ, ги.trimEnd() + НР + блок + НР);
  console.log('   ✅ .gitignore допълнен с ' + изход.length + ' файла');
} else console.log('   (вече е в .gitignore)');

let махнати = 0;
for (const x of изход) {
  try { cp.execSync('git rm --cached --quiet "' + x.ф + '"', { cwd: ROOT }); махнати++; }
  catch (e) { console.log('      ⚠️ не можах да махна ' + x.ф); }
}
console.log('   ✅ махнати от индекса: ' + махнати + '   (файловете са НА ДИСКА, проверено отдолу)');
let наДиска = 0;
for (const x of изход) if (fs.existsSync(path.join(ROOT, x.ф))) наДиска++;
console.log('   ' + (наДиска === изход.length ? '✅' : '🔴') + ' на диска: ' + наДиска + ' от ' + изход.length);
console.log('');
process.exit(наДиска === изход.length ? 0 : 1);
