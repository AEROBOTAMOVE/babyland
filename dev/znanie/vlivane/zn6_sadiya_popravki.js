function zameni(obekt, pole, staro, novo, etiket) {
  const t = String(obekt[pole] == null ? '' : obekt[pole]);
  const n = t.split(staro).length - 1;
  if (n !== 1) { console.log('🔴 ' + etiket + ' · ' + pole + ': намерено ' + n + ' пъти: ' + staro.slice(0, 70)); greshki++; return; }
  obekt[pole] = t.replace(staro, () => novo);
  broi++;
}
const karta = id => { const k = K.find(x => x.id === id); if (!k) { console.log('🔴 няма карта ' + id); greshki++; return {}; } return k; };
const statia = id => { const s = S.find(x => x.karta === id); if (!s) { console.log('🔴 няма статия ' + id); greshki++; return {}; } return s; };
const kz = (id, pole, a, b) => zameni(karta(id), pole, a, b, 'К ' + id);
const sz = (id, pole, a, b) => zameni(statia(id), pole, a, b, 'С ' + id);
function dobaviFollow(id, tekst) {               // добавя follow след tip, за да остане редът на полетата
  const i = K.findIndex(x => x.id === id);
  if (i < 0 || K[i].follow) { console.log('🔴 follow: ' + id + (i < 0 ? ' няма' : ' вече има')); greshki++; return; }
  const n = {};
  for (const [kl, v] of Object.entries(K[i])) { n[kl] = v; if (kl === 'tip') n.follow = tekst; }
  K[i] = n; broi++;
}
const KRAI = '\n\nЗаписките не заменят преглед.';
function dobaviKrai(id) {
  const s = statia(id);
  if (/Записките не заменят преглед\.\s*$/.test(s.body)) { console.log('🔴 ' + id + ' вече има последния ред'); greshki++; return; }
  s.body = s.body.replace(/\s+$/, '') + KRAI; broi++;
}

