// zn8b · кражби от ЕСТЕСТВЕНИ въпроси (не само ключовете): префикс × възраст × въпрос, мерено в три света:
//   W0 = живият kb.js · W5 = + петте стари карти zn8b · W8 = + всичките 8 (стажът). Нищо не пише.
// Кражба (а): днес вярна съществуваща карта (zn4b-*, igr-*, …) → нова карта от трите.
// Кражба (б): петте стари zn8b са отговаряли → нова карта от трите.
// Пускане: node dev/proba/red.js mozak -- node dev/znanie/vlivane/zn8b_kradezh3.js
'use strict';
const fs = require('fs');
const path = require('path');
const КОРЕН = path.resolve(__dirname, '../../..');
process.chdir(КОРЕН);
const { zaredi } = require(path.join(КОРЕН, 'dev/pyasachnik.js'));
const СТАЖ = JSON.parse(fs.readFileSync('dev/nahodki/karti_zn8b.json', 'utf8'));
const низ = s => "'" + String(s).replace(/\\/g, '\\\\') + "'";
const сКарти = стаж => kb => {
  const НР = kb.indexOf('\r\n') >= 0 ? '\r\n' : '\n';
  const КРАЙ = НР + '    }' + НР + '  ]' + НР + '};';
  const блок = к => ['    {', '      id: ' + низ(к.id) + ',' + (к.от != null ? ' от: ' + к.от + ',' : '') + (к.до != null ? ' до: ' + к.до + ',' : '') + ' room: ' + низ(к.room) + ',',
    '      keys: [' + к.keys.map(низ).join(', ') + '],', '      title: ' + низ(к.title) + ',', '      core: ' + низ(к.core) + ',', '      tip: ' + низ(к.tip) + ',',
    '      follow: ' + низ(к.follow || '') + ',', '      chips: [' + (к.chips || []).map(низ).join(', ') + ']', '    }'].join(НР);
  return kb.replace(КРАЙ, НР + '    },' + НР + стаж.map(блок).join(',' + НР) + НР + '  ]' + НР + '};');
};
const ПЕТ = new Set(СТАЖ.slice(0, 5).map(к => к.id));
const НОВИ3 = new Set(СТАЖ.slice(5).map(к => к.id));
const W0 = zaredi(null);
const W5 = zaredi(null, { kbPatch: сКарти(СТАЖ.slice(0, 5)) });
const W8 = zaredi(null, { kbPatch: сКарти(СТАЖ) });
const питай = (W, т, с) => { try { const р = W.BL_MATCH(т, с); const з = Array.isArray(р) ? р[0] : (р && (р.entry || р.item || р)); return з && з.id ? з.id : 'ТИШИНА'; } catch (e) { return 'ГР'; } };
const ПРЕФ = ['', 'на ', 'детето е на ', 'синът ми е на ', 'дъщеря ми е на ', 'малкият е на ', 'навърши ', 'вече е на ', 'дете на '];
const ВЪЗР = ['2 години', '2 години и половина', 'две години', '3 години', 'три години', '3 годинки', '3 години и половина',
  '4 години', 'четири години', '4 годинки', '4 години и половина', '5 години', 'пет години', '5 годинки', '5 години и половина', '6 години'];
const ВЪПР = ['какво трябва да може', 'какво е нормално да може', 'какво е нормално да прави', 'какво се очаква да може', 'какво трябва да умее',
  'какво прави', 'какво може', 'какво да очаквам', 'какви умения трябва да има', 'какво трябва да знае', 'какво трябва да прави'];
const ТЕМИ = ['какво трябва да яде', 'колко трябва да спи', 'не говори', 'заеква', 'се напишква', 'колко екран', 'какви играчки', 'кога без памперс'];
const СТАИ = { 'какво трябва да яде': 'Захранване', 'колко трябва да спи': 'Моето бебе' };
let общо = 0, а = 0, б = 0, теми = 0, поправени = 0;
const ред = [];
const мери = (т, с) => {
  общо++;
  const о0 = питай(W0, т, с), о5 = питай(W5, т, с), о8 = питай(W8, т, с);
  if (!НОВИ3.has(о8)) return [о0, о5, о8];
  // (а) спрямо ЖИВИЯ kb.js: днес вярна карта → нова (дори ако петте вече са я били отмъкнали — тогава белег „през петте“)
  if (/^zn4b-|^igr-|^rz-vaobrazhaem|^y3-parvoklasnik|^rz-cvetove|^rz2-pita/.test(о0)) { а++; ред.push('🔴 (а) „' + т + '“  ' + о0 + (о5 !== о0 ? ' → (петте: ' + о5 + ')' : '') + ' → ' + о8 + '   [' + (СТАЖ.find(к => к.id === о8).keys.filter(k => т.includes(k)).join(' · ')) + ']'); }
  // (б) петте са давали ВЯРНАТА си карта за възрастта (2–3 г.) → нова
  else if (о5 === 'zn8b-2-3-godini' && /(^|\s)(2|две)\s/.test(т)) { б++; ред.push('🔴 (б) „' + т + '“  ' + о5 + ' → ' + о8); }
  else if (о5 !== о8) { поправени++; if (process.argv.includes('--vsichko')) ред.push('↪  „' + т + '“  ' + о5 + ' → ' + о8); }
  return [о0, о5, о8];
};
for (const п of ПРЕФ) for (const в of ВЪЗР) for (const q of ВЪПР) мери((п + в + ' ' + q).trim(), 'Развитие и игри');
for (const в of ВЪЗР) for (const q of ВЪПР) мери(q + ' на ' + в, 'Развитие и игри');
for (const в of ВЪЗР) for (const т of ТЕМИ) {
  const с = СТАИ[т] || 'Развитие и игри';
  for (const фр of ['на ' + в + ' ' + т, т + ' на ' + в, 'детето е на ' + в + ' и ' + т]) {
    общо++;
    const о5 = питай(W5, фр, с), о8 = питай(W8, фр, с);
    if (о5 !== о8 && НОВИ3.has(о8)) { теми++; ред.push('🔴 (тема) „' + фр + '“  ' + о5 + ' → ' + о8); }
  }
}
console.log(ред.join('\n'));
console.log('\nвъпроси: ' + общо + ' · кражби (а) от вярна жива карта: ' + а + ' · кражби (б) от петте zn8b: ' + б +
  ' · съседни теми, отишли в новите: ' + теми + ' · преместени от тишина/грешна карта към новите: ' + поправени);
