'use strict';
const fs = require('fs');
const path = require('path');
const КОРЕН = path.resolve(__dirname, '../../..');
process.chdir(КОРЕН);
const { zaredi } = require(path.join(КОРЕН, 'dev/pyasachnik.js'));
const СТАЖ0 = JSON.parse(fs.readFileSync('dev/nahodki/karti_zn8b.json', 'utf8'));
const низ = s => "'" + String(s).replace(/\\/g, '\\\\') + "'";
const сКарти = стаж => kb => {
  const НР = kb.indexOf('\r\n') >= 0 ? '\r\n' : '\n';
  const КРАЙ = НР + '    }' + НР + '  ]' + НР + '};';
  const блок = к => ['    {', '      id: ' + низ(к.id) + ',' + (к.от != null ? ' от: ' + к.от + ',' : '') + (к.до != null ? ' до: ' + к.до + ',' : '') + ' room: ' + низ(к.room) + ',',
    '      keys: [' + к.keys.map(низ).join(', ') + '],', '      title: ' + низ(к.title) + ',', '      core: ' + низ(к.core) + ',', '      tip: ' + низ(к.tip) + ',',
    '      follow: ' + низ(к.follow || '') + ',', '      chips: [' + (к.chips || []).map(низ).join(', ') + ']', '    }'].join(НР);
  return kb.replace(КРАЙ, НР + '    },' + НР + стаж.map(блок).join(',' + НР) + НР + '  ]' + НР + '};');
};
const ВАРИАНТИ = {
  'сега': {},
  'без „какво трябва да може на четири години“': { 'zn8b-4-5-godini': ['какво трябва да може на четири години'] },
  'без всички „четири години…“': { 'zn8b-4-5-godini': ['какво трябва да може на четири години', 'четири години какво е нормално да може'] }
};
// кръг 2 (22.10 вечер): „дете на четири години …“ — кой ключ го отнема от zn4b-na-4-godini
const ВЪПРОСИ = [
  'дете на четири години какво трябва да може', 'дете на четири години какво е нормално да прави', 'дете на четири години какво се очаква да може',
  'дете на четири години какво може', 'какво трябва да може на четири години', 'на четири години какво трябва да може',
  'детето е на четири години какво е нормално да може', 'синът ми е на четири години какво е нормално да прави', 'какво трябва да може на 4 години'
];
const питай = (W, т) => { try { const р = W.BL_MATCH(т, 'Развитие и игри'); const з = Array.isArray(р) ? р[0] : (р && (р.entry || р.item || р)); return з && з.id ? з.id : 'ТИШИНА'; } catch (e) { return 'ГР'; } };
const W0 = zaredi(null);
const резултати = {};
for (const [име, махни] of Object.entries(ВАРИАНТИ)) {
  const стаж = СТАЖ0.map(к => Object.assign({}, к, { keys: к.keys.filter(k => !(махни[к.id] || []).includes(k)) }));
  const W = zaredi(null, { kbPatch: сКарти(стаж) });
  резултати[име] = ВЪПРОСИ.map(т => питай(W, т));
  // всеки ключ на 8-те карти към своята карта
  let лоши = [];
  for (const к of стаж) for (const k of к.keys) { const о = питай(W, k); if (о !== к.id) лоши.push(к.id + ' „' + k + '“ → ' + о); }
  резултати[име + '#ключове'] = лоши;
}
ВЪПРОСИ.forEach((т, i) => console.log('„' + т + '“  днес ' + питай(W0, т) + ' | ' + Object.keys(ВАРИАНТИ).map(в => в + ': ' + резултати[в][i]).join(' | ')));
for (const в of Object.keys(ВАРИАНТИ)) console.log('\n[' + в + '] ключове, които не вадят своята карта: ' + резултати[в + '#ключове'].length + (резултати[в + '#ключове'].length ? '\n  ' + резултати[в + '#ключове'].join('\n  ') : ''));
