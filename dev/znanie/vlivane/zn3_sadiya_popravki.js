let n = 0;
function zamen(spisak, kluch, id, pole, staro, novo) {
  const o = spisak.find(x => x[kluch] === id);
  if (!o) throw new Error('няма ' + id);
  const t = String(o[pole]);
  const broj = t.split(staro).length - 1;
  if (broj !== 1) throw new Error(id + ' · ' + pole + ' · старият текст се среща ' + broj + ' пъти: ' + staro.slice(0, 70));
  o[pole] = t.replace(staro, () => novo);
  n++;
}
const k = (id, pole, staro, novo) => zamen(K, 'id', id, pole, staro, novo);
const s = (id, pole, staro, novo) => zamen(S, 'karta', id, pole, staro, novo);

