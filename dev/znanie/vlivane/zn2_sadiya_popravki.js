function smeni(obj, pole, staro, novo, etiket) {
  const t = obj[pole];
  const n = t.split(staro).length - 1;
  if (n !== 1) throw new Error((etiket || obj.id || obj.karta) + ' · ' + pole + ': намерено ' + n + ' пъти: ' + staro.slice(0, 70));
  obj[pole] = t.replace(staro, novo);
}
function kluch(id, staro, novo) {
  const k = kart(id); const i = k.keys.indexOf(staro);
  if (i < 0 || k.keys.indexOf(staro, i + 1) > -1) throw new Error(id + ' · ключ не е точно веднъж: ' + staro);
  if (k.keys.includes(novo)) throw new Error(id + ' · новият ключ вече го има: ' + novo);
  k.keys[i] = novo;
}
