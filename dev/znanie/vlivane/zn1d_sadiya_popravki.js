const greshki = [];
function zameni(obj, pole, staro, novo, etiket) {
  const t = String(obj[pole]);
  const n = t.split(staro).length - 1;
  if (n !== 1) { greshki.push(etiket + ' · ' + pole + ': намерено ' + n + ' пъти: ' + staro.slice(0, 60)); return; }
  obj[pole] = t.replace(staro, () => novo);
}
for (const [id, pole, staro, novo] of KP) {
  const k = K.find(x => x.id === id);
  if (!k) { greshki.push('няма карта ' + id); continue; }
  zameni(k, pole, staro, novo, id);
}
for (const [id, staro, novo] of KL) {
  const k = K.find(x => x.id === id);
  const i = k ? k.keys.indexOf(staro) : -1;
  if (i < 0) { greshki.push(id + ' · ключ не е намерен: ' + staro); continue; }
  k.keys[i] = novo;
}
for (const [id, pole, staro, novo] of SP) {
  const s = S.find(x => x.karta === id);
  if (!s) { greshki.push('няма статия ' + id); continue; }
  zameni(s, pole, staro, novo, 'статия ' + id);
}
