const БЕЗ_4 = process.argv.includes('--bez4');
const низ = s => "'" + String(s).replace(/\\/g, '\\\\') + "'";
const кръпка = kb => {
  const нр = kb.indexOf('\r\n') >= 0 ? '\r\n' : '\n';
  const КРАЙ = нр + '    }' + нр + '  ]' + нр + '};';
  if (kb.split(КРАЙ).length !== 2) throw new Error('краят на entries не е разпознат');
  const блок = к => ['    {',
    '      id: ' + низ(к.id) + ',' + (к.от != null ? ' от: ' + к.от + ',' : '') + (к.до != null ? ' до: ' + к.до + ',' : '') + ' room: ' + низ(к.room) + ',',
    '      keys: [' + к.keys.map(низ).join(', ') + '],',
    '      title: ' + низ(к.title) + ',', '      core: ' + низ(к.core) + ',', '      tip: ' + низ(к.tip) + ',',
    '      follow: ' + низ(к.follow || '') + ',', '      chips: [' + (к.chips || []).map(низ).join(', ') + ']', '    }'].join(нр);
  return kb.replace(КРАЙ, нр + '    },' + нр + СТАЖ.map(блок).join(',' + нр) + нр + '  ]' + нр + '};');
};
const W0 = zaredi(null);
const W1 = zaredi(null, { kbPatch: кръпка });
const питай = (W, т, с) => { try { const р = W.BL_MATCH(т, с); const з = Array.isArray(р) ? р[0] : (р && (р.entry || р.item || р)); return з && з.id ? з.id : 'ТИШИНА'; } catch (e) { return 'ГР:' + e.message.slice(0, 40); } };
const мои = new Set(СТАЖ.map(к => к.id));
const изход = [];
const пиши = s => { изход.push(s); };

// (0) чиповете съществуват ли в живата база
const живи = new Set(W0.KB.entries.map(е => е.id));
for (const к of СТАЖ) for (const ч of к.chips || []) if (!живи.has(ч)) пиши('🔴 чип към несъществуваща карта: ' + к.id + ' → ' + ч);
пиши('карти в стажа: ' + СТАЖ.length + ' · живи карти: ' + живи.size);

// (1) тестът
const ТЕСТ = JSON.parse(fs.readFileSync('dev/znanie/vlivane/zn7a_test.json', 'utf8'));
let тестОк = 0;
пиши('── (1) ТЕСТЪТ zn7a_test.json ──');
ТЕСТ.forEach((в, i) => {
  const цел = СТАЖ[Math.floor(i / 3)].id;
  const п = питай(W0, в.q, в.r), с = питай(W1, в.q, в.r);
  if (с === цел) тестОк++;
  пиши((с === цел ? '✅ ' : '🔴 ') + '„' + в.q + '“  ' + п + ' → ' + с + (с === цел ? '' : '   (чака ' + цел + ')'));
});
пиши('тест: ' + тестОк + '/' + ТЕСТ.length + ' вадят своята карта');

// (2) въпросите от началото
пиши(НР + '── (2) zn7a_vaprosi.json преди → след ──');
for (const [т, с] of JSON.parse(fs.readFileSync('dev/znanie/vlivane/zn7a_vaprosi.json', 'utf8'))) {
  const п = питай(W0, т, с), сл = питай(W1, т, с);
  пиши((мои.has(сл) ? '✅ ' : (п === сл ? '·  ' : '↪  ')) + '„' + т + '“  ' + п + ' → ' + сл);
}

