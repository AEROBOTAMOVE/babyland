const СТАЖ_ПЪТ = (process.argv.find(a => a.startsWith('--staj=')) || '--staj=dev/nahodki/karti_zn7a.json').slice(7);
const СТАЖ = JSON.parse(fs.readFileSync(СТАЖ_ПЪТ, 'utf8'));
const СМЕС_ПЪТ = (process.argv.find(a => a.startsWith('--smes=')) || '').slice(7);
