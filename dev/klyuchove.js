// ═══════════════════════════════════════════════════════════
// 🔑 КЛЮЧ-ПАЗАЧ — боклук-ключове в базата на знанието
//
// Защо съществува (05.08.2026):
//   Редакция от агент разкъса `keys` масива на един запис. Вътре
//   останаха една скоба ')' и четири голи запетаи. Записът си стоеше,
//   приложението се зареждаше, конзолата мълчеше — и никой не забеляза.
//
//   Мълчи, защото матчърът в helper.js прави така:
//       const nk = normalize(k);  if (!nk) continue;
//   а normalize маха всичко извън [\wа-яё\s]. Ключ ')' се нормализира
//   до ПРАЗЕН низ и тихо се прескача. Тоест щетата не е „грешно
//   съвпадение", а ЗАГУБЕНИ ключове: истинските думи, които са били на
//   това място, ги няма и въпросът на майката вече не стига дотук.
//   Такава дупка не пада никъде — трябва да я питаш изрично.
//
//   Обратната беда е ключ от ЕДИН знак. Матчърът търси едносричния
//   ключ с `words.some(w => w.startsWith(nk))` — ключ 'а' пасва на
//   всяка дума, започваща с 'а', и записът почва да краде чужди
//   въпроси. Затова тук къси и боклук-ключове са еднакво червени.
//
// ⚠️ ЧЕТЕНЕ НА ПРАГОВЕТЕ — измерено на живия kb.js на 05.08, НЕ гадано:
//   383 записа · 3460 ключа · 3344 уникални · 0 боклук · 0 къси · 0 дубли.
//   Затова ЧЕРВЕНОТО е нула на чист файл — всяко червено е истинско.
//   Две неща обаче НЕ са грешки и стоят отделно, иначе пазачът щеше да
//   вика „вълк" върху здрав код още първия път:
//     · чисти числа ('38','39','56','62','68') — температура и размери;
//     · ключ в 3+ записа (днес 5: белези, сън, запек, тегло, цезарово) —
//       това е за поглед, не присъда: обща дума в няколко стаи е
//       нормална, но точно оттам почва кражбата на чужди въпроси.
//
// КАК СЕ ПУСКА (в конзолата на приложението):
//   const s=document.createElement('script'); s.src='dev/klyuchove.js'; document.body.appendChild(s);
//   BL_КЛЮЧОВЕ.провери()          // или BL_KEYS.провери() — същото
//
// ПЪТ НАЗАД: файлът само ЧЕТЕ. Не пипа KB, не пише в localStorage, не
//   праща заявки. Изтриването му не чупи нищо. НЕ е закачен в index.html.
// ═══════════════════════════════════════════════════════════
(function () {
  'use strict';

  // ⚠️ Кирилицата НЕ е \w в JavaScript. Затова буквите се изброяват изрично.
  var БУКВА = /[A-Za-zЀ-ӿ]/;
  var ЦИФРА = /[0-9]/;
  var ЧИСЛО = /^[0-9]+(?:[.,-][0-9]+)?$/;      // '38' · '6.5' · '56-62'
  var ЗНАЦИ = /[()\[\]{}<>;=|\\"`]/;           // следи от разкъсана редакция

  // ⚠️ Един ключ → ЕДНА присъда. Първата версия на този пазач броеше ')' и
  // като „боклук", и като „един знак" — 14 счупени ключа излизаха като 23
  // червени. Надутото число е малка лъжа, а пазач, който преувеличава,
  // почва да се чете като „сигурно пак преувеличава". Затова редът е строг
  // и се спира на първото попадение.
  function присъда(k) {
    if (typeof k !== 'string') return { вид: 'нениз', защо: 'ключът не е низ, а ' + typeof k };
    var s = k.trim();
    if (s.length === 0) return { вид: 'къс', защо: 'празен ключ' };
    if (!БУКВА.test(s) && !ЦИФРА.test(s))
      return { вид: 'боклук', защо: 'без буква и без цифра → normalize() го изтрива → МЪРТЪВ ключ' };
    if (s.length === 1) return { вид: 'къс', защо: 'един знак → startsWith пасва на всичко' };
    if (ЧИСЛО.test(s)) return { вид: 'число', защо: 'чисто число — легитимно (температура, размери)' };
    return { вид: 'ок' };
  }

  // Къде е базата. Не гадаем — питаме какво реално има на прозореца.
  function базата() {
    var KB = window.KB;
    if (!KB) return null;
    if (Array.isArray(KB.entries)) return { име: 'KB.entries', списък: KB.entries };
    if (Array.isArray(KB.items)) return { име: 'KB.items', списък: KB.items };
    return null;
  }

  function име(запис, i) {
    return (запис && запис.id) ? запис.id : '(без id) №' + (i + 1);
  }

  function провери() {
    var б = базата();
    if (!б || !б.списък.length) {
      var празно = {
        ПРЕГЛЕДАНИ_ЗАПИСА: 0,
        ГРЕШКА: !б
          ? 'няма нито KB.entries, нито KB.items — базата не е заредена'
          : 'базата е празен масив'
      };
      console.log('%c🔑 КЛЮЧ-ПАЗАЧ', 'font-size:15px;font-weight:700');
      console.log('%c🔴 НЯМА КАКВО ДА ПРЕГЛЕДАМ — ' + празно.ГРЕШКА,
        'color:#c62828;font-weight:700');
      console.log('Това НЕ е „чисто". Пазач без прегледани записи е счупен пазач.');
      window.BL_КЛЮЧОВЕ.последен = празно;
      return празно;
    }

    var записи = б.списък;
    var боклук = [], къси = [], дубли = [], непълни = [], ненизове = [];
    var числа = [], подозрителни = [];
    var разпределение = {};        // ключ → множество от записи, в които се среща
    var прегледаниКлючове = 0;

    записи.forEach(function (з, i) {
      var ид = име(з, i);

      // ── целостта на самия запис ──
      var липсва = [];
      if (!з || typeof з !== 'object') { непълни.push({ запис: ид, липсва: 'не е обект' }); return; }
      if (!Array.isArray(з.keys)) липсва.push(з.keys === undefined ? 'keys' : 'keys не е масив');
      else if (!з.keys.length) липсва.push('keys е празен масив');
      if (!з.title || !String(з.title).trim()) липсва.push('title');
      if (!з.core || !String(з.core).trim()) липсва.push('core');
      if (липсва.length) непълни.push({ запис: ид, липсва: липсва.join(', ') });

      if (!Array.isArray(з.keys)) return;

      // ── ключовете един по един ──
      var видени = {};
      з.keys.forEach(function (k, j) {
        прегледаниКлючове++;

        var п = присъда(k);
        if (п.вид === 'нениз') {
          ненизове.push({ запис: ид, позиция: j, тип: typeof k, стойност: String(k) });
          return;
        }
        var s = k.trim();
        if (п.вид === 'къс') { къси.push({ запис: ид, позиция: j, ключ: JSON.stringify(k), защо: п.защо }); return; }
        if (п.вид === 'боклук') { боклук.push({ запис: ид, позиция: j, ключ: JSON.stringify(k), защо: п.защо }); return; }
        if (п.вид === 'число') числа.push({ запис: ид, ключ: s });

        // Оттук нататък ключът е ГОДЕН. Дублирането и разпръскването се
        // мерят само между годни ключове — инак разкъсаният запис вдига и
        // „запетаята се повтаря 3 пъти", което е шум върху вече казаното.

        // има букви, но и следа от разкъсване ('температура)' ) — жълто
        if (БУКВА.test(s) && ЗНАЦИ.test(s)) {
          подозрителни.push({ запис: ид, ключ: JSON.stringify(k),
            защо: 'структурен знак вътре в ключа' });
        }

        // дублиран ключ ВЪТРЕ в един запис
        var долу = s.toLowerCase();
        if (видени[долу]) дубли.push({ запис: ид, ключ: s });
        видени[долу] = true;

        // в колко РАЗЛИЧНИ записа живее този ключ
        if (!разпределение[долу]) разпределение[долу] = {};
        разпределение[долу][ид] = true;
      });
    });

    // ключ в 3+ различни записа → кандидат за кражба (жълто, не червено)
    var крадци = [];
    Object.keys(разпределение).forEach(function (k) {
      var къде = Object.keys(разпределение[k]);
      if (къде.length >= 3) крадци.push({ ключ: k, брой: къде.length, записи: къде });
    });
    крадци.sort(function (a, b) { return b.брой - a.брой; });

    // ── плоските масиви с флагове: същият клас щета, отделна сметка ──
    // Открива се по форма (масив само от низове), за да хване и нов масив,
    // добавен утре, без някой да се сеща да пипне пазача.
    var флагове = { прегледани_масива: 0, прегледани_флага: 0, БОКЛУК: [], КЪСИ: [], ДУБЛИ: [] };
    var KB = window.KB;
    Object.keys(KB).forEach(function (име2) {
      var м = KB[име2];
      if (!Array.isArray(м) || !м.length) return;
      if (!м.every(function (x) { return typeof x === 'string'; })) return;
      флагове.прегледани_масива++;
      var видени2 = {};
      м.forEach(function (f, j) {
        флагове.прегледани_флага++;
        var п2 = присъда(f);
        if (п2.вид === 'къс') { флагове.КЪСИ.push({ масив: име2, позиция: j, флаг: JSON.stringify(f), защо: п2.защо }); return; }
        if (п2.вид === 'боклук') { флагове.БОКЛУК.push({ масив: име2, позиция: j, флаг: JSON.stringify(f), защо: п2.защо }); return; }
        var д = f.trim().toLowerCase();
        if (видени2[д]) флагове.ДУБЛИ.push({ масив: име2, флаг: f.trim() });
        видени2[д] = true;
      });
    });

    var червени = боклук.length + къси.length + дубли.length + непълни.length +
      ненизове.length + флагове.БОКЛУК.length + флагове.КЪСИ.length + флагове.ДУБЛИ.length;

    var доклад = {
      източник: б.име,
      ПРЕГЛЕДАНИ_ЗАПИСА: записи.length,
      ПРЕГЛЕДАНИ_КЛЮЧОВЕ: прегледаниКлючове,
      уникални_ключове: Object.keys(разпределение).length,
      ЧЕРВЕНИ_общо: червени,
      БОКЛУК: боклук,
      ПРАЗНИ_ИЛИ_ЕДИН_ЗНАК: къси,
      ДУБЛИРАНИ_В_ЕДИН_ЗАПИС: дубли,
      НЕПЪЛНИ_ЗАПИСИ: непълни,
      КЛЮЧ_НЕ_Е_НИЗ: ненизове,
      жълто_подозрителни_знаци: подозрителни,
      жълто_в_3_и_повече_записа: крадци,
      ок_чисти_числа: числа,
      флагови_масиви: флагове
    };

    // ── изход в конзолата ──
    console.log('%c🔑 КЛЮЧ-ПАЗАЧ', 'font-size:15px;font-weight:700');
    console.log('прегледани записа: ' + записи.length +
      '  ·  прегледани ключа: ' + прегледаниКлючове +
      '  ·  уникални: ' + Object.keys(разпределение).length +
      '  ·  източник: ' + б.име);
    console.log('прегледани флагови масива: ' + флагове.прегледани_масива +
      '  ·  флага: ' + флагове.прегледани_флага);

    if (червени) {
      console.log('%c🔴 ЧЕРВЕНИ: ' + червени, 'color:#c62828;font-weight:700');
      if (боклук.length) { console.log('— боклук-ключове (мъртви):'); console.table(боклук); }
      if (къси.length) { console.log('— празни или от един знак:'); console.table(къси); }
      if (дубли.length) { console.log('— дублирани в един запис:'); console.table(дубли); }
      if (ненизове.length) { console.log('— ключ, който не е низ:'); console.table(ненизове); }
      if (непълни.length) { console.log('— непълни записи:'); console.table(непълни); }
      if (флагове.БОКЛУК.length) { console.log('— боклук във флаговите масиви:'); console.table(флагове.БОКЛУК); }
      if (флагове.КЪСИ.length) { console.log('— къси флагове:'); console.table(флагове.КЪСИ); }
      if (флагове.ДУБЛИ.length) { console.log('— дублирани флагове:'); console.table(флагове.ДУБЛИ); }
    } else {
      console.log('%c✅ ЧЕРВЕНИ: 0 — в ' + записи.length + ' записа и ' +
        прегледаниКлючове + ' ключа няма боклук, къс, дублиран или липсващ.',
        'color:#2e7d32;font-weight:700');
    }

    if (подозрителни.length) {
      console.log('%c⚠ ключове със структурен знак вътре: ' + подозрителни.length,
        'color:#ef6c00;font-weight:700');
      console.table(подозрителни);
    }
    if (крадци.length) {
      console.log('%c⚠ за поглед — ключ в 3+ различни записа: ' + крадци.length +
        ' (не е грешка, но оттам почва кражбата на чужди въпроси)', 'color:#ef6c00');
      console.table(крадци.map(function (к) {
        return { ключ: к.ключ, записи: к.брой, къде: к.записи.join(', ') };
      }));
    }
    if (числа.length) {
      console.log('ℹ чисти числа (ЛЕГИТИМНИ — температура и размери): ' + числа.length +
        ' → ' + числа.map(function (ч) { return ч.ключ; }).join(', '));
    }

    window.BL_КЛЮЧОВЕ.последен = доклад;
    return доклад;
  }

  window.BL_КЛЮЧОВЕ = { провери: провери, последен: null };
  window.BL_KEYS = window.BL_КЛЮЧОВЕ;   // за писане без кирилица в конзолата
  console.log('🔑 ключ-пазачът е зареден → BL_КЛЮЧОВЕ.провери()  (или BL_KEYS.провери())');
})();
