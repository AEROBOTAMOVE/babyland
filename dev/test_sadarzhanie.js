// ═══════════════════════════════════════════════════════════
// 📑 СЪДЪРЖАНИЕТО НА СТАТИЯТА — пазач за скоковете
//
// ЗАЩО (02.09): дългите статии получиха списък за прескачане по подзаглавия.
// Той има ЕДИН тих начин да се счупи: два раздела с близки имена дават ЕДИН И
// СЪЩ котвен адрес. Тогава копчето „Гънките" води при „Гънките и кремът" — и
// това не гърми, не се логва и изглежда като нормално превъртане. Майката
// просто попада не там, където е поискала, и не разбира защо.
//
// Уредът чете СЪЩАТА функция за адрес, каквато е в js/articles.js — не своя
// препис. Ако утре тя се смени, тук трябва да гръмне, а не да мери старото.
//
// ПУСКАНЕ: node dev/test_sadarzhanie.js
// ПЪТ НАЗАД: файлът само ЧЕТЕ.
// ═══════════════════════════════════════════════════════════
const fs = require('fs');
const path = require('path');
const ROOT = path.resolve(__dirname, '..');

// ── взимаме слъг-функцията ДОСЛОВНО от живия файл ──
const изворен = fs.readFileSync(path.join(ROOT, 'js/articles.js'), 'utf8');
const редСлъг = изворен.split(/\r?\n/).filter(l => l.indexOf('const слъг =') >= 0)[0];
if (!редСлъг) { console.log('🔴 НЯМА функция слъг в js/articles.js — уредът мери нещо друго'); process.exit(1); }
const начало = изворен.indexOf(редСлъг);
const край = изворен.indexOf(';', изворен.indexOf('.slice(0, 40)', начало));
let слъг;
try { слъг = eval('(' + изворен.slice(начало, край + 1).replace(/^\s*const слъг =\s*/, '').replace(/;$/, '') + ')'); }
catch (e) { console.log('🔴 не мога да взема слъг: ' + e.message); process.exit(1); }

// ── и прага, при който изобщо се показва ──
const редПраг = изворен.split(/\r?\n/).filter(l => l.indexOf('if (думи <') >= 0)[0] || '';
const ПРАГ = Number((редПраг.match(/думи < (\d+)/) || [0, 450])[1]);
const редМин = изворен.split(/\r?\n/).filter(l => l.indexOf('заглавия.length <') >= 0)[0] || '';
const МИН = Number((редМин.match(/заглавия\.length < (\d+)/) || [0, 4])[1]);

console.log('');
console.log('📑 СЪДЪРЖАНИЕТО НА СТАТИЯТА — пазач за скоковете');
console.log('');
console.log('   прочетено от живия файл: праг ' + ПРАГ + ' думи · минимум ' + МИН + ' подзаглавия');

// ═══ САМОПРОВЕРКА ═══
const проби = [
  ['еднакви заглавия дават ЕДИН адрес (значи сблъсък се вижда)', слъг('Гънките') === слъг('Гънките')],
  ['различни заглавия дават РАЗЛИЧНИ адреси', слъг('Гънките') !== слъг('Ноктенцата')],
  ['емоджито не чупи адреса', /^ah-[а-яa-z0-9-]+$/i.test(слъг('🚨 Кога да търсиш лекар'))],
  ['адресът не е празен', слъг('Първата баня — не бързай').length > 4],
  ['🪤 дългите заглавия се РЕЖАТ на 40 и могат да се слеят',
    слъг('Много дълго заглавие за раздел с точно определени думи A') ===
    слъг('Много дълго заглавие за раздел с точно определени думи B')]
];
let слаби = 0;
for (const [име, ок] of проби) { if (!ок) слаби++; console.log('   ' + (ок ? '✅' : '🔴') + ' ' + име); }
if (слаби) { console.log(''); console.log('   🔴 УРЕДЪТ Е СЧУПЕН'); process.exit(1); }
console.log('');

// ═══ МЕРЕНЕ по всички статии ═══
let сСписък = 0, безСписък = 0, сблъсъци = [], спешниОтпред = 0, спешниИма = 0;
let общо = 0;
for (const f of fs.readdirSync(path.join(ROOT, 'lib')).filter(x => /^[a-z0-9-]+\.json$/.test(x) && x !== 'index.json')) {
  const о = JSON.parse(fs.readFileSync(path.join(ROOT, 'lib', f), 'utf8'));
  for (const [id, т] of Object.entries(о)) {
    if (typeof т !== 'string') continue;
    общо++;
    const думи = (т.match(/[а-яА-Яa-zA-Z]+/g) || []).length;
    const заглавия = т.split('\n').map(s => s.trim()).filter(s => s.startsWith('## '))
      .map(s => s.slice(3).replace(/\*\*(.+?)\*\*/g, '$1').trim());
    if (думи < ПРАГ || заглавия.length < МИН) { безСписък++; continue; }
    сСписък++;
    // сблъсък на адреси В ЕДНА СТАТИЯ — точно това праща майката другаде
    const адреси = заглавия.map(слъг);
    const видени = new Map();
    for (let i = 0; i < адреси.length; i++) {
      if (видени.has(адреси[i])) сблъсъци.push({ id, адрес: адреси[i], а: видени.get(адреси[i]), б: заглавия[i] });
      else видени.set(адреси[i], заглавия[i]);
    }
    const сп = заглавия.filter(з => з.indexOf('🚨') >= 0);
    if (сп.length) { спешниИма++; if (заглавия.indexOf(сп[0]) > 0) спешниОтпред++; }
  }
}

console.log('   статии общо                      : ' + общо);
console.log('   ✅ получават списък за прескачане : ' + сСписък);
console.log('      без списък (къси или без раздели): ' + безСписък);
console.log('   от тях със СПЕШЕН раздел          : ' + спешниИма);
console.log('      🔑 от които спешният НЕ беше пръв: ' + спешниОтпред + '  ← точно тези печелят най-много');
console.log('');
if (сблъсъци.length) {
  console.log('   🔴 СБЛЪСЪЦИ НА АДРЕСИ (скокът води другаде): ' + сблъсъци.length);
  for (const с of сблъсъци.slice(0, 10))
    console.log('      ' + с.id + '   „' + с.а + '"  ⇄  „' + с.б + '"   → ' + с.адрес);
  if (сблъсъци.length > 10) console.log('      … и още ' + (сблъсъци.length - 10));
} else {
  console.log('   ✅ НУЛА сблъсъка на адреси — всеки скок води на своето място');
}
console.log('');
process.exit(сблъсъци.length ? 1 : 0);
