function зареди(W, файл, кръпка) {
  let текст = чети('js/' + файл);
  if (кръпка) {
    const нов = кръпка(текст);
    if (нов === текст) { гръм('кръпката за ' + файл + ' НЕ хвана нищо — анкърът е сменен'); return false; }
    текст = нов;
  }
  try {
    new vm.Script(текст, { filename: файл }).runInContext(W);
    return true;
  } catch (e) {
    гръм('пясъчникът гръмна на ' + файл + ' → ' + e.message);
    return false;
  }
}

