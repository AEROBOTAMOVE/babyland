function инвентар(файлове) {
  const места = [];
  let прегледаниРедове = 0;
  файлове.forEach(f => {
    const текст = чети('js/' + f);
    const редове = текст.split('\n');
    прегледаниРедове += редове.length;
    редове.forEach((ред, i) => {
      const гол = ред.replace(/^\s+/, '');
      if (гол.startsWith('//')) return;                    // коментар не е сметка
      ЧЕТЕНЕ.lastIndex = 0;
      const ключове = [];
      let m;
      while ((m = ЧЕТЕНЕ.exec(ред))) ключове.push(m[1]);
      if (!ключове.length) return;
      // 🪤 Изразът може да продължава на следващите редове („.filter(…)“ отдолу).
      //    Ако гледаме САМО реда, изпускаме всяко многоредово място и после
      //    докладваме „0 находки“ от 0 прегледани. Прозорец от 3 реда.
      const прозорец = редове.slice(i, i + 3).join(' ');
      if (!СМЕТКА.some(s => прозорец.includes(s))) return;
      // контекст: три реда коментар над него дават темата
      const над = редове.slice(Math.max(0, i - 3), i).join(' ');
      места.push({
        файл: f, ред: i + 1, мой: МОИ.includes(f),
        ключове: [...new Set(ключове)],
        израз: гол.slice(0, 190),
        тема: тема(гол + ' ' + над)
      });
    });
  });
  return { места, прегледаниРедове, прегледаниФайлове: файлове.length };
}

