// Два медальона с ЕДНО И СЪЩО условие светват в един миг и застават един
// до друг на рафта с еднакъв надпис. Мама е направила едно нещо, а
// приложението ѝ казва, че е направила две. Това е същият клас — едно
// нещо, две числа — само че вместо число се дублира самата победа.
// Мярката е ЖИВА: условията се сравняват по СВОЯ СОБСТВЕН изходен текст
// (ok.toString()) и по думите, които мама чете (t), а после и по това
// кои светват заедно при истинско състояние.
function близнациМедальони(кръпка) {
  const W = пясъчник({});
  if (!зареди(W, 'extras.js', кръпка)) return { прегледани: 0, двойки: [] };
  const списък = W.BL_BADGES.list || [];
  const поУсловие = {}, поТекст = {};
  списък.forEach(b => {
    const у = String(b.ok).replace(/\s+/g, '');
    (поУсловие[у] = поУсловие[у] || []).push(b);
    (поТекст[b.t] = поТекст[b.t] || []).push(b);
  });
  const двойки = [];
  Object.keys(поУсловие).forEach(у => {
    if (поУсловие[у].length > 1) {
      двойки.push({ вид: 'еднакво УСЛОВИЕ', списък: поУсловие[у], детайл: у.slice(0, 110) });
    }
  });
  Object.keys(поТекст).forEach(t => {
    if (поТекст[t].length > 1 && !двойки.some(д => д.списък[0].t === t)) {
      двойки.push({ вид: 'еднакъв НАДПИС пред мама', списък: поТекст[t], детайл: t });
    }
  });
  двойки.forEach(д => {
    находка('🔴 БЛИЗНАЦИ',
      'два медальона с ' + д.вид + ' → светват едновременно и стоят един до друг:\n' +
      д.списък.map(b => '        · ' + b.e + ' „' + b.n + '“ (' + b.id + ') — ' + b.t).join('\n') +
      '\n        ' + д.детайл);
  });
  return { прегледани: списък.length, двойки };
}

