function нормализирай(израз, ключ) {
  const i = израз.indexOf(ключ);
  const парче = i > -1 ? израз.slice(Math.max(0, i - 60), i + 130) : израз;
  return парче.replace(/\s+/g, '').replace(/['"]/g, "'");
}
function двойници(места) {
  const поКлюч = {};
  места.forEach(м => м.ключове.forEach(k => { (поКлюч[k] = поКлюч[k] || []).push(м); }));
  const групи = [];
  Object.keys(поКлюч).sort().forEach(k => {
    const сп = поКлюч[k];
    const форми = new Set(сп.map(м => нормализирай(м.израз, k)));
    if (сп.length >= 2 && форми.size >= 2) групи.push({ ключ: k, места: сп, форми: форми.size });
  });
  return групи;
}

