    window.confirm = m => { роднидиалози.push(текущМаркер + ' → confirm: ' + String(m).slice(0, 50)); return false; };
    window.prompt = m => { роднидиалози.push(текущМаркер + ' → prompt: ' + String(m).slice(0, 50)); return null; };
    const върниРодните = () => { window.alert = родни.alert; window.confirm = родни.confirm; window.prompt = родни.prompt; };
