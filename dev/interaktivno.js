  function върни(с) {
    try {
      const сега = snapKeys();
      for (const k of сега) if (!(k in с)) localStorage.removeItem(k);
      for (const k of Object.keys(с)) if (localStorage.getItem(k) !== с[k]) localStorage.setItem(k, с[k]);
    } catch (e) {}
    function snapKeys() { const a = []; for (let i = 0; i < localStorage.length; i++) a.push(localStorage.key(i)); return a; }
  }
  function разлика(a, b) {
    const сменени = [];
    const всички = new Set(Object.keys(a).concat(Object.keys(b)));
    for (const k of всички) if (a[k] !== b[k]) сменени.push(k);
    return сменени;
  }
  // 🪤 ПЪРВАТА ВЕРСИЯ ползваше document.body.innerText — той ФОРСИРА подредба на
