  // ── самопроверка: може ли изобщо да различи жив бутон от мъртъв
  async function самопроверка() {
    const кутия = document.createElement('div');
    кутия.style.cssText = 'position:fixed;left:-9999px;top:0';
    const жив = document.createElement('button'); жив.textContent = 'жив';
    жив.addEventListener('click', () => { кутия.appendChild(document.createElement('span')); });
    const пишещ = document.createElement('button'); пишещ.textContent = 'пишещ';
    пишещ.addEventListener('click', () => { localStorage.setItem('__проба__', String(1)); });
    // хармоника: сменя САМО атрибут — точно случаят, който първата версия
    // на отпечатъка обяви за мъртъв бутон девет пъти
    const хармоника = document.createElement('button'); хармоника.textContent = 'хармоника';
    хармоника.setAttribute('aria-expanded', 'false');
    хармоника.addEventListener('click', () => {
      хармоника.setAttribute('aria-expanded', хармоника.getAttribute('aria-expanded') === 'true' ? 'false' : 'true');
    });
    // РАЗМЯНА: единият се затваря, другият се отваря — броят НЕ мърда.
    // Точно този случай направи 7 живи бутона на „мъртви" в първия обход.
    const размА = document.createElement('button'); размА.textContent = 'размяна А';
    const размБ = document.createElement('button'); размБ.textContent = 'размяна ББББ';
    размА.setAttribute('aria-expanded', 'true'); размБ.setAttribute('aria-expanded', 'false');
    размА.addEventListener('click', () => {
      размА.setAttribute('aria-expanded', 'false'); размБ.setAttribute('aria-expanded', 'true');
    });
    const мъртъв = document.createElement('button'); мъртъв.textContent = 'мъртъв';
    const опасен = document.createElement('button'); опасен.textContent = 'изтрий всичко';
    кутия.append(жив, пишещ, хармоника, размА, размБ, мъртъв, опасен);
    document.body.appendChild(кутия);
    const р1 = await натисни(жив), р2 = await натисни(пишещ), р3 = await натисни(мъртъв), р4 = await натисни(хармоника), р5 = await натисни(размА);
    try { localStorage.removeItem('__проба__'); } catch (e) {}
    const опасенХванат = РАЗРУШИТЕЛНИ.test(надпис(опасен));
    const живХванат = РАЗРУШИТЕЛНИ.test(надпис(жив));
    кутия.remove();
    return {
      '✅ вижда ЖИВ бутон (мени страницата)': р1.промени,
      '✅ вижда ПИШЕЩ бутон (мени паметта)': р2.записа.indexOf('__проба__') >= 0,
      '✅ вижда МЪРТЪВ бутон (нищо)': !р3.промени && !р3.записа.length,
      '✅ вижда ХАРМОНИКА (само атрибут aria-expanded)': р4.промени,
      '✅ вижда РАЗМЯНА (броят не мърда, отваря се друг)': р5.промени,
      '✅ пропуска РАЗРУШИТЕЛЕН': опасенХванат,
      '✅ и НЕ пропуска безобиден (обратната посока)': !живХванат
    };
  }

