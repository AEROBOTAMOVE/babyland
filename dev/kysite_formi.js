// ═══════════════════════════════════════════════════════════
// ✂️ КЪСИТЕ ФОРМИ — майката пише по-малко думи, отколкото сме предвидили
//
// ЗАЩО (02.09): след седем живи обиколки и ~140 въпроса се очерта една
// закономерност. Почти НИКОГА не липсва съдържание — липсват ДУМИТЕ:
//
//    ключ „хвърля храната"       ↔ майката пише „хвърля храна"      → ТИШИНА
//    ключ „кога да го дам на ясла" ↔ майката пише „ясла"            → ТИШИНА
//    ключ „заспива само на ръце"  ↔ майката пише „спи само на ръце"  → ТИШИНА
//
// 🔑 ПРИЧИНАТА Е В САМИЯ МАТЧЪР: многодумният ключ трябва да е ПОДНИЗ НА
//    ВЪПРОСА. Тоест по-дългият ключ НЕ хваща по-краткия въпрос — само
//    обратното. Всеки ключ, чиято по-къса форма води другаде, е тиха дупка.
//
// Този уред прави машинно това, което правех на ръка: за всеки ключ строи
// по-къси форми и пита къде отиват.
//    · маха определителния член („храната" → „храна")
//    · маха последната дума („кога да го дам на ясла" → „кога да го дам на")
//    · маха водещото „кога/как/може ли да"
//
// ⚠️ И НЕ ВСЯКА КЪСА ФОРМА ТРЯБВА ДА РАБОТИ. „кога" само по себе си не е
//    въпрос. Затова се докладват само форми с поне 2 думи или над 5 букви, и
//    само когато СЕГА водят ДРУГАДЕ или мълчат.
//
// ПУСКАНЕ: node dev/kysite_formi.js [брой карти]
// ПЪТ НАЗАД: файлът само ЧЕТЕ.
// ═══════════════════════════════════════════════════════════
const fs = require('fs');
const path = require('path');
const ROOT = path.resolve(__dirname, '..');
const { zaredi } = require(path.join(ROOT, 'dev/pyasachnik.js'));
const W = zaredi(null);

const питай = (т, с) => {
  try {
    const р = W.BL_MATCH(т, с);
    const з = Array.isArray(р) ? р[0] : (р && (р.entry || р.item || р));
    return з ? з.id : 'ТИШИНА';
  } catch (e) { return 'ГРЕШКА'; }
};

// ── как се прави по-къса форма ──
// членуването в българския е НА КРАЯ на думата, затова се маха оттам.
// 🪤 ПЪРВИЯТ ОПИТ БЕШЕ ГРЕШЕН И САМОПРОВЕРКАТА ГО ХВАНА:
//    писах един регулярен израз с алтернативи (та|то|те|ът|…) и „храната" стана
//    „хранат" — алчното начало грабва колкото може и оставя НАЙ-КЪСОТО
//    окончание („а"), вместо вярното („та").
//    А в българския и двете разчитания са възможни: „храна"+„та" е вярното,
//    „хран"+„ата" не е. Кое е кое зависи от думата, не от правило.
//    Затова тук НЕ СЕ ГАДАЕ: връщат се ВСИЧКИ кандидати и всеки се пробва.
//    По-добре три проби, от които две са безсмислени, отколкото една сгрешена.
const АРТИКЛИ = ['ата', 'ото', 'ята', 'ият', 'ият', 'ъте', 'та', 'то', 'те', 'ът', 'ят', 'а', 'я'];

// 🔑 РЕШАВАЩИЯТ ФИЛТЪР, добавен след ВТОРОТО пускане.
//    Дори с махнатото правило за откъслеците уредът даваше 2934 „тишини" —
//    защото произвеждаше НЕДУМИ: „бременностт", „седмицат", „стран".
//    Такава форма, разбира се, не намира карта, и НЕ БИВА.
//    Затова се пита базата: срещала ли се е тази дума НЯКЪДЕ другаде — в текст
//    на карта, в статия или в друг ключ? Ако не — това не е дума, а огризка,
//    и не се проверява изобщо.
//    ⚠️ Мярка, чиито находки не се четат, е равна на липсваща мярка. Затова
//    праговете тук се стягат, докато списъкът стане ЧЕТИМ, а не докато стане
//    дълъг.
const ЛЕКСИКОН = (() => {
  const думи = new Set();
  const гол = h => String(h || '').replace(/<[^>]+>/g, ' ');
  for (const z of W.KB.entries) {
    const т = гол(z.core) + ' ' + гол(z.tip) + ' ' + гол(z.follow) + ' ' + (z.keys || []).join(' ') + ' ' + String(z.title || '');
    for (const д of (т.toLowerCase().match(/[а-яё]{3,}/g) || [])) думи.add(д);
  }
  return думи;
})();

const БЕЗ_ЧЛЕН = д => {
  const изход = [];
  for (const о of АРТИКЛИ) {
    // 🪤 остатъкът трябва да е поне 4 букви: при 3 „уста" ставаше „уст" и уредът
    //    произвеждаше безсмислени проби, които после трябва да се четат на ръка.
    if (д.length - о.length < 4 || !д.toLowerCase().endsWith(о)) continue;
    const корен = д.slice(0, д.length - о.length);
    if (ЛЕКСИКОН.has(корен.toLowerCase())) изход.push(корен);   // ← само истински думи
  }
  return изход;
};

function късиФорми(ключ) {
  const думи = String(ключ).trim().split(/\s+/);
  const форми = new Set();
  // 1 · без определителен член на ПОСЛЕДНАТА дума (всички разчитания)
  if (думи.length >= 2) {
    for (const корен of БЕЗ_ЧЛЕН(думи[думи.length - 1])) {
      const без = думи.slice(0, -1).concat(корен).join(' ');
      if (без !== ключ) форми.add(без);
    }
  }
  // 2 · без водещото питане („кога да махна биберона" → „махна биберона")
  const безпитане = ключ.replace(/^(кога|как|какво|може ли|мога ли|трябва ли|защо|къде)\s+(да\s+)?/i, '');
  if (безпитане !== ключ && безпитане.split(/\s+/).length >= 2) форми.add(безпитане);

  // 🪤 ПЪРВОТО ПУСКАНЕ ДАДЕ 1428 „ТИШИНИ" ОТ 120 КАРТИ — и това е БЕЗПОЛЕЗНО.
  //    Имах и трето правило: „махни последната дума". То произвеждаше откъслеци
  //    („малко за", „вдигане на тежко в", „не мога да"), които, разбира се,
  //    не намират карта — и не бива. Сигналът се удави в собствения ми шум.
  //    Уред, който изкарва хиляда находки, е същото като уред, който не изкарва
  //    нито една: и в двата случая никой не ги чете.
  //    Затова правилото е махнато, а остатъкът се пресява:
  //    · формата не бива да свършва на предлог или частица (пак откъслек)
  //    · поне две думи, или една над 5 букви
  const ОПАШКА = /(^|\s)(за|в|във|на|до|от|с|със|по|при|да|ли|и|или|че|ми|му|си|се)$/i;
  return [...форми]
    .filter(ф => !ОПАШКА.test(ф))
    .filter(ф => ф.split(/\s+/).length >= 2 || ф.length > 5);
}

// ═══ САМОПРОВЕРКА ═══
const проби = [
  ['членът се маха', късиФорми('хвърля храната').indexOf('хвърля храна') >= 0],
  ['откъслек НЕ се произвежда', !късиФорми('кога да го дам на ясла').some(ф => /s(на|за|да|в)$/.test(ф))],
  ['водещото питане се маха', късиФорми('кога да махна биберона').some(ф => ф.indexOf('махна') === 0)],
  ['късо не се цепи още', късиФорми('сън').length === 0],
  ['късата дума не се цепи', БЕЗ_ЧЛЕН('уста').length === 0],
  ['НЕДУМА се отхвърля', БЕЗ_ЧЛЕН('бременността').indexOf('бременностт') < 0],
  ['истинската дума ОСТАВА', БЕЗ_ЧЛЕН('бременността').indexOf('бременност') >= 0],
  ['всички разчитания се връщат', БЕЗ_ЧЛЕН('храната').indexOf('храна') >= 0]
];
console.log('');
console.log('✂️ КЪСИТЕ ФОРМИ — води ли по-краткият въпрос при същата карта');
console.log('');
let слаби = 0;
for (const [име, ок] of проби) { if (!ок) слаби++; console.log('   ' + (ок ? '✅' : '🔴') + ' самопроверка: ' + име); }
if (слаби) { console.log(''); console.log('   🔴 УРЕДЪТ Е СЧУПЕН'); process.exit(1); }
console.log('');

// ═══ МЕРЕНЕ ═══
const ЛИМИТ = Number(process.argv[2] || 0) || W.KB.entries.length;
let прегледани = 0, проверени = 0;
const дупки = [];
for (const z of W.KB.entries.slice(0, ЛИМИТ)) {
  прегледани++;
  for (const к of (z.keys || [])) {
    for (const ф of късиФорми(к)) {
      проверени++;
      const г = питай(ф, z.room);
      if (г !== z.id) дупки.push({ карта: z.id, стая: z.room, ключ: к, къса: ф, отива: г });
    }
  }
}

// групираме по карта, за да не залее изходът
const поКарти = new Map();
for (const д of дупки) {
  if (!поКарти.has(д.карта)) поКарти.set(д.карта, []);
  поКарти.get(д.карта).push(д);
}
const тишина = дупки.filter(д => д.отива === 'ТИШИНА');
const чужди = дупки.filter(д => д.отива !== 'ТИШИНА');

console.log('   прегледани карти   : ' + прегледани);
console.log('   проверени къси форми: ' + проверени);
console.log('   🔇 водят в ТИШИНА  : ' + тишина.length);
console.log('   🔀 водят при ДРУГА : ' + чужди.length);
console.log('   засегнати карти    : ' + поКарти.size);
console.log('');
console.log('   ── първите 25 тишини (късата форма не намира нищо) ──');
for (const д of тишина.slice(0, 25))
  console.log('      „' + д.къса.padEnd(34) + '"   от ключ „' + д.ключ.slice(0, 32) + '"  → ' + д.карта);
console.log('');
console.log('   ── първите 20, които водят при ЧУЖДА карта ──');
for (const д of чужди.slice(0, 20))
  console.log('      „' + д.къса.padEnd(30) + '"  ' + д.карта.padEnd(20) + ' → ' + д.отива);
console.log('');
fs.writeFileSync(path.join(__dirname, 'kysite_formi.json'), JSON.stringify(дупки, null, 1));
console.log('   💾 dev/kysite_formi.json (' + дупки.length + ' записа)');
console.log('');
console.log('   ⚠️ НЕ ВСЯКА е дефект: „кога да го дам на" не е въпрос, а „бебето"');
console.log('      води другаде с право. Списъкът е за ЧЕТЕНЕ, не за автоматично');
console.log('      прилагане — точно както възрастта не се слага по ключова дума.');
console.log('');
