  //  САМОПРОВЕРКА — тестът нарочно чупи флаговете и доказва, че ги лови.
  //  Тест, който не пада на счупено, е декорация. Затова тук се саботира
  //  В ДВЕТЕ ПОСОКИ: първо флаг, който винаги мълчи (трябва да паднат
  //  всички спешни), после флаг, който винаги крещи (трябва да паднат
  //  всички спокойни). Пазач срещу фалшива тревога, тестван само в едната
  //  посока, вече веднъж създаде ПРОПУСНАТА — това няма да се повтори тук.
  // ═══════════════════════════════════════════════════════════
  // ⚠️ АРИТМЕТИКАТА, която обърках първия път (и я оставям записана, защото
  //    точно такава грешка прави пазача „вълк"): сравнявах реалните провала
  //    под саботаж с „колко реда може да счупи саботажът“ — и излизаше 62
  //    срещу 60, значи „САМОПРОВЕРКАТА Е СЧУПЕНА“ върху съвсем здрав тест.
  //    Разликата бяха седемте познати дупки от група Z: когато саботирам
  //    BL_REDFLAG, BL_MOTHERFLAG си остава ИСТИНСКИЯТ — и Z6/Z7 падат както
  //    падат и без саботаж. Тоест очакваното е ОБЕДИНЕНИЕ: редовете, които
  //    саботажът чупи, ПЛЮС редовете, които вече падат по НЕсаботираната
  //    функция. Инак самопроверката щеше да гърми при всяка нова дупка —
  //    точно когато тестът си върши работата най-добре.
  function самопроверка(базовиПровали) {
    var сцени = [
      { име: 'счупен BL_REDFLAG: винаги ТИХО', пипа: 'red',
        red: function () { return false; }, mother: null,
        трябва_да_паднат: function (t) { return t[3] === 'red' && t[4] === ГЪРМИ; },
        защо: 'всички спешни за бебето трябва да се обявят за ПРОПУСНАТИ' },
      { име: 'счупен BL_REDFLAG: винаги ГЪРМИ', пипа: 'red',
        red: function () { return true; }, mother: null,
        трябва_да_паднат: function (t) { return t[3] === 'red' && t[4] === ТИХО; },
        защо: 'всички спокойни трябва да се обявят за ФАЛШИВА ТРЕВОГА' },
      { име: 'счупен BL_MOTHERFLAG: винаги null', пипа: 'mother',
        red: null, mother: function () { return null; },
        трябва_да_паднат: function (t) { return t[3] === 'mother' && t[4] !== null; },
        защо: 'dv, loss, mother, mamabody и heavy трябва да паднат' },
      { име: 'счупен BL_MOTHERFLAG: винаги „mother"', пипа: 'mother',
        red: null, mother: function () { return 'mother'; },
        трябва_да_паднат: function (t) { return t[3] === 'mother' && t[4] !== 'mother'; },
        защо: 'всички без-флаг и всички други нива трябва да паднат' }
    ];

    var изход = [];
    for (var i = 0; i < сцени.length; i++) {
      var с = сцени[i];
      var отСаботаж = 0, отДупки = 0;
      (function (с) {
        var n = 0;
        tестовеЦикъл(ТЕСТОВЕ, function (t) {
          if (с.трябва_да_паднат(t)) отСаботаж++;
          // ред, който пада и без саботаж, по функцията, която НЕ пипаме
          else if (базовиПровали[n] && t[3] !== с.пипа) отДупки++;
          n++;
        });
      })(с);
      var очакванПад = отСаботаж + отДупки;
      var р = изпълни(ТЕСТОВЕ, с.red || window.BL_REDFLAG, с.mother || window.BL_MOTHERFLAG);
      var паднали = 0;
      for (var j = 0; j < р.length; j++) if (!р[j].мина) паднали++;
      // Търсим ТОЧНО толкова провала. По-малко → тестът е сляп за счупеното.
      // Повече → саботажът е замърсил чужди редове и числата вече лъжат.
      изход.push({
        саботаж: с.име,
        какво_доказва: с.защо,
        очаквани_от_саботажа: отСаботаж,
        плюс_вече_падащи: отДупки,
        очаквани_общо: очакванПад,
        реални_провала: паднали,
        ЛОВИ_ЛИ: (паднали === очакванПад && отСаботаж > 0) ? 'ДА' : 'НЕ'
      });
    }
    return изход;
  }

