  function изпълни(тестове, red, mother) {
    var изход = [];
    tестовеЦикъл(тестове, function (t) {
      var група = t[0], име = t[1], вход = t[2], вид = t[3], очаквано = t[4];
      var получено;
      try {
        получено = (вид === 'red') ? !!red(вход) : mother(вход);
        if (получено === undefined) получено = null;   // undefined и null са едно и също „нищо"
      } catch (e) {
        получено = 'ГРЕШКА: ' + (e && e.message ? e.message : e);
      }
      изход.push({
        група: група,
        име: име,
        вход: вход,
        функция: (вид === 'red') ? 'BL_REDFLAG' : 'BL_MOTHERFLAG',
        ОЧАКВАНО: показ(очаквано),
        ПОЛУЧЕНО: показ(получено),
        мина: получено === очаквано,
        // посоката на провала — двете грешки не струват еднакво
        вид_провал: получено === очаквано ? '' :
          (очаквано === ТИХО || очаквано === null ? 'ФАЛШИВА ТРЕВОГА' : 'ПРОПУСНАТА ТРЕВОГА')
      });
    });
    return изход;
  }
  function tестовеЦикъл(списък, f) { for (var i = 0; i < списък.length; i++) f(списък[i]); }
  function показ(v) {
    if (v === true) return 'ГЪРМИ (true)';
    if (v === false) return 'тихо (false)';
    if (v === null) return 'без флаг (null)';
    return String(v);
  }

  // ── Профилните: пазим bl_baby и го връщаме, каквото и да стане ──
  function изпълниПрофилни(red) {
    var КЛЮЧ = 'bl_baby';
    var пазено = null, пипано = false, върнато = false;
    var изход = [];
    try {
      пазено = localStorage.getItem(КЛЮЧ);
      tестовеЦикъл(ПРОФИЛНИ, function (t) {
        var група = t[0], име = t[1], вход = t[2], дни = t[3], очаквано = t[4];
        var д = new Date(Date.now() - дни * 86400000);
        var рожден = д.getFullYear() + '-' +
          ('0' + (д.getMonth() + 1)).slice(-2) + '-' + ('0' + д.getDate()).slice(-2);
        var получено;
        try {
          localStorage.setItem(КЛЮЧ, JSON.stringify({ birth: рожден }));
          пипано = true;
          получено = !!red(вход);
        } catch (e) {
          получено = 'ГРЕШКА: ' + (e && e.message ? e.message : e);
        }
        изход.push({
          група: група, име: име, вход: вход + '   (рожден ден ' + рожден + ')',
          функция: 'BL_REDFLAG',
          ОЧАКВАНО: показ(очаквано), ПОЛУЧЕНО: показ(получено),
          мина: получено === очаквано,
          вид_провал: получено === очаквано ? '' :
            (очаквано === ТИХО ? 'ФАЛШИВА ТРЕВОГА' : 'ПРОПУСНАТА ТРЕВОГА')
        });
      });
    } finally {
      try {
        if (пазено === null) localStorage.removeItem(КЛЮЧ);
        else localStorage.setItem(КЛЮЧ, пазено);
        върнато = (localStorage.getItem(КЛЮЧ) === пазено);
      } catch (e) { върнато = false; }
    }
    return { редове: изход, ключ: КЛЮЧ, пипан: пипано, ВЪРНАТ: върнато,
             беше_празен: пазено === null };
  }

