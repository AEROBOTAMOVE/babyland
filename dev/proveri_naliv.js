// Всеки писар твърди, че е чист. Твърдението не е доказателство. Тук се
// брои САМО от файловете, преди сливането:
//   1. валиден ли е JSON-ът
//   2. има ли ПРАВ знак за кавичка в текста (той чупи JSON и не е български)
//   3. има ли ЛАТИНСКА буква в кирилска дума (невидима, убива търсенето)
//   4. има ли забранени остарели практики (мед под година, спирт на пъпчето…)
//   5. има ли дози или имена на лекарства (забранени в целия проект)
//   6. има ли 🚨 ред при медицинска тема
//   7. колко дълги са ключовете (по-дълъг от въпроса = недостижим)
//
// 🪤 Пиша го като ФАЙЛ, не инлайн: два пъти днес bash изяде екранирането в
//   `node -e` и проверката ми се разпадна на средата.
//
// ПУСКАНЕ: node dev/proveri_naliv.js
// ПЪТ НАЗАД: файлът само ЧЕТЕ.
// ═══════════════════════════════════════════════════════════
const fs = require('fs');
const path = require('path');
process.chdir(path.resolve(__dirname, '..'));

const ПАПКА = 'dev/nahodki/naliv';
const ПРАВ = String.fromCharCode(34);

// 🪤 ПЪРВАТА ВЕРСИЯ ВДИГНА ФАЛШИВА ТРЕВОГА за „оцет" — а изречението беше
//   „Без разтривки с алкохол и БЕЗ ОЦЕТ", тоест точно правилният съвет.
//   Същият капан е записан и в dev/standarti.pl за думата „мед". Затова тук
//   всяко правило се проверява ЗАЕДНО С ОТРИЦАНИЕТО пред него: практика,
//   пред която стои „без", „не", „никога", „вече не" или „отпадна", НЕ Е
//   находка, а предупреждение — точно това, което искаме да пише.
const ОТРИЧА = /(без|не\s|никога|отпадн|вече не|нито)\s*[^.!?]{0,40}$/i;
function отречена(текст, поз) {
  const преди = текст.slice(Math.max(0, поз - 60), поз);
  return ОТРИЧА.test(преди);
}
const ЗАБРАНЕНИ = [
  [/мед[а-я]*\s+(на|под|преди)\s+(бебе|една година|годинката|1 година)/i, 'мед под 1 година'],
  [/спирт[а-я]*\s+(на|върху)\s+пъпч/i, 'спирт на пъпчето'],
  [/оцет/i, 'оцет (при температура)'],
  [/сок в шише/i, 'сок в шише'],
  [/пудра за бебе/i, 'пудра'],
  [/(разтривай|разтрий)\s+със\s+спирт/i, 'разтриване със спирт']
];
// 🪤 И ВТОРАТА МОЯ ГРЕШКА, хваната от собствената ми самопроверка: тук стоеше
//   `\b(нурофен|…)\b`. Но `\b` в JavaScript е граница само за латиница и
//   цифри — след кирилска буква НЯМА граница, затова изразът не намираше
//   НИЩО и мълчеше. Точно капанът, записан в целия този проект.
//   Кирилската граница е (^|[^а-яА-Я]) и (?![а-яА-Я]).
const ЛЕКАРСТВА = /(^|[^а-яА-Я])(нурофен|ибалгин|аналгин|аспирин|панадол|бромхексин|амоксицилин|аугментин)(?![а-яА-Я])/i;
const ДОЗА = /\d+\s?(мг|ml|мл)\s?\/\s?(кг|kg)|\d+\s?мг\s+на\s+килограм/i;

const МЕД_ДУМИ = /температур|лекар|болн|спешн|инфекц|кръв|диша|обрив|лечен|антибиот|доктор|112/i;

if (!fs.existsSync(ПАПКА)) { console.log('🔴 няма ' + ПАПКА); process.exit(1); }
const файлове = fs.readdirSync(ПАПКА).filter(f => f.endsWith('.json')).sort();

console.log('🔍 ПРОВЕРКА НА НАЛЯТОТО\n');
let общоСтатии = 0, общоЗнаци = 0, общоКарти = 0, червени = 0;
const проблеми = [];

for (const ф of файлове) {
  let d;
  try { d = JSON.parse(fs.readFileSync(ПАПКА + '/' + ф, 'utf8')); }
  catch (e) { червени++; проблеми.push('🔴 ' + ф + ' — СЧУПЕН JSON: ' + e.message); continue; }
  if (!Array.isArray(d)) { червени++; проблеми.push('🔴 ' + ф + ' — не е масив'); continue; }

  let прави = 0, латиница = [], безСирена = 0, дългиКлючове = 0, забранени = [], лекарства = [];
  let знаци = 0, карти = 0;

  for (const x of d) {
    const цял = [x.zaglavie, x.rezyume, x.tialo,
      x.karta && x.karta.title, x.karta && x.karta.core,
      x.karta && x.karta.tip, x.karta && x.karta.follow].filter(Boolean).join('\n');
    знаци += String(x.tialo || '').length;
    if (x.karta) carti();
    function carti() { карти++; }

    прави += (цял.match(new RegExp(ПРАВ, 'g')) || []).length;

    // латинска буква в кирилска дума
    for (const дума of цял.split(/[^а-яА-Яa-zA-Z]+/)) {
      if (дума.length < 2) continue;
      if (!/[а-яА-Я]/.test(дума) || !/[a-zA-Z]/.test(дума)) continue;
      if (/^[A-Z]{2,}/.test(дума)) continue;
      латиница.push(дума);
    }

    for (const [из, име] of ЗАБРАНЕНИ) { const м = из.exec(цял); if (м && !отречена(цял, м.index)) забранени.push(име); }
    if (ЛЕКАРСТВА.test(цял)) лекарства.push((цял.match(ЛЕКАРСТВА) || [])[0]);
    if (ДОЗА.test(цял)) лекарства.push('ДОЗА: ' + (цял.match(ДОЗА) || [])[0]);

    // медицинска тема без 🚨
    if (МЕД_ДУМИ.test(цял) && цял.indexOf('🚨') < 0) безСирена++;

    for (const k of ((x.karta && x.karta.klyuchove) || [])) {
      if (String(k).length > 34) дългиКлючове++;
    }
  }

  общоСтатии += d.length; общоЗнаци += знаци; общоКарти += карти;
  const лош = прави || латиница.length || забранени.length || лекарства.length;
  if (лош) червени++;
  console.log('  ' + (лош ? '🔴' : '✅') + ' ' + ф.padEnd(24) + d.length + ' статии · ' +
              знаци + ' знака · ' + карти + ' карти');
  if (прави) проблеми.push('🔴 ' + ф + ': ' + прави + ' ПРАВИ кавички (чупят JSON и не са български)');
  if (латиница.length) проблеми.push('🔴 ' + ф + ': латиница в кирилски думи → ' + латиница.slice(0, 6).join(', '));
  if (забранени.length) проблеми.push('🔴 ' + ф + ': ЗАБРАНЕНА ПРАКТИКА → ' + [...new Set(забранени)].join(', '));
  if (лекарства.length) проблеми.push('🔴 ' + ф + ': име на лекарство или доза → ' + [...new Set(лекарства)].join(', '));
  if (безСирена) проблеми.push('🔶 ' + ф + ': ' + безСирена + ' медицински теми БЕЗ 🚨 ред');
  if (дългиКлючове) проблеми.push('🔶 ' + ф + ': ' + дългиКлючове + ' ключа над 34 знака (вероятно недостижими)');
}

console.log('\n  ОБЩО: ' + файлове.length + ' файла · ' + общоСтатии + ' статии · ' +
            общоЗнаци.toLocaleString('bg') + ' знака · ' + общоКарти + ' карти');
if (проблеми.length) { console.log('\n  ── НАМЕРЕНО ──'); проблеми.forEach(x => console.log('     ' + x)); }
else console.log('\n  ✅ ЧИСТО');

// самопроверка
const примамка = [{ zaglavie: 'Проба', tialo: 'дай му мед на бебе и кръвнa проба, температура', karta: null }];
let сп = { прави: 0, лат: 0, забр: 0 };
const ц = примамка[0].tialo;
сп.прави = (ц.match(new RegExp(ПРАВ, 'g')) || []).length;
for (const д of ц.split(/[^а-яА-Яa-zA-Z]+/)) if (д.length > 1 && /[а-яА-Я]/.test(д) && /[a-zA-Z]/.test(д)) сп.лат++;
for (const [из] of ЗАБРАНЕНИ) if (из.test(ц)) сп.забр++;
console.log('\n  САМОПРОВЕРКА (иначе нулите не значат нищо):');
console.log('     ' + (сп.лат ? '✅' : '🔴') + ' лови латиница в кирилска дума („кръвнa")');
console.log('     ' + (сп.забр ? '✅' : '🔴') + ' лови забранена практика („мед на бебе")');
console.log('     ' + (ЛЕКАРСТВА.test('дай нурофен') ? '✅' : '🔴') + ' лови име на лекарство');
console.log('     ' + (!ЛЕКАРСТВА.test('дай му вода и мляко') ? '✅' : '🔴') + ' НЕ лови безобиден текст (обратната посока)');
console.log('     ' + (отречена('без разтривки с алкохол и без оцет', 34) ? '✅' : '🔴') + ' РАЗПОЗНАВА отрицание („без оцет" НЕ е находка)');
console.log('     ' + (!отречена('слагай оцет на челото', 7) ? '✅' : '🔴') + ' и НЕ го разпознава там, където го няма (обратната посока)');

process.exitCode = червени ? 1 : 0;
