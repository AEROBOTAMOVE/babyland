// ═══════════════════════════════════════════════════════════
// 🚪 ЧУЖДА СТАЯ — картата, която отговаря вместо съседа си
//
// ЗАЩО СЪЩЕСТВУВА: цял ден намирам един и същи клас дефект, но всеки път
// НА РЪКА и по случайност:
//     «паднах по стълбите»          → „Как да избера количка"
//     «изля вряла вода върху него»  → картата за водата за ПИЕНЕ
//     «вагинално течение»           → картата за НАСТИНКА
//     «изпускам урина»              → „как се взима проба урина"
//     «паник атака след раждане»    → чантата за родилното
//     «кафе при кърмене»            → „колко мляко трябва"
// Всяко от тях е било невидимо за всичките 62 уреда, защото те питат
// „намира ли се нещо", а не „намира ли се ПРАВИЛНОТО".
//
// КАК СЕ ЛОВИ БЕЗ ДА СЕ ЗНАЕ ВЕРНИЯТ ОТГОВОР:
// За всяка карта се съчинява въпрос ОТ НЕЙНОТО СОБСТВЕНО ЗАГЛАВИЕ и се пита
// В НЕЙНАТА СОБСТВЕНА СТАЯ. Ако отговорът дойде от ДРУГА стая — това е
// заподозрян: картата не може да защити собствената си тема на собствен терен,
// въпреки че домашната стая вече ѝ дава предимство (×1.6).
//
// 🪤 ЗАЩО НЕ Е ПРОСТО „сравни id-тата": част от кръстосването е ЗАКОННО.
//   „Здраве и SOS" нарочно отговаря на медицински въпроси, зададени от други
//   стаи — там има цял механизъм (MED_PASS). Затова такива двойки се броят
//   ОТДЕЛНО и не се обявяват за дефект.
//
// 🪤 И ВТОРО: заглавието не се преписва дословно. Тест с цялото заглавие мери
//   индекса, не двигателя, и винаги дава 100%. Взимат се 2-3 СМИСЛОВИ думи,
//   разбъркани — както пише майка.
//
// ПУСКАНЕ: node dev/chuzhda_staya.js [--spisak]
// ПЪТ НАЗАД: файлът само ЧЕТЕ.
// ═══════════════════════════════════════════════════════════
const fs = require('fs');
const vm = require('vm');
const path = require('path');
process.chdir(path.resolve(__dirname, '..'));

const СПИСЪК = process.argv.includes('--spisak');
const S = 'C:/Users/User/AppData/Local/Temp/claude/C--Users-User-Downloads-----/' +
          'a78d0ad3-272e-4eb0-929e-dba161c5ab2a/scratchpad';

let zaredi;
try { zaredi = require(S + '/pyasachnik.js').zaredi; }
catch (e) { console.log('🔴 няма пясъчник: ' + e.message); process.exit(1); }
const W = zaredi(null);
if (typeof W.BL_MATCH !== 'function') { console.log('🔴 няма BL_MATCH'); process.exit(1); }

// ── базата
const ctx = { console: { log() {} }, JSON, Math, Date, RegExp, String, Number, Array, Object };
ctx.window = ctx; ctx.globalThis = ctx; ctx.self = ctx;
vm.createContext(ctx);
new vm.Script(fs.readFileSync('js/kb.js', 'utf8')).runInContext(ctx);
const KB = ctx.BL_KB || ctx.KB;
const записи = KB.entries || [];
const поId = new Map(записи.map(z => [z.id, z]));
if (записи.length < 100) { console.log('🔴 базата е ' + записи.length + ' записа'); process.exit(1); }

// ── съчиняване на майчиния въпрос
const СЛУЖЕБНИ = new Set(['при', 'след', 'преди', 'през', 'към', 'между', 'без', 'над', 'под',
  'кога', 'какво', 'как', 'защо', 'кое', 'кои', 'кой', 'коя', 'или', 'това', 'тези', 'която',
  'които', 'срещу', 'според', 'дали', 'още', 'най', 'все', 'вече', 'само', 'също', 'едно',
  'една', 'един', 'става', 'прави', 'значи', 'има', 'няма', 'ако', 'дори', 'нещо']);
const думи = t => String(t || '').toLowerCase()
  .replace(/[0-9]+[-–—][0-9]+/g, ' ').replace(/[^а-яa-z\s]/g, ' ')
  .split(/\s+/).filter(w => w.length >= 4 && !СЛУЖЕБНИ.has(w));

// ── „Здраве и SOS" законно поема медицински въпроси от други стаи
const МЕДИЦИНСКА = 'Здраве и SOS';

let проверени = 0, своя = 0, чужда = 0, медицинска = 0, тишина = 0;
const заподозрени = [];

for (const з of записи) {
  const д = думи(з.title);
  if (д.length < 2) continue;
  const въпрос = [д[д.length - 1], д[0], д[1]].filter(Boolean).slice(0, 3).join(' ');
  if (въпрос.length < 8) continue;
  проверени++;

  let м = null;
  try { м = W.BL_MATCH(въпрос, з.room); } catch (e) {}
  const ид = м && (м.id || (м.entry && м.entry.id));
  if (!ид) { тишина++; continue; }
  if (ид === з.id) { своя++; continue; }

  const друга = поId.get(ид);
  const стаяНаОтговора = друга ? друга.room : '?';
  if (стаяНаОтговора === з.room) { своя++; continue; }        // друга карта, но СВОЯ стая — законно
  if (стаяНаОтговора === МЕДИЦИНСКА) { медицинска++; continue; } // законният медицински мост
  чужда++;
  заподозрени.push({
    от: з.room, id: з.id, заглавие: String(з.title).slice(0, 44),
    въпрос, отиде: ид, в: стаяНаОтговора,
    чуждоЗаглавие: друга ? String(друга.title).slice(0, 40) : '?'
  });
}

console.log('🚪 ЧУЖДА СТАЯ\n');
console.log('  ПРЕГЛЕДАНИ КАРТИ : ' + проверени + ' от ' + записи.length +
            '   (останалите имат под 2 смислови думи в заглавието)\n');
console.log('  ✅ отговаря СВОЯТА стая              : ' + своя + '  (' + (100 * своя / проверени).toFixed(0) + '%)');
console.log('  ⚪ отговаря „Здраве и SOS" (законно) : ' + медицинска);
console.log('  🔇 тишина                            : ' + тишина);
console.log('  🔴 ОТГОВАРЯ ЧУЖДА СТАЯ               : ' + чужда + '  (' + (100 * чужда / проверени).toFixed(0) + '%)');

if (заподозрени.length) {
  console.log('\n  ── ЗАПОДОЗРЕНИ ──');
  const показ = СПИСЪК ? заподозрени : заподозрени.slice(0, 25);
  for (const x of показ) {
    console.log('   „' + x.въпрос + '"');
    console.log('      от [' + x.от + '] ' + x.id + ' « ' + x.заглавие);
    console.log('      →  [' + x.в + '] ' + x.отиде + ' « ' + x.чуждоЗаглавие);
  }
  if (!СПИСЪК && заподозрени.length > 25) console.log('   … още ' + (заподозрени.length - 25) + ' — с --spisak');
}

// ── самопроверка: може ли изобщо да гръмне
// Правим изкуствен случай: питаме с думите на карта от една стая, но в ДРУГА стая.
let самоОК = false;
const проба = записи.find(z => z.room === 'Инструменти' && думи(z.title).length >= 2);
if (проба) {
  const д = думи(проба.title);
  const в = [д[д.length - 1], д[0]].filter(Boolean).join(' ');
  let м = null;
  try { м = W.BL_MATCH(в, 'Бременност'); } catch (e) {}
  const ид = м && (м.id || (м.entry && м.entry.id));
  const друга = ид ? поId.get(ид) : null;
  самоОК = !!(друга && друга.room !== 'Бременност');
}
console.log('\n  САМОПРОВЕРКА (иначе нулите не значат нищо):');
console.log('     ' + (самоОК ? '✅' : '🔶') + ' уредът РАЗПОЗНАВА отговор от чужда стая, когато има такъв');
console.log('     ✅ прегледани са ' + проверени + ' карти — числото е част от мярката');

console.log('\n  ЦЕЛТА: „отговаря чужда стая" под 5%. Всеки ред горе е въпрос,');
console.log('  на който майката получава отговор от съвсем друга тема.');
process.exitCode = 0;   // уредът ДОКЛАДВА, не блокира: част от находките са спорни
