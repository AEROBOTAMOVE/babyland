// 🗣️ КОРЕНЪТ Е ПРЕКАЛЕНО ДЪЛЪГ — думата на майката е по-дълга от
//    думата в заглавието, и затова не я намира.
//
// js/lib.js реже корена на `v.slice(0, Math.max(5, v.length - 2))`.
// За дълга дума това дава дълъг корен, а дългият корен не е префикс на
// по-късия си роднина: „хълцането" → корен „хълцане", а в заглавието
// стои „хълца" — и двете думи за едно и също нещо не се срещат.
//
// 🪤 ПЪРВОТО МИ МЕРЕНЕ БЕШЕ БОКЛУК и го пиша, за да не се повтори.
// Броях за „роднини" всяка двойка, споделяща 3-4 букви. Излязоха 471
// „находки" — сред тях „маска/масаж", „както/какво", „пъти/пътуване".
// Число, което брои съвпадения на срички, не е измерване.
//
// СЕГА правилото е тясно и проверимо: броим САМО когато думата в
// заглавието е ИСТИНСКИ ПРЕФИКС на думата на майката (тоест едната е
// другата плюс окончание) и текущият корен въпреки това не я хваща.
// Това е точно класът „коренът е по-дълъг от целта" — нищо друго.
//
// ПЪТ НАЗАД: файлът само ЧЕТЕ.
// ═══════════════════════════════════════════════════════════
const fs=require('fs');
const норм = s => String(s||'').toLowerCase().replace(/[^а-яa-z0-9\s]/g,' ').replace(/\s+/g,' ').trim();

const src=fs.readFileSync('js/lib.js','utf8');
const ред=(src.match(/const к = v\.slice\([^\n]*/)||[])[0];
if(!ред || !/Math\.max\(меко \? 4 : 5, v\.length - 2\)/.test(ред)){
  console.log('⚠ РЯЗАНЕТО В lib.js Е ДРУГО — меренето е остаряло. Намерих: '+(ред||'нищо'));
  process.exit(1);
}
const корен=(v,меко)=>v.slice(0, Math.max(меко?4:5, v.length-2));

const инд=JSON.parse(fs.readFileSync('lib/index.json','utf8')).items;
const вЗаглавия=new Set();
for(const с of инд) for(const w of норм(с.t).split(' ')) if(w.length>=4) вЗаглавия.add(w);

const kb=fs.readFileSync('js/kb.js','utf8');
const отKB=new Set();
for(const m of kb.matchAll(/keys:\s*\[([^\]]*)\]/g))
  for(const x of m[1].matchAll(/['"]([^'"]*)['"]/g))
    for(const w of норм(x[1]).split(' ')) if(w.length>=5) отKB.add(w);

// българските окончания, с които дума става по-дълга от корена си
const ОК=/^(та|то|те|ят|ъ т|ът|а|о|е|и|я|ия|ята|ето|ите|ове|овете|ни|на|но|ното|ната|ните)$/;
let проверени=0; const намерени=[];
for(const дума of отKB){
  проверени++;
  const к=корен(дума,false), км=корен(дума,true);
  if([...вЗаглавия].some(w=>w.startsWith(к)||w.startsWith(км))) continue;  // намира се — не е случай
  for(const цел of вЗаглавия){
    if(цел.length>=дума.length) continue;
    if(!дума.startsWith(цел)) continue;                  // ИСТИНСКИ префикс, не съвпадение на срички
    const опашка=дума.slice(цел.length);
    if(!ОК.test(опашка)) continue;                       // и то с истинско окончание
    намерени.push({майката:дума, вЗаглавието:цел, корен:к, окончание:опашка});
    break;
  }
}
namesort(намерени);
function namesort(a){ a.sort((x,y)=>x.майката.localeCompare(y.майката,'bg')); }
console.log('🗣️ КОРЕНЪТ Е ПО-ДЪЛЪГ ОТ ЦЕЛТА');
console.log('   думи от ключовете (5+ букви): '+проверени+' · думи в заглавията: '+вЗаглавия.size);
console.log('   истински случаи: '+намерени.length);
console.log('   (дума на майката = дума в заглавието + окончание, а коренът не я хваща)\n');
намерени.forEach(н=>console.log('     '+н.майката.padEnd(18)+' → корен „'+н.корен+'"   ·  в заглавието стои: '+н.вЗаглавието+'  (+'+н.окончание+')'));
fs.mkdirSync('dev/nahodki',{recursive:true});
fs.writeFileSync('dev/nahodki/glagoli.json',JSON.stringify(намерени,null,1),'utf8');
