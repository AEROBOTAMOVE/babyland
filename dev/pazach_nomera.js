// 🚩 ПАЗАЧ НА СПЕШНИТЕ НОМЕРА — мъртвият 116 006 да не се върне
//
// ПРОВЕРЕНО В РЕГИСТЪРА НА КРС (живо, 25.08.2026): в цяла България са
// предоставени ТРИ номера от обхват 116 — 116016 (жертви на насилие срещу
// жени, АМС), 116111 (деца, ДАЗД) и 116000 (изчезнали деца). 116 006 ГО НЯМА.
// Потвърдено и от МВР/ГДНП, Прокуратурата и Национална мрежа за децата.
//
// Защо е най-лошият вид грешка: до секундата преди да натисне, жена, която
// бяга от насилие вкъщи, вярва, че звъни на помощ. Получава „няма такъв номер".
// В приложението стояха ДВЕ ЖИВИ tel: връзки — набираха се с един палец.
//
// ЗАМЕСТНИКЪТ: 0800 18 676 — Национална телефонна линия за пострадали от
// домашно насилие. Безплатна, денонощна, целогодишна. Потвърдена от МВР,
// Прокуратурата, Министерски съвет и оператора (фондация „Асоциация Анимус").
//
// ⚠ ЗАЩО НЕ 116 016: предоставен е на 30.01.2025, но ОЩЕ НЕ Е ИЗГРАДЕН
// (отговор по ЗДОИ: очаква се до юни 2026). Непотвърден номер не влиза в
// спешен екран. По-добре работещ стар, отколкото красив мъртъв.
//
// ⛔ js/sos.js се проверява за ВРЪЗКИ, но НЕ за текста „116 006": двете
//    споменавания там са в ИСТОРИЧЕСКИЯ коментар, който обяснява защо
//    номерът е махнат. Той трябва да го назовава.
//
// 🪤 ГРЕШКА В САМИЯ ПАЗАЧ, платена веднага: проверката за „tel: с интервали"
//    беше `/tel:0800\s*18\s*676/`. Но `\s*` е НУЛА или повече — тоест хващаше
//    и напълно правилното `tel:080018676` и обяви вярната връзка за счупена.
//    Пазач, който гърми при здраво, е по-лош от липсващ. Иска се `\s+`.
//
// ПУСКАНЕ: node dev/pazach_nomera.js
// ПЪТ НАЗАД: файлът само ЧЕТЕ.
// ═══════════════════════════════════════════════════════════
const fs = require('fs');
const path = require('path');
process.chdir(path.resolve(__dirname, '..'));

const МЪРТВИ = [
  { гол: '116006', вид: /116\s?006/g, име: '116 006 — не съществува в България' }
];
const ЖИВИ_ФАЙЛОВЕ = [
  'js/helper.js', 'js/women5.js', 'js/kb.js',
  'lib/mama-1.json', 'lib/women-1.json', 'lib/index.json',
  'lib/health-1.json', 'lib/health-2.json', 'lib/health-3.json',
  'lib/tools-1.json', 'lib/modern-1.json', 'lib/modern-2.json',
  'lib/baby-1.json', 'lib/feed-1.json', 'lib/feed-2.json',
  'lib/preg-1.json', 'lib/dev-1.json', 'lib/lab-1.json'
];
const С_ВРЪЗКИ = ['js/helper.js', 'js/women5.js', 'js/sos.js'];

console.log('🚩 ПАЗАЧ НА СПЕШНИТЕ НОМЕРА\n');

let прегледани = 0, намерени = 0;
for (const ф of ЖИВИ_ФАЙЛОВЕ) {
  if (!fs.existsSync(ф)) continue;
  прегледани++;
  const т = fs.readFileSync(ф, 'utf8');
  for (const м of МЪРТВИ) {
    const n = (т.match(м.вид) || []).length;
    if (n) { намерени += n; console.log('  🔴 ' + ф + ': ' + n + '× ' + м.име); }
  }
}
console.log((намерени ? '  🔴 ' : '  ✅ ') + 'мъртви номера в текста: ' + намерени +
            '   (прегледани файла: ' + прегледани + ')');

// ── tel: стойност с интервал не се набира
let сИнтервал = 0, връзки = 0;
const видяни = [];
for (const ф of С_ВРЪЗКИ) {
  if (!fs.existsSync(ф)) continue;
  const т = fs.readFileSync(ф, 'utf8');
  for (const v of (т.match(/tel:[0-9+][0-9+\s]{2,19}/g) || [])) {
    връзки++;
    видяни.push(ф.replace('js/', '') + ':' + v.trim());
    if (/tel:[0-9+]*\s+[0-9+]/.test(v)) { сИнтервал++; console.log('  🔴 ' + ф + '  «' + v.trim() + '»'); }
  }
}
console.log((сИнтервал ? '  🔴 ' : '  ✅ ') + 'tel: с интервали (не се набират): ' + сИнтервал +
            '   (прегледани връзки с цифри: ' + връзки + ')');
console.log('     ' + видяни.join(' · '));

// ── самопроверка: може ли изобщо да гръмне
const примамка = 'href="tel:116006"';
const хващаМъртъв = (примамка.match(МЪРТВИ[0].вид) || []).length > 0;
const хващаИнтервал = /tel:[0-9+]*\s+[0-9+]/.test('tel:0800 18 676');
const неХващаЗдраво = !/tel:[0-9+]*\s+[0-9+]/.test('tel:080018676');
console.log('\n  САМОПРОВЕРКА (иначе нулите не значат нищо):');
console.log('     ' + (хващаМъртъв ? '✅' : '🔴') + ' лови мъртвия номер в примамка');
console.log('     ' + (хващаИнтервал ? '✅' : '🔴') + ' лови tel: с интервали');
console.log('     ' + (неХващаЗдраво ? '✅' : '🔴') + ' НЕ лови правилното tel:080018676 (обратната посока)');

const самоОК = хващаМъртъв && хващаИнтервал && неХващаЗдраво;
process.exitCode = (намерени || сИнтервал || !самоОК) ? 1 : 0;
console.log('\n  ' + (process.exitCode ? '🔴 ИМА ЧЕРВЕНО' : '✅ ЧИСТО'));
