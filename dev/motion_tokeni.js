// ЗАЩО (07.09.2026): наръчникът за immersive web иска „един ритъм" (§1.1) и
// motion токени (§53). Измерих какво има днес:
//
//     cubic-bezier(0.34, 1.56, 0.64, 1)   59 употреби  (пружина)
//     cubic-bezier(0.22, 1, 0.36, 1)      26 употреби  (плавно спиране)
//     cubic-bezier(0.4, 0, 0.3, 1)         5 употреби
//     ... и още 9 еднократни
//     токени: НУЛА
//
// Тоест дизайнът ВЕЧЕ има система — просто е написана по три различни начина
// за една и съща крива („0.34, 1.56" · „0.34,1.56" · „.34,1.56").
//
// ⚠️ ЗАЩО Е БЕЗОПАСНО: заменят се САМО стойности, които са БУКВА ПО БУКВА
//    еднакви след махане на празните места. `cubic-bezier(.34,1.56,.64,1)` и
//    `cubic-bezier(0.34, 1.56, 0.64, 1)` са ЕДНА И СЪЩА крива — браузърът
//    смята същото. Замяната с var() е визуално тъждествена по определение,
//    не по мнение. Еднократните криви НЕ се пипат: те може да са нарочни.
//
// ⚠️ КАКВО ПЕЧЕЛИМ, освен подредба: щом кривите и времената са в токени,
//    `html[data-motion='reduce']` ги занулява НА ЕДНО МЯСТО — и целият
//    проект утихва наистина, вместо на 66 отделни правила.
//
// ПУСКАНЕ: node dev/motion_tokeni.js [--pishi]
// ПЪТ НАЗАД: git checkout -- css/
// ═══════════════════════════════════════════════════════════════════════════
'use strict';
const fs = require('fs');
const path = require('path');
const КОРЕН = path.resolve(__dirname, '..');
process.chdir(КОРЕН);
const ПИШИ = process.argv.includes('--pishi');

// само кривите с 5+ употреби — еднократните са нарочен избор на дизайнера
const ТОКЕНИ = [
  ['--bl-ease-spring', '0.34,1.56,0.64,1'],
  ['--bl-ease-out', '0.22,1,0.36,1'],
  ['--bl-ease-in-out', '0.4,0,0.3,1'],
];

const свий = s => s.replace(/\s+/g, '').replace(/(^|[^0-9])0\./g, '$1.');

const файлове = fs.readdirSync('css').filter(f => /\.css$/.test(f));
let общо = 0;
const промени = [];

for (const ф of файлове) {
  const п = path.join('css', ф);
  let s = fs.readFileSync(п, 'utf8');
  const беше = s;
  let вФайла = 0;
  s = s.replace(/cubic-bezier\(([^)]*)\)/g, (цяло, вътре) => {
    const ключ = свий(вътре);
    for (const [име, стойност] of ТОКЕНИ) {
      if (ключ === свий(стойност)) { вФайла++; общо++; return 'var(' + име + ')'; }
    }
    return цяло;
  });
  if (вФайла) { промени.push([ф, вФайла]); if (ПИШИ) fs.writeFileSync(п, s); }
}

console.log('');
console.log('  ⏱️ МОТОРНИ ТОКЕНИ');
for (const [ф, n] of промени.sort((a, b) => b[1] - a[1])) console.log('     ' + String(n).padStart(4) + '  ' + ф);
console.log('     ─────');
console.log('     ' + String(общо).padStart(4) + '  общо заменени (всички визуално тъждествени)');
console.log('');
if (!ПИШИ) { console.log('  СУХО. За писане: node dev/motion_tokeni.js --pishi'); console.log(''); }
else { console.log('  ✅ записано. Токените се дефинират в css/tier.css'); console.log(''); }
