# -*- coding: utf-8 -*-
"""
🩺 ПАЗАЧ НА ЗАМРАЗЕНИТЕ СТАНДАРТИ
════════════════════════════════════════════════════════════════════
Пуска се върху цялата библиотека (lib/*.json) и KB-то (js/kb.js) и
проверява дали някъде не сме отворили вратичка в правилата, за които
сме се разбрали, че нямат изключения.

Защо съществува: три отделни армии от агенти намериха ТРИ РАЗЛИЧНИ
статии, които отварят вратичка в „вода преди 6 месеца — не“ (веднъж
с „при жега“, веднъж с „без педиатър“, веднъж с „при формула“). Не
защото някой е сгрешил нарочно, а защото 747 статии не се помнят.
Този скрипт помни вместо нас.

Пускане (от папката babyland):
    python dev/standarti.py

Изход: 0 = чисто, 1 = има нарушения.
"""
import json, io, glob, os, re, sys

КОРЕН = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
os.chdir(КОРЕН)

# ── зареждане ──
idx = {it['id']: it for it in json.load(io.open('lib/index.json', encoding='utf-8'))['items']}
тела = {}
for f in glob.glob('lib/*.json'):
    if f.endswith('index.json'): continue
    for k, v in json.load(io.open(f, encoding='utf-8')).items():
        if isinstance(v, str): тела[k] = (os.path.basename(f), v)
kb = io.open('js/kb.js', encoding='utf-8').read()

def заг(i): return (idx.get(i) or {}).get('t', '?')

нарушения = []
def сигнал(правило, файл, ид, откъс):
    нарушения.append((правило, файл, ид, откъс))

# ══════════════════════════════════════════════════════════════════
# 1. ВОДА ПРЕДИ 6 МЕСЕЦА — НЕ. Без „ама при жега“, „ама на формула“,
#    „ама ако педиатърът“. Търсим разрешение с условие.
# ══════════════════════════════════════════════════════════════════
ВРАТИЧКА = re.compile(
    r'(^|[^а-я])(вода|водичк\w+|чай|чайче)([^а-я][^.!?\n]{0,90})'
    r'(при жега|в горещи|през лятото|на формула|при адаптирано|без педиатър|ако лекар)',
    re.I)
for i, (f, t) in тела.items():
    for m in ВРАТИЧКА.finditer(t):
        ок = t[max(0, m.start()-120):m.end()+120]
        # ако наблизо изрично пише границата — минава
        if re.search(r'под 6 месец|преди 6-ия|под шест месец|не преди 6', ок, re.I): continue
        сигнал('вода преди 6 м.', f, i, m.group(0))

# ══════════════════════════════════════════════════════════════════
# 2. МЕД ПОД 1 ГОДИНА — АБСОЛЮТНА ЗАБРАНА
# ══════════════════════════════════════════════════════════════════
for i, (f, t) in тела.items():
    for m in re.finditer(r'\bмед\b|\bмедът\b|\bмеда\b', t, re.I):
        ок = t[max(0, m.start()-600):m.end()+600]
        if re.search(r'под (1|една) годин|до (1|една) годин|преди 12 месец|не преди (1|12)|първата годин|под годинк|под годин|преди годинк|първия рожден|след годинката|ботулиз', ок, re.I): continue
        if re.search(r'мед(ицин|ицинск|ик|сестр|окам)', t[m.start():m.start()+12], re.I): continue
        # медът в списък със ЗАБРАНЕНИ неща („не слагай сода, лимон, мед…“) е
        # правилна употреба — там границата на възрастта не е темата.
        преди = t[max(0, m.start()-90):m.start()]
        if re.search(r'\*\*Не\*\*|не\s+(слагай|мажи|давай|използвай|търкай)', преди, re.I): continue
        сигнал('мед под 1 г.', f, i, ок[100:210].replace('\n', ' '))

# ══════════════════════════════════════════════════════════════════
# 3. БЕЗОПАСЕН СЪН — щом статията описва средата, трябва и позицията
# ══════════════════════════════════════════════════════════════════
ОПИСВА = [re.compile(x, re.I) for x in
          [r'твърд(ия)? матрак', r'празно легло', r'без свободни възглавниц',
           r'позиционер', r'бебешко гнездо', r'обиколниц', r'безопасн\w+ сън']]
for i, (f, t) in тела.items():
    # ДВА отделни маркера, не един: една подмятана дума („празно легло“ в
    # статия за страховете на 2-годишно) не прави статията урок по безопасен сън.
    if sum(1 for r in ОПИСВА if r.search(t)) < 2: continue
    if re.search(r'по гръб|на гръб|по гърба', t, re.I): continue
    сигнал('безопасен сън без позиция', f, i, заг(i)[:50])

# ══════════════════════════════════════════════════════════════════
# 4. ЗАДАВЯНЕ — щом статията казва „действай“, трябва и КАК (5 и 5)
# ══════════════════════════════════════════════════════════════════
УЧИ = re.compile(r'удари по гърба|гръбни удари|удари между лопатки|притискания|хватк\w+ при задавян|действия(та)? при задавян', re.I)
for i, (f, t) in тела.items():
    if not УЧИ.search(t): continue
    if re.search(r'5 удара|пет удара', t, re.I) and re.search(r'5 притискан|пет притискан', t, re.I): continue
    сигнал('задавяне без броя на хватките', f, i, заг(i)[:50])

# ══════════════════════════════════════════════════════════════════
# 5. ДОЗИ — червената линия. Никакви мг/мл/капки/на килограм.
# ══════════════════════════════════════════════════════════════════
ДОЗА = re.compile(r'\d+[\d,.\s]*\s*(мг|мл|mg|ml)\b|\d+\s*капк[аи]\b|мг на килограм|на килограм тегло|/kg|на кг телесн', re.I)
for i, (f, t) in тела.items():
    for m in ДОЗА.finditer(t):
        сигнал('ДОЗА', f, i, t[max(0, m.start()-70):m.end()+40].replace('\n', ' '))
for m in ДОЗА.finditer(kb):
    сигнал('ДОЗА', 'js/kb.js', '-', kb[max(0, m.start()-70):m.end()+40].replace('\n', ' '))

# ══════════════════════════════════════════════════════════════════
# 6. ТЕМПЕРАТУРА — прагът е 38.0°, не 37.5 и не 38.5
# ══════════════════════════════════════════════════════════════════
for i, (f, t) in тела.items():
    for m in re.finditer(r'(3[5-9][.,]\d)\s*(°|градус|C\b)', t):
        ст = m.group(1).replace(',', '.')
        if ст in ('38.0', '39.0', '38.5', '37.5'):
            # 38.5/37.5 не са грешни сами по себе си (има контексти),
            # но ги показваме за око
            околност = t[max(0, m.start()-300):m.end()+200]
            if re.search(r'ваксин|имунизац|убождан|от кабинета', околност, re.I): continue
            if ст in ('37.5', '38.5'):
                сигнал('праг ≠ 38.0 (за око)', f, i, t[max(0, m.start()-80):m.end()+60].replace('\n', ' '))

# ══════════════════════════════════════════════════════════════════
# 7. ПАРА ЗА КРУП — забранено
# ══════════════════════════════════════════════════════════════════
for i, (f, t) in тела.items():
    for m in re.finditer(r'пара\w*', t, re.I):
        ок = t[max(0, m.start()-160):m.end()+160]
        if not re.search(r'круп|лаещ\w+ кашлиц|ларингит', ок, re.I): continue
        if re.search(r'не помага|не се препоръчва|не прави|няма полза|не лекува', ок, re.I): continue
        сигнал('пара при круп', f, i, ок[120:250].replace('\n', ' '))

# ══════════════════════════════════════════════════════════════════
# 8. ХРАНИ С РИСК ОТ ЗАДАВЯНЕ — предложени за ядене без предупреждение.
#    Библиотеката сама ги изрежда сред най-честите причини за задавяне,
#    а после друга статия ги съветва („сурово моркувче хрупа различно“).
#    Този клас грешки — една статия срещу друга — не се лови с четене
#    на една статия. (армия 29.07)
# ══════════════════════════════════════════════════════════════════
РИСКОВИ = re.compile(
    r'(сурово?\w* морков\w*|суров морков|цял\w* ядк|цяло грозде|пуканк|'
    r'твърд\w* бонбон|кренвирш на кръгче|морков на кръгче)', re.I)
СЪВЕТ = re.compile(r'пробвай|предложи|дай му|дай ѝ|давай|подходящ\w+ е|може да хрупа|хрупа', re.I)
for i, (f, t) in тела.items():
    for m in РИСКОВИ.finditer(t):
        ок = t[max(0, m.start()-220):m.end()+220]
        # ако наблизо пише, че е риск/забранено — статията ги ползва правилно
        if re.search(r'задавян|риск|не се дава|внимавай|опасн|наряз|настърж|не преди', ок, re.I): continue
        if not СЪВЕТ.search(ок): continue
        сигнал('рискова храна, съветвана', f, i, ок[180:300].replace('\n', ' '))

# ══════════════════════════════════════════════════════════════════
# 9. НАКЛОНЕНА ПОВЪРХНОСТ ЗА СЪН — съветвана като помощ при рефлукс,
#    круп или хрема. Стандартът е „твърд и РАВЕН“: при наклон детето се
#    смъква и брадичката притиска дихателните пътища.
# ══════════════════════════════════════════════════════════════════
НАКЛОН = re.compile(r'повдигни (горната част на )?(матрака|постелката|леглото|креватчето)|подложи .{0,20}под матрака|книга под матрака|на наклон|наклонена повърхност', re.I)
for i, (f, t) in тела.items():
    for m in НАКЛОН.finditer(t):
        ок = t[max(0, m.start()-260):m.end()+260]
        if re.search(r'не (се )?повдигай|не подпъхвай|риск|не помага|не се препоръчва|вместо това|не прави|недей|“: не|“: не\.|не лекуват|позиционер', ок, re.I): continue
        # „държат ли на наклон“ е за спирачки на количка, не за сън
        if re.search(r'спирачк|количк|стълб|рампа|тротоар', ок, re.I): continue
        сигнал('наклонена повърхност за сън', f, i, ок[220:340].replace(chr(10), ' '))

# ══════════════════════════════════════════════════════════════════
# 10. КАФЕТО ПРИ БРЕМЕННОСТ — замразената мярка е ЕДНО на ден.
#     Внесена статия беше удвоила границата („около две малки кафета
#     на ден“) срещу три места в кода, които казват едно. Числото е
#     замразено съзнателно (js/wisdom.js) — не се вдига от статия.
# ══════════════════════════════════════════════════════════════════
КАФЕ = re.compile(r'(две|2|три|3|четири|4)\s+(малки\s+)?кафе(та)?\b', re.I)
for i, (f, t) in тела.items():
    if (idx.get(i) or {}).get('r') != 'Бременност': continue
    for m in КАФЕ.finditer(t):
        ок = t[max(0, m.start()-160):m.end()+160]
        # „не повече от две“ / „две вече са много“ е правилна употреба
        if re.search(r'не повече от|вече (са )?много|прекалено|са много', ок, re.I): continue
        сигнал('кафе > 1 на ден (Бременност)', f, i, ок[130:250].replace('\n', ' '))

# ── доклад ──
print('═' * 70)
print('🩺 ПАЗАЧ НА ЗАМРАЗЕНИТЕ СТАНДАРТИ — %d статии + kb.js' % len(тела))
print('═' * 70)
if not нарушения:
    print('\n✅ ЧИСТО. Нито един стандарт не е нарушен.\n')
    sys.exit(0)

по_правило = {}
for пр, f, i, о in нарушения:
    по_правило.setdefault(пр, []).append((f, i, о))
for пр in sorted(по_правило, key=lambda x: -len(по_правило[x])):
    редове = по_правило[пр]
    знак = '🔴' if пр in ('ДОЗА', 'вода преди 6 м.', 'задавяне без броя на хватките', 'рискова храна, съветвана', 'наклонена повърхност за сън') else '🟠'
    print('\n%s %s — %d' % (знак, пр.upper(), len(редове)))
    for f, i, о in редове[:12]:
        print('   %-16s %-18s %s' % (f, i, о[:88]))
    if len(редове) > 12: print('   … и още %d' % (len(редове) - 12))
print('\nОБЩО: %d\n' % len(нарушения))
sys.exit(1)
