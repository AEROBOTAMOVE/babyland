// 📄 РЕЗЮМЕТАТА — описват ли още текста под себе си
//
// ЗАЩО: на 19.08 голям проход пренаписа 275 статии и наля +232 KB. Телата се
// смениха, а редовете в index.json останаха. Майката вижда едно обещание в
// списъка и намира друг текст, като влезе. Досега никой не го е мерил.
//
// КАК: от резюмето се вадят СМИСЛОВИТЕ думи (без служебните) и се пита колко
// от тях се срещат в тялото — по КОРЕН, не по цяла дума, за да оцелее
// склонението („обезводняване" ↔ „обезводнено").
//
// 🪤 ЗАЩО НЕ ПО ПЪРВОТО ИЗРЕЧЕНИЕ: част от резюметата НИКОГА не са били
// първото изречение — те са писани отделно, като обещание. Съвпадение по
// изречение би обявило всички тях за счупени.
//
// 🪤 И ВТОРО: късото резюме има малко думи, затова един пропуск дава 50%.
// Затова прагът е по БРОЙ несъвпаднали думи, не само по процент.
//
// ПУСКАНЕ: node dev/rezyumeta.js [--spisak]
// ПЪТ НАЗАД: файлът само ЧЕТЕ.
// ═══════════════════════════════════════════════════════════
const fs = require('fs');
const path = require('path');
process.chdir(path.resolve(__dirname, '..'));
const СПИСЪК = process.argv.includes('--spisak');

const СЛУЖЕБНИ = new Set(['това', 'този', 'тази', 'тези', 'което', 'която', 'които', 'когато',
  'какво', 'кога', 'как', 'защо', 'кое', 'кой', 'коя', 'кои', 'колко', 'дали', 'ако', 'или',
  'при', 'без', 'над', 'под', 'след', 'преди', 'през', 'към', 'между', 'няма', 'има', 'има',
  'още', 'най', 'все', 'вече', 'само', 'също', 'много', 'малко', 'едно', 'една', 'един',
  'ето', 'тук', 'там', 'сега', 'после', 'докато', 'защото', 'затова', 'обаче', 'нали',
  'става', 'прави', 'може', 'трябва', 'бъде', 'били', 'беше', 'себе', 'него', 'нея',
  'твоя', 'твоето', 'твоите', 'своя', 'своето', 'нещо', 'неща', 'някои', 'всеки', 'всичко']);

const думи = s => String(s || '').toLowerCase()
  .replace(/<[^>]*>/g, ' ')
  .split(/[^а-яa-z0-9]+/)
  .filter(w => w.length >= 5 && !СЛУЖЕБНИ.has(w));

const корен = w => w.slice(0, Math.max(5, w.length - 2));

const idx = JSON.parse(fs.readFileSync('lib/index.json', 'utf8'));
const тела = {};
for (const f of fs.readdirSync('lib')) {
  if (!f.endsWith('.json') || /BAK|ARCHIVE|PREDI|index/.test(f)) continue;
  const d = JSON.parse(fs.readFileSync('lib/' + f, 'utf8'));
  for (const k in d) тела[k] = String(d[k]).toLowerCase().replace(/<[^>]*>/g, ' ');
}

let прегледани = 0, безТяло = 0;
const съмнителни = [];
for (const x of (idx.items || [])) {
  const т = тела[x.id];
  if (!т) { безТяло++; continue; }
  прегледани++;
  const рд = [...new Set(думи(x.s))];
  const зд = [...new Set(думи(x.t))];
  if (рд.length < 3) continue;                       // твърде късо, за да се съди
  const липсват = рд.filter(w => т.indexOf(корен(w)) < 0);
  const заглЛипсват = зд.filter(w => т.indexOf(корен(w)) < 0);
  const дял = липсват.length / рд.length;
  // праг: поне 3 несъвпаднали думи И над 35% от резюмето
  if (липсват.length >= 3 && дял >= 0.35)
    съмнителни.push({ ид: x.id, t: x.t, s: x.s, липсват, дял, зл: заглЛипсват });
}

съмнителни.sort((a, b) => b.дял - a.дял);
console.log('📄 РЕЗЮМЕТАТА\n');
console.log('  ПРЕГЛЕДАНИ: ' + прегледани + ' от ' + (idx.items || []).length +
            '   (без тяло: ' + безТяло + ')');
console.log('  съмнителни (3+ думи липсват И над 35%): ' + съмнителни.length + '\n');

if (!съмнителни.length) { console.log('  ✅ всяко резюме се покрива от тялото си'); process.exit(0); }

console.log('  ид                     дял   липсващи думи');
съмнителни.slice(0, СПИСЪК ? 999 : 25).forEach(x => {
  console.log('  ' + x.ид.padEnd(22) + String(Math.round(x.дял * 100) + '%').padStart(4) + '   ' +
    x.липсват.slice(0, 6).join(', '));
  if (СПИСЪК) {
    console.log('     T: ' + String(x.t).slice(0, 78));
    console.log('     S: ' + String(x.s).slice(0, 120));
    if (x.зл.length) console.log('     ⚠ и в ЗАГЛАВИЕТО липсват: ' + x.зл.join(', '));
    console.log('');
  }
});
if (!СПИСЪК && съмнителни.length > 25) console.log('\n  … още ' + (съмнителни.length - 25) + ' — пусни с --spisak');
console.log('\n  ⚠ Това са КАНДИДАТИ. Резюмето може да преразказва вярно с други думи.');
console.log('     Всяко се отваря на ръка, преди да се пипне.');
