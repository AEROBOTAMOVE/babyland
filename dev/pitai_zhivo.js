// 🎤 ПИТАЙ ЖИВО — всякакви въпроси през ЖИВИЯ ред на вратите
//
// ЗАЩО (15.09.2026): dev/kade_sme_s_vaprosite.js мери само своите 609
//   въпроса. За НОВИ въпроси (от агенти, от майки, от корпус) трябваше уред,
//   който минава през СЪЩАТА присъда — не през BL_MATCH сам: там тревогите
//   липсват, тоест мери се друга система. Присъдата е общият модул
//   dev/prisada_zhivo.js — едно място, без препис.
//
// ПУСКАНЕ: node dev/pitai_zhivo.js <вход.json> [--brema] [--json изход.json]
//   входът е [{ "q": "въпросът на мама", "r": "Стая" }, …]
// ИЗХОД:   по ред за всеки въпрос — присъда · карта · заглавие; накрая броят.
//          С --json пише и пълния резултат (за съдии и за следващи уреди).
// САМОПРОВЕРКА: два въпроса с известен отговор; сгреши ли — изход 2.
// ПЪТ НАЗАД: само ЧЕТЕ (с --json пише само посочения файл).
// ═══════════════════════════════════════════════════════════════════════
const fs = require('fs');
const path = require('path');
process.chdir(path.resolve(__dirname, '..'));

const арг = process.argv.slice(2);
const iJ = арг.indexOf('--json');
const ИЗХОД = iJ > -1 ? арг[iJ + 1] : null;
// ⚠️ без --json iJ е -1 и „iJ + 1" е 0 — първият аргумент се изключваше сам
const ВХОД = арг.find((a, i) => /\.json$/.test(a) && !(iJ > -1 && i === iJ + 1));
if (!ВХОД || !fs.existsSync(ВХОД)) { console.log('ПУСКАНЕ: node dev/pitai_zhivo.js <вход.json> [--brema] [--json изход.json]'); process.exit(2); }

const { направи } = require('./prisada_zhivo.js');
let м;
try { м = направи({ чака: арг.includes('--brema') }); } catch (e) { console.log('🔴 ' + e.message); process.exit(2); }
const { W, присъда } = м;
const KB = W.BL_KB || W.KB;
const поId = new Map((KB.entries || []).map(e => [e.id, e]));

// самопроверка: уред, който не познава известния отговор, не мери нищо
const проби = [
  ['бебето не диша', 'Моето бебе', p => p.вид === 'тревога'],
  ['с мъжа ми само се караме откакто родих', 'Жената в мен', p => p.как === 'pt-karame-se-poveche'],
];
for (const [t, с, ок] of проби) {
  if (!ок(присъда(t, с))) { console.log('🔴 СЛЯП: „' + t + '" не дава известния отговор'); process.exit(2); }
}

const чист = s => String(s || '').replace(/<[^>]+>/g, '').replace(/\s+/g, ' ').trim();
const въпроси = JSON.parse(fs.readFileSync(ВХОД, 'utf8'));
const бр = { тревога: 0, вярна: 0, пита: 0, врата: 0, тишина: 0 };
const резултати = [];
for (const x of въпроси) {
  const t = x.q || x.t || x.v;
  if (!t) continue;
  const стая = x.r || x.стая || null;
  const p = присъда(t, стая);
  бр[p.вид] = (бр[p.вид] || 0) + 1;
  const e = p.как ? поId.get(p.как) : null;
  const р = { q: t, стая, вид: p.вид, как: p.как || null, към: p.стая || null,
    заглавие: e ? чист(e.title || e.t) : '', текст: e ? чист(e.core || e.text).slice(0, 260) : '' };
  if (x.очаквай) р.очаквай = x.очаквай;
  резултати.push(р);
  const знак = { тревога: '🚨', вярна: '✅', пита: '❓', врата: '🚪', тишина: '🔇' }[p.вид] || '?';
  console.log(знак + ' [' + (стая || '—') + '] ' + t);
  console.log('      → ' + (e ? e.id + ' [' + e.room + '] „' + р.заглавие + '"' : (p.как || p.вид)));
}
const общо = резултати.length;
console.log('');
console.log('📊 ' + общо + ' въпроса · 🚨 ' + бр.тревога + ' · ✅ ' + бр.вярна + ' · ❓ ' + бр.пита + ' · 🚪 ' + бр.врата + ' · 🔇 ' + бр.тишина);
if (ИЗХОД) { fs.writeFileSync(ИЗХОД, JSON.stringify(резултати, null, 1)); console.log('   → ' + ИЗХОД); }
