// ═══ ОБИКОЛКАТА ═══
let паднали = 0;
const провали = [];
for (const [т, с, чакам] of ВЪПРОСИ) {
  const г = питай(т, с);
  if (г !== чакам) { паднали++; провали.push({ т, с, чакам, г }); }
}
console.log('   въпроси на майчин език : ' + ВЪПРОСИ.length);
console.log('   ' + (паднали ? '🔴' : '✅') + ' паднали                : ' + паднали);
if (провали.length) {
  console.log('');
  for (const п of провали) console.log('      🔴 „' + п.т.padEnd(38) + '"  чакам ' + п.чакам.padEnd(22) + ' получих ' + п.г);
}
console.log('');

// ═══ И ФЛАГОВИЯТ ПЪТ ═══
let флагПаднали = 0;
for (const [т, вид] of ПРЕЗ_ФЛАГ) {
  const ф = майчин(т);
  if (ф !== вид) { флагПаднали++; console.log('      🔴 „' + т + '"  чакам флаг ' + вид + ' получих „' + ф + '"'); }
}
// ═══ ДВИЖЕНИЯТА: ДВЕТЕ ВРАТИ, В ДВЕТЕ ПОСОКИ ═══
const бременФлаг = т => { try { return !!W.BL_PREGFLAG(т, 'Бременност') || !!W.BL_REDFLAG(т); } catch (e) { return false; } };
let движПаднали = 0;
for (const т of ДВИЖЕНИЯТА_СПРЯХА) {
  const к = питай(т, 'Бременност'), ф = бременФлаг(т);
  if (к !== 'nb-dvizheniy-tvoyata') { движПаднали++; console.log('      🔴 „' + т + '" → карта ' + к + ' (чакам nb-dvizheniy-tvoyata)'); }
  if (!ф) { движПаднали++; console.log('      🔴 „' + т + '" НЕ вдига флаг — а това е втората врата'); }
}
for (const т of ОЩЕ_НЕ_СЕ_УСЕЩА) {
  if (бременФлаг(т)) { движПаднали++; console.log('      🔴 ФАЛШИВА СИРЕНА при ранна бременност: „' + т + '"'); }
  const к = питай(т, 'Бременност');
  if (к === 'nb-dvizheniy-tvoyata') { движПаднали++; console.log('      🔴 „' + т + '" отива при спешната карта, а е за ПЪРВОТО раздвижване'); }
}

// ═══ СПЕШНИТЕ ФОРМУЛИРОВКИ ═══
let спешниПаднали = 0;
for (const т of ЧЕРВЕНИ_ФОРМУЛИРОВКИ) if (!червен(т)) { спешниПаднали++; console.log('      🔴 НЕ вдига тревога: „' + т + '"'); }
let фалшиви = 0;
for (const т of НЕВИННИ) if (червен(т)) { фалшиви++; console.log('      🔴 ФАЛШИВА тревога: „' + т + '"'); }
console.log('   спешни формулировки    : ' + ЧЕРВЕНИ_ФОРМУЛИРОВКИ.length + '   ' + (спешниПаднали ? '🔴 мълчат ' + спешниПаднали : '✅ всички вдигат'));
console.log('   невинни (без тревога)  : ' + НЕВИННИ.length + '   ' + (фалшиви ? '🔴 фалшиви ' + фалшиви : '✅ всички мълчат'));
console.log('   през ФЛАГ (не през карта): ' + ПРЕЗ_ФЛАГ.length + '   ' + (флагПаднали ? '🔴 паднали ' + флагПаднали : '✅ всички държат'));
console.log('');
console.log('   движения: спрели/още не (двете врати): ' + (ДВИЖЕНИЯТА_СПРЯХА.length + ОЩЕ_НЕ_СЕ_УСЕЩА.length) +
  '   ' + (движПаднали ? '🔴 паднали ' + движПаднали : '✅ и в двете посоки'));
console.log('');
if (!паднали && !флагПаднали && !спешниПаднали && !фалшиви && !движПаднали) console.log('   ✅ обиколката минава изцяло.');
console.log('');
process.exit(паднали + флагПаднали + спешниПаднали + фалшиви ? 1 : 0);
