// ═══════════════════════════════════════════════════════════════════
// 🛰️  ОФЛАЙН — работи ли приложението без мрежа?
//
// sw.js е пипан 35+ пъти и никой не е мерил дали кешът още покрива
// това, което index.html наистина тегли. Този уред мери ТРИ неща:
//
//   1) ЧЕРНИ ДУПКИ — index.html (или css, или lib.js) иска файл,
//      sw.js НЕ го кешира → офлайн майката вижда празно.
//   2) МЪРТВИ АДРЕСИ — sw.js кешира файл, който вече го няма на диска.
//      При cache.addAll това е СМЪРТ: addAll е всичко-или-нищо, един
//      404 проваля ЦЕЛИЯ кеш и приложението остава БЕЗ офлайн изобщо.
//   3) ВЕРСИИТЕ — index.html иска `js/helper.js?v=117`, sw.js кешира
//      `js/helper.js` без версия. Дали се намира офлайн зависи ЕДИНСТВЕНО
//      от това дали в fetch-хендлъра има `ignoreSearch: true`.
//      Уредът ЧЕТЕ кода и казва какво прави ТОЗИ sw.js — не какво
//      обикновено се прави.
//
// ЖЕЛЯЗНО: всеки брой се придружава от КОЛКО СА ПРЕГЛЕДАНИ.
//          „0 находки" без брой прегледани значи „0 прегледани".
//
// ПУСКАНЕ:  node dev/oflayn.js
//           node dev/oflayn.js --vsichko   (изброява и зелените)
// ═══════════════════════════════════════════════════════════════════
const fs = require('fs');
const path = require('path');

const КОРЕН = path.resolve(__dirname, '..');
const ВСИЧКО = process.argv.includes('--vsichko');
const ч = (n, ед, мн) => n + ' ' + (n === 1 ? ед : мн);
const чети = f => fs.readFileSync(path.join(КОРЕН, f), 'utf8');
const има = f => fs.existsSync(path.join(КОРЕН, f));

// брояч на прегледаното — иначе „0 находки" е лъжа
const прегледани = { файлове: 0, редове: 0, адреси: 0 };
function преглед(f) {
  const t = чети(f);
  прегледани.файлове++;
  прегледани.редове += t.split('\n').length;
  return t;
}

const ЧЕРВЕНО = [];   // офлайн е счупен
const ЖЪЛТО = [];     // крехко / заслужава око
const ЗЕЛЕНО = [];

// ── 1. Какво кешира sw.js ─────────────────────────────────────────
// --sw <път> позволява да се провери КОПИЕ (за самопроверка на уреда:
// чупим копието нарочно и гледаме дали уредът крещи — проверчик, който
// не може да изкрещи, не е измерил нищо).
const swПът = (() => {
  const i = process.argv.indexOf('--sw');
  return i > -1 && process.argv[i + 1] ? process.argv[i + 1] : 'sw.js';
})();
const swТекст = (() => {
  const п = path.isAbsolute(swПът) ? swПът : path.join(КОРЕН, swПът);
  const t = fs.readFileSync(п, 'utf8');
  прегледани.файлове++; прегледани.редове += t.split('\n').length;
  if (swПът !== 'sw.js') console.log('⚙️  проверявам КОПИЕ: ' + swПът);
  return t;
})();

// ASSETS = [ ... ];  — вадим само низовете, коментарите вътре се игнорират
const блок = swТекст.match(/const\s+ASSETS\s*=\s*\[([\s\S]*?)\n\];/);
if (!блок) { console.log('❌ НЕ НАМЕРИХ ASSETS в sw.js — уредът спира, за да не лъже.'); process.exit(1); }
const безКоментари = блок[1].replace(/\/\/[^\n]*/g, '');
const ASSETS = [...безКоментари.matchAll(/['"]([^'"]+)['"]/g)].map(m => m[1]);
прегледани.адреси += ASSETS.length;

const кешСет = new Set(ASSETS);
// какво реално е налично офлайн при точно съвпадение (без query)
const кешБезQuery = new Set(ASSETS.map(a => a.split('?')[0]));

// ── 2. Как се държи fetch-хендлърът (ЧЕТЕМ кода, не предполагаме) ──
const мачове = [...swТекст.matchAll(/caches\.match\(([^)]*)\)/g)].map(m => m[1].trim());

// 🪤 капан, в който уредът вече падна веднъж: `ignoreSearch` в ЦЕЛИЯ файл
// не значи `ignoreSearch` в НАВИГАЦИОННИЯ клон. Режем двата клона поотделно.
const fetchБлок = (swТекст.split(/addEventListener\('fetch'/)[1] || '');
const навБлок = (fetchБлок.match(/if\s*\(\s*навигация\s*\)\s*\{([\s\S]*?)\n\s{2}\}/) || [, ''])[1];
const статБлок = fetchБлок.slice(fetchБлок.indexOf(навБлок) + навБлок.length);

const навигацияИма = /ignoreSearch:\s*true/.test(навБлок);
const навигацияРезервHTML = /caches\.match\(\s*['"]index\.html['"]\s*\)/.test(навБлок);
// в статичния клон: първият match е ГОЛ (без ignoreSearch) → точен кеш-мис при ?v=
const статиченГол = /caches\.match\(req\)\.then\(hit/.test(статБлок);
const статиченРезерв = /catch\([^)]*\)\s*=>\s*caches\.match\(req,\s*\{\s*ignoreSearch:\s*true\s*\}\)/.test(статБлок)
  || /\.catch\(\(\)\s*=>\s*caches\.match\(req,\s*\{\s*ignoreSearch:\s*true\s*\}\)\)/.test(статБлок);
if (!навБлок) ЖЪЛТО.push('не намерих навигационния клон в sw.js — проверката на навигацията е СЛЯПА');
const addAllВсичкоИлиНищо = /\.addAll\(/.test(swТекст);
const поединично = /addAll/.test(swТекст) === false && /cache\.add\(|c\.add\(/.test(swТекст);
const логваПаднали = /(паднал|провал|липсв|console\.(warn|error))/i.test(swТекст);

// ── 3. Какво index.html НАИСТИНА тегли ────────────────────────────
const html = преглед('index.html');
const искани = new Map();   // адрес-без-query → пълен адрес от html
function запиши(raw, откъде) {
  прегледани.адреси++;
  if (!raw) return;
  if (/^(#|data:|blob:|mailto:|tel:|https?:|\/\/)/.test(raw)) return;  // външно/фрагмент
  const гол = raw.split('?')[0].replace(/^\.\//, '');
  if (!гол || гол === '.') return;
  if (!искани.has(гол)) искани.set(гол, { пълен: raw, откъде: new Set() });
  искани.get(гол).откъде.add(откъде);
}
for (const m of html.matchAll(/<script[^>]*\ssrc=["']([^"']+)["']/g)) запиши(m[1], 'index.html script');
for (const m of html.matchAll(/<link[^>]*\shref=["']([^"']+)["']/g)) запиши(m[1], 'index.html link');
for (const m of html.matchAll(/<img[^>]*\ssrc=["']([^"']+)["']/g)) запиши(m[1], 'index.html img');
for (const m of html.matchAll(/url\((["']?)([^"')]+)\1\)/g)) запиши(m[2], 'index.html inline css');

// ── 4. Какво css-ите теглят на свой ред (шрифтове, картинки) ──────
const cssФайлове = [...искани.keys()].filter(f => f.endsWith('.css'));
for (const c of cssФайлове) {
  if (!има(c)) continue;
  const т = преглед(c);
  const база = path.posix.dirname(c);
  for (const m of т.matchAll(/url\((["']?)([^"')]+)\1\)/g)) {
    const r = m[2];
    прегледани.адреси++;
    if (/^(#|data:|https?:|\/\/)/.test(r)) continue;
    const абс = path.posix.normalize(path.posix.join(база, r));
    if (!искани.has(абс)) искани.set(абс, { пълен: абс, откъде: new Set() });
    искани.get(абс).откъде.add(c);
  }
}

// ── 5. Библиотеката: 791 статии в 14 пакета — офлайн ли са? ───────
const библио = { статии: 0, пакети: new Set(), непокрити: [], LV: null, индексКеширан: false };
if (има('js/lib.js')) {
  const t = преглед('js/lib.js');
  const lv = t.match(/const\s+LV\s*=\s*'([^']+)'/);
  библио.LV = lv ? lv[1] : null;
}
if (има('lib/index.json')) {
  const сурово = преглед('lib/index.json');
  try {
    const d = JSON.parse(сурово);
    const items = d.items || [];
    библио.статии = items.length;
    items.forEach(x => { if (x.f) библио.пакети.add(x.f); });
  } catch (e) { ЖЪЛТО.push('lib/index.json не се чете като JSON: ' + e.message); }
}
библио.индексКеширан = кешБезQuery.has('lib/index.json');
const статииНаПакет = {};
if (има('lib/index.json')) {
  try { (JSON.parse(чети('lib/index.json')).items || []).forEach(x => { статииНаПакет[x.f] = (статииНаПакет[x.f] || 0) + 1; }); } catch (e) {}
}
let статииОфлайн = 0, статииЧернаДупка = 0;
for (const п of библио.пакети) {
  прегледани.адреси++;
  const адрес = 'lib/' + п;
  const вКеша = кешБезQuery.has(адрес);
  const наДиска = има(адрес);
  if (вКеша && наДиска) статииОфлайн += статииНаПакет[п] || 0;
  else {
    статииЧернаДупка += статииНаПакет[п] || 0;
    библио.непокрити.push(адрес + (наДиска ? ' (има го на диска, но НЕ Е в кеша)' : ' (ЛИПСВА и на диска)'));
  }
}

// ── 6. СРАВНЕНИЕТО ────────────────────────────────────────────────
// 6а. Черни дупки: искано от страницата, некеширано от sw.js
const черниДупки = [];
for (const [гол, инфо] of искани) {
  if (!кешБезQuery.has(гол)) черниДупки.push({ гол, ...инфо });
  else ЗЕЛЕНО.push(гол);
}

// 6б. Мъртви адреси: в sw.js, но не на диска → addAll гърми, кешът е НУЛА
const мъртви = [];
for (const a of ASSETS) {
  const гол = a.split('?')[0];
  if (гол === '.' || гол === './' || гол === '') continue;  // директорията
  if (!има(гол)) мъртви.push(a);
}

// 6в. Излишни: кеширани, но никой не ги иска (не са фатални, само тежест)
const излишни = ASSETS.filter(a => {
  const г = a.split('?')[0];
  if (г === '.' || г === 'index.html' || г === 'manifest.webmanifest') return false;
  if (г.startsWith('lib/')) return false;
  if (г.startsWith('icons/') || г.startsWith('img/')) return false;
  return !искани.has(г);
});

// 6г. Версиите: колко искани адреса носят ?v= а кешът ги пази без версия
const сВерсия = [...искани.entries()].filter(([, i]) => i.пълен.includes('?v='));

// ── ДОКЛАД ────────────────────────────────────────────────────────
function l(s) { console.log(s); }
l('═══════════════════════════════════════════════════════════');
l('🛰️  ОФЛАЙН ПРОВЕРКА — Baby Land');
l('═══════════════════════════════════════════════════════════');

l('');
l('📖 ПРЕГЛЕДАНИ: ' + ч(прегледани.файлове, 'файл', 'файла') +
  ' · ' + ч(прегледани.редове, 'ред', 'реда') +
  ' · ' + ч(прегледани.адреси, 'адрес', 'адреса') + ' проверени');
l('   (sw.js, index.html, ' + ч(cssФайлове.length, 'css файл', 'css файла') + ', js/lib.js, lib/index.json)');
l('');
l('📦 КЕШИРА: ' + ч(ASSETS.length, 'адрес', 'адреса') + ' в ASSETS  ·  кеш „' +
  (swТекст.match(/const\s+CACHE\s*=\s*'([^']+)'/) || [, '?'])[1] + '"');
l('🌐 ИСКА:   ' + ч(искани.size, 'адрес', 'адреса') + ' от index.html + css');
l('');

// --- версии ---
l('── ВЕРСИИТЕ (?v=) ─────────────────────────────────────────');
l('   ' + ч(сВерсия.length, 'адрес носи', 'адреса носят') + ' ?v= в index.html.');
l('   Кешът ги пази БЕЗ версия (' + ASSETS.filter(a => a.includes('?')).length + ' от ' + ASSETS.length + ' адреса в ASSETS имат query).');
l('   Какво прави ТОЗИ sw.js:');
l('     · статичен клон, 1-ви опит: ' + (статиченГол
  ? 'caches.match(req) — ГОЛ, без ignoreSearch → ?v=N е ТОЧЕН КЕШ-МИС'
  : 'НЕ разпознах формата — виж ръчно'));
l('     · при мис → fetch(req); офлайн fetch пада → catch');
l('     · catch: ' + (статиченРезерв
  ? 'caches.match(req, {ignoreSearch:true}) → НАМИРА кешираното без версия ✅'
  : '❌ НЯМА ignoreSearch резерв → всеки ?v= е ЧЕРНА ДУПКА офлайн'));
l('     · навигация (index.html): ' + (навигацияИма
  ? 'мрежа-първо, офлайн → ignoreSearch ✅'
  : '❌ БЕЗ ignoreSearch в навигационния клон — „/?go=feed" няма да се намери')
  + (навигацияРезервHTML ? ' + краен резерв index.html ✅' : ' · ❌ без краен резерв index.html'));
l('   ИЗВОД: ' + (статиченРезерв && навигацияИма
  ? 'версиите се намират офлайн — но по ВТОРИЯ опит, след като fetch падне.'
  : 'ВЕРСИИТЕ НЕ СЕ НАМИРАТ ОФЛАЙН.'));
l('   (' + ч(мачове.length, 'извикване', 'извиквания') + ' на caches.match в sw.js, прегледани всички)');
l('');

// --- инсталация ---
l('── ИНСТАЛАЦИЯТА ───────────────────────────────────────────');
if (addAllВсичкоИлиНищо) {
  l('   ⚠️  cache.addAll(ASSETS) — ВСИЧКО ИЛИ НИЩО.');
  l('       Един липсващ адрес от ' + ASSETS.length + ' проваля ЦЕЛИЯ кеш →');
  l('       приложението остава БЕЗ офлайн изобщо, мълчаливо.');
} else if (поединично) {
  l('   ✅ поединично кеширане — един липсващ адрес не сваля останалите.');
  l('      Логва ли падналите: ' + (логваПаднали ? 'ДА ✅' : '❌ НЕ — тихо преглъщане!'));
} else {
  l('   ❓ не разпознах стратегията на install — виж ръчно.');
}
l('');

// --- черни дупки ---
l('── ЧЕРНИ ДУПКИ (страницата иска, кешът няма) ──────────────');
l('   Прегледани ' + ч(искани.size, 'искан адрес', 'искани адреса') + '. Находки: ' + черниДупки.length);
if (черниДупки.length === 0) l('   ✅ нула — всичко искано е в кеша.');
черниДупки.forEach(д => l('   ❌ ' + д.гол + '   ← ' + [...д.откъде].join(', ') +
  (има(д.гол) ? '' : '   (и НЯМА такъв файл на диска!)')));
l('');

// --- мъртви адреси ---
l('── МЪРТВИ АДРЕСИ (кешът иска, дискът няма) ────────────────');
l('   Прегледани ' + ч(ASSETS.length, 'кеширан адрес', 'кеширани адреса') + '. Находки: ' + мъртви.length);
if (мъртви.length === 0) l('   ✅ нула — всеки адрес в ASSETS съществува на диска.');
мъртви.forEach(a => l('   💀 ' + a + '   → ' + (addAllВсичкоИлиНищо
  ? 'СВАЛЯ ЦЕЛИЯ КЕШ (addAll)' : 'пропуска се, останалите оцеляват')));
l('');

// --- библиотеката ---
l('── БИБЛИОТЕКАТА ОФЛАЙН ────────────────────────────────────');
l('   Статии в lib/index.json: ' + библио.статии + ' в ' + ч(библио.пакети.size, 'пакет', 'пакета'));
l('   lib/index.json в кеша: ' + (библио.индексКеширан ? 'ДА ✅' : 'НЕ ❌ (без него търсачката е сляпа офлайн)'));
l('   Пакети в кеша: ' + (библио.пакети.size - библио.непокрити.length) + '/' + библио.пакети.size);
l('   Достижими офлайн: ' + статииОфлайн + ' статии.  Черна дупка: ' + статииЧернаДупка + ' статии.');
l('   lib.js тегли с ?v=' + библио.LV + ' → офлайн разчита ИЗЦЯЛО на ignoreSearch резерва: ' +
  (статиченРезерв ? 'има го ✅' : 'НЯМА ГО ❌'));
библио.непокрити.forEach(п => l('   ❌ ' + п));
if (!библио.непокрити.length) l('   ✅ всеки пакет, който index.json сочи, е в кеша.');
l('');

// --- излишни ---
l('── ИЗЛИШНИ В КЕША (никой не ги иска) ──────────────────────');
l('   Находки: ' + излишни.length + ' от ' + ASSETS.length + ' прегледани.');
излишни.forEach(a => l('   🧹 ' + a + (има(a.split('?')[0]) ? ' (файлът го има, но index.html не го зарежда)' : '')));
if (!излишни.length) l('   ✅ нула.');
l('');

if (ВСИЧКО) {
  l('── ПОКРИТИ (зелени) ───────────────────────────────────────');
  ЗЕЛЕНО.sort().forEach(z => l('   ✅ ' + z));
  l('');
}

// --- равносметка ---
const червени = черниДупки.length + мъртви.length + библио.непокрити.length +
  (статиченРезерв ? 0 : 1) + (навигацияИма ? 0 : 1) + (навигацияРезервHTML ? 0 : 1) +
  (библио.индексКеширан ? 0 : 1);
ЖЪЛТО.forEach(ж => l('🟡 ' + ж));
if (статииЧернаДупка) l('📚 ' + статииЧернаДупка + ' статии няма да се отворят офлайн.');
l('═══════════════════════════════════════════════════════════');
l(червени === 0
  ? '🟢 ЧИСТО — ' + прегледани.файлове + ' файла, ' + прегледани.адреси + ' адреса прегледани, 0 червени.'
  : '🔴 ' + червени + ' ЧЕРВЕНИ от ' + прегледани.адреси + ' прегледани адреса.');
if (addAllВсичкоИлиНищо) l('⚠️  addAll остава крехък дори при 0 находки: следващият изтрит файл сваля офлайна.');
l('═══════════════════════════════════════════════════════════');
process.exitCode = червени === 0 ? 0 : 1;
