const { zaredi } = require('./pyasachnik.js');
const W = zaredi(null);

function кой(изр, стая) {
  const из = [];
  try { if (W.BL_REDFLAG && W.BL_REDFLAG(изр)) из.push('червен'); } catch (e) {}
  try { const m = W.BL_MOTHERFLAG && W.BL_MOTHERFLAG(изр); if (m) из.push('майка:' + m); } catch (e) {}
  try { if (W.BL_PREGFLAG && W.BL_PREGFLAG(изр, стая || 'Бременност')) из.push('бременност'); } catch (e) {}
  return из.length ? из.join(' + ') : null;
}

const ТРЯБВА = [
  // самоубийство и самонараняване
  'ще се убия', 'искам да се убия', 'ще се обеся', 'мисля да си резна вените',
  'режа се когато никой не гледа', 'удрям си главата в стената',
  'омръзна ми да живея', 'писна ми да живея', 'по-добре мъртва отколкото така',
  'животът ми няма смисъл',
  // насилие в дома
  'мъжът ми ме преби', 'преби ме', 'изнасили ме', 'мъжът ми ме изнасили',
  'насилва ме', 'мъжът ми ме ритна в корема',
  // кръвоизлив
  'лее се кръв и не спира', 'шурти ми кръв от вчера', 'бликна ми кръв изведнъж',
  'изтичам от кръв',
  // бременност
  'потече ми кръв', 'тръгна ми кръв', 'имам кръвотечение',
  // бебето
  'бебето гори а е на две седмици', 'пари като жар',
  // и глаголът, от който тръгна всичко
  'не изпитвам нищо към бебето'
];

const НЕ_ТРЯБВА = [
  'не изпитвам вина', 'не изпитвам болка при кърмене', 'не изпитвам нужда от помощ',
  'бебето спи спокойно', 'ака нормално и е весело', 'нямам връзка с интернет',
  'мъжът ми много помага', 'кръвната ми картина е добра', 'режа зеленчуци за пюре',
  'гори лампата в коридора', 'парите не стигат до заплата', 'искам да живея пълноценно',
  'животът ми има смисъл сега', 'не издържам на този шум от съседите',
  'спрях да кървя преди седмица', 'бие камбаната на църквата'
];

let паднали = 0;
console.log('');
console.log('🚨 НАЙ-ТЕЖКИТЕ — трябва да ВДИГАТ');
for (const и of ТРЯБВА) {
  const р = кой(и, и.indexOf("кръв")>=0||и.indexOf("кървя")>=0?"Бременност":"Здраве и SOS");
  if (!р) { паднали++; console.log('    🔴 МЪЛЧИ  „' + и + '"'); }
  else console.log('    ✅ ' + String(р).slice(0,22).padEnd(24) + ' „' + и + '"');
}
console.log('');
console.log('🕊️ НЕВИННИТЕ — трябва да МЪЛЧАТ');
for (const и of НЕ_ТРЯБВА) {
  const р = кой(и, и.indexOf("кървя")>=0?"Бременност":"Здраве и SOS");
  if (р) { паднали++; console.log('    🔴 ВДИГА ' + р + '  „' + и + '"'); }
  else console.log('    ✅ мълчи        „' + и + '"');
}
console.log('');
console.log('  ПРЕГЛЕДАНИ: ' + (ТРЯБВА.length + НЕ_ТРЯБВА.length) + ' изречения  ·  ' +
            (паднали ? '🔴 ПАДНАЛИ: ' + паднали : '✅ и двете посоки държат'));
console.log('');
process.exit(паднали ? 1 : 0);
