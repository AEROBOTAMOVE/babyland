// ── изразите ───────────────────────────────────────────────────────────
// 🪤 ТРЕТИЯТ КАПАН (платен в тази сесия): АТРИБУТНАТА кавичка.
//    index.html:1319  Стая „<span id="roTitle"></span>“   е НАПИСАНА ПРАВИЛНО,
//    но първата версия хвана кавичката на id=" и я обяви за ЧЕРВЕНА.
//    Затова < и > спират обхвата: щом между „ и кавичката има таг, това не е
//    затваряща кавичка, а атрибут. Цената: пропускаме дефект вътре в таг.
//    Приемам я — фалшивата тревога е по-скъпа.
//
// .json : низът е "…", вътрешната кавичка е \" → ДЕФЕКТ е \" след „
//         в обхвата пускаме законните escape-и (\n \t \\ \/ \uXXXX), но НЕ \"
const RE_JSON = new RegExp(D + '((?:[^' + D + C + '"<>\\\\\\n]|\\\\[nrtbf\\\\/u]){1,400}?)\\\\"', 'g');
// .js   : низът е '…' → ДЕФЕКТ е ГОЛА " след „ (апострофът спира обхвата,
//         за да не прескочим края на низа). Хваща и \" за двойно-кавичкови низове.
const RE_JS   = new RegExp(D + '([^' + D + C + '\'"<>\\\\\\n]{1,400})\\\\?"', 'g');

function изразЗа(п) {
  if (п.endsWith('.json')) return RE_JSON;
  return RE_JS;   // .js .css .html .webmanifest
}

// правилно затворена двойка — знаменателят „колко изобщо има"
const RE_DOBRE = new RegExp(D + '[^' + D + C + '\\n]{0,400}?' + C, 'g');

// ── кои файлове: само това, което майката ТЕГЛИ ─────────────────────────
function живиФайлове() {
  const сп = new Set(['index.html', 'sw.js']);
  const idx = fs.readFileSync(path.join(КОРЕН, 'index.html'), 'utf8');
  const re = /(?:src|href)="([^"]+\.(?:js|css))(?:\?[^"]*)?"/g;
  let m; while ((m = re.exec(idx))) сп.add(m[1]);
  for (const f of fs.readdirSync(path.join(КОРЕН, 'lib'))) {
    if (f.endsWith('.json') && !/BAK|ARCHIVE|PREDI/.test(f)) сп.add('lib/' + f);
  }
  return [...сп].filter(f => fs.existsSync(path.join(КОРЕН, f))).sort();
}

// ── коментар ли е редът ─────────────────────────────────────────────────
// ВАЖНО (платено веднъж в тази сесия): първата версия познаваше само // и /* */
// в .js и обяви 48 реда в css/*.css за ЧЕРВЕНИ — а всичките бяха в /* */.
// Фалшивата тревога е също толкова опасна: пазач, който вика напразно,
// го изключват, и следващият истински дефект минава.
//   .js   → // и /* */
//   .css  → /* */          (в CSS няма //)
//   .html → <!-- -->
//   .json → няма коментари → всичко е ДАННИ
function картаНаКоментарите(редове, вид) {
  const карта = new Array(редове.length).fill(false);
  if (вид === 'json') return карта;
  const блокОт = (вид === 'html') ? '<!--' : '/*';
  const блокДо = (вид === 'html') ? '-->'  : '*/';
  let вБлок = false;
  for (let i = 0; i < редове.length; i++) {
    const л = редове[i], т = л.trim();
    if (вБлок) { карта[i] = true; if (л.indexOf(блокДо) >= 0) вБлок = false; continue; }
    if (вид === 'js' && т.startsWith('//')) { карта[i] = true; continue; }
    const b = л.indexOf(блокОт), q = л.indexOf(D);
    if (b >= 0) {
      const край = л.indexOf(блокДо, b + блокОт.length);
      if (край < 0) вБлок = true;
      // находката е в коментара, ако „ стои след отварящата и преди затварящата
      if (q > b && (край < 0 || q < край)) карта[i] = true;
      if (карта[i]) continue;
    }
    if (вид === 'js') {
      const p = л.indexOf('//');
      if (p >= 0 && q >= 0 && p < q) карта[i] = true;
    }
  }
  return карта;
}
function видЗа(п) {
  if (п.endsWith('.json')) return 'json';
  if (п.endsWith('.js'))   return 'js';
  if (п.endsWith('.css'))  return 'css';
  return 'html';
}

// ── ядрото: сканира ЕДИН текст ──────────────────────────────────────────
function сканирай(път, текст) {
  const re = изразЗа(път);
  const редове = текст.split('\n');
  const карта = картаНаКоментарите(редове, видЗа(път));
  const из = { файл: път, редове: редове.length, байта: Buffer.byteLength(текст),
               червени: [], оранжеви: [], добри: 0 };
  for (let i = 0; i < редове.length; i++) {
    const л = редове[i];
    if (л.indexOf(D) < 0) continue;
    re.lastIndex = 0;
    let m;
    while ((m = re.exec(л)) !== null) {
      const запис = { ред: i + 1, текст: (D + m[1] + '"').slice(0, 90) };
      if (карта[i]) из.оранжеви.push(запис); else из.червени.push(запис);
      if (m.index === re.lastIndex) re.lastIndex++;
    }
    RE_DOBRE.lastIndex = 0;
    const д = л.match(RE_DOBRE);
    if (д) из.добри += д.length;
  }
  return из;
}

