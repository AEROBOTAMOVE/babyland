for (const ф of файлове) {
  const текст = fs.readFileSync(ЕДИНФАЙЛ ? ф : path.join(КОРЕН, ф), 'utf8');
  const r = сканирай(ф, текст);
  фБр++; рБр += r.редове; бБр += r.байта; ДОБРИ += r.добри;
  ЧЕРВЕНИ += r.червени.length; ОРАНЖЕВИ += r.оранжеви.length;
  if (r.червени.length || r.оранжеви.length) поФайл.push(r);
  if (ТИПО) {
    const t = типография(ф, текст);
    t.хомоглиф.forEach(h => tИмаМясто(h, ф));
    тип.тире += t.тире; тип.дваИнтервала += t.дваИнтервала;
    тип.nbsp += t.nbsp; тип.правиДвойки += t.правиДвойки;
    тип.прозаKB += t.прозаKB; if (t.прозаKB) тип.прозаФ++;
  }
}
function tИмаМясто(h, ф) { if (тип.хомоглиф.length < 5000) тип.хомоглиф.push(ф + ':' + h.ред + '  ' + h.дума); }

console.log('„ ПАЗАЧ НА КАВИЧКИТЕ\n');
console.log('  ПРЕГЛЕДАНИ : ' + фБр + ' файла · ' + рБр + ' реда · ' +
            Math.round(бБр / 1024) + ' KB · ' + (Date.now() - т0) + ' мс');
console.log('  правилни „…“ двойки: ' + ДОБРИ + '   ← знаменателят');
console.log('');
console.log('  🔴 ЧЕРВЕНИ (в ДАННИ, майката ги вижда) : ' + ЧЕРВЕНИ);
console.log('  🟠 ОРАНЖЕВИ (в коментар)               : ' + ОРАНЖЕВИ);

for (const r of поФайл) {
  console.log('\n  ' + r.файл + '   червени ' + r.червени.length + ' · оранжеви ' + r.оранжеви.length);
  const показ = ВСИЧКО ? r.червени.concat(r.оранжеви) : r.червени.slice(0, 5);
  for (const з of показ) console.log('      ред ' + String(з.ред).padStart(5) + ':  ' + з.текст);
  if (!ВСИЧКО && r.червени.length > 5) console.log('      … още ' + (r.червени.length - 5) + ' (--vsichko)');
}

if (ТИПО) {
  console.log('\n─── ДРУГИ ТИПОГРАФСКИ (само броене, НЕ блокират) ───');
  console.log('  прегледана ПРОЗА: ' + тип.прозаФ + ' json файла · ' + тип.прозаKB + ' KB');
  console.log('  латиница в кирилска дума : ' + тип.хомоглиф.length +
              '  ← КАНДИДАТИ (имена на променливи също влизат), прочети ги');
  тип.хомоглиф.slice(0, 12).forEach(x => console.log('      ' + x));
  console.log('  " - " вместо тире  —     : ' + тип.тире);
  console.log('  прави \\"кавички\\" вм. „…“ : ' + тип.правиДвойки);
  console.log('  двоен интервал в текст   : ' + тип.дваИнтервала);
  console.log('  неразделим интервал U+00A0: ' + тип.nbsp);
}

const провал = ЧЕРВЕНИ > 0 || (СТРОГО && ОРАНЖЕВИ > 0);
console.log('\n' + (провал
  ? '🔴 НЕ КАЧВАЙ. Поправи с: node dev/kavichki.js --pishi   после пусни пазача пак.'
  : ОРАНЖЕВИ ? '✅ ДАННИТЕ СА ЧИСТИ (' + ОРАНЖЕВИ + ' в коментари — не блокират)'
             : '✅ ЧИСТО'));
process.exit(провал ? 1 : 0);
