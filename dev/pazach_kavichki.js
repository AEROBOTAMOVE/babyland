// Не ползвам \b — той е САМО латиница и цифри и МЪЛЧИ над кирилица.
//
// 🪤 ЧЕТВЪРТИЯТ КАПАН, платен в тази сесия: тези мерки върху КОД дават
//    почти само боклук. Първата версия каза 173 „тирета" и 3190 „прави
//    кавички" — а пробите бяха  `мес - п[0]`  (изваждане с кирилски имена)
//    и  `, "цикъл след раждане"`  (масив от ключове в kb.js).
//    Затова ПРОЗАТА се мери САМО в lib/*.json, където всеки низ е статия.
//    Хомоглифът се мери навсякъде, но се обявява за КАНДИДАТ, не за дефект —
//    целX, медKB, ecБлокове са нарочни имена на променливи, не грешки.
const ХОМОГЛИФИ = 'aceopxyABCEHKMOPTXY';   // латински букви, които изглеждат кирилски
function типография(път, текст) {
  const р = { хомоглиф: [], тире: 0, дваИнтервала: 0, nbsp: 0, правиДвойки: 0, прозаKB: 0 };
  const проза = път.endsWith('.json');   // само там е сигурно, че низът е текст за майката
  if (проза) р.прозаKB = Math.round(Buffer.byteLength(текст) / 1024);
  const редове = текст.split('\n');
  const реДума = /[A-Za-zА-Яа-яЁё]{3,}/g;
  const реКир = /[А-Яа-яЁё]/, реЛат = /[A-Za-z]/;
  for (let i = 0; i < редове.length; i++) {
    const л = редове[i];
    if (!реКир.test(л)) continue;
    реДума.lastIndex = 0;
    let m;
    while ((m = реДума.exec(л)) !== null) {
      const д = m[0];
      if (!реКир.test(д) || !реЛат.test(д)) continue;
      const лат = д.split('').filter(ch => реЛат.test(ch));
      if (лат.length > 3) continue;                                  // истинска смес, не хомоглиф
      if (!лат.every(ch => ХОМОГЛИФИ.indexOf(ch) >= 0)) continue;    // само визуалните близнаци
      if (р.хомоглиф.length < 2000) р.хомоглиф.push({ ред: i + 1, дума: д });
    }
    if (!проза) continue;
    // тире: " - " между български думи (в проза трябва " — ")
    const т = л.match(/[А-Яа-я] - [А-Яа-я]/g); if (т) р.тире += т.length;
    // двоен интервал ВЪТРЕ в изречение (не отстъп): буква + 2 интервала + буква
    const и = л.match(/[А-Яа-я,.!?]  +[А-Яа-я]/g); if (и) р.дваИнтервала += и.length;
    // неразделим интервал
    const н = л.match(/ /g); if (н) р.nbsp += н.length;
    // изцяло ПРАВИ кавички около българска дума: \"дума\" вместо „дума“
    const п = л.match(/\\"[А-Яа-я][^"\n]{0,60}?\\"/g); if (п) р.правиДвойки += п.length;
  }
  return р;
}

