const fs = require('fs');
const path = require('path');
process.chdir(path.resolve(__dirname, '..'));

const РАЗРЕШЕНИ = new Set(['lab.js', 'river.js', 'data.js']);   // виж коментара горе

function прегледай(име, текст) {
  const L = текст.split(/\r?\n/);
  const сурови = [], спазени = [];
  L.forEach((ред, i) => {
    if (/^\s*\/\//.test(ред)) return;               // коментар
    if (ред.indexOf('604800000') < 0) return;
    if (!/Date\.now\(\)|new Date\(/.test(ред)) return;
    (/BL_PREG/.test(ред) ? спазени : сурови).push(име + ':' + (i + 1) + '  ' + ред.trim().slice(0, 92));
  });
  return { сурови, спазени };
}

const файлове = fs.readdirSync('js').filter(f => f.endsWith('.js') && !/ARCHIVE|PREDI/.test(f));
let сурови = [], спазени = [], редове = 0, разрешени = 0;
for (const f of файлове) {
  const т = fs.readFileSync('js/' + f, 'utf8');
  редове += т.split(/\r?\n/).length;
  if (РАЗРЕШЕНИ.has(f)) { if (т.indexOf('604800000') >= 0) разрешени++; continue; }
  const р = прегледай(f, т);
  сурови = сурови.concat(р.сурови);
  спазени = спазени.concat(р.спазени);
}

console.log('🤰 ЕДНА СЕДМИЦА — една сметка за целия проект\n');
console.log('  ПРЕГЛЕДАНИ ФАЙЛОВЕ : ' + файлове.length);
console.log('  ПРЕГЛЕДАНИ РЕДОВЕ  : ' + редове.toLocaleString('bg'));
console.log('  ✅ минават през BL_PREG : ' + спазени.length);
console.log('  ⚪ поименно разрешени    : ' + разрешени + '   (lab.js, river.js, data.js)');
console.log('  ' + (сурови.length ? '🔴' : '✅') + ' СУРОВИ                : ' + сурови.length + '\n');
сурови.forEach(x => console.log('     🔴 ' + x));

// ── САМОПРОВЕРКА в ДВЕТЕ посоки ──
const п = [
  ['  const w = Math.floor((Date.now() - new Date(lmp)) / 604800000);', true, 'суровата сметка'],
  ['  const w = (window.BL_PREG ? BL_PREG.седмица(new Date(lmp)) : Math.floor((Date.now() - new Date(lmp)) / 604800000));',
                                                                        false, 'през BL_PREG с резервен изход'],
  ['  // Math.floor((Date.now() - new Date(lmp)) / 604800000)',          false, 'ред-коментар'],
  ['  const ms = x.w * 604800000;',                                      false, 'умножение, не сметка за седмица']
];
console.log('  САМОПРОВЕРКА (иначе нулата горе не значи нищо):');
let паднала = false;
for (const [ред, очаква, какво] of п) {
  const има = прегледай('проба', ред).сурови.length > 0;
  if (има !== очаква) паднала = true;
  console.log('     ' + (има === очаква ? '✅' : '🔴') + ' ' + (очаква ? 'ХВАЩА  ' : 'ПРОПУСКА') + ' ' + какво);
}
if (паднала) { console.log('\n  🔴 САМОПРОВЕРКАТА ПАДНА.'); process.exit(2); }

if (сурови.length) {
  console.log('\n  ЛЕКЪТ: (window.BL_PREG ? BL_PREG.седмица(<дата>) : <старият израз>)');
  console.log('  BL_PREG брои КАЛЕНДАРНИ дни между две МЕСТНИ полунощи —');
  console.log('  затова часът на деня не може да измести числото.');
}
process.exit(сурови.length ? 1 : 0);
