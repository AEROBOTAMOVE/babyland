// ИЗМЕРЕНИ:
//   · дава ЕДНА СЕДМИЦА ПО-МАЛКО всеки седми ден между 00:00 и 02:00
//     (5760 проверени мига → разминаване в 1.6%)
//   · в самия ден на последната менструация, между 00:00 и 02:00, дава −1
// А отделно: „остават N дни" се смяташе с Math.ceil на едни места и
// Math.round на други — измерено разминаване в 50% от миговете. Мама вижда
// 12 дни на един екран и 11 на друг.
//
// Сега има един източник: BL_PREG (js/data.js). Този файл пази да остане един.
