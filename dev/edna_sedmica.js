// 🪤 КОЕ НЕ Е НАРУШЕНИЕ (и защо се проверява поименно):
//   · js/lab.js брои седмицата ОТ ГОДИНАТА (номер на седмица в календара) —
//     съвсем друго нещо, което случайно ползва същото число 604800000.
//   · js/river.js СТРОИ миг от седмица (обратната посока), не чете седмица.
//   · резервният изход след `||` или в тернарен израз е НАРОЧЕН: ако
//     data.js не се зареди, старата сметка пази поведението.
//   Затова за нарушение се брои само СУРОВ израз БЕЗ BL_PREG наблизо.
