#!/usr/bin/perl
# 🩺 ПАЗАЧ НА ЗАМРАЗЕНИТЕ СТАНДАРТИ — Perl-близнак на dev/standarti.py
#
# Защо съществува: на тази машина НЯМА работещ python (проверено 11.08:
# `python -c "print(1)"` връща „Python was not found“). Пазачът беше
# единствената защита срещу отваряне на вратичка в правилата и мълчеше.
# Този файл е СЪЩИТЕ десет правила, дума по дума, само на друг език.
# Ако някой ден python се върне — двата трябва да дават еднакъв брой.
#
# Пускане (от папката babyland):  perl dev/standarti.pl
# Изход: 0 = чисто, 1 = има нарушения.
use strict; use warnings; use utf8;
use JSON::PP;
binmode(STDOUT, ':encoding(UTF-8)');

use Cwd qw(abs_path);
my $корен = abs_path($0); $корен =~ s![/\\][^/\\]+$!!; $корен =~ s![/\\]dev$!!;
chdir($корен) or die "не мога да вляза в $корен";

my $idxTxt = слурп('lib/index.json');
my $idx = JSON::PP->new->utf8(0)->decode($idxTxt);
my %заглавие; $заглавие{$_->{id}} = $_->{t} for @{ $idx->{items} };
my %стая;     $стая{$_->{id}}     = $_->{r} for @{ $idx->{items} };

my %тела;
for my $f (glob('lib/*.json')) {
  next if $f =~ /index\.json$/ or $f =~ /\.BAK|ARCHIVE/;
  my $d = eval { JSON::PP->new->utf8(0)->decode(слурп($f)) };
  next unless ref $d eq 'HASH';
  while (my ($k, $v) = each %$d) { $тела{$k} = [$f, $v] if !ref $v; }
}
my $kb = слурп('js/kb.js');

my @нарушения;
sub сигнал { push @нарушения, [@_]; }
sub слурп { my $п = shift; open(my $fh, '<:encoding(UTF-8)', $п) or die "няма $п"; local $/; my $t = <$fh>; close $fh; return $t; }
sub около { my ($t, $s, $e, $л, $д) = @_; my $a = $s - $л; $a = 0 if $a < 0; return substr($t, $a, ($e + $д) - $a); }

while (my ($i, $р) = each %тела) {
  my ($f, $t) = @$р;

  # 1. ВОДА ПРЕДИ 6 МЕСЕЦА — без вратички
  while ($t =~ /(^|[^а-я])(вода|водичк[а-я]+|чай|чайче)([^а-я][^.!?\n]{0,90})(при жега|в горещи|през лятото|на формула|при адаптирано|без педиатър|ако лекар)/gi) {
    my $ок = около($t, $-[0], $+[0], 120, 120);
    next if $ок =~ /под 6 месец|преди 6-ия|под шест месец|не преди 6/i;
    сигнал('вода преди 6 м.', $f, $i, substr($&, 0, 88));
  }
  # 2. МЕД ПОД 1 ГОДИНА
  while ($t =~ /(?<![а-я])(мед|медът|меда)(?![а-я])/gi) {
    my ($s, $e) = ($-[0], $+[0]);
    my $ок = около($t, $s, $e, 600, 600);
    next if $ок =~ /под (1|една) годин|до (1|една) годин|преди 12 месец|не преди (1|12)|първата годин|под годинк|под годин|преди годинк|първия рожден|след годинката|ботулиз/i;
    my $преди = около($t, $s, $s, 90, 0);
    # 🪤 18.08: тук се искаше „не" НЕПОСРЕДСТВЕНО до глагола, затова
    #   „Сложи ракия на венците." Никога. НЕ СЕ МАЖЕ И С МЕД."
    #   се броеше за нарушение — а това е точно ПРАВИЛНОТО предупреждение.
    #   Пазач, който вдига тревога срещу верен текст, учи да го пренебрегват.
    #   Сега се допускат и възвратните форми („не се маже/дава/слага"),
    #   „никога" и „не бива/не трябва".
    next if $преди =~ /\*\*Не\*\*|никога|не\s+(се\s+)?(слагай|слага|мажи|маже|давай|дава|използвай|използва|търкай|търка|препоръчва|бива|трябва)/i;
    сигнал('мед под 1 г.', $f, $i, substr($ок, 100, 110));
  }
  # 3. БЕЗОПАСЕН СЪН — описва средата → трябва и позицията
  my @описва = ('твърд(ия)? матрак', 'празно легло', 'без свободни възглавниц', 'позиционер', 'бебешко гнездо', 'обиколниц', 'безопасн[а-я]+ сън');
  my $бр = 0; for my $r (@описва) { $бр++ if $t =~ /$r/i; }
  сигнал('безопасен сън без позиция', $f, $i, substr($заглавие{$i} // '?', 0, 50))
    if $бр >= 2 && $t !~ /по гръб|на гръб|по гърба/i;
  # 4. ЗАДАВЯНЕ — учи „действай“ → трябва и 5 и 5
  if ($t =~ /удари по гърба|гръбни удари|удари между лопатки|притискания|хватк[а-я]+ при задавян|действия(та)? при задавян/i) {
    сигнал('задавяне без броя на хватките', $f, $i, substr($заглавие{$i} // '?', 0, 50))
      unless ($t =~ /5 удара|пет удара/i && $t =~ /5 притискан|пет притискан/i);
  }
  # 5. ДОЗИ — червената линия
  while ($t =~ /\d+[\d,.\s]*\s*(мг|мл|mg|ml)(?![а-яa-z])|\d+\s*капк[аи](?![а-я])|мг на килограм|на килограм тегло|\/kg|на кг телесн/gi) {
    сигнал('ДОЗА', $f, $i, около($t, $-[0], $+[0], 70, 40));
  }
  # 6. ТЕМПЕРАТУРА — прагът е 38.0
  while ($t =~ /(3[5-9][.,]\d)\s*(°|градус|C(?![a-z]))/g) {
    my $ст = $1; $ст =~ s/,/./;
    next unless $ст eq '37.5' || $ст eq '38.5';
    next if около($t, $-[0], $+[0], 300, 200) =~ /ваксин|имунизац|убождан|от кабинета/i;
    сигнал('праг != 38.0 (за око)', $f, $i, около($t, $-[0], $+[0], 80, 60));
  }
  # 7. ПАРА ЗА КРУП
  while ($t =~ /пара[а-я]*/gi) {
    my $ок = около($t, $-[0], $+[0], 160, 160);
    next unless $ок =~ /круп|лаещ[а-я]+ кашлиц|ларингит/i;
    next if $ок =~ /не помага|не се препоръчва|не прави|няма полза|не лекува/i;
    сигнал('пара при круп', $f, $i, substr($ок, 120, 130));
  }
  # 8. РИСКОВИ ХРАНИ, СЪВЕТВАНИ
  while ($t =~ /(сурово?[а-я]* морков[а-я]*|суров морков|цял[а-я]* ядк|цяло грозде|пуканк|твърд[а-я]* бонбон|кренвирш на кръгче|морков на кръгче)/gi) {
    my $ок = около($t, $-[0], $+[0], 220, 220);
    next if $ок =~ /задавян|риск|не се дава|внимавай|опасн|наряз|настърж|не преди/i;
    next unless $ок =~ /пробвай|предложи|дай му|дай ѝ|давай|подходящ[а-я]+ е|може да хрупа|хрупа/i;
    сигнал('рискова храна, съветвана', $f, $i, substr($ок, 180, 120));
  }
  # 9. НАКЛОНЕНА ПОВЪРХНОСТ ЗА СЪН
  while ($t =~ /повдигни (горната част на )?(матрака|постелката|леглото|креватчето)|подложи .{0,20}под матрака|книга под матрака|на наклон|наклонена повърхност/gi) {
    my $ок = около($t, $-[0], $+[0], 260, 260);
    next if $ок =~ /не (се )?повдигай|не подпъхвай|риск|не помага|не се препоръчва|вместо това|не прави|недей|не лекуват|позиционер/i;
    next if $ок =~ /спирачк|количк|стълб|рампа|тротоар/i;
    сигнал('наклонена повърхност за сън', $f, $i, substr($ок, 220, 120));
  }
  # 10. КАФЕТО ПРИ БРЕМЕННОСТ — замразената мярка е ЕДНО
  if (($стая{$i} // '') eq 'Бременност') {
    while ($t =~ /(две|2|три|3|четири|4)\s+(малки\s+)?кафе(та)?(?![а-я])/gi) {
      my $ок = около($t, $-[0], $+[0], 160, 160);
      next if $ок =~ /не повече от|вече (са )?много|прекалено|са много/i;
      сигнал('кафе > 1 на ден (Бременност)', $f, $i, substr($ок, 130, 120));
    }
  }
}
while ($kb =~ /\d+[\d,.\s]*\s*(мг|мл|mg|ml)(?![а-яa-z])|\d+\s*капк[аи](?![а-я])|мг на килограм|на килограм тегло|\/kg|на кг телесн/gi) {
  сигнал('ДОЗА', 'js/kb.js', '-', около($kb, $-[0], $+[0], 70, 40));
}

print '=' x 70, "\n";
printf("ПАЗАЧ НА ЗАМРАЗЕНИТЕ СТАНДАРТИ — %d статии + kb.js\n", scalar keys %тела);
print '=' x 70, "\n";
unless (@нарушения) { print "\nЧИСТО. Нито един стандарт не е нарушен.\n\n"; exit 0; }
my %по;
for my $н (@нарушения) { push @{ $по{$н->[0]} }, $н; }
for my $пр (sort { @{$по{$b}} <=> @{$по{$a}} } keys %по) {
  printf("\n%s — %d\n", uc($пр), scalar @{ $по{$пр} });
  my $n = 0;
  for my $н (@{ $по{$пр} }) {
    last if $n++ >= 12;
    my $о = $н->[3] // ''; $о =~ s/\n/ /g;
    printf("   %-18s %-16s %s\n", $н->[1], $н->[2], substr($о, 0, 86));
  }
  printf("   ... и още %d\n", scalar(@{ $по{$пр} }) - 12) if @{ $по{$пр} } > 12;
}
printf("\nОБЩО: %d\n\n", scalar @нарушения);
exit 1;
