// 🔢 СВЕРКА НА ВЕРСИИТЕ В ДВЕТЕ ПОСОКИ
//
// ЗАЩО: dev/versii_po_sadarjanie.js ВДИГА номерата по съдържание. Но кой
// проверява ВДИГАЧА? Две грешки са възможни и двете са тихи:
//   · файл е ПРОМЕНЕН, а номерът му НЕ е вдигнат → върналата се майка чете
//     СТАРОТО от кеша и всичко днешно е невидимо за нея. Това е по-лошо от
//     да не си качвал: изглежда качено, а не е стигнало.
//   · номер е вдигнат БЕЗ промяна → всички теглят наново без причина.
// Уред, който гледа само едната посока, пропуска половината.
//
// 🪤 БЕЗ РЕГУЛЯРНИ ИЗРАЗИ ЗА ПЪТИЩАТА. Днес два пъти писах такъв уред през
//    bash heredoc и обратните наклонени черти в екранирането бяха ИЗЯДЕНИ →
//    „Invalid regular expression". Тук се търси с indexOf по низ — няма какво
//    да се екранира, значи няма какво да се счупи.
//
// ПУСКАНЕ: node dev/versii_sverka.js [sha]   (по подразбиране HEAD)
// ПЪТ НАЗАД: файлът само ЧЕТЕ. Изтрий го и нищо не се променя.
// ═══════════════════════════════════════════════════════════
const { execSync } = require('child_process');
const fs = require('fs');
const path = require('path');
const КОРЕН = path.resolve(__dirname, '..');
const SHA = process.argv[2] || 'HEAD';

// ── всички „файл?v=номер" от index.html, без регулярен израз ──
function версии(html) {
  const карта = {};
  let i = 0;
  for (;;) {
    const н = html.indexOf('?v=', i);
    if (н < 0) break;
    // назад до кавичката, която отваря адреса
    let а = н;
    while (а > 0 && html[а - 1] !== '"' && html[а - 1] !== "'") а--;
    // напред до затварящата кавичка
    let б = н + 3;
    while (б < html.length && html[б] >= '0' && html[б] <= '9') б++;
    const файл = html.slice(а, н);
    const ном = Number(html.slice(н + 3, б));
    if (файл && !isNaN(ном) && файл.indexOf('http') !== 0) карта[файл] = ном;
    i = б;
  }
  return карта;
}

function откъм(sha, файл) {
  try {
    return execSync('git show ' + sha + ':' + файл, { cwd: КОРЕН, encoding: 'buffer', maxBuffer: 128 * 1024 * 1024 }).toString('utf8');
  } catch (e) { return null; }
}

// 🔴 ПЪРВАТА ВЕРСИЯ НА ТОЗИ УРЕД ОБЯВИ 10+ НЕПИПНАТИ ФАЙЛА ЗА ПРОМЕНЕНИ.
//    Причината: git пази съдържанието с LF, а на диска в Windows е CRLF
//    (git сам предупреждава при add: „LF will be replaced by CRLF"). Тоест
//    сравнявах окончанията на редовете, не текста, и ВСЕКИ файл излизаше
//    сменен. Ако бях повярвал, щях да „оправям" версии, които са наред, и
//    истинските находки щяха да се удавят в шума.
//    Същият капан е плащан и другаде в проекта: js/kb.js е СМЕСЕН CRLF/LF и
//    търсене с грешното окончание връща −1 МЪЛЧАЛИВО.
const еднакво = (а, б) => {
  if (а == null || б == null) return false;
  const н = т => String(т).split('\r\n').join('\n');
  return н(а) === н(б);
};

const сегаHTML = fs.readFileSync(path.join(КОРЕН, 'index.html'), 'utf8');
const предиHTML = откъм(SHA, 'index.html');
if (!предиHTML) { console.log('🔴 не мога да прочета index.html от ' + SHA + ' — сверката би била лъжа'); process.exit(2); }

const сегаВ = версии(сегаHTML);
const предиВ = версии(предиHTML);

const промененБезНомер = [];
const номерБезПромяна = [];
let прегледани = 0, безСтара = 0;

for (const файл of Object.keys(сегаВ)) {
  const пълен = path.join(КОРЕН, файл);
  if (!fs.existsSync(пълен)) continue;
  прегледани++;
  const сега = fs.readFileSync(пълен, 'utf8');
  const преди = откъм(SHA, файл);
  const сменен = преди !== null && !еднакво(преди, сега);   // 🪤 през еднакво(), не през !==
  const стар = предиВ[файл];
  if (стар === undefined) { безСтара++; continue; }   // нов файл — няма с какво да се сравни
  const вдигнат = сегаВ[файл] > стар;
  if (сменен && !вдигнат) промененБезНомер.push(файл + '   v' + сегаВ[файл] + ' (не мръдна)');
  if (!сменен && вдигнат) номерБезПромяна.push(файл + '   v' + стар + ' → v' + сегаВ[файл]);
}

console.log('');
console.log('🔢 СВЕРКА НА ВЕРСИИТЕ  (срещу ' + SHA + ')');
console.log('');
console.log('  ПРЕГЛЕДАНИ ФАЙЛА : ' + прегледани + (безСтара ? '   (' + безСтара + ' нови, без с какво да се сравнят)' : ''));
console.log('  ' + (промененБезНомер.length ? '🔴' : '✅') + ' ПРОМЕНЕН без вдигнат номер : ' + промененБезНомер.length + '    ← мама чете СТАРОТО от кеша');
промененБезНомер.forEach(x => console.log('       ' + x));
console.log('  ' + (номерБезПромяна.length ? '🟠' : '✅') + ' вдигнат номер БЕЗ промяна   : ' + номерБезПромяна.length + '    ← излишно теглене');
номерБезПромяна.forEach(x => console.log('       ' + x));

