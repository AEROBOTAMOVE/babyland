//   САМО ако мама още не се е представила:
//       var onb = $('onbOverlay');  … if (!онбордингът е минат) …
//   На всяка машина с готов профил екранът се ПРОПУСКА МЪЛЧАЛИВО.
//   Резултат: първият екран, който вижда ВСЯКА майка, е единственият,
//   който никой уред не е мерил. Не е бил подминат — не е бил ВИДЯН.
//
//   Този тест го отваря НАСИЛА и връща паметта както я е заварил.
//
// КАКВО ПАЗИ (това са истинските опасности в този екран):
//   · рождена дата в БЪДЕЩЕТО прави BL_AGE null и цялото приложение се
//     държи, все едно няма бебе
//   · „Още чакам" слага обратно сметнатата ОДР в полето; натиснеш ли после
//     „Момиче", ОЧАКВАНАТА дата се записва като РОЖДЕНА — с едно докосване.
//     Оттам тръгват сгрешени възраст, ваксини и захранване.
//   · очакваната дата отключва цялата бременностна машина през bl_lmp;
//     изхвърли ли се, приложението стои празно пред точно тази майка
//   · „По-късно" трябва да я отпише, а клик на фона — НЕ (случайно докосване
//     не бива да убие поканата завинаги)
//
// ПУСКАНЕ (в конзолата на приложението):
//   var s=document.createElement('script'); s.src='dev/test_vhod.js'; document.body.appendChild(s);
//   await BL_ВХОД.провери()
//
// ⚠ Тестът ПИШЕ в localStorage и го ВРЪЩА накрая. Ако гръмне по средата,
//   викни BL_ВХОД.върни() на ръка.
//
// ПЪТ НАЗАД: файлът не пипа нищо в проекта. НЕ е закачен в index.html.
// ═══════════════════════════════════════════════════════════
(function () {
  'use strict';

  var $ = function (id) { return document.getElementById(id); };
  var КЛЮЧОВЕ = ['bl_baby', 'bl_lmp', 'bl_me', 'bl_preterm', 'bl_onboarded', 'bl_tour_done'];
  var снимка = null;

  function снеми() {
    var с = {};
    КЛЮЧОВЕ.forEach(function (k) { с[k] = localStorage.getItem(k); });
    return с;
  }
  function върни() {
    if (!снимка) return 'няма какво да се връща';
    КЛЮЧОВЕ.forEach(function (k) {
      if (снимка[k] === null) localStorage.removeItem(k);
      else localStorage.setItem(k, снимка[k]);
    });
    return 'паметта е върната (' + КЛЮЧОВЕ.length + ' ключа)';
  }
  function изчисти() { КЛЮЧОВЕ.forEach(function (k) { localStorage.removeItem(k); }); }

  function спи(ms) { return new Promise(function (r) { setTimeout(r, ms); }); }
  function ден(отместване) {
    var d = new Date(Date.now() + отместване * 86400000);
    return d.getFullYear() + '-' + String(d.getMonth() + 1).padStart(2, '0') +
           '-' + String(d.getDate()).padStart(2, '0');
  }
  function ред(група, име, очаквано, получено, мина, бележка) {
    return { група: група, име: име, ОЧАКВАНО: очаквано, ПОЛУЧЕНО: получено,
             мина: !!мина, бележка: бележка || '' };
  }

  // отваря екрана НАСИЛА — не чака условието „още не се е представила"
  async function отвори() {
    if (!window.BL_ONBOARD) return false;
    BL_ONBOARD.open();
    await спи(120);
    return $('onbOverlay') && !$('onbOverlay').hidden;
  }
  function натисни(el) { if (el) el.click(); }
  function пол(коя) {
    var b = $('onbSex') && $('onbSex').querySelector('.onb-sexbtn[data-sex="' + коя + '"]');
    натисни(b); return !!b;
  }

  async function провери() {
    var редове = [];
    if (!window.BL_ONBOARD || !$('onbOverlay')) {
      return { ПУСНАТИ_ТЕСТА: 0,
               ГРЕШКА: 'BL_ONBOARD или #onbOverlay липсва — приложението не е заредено. Това НЕ е „чисто".' };
    }
    снимка = снеми();

    try {
      // ── А · ОТВАРЯ ЛИ СЕ ИЗОБЩО ──
      изчисти();
      var отворен = await отвори();
      редове.push(ред('А · отваряне', 'екранът се отваря насила',
        'onbOverlay видим', отворен ? 'видим' : 'СКРИТ', отворен,
        'ако това падне, всичко останало е без значение'));
      if (!отворен) throw new Error('екранът не се отвори');

      // всички полета налице
      var липсват = ['onbName', 'onbSex', 'onbDate', 'onbDateLbl', 'onbSave', 'onbSkip', 'onbMeDate']
        .filter(function (id) { return !$(id); });
      редове.push(ред('А · отваряне', 'всички полета съществуват',
        '0 липсващи', липсват.length ? липсват.join(', ') : '0', липсват.length === 0));

      // ── Б · БЪДЕЩАТА ДАТА ──
      // това е пазачът, който спасява цялото приложение: рождена дата напред
      // прави BL_AGE null и апп-ът се държи, все едно няма бебе
      изчисти(); await отвори();
      пол('girl');
      $('onbDate').value = ден(30);          // след месец
      натисни($('onbSave'));
      await спи(150);
      var записано = localStorage.getItem('bl_baby');
      редове.push(ред('Б · бъдеща дата', 'рождена дата НАПРЕД се отказва',
        'нищо не се записва', записано ? 'ЗАПИСА СЕ: ' + записано : 'нищо', !записано,
        'иначе възрастта става null и цялото приложение мисли, че няма бебе'));
      редове.push(ред('Б · бъдеща дата', 'екранът ОСТАВА отворен, за да поправи',
        'видим', $('onbOverlay').hidden ? 'ЗАТВОРИ СЕ' : 'видим', !$('onbOverlay').hidden));

      // ── В · „ОЩЕ ЧАКАМ" → „МОМИЧЕ": НАЙ-ОПАСНОТО ЕДНО ДОКОСВАНЕ ──
      изчисти();
      var одр = ден(60);
      localStorage.setItem('bl_lmp', ден(60 - 280));
      await отвори();
      await спи(60);
      var предиСмяна = $('onbDate').value;
      пол('girl');                              // ← точката на риска
      await спи(60);
      var следСмяна = $('onbDate').value;
      редове.push(ред('В · чакам → роди се', 'предложената ОДР се ЧИСТИ при смяна',
        'полето празно', следСмяна === '' ? 'празно' : 'ОСТАНА: ' + следСмяна,
        следСмяна === '',
        'иначе ОЧАКВАНАТА дата се записва като РОЖДЕНА и тръгват сгрешени ваксини'));
      редове.push(ред('В · чакам → роди се', 'преди смяната полето Е било попълнено',
        'непразно (иначе тестът не мери нищо)', предиСмяна || 'ПРАЗНО', !!предиСмяна,
        'контрола, че сценарият изобщо е възпроизведен'));

      // ── Г · БРЕМЕННАТА: ОДР отключва машината ──
      изчисти(); await отвори();
      пол('wait');
      await спи(60);
      $('onbDate').value = ден(70);
      натисни($('onbSave'));
      await спи(200);
      var lmp = localStorage.getItem('bl_lmp');
      var очакванLmp = null;
      if (lmp) {
        var d = new Date(JSON.parse(lmp));
        очакванLmp = Math.abs(d.getTime() - (new Date(ден(70)).getTime() - 280 * 86400000)) < 2 * 86400000;
      }
      редове.push(ред('Г · бременната', 'ОДР се превръща в bl_lmp (ОДР − 280 дни)',
        'записан и верен', lmp ? (очакванLmp ? 'верен: ' + lmp : 'ГРЕШЕН: ' + lmp) : 'НЯМА',
        !!lmp && !!очакванLmp,
        'без него бременностната машина стои празна пред точно тази майка'));
      var бебе = JSON.parse(localStorage.getItem('bl_baby') || '{}');
      редове.push(ред('Г · бременната', 'при „чакам" НЕ се записва рождена дата',
        'birth празно', бебе.birth ? 'ЗАПИСА: ' + бебе.birth : 'празно', !бебе.birth));

      // ── Д · РОДИ СЕ → бременността приключва ──
      изчисти();
      localStorage.setItem('bl_lmp', JSON.stringify(ден(-200)));
      await отвори();
      пол('boy');
      $('onbDate').value = ден(-10);
      натисни($('onbSave'));
      await спи(200);
      редове.push(ред('Д · роди се', 'bl_lmp се маха при въведена рождена дата',
        'няма bl_lmp', localStorage.getItem('bl_lmp') ? 'ОСТАНА' : 'махнат',
        !localStorage.getItem('bl_lmp'),
        'иначе приложението мисли, че е и бременна, и родила'));

      // ── Е · НЕДОНОСЕНОСТТА ──
      изчисти(); await отвори();
      пол('wait'); await спи(60);
      var скритПриЧакам = $('onbPretermWrap') ? $('onbPretermWrap').hidden : null;
      пол('girl'); await спи(60);
      var видимПриРодено = $('onbPretermWrap') ? !$('onbPretermWrap').hidden : null;
      редове.push(ред('Е · недоносеност', 'полето е СКРИТО при „още чакам"',
        'скрито', скритПриЧакам === null ? 'няма поле' : (скритПриЧакам ? 'скрито' : 'ВИДИМО'),
        скритПриЧакам === true, 'няма смисъл да питаш чакащата на коя седмица се е родило'));
      редове.push(ред('Е · недоносеност', 'полето е ВИДИМО при родено бебе',
        'видимо', видимПриРодено === null ? 'няма поле' : (видимПриРодено ? 'видимо' : 'СКРИТО'),
        видимПриРодено === true));

      // ── Ж · „ПО-КЪСНО" срещу КЛИК НА ФОНА ──
      изчисти(); await отвори();
      натисни($('onbSkip'));
      await спи(120);
      редове.push(ред('Ж · излизане', '„По-късно" отписва (bl_onboarded)',
        'true', String(localStorage.getItem('bl_onboarded')), !!localStorage.getItem('bl_onboarded'),
        'иначе поканата ще я гони всеки път'));

      изчисти(); await отвори();
      $('onbOverlay').click();                  // клик на самия фон
      await спи(120);
      редове.push(ред('Ж · излизане', 'клик на ФОНА само затваря, БЕЗ да отписва',
        'няма bl_onboarded', localStorage.getItem('bl_onboarded') ? 'ОТПИСА Я' : 'няма',
        !localStorage.getItem('bl_onboarded'),
        'случайно докосване не бива да убие поканата завинаги'));

      // ── З · ПРАЗНО ИМЕ и САМО ИМЕ ──
      изчисти(); await отвори();
      пол('girl');
      натисни($('onbSave'));
      await спи(150);
      редове.push(ред('З · празни полета', 'запис БЕЗ име и БЕЗ дата минава',
        'записано', localStorage.getItem('bl_baby') ? 'записано' : 'ОТКАЗА',
        !!localStorage.getItem('bl_baby'),
        'името е „по желание“ — не бива да е капан'));

      // ── И · РОЖДЕНАТА ДАТА НА МАЙКАТА ──
      изчисти(); await отвори();
      пол('girl');
      $('onbDate').value = ден(-100);
      $('onbMeDate').value = '1994-05-17';
      натисни($('onbSave'));
      await спи(200);
      var me = null; try { me = JSON.parse(localStorage.getItem('bl_me') || 'null'); } catch (e) {}
      редове.push(ред('И · майката', 'нейната дата се записва в bl_me',
        '1994-05-17', me && me.birth ? me.birth : 'НЯМА', !!(me && me.birth === '1994-05-17'),
        'тя отключва стая „Жената в мен“'));

      // ── Й · ВРЪЩАНЕ: помни ли предишното ──
      изчисти();
      localStorage.setItem('bl_baby', JSON.stringify({ name: 'Мая', sex: 'girl', birth: ден(-200) }));
      await отвори();
      await спи(80);
      редове.push(ред('Й · връщане', 'при повторно отваряне полетата са попълнени',
        'име Мая', $('onbName').value || 'ПРАЗНО', $('onbName').value === 'Мая',
        'мама влиза да поправи, не да въвежда наново'));
      var избран = $('onbSex').querySelector('.onb-sexbtn.on');
      редове.push(ред('Й · връщане', 'избраният пол е отбелязан',
        'girl', избран ? избран.dataset.sex : 'НИЩО',
        !!(избран && избран.dataset.sex === 'girl')));

      // ── К · МИШЕНИ И ЧЕТИМОСТ на телефон ──
      изчисти(); await отвори(); await спи(200);
      var малки = [], прегледани = 0;
      var поле = $('onbOverlay');
      poleЦикъл(poleЦели(поле), function (el) {
        var r = el.getBoundingClientRect();
        var cs = getComputedStyle(el);
        if (cs.display === 'none' || cs.visibility === 'hidden' || !r.width || !r.height) return;
        прегледани++;
        var w = r.width, h = r.height;
        ['::after', '::before'].forEach(function (п) {
          var c = getComputedStyle(el, п);
          if (c.content === 'none') return;
          if (c.position === 'absolute' || c.position === 'fixed') {
            w = Math.max(w, parseFloat(c.width) || 0);
            h = Math.max(h, parseFloat(c.height) || 0);
          }
        });
        if (w < 44 || h < 44)
          малки.push((el.id || el.className || el.tagName) + ' ' + Math.round(w) + '×' + Math.round(h));
      });
      редове.push(ред('К · телефон', 'всички цели са ≥44×44',
        '0 малки от ' + прегледани, малки.length + (малки.length ? ': ' + малки.slice(0, 5).join(' · ') : ''),
        малки.length === 0, 'мама държи бебето с другата ръка'));

      var пр = поле.getBoundingClientRect();
      редове.push(ред('К · телефон', 'екранът се побира по ширина',
        'без хоризонтален скрол',
        поле.scrollWidth > поле.clientWidth + 2 ? 'СКРОЛ: ' + поле.scrollWidth + ' срещу ' + поле.clientWidth : 'няма',
        поле.scrollWidth <= поле.clientWidth + 2));

      // ── Л · САМОПРОВЕРКА: тестът може ли изобщо да гърми ──
      // Счупваме нарочно пазача за бъдеща дата и гледаме дали Б го хваща.
      изчисти(); await отвори();
      пол('girl');
      $('onbDate').value = ден(-5);           // валидна дата
      натисни($('onbSave'));
      await спи(150);
      var валиднатаМина = !!localStorage.getItem('bl_baby');
      редове.push(ред('Л · самопроверка', 'ВАЛИДНА дата минава (иначе Б е фалшиво зелено)',
        'записва се', валиднатаМина ? 'записа се' : 'ОТКАЗА',
        валиднатаМина,
        'ако и валидната се отказва, значи Б минава по грешна причина'));

    } catch (e) {
      редове.push(ред('🔴 гръмна', String(e.message).slice(0, 120), '—', '—', false));
    } finally {
      try { if (window.BL_ONBOARD) BL_ONBOARD.close(); } catch (e) {}
      върни();
    }

    var паднали = редове.filter(function (r) { return !r.мина; });
    var доклад = {
      ПУСНАТИ_ТЕСТА: редове.length,
      МИНАЛИ: редове.length - паднали.length,
      ПАДНАЛИ: паднали.length,
      ПРОВАЛИ: паднали,
      ПАМЕТТА_ВЪРНАТА: върни(),
      всички_редове: редове
    };
    console.log('%c🚪 ТЕСТ ЗА ВХОДА', 'font-size:15px;font-weight:700');
    console.table(редове.map(function (r) {
      return { група: r.група, име: r.име, статус: r.мина ? '✅' : '🔴', получено: r.ПОЛУЧЕНО };
    }));
    console.log('пуснати ' + доклад.ПУСНАТИ_ТЕСТА + ' · минали ' + доклад.МИНАЛИ +
                ' · ПАДНАЛИ ' + доклад.ПАДНАЛИ);
    window.BL_ВХОД.последен = доклад;
    return доклад;
  }

  function poleЦели(корен) {
    return корен.querySelectorAll('button, input, select, [role="button"], a[href]');
  }
  function poleЦикъл(списък, работа) {
    for (var i = 0; i < списък.length; i++) работа(списък[i]);
  }

  window.BL_ВХОД = { провери: провери, върни: върни, последен: null };
  window.BL_ENTRY = window.BL_ВХОД;
  console.log('🚪 зареден. Пусни:  await BL_ВХОД.провери()   ·   аварийно: BL_ВХОД.върни()');
})();
