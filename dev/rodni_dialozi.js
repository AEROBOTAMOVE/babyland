// ЗАЩО (25.08.2026): живият обходчик (dev/interaktivno.js) заби мъртво насред
// стая „Бременност" — един натиснат бутон отвори native confirm() и той
// БЛОКИРА цялата JavaScript нишка. Страницата спря да отговаря и обходът
// трябваше да се убие с презареждане.
//
// Това не е проблем само на уреда. Проектът вече е записал ДВА ПЪТИ защо
// тези кутии са лоши за майката — в js/rooms17.js и js/wisdom2.js стои
// черно на бяло: „в режим приложение системната кутия на част от телефоните
// изобщо не се показва — мама натиска и не се случва нищо."
// Тоест бутон със суров prompt() е бутон, който на някои телефони НЕ РАБОТИ,
// и то мълчаливо.
//
// js/ui.js дава топлата вградена замяна: BL_UI.confirm и BL_UI.note.
// Няма BL_UI.prompt — за въвеждане правилният модел е ИНЛАЙН ПОЛЕ в самата
// карта (виж js/rooms17.js, js/wisdom2.js, js/baby2.js).
//
// КАКВО БРОИ ЗА ДОБРО:
//   · извикване, до което в близките редове стои BL_UI → резервен изход,
//     който на практика никога не се ползва (BL_UI винаги съществува)
//   · ред, който е коментар
// КАКВО Е НАХОДКА:
//   · сурово alert/confirm/prompt без BL_UI наблизо
//
// 🪤 КАПАНИ, ЗАРАДИ КОИТО ИЗРАЗЪТ ИЗГЛЕЖДА ТАКА:
//   · `.prompt(` е ЧУЖД метод (нечий обект), не системната кутия → пред
//     името се иска начало на ред или знак, който не е точка/буква
//   · файловете са с CRLF → делим на /\r?\n/, не на '\n'
//   · ARCHIVE и PREDI_* копия не се броят — те са минало, не жив код
//
// ПУСКАНЕ: node dev/rodni_dialozi.js
// ПЪТ НАЗАД: файлът само ЧЕТЕ. Изход 1 при находка.
// ═══════════════════════════════════════════════════════════
const fs = require('fs');
const path = require('path');
process.chdir(path.resolve(__dirname, '..'));

const ИЗРАЗ = /(^|[^.\w])(alert|confirm|prompt)\s*\(/;

function прегледай(име, текст) {
  const редове = текст.split(/\r?\n/);
  const сурови = [], спазени = [];
  редове.forEach((ред, i) => {
    if (/^\s*\/\//.test(ред)) return;                 // цял ред коментар
    if (!ИЗРАЗ.test(ред)) return;
    const около = редове.slice(Math.max(0, i - 4), i + 2).join(' ');
    (/BL_UI/.test(около) ? спазени : сурови).push(име + ':' + (i + 1) + '  ' + ред.trim().slice(0, 92));
  });
  return { сурови, спазени };
}

const файлове = fs.readdirSync('js')
  .filter(f => f.endsWith('.js') && !/ARCHIVE|PREDI/.test(f))
  .map(f => 'js/' + f)
  .concat(fs.readdirSync('.').filter(f => f.endsWith('.html')));

let сурови = [], спазени = [], редовеОбщо = 0;
for (const f of файлове) {
  const т = fs.readFileSync(f, 'utf8');
  редовеОбщо += т.split(/\r?\n/).length;
  const р = прегледай(f, т);
  сурови = сурови.concat(р.сурови);
  спазени = спазени.concat(р.спазени);
}

console.log('💬 СУРОВИ СИСТЕМНИ КУТИИ\n');
console.log('  ПРЕГЛЕДАНИ ФАЙЛОВЕ : ' + файлове.length);
console.log('  ПРЕГЛЕДАНИ РЕДОВЕ  : ' + редовеОбщо.toLocaleString('bg'));
console.log('  ✅ с резервен BL_UI изход : ' + спазени.length);
console.log('  ' + (сурови.length ? '🔴' : '✅') + ' СУРОВИ                  : ' + сурови.length + '\n');
сурови.forEach(x => console.log('     🔴 ' + x));

// ── САМОПРОВЕРКА в ДВЕТЕ посоки ───────────────────────────
// Уред, който не може да гръмне, не мери нищо. Тук се подават четири реда с
// известен отговор: ако той сбърка който и да е от тях, числото горе е боклук.
const п = [
  ['  const н = prompt("Име:", x);',                         true,  'сурово prompt'],
  ['  } else alert(t);',                                     true,  'сурово alert'],
  ['  ? BL_UI.confirm(m) : Promise.resolve(confirm(m));',     false, 'confirm с BL_UI до него'],
  ['  const r = await this.prompt(x);',                       false, 'ЧУЖД .prompt метод, не кутия'],
  ['  // тук имаше prompt(), махнат е',                       false, 'ред-коментар']
];
console.log('\n  САМОПРОВЕРКА (иначе нулата горе не значи нищо):');
let счупена = false;
for (const [ред, очаква, какво] of п) {
  const р = прегледай('проба', ред);
  const намери = р.сурови.length > 0;
  const ок = намери === очаква;
  if (!ок) счупена = true;
  console.log('     ' + (ок ? '✅' : '🔴') + ' ' + (очаква ? 'ХВАЩА  ' : 'ПРОПУСКА') + ' ' + какво);
}
if (счупена) { console.log('\n  🔴 САМОПРОВЕРКАТА ПАДНА — числото горе не важи.'); process.exit(2); }

console.log('\n  Замяната: BL_UI.confirm / BL_UI.note (js/ui.js).');
console.log('  За ВЪВЕЖДАНЕ няма BL_UI.prompt — прави ИНЛАЙН поле в самата карта');
console.log('  (модел: js/rooms17.js, js/wisdom2.js, js/baby2.js).');
process.exit(сурови.length ? 1 : 0);
