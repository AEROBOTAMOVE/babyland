  // ═══════════ 3) ЦИКЪЛЪТ СЕ ВРЪЩА (Жената в мен) ═══════════
  function цикълКарта(root) {
    const c = card('Цикълът се връща 🌙 <span class="jr-sub">тиха лична хроника — само за теб</span>');
    const out = el('p', 'bb-feed', '');
    const списък = el('p', 'bb-feed'); списък.style.opacity = '.85'; списък.style.fontSize = '.92em';

    function рисувай() {
      const log = load('bl_period', []);
      if (!log.length) {
        out.innerHTML = 'Още няма отбелязано. Върне ли се цикълът — отбележи тук и ще ти помня ритъма.';
        списък.innerHTML = '';
        return;
      }
      const посл = log[log.length - 1];
      // 🟠 11.08 (обиколка във времето): броеше 24-часови блокове, не КАЛЕНДАРНИ
      //    дни. Отбелязано вчера в 22:00 и погледнато днес в 13:00 → 15 часа →
      //    „0“ → редът пишеше „Последно отбелязано: 10.8.2026 (днес)“. Датата и
      //    думата до нея си противоречаха, а мама няма как да познае коя е вярната.
      //    Сега денят се мери от полунощ до полунощ, както го брои и тя.
      const ден0 = ts => { const d = new Date(ts); d.setHours(0, 0, 0, 0); return d.getTime(); };
      const дни = Math.round((ден0(Date.now()) - ден0(посл)) / 86400000);
      out.innerHTML = 'Последно отбелязано: <strong>' + дата(посл) + '</strong>' +
        (дни < 0 ? '' : дни === 0 ? ' (днес)' : дни === 1 ? ' (вчера)' : ' — преди ' + дни + ' дни');
      if (log.length >= 3) {
        const инт = [];
        for (let i = 1; i < log.length; i++) инт.push(Math.round((log[i] - log[i - 1]) / 86400000));
        const посл3 = инт.slice(-3).sort((a, b) => a - b);
        const мед = посл3[Math.floor(посл3.length / 2)];
        if (мед > 10 && мед < 90) списък.innerHTML = 'Твоят ритъм напоследък: около <strong>' + мед + ' дни</strong> между отбелязванията.';
        else списък.innerHTML = 'Първите цикли след раждане често са неравни — това е нормално.';
      } else {
        списък.innerHTML = 'След още няколко отбелязвания ще виждаш ритъма си.';
      }
    }

    c.appendChild(out); c.appendChild(списък);
    const row = el('div', 'jr-quick');
    // 🔴 11.08 (обиколка по картите): и двата бутона умееха да МЪЛЧАТ. „Върна се
    //    днес“ в рамките на 3 дни от предишното отбелязване не правеше нищо и не
    //    казваше нищо — мама натиска пак и пак, мислейки, че не е уцелила. „Върни
    //    последното“ на празен списък — също. Пазачът срещу дублите остава; само
    //    вече си отваря устата.
    const думичка = el('p', 'jr-hint', ''); думичка.hidden = true;
    думичка.setAttribute('aria-live', 'polite');
    const кажи = т => { думичка.textContent = т; думичка.hidden = false; };
    const b = el('button', 'jr-chip', '🌙 Върна се днес'); b.type = 'button';
    b.addEventListener('click', () => {
      const log = load('bl_period', []);
      const днес = Date.now();
      if (log.length && (днес - log[log.length - 1]) < 86400000 * 3) {   // без дубли в 3 дни
        кажи('Вече го отбелязах на ' + дата(log[log.length - 1]) + ' — държа само първия ден, за да не се раздвои ритъмът ти. Ако е било грешка, „↺ Върни последното“ го маха. 💜');
        fx().buzz(6);
        return;
      }
      думичка.hidden = true;
      log.push(днес); save('bl_period', log.slice(-24));
      рисувай(); fx().buzz(8);
    });
    const undo = el('button', 'jr-chip', '↺ Върни последното'); undo.type = 'button';
    undo.addEventListener('click', () => {
      const log = load('bl_period', []);
      if (!log.length) { кажи('Още няма какво да върна — списъкът е празен.'); return; }
      думичка.hidden = true;
      log.pop(); save('bl_period', log); рисувай(); fx().buzz(6);
    });
    row.appendChild(b); row.appendChild(undo);
    c.appendChild(row); c.appendChild(думичка);
    рисувай();
    c.appendChild(el('p', 'jr-privacy', 'При кърмене цикълът може да се върне след месеци — или да подрани. И двете са нормални. Помни: може да забременееш и ПРЕДИ първия цикъл. 💜'));
    root.appendChild(c);
  }

