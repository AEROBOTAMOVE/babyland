// ═══════════════════════════════════════════════════════════
// 🎬 ИЗВЪН ЕКРАНА — каквото не се вижда, не се движи
//
// Собственикът: „началната страница, роудмапа — зацепва леко анимацията,
// нацепва на места."
//
// ИЗМЕРЕНО 12.08, преди да пипна каквото и да е:
//   396 @keyframes в 14 css файла
//   от тях СКЪПИ (пипат подредбата): 0
//   333 БЕЗКРАЙНИ едновременно
//
// 🪤 И ЕДНА МОЯ ГРЕШКА, която за малко да ме прати да „поправям" здраво:
// първият ми скенер каза, че 24 анимации се движат по width/height/top/left.
// Невярно. Изразът беше /@keyframes\s+(\w+)\s*\{([\s\S]*?)\n\}/, а в този
// проект повечето keyframes са на ЕДИН РЕД — затова „\n}" се намираше чак
// няколко реда по-долу и в „тялото" влизаха СЪСЕДНИТЕ правила, които
// естествено съдържат left/top/width. Новият брояч (dev/cena_animacii.js)
// брои скоби и казва: нула скъпи.
//
// Тоест причината НЕ е видът, а БРОЯТ. Всяка е евтина сама; композиторът
// на телефона обработва 333 слоя на кадър, а мама скролва точно тогава.
//
// КАКВО ПРАВИ ТОЗИ ФАЙЛ:
//   Диригентът sceneIO (js/app.js:61) вече гаси сцените ИЗВЪН ЕКРАН — но
//   само за .room-card и #phoneStage. Тук същото се прилага за ВСИЧКО
//   останало, без да се знае нищо за конкретните елементи: намираме кой
//   има безкрайна анимация и го спираме, докато е извън кадър.
//
// ЗАЩО НЕ Е СЪЩОТО КАТО js/plavno.js:
//   plavno.js спира ВСИЧКО по ВРЕМЕ — докато пръстът се движи, 180 мс.
//   Тук спираме по МЯСТО — завинаги, докато елементът е извън екрана.
//   Двете се допълват: едното пази жеста, другото пази батерията.
//
// ⚠ КАПАНЪТ, В КОЙТО ПАДНА ПЪРВАТА ВЕРСИЯ НА plavno.js (и е записан там):
//   наблюдение по видимост е СЛЯПО за `position: fixed` — небето (.sky) е
//   inset:0 и ВИНАГИ е в кадър. Затова тук такива елементи се пропускат
//   изрично: за тях наблюдателят е безполезен и само хаби работа.
//
// ПЪТ НАЗАД: махни реда за този файл от index.html. Нищо не зависи от него;
//   класът само спира анимация и я пуска обратно оттам, откъдето е спряла.
// ═══════════════════════════════════════════════════════════
(function () {
  'use strict';

  if (!window.IntersectionObserver) return;
  if (window.matchMedia && matchMedia('(prefers-reduced-motion: reduce)').matches) return;

  var КЛАС = 'bl-vun';
  var s = document.createElement('style');
  s.textContent = '.' + КЛАС + ', .' + КЛАС + ' *, .' + КЛАС + '::before, .' + КЛАС + '::after' +
                  ' { animation-play-state: paused !important; }';
  document.head.appendChild(s);

  var наблюдавани = 0, спрени = 0, пропуснатиФиксирани = 0;
  var записаниЕл = [];   // пазим ги, за да може геометричната сверка да ги обходи

  var набл = new IntersectionObserver(function (записи) {
    записи.forEach(function (з) {
      if (з.isIntersecting) {
        if (з.target.classList.contains(КЛАС)) { з.target.classList.remove(КЛАС); спрени--; }
      } else {
        if (!з.target.classList.contains(КЛАС)) { з.target.classList.add(КЛАС); спрени++; }
      }
    });
  }, {
    // 300px запас: анимацията тръгва, преди мама да е стигнала дотам,
    // за да не вижда как нещо „се събужда" под пръста ѝ
    rootMargin: '300px 0px 300px 0px',
    threshold: 0
  });

  // Кой има безкрайна анимация. Гледаме computed style — така хващаме и
  // това, което е сложено от JS, не само от CSS файловете.
  function запиши(корен) {
    var к = корен || document.body;
    // 🪤 querySelectorAll('*') НЕ връща самия корен. При обхождането на цялото
    //   тяло това е без значение, но когато корен е новодобавен възел (виж
    //   наблюдателя за нови възли по-долу), самият той често е анимираният.
    var кандидати = (к.nodeType === 1 && к !== document.body)
      ? [к].concat(Array.prototype.slice.call(к.querySelectorAll('*')))
      : к.querySelectorAll('*');
    for (var i = 0; i < кандидати.length; i++) {
      var e = кандидати[i];
      if (!e) continue;
      if (e.__blVun) continue;
      var cs = getComputedStyle(e);
      if (cs.animationName === 'none') continue;
      if (cs.animationIterationCount.indexOf('infinite') < 0) continue;
      // 🪤 fixed/sticky са винаги в кадър — наблюдателят е сляп за тях
      if (cs.position === 'fixed' || cs.position === 'sticky') { пропуснатиФиксирани++; e.__blVun = 1; continue; }
      // елемент вътре в друг наблюдаван предшественик — родителят стига
      if (e.closest('.' + КЛАС)) continue;
      e.__blVun = 1;
      набл.observe(e);
      записаниЕл.push(e);
      наблюдавани++;
    }
  }

  // ═══════════════════════════════════════════════════════════
  // 🔴🔴 19.08 — НАБЛЮДАТЕЛЯТ ПО ВИДИМОСТ СПИРАШЕ НУЛА. ИЗМЕРЕНО:
  //     186 елемента с безкрайна анимация · 179 записани при наблюдателя
  //     104 от тях ГЕОМЕТРИЧНО извън екрана (top до 1986 при прозорец 760)
  //     от тези 104 с клас за пауза:  0
  //     общо работещи анимации: 198
  // Тоест целият файл се смяташе за свършена работа, а не спираше нищо.
  //
  // ЗАЩО: страницата НЕ се плъзга в прозореца — `window.scrollTo(0,1500)`
  // оставя scrollY на 0 при съдържание 10484 пиксела. Плъзгачът е вътрешен
  // контейнер. При такава подредба IntersectionObserver с подразбиращ се
  // корен не докладва тези елементи като излезли и обажданията му спират.
  // (Проверено, че НЕ Е от моята промяна: същите 140/0 се мерят и с върнатия
  //  файл отпреди нея.)
  //
  // ЛЕКЪТ: геометрична сверка, която има ПОСЛЕДНАТА дума. Чете правоъгълника
  // на записаните елементи и слага/маха класа сам. Наблюдателят остава —
  // той е евтин и бърз, когато работи; сверката го поправя, когато не.
  //
  // ЦЕНАТА, измерена: ~180 четения на правоъгълник, групирани в един залп,
  // не по-често от веднъж на 250 мс и само докато табът се вижда.
  // ПЪТ НАЗАД: махни сверѝГеометрично и извикванията ѝ.
  // ═══════════════════════════════════════════════════════════
  var ЗАПАС = 300;   // същият запас като на наблюдателя
  function сверѝГеометрично() {
    if (document.hidden) return;
    var H = window.innerHeight || 0, W = window.innerWidth || 0;
    if (!H) return;
    var живи = 0;
    for (var i = 0; i < записаниЕл.length; i++) {
      var e = записаниЕл[i];
      if (!e || !e.isConnected) continue;
      записаниЕл[живи++] = e;                      // и чистим откъснатите пътьом
      var r = e.getBoundingClientRect();
      // елемент без кутия (скрит родител) също не се вижда → спира се
      var извън = (r.width === 0 && r.height === 0) ||
                  r.bottom < -ЗАПАС || r.top > H + ЗАПАС ||
                  r.right < -ЗАПАС || r.left > W + ЗАПАС;
      var има = e.classList.contains(КЛАС);
      if (извън && !има) { e.classList.add(КЛАС); спрени++; }
      else if (!извън && има) { e.classList.remove(КЛАС); спрени--; }
    }
    записаниЕл.length = живи;
  }
  var чакаСверка = null;
  function сверѝСкоро() {
    if (чакаСверка) return;
    чакаСверка = setTimeout(function () { чакаСверка = null; сверѝГеометрично(); }, 250);
  }
  // Плъзгачът е вътрешен → слушаме в ЗАХВАТ, за да чуем всеки контейнер.
  document.addEventListener('scroll', сверѝСкоро, true);
  window.addEventListener('resize', сверѝСкоро);
  document.addEventListener('visibilitychange', сверѝСкоро);

  function тръгни() {
    запиши(document.body);
    // Началната страница дорисува неща след първия кадър (хълма, картите).
    // Два късни огледа хващат тях, без да въртим наблюдател вечно.
    setTimeout(function () { запиши(document.body); }, 1200);
    setTimeout(function () { запиши(document.body); }, 3500);
  }

  if (document.readyState === 'loading')
    document.addEventListener('DOMContentLoaded', тръгни);
  else тръгни();

  // ═══════════════════════════════════════════════════════════
  // 🔴 19.08 — ВСИЧКО, НАРИСУВАНО СЛЕД 3.5 СЕКУНДИ, НЕ СЕ ПАЗЕШЕ ИЗОБЩО
  //
  // `запиши` минаваше точно три пъти: при зареждане, на 1.2 и на 3.5 сек.
  // А приложението рисува стаите, статиите и сцените ПО ИСКАНЕ — тоест
  // много по-късно. Тези елементи не влизаха при наблюдателя НИКОГА и се
  // въртяха вечно, независимо къде са.
  //
  // ИЗМЕРЕНО НА ЖИВО (360×760, отворена стая, после начална):
  //     14 анимации вървят на 1750-1920 пиксела ПОД ръба на екрана
  //     нито една няма клас за пауза, нито една няма спрян родител
  //     (тоест не са „пропуснати заради родителя" — просто не са видени)
  //
  // ЛЕКЪТ — икономичен нарочно:
  //   · обхождат се САМО добавените поддървета, не цялото тяло;
  //   · събират се и се преглеждат наведнъж, веднъж на 400 мс;
  //   · вече записаните се пропускат по e.__blVun, както досега.
  // Тоест цената е един обход на новото съдържание, а не постоянен скенер.
  //
  // ПЪТ НАЗАД: махни този блок. Наблюдателят се връща към трите минавания.
  // ═══════════════════════════════════════════════════════════
  // 🪤 ПЪРВАТА МИ ВЕРСИЯ ЗАБИ БРАУЗЪРА. Събирах ВСЕКИ добавен възел в списък
  //   и за всеки правех querySelectorAll('*') — а стаята добавя стотици възли,
  //   вложени един в друг, тоест едно и също поддърво се обхождаше по
  //   десетки пъти. Извикванията в конзолата почнаха да засичат на 30 сек.
  //   Правилното е ЕДИН обход на тялото за цял залп промени, с таван по
  //   честота. Обходът е евтин: вече записаните се прескачат по __blVun
  //   ПРЕДИ да се пита getComputedStyle.
  var чакаНов = null, последенОбход = 0;
  var ПАУЗА = 700;     // изчакване след последната промяна
  var НАЙ_ЧЕСТО = 2000; // и не повече от веднъж на 2 секунди
  function прегледайНовите() {
    чакаНов = null;
    последенОбход = Date.now();
    try { запиши(document.body); } catch (e) {}
    сверѝГеометрично();   // новото съдържание веднага получава присъда
  }
  try {
    new MutationObserver(function () {
      if (чакаНов) return;
      var изчакай = Math.max(ПАУЗА, НАЙ_ЧЕСТО - (Date.now() - последенОбход));
      чакаНов = setTimeout(прегледайНовите, изчакай);
    }).observe(document.body, { childList: true, subtree: true });
  } catch (e) {}

  // ═══════════════════════════════════════════════════════════
  // 🌌 НЕБЕТО — 20-те, които не спират НИКЪДЕ
  //
  // ИЗМЕРЕНО 12.08 със собствен видим Chrome (не headless — headless не
  // заключва rAF за vsync и дава невъзможни 111 fps):
  //   анимации, които ВЪРВЯТ:  без защита 137 · с защита 54 на върха, 20 на дъното
  //   тези 20 са: twinkle×11, twinkleOp×7, blobDrift×4, miniFloat×3,
  //               cloudDrift×1, mascotFly×1 — всичките в .sky
  //
  // Защо наблюдателят не ги хваща: .sky е `position: fixed; inset: 0`, тоест
  // ВИНАГИ е в кадър. Децата му са absolute ВЪТРЕ в него и също винаги се
  // засичат. Това е същият капан, записан в главата на js/plavno.js.
  //
  // Тук се гаси по ДРУГ признак: когато отгоре има отворена стая, небето е
  // ПОКРИТО — невидимо е, но продължава да се движи. Същото при скрит таб.
  // ПЪТ НАЗАД: махни този блок; нищо друго не зависи от него.
  // ═══════════════════════════════════════════════════════════
  var ПОКРИВАЩИ = ['roomOverlay', 'artOverlay', 'searchOverlay', 'onbOverlay'];
  var небе = null, небеСпряно = false;
  function покрито() {
    // 🪤 Първата ми версия питаше за `libOverlay` — такъв id НЯМА в index.html.
    // getElementById щеше да връща null завинаги и проверката щеше да е тиха
    // измислица. Истинските пълноекранни слоеве са точно тези четири
    // (проверено: grep id="…Overlay" в index.html).
    // 🔴 19.08 — ВТОРА ПРОВЕРКА, КОЯТО НЕ МОЖЕШЕ ДА БЪДЕ ВЯРНА НИКОГА.
    //   Тук пишеше `e.offsetParent !== null`. Но и четирите слоя са
    //   `position: fixed`, а за фиксиран елемент offsetParent Е null ВИНАГИ —
    //   и когато се вижда на цял екран. Тоест условието беше вечно false и
    //   небето НЕ Е спирало под отворена стая нито веднъж.
    //   ИЗМЕРЕНО на живо, при ОТВОРЕНА стая:
    //       #roomOverlay: hidden=false · display=flex · размер 360×760
    //                     offsetParent === null → ДА
    //                     старата сметка → „не е покрито"
    //   (Личеше само защото другият клон — скрит таб — вършеше работата.
    //    dev/test_nebe.js го отчиташе като 1 паднала от 14.)
    //   ЛЕКЪТ: пита се за истинска кутия на екрана. Работи и за fixed.
    //   ⚠ Безопасно е в правилната посока: най-лошото, което може да стане, е
    //   небето да спре, докато отгоре стои слой — тоест докато никой не го вижда.
    //   ПЪТ НАЗАД: върни `e.offsetParent !== null`.
    for (var i = 0; i < ПОКРИВАЩИ.length; i++) {
      var e = document.getElementById(ПОКРИВАЩИ[i]);
      if (!e || e.hidden) continue;
      if (getComputedStyle(e).display === 'none') continue;
      var r = e.getBoundingClientRect();
      if (r.width > 0 && r.height > 0) return true;
    }
    return document.hidden === true;
  }
  function сверинебе() {
    // 🪤 ПЪРВАТА ВЕРСИЯ СРАВНЯВАШЕ С ПАМЕТТА СИ, НЕ С ДЕЙСТВИТЕЛНОСТТА:
    //   if (трябва === небеСпряно) return;
    // Махнеше ли класа някой отвън (пререндер, друг код, тест), променливата
    // оставаше true, проверката излизаше рано и небето вървеше вечно, докато
    // кодът „смяташе", че го е спрял. Хванато от dev/test_nebe.js на живо.
    // Сега се пита САМИЯТ ЕЛЕМЕНТ. Паметта е бележка, не доказателство.
    if (!небе || !небе.isConnected) небе = document.querySelector('.sky');
    if (!небе) return;
    var трябва = покрито();
    if (небе.classList.contains(КЛАС) === трябва) return;
    небе.classList.toggle(КЛАС, трябва);
    небеСпряно = трябва;
  }
  document.addEventListener('visibilitychange', сверинебе);
  // стаята се отваря и затваря през същия бутон-щрак; един наблюдател върху
  // атрибута `hidden` е по-евтин от таймер и не пропуска програмни отваряния
  function закачи() {
    for (var i = 0; i < ПОКРИВАЩИ.length; i++) {
      var о = document.getElementById(ПОКРИВАЩИ[i]);
      if (о && !о.__blНебе) {
        о.__blНебе = 1;
        new MutationObserver(сверинебе).observe(о, { attributes: true, attributeFilter: ['hidden', 'style', 'class'] });
      }
    }
    сверинебе();
  }
  setTimeout(закачи, 1200);
  setTimeout(закачи, 3500);
  // и три сверки по петите на трите обхода — първата присъда да не закъснее
  setTimeout(сверѝГеометрично, 300);
  setTimeout(сверѝГеометрично, 1500);
  setTimeout(сверѝГеометрично, 3800);

  window.BL_ИЗВЪН = {
    небе_спряно: function () { return небеСпряно; },
    сверѝ: function () { сверѝГеометрично(); return { записани: записаниЕл.length, спрени: спрени }; },
    наблюдавани: function () { return наблюдавани; },
    спрени_сега: function () { return спрени; },
    прегледай_пак: function (корен) { запиши(корен); return наблюдавани; },
    изключи: function () {
      набл.disconnect();
      var в = document.querySelectorAll('.' + КЛАС);
      for (var i = 0; i < в.length; i++) в[i].classList.remove(КЛАС);
      спрени = 0;
      return 'наблюдението е спряно, всичко пак се движи';
    },
    // числото, което има значение: колко ВСЪЩНОСТ вървят сега
    мери: function () {
      var вървят = 0, всички = 0;
      var e = document.querySelectorAll('*');
      for (var i = 0; i < e.length; i++) {
        var cs = getComputedStyle(e[i]);
        if (cs.animationName === 'none') continue;
        всички++;
        if (cs.animationPlayState === 'running') вървят++;
      }
      return { с_анимация: всички, вървят: вървят, спрени_от_мен: спрени,
               наблюдавани: наблюдавани, фиксирани_пропуснати: пропуснатиФиксирани };
    }
  };
})();
