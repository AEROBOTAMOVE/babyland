(function () {
  'use strict';

  // 🔴 05.08: този номер е ВТОРИЯТ етаж на кеша — index.html не го вижда.
  //    Десет файла в lib/ бяха пренаписани днес, а LV стоеше на 37:
  //    върналата се майка щеше да чете СТАРИТЕ статии от кеша.
  //    Пипнеш ли каквото и да е в lib/, вдигни и това число.
  // 🔴 05.08 (скептикът): LV беше вдигнато на 38 в 16:45:16, а lib/index.json
  //    (16:46:35) и lib/tools-1.json (16:47:12) са писани СЛЕД това — тоест
  //    новите статии (№373 „без месо", №375 „припознаване") и записите им в
  //    индекса стоят зад вече издаден номер 38. Който е заредил приложението в
  //    тази пролука, държи старите файлове в кеша и няма как да ги види.
  //    Измерено по времената на файловете, не предположено. Път назад: '38'.
  // 🔴 05.08 (СКЕПТИКЪТ): lib/tools-1.json пипнат пак (№214, двете останали
  //    статии без изречение към майката) → номерът се вдига, иначе върналата се
  //    майка чете старото от кеша. ПЪТ НАЗАД: '39'.
  const LV = '40';            // версия на библиотеката (кеш-бюст)
  let index = null;          // items от lib/index.json
  const bundles = {};        // име на пакет → Promise<{id: body}>
  let loading = null;

  function fetchBundle(f) {
    if (!bundles[f]) {
      bundles[f] = fetch('lib/' + f + '?v=' + LV).then(r => r.json()).catch(() => { delete bundles[f]; return {}; });
    }
    return bundles[f];
  }

  function init() {
    if (loading) return loading;
    loading = fetch('lib/index.json?v=' + LV)
      .then(r => r.json())
      .then(data => {
        index = data.items || [];
        // стъбчета в четеца — подредени по ТОП ТЪРСЕНИЯ (ранг от реалните
        // майчини въпроси) + локална популярност (кое мама отваря най-често)
        const opens = (() => { try { return JSON.parse(localStorage.getItem('bl_lib_opens')) || {}; } catch (e) { return {}; } })();
        const hot = it => (it.p || 20) + (opens[it.id] || 0) * 8;
        const arr = window.BL_ARTICLES_DATA;
        if (arr) {
          index.slice().sort((a, b) => hot(b) - hot(a)).forEach(it => {
            arr.push({
              id: it.id, room: it.r, title: it.t, emoji: it.e, cat: it.c || '',
              tags: (it.g ? it.g.split(', ').filter(Boolean) : []).slice(0, 3),
              summary: it.s || 'От Голямата библиотека',
              keys: it.k || '',                    // рафтът търси и в тях
              lib: true,
              source: 'Голямата библиотека 📚 · образователно — не замества лекар.',
              load: () => {
                try { // броим отварянията — списъкът се учи от мама
                  const o = JSON.parse(localStorage.getItem('bl_lib_opens')) || {};
                  o[it.id] = (o[it.id] || 0) + 1;
                  localStorage.setItem('bl_lib_opens', JSON.stringify(o));
                } catch (e) {}
                return fetchBundle(it.f).then(b => b[it.id]);
              }
            });
          });
        }
        return index;
      })
      .catch(() => { loading = null; return []; });
    return loading;
  }

  // 🔤 КОРЕНИТЕ НА ДУМИТЕ — една дефиниция за цялото приложение.
  //    Изнесена от search(), за да я ползва и търсачката в рафта
  //    (articles.js), която досега търсеше с гол `includes`: „спане“ не
  //    намираше „Сънят по месеци“, „колика“ не намираше „Колики“, и мама
  //    виждаше „Няма съвпадение“ върху 223 статии. (армия 22.07)
  //    5, не 4 букви: с 4 „колики“ ставаше „коли“ и хващаше „КОЛАн“ от
  //    статията за столчето в колата. По-късите думи си остават цели.
  const ЕСК = /[.*+?^${}()|[\]\\]/g;

  // 🗣️ ДУМИТЕ НА МАЙКАТА → думите в заглавията. Мама пише „спане“, статията
  //    се казва „Сънят по месеци“; тя пише „аки“, а вътре е „изхождане“.
  //    Никакво рязане на корени не свързва тези две — трябва речник.
  //    Двупосочен е: който и от двата варианта да напише, намира и другия.
  const СИНОНИМИ = [
    ['спане', 'сън', 'спи', 'приспиване', 'заспива'],
    ['кърмя', 'кърмене', 'кърма', 'бозая', 'суче'],
    // ⚠️ „ако“ НЕ влиза тук — то е и съюз и вадеше „Бабини деветини: АКО
    //    бебето хърка“ на всяко търсене за изхождане.
    ['аки', 'изхождане', 'изпражнени', 'какане', 'акане'],
    ['пишка', 'урина', 'уриниране', 'пелена'],
    ['повръща', 'връща', 'бълва', 'изхвърля'],
    ['колика', 'колики', 'газове', 'плач'],
    ['зъби', 'зъбки', 'никнене', 'зъбче'],
    ['температура', 'треска', 'градуса', 'горещ'],
    ['обрив', 'пъпки', 'изрив', 'подсичане'],
    ['захранване', 'твърда храна', 'първа храна', 'лъжичка'],
    ['шише', 'адаптирано', 'формула', 'мляко'],
    ['количка', 'столче', 'кошче', 'бебеносене'],
    ['ваксина', 'имунизация', 'имунизационен'],
    ['тръшка', 'истерия', 'инат', 'каприз'],
    ['проговори', 'говор', 'дума', 'приказва'],
    ['ходи', 'прохождане', 'стъпки', 'прави стъпки']
  ];
  function разшири(дума) {
    const из = [дума];
    СИНОНИМИ.forEach(гнездо => {
      if (гнездо.some(с => дума.startsWith(с.slice(0, 4)) || с.startsWith(дума.slice(0, 4)))) {
        гнездо.forEach(с => { if (из.indexOf(с) < 0) из.push(с); });
      }
    });
    return из;
  }

  function роднини(думи, меко) {
    return думи.map(w => {
      const варианти = разшири(w);
      const части = [];
      варианти.forEach(v => {
        // меко = по-къс корен (за втори опит, когато строгият не намери нищо).
        // 5, не 4 по подразбиране: с 4 „колики“ ставаше „коли“ и хващаше
        // „КОЛАн“ от статията за столчето в колата.
        const к = v.slice(0, Math.max(меко ? 4 : 5, v.length - 2));
        const alt = к.includes('о') ? к.replace(/о([^о]*)$/, 'а$1')
                  : (к.includes('а') ? к.replace(/а([^а]*)$/, 'о$1') : null);
        [к, alt].forEach(x => { if (x && части.indexOf(x) < 0) части.push(x); });
      });
      // „начало на низ ИЛИ след небуквен знак“ — \b не важи за кирилица
      return new RegExp('(^|[^а-яa-z0-9])(' + части.map(x => x.replace(ЕСК, '\\$&')).join('|') + ')');
    });
  }

  // ── търсене за помощничките: върни най-близките статии ──
  const norm = s => (s || '').toLowerCase().replace(/[^\wа-яё\s]/gi, ' ').replace(/\s+/g, ' ').trim();
  function search(q, room, n) {
    if (!index) return [];
    // 🤍 22.07 (мега одит, критично): на „не ми се живее“ приложението
    // сервираше каталог от статии („Злоядо дете, отказ от храна“). Тежкото
    // изречение НИКОГА не получава списък за четене — то има свой път през
    // флаговете. Тук библиотеката просто мълчи.
    try { if (window.BL_MOTHERFLAG && BL_MOTHERFLAG(q)) return []; } catch (e) {}
    // БП35 (одит-флот П23): прагът беше >3 и режеше важни къси български думи —
    // „сън", „газ", „зъб", „ухо", „око", „нос". Сваляме на >2 (пазим 3-буквените,
    // махаме само шума „на/за/и"). За 3-буквена дума коренът е самата дума.
    const words = norm(q).split(' ').filter(w => w.length > 2);
    if (!words.length) return [];
    // 🔍 22.07 (жива обиколка, реален бъг): търсенето за „колики“ връщаше
    //   „Изгаряния и попарвания“ и „Пътна безопасност“ ПРЕДИ статията за
    //   колики. Причината е двойна: коренът се режеше на 4 букви („колики“ →
    //   „коли“), после о/а редуването го правеше „кали“ — и `includes` го
    //   намираше по средата на думата „хими-КАЛИ“. Затова сега коренът се
    //   търси само в НАЧАЛОТО на дума. „изгори“ → „изга“ пак хваща
    //   „ИЗГАряния“, но „кали“ вече не се крие вътре в химикали.
    //   Regex-ите се правят веднъж за заявката, не 822 пъти.
    const корени = роднини(words);
    const scored = [];
    for (const it of index) {
      let sc = 0;
      // БП34: търсим и в подзаглавието (s), не само в заглавието и ключовете —
      // мама често пише с думи от резюмето. Нормализираме и ключовете.
      const hayT = norm(it.t), hayK = norm(it.k || ''), hayS = norm(it.s || '');
      // 22.07: „самота“ извеждаше „Зъбките: как се пазят от САМОТо начало“
      // наравно със „Самотата насред пълната къща“ — и печелеше редът в
      // индекса. Думата, с която заглавието ЗАПОЧВА, е темата на статията;
      // същата дума в средата е случайност. Затова началото тежи повече.
      const начало = hayT.split(' ').slice(0, 3).join(' ');
      корени.forEach(re => {
        if (re.test(hayT)) sc += re.test(начало) ? 4 : 3;
        else if (re.test(hayK)) sc += 2;
        else if (re.test(hayS)) sc += 1;
      });
      if (!sc) continue;
      if (it.r === room) sc *= 1.5;
      scored.push([sc, it]);
    }
    scored.sort((a, b) => b[0] - a[0]);
    // 🕳️ 22.07 (мега одит, критично): нямаше праг — ЕДНА точка от подзаглавие
    // стигаше, за да се сервира статия. Затова „не ми се живее“ получаваше
    // каталог („Злоядо дете, отказ от храна“). По-добре мълчание, отколкото
    // подигравка: искаме или попадение в заглавие/ключове (3 или 2 точки),
    // или две отделни думи да са улучили.
    const праг = scored.filter(x => x[0] >= 2);
    // 22.07: библиотеката има 14 групи почти-еднакви статии (два пъти „круп“,
    // три пъти „изцедена кърма“…). Мама питаше веднъж и получаваше същото
    // нещо, преразказано — вместо три различни гледни точки. Тук не трием
    // нищо: просто не показваме втори резултат, който повтаря първия.
    const СТОП = /^(и|или|на|в|за|от|с|със|до|как|кога|защо|кое|какво|ли|не|да|при|след|преди|през|без|по)$/;
    const същност = t => new Set(norm(t).split(' ').filter(w => w.length > 3 && !СТОП.test(w)).slice(0, 6));
    const повтаря = (a, b) => {
      if (!a.size || !b.size) return false;
      let общи = 0; a.forEach(w => { if (b.has(w)) общи++; });
      return общи / Math.min(a.size, b.size) >= 0.75;
    };
    const избрани = [], техните = [];
    for (const [, it] of праг) {
      const с = същност(it.t);
      if (техните.some(п => повтаря(с, п))) continue;
      избрани.push(it); техните.push(с);
      if (избрани.length >= (n || 3)) break;
    }
    return избрани;
  }

  function count() { return index ? index.length : 0; }

  // зареждаме индекса тихо, след като страницата си отдъхне
  if (document.readyState === 'complete') setTimeout(init, 800);
  else window.addEventListener('load', () => setTimeout(init, 800));

  // 04.08: запис в kb.js вече може да ПОСОЧИ статията си изрично (поле `lib`).
  // Автоматичното търсене е добро за общите въпроси, но при тежка тема то
  // налучква — проверено: на „детето ми може да е аутист“ подаде „Ясла/градина“,
  // защото трите статии за аутизма живеят в друга стая и филтърът ги изряза.
  function поId(id) { return index ? (index.find(x => x.id === id) || null) : null; }

  window.BL_LIB = { init, search, count, fetchBundle, роднини, поId };
})();
