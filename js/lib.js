  //    пасва() отдавна пази гнездата с ОКОНЧАНИЯ („спи“ да не отваря съня на
  //    „спира“), но САМИЯТ регекс нямаше такъв пазач и си остана чист префикс.
  //    Измерено наживо, 748 статии, „бебето не спи“:
  //      корен „спи“ → „Кенгуру: СПИсание, предавания“ и „Административни
