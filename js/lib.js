  //    ПЪТ НАЗАД: изтрий ОПАШКИ и `+ (ОПАШКИ[x] || '')` по-долу.
  const ОПАШКИ = { 'мед': '(?!и|ал)' };

  // меко = по-къс корен (за втори опит, когато строгият не намери нищо).
