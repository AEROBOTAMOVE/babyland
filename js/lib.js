  //    `всичко` е старият общ регекс — articles.js го ползва през роднини().
  function двойки(думи, меко) {
    return думи.map(w => {
      const варианти = разшири(w);          // [самата дума, ...синонимите ѝ]
      const свои = [], чужди = [];
      // 🔴 19.08: О/А РЕДУВАНЕТО Е ДОГАДКА, НЕ ДУМАТА НА МАЙКАТА. корениНа()
      //    връща два корена — истинския и един с разменена гласна („мога" →
      //    „мага"). Вторият е точно такова налучкване, каквото е и синонимът
      //    (коментарът горе го знае: „мага" → „МАГАрешка кашлица"), но стоеше
      //    в `свои` с ПЪЛНА тежест. Сега сяда при чуждите, тоест 0.55.
      //    ⚠️ Само РЕДЪТ: `всичко` = свои+чужди е непокътнат, значи прагът и
      //    articles.js през роднини() виждат същото както преди.
      //    ПЪТ НАЗАД: върни `(i === 0 ? свои : чужди)` и махни `ki`.
      варианти.forEach((v, i) => корениНа(v, меко).forEach((x, ki) => {
        if (свои.indexOf(x) >= 0 || чужди.indexOf(x) >= 0) return;
        (i === 0 && ki === 0 ? свои : чужди).push(x);
      }));
      return {
        точен: регекс(свои),
        разширен: чужди.length ? регекс(чужди) : null,
        всичко: регекс(свои.concat(чужди))
      };
    });
  }
  // ПУБЛИЧНАТА врата остава дума → ЕДИН регекс (articles.js разчита на това).
  function роднини(думи, меко) { return двойки(думи, меко).map(д => д.всичко); }

  // ── търсене за помощничките: върни най-близките статии ──
  const norm = s => (s || '').toLowerCase().replace(/[^\wа-яё\s]/gi, ' ').replace(/\s+/g, ' ').trim();
  // Служебните думи — нито тема на въпроса, нито тема на статия. Ползват се на
  // ДВЕ места: изхвърлят се от заявката (за да не стават корени) и не се броят,
  // когато се мери дали две заглавия си повтарят същността.
  const СТОП = /^(и|или|на|в|за|от|с|със|до|как|кога|защо|кое|какво|ли|не|да|при|след|преди|през|без|по)$/;
  function search(q, room, n) {
    if (!index) return [];
    // 🤍 22.07 (мега одит, критично): на „не ми се живее“ приложението
    // сервираше каталог от статии („Злоядо дете, отказ от храна“). Тежкото
    // изречение НИКОГА не получава списък за четене — то има свой път през
    // флаговете. Тук библиотеката просто мълчи.
    try { if (window.BL_MOTHERFLAG && BL_MOTHERFLAG(q)) return []; } catch (e) {}
    // БП35 (одит-флот П23): прагът беше >3 и режеше важни къси български думи —
    // „сън", „газ", „зъб", „ухо", „око", „нос". Сваляме на >2 (пазим 3-буквените,
    // махаме само шума „на/за/и"). За 3-буквена дума коренът е самата дума.
    let words = norm(q).split(' ').filter(w => w.length > 2);
    if (!words.length) return [];
    // 🔴 11.08: ПРЕДЛОГЪТ НЕ Е ТЕМА. „при“ е 3 букви — минаваше филтъра горе и
    //    ставаше пълноправен корен. А коренът се търси в НАЧАЛОТО на дума:
    //    „при“ пасва на „ПРИспиване“, „ПРИвързаност“, „ПРИготвяне“,
    //    „ПРИятелства“. Преброено върху живия индекс (748 статии): коренът „при“
    //    стои в 111 ЗАГЛАВИЯ и в 279 статии общо — всяка трета — и всяка от тях
    //    взимаше по 4 точки, колкото и самата тема. Дори след пазача за къси
    //    корени по-долу „при“ остава в 78 заглавия (то е и самостоятелна дума в
    //    „Обриви ПРИ бебе“), тоест пазачът сам не стига.
    //    Измерено наживо (стар двигател):
    //      „слинг при бебето“  → „ПРИятелствата се менят след бебето“,
    //                            „Температура ПРИ бебе/дете“, „Адаптирано мляко“
    //                            — нула за слинга, при положение че голото
    //                            „слинг“ намира двете статии;
    //      „фимоза при бебето“ → същите три, макар за фимоза да няма НИТО ЕДНА
    //                            статия. По-добре мълчание, отколкото подигравка.
    //    Списъкът е същият СТОП, с който се мери и повторението по-долу.
    //    ⚠️ Ако всичко в изречението е стоп-дума, НЕ мълчим — връщаме старото
    //    поведение, за да не изчезне отговор, който досега е идвал.
    //    ПЪТ НАЗАД: изтрий тези три реда (`const същински` … `words = ...`).
    const същински = words.filter(w => !СТОП.test(w));
    if (същински.length) words = същински;
    // 🔍 22.07 (жива обиколка, реален бъг): търсенето за „колики“ връщаше
    //   „Изгаряния и попарвания“ и „Пътна безопасност“ ПРЕДИ статията за
    //   колики. Причината е двойна: коренът се режеше на 4 букви („колики“ →
    //   „коли“), после о/а редуването го правеше „кали“ — и `includes` го
    //   намираше по средата на думата „хими-КАЛИ“. Затова сега коренът се
    //   търси само в НАЧАЛОТО на дума. „изгори“ → „изга“ пак хваща
    //   „ИЗГАряния“, но „кали“ вече не се крие вътре в химикали.
    //   Regex-ите се правят веднъж за заявката, не 822 пъти.
    const дв = двойки(words);
    // ⚖️ 11.08: „бебе“ е думата, която мама пише най-често — и тъкмо затова тя
    //    не казва нищо за темата. Тежеше колкото „хърка“ и печелеше равенството
    //    по ред в индекса: „бебето хърка“ → „Температура бебета деца кога е
    //    спешно“, „окото на бебето е зачервено“ → пак температурата, а статията
    //    за конюнктивита оставаше втора. Тук тя тежи четвърт — но само ако в
    //    изречението има и ДРУГА дума; на голото „бебето“ нищо не се сваля,
    //    иначе прагът по-долу би отрязал всичко и мама остава без нито една
    //    страница. ПЪТ НАЗАД: изтрий тежест и върни sc += ... без множител.
    const общи = words.map(w => /^бебе/.test(w));
    const имаДруга = общи.some(g => !g);
    const тежест = i => (имаДруга && общи[i] ? 0.25 : 1);
    // 🔴 11.08: РЯДКАТА ДУМА ТЕЖИ ПОВЕЧЕ ОТ ЧЕСТАТА — измерено, не отсъдено.
    //    Дотук единственото изключение беше ръчното „бебе“ (горе). Но същият
    //    дефект имаше и другаде: „слинг за новородено“ → трите първи бяха
    //    „Скрининги при новородено“, „Новородено хълца…“, „Новородено
    //    трепери…“ и НУЛА за слинга. Не защото слингът бърка нещо: и двете
    //    страни имаха точно по 4 точки и печелеше редът в индекса. Преброено
    //    върху живия индекс (748): „новороде“ стои в 24 заглавия / 35 статии,
    //    „слинг“ — в 2 / 4. Деветкратна разлика, а тежаха еднакво.
    //    Общата дума не бива да носи колкото рядката. Затова редът се
    //    претегля с рядкостта (idf), пресметната ВЪРХУ ТОЗИ ИНДЕКС в същата
    //    обиколка — не с речник, който ще остарее.
    //    ⚠️ Рядкостта пипа само РЕДА. Прагът долу гледа стария сбор (`sc`) —
    //    иначе смъкването на теглата щеше да отреже статии, които днес
    //    минават, и мама щеше да остане без страница. Кое ВЛИЗА се решава
    //    както досега; кое е ПЪРВО — вече по темата.
    const N = index.length || 1;
    const дф = дв.map(() => 0);            // в колко статии стои самата дума
    const scored = [];
    for (const it of index) {
      let sc = 0;
      // БП34: търсим и в подзаглавието (s), не само в заглавието и ключовете —
      // мама често пише с думи от резюмето. Нормализираме и ключовете.
      const hayT = norm(it.t), hayK = norm(it.k || ''), hayS = norm(it.s || '');
      // 22.07: „самота“ извеждаше „Зъбките: как се пазят от САМОТо начало“
      // наравно със „Самотата насред пълната къща“ — и печелеше редът в
      // индекса. Думата, с която заглавието ЗАПОЧВА, е темата на статията;
      // същата дума в средата е случайност. Затова началото тежи повече.
      const думиТ = hayT.split(' ');
      const начало = думиТ.slice(0, 3).join(' ');
      const база = re => re.test(hayT) ? (re.test(начало) ? 4 : 3)
                       : (re.test(hayK) ? 2 : (re.test(hayS) ? 1 : 0));
      // 🔴 19.08 (дупката при ЕДНА дума): „в първите ТРИ думи" беше един кош —
      //    и двете статии вземаха по 4 точки, а редът се решаваше от мястото в
      //    index.json. Измерено на 158 статии: при 55 от 56 загубени първи места
      //    И ЦЕЛТА, И КРАДЕЦЪТ имаха думата в първите три думи, и в 56 от 56 бяха
      //    в СЪЩАТА стая — тоест сборът им беше буквално равен.
      //    Примери: „обриви" → „Обриви при бебе…" (дума 1) губеше от „Кожа ОБРИВИ
      //    кожни…" (дума 2); „бебе" → „Бебе и малко дете при бедствия" (дума 1)
      //    губеше от „Температура при БЕБЕ и дете" (дума 3).
      //    Заглавието ЗАПОЧВА с темата си — колкото по-навътре е думата, толкова
      //    по-случайно е попадението. Затова кошът се разчита на стъпала.
      //    ⚠️ Само РЕДЪТ: 4.0/3.8/3.6 не излизат извън стария коридор (3, 4],
      //    така че думата насред заглавието (3) и думата в ключовете (2) си
      //    остават под тях. Прагът (`sc`) продължава да брои старите цели числа.
      //    ПЪТ НАЗАД: върни `бази.push([бТ, бР])` и изтрий думиТ/фино.
      //    ⚠️ ПРОБВАНО И ВЪРНАТО (19.08): стъпалата да продължат и СЛЕД третата
      //    дума (3.5 → 3.05, за да се различи „Сън 6-12 МЕСЕЦА…" от
      //    „…прилепчивост 6-36 МЕСЕЦА"). Една дума: 80% → 80% (нищо); три думи:
      //    100% → 99%. Не помага и вреди — не се връща без ново измерване.
      const фино = (re, б) => {
        if (б < 4) return б;                      // не е в първите три думи
        for (let j = 0; j < 3 && j < думиТ.length; j++) if (re.test(думиТ[j])) return 4 - j * 0.2;
        return б;
      };
      const бази = [];
      дв.forEach((д, i) => {
        const бТ = база(д.точен);
        const бР = д.разширен ? база(д.разширен) : 0;
        if (бТ) дф[i]++;
        // 🔴 19.08: ЦЯЛАТА ДУМА Е ПО-ДОБРА ОТ КОРЕНА ѝ. Коренът се реже на 5
        //    букви, тоест „кърмене" се търси като „кърме" и пасва еднакво на
        //    „КЪРМЕНЕ - засукване…" и на „КЪРМЕНЕто: честно за проблемите".
        //    Измерено: точно тези две си разменяха първото място, същото и
        //    „гърнето" срещу „Гърне и тоалетни навици". Ако мама е написала
        //    думата и тя стои в заглавието ЦЯЛА — това е по-точно попадение.
        //    Стойността е 0.4 = точно ДВЕ стъпала от 0.2, тоест цялата дума
        //    струва колкото две места напред в заглавието: „112 в БЪЛГАРИЯ"
        //    (цяла дума, трета) настига „БЪЛГАРски блогове" (корен, първа).
        //    Мерено на трите мерки: 0.2/0.3/0.35 не мърдат нищо, от 0.4 нагоре
        //    се обръща един случай и повече не се променя — тоест 0.4 е прагът,
        //    не нагласено число.
        //    ПЪТ НАЗАД: изтрий реда с `+= 0.4`.
        let фТ = фино(д.точен, бТ);
        if (бТ >= 3 && думиТ.indexOf(words[i]) >= 0) фТ += 0.4;
        бази.push([фТ, д.разширен ? фино(д.разширен, бР) : бР]);
        // Math.max е ТОЧНО старото поведение: единият общ регекс даваше
        // най-силното попадение измежду всички корени на думата.
        sc += Math.max(бТ, бР) * тежест(i);
      });
      if (!sc) continue;
      if (it.r === room) sc *= 1.5;
      scored.push([sc, it, бази, it.r === room, 0]);
    }
    // втора обиколка: сега вече знаем колко честа е всяка дума в индекса
    const рядкост = дф.map(d => Math.max(0.05, Math.log(N / (1 + d))));
    for (const р of scored) {
      let ранг = 0;
      р[2].forEach((б, i) => {
        // синонимът е ДОГАДКА за думата на майката, не самата дума: „колики“
        // отваря „плач“ и заглавие, което почва с „плач“, взимаше същите 4
        // точки като заглавие, което почва с „колики“. Затова разширението
        // тежи по-малко от точното попадение (0.55: попадение в началото на
        // заглавие през синоним = 2.2 — под 3-те на думата насред заглавието
        // и над 2-те на думата в ключовете).
        ранг += Math.max(б[0], б[1] * 0.55) * тежест(i) * рядкост[i];
      });
      р[4] = р[3] ? ранг * 1.5 : ранг;
    }
    // 🔴 19.08: ПОСЛЕДНАТА ДУМА ПРИ ПЪЛНО РАВЕНСТВО. Когато мама напише една
    //    дума, десет статии могат да са еднакво прави: „Ясла: адаптация…",
    //    „Ясла и градина: инфекциите…", „Ясла/градина 0-3: конюнктивит…".
    //    Дотук редът между тях се решаваше от мястото в index.json — тоест от
    //    нищо. Сега решава `p`, рангът от реалните майчини въпроси, който
    //    приложението вече ползва, за да подрежда рафта в четеца (init() горе).
    //    ⚠️ Трети критерий, не събираемо: включва се САМО ако и рангът, и
    //    сборът са ТОЧНО равни, тоест не може да пребори никакво истинско
    //    попадение. ПЪТ НАЗАД: махни третото `||`.
    scored.sort((a, b) => (b[4] - a[4]) || (b[0] - a[0]) || ((b[1].p || 20) - (a[1].p || 20)));
    // 🕳️ 22.07 (мега одит, критично): нямаше праг — ЕДНА точка от подзаглавие
    // стигаше, за да се сервира статия. Затова „не ми се живее“ получаваше
    // каталог („Злоядо дете, отказ от храна“). По-добре мълчание, отколкото
    // подигравка: искаме или попадение в заглавие/ключове (3 или 2 точки),
    // или две отделни думи да са улучили.
    const праг = scored.filter(x => x[0] >= 2);
    // 22.07: библиотеката има 14 групи почти-еднакви статии (два пъти „круп“,
    // три пъти „изцедена кърма“…). Мама питаше веднъж и получаваше същото
    // нещо, преразказано — вместо три различни гледни точки. Тук не трием
    // нищо: просто не показваме втори резултат, който повтаря първия.
    const същност = t => new Set(norm(t).split(' ').filter(w => w.length > 3 && !СТОП.test(w)).slice(0, 6));
    const повтаря = (a, b) => {
      if (!a.size || !b.size) return false;
      let общи = 0; a.forEach(w => { if (b.has(w)) общи++; });
      return общи / Math.min(a.size, b.size) >= 0.75;
    };
    const избрани = [], техните = [];
    for (const [, it] of праг) {
      const с = същност(it.t);
      if (техните.some(п => повтаря(с, п))) continue;
      избрани.push(it); техните.push(с);
      if (избрани.length >= (n || 3)) break;
    }
    return избрани;
  }

  function count() { return index ? index.length : 0; }

  // зареждаме индекса тихо, след като страницата си отдъхне
  if (document.readyState === 'complete') setTimeout(init, 800);
  else window.addEventListener('load', () => setTimeout(init, 800));

  // 04.08: запис в kb.js вече може да ПОСОЧИ статията си изрично (поле `lib`).
  // Автоматичното търсене е добро за общите въпроси, но при тежка тема то
  // налучква — проверено: на „детето ми може да е аутист“ подаде „Ясла/градина“,
  // защото трите статии за аутизма живеят в друга стая и филтърът ги изряза.
  function поId(id) { return index ? (index.find(x => x.id === id) || null) : null; }

  window.BL_LIB = { init, search, count, fetchBundle, роднини, поId };
