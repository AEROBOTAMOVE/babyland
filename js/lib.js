  //    Същото и от о/а редуването: „мога“ → „мага“ → „МАГАрешка кашлица“,
  //    „Големи бебешки МАГАзини“ на въпроса „след раждането не мога да спя“.
  //    Затова: корен до 4 букви (това е ЦЯЛАТА дума, не отрязано стъбло) пасва
  //    само ако след него стои българско окончание и думата свършва. По-дългите
  //    корени си остават префикси — „колик“ трябва да хваща и „коликите“.
  //    ПЪТ НАЗАД: върни `const пазач = ''` (един ред по-долу).
  const РЕГ_ОКОНЧАНИЯ = 'а|о|е|и|я|ъ|т|м|ш|ат|ят|ът|та|то|те|ме|на|не|ки|ни|ха|ла|ло|ли|ва|ове|ите|ята|ото|ена|ища';
  // „начало на низ ИЛИ след небуквен знак“ — \b не важи за кирилица
  function регекс(части) {
    return new RegExp('(^|[^а-яa-z0-9])(' + части.map(x => {
      const пазач = x.length <= 4 ? '(?:' + РЕГ_ОКОНЧАНИЯ + ')?(?![а-яa-z0-9])' : '';
      return x.replace(ЕСК, '\\$&') + (ОПАШКИ[x] || '') + пазач;
    }).join('|') + ')');
  }

