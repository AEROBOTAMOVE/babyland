  //      „колики“ → регексът беше
  //         (колик|калик|газов|газав|плач|плоч|колич|калич|столч|сталч|кошче|кашче)
  //      тоест въпросът за колики търсеше и СТОЛЧЕ, и КОЛИЧКА, и КОШЧЕ —
  //      защото пасва() отваря гнездо по 4-буквено начало и „колики“.slice(0,4)
  //      = „коли“ ≡ началото на „количка“. Всичките получаваха по 4 точки —
