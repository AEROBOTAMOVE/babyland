// ═══════════════════════════════════════════════════════════
// JOURNAL — РЕДЪТ В ДНЕВНИКА НА МАМА 📖👑
// Короната на приложението заслужава собствена подредба:
// 6 смислени кътчета вместо „Още“-кофа, изписано съдържание,
// без дубликати. Всичко тук е за МАМА, не за бебето.
// ═══════════════════════════════════════════════════════════
(function () {
  'use strict';
  const ROOM = 'Дневник на мама';

  // ── шестте кътчета на стаята (авторски ред, не по употреба) ──
  const SECTIONS = [
    ['jd', '💜 Днес за теб'],
    ['jc', '🌬️ Когато е тежко'],
    ['jw', '✍️ Пиши и помни'],
    ['jp', '🌌 Твоите картини'],
    ['jt', '📸 Съкровищницата'],
    ['jl', '🔒 Лично']
  ];

  // ── кое къде отива (по заглавие) ──
  // „Пиши и помни" (jw, default) беше кофа — тежките/картинните карти падаха
  // там. Пращаме ги по места (одит-флот П23): дишане/плач/подреди → jc; двете
  // годишни изгледи → jp. „Тук може да плачеш" вече не стои в секция „ПОМНИ".
  const RULES = [
    [/как си днес|време за мен|подканата на деня|как е тялото/i, 'jd'],
    [/дъх|дишай|скъсай листа|пукни балончето|банка с идеи|разпускане|тук може да плачеш|подреди мислите/i, 'jc'],
    [/свободна страница|три хубави|днес успях|писма между нас|писмо за месеца|капсули/i, 'jw'],
    [/съзвездие|годината ти в думи|годината ти в един|същият ден|месецът ти|огледало|медальон/i, 'jp'],
    [/снимка на деня|гласови|историята ни|годишник|сподели|споменче/i, 'jt'],
    [/ключалка|пин/i, 'jl']
  ];
  const match = t => (RULES.find(([re]) => re.test(t)) || [null, 'jw'])[1];

  window.BL_ROOM_SECTIONS = window.BL_ROOM_SECTIONS || {};
  window.BL_ROOM_SECTIONS[ROOM] = { sections: SECTIONS, match, keepOrder: true, toc: true };

  // ── чистене на дублажа: „Месечното огледало“ и „Месецът ти в числа“ ──
  // казваха едно и също; старото огледало отпада, новото поема всичко.
  const base = window.ROOM_FEATURES && window.ROOM_FEATURES[ROOM];
  if (base) {
    window.ROOM_FEATURES[ROOM] = root => {
      base(root);
      const cards = [...root.querySelectorAll(':scope > .jr-card')];
      const mirror = cards.find(c => /Месечното огледало/.test(c.textContent));
      const numbers = cards.find(c => /Месецът ти в числа/.test(c.textContent));
      if (mirror && numbers) mirror.remove(); // дубликат — вън
      // едничкото останало получава пълното име
      const keep = numbers || mirror;
      if (keep) {
        const t = keep.querySelector('.jr-title');
        if (t) t.innerHTML = 'Месецът ти в числа 📊 <span class="jr-sub">твоят месец с един поглед — Луна брои вместо теб</span>';
      }
      // подзаглавия там, където липсват (мамата да знае какво е това)
      const SUBS = {
        'Скъсай листа': 'напиши гнева и го скъсай — никой няма да го види',
        'Три хубави неща': 'вечерният ритуал, който сменя деня',
        'Днес успях да…': 'малките победи са истинските',
        'Пукни балончето': '30 секунди глупост — колкото да си поемеш дъх',
        'Капсули на времето': 'писмо до бъдещето — отваря се, когато кажеш',
        'Свободна страница': 'без структура, без правила — само ти'
      };
      root.querySelectorAll(':scope > .jr-card .jr-title').forEach(t => {
        if (t.querySelector('.jr-sub')) return;
        const name = [...t.childNodes].filter(n => n.nodeType === 3).map(n => n.textContent).join('').trim().replace(/[\s✍️💥🙏🎈💌📖]+$/u, '').trim();
        const key = Object.keys(SUBS).find(k => name.startsWith(k.replace('…', '')));
        if (key) t.insertAdjacentHTML('beforeend', ` <span class="jr-sub">${SUBS[key]}</span>`);
      });
    };
  }
})();
