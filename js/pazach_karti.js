//   и споделянето, И КЛЮЧАЛКАТА НА ДНЕВНИКА. Тоест един лош байт в паметта
//   заключваше цяла стая, а майката вижда празен екран без обяснение.
//
// ЗАЩО СЕ СЛУЧВА НА ВСЯКА СТАЯ, НЕ САМО ТАМ:
//   Стаите се строят с верига. 214 места в проекта правят точно това:
//       const база = window.ROOM_FEATURES[стая];
//       window.ROOM_FEATURES[стая] = root => { база(root); моето(root); };
//   Всяка нова карта се закача върху предишната. Гръмне ли ЕДНА брънка,
//   всичко СЛЕД нея не се изпълнява никога — а „след нея" са десетки карти.
//   Тоест цената на всеки бъдещ бъг в която и да е карта е ЦЯЛАТА стая.
//
// КАКВО ПРАВИ ТОЗИ ФАЙЛ:
//   Слага капан около ВСЯКА брънка в момента на закачането ѝ. Гръмне ли
