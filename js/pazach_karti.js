//   вместо всичко след нея. Понеже всяка брънка се пази поотделно, външната
//   `база(root)` се връща нормално и `моето(root)` се изпълнява.
//
// ЗАЩО Е ТОЧНО ТУК В РЕДА НА ЗАРЕЖДАНЕ:
//   js/rooms.js създава ROOM_FEATURES; всички останали го РАЗШИРЯВАТ. Този
//   файл стои между тях — след създателя, преди първия разширител. Мръдне ли
