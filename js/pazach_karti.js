(function () {
  'use strict';

  var истински = window.ROOM_FEATURES;
  if (!истински || typeof истински !== 'object') {
    // няма какво да се пази — казваме го, вместо да се правим на свършена работа
    try { console.warn('[Бейби Ленд] pazach_karti.js се зареди ПРЕДИ rooms.js — не пази нищо.'); } catch (e) {}
    return;
  }

  window.BL_КАРТИ_ГРЕШКИ = window.BL_КАРТИ_ГРЕШКИ || [];

  function обвий(име, f) {
    if (typeof f !== 'function' || f.__blПазен) return f;
    var g = function (root) {
      try { return f(root); }
      catch (e) {
        window.BL_КАРТИ_ГРЕШКИ.push({ стая: име, грешка: (e && e.message) || String(e) });
        try { console.warn('[Бейби Ленд] карта в „' + име + '" не се построи:', e); } catch (_) {}
      }
    };
    g.__blПазен = 1;
    return g;
  }

  for (var k in истински) истински[k] = обвий(k, истински[k]);

  if (typeof Proxy === 'function') {
    window.ROOM_FEATURES = new Proxy(истински, {
      set: function (цел, ключ, стойност) { цел[ключ] = обвий(String(ключ), стойност); return true; }
    });
  }

  window.BL_ПАЗАЧ_КАРТИ = {
    грешки: function () { return window.BL_КАРТИ_ГРЕШКИ.slice(); },
    пази_ли: function () { return typeof Proxy === 'function'; }
  };
})();
