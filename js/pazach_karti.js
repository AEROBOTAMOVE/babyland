//
// 🪤 КАПАНИ, ОБМИСЛЕНИ ПРЕДИ ДА СЕ НАПИШЕ:
//   · Пазенето НЕ бива да мълчи напълно — иначе утре ще крие истински бъг.
//     Затова всяка хваната грешка влиза в window.BL_КАРТИ_ГРЕШКИ и в конзолата.
//   · На МАЙКАТА не се показва нищо. Днешното поведение при същия бъг е
//     „изчезва цялата стая", тоест мълчаливо вече е — тук поне остатъкът
//     оцелява. Плашещо съобщение би било по-лошо от липсваща карта.
//   · Ако картата е успяла да сложи половин съдържание и после е гръмнала,
//     половината остава. По-добре от нищо и е видимо в списъка с грешки.
//   · Без Proxy (много стар браузър) файлът пази само вече съществуващите
//     брънки и не пречи на нищо друго.
//
// ПРОВЕРКА: node dev/test_pazach_karti.js  (гърми нарочно и в двете посоки)
// ПЪТ НАЗАД: махни реда за този файл от index.html. Нищо не зависи от него —
