(function () {
  'use strict';
  const ROOM = 'Лабораторията';

  // редът следва пътя на мама: правя опит → проверявам баба → диря следи → записвам
  const SECTIONS = [
    ['l1', '🧪 Опитите'],
    ['l2', '👵 Бабините митове'],
    ['l3', '🕵️ Следите'],
    ['l4', '📓 Тетрадката']
  ];

  const RULES = [
    [/докосване|опитът в ход|присъдата|тръгни на опит|втори опит/i, 'l1'],
    // 🔴 05.08 (одит г11, №146): обичаите нямаха правило — дори подредени, щяха
    //    да паднат по подразбиране при „🧪 Опитите". Мястото им е при бабите.
    [/митът на седмицата|къде баба позна|обичаи/i, 'l2'],
    [/какво се смени|работеше|защо се буди|числата вместо/i, 'l3'],
    [/какво знам за|досието|сподели откритие/i, 'l4']
  ];
  const match = t => (RULES.find(([re]) => re.test(t)) || [null, 'l1'])[1];

  window.BL_ROOM_SECTIONS = window.BL_ROOM_SECTIONS || {};
  window.BL_ROOM_SECTIONS[ROOM] = { sections: SECTIONS, match: match, keepOrder: true, toc: true };
})();
