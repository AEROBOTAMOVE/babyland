// 🔢 БРОЙ — числото и думата до него да не си противоречат
//
// Защо съществува (12.08, единиците и бройните форми):
//   Числото се лепеше за съществителното на сляпо, винаги в множествено:
//   „1 пъти“, „1 дни“, „1 мига“, „1 снимки“, „1 месеца“, „1 пелени“.
//   Мама с едно бебе, един ден запис и една снимка чете приложение,
//   което говори неграмотно точно за нейния случай — първия ден, когато
//   всичко е по едно. А правилото на къщата вече е изречено веднъж
//   (rooms10.js:426): „числото и думата до него не бива да си противоречат“.
//
//   Отделно от това стоеше по-опасният случай: rooms6.js лепеше „ ч.“ на
//   ЧАШИТЕ вода на мама, а „ч.“ в цялото приложение значи ЧАСА
//   (rooms8.js:223 — `мин + ' мин.' : Math.round(мин/60) + ' ч.'`).
//   „Вода (мама) 3 ч.“ се чете „три часа“, не „три чаши“.
//
//   Поправката съществуваше вече осем пъти, копирана на ръка:
//     rooms4.js:63   `data.n === 1 ? 'чаша' : 'чаши'`
//     rooms10.js:427 `часове === 1 ? 'час' : 'часа'`
//     rooms16.js:62  `бъдещи.length === 1 ? 'ден' : 'дни'`
//     women5.js:251  `n === 1 ? 'ставане' : 'ставания'`
//     river.js:282, rooms8.js:356, firstday.js:264, baby2.js:90
//   Осем копия значи осем места, които могат да се разминат. Живее тук.
//
// ПРАВИЛОТО (единствено само при точно 1):
//   Взето е от самото приложение — всичките осем вече написани поправки
//   съдят по `=== 1`, не по последната цифра. Същото казва и CLDR за
//   български (`one: i = 1 and v = 0`): 21, 101 и 1.0 не са „едно“.
//   Затова: 1 → единствено, всичко друго → бройна форма/множествено.
//   Отрицателните (разлики „−1 чаша“) се съдят по модул.
//
//   Помощникът НЕ измисля форми. Ако не му подадеш множественото и то не
//   е в РЕЧНИКА, връща подаденото — по-добре видимо еднакво, отколкото
//   измислена дума в текст, който майка чете за бебето си.
//
// ПЪТ НАЗАД: файлът само добавя window.BL_BROI. Махнеш ли реда от
// index.html, всяко място, което го ползва, пада на своя вграден резерв
// (`window.BL_BROI ? … : … === 1 ? ед : мн`) и текстът остава същият.
// ═══════════════════════════════════════════════════════════
(function () {
  'use strict';

  // Само форми, които вече са изписани някъде в приложението или са
  // безспорни. Нищо тук не е сглобено по правило — всяко е написано на ръка.
  var РЕЧНИК = {
    'чаша': 'чаши',
    'ден': 'дни',
    'нощ': 'нощи',
    'седмица': 'седмици',
    'месец': 'месеца',
    'година': 'години',
    'час': 'часа',
    'минута': 'минути',
    'път': 'пъти',
    'снимка': 'снимки',
    'миг': 'мига',
    'пелена': 'пелени',
    'хранене': 'хранения',
    'ставане': 'ставания',
    'запис': 'записа',
    'мярка': 'мерки',
    'карта': 'карти',
    'нещо': 'неща',
    'продукт': 'продукта',
    'трик': 'трика',
    'стая': 'стаи',
    'дума': 'думи'
  };

  // n → true, ако до думата стои точно едно
  function едно(n) {
    var ч = typeof n === 'number' ? n : parseFloat(String(n).replace(',', '.'));
    if (!isFinite(ч)) return false;
    return Math.abs(ч) === 1;
  }

  // само думата, без числото
  function дума(n, ед, мн) {
    if (едно(n)) return ед;
    return мн || РЕЧНИК[ед] || ед;
  }

  // числото + интервал + думата; числото се връща както е подадено
  // (за да не се променят „2.5“, „+3“ и вече форматираните низове)
  function брой(n, ед, мн) {
    return String(n) + ' ' + дума(n, ед, мн);
  }

  // самопроверка: очакваното е изписано на ръка, не сметнато от правилото
  function самопроверка() {
    var случаи = [
      [1, 'чаша', 'чаши', '1 чаша'],
      [2, 'чаша', 'чаши', '2 чаши'],
      [0, 'чаша', 'чаши', '0 чаши'],
      [-1, 'чаша', 'чаши', '-1 чаша'],   // разлика „с една по-малко“
      [-3, 'чаша', 'чаши', '-3 чаши'],
      [21, 'ден', 'дни', '21 дни'],      // CLDR bg: „едно“ е само 1
      [11, 'ден', 'дни', '11 дни'],
      [1, 'ден', null, '1 ден'],         // от РЕЧНИКА
      [5, 'ден', null, '5 дни'],
      [1, 'път', null, '1 път'],
      [3, 'път', null, '3 пъти'],
      [1, 'месец', null, '1 месец'],
      [2, 'месец', null, '2 месеца'],
      [1, 'миг', null, '1 миг'],
      [7, 'миг', null, '7 мига'],
      [1, 'снимка', null, '1 снимка'],
      [4, 'снимка', null, '4 снимки'],
      [1, 'пелена', null, '1 пелена'],
      [9, 'пелена', null, '9 пелени'],
      [1.0, 'час', null, '1 час'],
      [2.5, 'час', null, '2.5 часа'],
      [1, 'мяу', null, '1 мяу'],         // непозната дума → не се измисля
      [4, 'мяу', null, '4 мяу']          // …и в множествено пак не се измисля
    ];
    var лоши = [];
    случаи.forEach(function (с) {
      var got = брой(с[0], с[1], с[2]);
      if (got !== с[3]) лоши.push(с[0] + ' „' + с[1] + '“ → ' + got + ' (чакахме ' + с[3] + ')');
    });
    // речникът не бива да сочи дума към самата себе си (тиха загуба на форма)
    for (var k in РЕЧНИК) {
      if (РЕЧНИК[k] === k) лоши.push('речник: „' + k + '“ сочи към себе си');
    }
    return { проверени: случаи.length + Object.keys(РЕЧНИК).length,
             грешни: лоши.length, списък: лоши,
             присъда: лоши.length ? '🔴 ПАДА' : '✅ ПРЕМИНАВА' };
  }

  window.BL_BROI = брой;
  window.BL_BROI.дума = дума;
  window.BL_BROI.речник = РЕЧНИК;
  window.BL_BROI.самопроверка = самопроверка;
})();
