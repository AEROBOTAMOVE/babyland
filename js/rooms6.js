  function bagProgress(root) {
    const карта = [...root.querySelectorAll(':scope > .jr-card')]
      .find(c => /чанта/i.test(c.querySelector('.jr-title')?.textContent || ''));
    if (!карта || карта.querySelector('.bg-prog')) return;
    const обнови = () => {
      const редове = [...карта.querySelectorAll('.jr-check')];
      if (!редове.length) return;
      const готови = редове.filter(x => x.textContent.trim() === '✔').length;
      const проц = Math.round(готови / редове.length * 100);
      let p = карта.querySelector('.bg-prog');
      if (!p) { p = el('div', 'bg-prog'); карта.insertBefore(p, карта.children[1]); }
      // Б9.1: никога „липсват ти N неща“ — броим СЪБРАНОТО, не дупките.
      // Б8.6: на 100% ципът се дърпа (CSS клас bg-zipped).
      карта.classList.toggle('bg-zipped', проц === 100);
      p.innerHTML = `<div class="bg-track"><div class="bg-fill" style="width:${проц}%"></div></div>
        <p class="bg-txt">${проц === 100 ? '🎉 Чантата е готова. Сега само чакаме него. 🤍' :
          готови === 0 ? `<strong>${редове.length}</strong> неща те чакат — почваме, когато кажеш. 🧳` :
          `Събрани <strong>${готови} от ${редове.length}</strong> — добра работа. 💜`}</p>`;
    };
    обнови();
    карта.addEventListener('click', () => setTimeout(обнови, 60));
  }

