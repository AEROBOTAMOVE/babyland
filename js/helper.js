  function pregLevel(text, room) {
    if (!KB.pregFlags) return false;
    const q = normalize(String(text || ''));
    if (/лохи|след раждане|следродил/.test(q)) return false;   // има си статия
    const бременна = (room === 'Бременност') ||
      (window.BL_EXPECT ? !!BL_EXPECT.lmp() : !!lsGet('bl_lmp', ''));
    const пауза = window.BL_EXPECT && BL_EXPECT.paused ? BL_EXPECT.paused() : false;
    return KB.pregFlags.some(f => {
      if (!phraseHit(q, f)) return false;
      if (/кърв|кръв/.test(normalize(f))) return бременна || пауза;
      return бременна;
    });
  }
