  // Това е най-честата грешка при писане с една ръка и я нямаше:
  // за горния алгоритъм разместването е ДВЕ разлики, значи пропуск.
  function разместено(a, b) {
    if (a.length !== b.length) return false;
    const d = [];
    for (let i = 0; i < a.length; i++) if (a[i] !== b[i]) { d.push(i); if (d.length > 2) return false; }
    return d.length === 2 && d[1] === d[0] + 1 && a[d[0]] === b[d[1]] && a[d[1]] === b[d[0]];
  }
