  // „темепратура“, „кърмче“, „безоница“ — една сбъркана буква и Мира казваше
  // „не знам“. Разстояние ≤1 (една замяна/вмъкване/изтриване) е достатъчно:
  // при по-хлабаво почват грешни попадения, а те са по-лоши от „не знам“.
  function близо(a, b) {
    if (a === b) return true;
    const la = a.length, lb = b.length;
    if (Math.abs(la - lb) > 1) return false;
    let i = 0, j = 0, разлики = 0;
    while (i < la && j < lb) {
      if (a[i] === b[j]) { i++; j++; continue; }
      if (++разлики > 1) return false;
      if (la > lb) i++; else if (lb > la) j++; else { i++; j++; }
    }
    return разлики + (la - i) + (lb - j) <= 1;
  }
