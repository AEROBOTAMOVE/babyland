  //    пробваме ВСЯКА възможна начална дума, не само първата. Промяната може
  //    само да ДОБАВИ попадения (никое старо не изчезва) — а несиметрията тук
  //    е ясна: цената на фалшивата тревога е едно топло изречение.
  function phraseHit(q, phrase) {
    const fw = normalize(phrase).split(' ').filter(Boolean);
    if (!fw.length) return false;
    const qw = q.split(' ');
    const pre = w => w.slice(0, Math.max(3, w.length - 1));
    for (let s = 0; s < qw.length; s++) {
      if (!qw[s].startsWith(pre(fw[0]))) continue;   // възможно начало на фразата
      let pos = s, ok = true;
      for (let k = 1; k < fw.length; k++) {
        const at = qw.findIndex((x, i) => i > pos && x.startsWith(pre(fw[k])));
        if (at === -1) { ok = false; break; }        // липсва дума → не е тази фраза
        pos = at;                                    // РЕДЪТ се пази
      }
      if (ok && (pos - s) <= fw.length + 2) return true; // и стоят близо
    }
    return false;
  }
