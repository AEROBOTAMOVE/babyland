// ═══════════════════════════════════════════════════════════════════════════
// 📶 СИЛАТА НА ТЕЛЕФОНА — един договор, който CSS и JS четат еднакво
// ═══════════════════════════════════════════════════════════════════════════
//
// ЗАЩО (07.09.2026, измерено): приложението върви с ПЪЛНА сила навсякъде.
// Измерено живо на началния екран, преди този файл:
//     542 анимирани елемента · 162 с `will-change` · 16 blur филтъра
//     нула capability tiers · `data-motion` изобщо липсваше
// CSS уважаваше `prefers-reduced-motion` (66 правила), но JS НЕ ЗНАЕШЕ за
// него — тоест цикли и таймери вървяха и при изключено движение.
//
// Наръчникът за immersive web го формулира като договор:
//     „Визуалният слой може да бъде необичаен; interaction semantics не бива."
//     „Не определяй качеството само по innerWidth."
//     „will-change е диагностична оптимизация, не CSS reset."
//
// КАКВО ПРАВИ: слага две отметки на <html>, ЕДИН ПЪТ, преди рисуването:
//     data-motion  = 'reduce' | 'full'
//     data-quality = 'low' | 'medium' | 'high'
// и ги изнася като window.BL_TIER за JS.
//
// ⚠️ ТОВА НЕ Е ЗАБРАНА, А НАСТРОЙКА. Нищо не се скрива и нищо не се изключва
//    от съдържанието — само украсата олеква. Майка на слаб телефон получава
//    СЪЩИТЕ карти, същите флагове и същите отговори.
//
// ⚠️ ЗАЩО НЕ ПО ШИРОЧИНА НА ЕКРАНА: телефон с широк екран може да е слаб, а
//    малък лаптоп — мощен. Гледат се памет, ядра и режим „пестене на данни",
//    а когато браузърът не ги казва (Safari не ги дава), се пада на
//    предпазливото средно, не на най-високото.
//
// ПЪТ НАЗАД: махни реда за js/tier.js от index.html. Атрибутите изчезват и
// всички правила в css/tier.css престават да важат — приложението се връща
// точно към предишното си поведение.
// ═══════════════════════════════════════════════════════════════════════════
(function () {
  'use strict';
  var корен = document.documentElement;

  function иска(заявка) {
    try { return window.matchMedia && window.matchMedia(заявка).matches; } catch (e) { return false; }
  }

  // ── движение ──
  function движение() {
    return иска('(prefers-reduced-motion: reduce)') ? 'reduce' : 'full';
  }

  // ── сила ──
  // Никой сигнал сам по себе си не е присъда. Събират се, и при липса на
  // данни се пада на 'medium' — не на 'high'.
  function сила() {
    if (движение() === 'reduce') return 'low';
    var точки = 0, знаехме = 0;

    var памет = navigator.deviceMemory;                 // Chrome/Android
    if (typeof памет === 'number') {
      знаехме++;
      if (памет <= 2) точки -= 2; else if (памет <= 4) точки -= 1; else if (памет >= 8) точки += 1;
    }
    var ядра = navigator.hardwareConcurrency;
    if (typeof ядра === 'number') {
      знаехме++;
      if (ядра <= 4) точки -= 1; else if (ядра >= 8) точки += 1;
    }
    // „пестене на данни" е ИЗРИЧНО желание на човека — тежи най-много
    try {
      var връзка = navigator.connection;
      if (връзка) {
        знаехме++;
        // 🔴 07.09, хванато със собствената проба: тук стоеше „точки -= 3",
        //   но добър хардуер (8 GB + 8 ядра = +2) НАДГЛАСЯВАШЕ изричното
        //   желание на човека — мощен телефон в „пестене на данни" получаваше
        //   medium, докато коментарът ми отгоре твърдеше, че това тежи най-много.
        //   Кодът трябва да казва същото като коментара. „Пестене на данни"
        //   и 2g не са сигнал за слаб телефон — те са ИЗБОР и обстоятелство,
        //   и се уважават без гласуване.
        if (връзка.saveData) return 'low';
        var вид = String(връзка.effectiveType || '');
        if (вид === 'slow-2g' || вид === '2g') return 'low';
        if (вид === '3g') точки -= 1;
      }
    } catch (e) {}
    // груб допир без прецизен показалец обикновено значи телефон
    if (иска('(pointer: coarse)')) точки -= 1;

    if (!знаехме) return 'medium';                      // Safari не казва нищо
    if (точки <= -3) return 'low';
    if (точки >= 2) return 'high';
    return 'medium';
  }

  var _движение = движение();
  var _сила = сила();

  function приложи() {
    корен.setAttribute('data-motion', _движение);
    корен.setAttribute('data-quality', _сила);
  }
  приложи();

  // човек може да смени предпочитанието, без да презарежда
  try {
    var мк = window.matchMedia('(prefers-reduced-motion: reduce)');
    var сменено = function () {
      _движение = движение();
      _сила = сила();
      приложи();
      try {
        document.dispatchEvent(new CustomEvent('bl:tier', { detail: { motion: _движение, quality: _сила } }));
      } catch (e) {}
    };
    if (мк.addEventListener) мк.addEventListener('change', сменено);
    else if (мк.addListener) мк.addListener(сменено);
  } catch (e) {}

  // ── 🚨 ПАНИКА НЕ СЕ УКРАСЯВА ──────────────────────────────────────────
  //   Приложението вече вдига събитие bl:alarm на трите места, където
  //   излиза спешен отговор (helper.js:3052, 3174, 3275). Дотук то спираше
  //   само търговията. Сега спира и УКРАСАТА.
  //
  //   ЗАЩО: жена, която чете „обади се на 112", не бива да гледа подскачащ
  //   балон и дишащ фон. Движението в този миг не е топлина, а шум върху
  //   най-важното изречение в цялото приложение.
  //
  //   ⚠️ НЕ спира самия отговор да се появи и НЕ пипа преходите на
  //   интерфейса — само повтарящата се украса. Вдига се за 30 секунди:
  //   достатъчно да прочете, недостатъчно приложението да изглежда мъртво.
  var _тревогаТаймер = null;
  try {
    document.addEventListener('bl:alarm', function () {
      корен.setAttribute('data-alarm', '1');
      if (_тревогаТаймер) clearTimeout(_тревогаТаймер);
      _тревогаТаймер = setTimeout(function () { корен.removeAttribute('data-alarm'); }, 30000);
    });
  } catch (e) {}

  // ── договорът за JS ──
  // Всеки цикъл/таймер, който рисува украса, пита ТУК, вместо да гадае.
  window.BL_TIER = {
    motion: function () { return _движение; },
    quality: function () { return _сила; },
    reduced: function () { return _движение === 'reduce'; },
    // „може ли да рисувам украса сега" — едно място за целия проект
    animate: function () { return _движение !== 'reduce' && _сила !== 'low'; },
    // колко частици/повторения да си позволи даден ефект
    density: function (пълно) {
      var n = +пълно || 0;
      if (_движение === 'reduce') return 0;
      if (_сила === 'low') return Math.round(n * 0.25);
      if (_сила === 'medium') return Math.round(n * 0.6);
      return n;
    }
  };
})();
