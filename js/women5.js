    //    „3 ставания тази нощ“, а редът отдолу твърдеше все така 12 вместо 15.
    //    Освен това целият ред се СЪЗДАВАШЕ само ако вече има ≥2 дни: първата
    //    нощ на мама нямаше никакъв сбор, колкото и да тапва. Сега се смята
