      брой.innerHTML = n ? '<strong>' + n + '</strong> ' + (n === 1 ? 'ставане' : 'ставания') + ' тази нощ' : 'Още нищо тази нощ.';
      назад.hidden = !n;
      const дд = new Date(); дд.setDate(дд.getDate() - 6);
      const рано = дд.getFullYear() + '-' + String(дд.getMonth() + 1).padStart(2, '0') + '-' + String(дд.getDate()).padStart(2, '0');
      const дни7 = Object.keys(st).filter(k => k >= рано && k <= д).sort();
