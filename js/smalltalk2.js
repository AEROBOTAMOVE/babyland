    // „обичам те“ си има свой, по-топъл отговор в smalltalk.js — не го крада
    if (БЛАГОДАРЯ.test(нормален) && !/обичам/.test(нормален) && ОТВРЪЩАМ[personaName]) {
      return { text: случайно(ОТВРЪЩАМ[personaName]), kind: 'smalltalk' };
    }

    const изход = оригиналът.call(this, text, personaName, room);

    // 12.6.1 — вицът идва от рафта на ТАЗИ помощничка, ако има свой
