  function soundCard() {
    const c = el('section', 'jr-card');
    c.appendChild(el('h4', 'jr-title', 'Милички звуци 🔔 <span class="jr-sub">мек „пльок“ при отметка — по избор</span>'));
    const b = el('button', 'jr-btn', ''); b.type = 'button';
    const isOn = () => { try { return localStorage.getItem('bl_sounds') === '1'; } catch (e) { return false; } };
    const draw = () => { b.textContent = isOn() ? 'Звуците са включени — изключи 🔕' : 'Включи звуците 🔔'; };
    b.addEventListener('click', () => {
      try { localStorage.setItem('bl_sounds', isOn() ? '0' : '1'); } catch (e) {}
      draw();
      if (isOn() && window.BL_FX && BL_FX.pop) BL_FX.pop(true);
    });
    draw();
    c.appendChild(b);
    c.appendChild(el('p', 'jr-privacy', 'Изключени по подразбиране. Без музика, без дрънчене — само мънички потвърждения.'));
    return c;
  }

