  function walkState() {
    const t = today();
    const ck = !!load('bl_checkins', {})[t];
    const ph = load('bl_photo_day', '') === t;
    const jr = load('bl_prompt_done', '') === t ||
      load('bl_freepage', []).some(n => n && n.d && localDate(new Date(n.d)) === t);
    return { ck, ph, jr, n: (ck ? 1 : 0) + (ph ? 1 : 0) + (jr ? 1 : 0) };
  }

