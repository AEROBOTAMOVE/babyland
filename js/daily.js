  const ЗА_РОДЕНО = /бебе|пелен|проговор|ръчичк|косичк|личице|порасн|гушкан|количк|двамата|го погледна/;
  function иматБебе() {
    try { const b = JSON.parse(localStorage.getItem('bl_baby')); return !!(b && b.birth); } catch (e) { return false; }
  }
  function кошница() {
    if (иматБебе()) return PROMPTS;
    const неутрални = PROMPTS.filter(q => !ЗА_РОДЕНО.test(q));
    return неутрални.length ? неутрални : PROMPTS;
  }
  function todaysPrompt() {
    // офсет по годината, за да не се повтаря същият въпрос на същата дата догодина
    const К = кошница();
    return К[(dayOfYear() + new Date().getFullYear() * 131) % К.length];
  }

  function promptCard() {
    const c = el('section', 'jr-card pr-card');
    c.appendChild(el('h4', 'jr-title', 'Подканата на деня 💭 <span class="jr-sub">различен въпрос всеки ден — едно изречение стига</span>'));
    const q = todaysPrompt();
    c.appendChild(el('p', 'pr-q', '„' + q + '“'));

    const doneBox = el('div');
    c.appendChild(doneBox);

    function drawDone() {
      doneBox.innerHTML = '';
      const log = load('bl_prompt_log', []);
      const doneToday = load('bl_prompt_done', '') === today();
      if (doneToday) {
        doneBox.appendChild(el('p', 'pr-done', 'Отговорено за днес ✓ Утре — нов въпрос. 💜'));
        // ✏️ 11.08 (обиколка №2): написаното се заключваше на мига. Дописване,
        //    поправена дума, второ хрумване по-късно вечерта — нямаше как.
        //    Отваряме пак СЪЩИЯ запис (не втори ред в дневника).
        const поправи = el('button', 'jr-chip', '✏️ Допиши или поправи'); поправи.type = 'button';
        поправи.style.minHeight = '44px';
        поправи.addEventListener('click', () => {
          const lg = load('bl_prompt_log', []);
          const посл = lg[lg.length - 1];
          save('bl_draft_prompt', (посл && посл.t) || '');
          if (посл) save('bl_prompt_log', lg.slice(0, -1));
          save('bl_prompt_done', '');
          fx().buzz(8);
          drawDone();
          const поле = doneBox.querySelector('textarea');
          if (поле) { try { поле.focus({ preventScroll: true }); поле.setSelectionRange(поле.value.length, поле.value.length); } catch (e) { } }
          if (window.refreshToday) refreshToday();
        });
        doneBox.appendChild(поправи);
      } else {
        const ta = el('textarea', 'jr-paper pr-in');
        ta.rows = 2; ta.placeholder = 'Отговори тук…';
        ta.dataset.draft = 'bl_draft_prompt';
        ta.value = load('bl_draft_prompt', '');
        // 📱 клавиатурата закрива полето, когато картата е ниско в стаята
        ta.addEventListener('focus', () => {
          setTimeout(() => { try { ta.scrollIntoView({ block: 'center', behavior: 'smooth' }); } catch (e) { } }, 250);
        });
        const btn = el('button', 'jr-btn', 'Запиши в дневника ✍️'); btn.type = 'button';
        btn.addEventListener('click', () => {
          const v = ta.value.trim(); if (!v) return;
          const lg = load('bl_prompt_log', []);
          lg.push({ q, t: v, d: Date.now() });
          save('bl_prompt_log', lg.slice(-400));
          save('bl_prompt_done', today());
          save('bl_draft_prompt', '');
          fx().buzz(12); fx().confetti(btn, 14);
          drawDone();
          if (window.refreshToday) refreshToday();
        });
        doneBox.appendChild(ta); doneBox.appendChild(btn);
      }
      // последните 2 отговора — за да се вижда, че се трупа съкровище
      const last = log.slice(-2).reverse();
      if (last.length) {
        const hist = el('div', 'pr-hist');
        last.forEach(r => {
          hist.appendChild(el('div', 'pr-hrow',
            `<span class="pr-hq">„${esc(r.q)}“</span><span class="pr-ht">${esc(r.t)}</span><span class="pr-hd">${new Date(r.d).toLocaleDateString('bg-BG')}</span>`));
        });
        doneBox.appendChild(hist);
      }
    }
    drawDone();
    return c;
  }

