  const capKey = c => c.sealed + '§' + String((c.text || '').length) + '§' + c.unlock;
  function pendingCapsule(baby) {
    const seen = load('bl_surfaced_caps', []);
    const caps = load('bl_capsules', []);
    const c = caps.find(x => x && x.to === 'self' && x.unlock <= today() && seen.indexOf(capKey(x)) < 0);
    if (c) return { kind: 'cap', text: c.text, title: '💌 Капсулата ти се отвори', markKey: capKey(c) };
    const lb = load('bl_letter_baby', null), born = !!(baby && baby.birth);
    if (lb && born && !load('bl_surfaced_lb', false)) return { kind: 'lb', text: lb.t, title: '💌 Писмо до бебето', markLb: true };
    return null;
  }

