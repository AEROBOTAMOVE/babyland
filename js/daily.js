  // ═══════════════ ⏩ „ПРОДЪЛЖИ ОТКЪДЕТО СПРЯ“ ═══════════════

  function ordinal(n) {
    const last = n % 10, teen = n % 100 >= 11 && n % 100 <= 14;
    const suf = teen ? 'и' : last === 1 ? 'ви' : last === 2 ? 'ри' : (last === 3 || last === 4) ? 'ти' : 'и';
    return n + '-' + suf;
  }

  function continueTarget(baby, a) {
    const D = window.BL_DATA || {};
    // 1) Лексиконът на бебето — започнат, но недовършен
    // 🟠 11.08 (обиколка „редки състояния“, ИЗМЕРЕНО): стаята вече скрива трите
    //    въпроса за тати при „🤍 Сама съм“ (rooms2.js), но таванът тук остана
    //    тридесет. Жена, попълнила всичките си двайсет и седем, получаваше на
    //    началния екран вечното „Лексиконът чака своя 28-ми отговор“ — покана
    //    към ред, който приложението само ѝ е скрило. Броим СЪЩИТЕ въпроси,
    //    които вижда, и то по отговор, а не по брой ключове (стар отговор на
    //    скрит въпрос вдигаше числото и подканата сочеше грешен ред).
    if (D.babyLex) {
      const сама = load('bl_partner', '') === 'не';
      const въпроси = сама ? D.babyLex.filter(q => !/тати/i.test(q)) : D.babyLex;
      const лекс = load('bl_baby_lexicon', {});
      const n = въпроси.filter(q => лекс[q]).length;
      if (n > 0 && n < въпроси.length) {
        return { label: `✨ Лексиконът чака своя ${ordinal(n + 1)} отговор`, room: 'Моето бебе' };
      }
    }
    // 2) Фото-лентата — текущият месец е без снимка
    if (a && a.ym >= 0 && a.ym <= 24) {
      const photos = load('bl_photos', {});
      if (Object.keys(photos).length > 0 && !photos[a.ym]) {
        return { label: `📸 Фото-лентата чака снимката за ${a.ym === 0 ? 'раждането' : a.ym + ' м.'}`, room: 'Моето бебе' };
      }
    }
    // 3) Подканата на деня — още без отговор
    if (load('bl_prompt_done', '') !== today() && load('bl_prompt_log', []).length > 0) {
      return { label: '💭 Подканата на деня чака отговор', room: 'Дневник на мама' };
    }
    // 4.9.12: опитът в ход — днешното докосване. Стои НАКРАЯ нарочно: опитът
    // е 7 вечери, ще чака и утре; лексиконът и снимката на месеца — не.
    const лаб = load('bl_lab', { list: [] });
    const опит = (лаб.list || []).find(x => x && !x.closed && !(x.log || {})[today()]);
    if (опит) {
      const остават = Math.max(0, (опит.d || 7) - Object.keys(опит.log || {}).length);
      return {
        label: `🔬 Опитът чака докосване${остават ? ' · още ' + остават + (остават === 1 ? ' вечер' : ' вечери') : ''}`,
        room: 'Лабораторията'
      };
    }
    return null;
  }

