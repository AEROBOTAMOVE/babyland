  // 12.3.3: подбира се по ВЪЗРАСТТА, не случайно. Трик за захранване
  // при 2-месечно е шум; трик за шише при 2-годишно — също.
  const ТЕМА_ВЪЗРАСТ = {   // емоджи → [от месец, до месец]
    '🍼': [0, 15], '🥄': [4, 24], '🧷': [0, 30], '🧸': [0, 99], '👶': [0, 99],
    '😴': [0, 99], '🚗': [0, 99], '📦': [0, 99], '💜': [0, 99]
  };
  function трикЗа(месеци) {
    const подходящи = TRICKS.filter(([e]) => {
      const г = ТЕМА_ВЪЗРАСТ[e]; if (!г) return true;
      return месеци == null || (месеци >= г[0] && месеци <= г[1]);
    });
    const списък = подходящи.length ? подходящи : TRICKS;
    const doy = Math.floor((new Date() - new Date(new Date().getFullYear(), 0, 0)) / 86400000);
    return списък[doy % списък.length];
  }
