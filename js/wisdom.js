  // ═══════════ 🧿 играта „Мит или истина?“ ═══════════
  function quizCard() {
    const c = el('section', 'jr-card');
    c.appendChild(el('h4', 'jr-title', 'Мит или истина? 🧿 <span class="jr-sub">бабините деветини срещу науката — играй!</span>'));
    // 🎯 темата се избира от мама (dev.js слага чиповете); истините остават
    // винаги в тестето — иначе при избрана тема всичко щеше да е „мит“. 😄
    // #28: темата се преизгражда БЕЗ да пре-рисуваме цялата стая (виж c._reTheme долу)
    let pool = [];
    function строиТесте() {
      const th = window.BL_QUIZ_THEME || null;
      pool = MYTHS.filter(m => !th || m[2] === th).map(([m, t]) => ({ s: m, truth: false, why: t }))
        .concat(TRUTHS.map(([s, why]) => ({ s, truth: true, why })));
    }
    строиТесте();
    const box = el('div', 'qz-box');
    const stat = el('p', 'cs-note', '');
    let cur = null, streak = load('bl_quiz_streak', 0), best = load('bl_quiz_best', 0);
    // 12.3.2: рунд от 10 → резултат, който може да се сподели
    const РУНД = 10;
    let въпрос = 0, познати = 0, тесте = [];
    function размесиТесте() {
      тесте = pool.slice();
      for (let i = тесте.length - 1; i > 0; i--) { const j = Math.floor(Math.random() * (i + 1)); [тесте[i], тесте[j]] = [тесте[j], тесте[i]]; }
      въпрос = 0; познати = 0;
    }
    function next() {
      if (въпрос >= РУНД) { резултат(); return; }
      if (!тесте.length) размесиТесте();
      въпрос++;
      cur = тесте.pop();
      box.innerHTML = `<p class="qz-q">„${cur.s}“</p>
        <div class="jr-quick"><button class="jr-btn qz-b" data-v="0" type="button">Мит! 🧿</button>
        <button class="jr-btn qz-b qz-t" data-v="1" type="button">Истина! ✅</button></div>`;
      box.querySelectorAll('.qz-b').forEach(b => b.addEventListener('click', () => answer(b.dataset.v === '1')));
      upd();
    }
    // 12.3.2: краят на рунда — резултат + споделяне
    function резултат() {
      const реплики = [
        [10, '🏆 Пълен отличник! Бабите свалят шапка.'],
        [8, '🎉 Браво! Ти отсяваш зърното от плявата.'],
        [6, '💜 Добре се справяш — и вече знаеш кои са капаните.'],
        [4, '🌱 Половината са хванати. Тестето е коварно, върни се пак.'],
        [0, '🧿 Няма страшно — точно затова е играта. Опитай пак!']
      ];
      const дума = (реплики.find(([п]) => познати >= п) || реплики[реплики.length - 1])[1];
      const рекорд = load('bl_quiz_round', 0);
      const нов = познати > рекорд;
      if (нов) save('bl_quiz_round', познати);
      box.innerHTML = `<div class="qz-res ok qz-final">
        <p class="qz-score">${познати} <span>от ${РУНД}</span></p>
        <p>${дума}</p>${нов ? '<p class="qz-new">✨ Нов личен рекорд!</p>' : ''}</div>
        <div class="jr-quick"><button class="jr-btn" type="button" id="qzAgain">Още един рунд ➤</button>
        <button class="jr-btn" type="button" id="qzShare">📤 Сподели</button></div>`;
      box.querySelector('#qzAgain').addEventListener('click', () => { размесиТесте(); next(); });
      box.querySelector('#qzShare').addEventListener('click', async () => {
        const b = box.querySelector('#qzShare');
        const текст = `🧿 „Мит или истина?“ — познах ${познати} от ${РУНД} бабини деветини!\nА ти колко ще познаеш? 😄\n\n(от Помощникът на мама 🎈)`;
        if (navigator.share) { try { await navigator.share({ text: текст }); return; } catch (e) { if (e.name === 'AbortError') return; } }
        try { await navigator.clipboard.writeText(текст); b.textContent = '✔ Копирано'; setTimeout(() => b.textContent = '📤 Сподели', 1600); } catch (e) {}
      });
      if (познати >= 8) fx().confetti(box);
      upd();
    }
    function answer(guess) {
      const right = guess === cur.truth;
      if (right) познати++;
      streak = right ? streak + 1 : 0;
      if (streak > best) { best = streak; save('bl_quiz_best', best); }
      save('bl_quiz_streak', streak);
      box.innerHTML = `<p class="qz-q">„${cur.s}“</p>
        <div class="qz-res ${right ? 'ok' : 'no'}">${right ? '🎉 Позна!' : 'Опа!'} Това е <strong>${cur.truth ? 'ИСТИНА' : 'МИТ'}</strong>.<br>${cur.why}</div>
        <button class="jr-btn" type="button">${въпрос >= РУНД ? 'Виж резултата 🏁' : 'Следващо ➤'}</button>`;
      box.querySelector('.jr-btn').addEventListener('click', next);
      if (right) { fx().buzz(10); if (streak && streak % 5 === 0) { fx().cheer(streak + ' поред! Бабите се съвещават. 😄'); } }
      upd();
    }
    function upd() {
      const къде = въпрос > 0 && въпрос <= РУНД ? `Въпрос <strong>${въпрос}</strong> от ${РУНД} · познати: <strong>${познати}</strong> · ` : '';
      stat.innerHTML = `${къде}серия: <strong>${streak}</strong> · рекорд: <strong>${best}</strong> · ${pool.length} карти в тестето`;
    }
    размесиТесте();
    next();
    c.appendChild(box); c.appendChild(stat);
    // #28: dev.js вика това при смяна на тема — само куизът се рестартира,
    // стаята НЕ се затваря/отваря (пази скрол, сгъвания, всичко останало)
    c._reTheme = () => { строиТесте(); размесиТесте(); next(); };
    return c;
  }

