// 📅 ДАТИТЕ  (М−3, одит 7)
//
// Защо съществува: `d.setMonth(d.getMonth() + 6)` е капан. JavaScript не
// клампва деня — той ПРЕЛИВА в следващия месец. Бебе, родено на 31 август:
//     setMonth(+6)  →  31 февруари  →  преброява се като 3 март  ❌
// Шест месеца по-късно мама води бебето на ваксина на грешен ден и никъде
// не гърми — датата изглежда съвсем правдоподобна.
//
// Правилото: при по-къс месец се взима ПОСЛЕДНИЯТ му ден.
//     31 август + 6 месеца  →  28 февруари (или 29 във високосна)  ✅
// ═══════════════════════════════════════════════════════════
window.BL_DATE = {
  addMonths: function (date, n) {
    const x = new Date(date);
    if (isNaN(x)) return x;
    const day = x.getDate();
    x.setDate(1);                       // първо на 1-во — така месецът не прелива
    x.setMonth(x.getMonth() + Number(n || 0));
    const last = new Date(x.getFullYear(), x.getMonth() + 1, 0).getDate();
    x.setDate(Math.min(day, last));     // и връщаме деня, клампнат до края на месеца
    return x;
  }
};

