// 🤰 BL_PREG — ЕДНА сметка за седмицата и за дните до термина
//
// ЗАЩО (25.08.2026): тринайсет места в проекта смятаха седмицата с един и
// същ израз, преписан дума по дума:
//     Math.floor((Date.now() - new Date(lmp)) / 604800000)     ← старият, преписан 13 пъти
// Изглежда безобиден. Не е — по ДВЕ причини, и двете ИЗМЕРЕНИ, не изведени:
//
//   1. `new Date('2026-01-01')` е UTC полунощ, а `Date.now()` е тукашно време.
//      В София това са 2-3 часа разлика. Резултат: ВСЕКИ СЕДМИ ДЕН, между
//      00:00 и 02:00, седмицата излиза с ЕДНА ПО-МАЛКО от календарната.
//      Измерено върху 5760 мига (всеки час от 240 дни): разминаване в 1.6%.
//      А в самия ден на последната менструация, между 00:00 и 02:00, изразът
//      дава  −1  — тоест отрицателна седмица.
//   2. Едно и също нещо се смяташе на 13 места. Разминат ли се веднъж (а
//      вече се бяха разминали за „остават N дни": едни файлове ползваха
//      Math.ceil, други Math.round — ИЗМЕРЕНО разминаване в 50% от
//      миговете), мама вижда 12 дни на един екран и 11 на друг.
//
// ПРАВИЛОТО ТУК: броим КАЛЕНДАРНИ ДНИ между две МЕСТНИ полунощи. Тогава
// часът на деня не участва изобщо и няма какво да се измести.
//
// 🪤 ЗАЩО Math.round при делението на 86400000: два пъти в годината часовникът
//   се мести с час (лятно/зимно време) и разликата между две полунощи става
//   23 или 25 часа. Голото деление би дало 0.958 или 1.042 дни; закръглянето
//   връща честното 1.
//
// ПРОВЕРКА: node dev/test_preg_smetki.js
// ПЪТ НАЗАД: всяко място пази стария израз като резервен изход след `||`.
// ═══════════════════════════════════════════════════════════
window.BL_PREG = (function () {
  // местна полунощ от 'ГГГГ-ММ-ДД' или от Date — БЕЗ минаване през UTC
  function полунощ(x) {
    if (x instanceof Date) return isNaN(x) ? null : new Date(x.getFullYear(), x.getMonth(), x.getDate());
    const m = String(x || '').match(/^(\d{4})-(\d{2})-(\d{2})/);
    if (m) return new Date(+m[1], +m[2] - 1, +m[3]);
    const d = new Date(x);
    return isNaN(d) ? null : new Date(d.getFullYear(), d.getMonth(), d.getDate());
  }
  function дни(от, до) {
    const а = полунощ(от), б = полунощ(до || new Date());
    if (!а || !б) return null;
    return Math.round((б - а) / 86400000);
  }
  return {
    полунощ: полунощ,
    дни: дни,
    // ПЪЛНИ седмици от първия ден на цикъла (както го брои медицината)
    седмица: function (пм, сега) { const д = дни(пм, сега); return д == null ? null : Math.floor(д / 7); },
    // терминът по Негеле: 280 дни, броени по календар
    термин: function (пм) { const а = полунощ(пм); if (!а) return null;
      return new Date(а.getFullYear(), а.getMonth(), а.getDate() + 280); },
    // колко ЦЕЛИ дни остават — една сметка за целия проект
    доТермина: function (пм, сега) { const т = this.термин(пм); if (!т) return null; return дни(сега || new Date(), т); }
  };
})();
