// 🔢 РЕДНА — правилната наставка на редните числителни
//
// Защо съществува (05.08, езиковата вълна):
//   Наставката се лепеше на сляпо: винаги '-та'. Жената в 28-а седмица
//   четеше „28-та седмица", а базата на помощничките (kb.js) пише
//   „28-ма" на двайсет места. Едно и също число, два правописа в едно
//   приложение — и то на екрана, където се решава дали да се звъни.
//
//   Грешно беше точно за 1, 2, 7, 8, 21, 22, 27, 28, 31, 32 —
//   най-често изричаните седмици в бременността, включително 37-ма,
//   която стои в спешния текст за контракции.
//
//   Помощникът беше написан в rooms2.js, но preg20.js и rooms8.js не го
//   виждат. Затова живее тук — един път, за целия проект.
//
// Правилото:
//   1 → -ва (първа)      2 → -ра (втора)      7 → -ма (седма)
//   8 → -ма (осма)       всичко друго → -та
//   11–19 винаги -та (единайсета, дванайсета, седемнайсета)
//
// ПЪТ НАЗАД: файлът само добавя window.BL_REDNA. Махнеш ли реда от
// index.html, местата, които го ползват, падат на своя резерв '-та'.
// ═══════════════════════════════════════════════════════════
(function () {
  'use strict';

  function редна(n) {
    n = parseInt(n, 10);
    if (!isFinite(n) || n < 0) return String(n);
    var е = n % 10, д = n % 100;
    if (д >= 11 && д <= 19) return n + '-та';
    return n + (е === 1 ? '-ва'
              : е === 2 ? '-ра'
              : (е === 7 || е === 8) ? '-ма'
              : '-та');
  }

  // самопроверка: сверена с изписаните с думи числителни
  function самопроверка() {
    var очаквано = {
      1: '1-ва', 2: '2-ра', 3: '3-та', 4: '4-та', 5: '5-та', 6: '6-та',
      7: '7-ма', 8: '8-ма', 9: '9-та', 10: '10-та',
      11: '11-та', 12: '12-та', 17: '17-та', 18: '18-та', 19: '19-та',
      20: '20-та', 21: '21-ва', 22: '22-ра', 27: '27-ма', 28: '28-ма',
      30: '30-та', 31: '31-ва', 32: '32-ра', 37: '37-ма', 38: '38-ма',
      40: '40-та', 41: '41-ва', 42: '42-ра'
    };
    var лоши = [];
    for (var k in очаквано) {
      if (редна(k) !== очаквано[k]) лоши.push(k + ' → ' + редна(k) + ' (чакахме ' + очаквано[k] + ')');
    }
    return { проверени: Object.keys(очаквано).length,
             грешни: лоши.length, списък: лоши,
             присъда: лоши.length ? '🔴 ПАДА' : '✅ ПРЕМИНАВА' };
  }

  window.BL_REDNA = редна;
  window.BL_REDNA.самопроверка = самопроверка;
})();
