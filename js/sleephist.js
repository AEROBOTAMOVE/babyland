// ═══════════════════════════════════════════════════════════
// ИСТОРИЯТА НА СЪНЯ (план 19, основата под 4.9.5)
//
// Планът казваше „опитът да чете САМ данните от bl_sleep“. Проверих: bl_sleep
// пази САМО днешния ден и се нулира всяка нощ (rooms2.js: `if (s.d !== t)`).
// История НЯМА никъде. Значи нямаше какво да се чете.
//
// Този модул я създава — тихо, без нова карта и без да пипа bl_sleep:
// при пускане на приложението, ако в bl_sleep стои ВЧЕРАШЕН ден, сборът му
// се прибира в bl_sleep_hist ПРЕДИ rooms2 да го изтрие.
//
// ЧЕСТНО: историята тръгва от деня, в който това влезе. Минало не измисляме.
// ═══════════════════════════════════════════════════════════
(function () {
  'use strict';

  const load = (k, d) => { try { const v = JSON.parse(localStorage.getItem(k)); if (v == null) return d; if (Array.isArray(d) !== Array.isArray(v)) return d; if (d && typeof d === 'object' && (!v || typeof v !== 'object')) return d; return v; } catch (e) { return d; } };
  // записът казва ДА или НЕ — при пълна памет тук се решава дали да пипаме
  // живия брояч (виж реда в прибери() долу)
  const save = (k, v) => { try { localStorage.setItem(k, JSON.stringify(v)); } catch (e) { if (window.BL_ZAPIS_PADNA) BL_ZAPIS_PADNA(); return false; } return true; };
  const localDate = d => d.getFullYear() + '-' + String(d.getMonth() + 1).padStart(2, '0') + '-' + String(d.getDate()).padStart(2, '0');
  const today = () => localDate(new Date());

  const K = 'bl_sleep_hist';   // { 'YYYY-MM-DD': минути }

  // Сборът на затворените отрязъци. Отворен отрязък (мама е забравила да
  // спре брояча) НЕ се брои — не знаем кога е свършил и не го измисляме.
  function минути(s) {
    if (!s || !Array.isArray(s.segs)) return 0;
    let ms = 0;
    s.segs.forEach(x => {
      if (!x || typeof x.s !== 'number' || typeof x.e !== 'number') return;
      const d = x.e - x.s;
      if (d > 0 && d < 86400000) ms += d;
    });
    return Math.round(ms / 60000);
  }

  // прибира вчерашното, ако още стои непокътнато
  function прибери() {
    let s = load('bl_sleep', null);
    if (!s || !s.d || s.d === today()) return;      // няма или е днешно — не пипаме
    // проход 3 T7: нощният сън през полунощ. Ако ВЧЕРА е останал ОТВОРЕН отрязък
    // (заспал снощи, буден днес), разцепваме в полунощ: вчерашната част влиза в
    // историята, остатъкът продължава като днешен отворен сън. Само за ВЧЕРА —
    // по-стар изоставен брояч не пренасяме (не знаем колко дни е стоял).
    // 🔴 04.08 (обиколка, стая Моето бебе): горният коментар обещава „не го
    //    измисляме“, а точно това се случваше. Разцепването в полунощ нямаше
    //    НИКАКЪВ таван: мама натиска „😴 Заспа“ в 9 сутринта и забравя →
    //    вчера получава 15 часа сън, а днес стартира с включен брояч от 00:00
    //    и в 9 сутринта картата пише „9 ч“. Едно забравено докосване правеше
    //    ДВЕ измислени числа. После „Сънят по месеци“ ѝ показва 14 ч средно,
    //    а тя знае, че бебето спи 8 — и спира да вярва на приложението.
    //    Нощен сън над 12 часа до полунощ не е сън, а забравен брояч.
    const ТАВАН = 12 * 3600000;
    // 🔴 25.08 · РЕДЪТ НА ДВАТА ЗАПИСА. Досега живият брояч се нулираше ПЪРВИ,
    //    а историята се пишеше ВТОРА — и то с гълтане на грешката. При пълна
    //    памет (телефон със снимки и гласови записи) вторият запис пада тихо и
    //    вчерашната нощ изчезва СЛЕД като живият ключ вече е занулен: нито в
    //    историята, нито в брояча. Затова сега: първо историята, и само ако е
    //    минала — нулиране на живия ключ. Не мине ли, всичко си стои и следващият
    //    опит (rooms2.js:605 или пазачът долу) пробва пак.
    //    ПЪТ НАЗАД: върни двата `save('bl_sleep', …)` на местата им горе и
    //    голия `save(K, h)` накрая.
    let ново = null;                                 // какво да стане с живия ключ
    if (typeof s.open === 'number') {
      const вчера = localDate(new Date(Date.now() - 86400000));
      const полунощ = new Date(today() + 'T00:00:00').getTime();
      if (s.d === вчера && s.open < полунощ) {
        if (полунощ - s.open <= ТАВАН) {
          // истински нощен сън през полунощ — вчерашната част влиза, остатъкът продължава
          s = Object.assign({}, s, { segs: (Array.isArray(s.segs) ? s.segs : []).concat({ s: s.open, e: полунощ }) });
          ново = { d: today(), segs: [], open: полунощ };   // сутрин: бутонът е „🌅 Събуди се"
        } else {
          // забравен брояч — нищо не се измисля и нищо не се пренася
          s = Object.assign({}, s, { open: null });
          ново = { d: today(), segs: [], open: null };
        }
      }
    }
    const h = load(K, {});
    const m = минути(s);
    if (h[s.d] == null && m > 0) {                   // „вече прибрано“ и „празен ден“ не се пишат
      h[s.d] = m;
      // пази последните 120 дни — толкова стигат за всеки опит
      const ключове = Object.keys(h).sort();
      while (ключове.length > 120) delete h[ключове.shift()];
      if (!save(K, h)) return;                       // не се записа → живият брояч НЕ се пипа
    }
    if (ново) save('bl_sleep', ново);
  }

  // ── четене за другите модули ──
  const чети = () => load(K, {});

  // сборът за ДНЕС (от живия bl_sleep, не от историята)
  // 🔴 25.08 (ИЗМЕРЕНО, dev/broyachi_dnevnik.js П4.1 — състояние „бебето спи
  //    в момента“): тук се броеха САМО затворените отрязъци. Докато бебето
  //    спи, картата „Сънят днес“ в стаята (rooms2.js:617 totalSleep) пишеше
  //    „Днес: 5 ч 0 мин“, а профилът и „Числата вместо усещането“ — които
  //    четат оттук — казваха „3 ч 0 мин“ за СЪЩИЯ ден в същата минута.
  //    Две числа за едно нещо: мама вижда, че някое лъже, но не кое.
  //    Сега сметката е ДУМА ПО ДУМА като на картата: сборът на отрязъците
  //    плюс течащия брояч, със СЪЩИЯ таван от 14 часа (над него не е сън,
  //    а забравено докосване — rooms2.js:614 ТАВАН_СЪН).
  //    ПЪТ НАЗАД: тялото беше един ред — `return (s && s.d === today()) ? минути(s) : 0;`
  const ТАВАН_ОТВОРЕН = 14 * 3600000;      // = rooms2.js ТАВАН_СЪН
  function днес() {
    const s = load('bl_sleep', null);
    if (!s || s.d !== today()) return 0;
    let ms = 0;
    (Array.isArray(s.segs) ? s.segs : []).forEach(x => {
      if (!x || typeof x.s !== 'number' || typeof x.e !== 'number') return;
      const d = x.e - x.s;
      if (d > 0 && d < 86400000) ms += d;
    });
    if (typeof s.open === 'number' && s.open > 0) {
      const тече = Date.now() - s.open;
      if (тече > 0 && тече <= ТАВАН_ОТВОРЕН) ms += тече;
    }
    return Math.floor(ms / 60000);         // картата също реже надолу, не закръгля
  }

  // средното от дните ПРЕДИ дадена дата (базата, спрямо която сравняваме)
  function средно(преди, максДни) {
    const h = чети();
    const дни = Object.keys(h).filter(d => !преди || d < преди).sort().slice(-(максДни || 14));
    if (!дни.length) return null;
    return Math.round(дни.reduce((a, d) => a + h[d], 0) / дни.length);
  }

  // колко нощи изобщо имаме
  const брой = () => Object.keys(чети()).length;

  прибери();
  window.BL_SLEEPHIST = { чети, днес, средно, брой, минути, прибери };

  // ── Г1+Г2 (план 23): и другите дневни броячи не бива да се губят ──
  // „Вода днес“ и „Изпито мл“ се нулираха в полунощ БЕЗ следа. Прибираме
  // вчерашното по същия начин: рано, преди картата да го изтрие.
  //
  // 📌 bl_ml_hist СЕ ПЪЛНИ, макар че още никоя карта не я чете (25.08 —
  //    измерено: 0 четци извън този файл). Нарочно е и не се маха: история,
  //    която тръгва чак когато се появи картата, показва „нямам минало“ точно
  //    на майката, която е бележила месеци наред. Същото се случи и с
  //    bl_water_hist — тя се пълнеше сама, докато profile.js и rooms6.js я
  //    прочетоха. Вратата е отворена: BL_DAYHIST.мл().
  function прибериДневни() {
    [['bl_water', 'bl_water_hist'], ['bl_ml', 'bl_ml_hist']].forEach(([жив, хист]) => {
      const s = load(жив, null);
      if (!s || !s.d || s.d === today()) return;
      if (typeof s.n !== 'number' || s.n <= 0) return;
      const h = load(хист, {});
      if (h[s.d] != null) return;                    // вече прибрано
      h[s.d] = s.n;
      const кл = Object.keys(h).sort();
      while (кл.length > 120) delete h[кл.shift()];
      save(хист, h);
    });
    // и СЕДМИЧНАТА касичка „време за мен“ — нулира се всеки понеделник,
    // а миналите седмици се губеха. Прибираме изтеклата седмица.
    const пон = (() => { const n = new Date(); const p = new Date(n); p.setDate(n.getDate() - ((n.getDay() + 6) % 7)); return localDate(p); })();
    const м = load('bl_metime', null);
    if (м && м.week && м.week !== пон && typeof м.minutes === 'number' && м.minutes > 0) {
      const h = load('bl_metime_hist', {});
      if (h[м.week] == null) {
        h[м.week] = м.minutes;
        const кл = Object.keys(h).sort();
        while (кл.length > 60) delete h[кл.shift()];
        save('bl_metime_hist', h);
      }
    }
  }
  прибериДневни();

  // ── 🕛 ПАЗАЧЪТ НА ПОЛУНОЩ ──
  // 🔴 25.08 (ИЗМЕРЕНО, dev/broyachi_dnevnik.js П4.2): прибирачите горе се
  //    викаха САМО веднъж — при зареждане на файла. Мама, която държи
  //    приложението отворено от 23:50 до 00:10 (най-обикновеното нощно
  //    кърмене), минава полунощ БЕЗ презареждане. Тогава първото ѝ докосване
  //    среща чужд ден и почва от нула:
  //      rooms4.js:39  `if (data.d !== today()) data = { d: today(), n: 0 }`
  //      rooms.js:297  `if (w.week !== monday()) w = { week: monday(), minutes: 0 }`
  //    Вчерашните шест чаши вода, 480 мл и минутите сън изчезваха, ПРЕДИ
  //    историята да ги е взела. Измерено: 3 от 3 числа се губеха.
  //    Пазачът само СВЕРЯВА датата; при същия ден не пипа нищо, а прибирачите
  //    и без това не удвояват (`if (h[s.d] != null) return`).
  //    ПЪТ НАЗАД: махни блока до края — остава старото „само при зареждане“.
  let последенДен = today();
  function сверка() {
    const т = today();
    if (т === последенДен) return;          // денят не е сменен — нищо не се пипа
    последенДен = т;
    try { прибери(); } catch (e) {}
    try { прибериДневни(); } catch (e) {}
  }
  try {
    document.addEventListener('visibilitychange', function () { if (!document.hidden) сверка(); });
    window.addEventListener('focus', сверка);
    // и когато телефонът просто стои буден на масата (таймерите в скрит таб
    // спят — затова сверката е и на двете събития горе, не само тук)
    setInterval(сверка, 60000);
  } catch (e) {}

  window.BL_DAYHIST = {
    вода: () => load('bl_water_hist', {}),
    мл: () => load('bl_ml_hist', {}),
    време: () => load('bl_metime_hist', {}),   // проход 3 T22: касичката „време за мен" вече се ЧЕТЕ
    приберете: прибериДневни
  };
})();
