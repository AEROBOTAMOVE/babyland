    const СПЕШНИ = /посинее|посинял|посинява|спре да диша|спира да диша|не диша|гърч|конвулс|припадък|изгуби съзнание|неотзивчив|анафилакс|подуване на езика|подут език|затруднено дишане|не реагира/i;
    const спешноHtml = СПЕШНИ.test(a.body || '')
