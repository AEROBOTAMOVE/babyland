    const known = Date.UTC(2000, 0, 6, 18, 14);           // известно новолуние
    const days = (d.getTime() - known) / 86400000;
    const age = ((days % 29.53059) + 29.53059) % 29.53059;
    // + 0.5 ЦЕНТРИРА кошчето върху събитието (одит 8, поправка М4).
    // Без него кошчетата тръгваха ОТ новолунието вместо да са около него и
