  function tarotCard() {
    const c = card('Картата на деня 🃏' + sub('една на ден · събираш ги'));
    c.appendChild(el('div', 'wm-band', FUN));
    // `load` дава подразбирането само ако ключът ЛИПСВА. Ако в паметта има
    // запис от стара версия (или от внесено копие) без поле `seen`, цялата
    // стая гърмеше при рисуването. Затова полетата се доизкусуряват тук.
    const st = load('bl_cards', {});
    if (!Array.isArray(st.seen)) st.seen = [];
    if (typeof st.last !== 'string') st.last = '';
    if (typeof st.idx !== 'number') st.idx = -1;
    if (typeof st.кръг !== 'number') st.кръг = 1;   // г12 №194: кой път минава тестето
    const box = el('div', 'wm-card-box');
    const btn = el('button', 'jr-chip wm-draw', '🃏 Изтегли картата за днес'); btn.type = 'button';
    const seenP = el('p', 'wm-seen', '');
    function drawSeen() {
      // г12 №194: на 61-вия ден колекцията се нулираше МЪЛЧАЛИВО — „60 от 60“
      // ставаше „1 от 60“ и изглеждаше като изтрита памет. Кръгът го обяснява.
      seenP.innerHTML = 'Събрани: <strong data-cnt="' + st.seen.length + '">' + st.seen.length + '</strong> от ' + CARDS.length +
        '<br><span class="wm-mini">' + CARDS.map((x, i) => st.seen.indexOf(i) > -1 ? x[0] : '<span class="wm-dim">·</span>').join(' ') + '</span>' +
        (st.кръг > 1 ? '<br><span class="wm-mini">Събра цялото тесте — това е кръг ' + st.кръг + ' 🃏</span>' : '');
    }
    function show(i) {
      const [e, t, txt] = CARDS[i];
      box.innerHTML = '<div class="wm-tarot"><span class="wm-te">' + e + '</span><strong>' + esc(t) + '</strong><p>' + esc(txt) + '</p></div>';
    }
    function refresh() {
      if (st.last === today() && st.idx > -1) { show(st.idx); btn.hidden = true; }
      else { btn.hidden = false; box.innerHTML = '<p class="jr-privacy">Днешната карта те чака. 🃏</p>'; }
      drawSeen();
    }
    btn.addEventListener('click', () => {
      // Беше чист Math.random от тестето. По парадокса на рождените дни това
      // значи една и съща карта два пъти още в първата седмица — а мама си мисли,
      // че тегли. Сега теглим от НЕИЗТЕГЛЕНИТЕ: 60 дни подред без повторение,
      // и събирането на тестето най-после значи нещо.
      const непокрити = CARDS.map((_, k) => k).filter(k => st.seen.indexOf(k) < 0);
      const пул = непокрити.length ? непокрити : CARDS.map((_, k) => k);
      if (!непокрити.length) { st.кръг = (st.кръг || 1) + 1; st.seen = []; }   // тестето се изчерпа → нов кръг, но помним кой е
      const i = пул[Math.floor(Math.random() * пул.length)];
      st.idx = i; st.last = today();
      if (st.seen.indexOf(i) < 0) st.seen.push(i);
      save('bl_cards', st); show(i); btn.hidden = true; drawSeen();
      fx().buzz(12);
      if (st.seen.length === CARDS.length) fx().cheer();
      if (window.BL_FX && BL_FX.countUp) BL_FX.countUp(c);
    });
    c.appendChild(btn); c.appendChild(box); c.appendChild(seenP); refresh();
    return c;
  }

