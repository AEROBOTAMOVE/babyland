//
// ЗАЩО СЪЩЕСТВУВА (04.08.2026, живата обиколка):
//   Отворих стая „Захранване“ и преброих: 23 карти. Думата „задавяне“
//   се среща ЕДИН път. Хватки — нула. Рискови храни — нула.
//   Това е стаята, в която майката за пръв път слага твърда храна в
//   устата на бебето си. Тя няма къде да прочете разликата между
//   напъване (нормално, шумно, не пипай) и задавяне (тихо, действай) —
//   а точно това е знанието, което ѝ трябва в първата седмица.
//
// КАКВО НЕ ПРАВИ:
//   Не преписва хватките. Те са замразени в js/rooms6.js (5 удара по
//   гърба + 5 натиска на гърдите) и се отварят с бутон оттук. Един
//   източник — един текст. Ако утре стандартът се смени, се сменя на
//   едно място, не на две.
//
// ПЪТ НАЗАД:
//   Файлът е самостоятелен и само ДОБАВЯ карта. Махаш реда от
//   index.html → стаята се връща точно каквато беше. Нищо не се
//   презаписва, нищо не се пипа в чужд файл.
// ═══════════════════════════════════════════════════════════
(function () {
  'use strict';

  const el = (t, c, h) => { const n = document.createElement(t); if (c) n.className = c; if (h !== undefined) n.innerHTML = h; return n; };
  const card = t => { const c = el('section', 'jr-card'); c.appendChild(el('h4', 'jr-title', t)); return c; };

  // ── Формата, не храната ──
  // Опасната комбинация е КРЪГЛО + ТВЪРДО + колкото дихателната тръбичка.
  // Затова решението почти никога не е „не давай“, а „нареж го другояче“.
  const ФОРМИ = [
    { х: '🍇', име: 'Грозде, чери домат, боровинка',
      как: 'Разрежи ги НАДЛЪЖНО на четвъртинки. Цели или на кръгчета имат точно формата на тръбичката — на четвъртинки нямат.' },
    { х: '🌭', име: 'Кренвирш, наденичка',
      как: 'Никога на кръгчета. Разрежи по дължина на четири и после на къси парченца.' },
    { х: '🥕', име: 'Суров морков, ябълка, твърда круша',
      как: 'Сурови и твърди не се дават на парчета. Настържи ги или ги задуши, докато се мачкат между твоите пръсти.' },
    { х: '🥜', име: 'Ядки, семки, пуканки',
      как: 'Цели — не преди 4-5 годинки. Фъстъченото масло обаче е добре дошло рано: разредено и размазано тънко, не на лъжица бучка.' },
    { х: '🧀', име: 'Кашкавал, сирене на кубчета',
      как: 'Кубчето се плъзга цяло. Настържи го или го нареж на тънки лентички.' },
    { х: '🍬', име: 'Твърди бонбони, желирани, дъвка',
      как: 'Тези нямат безопасна форма. Просто не сега.' },
    { х: '🥖', име: 'Голяма хапка хляб, сурово тесто',
      как: 'Мекият бял хляб се събира на топка в устата. По-добре подсушен, на малки парченца.' }
  ];

  function безопасниФормиCard() {
    const c = card('✂️ Формата, не храната');
    c.classList.add('fs-keep');
    c.appendChild(el('p', 'jr-sub', 'опасното е КРЪГЛО + ТВЪРДО — то се сменя с нож, не със забрана'));

    const списък = el('div', 'fs-list');
    ФОРМИ.forEach(ф => {
      const ред = el('button', 'fs-row');
      ред.type = 'button';
      ред.setAttribute('aria-expanded', 'false');
      const глава = el('span', 'fs-head');
      glava(глава, ф);
      const тяло = el('span', 'fs-body', ф.как);
      тяло.hidden = true;
      ред.appendChild(глава); ред.appendChild(тяло);
      ред.addEventListener('click', () => {
        const отв = !тяло.hidden;
        тяло.hidden = отв;
        ред.setAttribute('aria-expanded', String(!отв));
        ред.classList.toggle('is-open', !отв);
      });
      списък.appendChild(ред);
    });
    c.appendChild(списък);
    c.appendChild(el('p', 'fs-foot', 'Няма списък, който да покрие всичко. Затова помни правилото, не списъка: кръгло и твърдо → разрежи го надлъжно или го омекоти.'));
    return c;
  }

  function glava(възел, ф) {
    възел.appendChild(el('span', 'fs-emo', ф.х));
    възел.appendChild(el('span', 'fs-name', ф.име));
    възел.appendChild(el('span', 'fs-arrow', '▾'));
  }

  // ── Напъване или задавяне ──
  const РАЗЛИКА = {
    напъване: {
      з: '😝 Напъване', под: 'нормално · случва се често · НЕ пипай',
      р: ['Издава звук: кашля, дави се шумно, изкашлюква.',
          'Езикът излиза напред, лицето почервенява, очите сълзят.',
          'Изглежда страшно за теб. За него е упражнение — така се учи да мести храната.',
          'Ти какво правиш: седиш срещу него и не се месиш. Не бъркай с пръст в устата, не го вдигай рязко, не го тупай по гърба. Кашлицата му работи по-добре от която и да е твоя ръка.']
    },
    задавяне: {
      з: '🤫 Задавяне', под: 'тихо · рядко · действай веднага',
      р: ['НЯМА звук. Няма кашлица, няма плач. Тишината е знакът.',
          'Отваря уста, но нищо не излиза. Паникьосан поглед.',
          'Устните и лицето може да посинеят.',
          'Ти какво правиш: викаш 112 (или някой друг звъни, докато ти действаш) и започваш хватките веднага.']
    }
  };

  function напъванеCard() {
    const c = card('🫁 Напъване или задавяне');
    c.classList.add('fs-keep');
    c.appendChild(el('p', 'jr-sub', 'едното е шумно и нормално, другото е тихо — това е цялата разлика'));

    const превкл = el('div', 'fs-tabs');
    const плоскост = el('div', 'fs-pane');
    // 05.08 (одит г06, №246): съдържанието се пренаписва изцяло при смяна на
    // таба, но нищо не го обявяваше — незрящата майка натискаше „🤫 Задавяне“
    // и не чуваше нищо.
    плоскост.setAttribute('role', 'status');
    плоскост.setAttribute('aria-live', 'polite');

    function покажи(ключ) {
      const д = РАЗЛИКА[ключ];
      плоскост.textContent = '';
      плоскост.className = 'fs-pane fs-' + (ключ === 'напъване' ? 'ok' : 'alarm');
      плоскост.appendChild(el('p', 'fs-pt', д.под));
      const ul = el('ul', 'fs-ul');
      д.р.forEach(x => ul.appendChild(el('li', null, x)));
      плоскост.appendChild(ul);
      // №246: активният таб се виждаше САМО по CSS класа is-on — четецът нямаше
      // откъде да разбере кой е избран. aria-pressed казва и двете.
      [...превкл.children].forEach(b => {
        const той = b.dataset.k === ключ;
        b.classList.toggle('is-on', той);
        b.setAttribute('aria-pressed', String(той));
      });
    }

    Object.keys(РАЗЛИКА).forEach(k => {
      const b = el('button', 'fs-tab', РАЗЛИКА[k].з);
      b.type = 'button'; b.dataset.k = k;
      b.setAttribute('aria-pressed', 'false');
      b.addEventListener('click', () => покажи(k));
      превкл.appendChild(b);
    });

    c.appendChild(превкл);
    c.appendChild(плоскост);
    покажи('напъване');

    // Хватките НЕ се преписват тук — отваря се замразеният им текст.
    const бут = el('button', 'jr-chip fs-steps', '🚑 Стъпките при задавяне');
    бут.type = 'button';
    бут.addEventListener('click', () => {
      if (window.BL_FIRSTAID && BL_FIRSTAID.open) BL_FIRSTAID.open('zadavi');
    });
    c.appendChild(бут);
    c.appendChild(el('p', 'fs-foot', 'Прочети ги веднъж, докато всичко е спокойно. После ръцете помнят.'));
    return c;
  }

  // ── Масата ──
  // Нарочно кратко и без броене: това не е списък с провали, а пет неща,
  // които правят разликата и се помнят от първия път.
  const МАСАТА = [
    'Седнал изправен, не полегнал и не в скута ти на една страна.',
    'На едно място — не в количката, не в колата, не в движение.',
    'Ти си на масата. Не в другата стая, не с гръб.',
    'Не яде докато тича, скача или се смее с пълна уста.',
    'Едно ново нещо на спокойствие, не пет наведнъж в бързината.'
  ];

  function масатаCard() {
    const c = card('🪑 Масата');
    // 🔴 05.08 (одит г06, №37): тази карта се раждаше СГЪНАТА. polish.js сгъва
    //    „справочните" карти при първо влизане в претрупана стая — а критерият
    //    му е „няма нито един бутон/поле". Масата е чист текст, заглавието ѝ не
    //    съдържа нито „задав", нито „112", значи NO_FOLD не я лови, и класът ѝ
    //    не е сред защитените. Двете ѝ сестри оцеляват само защото случайно имат
    //    бутони. Затова: явен клас fs-keep, който polish.js чете (виж там).
    c.classList.add('fs-keep');
    c.appendChild(el('p', 'jr-sub', 'повечето случаи не идват от храната, а от положението'));
    const ul = el('ul', 'fs-ul fs-table');
    МАСАТА.forEach(x => ul.appendChild(el('li', null, x)));
    c.appendChild(ul);
    return c;
  }

  // ═══════════ регистрация ═══════════
  // Обвиваме съществуващата стая — не я заместваме. Ако някой преди нас
  // вече я е обвил, неговите карти идват първи, после нашите.
  function закачи() {
    const base = window.ROOM_FEATURES && window.ROOM_FEATURES['Захранване'];
    if (!base) return false;
    window.ROOM_FEATURES['Захранване'] = root => {
      base(root);
      // 🔴 05.08 (одит г06, №38): трите падаха НАЙ-ОТДОЛУ в „⚠️ Внимавай с това".
      //    order4.js:113 обявява keepOrder:true, а polish.js излива кътчето в реда
      //    на вмъкване — значи append след base значи последни. Мама минаваше
      //    покрай печатаема картичка за баба и списък с алергени, за да стигне до
      //    единствената карта за задавяне. Слагаме ги ПРЕД първата карта: редът
      //    вътре в кътчето върви по DOM, значи стават първи в „Внимавай с това".
      const пакет = document.createDocumentFragment();
      пакет.appendChild(напъванеCard());
      пакет.appendChild(безопасниФормиCard());
      пакет.appendChild(масатаCard());
      const първа = root.querySelector(':scope > .jr-card');
      root.insertBefore(пакет, първа || null);
    };
    return true;
  }

  if (!закачи()) {
    // стаите още не са се обявили — чакаме едно завъртане на цикъла
    document.addEventListener('DOMContentLoaded', закачи);
  }

  // Подредбата (order4.js) праща картите по кътчета по ЗАГЛАВИЕ. Трите нови
  // трябва да паднат в „⚠️ Внимавай с това“ (fa) — иначе увисват в „Помним“,
  // което е кофата по подразбиране.
  //
  // ⚠️ ВНИМАНИЕ, скъпа поука: order4.js НЕ излага `rules`. Той ги превръща
  //    във функция `match(заглавие) → ключ на кътче`. Първата ми версия
  //    правеше `.rules.unshift(...)` вътре в `if (…rules)` — условието беше
  //    невярно, нищо не гръмна, картите тихо паднаха в грешното кътче.
  //    Пазено с изричен вик в конзолата, ако утре структурата пак се смени.
  const S = window.BL_ROOM_SECTIONS && window.BL_ROOM_SECTIONS['Захранване'];
  if (S && typeof S.match === 'function') {
    const МОИТЕ = /напъване или задавяне|формата, не храната|масата/i;
    const старо = S.match;
    S.match = t => (МОИТЕ.test(t) ? 'fa' : старо(t));
  } else {
    console.warn('feedsafe: BL_ROOM_SECTIONS["Захранване"].match липсва — ' +
                 'трите карти ще паднат в кофата по подразбиране.');
  }
})();
