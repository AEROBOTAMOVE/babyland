// Защо съществува този файл:
// Жена, която е загубила бебето си, отваряше приложението и я посрещаше
// „изминала си 55%“, „Пътят до термина“ и месечно писмо от Реката.
// Единственият ѝ изход беше да изтрие приложението — тоест да изтрие и
// дневника, и снимките, и писмата си. Наказвахме я двойно.
//
// Как работи: НЕ трие нищо. Датата ѝ (bl_lmp) си стои непокътната.
// Просто спираме да я подаваме на онова, което брои и показва.
// Един вратар — затова всички шест четци минават оттук.
//
// Обратният път съществува (resume), но НИКЪДЕ не се предлага сама.
// Тя го намира в настройките, когато е готова. Не приложението решава кога.
// ═══════════════════════════════════════════════════════════
(function () {
  'use strict';

  const KEY = 'bl_expect_paused';

  const get = k => { try { return localStorage.getItem(k) || ''; } catch (e) { return ''; } };
  const set = (k, v) => { try { localStorage.setItem(k, v); } catch (e) {} };
  const del = k => { try { localStorage.removeItem(k); } catch (e) {} };

  function paused() { return get(KEY) === '1'; }

  // Единственият начин, по който показващият код вижда датата.
  // На пауза връща празно — за всички те това значи „няма бременност“
  // и всичко се гаси само, без да пипаме по десет места.
  function lmp() {
    if (paused()) return '';
    const raw = get('bl_lmp');
    return raw ? raw.replace(/^"|"$/g, '') : '';
  }

  function pause() {
    set(KEY, '1');
    document.dispatchEvent(new CustomEvent('bl:expect'));
  }

  function resume() {
    del(KEY);
    document.dispatchEvent(new CustomEvent('bl:expect'));
  }

  // Има ли изобщо какво да се паузира (за да не показваме превключвател
  // на жена, която никога не е въвеждала дата)
  // 🤍 Беше `!!get('bl_lmp')` — гол ключ, без разопаковане. Празно поле,
  // записано като JSON, оставя низа "" (два символа кавички) и вратарят
  // казваше „да, има бременност". Питаме за самата ДАТА (lmp() маха
  // кавичките); паузата държи превключвателя видим, за да има връщане.
  function has() { return !!lmp() || paused(); }

  window.BL_EXPECT = { paused, pause, resume, lmp, has };
})();
