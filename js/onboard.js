// ═══════════════════════════════════════════════════════════
// ПЪРВО ЗАПОЗНАВАНЕ — топъл onboarding, който прави апп-а личен
// ═══════════════════════════════════════════════════════════
(function () {
  'use strict';
  const $ = id => document.getElementById(id);
  const load = (k, d) => { try { const v = JSON.parse(localStorage.getItem(k)); if (v == null) return d; if (Array.isArray(d) !== Array.isArray(v)) return d; if (d && typeof d === 'object' && (!v || typeof v !== 'object')) return d; return v; } catch (e) { return d; } };
  const save = (k, v) => { try { localStorage.setItem(k, JSON.stringify(v)); } catch (e) {} };

  // днешната дата като „ГГГГ-ММ-ДД“ по МЕСТНО време. Три копия на този израз
  // живееха инлайн из файла; сравняваме низ с низ, за да не влизаме изобщо в
  // капана „new Date('2026-08-19') е полунощ по Гринуич, не тук“.
  const днесНиз = () => { const d = new Date(); return d.getFullYear() + '-' + String(d.getMonth() + 1).padStart(2, '0') + '-' + String(d.getDate()).padStart(2, '0'); };

  let sex = '';   // 04.08: без подразбиращ се пол — кривите на СЗО са различни
  // 22.07 (армия): какво сме сложили АВТОМАТИЧНО в полето за дата. Само то
  //   се чисти при превключване „чакам“ → „роди се“; дата, написана от
  //   мама, не се пипа никога.
  let предложенаОДР = '';

  function open() {
    const baby = load('bl_baby', { name: '', sex: '', birth: '' });
    $('onbName').value = baby.name || '';
    sex = baby.sex || '';
    $('onbSex').querySelectorAll('.onb-sexbtn').forEach(b => b.classList.toggle('on', b.dataset.sex === sex));
    $('onbDate').value = baby.birth || '';
    $('onbDate').max = днесНиз();
    // 🤰 ако мама е бременна (има bl_lmp, няма роден ден) → покажи „Още чакам"
    // и обратно-сметнатата ОДР, за да не вижда „момиче" при редакция (проход 2 №9)
    // 🤍 11.08 (жива обиколка): ТОЗИ четец заобикаляше вратаря BL_EXPECT —
    //    единственият останал в приложението. Измерено наживо с включена пауза
    //    (жена, спряла броенето след загуба): BL_EXPECT.lmp() връща '', а екранът
    //    пак светваше „Още чакам“ и попълваше сметнатата ОДР (2026-11-08) в
    //    полето. Тоест мястото, където тя влиза да си оправи профила, ѝ
    //    пре-утвърждаваше бременността, която е спряла. Паузата НЕ трие нищо:
    //    bl_lmp си стои, „Върни броенето“ в настройките връща и този екран.
    //    Същият израз, който ползват другите ~20 четци.
    //    ПЪТ НАЗАД: `const _lmp = load('bl_lmp', '');`.
    const _lmp = (window.BL_EXPECT && BL_EXPECT.lmp) ? BL_EXPECT.lmp() : load('bl_lmp', '');
    if (!baby.birth && _lmp && !isNaN(new Date(_lmp))) {
      sex = 'wait';
      $('onbSex').querySelectorAll('.onb-sexbtn').forEach(b => b.classList.toggle('on', b.dataset.sex === 'wait'));
      предложенаОДР = new Date(new Date(_lmp).getTime() + 280 * 86400000).toISOString().slice(0, 10);
      $('onbDate').value = предложенаОДР;
    }
    // проход 3 S6: възстанови избраната недоносеност (гестационна седмица)
    if ($('onbPreterm')) $('onbPreterm').value = String(load('bl_preterm', 0) || 0);
    updateDateLbl();
    // 3.3.1: по избор — рождената дата на МАМА (не на бебето), отключва стая 8.
    // Пази СЪЩИЯ ключ bl_me, който вече ползват хороскопа/числото/тарото.
    const me = load('bl_me', { birth: '', name: '' });
    $('onbMeDate').value = me.birth || '';
    // 🔴 19.08 (първата минута, ИЗМЕРЕНО): беше `$('onbDate').max`. Но при
    //    бременна мама updateDateLbl() ТОКУ-ЩО е изчистил max на onbDate (за
    //    очаквана дата няма таван) — и рожденият ден на МАМА оставаше без
    //    таван изобщо. Взима си своя таван сам, а не назаем от чуждо поле.
    //    ПЪТ НАЗАД: `$('onbMeDate').max = $('onbDate').max;`
    $('onbMeDate').max = днесНиз();
    $('onbOverlay').hidden = false;
    document.body.style.overflow = 'hidden';
  }
  function close() {
    try { if (window.BL_GREET) BL_GREET(); } catch (e) {}   // поздравът става личен веднага
    // 🔴 18.08 (жива обиколка на таба „Вход/Профил“): и „Готово“, и „По-късно“
    //    записват bl_onboarded, а profile.js смята надписа на долния бутон
    //    само веднъж — при зареждане. Резултат: бутонът пише „🔑 Вход“, а
    //    отваря профила. Един ред тук държи надписа честен веднага.
    //    ПЪТ НАЗАД: махни следващия ред.
    try { if (window.BL_PROFILE && BL_PROFILE.refresh) BL_PROFILE.refresh(); } catch (e) {}
    $('onbOverlay').hidden = true;
    document.body.style.overflow = '';
  }
  // ═══ 💬 ЕДИН ГЛАС, КОЙТО СТИГА ДО НЕЯ ═══
  // 🔴 19.08 (първата минута, ИЗМЕРЕНО): единственото съобщение за грешка тук
  //    вървеше през BL_FX.cheer — а js/firstday.js ЗАГЛУШАВА cheer за целия
  //    ден, ако мама е избрала тона „🫂 на ръба". Тоест точно жената, чиито
  //    ръце треперят, натиска „Готово", нищо не се записва и НИЩО не ѝ се
  //    казва: формата просто не реагира. Съобщението вече слиза ПОД полето,
  //    за което се отнася, и стои там, докато тя не го оправи.
  //    Без собствен цвят: .onb-lbl вече е var(--ink-soft) и в двете теми
  //    (тъмната обръща контраста — измерено в друг проход).
  //    ПЪТ НАЗАД: върни `if (window.BL_FX && BL_FX.cheer) BL_FX.cheer(текст)`.
  let редГрешка = null;
  function кажи(текст, поле) {
    if (!редГрешка) {
      редГрешка = document.createElement('p');
      редГрешка.className = 'onb-lbl';
      редГрешка.id = 'onbSay';
      try { редГрешка.setAttribute('role', 'alert'); } catch (e) {}
    }
    редГрешка.textContent = текст;
    редГрешка.hidden = false;
    if (поле && поле.insertAdjacentElement) поле.insertAdjacentElement('afterend', редГрешка);
  }
  function мълчи() { if (редГрешка) { редГрешка.hidden = true; редГрешка.textContent = ''; } }
  // спира записа и ОБЯСНЯВА защо — двете винаги заедно
  function спри(поле, текст) {
    поле.classList.add('bl-нужно');
    setTimeout(() => поле.classList.remove('bl-нужно'), 1400);
    кажи(текст, поле);
    if (window.BL_FX && BL_FX.buzz) BL_FX.buzz(10);
  }

  // ОДР → последна менструация → седмицата, която ще види. Смята се ТОЧНО
  // както я смятат preg20.js, home2.js, iface.js и rooms2.js (`new Date(низ)`),
  // за да не може онбордингът да приеме дата, която после никой не показва.
  const одрВлмп = due => new Date(new Date(due).getTime() - 280 * 86400000).toISOString().slice(0, 10);
  function седмицаОт(due) {
    if (!due || isNaN(new Date(due))) return null;
    return Math.floor((Date.now() - new Date(одрВлмп(due))) / 604800000);
  }

  // ═══ 🎁 КАКВО ѝ ДАВА ТОВА ═══
  // 19.08 (първата минута, ИЗМЕРЕНО): от четирите полета три казваха „по
  // желание“, а най-важното — датата — не казваше нито че е по желание, нито
  // какво отключва. Жена, която не е чела нищо, вижда празно поле за дата и
  // има две причини да го подмине: „май е задължително“ или „защо им е“.
  // Един ред, веднъж, без да натяква. (Същият похват като при недоносеността
  // и рождения ден на мама — там го има отдавна и работи.)
  // ПЪТ НАЗАД: махни функцията и извикването ѝ в updateDateLbl.
  let редЗащо = null;
  function защоДатата(waiting) {
    if (!редЗащо) {
      редЗащо = document.createElement('p');
      редЗащо.className = 'onb-lbl onb-lbl-soft';
      редЗащо.id = 'onbWhy';
      редЗащо.style.marginTop = '4px';
      const п = $('onbDate');
      if (!п || !п.insertAdjacentElement) { редЗащо = null; return; }
      п.insertAdjacentElement('afterend', редЗащо);
    }
    // 📏 ИЗМЕРЕНО на 375×812: тези два низа се събират на ЕДИН ред (17px).
    //    По-дългият вариант („Оттам излизат възрастта…“, 50 знака) се пренася
    //    на два и вдига картата с 40px вместо с 22px — а „Готово“ на този
    //    екран и без това е на ръба на видимото. Ако някой ги удължи, ще
    //    плати височина; dev/parvata_minuta.js мери и това.
    редЗащо.textContent = waiting
      ? 'Оттам са седмиците и броенето до термина.'
      : 'Оттам са възрастта, ваксините и захранването.';
  }

  function updateDateLbl() {
    const waiting = sex === 'wait';
    $('onbDateLbl').textContent = waiting ? 'Очаквана дата на раждане (по желание):' : 'Рождена дата (по желание):';
    защоДатата(waiting);
    $('onbDate').max = waiting ? '' : днесНиз();
    // проход 3 S6: полето за недоносеност има смисъл само за РОДЕНО бебе (не за чакащата)
    const pw = $('onbPretermWrap'); if (pw) pw.hidden = waiting;
  }

  document.addEventListener('DOMContentLoaded', () => {
    if (!$('onbOverlay')) return;
    $('onbSex').addEventListener('click', e => {
      const b = e.target.closest('.onb-sexbtn'); if (!b) return;
      const предишен = sex;
      sex = b.dataset.sex;
      // 🚨 22.07 (армия): при „Още чакам“ в полето стои ОБРАТНО СМЕТНАТАТА ОДР.
      //   Натиснеше ли „Момиче/Момче“ след раждането, сменяше се само етикетът
      //   и мама записваше ОЧАКВАНАТА дата като рождена — с едно докосване.
      //   Оттам тръгват сгрешени възраст, ваксинационен календар и захранване.
      //   Чистим само нашето предложение, не и нейн текст.
      if (предишен === 'wait' && sex !== 'wait' && предложенаОДР &&
          $('onbDate').value === предложенаОДР) {
        $('onbDate').value = '';
        предложенаОДР = '';
      }
      $('onbSex').querySelectorAll('.onb-sexbtn').forEach(x => x.classList.toggle('on', x === b));
      мълчи();   // съобщението беше за старото състояние — не бива да я гони
      updateDateLbl();
    });
    $('onbSave').addEventListener('click', () => {
      const waiting = sex === 'wait';
      мълчи();
      // и втори предпазител: рождена дата в бъдещето прави BL_AGE null и цялото
      // приложение се държи, все едно няма бебе. По-добре питаме сега.
      if (!waiting && $('onbDate').value) {
        const д = new Date($('onbDate').value);
        if (!isNaN(д) && д.getTime() > Date.now() + 86400000) {
          return спри($('onbDate'), 'Тази дата е в бъдещето 💛 Ако още чакаш — избери „Още чакам“.');
        }
      }
      // 🤰 19.08 (първата минута, ИЗМЕРЕНО): очакваната дата нямаше НИКАКВА
      //    проверка — при „Още чакам" полето дори си маха `max`. Сгрешена
      //    година е най-обикновената грешка в поле за дата на телефон, а
      //    цената ѝ се плаща на първия екран: термин отпреди 400 дни даваше
      //    „Седмица 97 🤰" (rooms2.js не реже отгоре), а термин след 2 години —
      //    „Седмица 1 🤰 · още 795 дни до срещата". И в двата случая тя вижда
      //    уверено число, което е лъжа, и няма как да разбере какво е сбъркала.
      //    Границата НЕ Е моя измислица: това е точно обхватът, който всички
      //    четци вече показват (preg20 МАКС_С=45, home2/iface `w>=1 && w<=45`).
      //    Извън него приложението и без това мълчи — сега поне казва защо.
      //    ПЪТ НАЗАД: махни целия блок долу.
      if (waiting && $('onbDate').value) {
        const с = седмицаОт($('onbDate').value);
        if (с !== null && (с < 1 || с > 45)) {
          return спри($('onbDate'), с < 1
            ? 'Този термин е много напред 💛 Провери годината — бременността се брои до към 9 месеца напред.'
            : 'Този термин е минал отдавна 💛 Провери годината — а ако бебето вече е тук, избери „Момиче“ или „Момче“.');
        }
      }
      // 🔴 19.08 (първата минута, ИЗМЕРЕНО): рожденият ден на МАМА нямаше
      //    НИКАКВА проверка в кода — само атрибут `max`, който е подсказка за
      //    календарчето и не спира нищо (а при бременна беше и празен, виж
      //    open()). Сгрешена година тръгваше право към хороскопа, числото и
      //    таро картите в „Жената в мен“ — на човек, който още не е роден.
      //    Сравняваме НИЗ с НИЗ: никакви часови пояси.
      //    ПЪТ НАЗАД: махни следващите три реда.
      if ($('onbMeDate').value && $('onbMeDate').value > днесНиз()) {
        return спри($('onbMeDate'), 'Тази дата е в бъдещето 💛 Тук е твоят рожден ден — провери годината.');
      }
      const baby = { name: $('onbName').value.trim(), sex: waiting ? '' : sex, birth: waiting ? '' : $('onbDate').value };
      save('bl_baby', baby);
      // 🤰 БРЕМЕННАТА (одит-флот П23, проход 2 №1): очакваната дата на раждане
      // отваря ЦЯЛАТА бременностна машина (седмици, калкулатор, приспиване на
      // стаите). Досега датата се ИЗХВЪРЛЯШЕ и апп-ът стоеше празен пред точно
      // тази майка. Пазим bl_lmp (последна менструация = ОДР − 280 дни), както
      // preg20/BL_EXPECT очакват; иначе чистим, ако е избрала друго.
      if (waiting) {
        const due = $('onbDate').value;
        if (due && !isNaN(new Date(due))) {
          save('bl_lmp', одрВлмп(due));   // същата сметка, която току-що провери седмицата
          // 🤍 19.08 (първата минута, ИЗМЕРЕНО): паузата на очакването гаси
          //    и шестте четеца на датата. Жена, спряла броенето след загуба,
          //    влиза пак, избира „Още чакам“ и въвежда НОВ термин — датата
          //    се записваше в bl_lmp, а екранът ѝ оставаше тъмен: нула
          //    седмици, нула броене, нула писма. Единственият ѝ изход беше
          //    превключвател в настройките, за който не знае, че съществува.
          //    Паузата пази СТАРАТА бременност — тя не е забрана за нова.
          //    Когато е на пауза, вратарят връща '' и полето се отваря
          //    ПРАЗНО (виж open() по-горе) — значи този термин е несъмнено
          //    нов и написан от нея сега. Нищо не се трие; само пускаме
          //    броенето, което тя току-що поиска. Не приложението решава
          //    кога — тя вече е решила, с датата.
          //    ПЪТ НАЗАД: махни следващия ред.
          try { if (window.BL_EXPECT && BL_EXPECT.paused && BL_EXPECT.paused()) BL_EXPECT.resume(); } catch (e) {}
        }
      } else if ($('onbDate').value) {
        localStorage.removeItem('bl_lmp');   // роди се → бременността приключи
        // без bl_lmp паузата няма какво да пази: остава само да държи
        // „▶️ Пусни отново броенето до термина“ видимо в настройките завинаги,
        // пред мама с бебе на ръце. ПЪТ НАЗАД: махни следващия ред.
        try { if (window.BL_EXPECT && BL_EXPECT.paused && BL_EXPECT.paused()) BL_EXPECT.resume(); } catch (e) {}
      }
      // проход 3 S6: недоносеност (само за родено бебе) — коригираната възраст
      // мери развитието/храните/съня; ageFromBirth приема гестационни седмици 24-36.
      if (!waiting && $('onbPreterm')) {
        const gc = parseInt($('onbPreterm').value, 10) || 0;
        if (gc >= 24 && gc <= 36) save('bl_preterm', gc); else localStorage.removeItem('bl_preterm');
      }
      // по избор: рождената дата на мама, ако я е дала
      const meDate = $('onbMeDate').value;
      if (meDate) { const me = load('bl_me', { birth: '', name: '' }); save('bl_me', { name: me.name || '', birth: meDate }); }
      save('bl_onboarded', true);
      // проход 4: най-топлият пръв момент — мека вибрация + лично „здравей".
      if (window.BL_FX) { BL_FX.buzz(14); if (BL_FX.cheer) BL_FX.cheer('Здравей 💜 Радвам се, че сте тук.'); }
      close();
      if (window.refreshToday) window.refreshToday();
      // 🤰 проход 2 №8: бременната да ВИДИ какво отключи датата ѝ — водим я
      // право в събудената стая, вместо да я оставим да я търси сама
      if (waiting && $('onbDate').value && window.MamaHelper) {
        setTimeout(() => { try { MamaHelper.open('Бременност'); } catch (e) {} }, 450);
      }
    });
    $('onbSkip').addEventListener('click', () => { save('bl_onboarded', true); close(); });
    // клик на фона = само затваряне, БЕЗ отписване — случайно докосване не
    // бива да убие меката покана завинаги (одит-флот П23, проход 2 №12);
    // трайното „не ми показвай повече" е само изричният бутон „Прескочи".
    $('onbOverlay').addEventListener('click', e => { if (e.target === $('onbOverlay')) close(); });

    // първо посещение → меко покани (веднъж). НО изчакай обиколката: на самото
    // първо пускане турът е пълноекранен; двата оверлея се блъскаха (онбордингът
    // дори отключваше скрола, докато турът е още отворен). Затова автопоканата
    // тръгва само СЛЕД като турът е приключил (bl_tour_done). При първо пускане
    // самият тур пуска онбординга след себе си (home.js close()).
    let турГотов = false; try { турГотов = !!localStorage.getItem('bl_tour_done'); } catch (e) {}
    if (турГотов && !load('bl_onboarded', false) && !load('bl_baby', { birth: '' }).birth) {
      setTimeout(open, 900);
    }
  });

  window.BL_ONBOARD = { open, close };
})();
