const коя = (t, стая) => {
  const m = W.BL_MOTHERFLAG(t, стая); if (m) return { вид: "ГЕЙТ", id: "motherflag:" + m };
  // 🔴 НАМЕРЕНО 30.09: BL_PREGFLAG ГЪРМИ (ReferenceError заБебетоТук) —
  //    helper.js:3668/3680. В живото приложение викащият на helper.js:4132
  //    НЕ е в try/catch → майката не получава НИКАКЪВ отговор.
  try { if (W.BL_PREGFLAG(t, стая)) return { вид: "ГЕЙТ", id: "pregflag" }; }
  catch (e) { return { вид: "ГРЪМ", id: "ГРЪМ:pregLevel " + e.message }; }
  if (W.BL_REDFLAG(t)) return { вид: "ГЕЙТ", id: "redflag" };
  const k = W.BL_MATCH(t, стая);
  if (!k) return { вид: "ТИШИНА", id: "ТИШИНА" };
  return { вид: "КАРТА", id: k.id, title: k.title, room: k.room };
};

