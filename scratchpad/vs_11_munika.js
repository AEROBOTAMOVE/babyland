const { zaredi } = require('../dev/pyasachnik.js');
const A = zaredi(null, { памет: { bl_baby: { birth: '2025-11-20' } } });
const к = r => r ? (r.room + '::' + r.id) : 'ТИШИНА';
const тройки = [
  ['Инструменти','протече по гърба навън','протече по гърба на мъника навън','протече по гърба на бебето навън'],
  ['Моето бебе','на гости къде да го приспя','на гости къде да приспя мъника','на гости къде да приспя бебето'],
  ['Моето бебе','колко спи бебето','колко спи мъника','колко спи пиленцето'],
  ['Захранване','кога да започна захранването','кога да започна захранването на мъника','кога да започна захранването на бебето'],
  ['Моето бебе','плаче през цялата баня','мъника плаче през цялата баня','пиленцето плаче през цялата баня'],
  ['Инструменти','колко пелени на ден','колко пелени на ден за мъника','колко пелени на ден за пиленцето'],
];
let счупени = 0, общо = 0;
for (const [ст, гол, сГален, сБебе] of тройки) {
  const a = A.BL_MATCH(гол, ст), b = A.BL_MATCH(сГален, ст), c = A.BL_MATCH(сБебе, ст);
  const счупиГален = a && (!b || a.id !== b.id);
  const счупиБебе  = a && (!c || a.id !== c.id);
  общо += 2; if (счупиГален) счупени++; if (счупиБебе) счупени++;
  console.log('[' + ст + ']');
  console.log('  гол            « ' + гол     + ' » → ' + к(a));
  console.log('  ' + (счупиГален?'СЧУПИ':'държи') + ' галено  « ' + сГален + ' » → ' + к(b));
  console.log('  ' + (счупиБебе ?'СЧУПИ':'държи') + ' «бебето» « ' + сБебе  + ' » → ' + к(c));
}
console.log('\nСЧУПЕНИ ОТ ДОБАВЕНА ДУМА В СРЕДАТА: ' + счупени + '/' + общо);

