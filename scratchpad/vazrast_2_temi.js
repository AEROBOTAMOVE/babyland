// 🔴 ПЛАТЕНО С КОНТРОЛА (30.09): първата версия ползваше `\b` около кирилски
//    думи. В JS без /u кирилицата НЕ е \w, значи `\bмесеца\b` не съвпада НИКОГА.
//    Контролното изречение „На 6 месеца бебето сяда" даде НУЛА шаблона — ако
//    бях повярвал на нулата, докладът щеше да каже „0 карти назовават възраст".
//    Сега границите са изрични lookaround-и по буква.
// ПЪТ НАЗАД: само чете.
const fs = require('fs');
const { zaredi } = require('../dev/pyasachnik.js');
const W = zaredi(null, { памет: { bl_baby: { birth: '2025-11-20' } } });
const KB = W.BL_KB || W.KB;
const E = KB.entries;

const Л = 'А-Яа-яA-Za-zЀ-ӿ';             // буква (вкл. кирилица)
const НЛ = `(?<![${Л}])`, НД = `(?![${Л}])`;  // не-буква отляво / отдясно
const R = (тяло, f = 'gi') => new RegExp(НЛ + тяло + НД, f);

const текст = e => [e.title, e.core, e.tip, e.follow, ...(e.keys || [])].filter(Boolean).join(' \n ');

// ── шаблони за възраст в ТЕКСТА ────────────────────────────────────────
const ШАБЛОНИ = [
  ['месеци', R('(\\d{1,2}|един|два|две|три|четири|пет|шест|седем|осем|девет|десет|единай?найсет|единадесет|дванай?сет|дванадесет|осемнай?сет|осемнадесет)\\s*(?:-|–|—|до|и)?\\s*(?:\\d{1,2})?\\s*(?:-|–|—)?\\s*(?:месеца|месец|месеци)')],
  ['редни_месец', R('(първи|втори|трети|четвърти|пети|шести|седми|осми|девети|десети|единайсети|дванайсети)(?:ят|я)?\\s+месец')],
  ['години', R('(\\d{1,2}|една|две|три|четири|пет|шест|седем)\\s*(?:-|–|—|до|и)?\\s*(?:\\d{1,2})?\\s*(?:годин[аи]|годинки|г\\.)')],
  ['седмици', R('(\\d{1,2})\\s*(?:-|–|—|до|и)?\\s*(?:\\d{1,2})?\\s*(?:-|–|—)?\\s*(?:седмица|седмици|седмична|седмичн[аио])')],
  ['новородено', R('(новородено|новороденото|новородени|първите дни|първата седмица|първия месец|първите седмици|първите месеци)')],
  ['дни', R('(\\d{1,2})\\s*(?:-|–|—|до)?\\s*(?:\\d{1,2})?\\s*(?:дни|дена|ден)')],
];

// ── КОНТРОЛА: уредът вижда ли? ──────────────────────────────────────────
const к1 = 'На 6 месеца бебето сяда само, а на 12 месеца прави първи стъпки. На 2 години говори.';
const к2 = 'Кремът за стрии не трие стрия, мажи заради усещането след душ.';
const гърми = s => ШАБЛОНИ.filter(([, rx]) => { rx.lastIndex = 0; return rx.test(s); }).map(([и]) => и);
const в1 = гърми(к1), в2 = гърми(к2);
console.log('КОНТРОЛА+ · изречение С месеци/години →', в1.length, 'шаблона:', в1.join(', ') || '—',
  в1.length >= 2 ? '· ОК вижда' : '· !!! СЛЯП');
console.log('КОНТРОЛА− · изречение БЕЗ възраст   →', в2.length, 'шаблона:', в2.join(', ') || '—',
  в2.length === 0 ? '· ОК не гърми напразно' : '· !!! ЛЪЖЛИВО ПОЛОЖИТЕЛНО');
if (в1.length < 2 || в2.length > 0) { console.log('СПИРАМ — уредът не е годен.'); process.exit(2); }

const без = E.filter(e => e.от == null && e.до == null);
const сИмат = E.filter(e => e.от != null || e.до != null);

function намери(e) {
  const t = текст(e); const хит = [];
  for (const [име, rx] of ШАБЛОНИ) { rx.lastIndex = 0; let m; while ((m = rx.exec(t))) хит.push(име + ':' + m[0].trim()); }
  return хит;
}

const базаХит = сИмат.filter(e => намери(e).length > 0).length;
console.log('\nБАЗА  · от', сИмат.length, 'карти С поле `от`/`до`, назоваваат възраст в текста:',
  базаХит, '(' + (100 * базаХит / сИмат.length).toFixed(0) + '%)');
const безХит = без.filter(e => намери(e).length > 0);
console.log('МЯРКА · от', без.length, 'карти БЕЗ поле, назоваваат възраст в текста:',
  безХит.length, '(' + (100 * безХит.length / без.length).toFixed(0) + '%)');
console.log('МЯРКА · без поле И без възраст в текста:', без.length - безХит.length);

// ── тематични маркери ───────────────────────────────────────────────────
const ТЕМИ = {
  'МАЙКАТА': R('(зърна|гърдите ми|млякото ми|шевове|епизиотом|цезарово|следродилн|лохии|тазово дъно|отслабван|косопад|менструац|цикъл|контрацепц|овулац|либидо|депресия|тревожност|самота|вина|гняв|изтощение|психолог|терапия|отпуск|моето тяло|за мен|мама е|майката е)'),
  'ПАРТНЬОР/СЕМЕЙСТВО': R('(партньор|мъжът ми|бащата|татко|секс|двойка|свекърв|майка ми|роднини|подкрепа|семейството)'),
  'БРЕМЕННОСТ': R('(бременн|бременност|контракции|изтичане на води|акушер|женска консултация|плода|матката|тест за бременност|раждането)'),
  'ИНСТРУМЕНТ/ПЛАТФОРМА': R('(дневник|таймер|бутон|екран|приложението|чеклист|напомнян|график|калкулатор|настройк|профил|офлайн|инсталир|как работи приложението)'),
  'СПЕШНО/БЕЗОПАСНОСТ': R('(спешно|линейк|112|задушав|давене|изгарян|попарв|отравян|глътна|сътресение|гърч|припадък|менингит|анафилакс|червен флаг)'),
  'ЕТАП НА БЕБЕТО': R('(сяда|проговар|прохожда|пълзи|обръща се|първи зъб|зъбче|гука|срича|първи думи|първи стъпки|моторик|етап|умения|ясла|градина|гърне|памперс)'),
  'ХРАНЕНЕ ПО МЕСЕЦИ': R('(захранван|първа хапка|пюре|твърда храна|адаптирано мляко|шише|кърма|отбиван|глутен|алерген|BLW|лъжичк)'),
  'СЪН ПО ВЪЗРАСТ': R('(дрямк|нощно будене|регресия|приспиван|креватче|безопасен сън|колко спи)'),
};
const темаНа = e => { const t = текст(e); return Object.entries(ТЕМИ).filter(([, rx]) => { rx.lastIndex = 0; return rx.test(t); }).map(([k]) => k); };

const групи = {};
for (const e of без) { const к = темаНа(e); (к.length ? к : ['(без маркер)']).forEach(k => групи[k] = (групи[k] || 0) + 1); }
console.log('\n=== 591-те по ТЕМА (карта може да падне в няколко) ===');
Object.entries(групи).sort((a, b) => b[1] - a[1]).forEach(([k, v]) => console.log(String(v).padStart(5), k));

// ── стая × назовава-ли-възраст ──────────────────────────────────────────
const мат = new Map();
for (const e of без) { const r = e.room || '(без стая)'; if (!мат.has(r)) мат.set(r, [0, 0]); const c = мат.get(r); c[0]++; if (намери(e).length) c[1]++; }
console.log('\n=== СТАЯ · без поле / от тях НАЗОВАВАТ възраст в текста ===');
[...мат.entries()].sort((a, b) => b[1][1] - a[1][1]).forEach(([r, [a, b]]) =>
  console.log(String(r).padEnd(26), String(a).padStart(4), '→', String(b).padStart(4), '(' + (100 * b / a).toFixed(0) + '%)'));

fs.writeFileSync(__dirname + '/_bez_vazrast_pyln.json', JSON.stringify(без.map(e => ({
  id: e.id, room: e.room || null, title: e.title || null,
  хит: намери(e).slice(0, 8), теми: темаНа(e), keys0: (e.keys || []).slice(0, 5),
  core: (e.core || '').slice(0, 260),
})), null, 1), 'utf8');
console.log('\nзаписах scratchpad/_bez_vazrast_pyln.json');
