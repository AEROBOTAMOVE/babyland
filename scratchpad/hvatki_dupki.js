function ред(т) {
  const rf = !!W.BL_REDFLAG(т);
  const mf = !!(W.BL_MOTHERFLAG && W.BL_MOTHERFLAG(т, 'Здраве и SOS'));
  const с = W.__СЦЕН(т);
  // хватките се СМЯТАТ само вътре в `if (isRedFlag(text))` и САМО ако майчиният
  // флаг не е върнал по-рано — това е живият път, не само решетката
  const стига = rf && !mf && !!(с && с !== 'poglatnat' && ИМА.has(с));
  const e = W.BL_MATCH(т, 'Здраве и SOS');
  return { т, rf, mf, с, стига, карта: e ? e.id : null };
}

function групa(име, списък) {
  console.log('### ' + име);
  let к = 0;
  for (const т of списък) {
    const r = ред(т);
    if (r.стига) к++;
    console.log('  ' + (r.стига ? '🚑 ' : '❌ ') + r.т.padEnd(40) +
      ' флаг:' + (r.rf ? 'ДА ' : 'не ') + ' майчин:' + (r.mf ? 'ДА ' : 'не ') +
      ' сцен:' + String(r.с).padEnd(9) + ' карта:' + r.карта);
  }
  console.log('  → ХВАТКИ СТИГАТ при ' + к + ' от ' + списък.length + '\n');
  return [к, списък.length];
}

