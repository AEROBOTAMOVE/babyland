// САМО ЧЕТЕ. Диагноза: липсват ли ДУМИ (галени имена, „скука") или СЪДЪРЖАНИЕ.
'use strict';
const path = require('path'), fs = require('fs');
const КОРЕН = path.resolve(__dirname, '..');
const { zaredi } = require(path.join(КОРЕН, 'dev/pyasachnik.js'));
const W = zaredi(null, { памет: { bl_baby: { birth: '2025-11-20' } } });
const KB = W.BL_KB || W.KB;

const питай = (т, с) => {
  const р = W.BL_MATCH(т, с);
  const з = Array.isArray(р) ? р[0] : (р && (р.entry || р.item || р));
  return з && з.id ? (з.id + ' «' + з.title + '» [' + з.room + ']') : null;
};

// ── 1. ГАЛЕНИТЕ ИМЕНА: има ли ги В ключовете ИЛИ в речника на синонимите?
const ГАЛЕНИ = ['мъник', 'пиленц', 'пиле', 'мъничк', 'зайче', 'мецан', 'бонбонч', 'сладур',
  'принцес', 'мъжле', 'малчуг', 'дребосъч', 'коремч', 'крачет', 'ръчичк', 'главичк'];
console.log('═══ 1. ГАЛЕНИ / УМАЛИТЕЛНИ В КЛЮЧОВЕТЕ (цялата база, 1621 карти) ═══');
for (const г of ГАЛЕНИ) {
  const карти = [];
  for (const e of KB.entries) for (const k of (e.keys || []))
    if (String(k).toLowerCase().includes(г)) { карти.push(e.id + ':' + k); break; }
  console.log('  „' + г + '" → ' + карти.length + ' карти' + (карти.length ? '  ' + карти.slice(0, 4).join(' · ') : ''));
}

// речникът на синонимите — там ли се превеждат?
console.log('');
console.log('═══ 1б. В РЕЧНИКА НА СИНОНИМИТЕ (SYN / SYN_ФРАЗИ) ═══');
const helperSrc = fs.readFileSync(path.join(КОРЕН, 'js/helper.js'), 'utf8');
for (const г of ГАЛЕНИ) {
  const намерен = new RegExp('[\'"„]' + г + '[а-яьъ]*[\'"“]\\s*:').test(helperSrc) ||
    new RegExp('\\b' + г + '[а-яьъ]*\\s*:\\s*[\'"]').test(helperSrc);
  console.log('  „' + г + '" в helper.js като ключ на речник: ' + (намерен ? 'ДА' : 'НЕ'));
}

// жива проба: сменяме само галената дума и гледаме дали отговорът пада
console.log('');
console.log('═══ 1в. ЖИВА ПРОБА: същото изречение, само думата за детето сменена ═══');
const ДВОЙКИ = [
  ['как да работя от вкъщи като бебето е при мен', 'как да работя от вкъщи като мъника е при мен', 'Жената в мен'],
  ['караме се повече откакто се роди бебето', 'караме се повече откакто се роди мъника', 'Дневник на мама'],
  ['цял ден не съм говорила с жив човек само с бебето', 'цял ден не съм говорила с жив човек само с мъника', 'Дневник на мама'],
  ['той се прибира и бебето светва', 'той се прибира и пиленцето светва', 'Дневник на мама'],
];
for (const [а, б, с] of ДВОЙКИ) {
  console.log('  [' + с + ']');
  console.log('     „бебето"  → ' + питай(а, с));
  console.log('     галено    → ' + питай(б, с));
}

// ── 2. ДУМАТА „СКУКА" — на кого принадлежи
console.log('');
console.log('═══ 2. КОЙ ДЪРЖИ ДУМИТЕ ЗА СКУКА ═══');
for (const д of ['скука', 'скучно', 'скучае', 'отегч', 'омръзна', 'едно и също', 'един и същ']) {
  const карти = [];
  for (const e of KB.entries) for (const k of (e.keys || []))
    if (String(k).toLowerCase().includes(д)) карти.push(e.id + '[' + e.room + ']:„' + k + '"');
  console.log('  „' + д + '" → ' + карти.length + ': ' + карти.slice(0, 8).join(' · '));
}

// ── 3. ИМА ЛИ СЪДЪРЖАНИЕ ЗА „ТАТКО Е ЗАБАВНИЯТ, АЗ СЪМ ЛОШАТА"
console.log('');
console.log('═══ 3. ТЪРСЯ СЪДЪРЖАНИЕ: „татко е забавният, аз съм тази с правилата" ═══');
const ТЪРСЕНЕ = ['забавн', 'лошото ченге', 'аз съм лошата', 'забранява', 'правилата', 'дисциплин',
  'добрият родител', 'лошият родител', 'разглези'];
for (const т of ТЪРСЕНЕ) {
  const карти = [];
  for (const e of KB.entries) {
    const съвп = (e.keys || []).find(k => String(k).toLowerCase().includes(т));
    if (съвп) карти.push(e.id + '[' + e.room + ']«' + e.title + '»:„' + съвп + '"');
  }
  console.log('  „' + т + '" → ' + карти.length + (карти.length ? '\n        ' + карти.slice(0, 6).join('\n        ') : ''));
}
const заглавия = KB.entries.filter(e => /забавн|лоша|лошия|строг|правила|забран/i.test(e.title))
  .map(e => e.id + '[' + e.room + ']«' + e.title + '»');
console.log('  заглавия, които звучат по темата: ' + заглавия.length + '\n        ' + заглавия.join('\n        '));

// ── 4. ЛАКОМИЯТ КЛЮЧ „срам ме е"
console.log('');
console.log('═══ 4. ЛАКОМИ ГОЛИ КЛЮЧОВЕ ═══');
for (const k of ['срам ме е', 'сравнявам се', 'виновна', 'сама съм', 'скучно', 'крещя']) {
  const държат = KB.entries.filter(e => (e.keys || []).some(x => String(x).toLowerCase().trim() === k))
    .map(e => e.id + '[' + e.room + ']');
  console.log('  гол ключ „' + k + '" държан от: ' + (държат.join(' · ') || 'никой'));
}
