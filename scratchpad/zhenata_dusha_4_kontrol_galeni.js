// САМО ЧЕТЕ. Контрол: галените имена ли късат отговора, или не?
// Пускам ВСИЧКИТЕ 60 въпроса два пъти: както са, и с „мъника/пиленцето" → „бебето".
'use strict';
const path = require('path'), fs = require('fs');
const КОРЕН = path.resolve(__dirname, '..');
const { zaredi } = require(path.join(КОРЕН, 'dev/pyasachnik.js'));
const W = zaredi(null, { памет: { bl_baby: { birth: '2025-11-20' } } });
const KB = W.BL_KB || W.KB;
const поId = new Map(KB.entries.map(e => [e.id, e]));
const питай = (т, с) => {
  const р = W.BL_MATCH(т, с);
  const з = Array.isArray(р) ? р[0] : (р && (р.entry || р.item || р));
  return з && з.id ? з.id : null;
};

const ИЗХОД = JSON.parse(fs.readFileSync(path.join(__dirname, 'zhenata_dusha_1_out.json'), 'utf8'));
const РЕД = ИЗХОД.РЕД;

const обезгален = т => т
  .replace(/мъника/g, 'бебето').replace(/мъникът/g, 'бебето')
  .replace(/пиленцето/g, 'бебето').replace(/пиленце/g, 'бебето');

let сменени = 0, промени = 0, спечелени = 0, загубени = 0;
const редове = [];
for (let i = 0; i < РЕД.length; i++) {
  const р = РЕД[i];
  const б = обезгален(р.въпрос);
  if (б === р.въпрос) continue;
  сменени++;
  const нов = питай(б, р.стая);
  const видНов = !нов ? 'ТИШИНА' : (р.чакани.includes(нов) ? 'ВЯРНА' : 'ЧУЖДА');
  if (нов !== р.id) промени++;
  if (видНов === 'ВЯРНА' && р.вид !== 'ВЯРНА') спечелени++;
  if (видНов !== 'ВЯРНА' && р.вид === 'ВЯРНА') загубени++;
  редове.push('  ' + String(i + 1).padStart(2) + '. „' + р.въпрос + '"\n' +
    '        с галено → ' + р.вид + ' ' + р.id + '\n' +
    '        с „бебето" → ' + видНов + ' ' + нов);
}
console.log('═══ КОНТРОЛ НА ГАЛЕНИТЕ ИМЕНА ═══');
console.log('въпроси с галено име: ' + сменени);
console.log(редове.join('\n'));
console.log('смени на отговора след обезгаляване: ' + промени);
console.log('спечелени верни: ' + спечелени + ' · загубени верни: ' + загубени);
console.log('ИЗВОД: ' + (спечелени === 0 && загубени === 0
  ? 'галената дума НЕ мени нищо — не е тя причината'
  : 'галената дума МЕНИ резултата'));

