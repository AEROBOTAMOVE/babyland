// Кои чат-думи НАИСТИНА чупят маршрута: взима СЪЩЕСТВУВАЩ ключ, сменя една дума,
// и гледа дали картата остава същата. 6 проби на дума, за да не съдя по една.
const { zaredi } = require('../dev/pyasachnik.js');
const A = zaredi(null, { памет: { bl_baby: { birth: '2025-11-20' } } });
const e = (A.BL_KB || A.KB).entries;
const двойки = [
  ['трябва','требва'], ['къде','где'], ['няма','нема'], ['какво','кво'],
  ['върти','врти'], ['казва','вика'], ['плаче','пищи'], ['плаче','реве'],
  ['главата','главичката'], ['дупето','дупенцето'], ['пелената','пеленката'],
  ['носа','нослето'], ['бебето','мъника'], ['бебето','пиленцето'],
  ['мия','измия'], ['не успявам','не смогвам'],
];
console.log('дума'.padEnd(26) + 'проби  държи  СЧУПИ');
const итог = [];
for (const [кн, раз] of двойки) {
  const рег = new RegExp('(^|[^а-яА-Я])' + кн + '([^а-яА-Я]|$)');
  const проби = [];
  for (const c of e) {
    if (проби.length >= 6) break;
    const k = (c.keys||[]).find(k => рег.test(String(k)) && String(k).length > 12);
    if (k) проби.push([c.room, k, c.id]);
  }
  let държи = 0, счупи = 0;
  const примери = [];
  for (const [ст, k, соб] of проби) {
    const нов = String(k).replace(рег, (m,a,b) => a + раз + b);
    const b = A.BL_MATCH(нов, ст);
    const a = A.BL_MATCH(k, ст);
    if (!a || a.id !== соб) continue;             // изходната проба не е чиста — прескача
    if (b && b.id === соб) държи++; else { счупи++; примери.push(нов + ' → ' + (b?b.id:'ТИШИНА') + ' (вместо ' + соб + ')'); }
  }
  итог.push([кн + ' → ' + раз, държи + счупи, държи, счупи, примери]);
  console.log((кн + ' → ' + раз).padEnd(26) + String(държи+счупи).padStart(5) + String(държи).padStart(7) + String(счупи).padStart(7));
}
console.log('\n═══ ПРИМЕРИ ЗА СЧУПВАНЕ ═══');
for (const [име,,,с,прим] of итог) if (с) { console.log(' ' + име + ':'); for (const p of прим.slice(0,2)) console.log('    « ' + p + ' »'); }
