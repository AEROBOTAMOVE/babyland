// КОНТРОЛИРАН ОПИТ: същият въпрос, сменена САМО една дума (книжна → разговорна).
const { zaredi } = require('../dev/pyasachnik.js');
const A = zaredi(null, { памет: { bl_baby: { birth: '2025-11-20' } } });
const к = r => r ? (r.room + '::' + r.id) : 'ТИШИНА';
const двойки = [
  ['Инструменти','трябва ли ми стерилизатор','требва ли ми стерилизатор'],
  ['Моето бебе','къде да го приспя на гости','где да го приспя на гости'],
  ['Инструменти','няма къде да го преповия навън','нема где да го преповия навън'],
  ['Моето бебе','върти се докато го преповивам','врти се докато го преповивам'],
  ['Инструменти','какво да сложа в куфара','кво да сложа в куфара'],
  ['Моето бебе','баба казва че ще го разглезя','баба вика че ще го разглезя'],
  ['Моето бебе','плаче през цялата баня','пищи през цялата баня'],
  ['Моето бебе','червено е дупето','дупенцето е червено'],
  ['Моето бебе','как да мия главата без сълзи','как да измия главичката без сълзи'],
  ['Инструменти','трябва ли да гладя','требва ли да гладя'],
  ['Моето бебе','колко често да сменям пелената','колко често да сменям пеленката'],
  ['Инструменти','колко пелени трябват на месец','колко пелени требват на месец'],
];
let счупени = 0;
console.log('══════ КНИЖНО → РАЗГОВОРНО ══════');
for (const [ст, кн, раз] of двойки) {
  const a = A.BL_MATCH(кн, ст), b = A.BL_MATCH(раз, ст);
  const счупи = (a && (!b || a.id !== b.id));
  if (счупи) счупени++;
  console.log((счупи ? 'СЧУПИ ' : 'държи ') + '[' + ст + ']');
  console.log('        « ' + кн  + ' » → ' + к(a));
  console.log('        « ' + раз + ' » → ' + к(b));
}
console.log('\nСЧУПЕНИ ОТ ЕДНА ДУМА: ' + счупени + '/' + двойки.length);
