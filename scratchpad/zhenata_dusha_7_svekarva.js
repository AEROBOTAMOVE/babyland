'use strict';
const path = require('path');
const КОРЕН = path.resolve(__dirname, '..');
const { zaredi } = require(path.join(КОРЕН, 'dev/pyasachnik.js'));

const ВЪПРОС = 'свекърва ми се обиди че не я пускам да спи при нас';
const СТАЯ = 'Жената в мен';
const ПАЗЯ = [
  ['може ли да спи с нас в леглото', 'Моето бебе', 'nm-kade-spi'],
  ['иска да спи при нас', 'Моето бебе', 'nm-kade-spi'],
  ['да спи при нас', 'Моето бебе', 'nm-kade-spi'],
  ['буди се нощем и иска в нашето легло', 'Моето бебе', 'nm-kade-spi'],
  ['свекърва ми се меси във всичко', 'Жената в мен', 'nia-svekarva'],
];

const КАНДИДАТИ = [
  ['свекърва ми се обиди че не я пускам'],
  ['не я пускам да спи при нас'],
  ['свекърва ми иска да остане да спи у нас'],
  ['свекърва ми се обиди че не я пускам', 'не я пускам да спи при нас'],
  ['свекърва ми се обиди че не я пускам', 'свекърва ми иска да остане да спи у нас'],
];

for (const набор of КАНДИДАТИ) {
  const W = zaredi(null, { памет: { bl_baby: { birth: '2025-11-20' } } });
  const KB = W.BL_KB || W.KB;
  const e = KB.entries.find(x => x.id === 'nia-svekarva');
  for (const k of набор) e.keys.push(k);
  const питай = (т, с) => {
    const р = W.BL_MATCH(т, с);
    const з = Array.isArray(р) ? р[0] : (р && (р.entry || р.item || р));
    return з && з.id ? з.id : null;
  };
  if (питай('зжбкт пшшш кврлмн', СТАЯ) !== null) throw new Error('пробата ослепя');
  const резултат = питай(ВЪПРОС, СТАЯ);
  const счупени = ПАЗЯ.filter(([т, с, ч]) => питай(т, с) !== ч);
  console.log('набор: ' + набор.map(x => '„' + x + '"').join(' + '));
  console.log('   въпросът → ' + резултат + (резултат === 'nia-svekarva' ? '  ✅' : '  🔴'));
  console.log('   счупени пазени: ' + счупени.length +
    (счупени.length ? '  ' + счупени.map(([т, с, ч]) => '„' + т + '" (чакано ' + ч + ', дадено ' + питай(т, с) + ')').join(' · ') : ''));
  console.log('');
}
