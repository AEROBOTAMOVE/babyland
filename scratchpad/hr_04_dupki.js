// Търси ДУПКИ В СЪДЪРЖАНИЕТО: дали за темата има карта ВЪОБЩЕ (по текста на
// core/tip/keys), независимо дали BL_MATCH я намира.
const { zaredi } = require('../dev/pyasachnik.js');
const A = zaredi(null, { памет: { bl_baby: { birth: '2025-11-20' } } });
const e = (A.BL_KB || A.KB).entries;
const текст = c => [c.title, c.core, c.tip, c.follow, (c.keys || []).join(' ')].join(' ').toLowerCase();

const теми = {
  'плюе нарочно / на игра, за реакция': [/плю\w* нарочно/, /нарочно плю/, /на игра.{0,30}плю/, /плю\w*.{0,40}за реакция/, /плюенето.{0,30}игра/],
  'бавачка — храни се при нея': [/бавачк/],
  'нощното шише и зъбите (кариес)': [/нощно шише/, /шише в лег/, /кариес/],
  'колко вода в мл по възраст': [/мл вода/, /милилитра вода/, /\d{2,3}\s*мл.{0,20}вода/],
  'отказва да яде ОТ МЕН, от друг яде': [/при татко яде/, /от мен не яде/, /при баба яде/],
  'изхвърляне на храна / майката се чувства виновна за изхвърленото': [/изхвърлям храна/, /жал за храната/, /изхвърлената храна/],
  'едно хранене трае час': [/трае час/, /колко трае едно хранене/, /дълго хранене/],
  'бебето заспива на шишето': [/заспива.{0,25}шише/, /заспива, докато яде/],
  'сол / досоляване': [/досолявам/, /солта и бъбреците/],
  'столче за хранене, поза, опора за крачетата': [/опора за краката/, /висят му краката/],
  'ресторант / детско меню панирано': [/детското меню е панирано/, /в ресторант с дете/],
  'чужд човек подава храна': [/чужд човек му подаде храна/],
  'напъхва цялото наведнъж': [/напъхва цялото наведнъж/],
  'на пара срещу печено': [/на пара или варено/, /печено или пържено/],
  'вилица — кога': [/кога се дава вилица/, /дава ли се вилица/],
  'отказва зелено': [/не иска нищо зелено/],
};
for (const [тема, ре] of Object.entries(теми)) {
  const намерени = e.filter(c => { const t = текст(c); return ре.some(r => r.test(t)); });
  console.log((намерени.length ? 'ИМА  ' : 'НЯМА ') + тема + ' → ' + (намерени.length ? намерени.map(c => c.room + '/' + c.id).join(', ') : '—'));
}
