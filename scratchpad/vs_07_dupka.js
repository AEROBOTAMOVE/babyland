// Има ли СЪДЪРЖАНИЕ по темата, или наистина липсва карта?
const { zaredi } = require('../dev/pyasachnik.js');
const A = zaredi(null, { памет: { bl_baby: { birth: '2025-11-20' } } });
const e = (A.BL_KB || A.KB).entries;
const теми = {
  'ИЗБОР НА МАРКА/НОМЕР ПЕЛЕНИ': /марка пелен|кои пелени|какви пелени|номер(а)? (на )?пелен|размер(а)? (на )?пелен|пелените протичат|друга марка пелен|пелени номер/i,
  'ОБЕМЪТ НА ПРАНЕТО / НЕ СМОГВАМ': /пералня|много пране|затънала в пран|не смогвам с пран|пране всеки ден/i,
  'ВАНИЧКА — ИЗБОР': /ваничк|вана за къпане|каква вана/i,
  'ДЪЖДОБРАН': /дъждобран/i,
};
for (const [име, рег] of Object.entries(теми)) {
  console.log('\n═══ ' + име + ' ═══');
  let n = 0;
  for (const c of e) {
    const вКлюч = (c.keys||[]).filter(k => рег.test(k));
    const вТяло = рег.test(String(c.core||'')) || рег.test(String(c.title||''));
    if (вКлюч.length || вТяло) {
      n++;
      console.log('  ' + c.room + '::' + c.id + ' « ' + c.title + ' »' + (вТяло ? '  [В ТЯЛОТО]' : ''));
      if (вКлюч.length) console.log('      ключове: ' + вКлюч.slice(0,6).join(' · '));
    }
  }
  if (!n) console.log('  НИЩО — нито ключ, нито тяло, нито заглавие');
}
