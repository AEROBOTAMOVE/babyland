// 🔬 УРЕДЪТ ЛЪЖЕ ТИХО: BL_MATCH чиста функция ли е?
// Подозрение: „ПРЕДИ" стойностите ми се сменят между две пускания на един и
// същ скрипт, щом преди тях са минали различен брой други въпроси.
// Ако е вярно, ВСИЧКИ мои числа зависят от РЕДА — и трябва свеж мозък на въпрос.
const path = require("path");
const ROOT = path.resolve(__dirname, "..");
const { zaredi } = require(path.join(ROOT, "dev", "pyasachnik.js"));
const пам = { bl_baby: { birth: "2025-11-20" } };
const Ж = "Жената в мен";
const коя = (W) => (t) => { const k = W.BL_MATCH(t, Ж); return k ? k.id : "ТИШИНА"; };

const в = "челото ми се оголи отпред и не знам как да го крия";

// A: свеж мозък, въпросът е ПЪРВИ
const A = zaredi(null, { памет: пам });
console.log("свеж мозък, въпросът е ПЪРВИ:            " + коя(A)(в));
console.log("същият мозък, ВТОРИ път същият въпрос:   " + коя(A)(в));
console.log("същият мозък, ТРЕТИ път:                 " + коя(A)(в));

// B: свеж мозък, но преди въпроса минават 30 други
const B = zaredi(null, { памет: пам });
["косата ми пада", "зъбите ме болят", "кожата ми е суха", "цикълът ми", "боли ме гърбът",
 "хемороиди", "изпускам урина", "вените ми", "гърдите ми", "уморена съм"].forEach(t => коя(B)(t));
console.log("\nсвеж мозък, СЛЕД 10 други въпроса:       " + коя(B)(в));

const C = zaredi(null, { памет: пам });
for (let i = 0; i < 40; i++) коя(C)("въпрос номер " + i + " за нищо");
console.log("свеж мозък, СЛЕД 40 безсмислици:         " + коя(C)(в));

// същият опит с втори въпрос
const в2 = "коремните преси може ли вече да ги правя";
const D = zaredi(null, { памет: пам });
console.log("\n[2] свеж мозък, ПЪРВИ:                   " + коя(D)(в2));
const E = zaredi(null, { памет: пам });
["косата ми пада", "зъбите ме болят", "кожата ми е суха"].forEach(t => коя(E)(t));
console.log("[2] свеж мозък, след 3 други:            " + коя(E)(в2));

// има ли изрично заглушаване
const F = zaredi(null, { памет: пам });
