// Мери ЛИ ги има думите, с които майката пише в чат — в ключовете на цялата база.
const { zaredi } = require('../dev/pyasachnik.js');
const A = zaredi(null, { памет: { bl_baby: { birth: '2025-11-20' } } });
const e = (A.BL_KB || A.KB).entries;
const всички = [];
for (const c of e) for (const k of (c.keys||[])) всички.push({ id:c.id, room:c.room, k:String(k).toLowerCase() });
console.log('ОБЩО КЛЮЧОВЕ В БАЗАТА: ' + всички.length + ' (в ' + e.length + ' карти)');

const двойки = [
  ['требва','трябва'], ['где','къде'], ['врти','върти'], ['кво','какво'],
  ['вика че','казва че'], ['пищи','плаче'], ['реве','плаче'], ['дере се','крещи'],
  ['нема','няма'], ['смогвам','успявам'],
];
console.log('\n═══ РАЗГОВОРНАТА ДУМА срещу КНИЖНАТА (брой ключове, в които се среща) ═══');
for (const [раз, кн] of двойки) {
  const r = всички.filter(x => new RegExp('(^|[^а-яa-z])' + раз + '([^а-яa-z]|$)').test(x.k)).length;
  const b = всички.filter(x => new RegExp('(^|[^а-яa-z])' + кн  + '([^а-яa-z]|$)').test(x.k)).length;
  console.log(('«' + раз + '»').padEnd(14) + String(r).padStart(5) + '   срещу   ' + ('«' + кн + '»').padEnd(14) + String(b).padStart(5));
}

console.log('\n═══ ГАЛЕНИ ИМЕНА И УМАЛИТЕЛНИ (брой ключове) ═══');
const гален = ['мъника','мъникът','мъниче','пиленцето','мишока','мъжлето','принцесата','бебчето','детенцето',
  'коремчето','крачетата','главичката','ръчичките','дупенцето','нослето','устичката','очичките','пеленката','ушичките','зъбчетата'];
for (const g of гален) {
  const хит = всички.filter(x => x.k.includes(g));
  console.log(g.padEnd(13) + String(хит.length).padStart(4) + (хит.length && хит.length<=4 ? '   ← ' + хит.map(h=>h.id).join(', ') : ''));
}
