// Мери ПОВТОРЕНИЯТА: шаблонните завършеци и колко пъти едно и също послание
// се казва ВЪТРЕ в една статия.  САМО ЧЕТЕ.
const fs = require('fs');
const path = require('path');
const ROOT = path.resolve(__dirname, '..');
const LIB = path.join(ROOT, 'lib');
const idx = JSON.parse(fs.readFileSync(path.join(LIB, 'index.json'), 'utf8'));
const мета = {}; for (const a of idx.items) мета[a.id] = a;
const тела = {};
for (const f of fs.readdirSync(LIB).filter(f => /^[a-z0-9-]+\.json$/.test(f) && f !== 'index.json'))
  Object.assign(тела, JSON.parse(fs.readFileSync(path.join(LIB, f), 'utf8')));
const думи = t => (String(t).match(/[а-яА-Яa-zA-Z]+/g) || []).length;
const вс = Object.entries(тела).filter(([k, v]) => typeof v === 'string');
const дълги = вс.filter(([k, v]) => думи(v) > 700);

console.log('── ШАБЛОННИ ЗАВЪРШЕЦИ (същите думи в много статии) ──');
const шаблони = [
  ['вътрешният ти глас / вътрешният глас', /вътрешни(я|ят) (ти )?глас/i],
  ['„Няма списък, който да покрива всичко"', /Няма списък, който да покрива всичко/i],
  ['„познаваш детето си по начин, по който никой друг"', /познаваш детето си по начин/i],
  ['„едно обаждане повече никога не е сгрешило"', /обаждане повече никога не е сгрешило/i],
  ['„достатъчна причина да се обадиш"', /достатъчна причина да се обадиш/i]
];
for (const [ет, Р] of шаблони) {
  const вВсички = вс.filter(([k, v]) => Р.test(v)).length;
  const вДълги = дълги.filter(([k, v]) => Р.test(v)).length;
  console.log('  ' + String(вВсички).padStart(4) + ' от 1323 статии · ' + String(вДълги).padStart(3) + ' от 83 дълги   ' + ет);
}
// колко дълги статии носят ПОВЕЧЕ ОТ ЕДИН шаблонен завършек
const двойни = дълги.filter(([k, v]) => шаблони.filter(([e, Р]) => Р.test(v)).length >= 2);
console.log('  ' + String(двойни.length).padStart(4) + ' от 83 дълги носят ДВА ИЛИ ПОВЕЧЕ такива завършека наведнъж:');
for (const [k, v] of двойни) console.log('        ' + String(думи(v)).padStart(4) + ' д · ' + k + ' · ' + (мета[k] || {}).t);

console.log('');
console.log('── ЕДНО И СЪЩО ПОСЛАНИЕ, ПОВТОРЕНО ВЪТРЕ В ЕДНА СТАТИЯ ──');
const вътре = [
  ['lib-2ceefd4b', 'НОИ ≠ АСП (различни каси)', /(НОИ[^.]{0,60}АСП|АСП[^.]{0,60}НОИ)/gi],
  ['lib-2ceefd4b', '„сумата не се казва наизуст"', /(наизуст|не се гадае|без данни и официална проверка|никой не бива да ти)/gi],
  ['lib-2ceefd4b', '12 месеца осигурителен стаж', /12 месеца осигурителен стаж/gi],
  ['lib-krup-laesha-kashlitsa-nosht', 'парата/горещата вода не помага', /(парата НЕ|Горещата вода|тенджера с вряла|попарван|изгарян)/gi],
  ['lib-krup-laesha-kashlitsa-nosht', 'стридор в покой = лекар сега', /стридор[^.]{0,80}покой|покой[^.]{0,80}стридор/gi],
  ['lib-47903d41', 'усещането на майката е достатъчно', /(усещане|вътрешни|не е както обичайно|не изглежда като обичайното)/gi],
  ['lib-820b79e1', 'никога само във водата', /(без теб|не остава сам|нито за секунда|дори за секунда)/gi],
  ['lib-a68b59a0', 'питай личния лекар', /(личния лекар|личен лекар|педиатъра)/gi],
  ['lib-bbbc7476', 'питай яслата/лекаря, не гадай', /(питай|не гадай|питаш)/gi]
];
for (const [id, ет, Р] of вътре) {
  const t = тела[id] || '';
  const n = (t.match(Р) || []).length;
  console.log('  ' + String(n).padStart(3) + '× ' + ет + '   [' + id + ']');
}

console.log('');
console.log('── ИМА ЛИ ОТДЕЛНА СТАТИЯ ЗА НОЩНОТО НАПИКАВАНЕ? ──');
const нощ = idx.items.filter(a => /напикав|нощен контрол|суха нощ|мокро легло|енуреза/i.test(String(a.t) + ' ' + String(a.s) + ' ' + String(a.k)));
console.log('  ' + нощ.length + ' статии');
for (const a of нощ) console.log('     ' + String(думи(тела[a.id] || '')).padStart(4) + ' д · ' + a.id.padEnd(16) + ' [' + a.r + '] ' + a.t);

console.log('');
console.log('── КОЛКО ОТ 83-те НОСЯТ 🚨 БЛОК И КОЛКО ЕДЪР Е ТОЙ ──');
let сФлаг = 0, сумаФлаг = 0, макс = 0, максИд = '';
for (const [k, v] of дълги) {
  const i = v.search(/^##\s*🚨/m);
  if (i < 0) continue;
  сФлаг++;
  const д = думи(v.slice(i));
  сумаФлаг += д;
  if (д > макс) { макс = д; максИд = k; }
}
console.log('  ' + сФлаг + ' от 83 имат ## 🚨 раздел');
console.log('  средно ' + Math.round(сумаФлаг / сФлаг) + ' думи в 🚨 раздела · най-голям ' + макс + ' д (' + максИд + ')');
